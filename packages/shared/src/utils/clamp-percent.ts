/**
 * G-815966(2026-10-01):百分比裁剪的具名唯一出口。
 *
 * 旧形态:`Math.max(0, Math.min(100, x))` 逐处手搓(上游同族两份拷贝正是
 * 守门 103/D3 反复记的"第二处真相");语义分散后,"恰好等于边界"与
 * "undefined 缺席"在每处各猜一遍。统一出口:非数值(undefined/null/NaN)
 * ⇒ 0;其余钳到 [0, 100]。同一语义不得再出现第二份内联实现。
 */
export function clampPercent(value: number | null | undefined): number {
  if (typeof value !== 'number' || Number.isNaN(value)) return 0
  return Math.max(0, Math.min(100, value))
}
