/**
 * safeDecodeURIComponent —— URI 百分号解码的唯一容错出口（跨端共享）。
 *
 * 立因（2026-10-25 移动端行为级深挖轮）：小程序 `router.params` / RN 深链参数由框架**自动解码一次**，
 * 端上再手写 `decodeURIComponent(...)` 属"二次解码"。原文一旦含孤立 `%`（分享文案「100%好评」、
 * 昵称/房间名/头像 URL 里带百分号），二次解码当场抛 `URIError: URI malformed`——
 * 而这些调用点大多落在 useEffect / useMemo / useState 初始值的**渲染求值路径**上，
 * throw 不被 React 捕获，直接白屏/页面崩。typecheck/lint/守门全测不到（纯运行时炸点）。
 *
 * 语义（与 packages/auth 历史实现一致，自本文件起为唯一真相源）：
 *  - 能解则解；
 *  - 解不动（URIError）**原样返回**。"原样"正是框架已替我们解过一次时的正确答案，
 *    对未编码串也是最有信息量的降级（显示 `%zz` 好过整页崩）。
 *
 * 端内不得再自建第二份 try/catch 包装（§0.6 单一真相源）；防回潮由
 * `scripts/check-bare-decode-uri.mjs` 按"HEAD 该文件自身违规数"差值棘轮拦新增。
 */

/**
 * 容错版 `decodeURIComponent`：非法百分号编码输入返回原串，永不抛。
 */
export function safeDecodeURIComponent(value: string): string {
  try {
    return decodeURIComponent(value)
  } catch {
    return value
  }
}
