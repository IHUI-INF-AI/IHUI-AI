import { describe, expect, it } from 'vitest'

import { parseQrLoginTicket } from '../qr-login-ticket'

const T = 'qr_467c74c8-f02c-4704-a79c-b666a7bd4358'

describe('parseQrLoginTicket', () => {
  it('纯 ticket 原样返回', () => {
    expect(parseQrLoginTicket(T)).toBe(T)
  })

  it('前后空白不影响', () => {
    expect(parseQrLoginTicket(`  ${T}\n`)).toBe(T)
  })

  it('URL 形态取 ticket 参数', () => {
    expect(parseQrLoginTicket(`https://www.aizhs.top/login?method=qr&ticket=${T}`)).toBe(T)
  })

  it('参数被百分号编码也能解出来', () => {
    expect(parseQrLoginTicket(`https://www.aizhs.top/x?ticket=${encodeURIComponent(T)}`)).toBe(T)
  })

  it('非本站码 / 空值返回 null', () => {
    expect(parseQrLoginTicket('https://example.com/hello')).toBeNull()
    expect(parseQrLoginTicket('')).toBeNull()
    expect(parseQrLoginTicket(null)).toBeNull()
    expect(parseQrLoginTicket(undefined)).toBeNull()
  })

  it('过短的伪 ticket 不认', () => {
    expect(parseQrLoginTicket('qr_abc')).toBeNull()
  })

  it('坏编码不抛异常', () => {
    expect(parseQrLoginTicket('https://www.aizhs.top/x?ticket=%E0%A4%A')).toBeNull()
  })
})
