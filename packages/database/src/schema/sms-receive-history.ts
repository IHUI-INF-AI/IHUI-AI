/**
 * 短信接码历史台账(d1jiema 取号收码流水,管理员短信接码页 /admin/sms-receive 用)。
 *
 * 目的:回答"这个手机号有没有接过某平台的码/是否已在该平台注册过"——
 * 平台 queryUsed 只回 24h 内 100 条且限频 1 次/分钟,本地台账一次开发永久留痕。
 * 写入时机:getMsg 收到短信(status=received)时由路由层落一条流水。
 * usage_kind 从短信文案判定:含「注册」=register(该号未注册过该平台,本次新号),
 * 含「登录」=login(该号已注册过该平台,本次为登录码),其余 other。
 */

import { pgTable, uuid, varchar, text, timestamp, index } from 'drizzle-orm/pg-core'

export const smsReceiveHistory = pgTable(
  'sms_receive_history',
  {
    id: uuid('id').defaultRandom().primaryKey(),
    phone: varchar('phone', { length: 20 }).notNull(), // 接码手机号
    keyword: varchar('keyword', { length: 64 }), // 取号时填的短信关键词
    platform: varchar('platform', { length: 64 }), // 从短信原文【】提取的平台名(如 trae)
    usageKind: varchar('usage_kind', { length: 16 }).notNull().default('other'), // register/login/other
    smsCode: varchar('sms_code', { length: 16 }), // 提取出的验证码
    smsRaw: text('sms_raw').notNull(), // 短信原文
    receivedAt: timestamp('received_at', { withTimezone: true }).defaultNow().notNull(),
  },
  (t) => ({
    phoneReceivedIdx: index('sms_receive_history_phone_received_idx').on(t.phone, t.receivedAt),
    platformIdx: index('sms_receive_history_platform_idx').on(t.platform),
  }),
)

export type SmsReceiveHistory = typeof smsReceiveHistory.$inferSelect
export type NewSmsReceiveHistory = typeof smsReceiveHistory.$inferInsert
