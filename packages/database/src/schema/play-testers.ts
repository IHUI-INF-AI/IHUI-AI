import { pgTable, uuid, varchar, boolean, timestamp, index } from 'drizzle-orm/pg-core'

export const playTesters = pgTable(
  'play_testers',
  {
    id: uuid('id').defaultRandom().primaryKey(),
    email: varchar('email', { length: 255 }).notNull().unique(),
    locale: varchar('locale', { length: 10 }).notNull().default('zh-CN'),
    source: varchar('source', { length: 30 }).notNull().default('web'),
    status: varchar('status', { length: 20 }).notNull().default('pending'),
    agreedPrivacy: boolean('agreed_privacy').notNull().default(false),
    createdAt: timestamp('created_at').defaultNow().notNull(),
    updatedAt: timestamp('updated_at').defaultNow().notNull(),
  },
  (table) => ({
    statusIdx: index('play_testers_status_idx').on(table.status),
    createdAtIdx: index('play_testers_created_at_idx').on(table.createdAt),
  }),
)

export type PlayTester = typeof playTesters.$inferSelect
export type NewPlayTester = typeof playTesters.$inferInsert

