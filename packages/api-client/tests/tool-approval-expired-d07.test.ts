/**
 * D-07(2026-10-26):断线失效审批"端上可见"的解析层判据。
 *
 * 为什么单独测这一层:服务端把失效条目投影成同形 `tool-approval` + `expired` 标记,
 * 但消费方拿到的事件若丢了这一格,端上就会把"已失效"当"新审批"再弹一次窗 ——
 * 与 D159 同一个失效型(解析层不递 ⇒ 端上永远看不到)。
 *
 * 本文件钉两条反向:缺省/false/字符串 "true" 都不算失效标记(不许造默认值);
 * 原因只在非空 string 时透传(不猜、不补)。
 */
import { describe, it, expect } from 'vitest'

import { projectToolApprovalExpiredFact } from '../src/index.js'

describe('D-07 projectToolApprovalExpiredFact', () => {
  it('① 失效帧 ⇒ expired 标记与原因逐键投影', () => {
    const out = projectToolApprovalExpiredFact({
      expired: true,
      expired_reason: 'stream_closed',
    })
    expect(out).toEqual({ expired: true, expiredReason: 'stream_closed' })
  })

  it('② 正常审批帧(无 expired 键)⇒ 零新增字段', () => {
    expect(projectToolApprovalExpiredFact({ approval_id: 'appr_1' })).toEqual({})
  })

  it('③ 非布尔真值不得当失效:false / "true" / 1 一律不投影', () => {
    for (const value of [false, 'true', 1, null, undefined]) {
      expect(projectToolApprovalExpiredFact({ expired: value })).toEqual({})
    }
  })

  it('④ 原因不是字符串 ⇒ 只带标记,不补默认原因', () => {
    expect(projectToolApprovalExpiredFact({ expired: true, expired_reason: null })).toEqual({
      expired: true,
    })
  })
})
