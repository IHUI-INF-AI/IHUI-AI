import { describe, it, expect } from 'vitest'
import { ApiError, isNotFound, isErrorCode } from '../src/api-error.js'

describe('ApiError', () => {
  it('构造时设置 name/status/errorCode', () => {
    const err = new ApiError('not found', 404, 'NOT_FOUND')
    expect(err.name).toBe('ApiError')
    expect(err.message).toBe('not found')
    expect(err.status).toBe(404)
    expect(err.errorCode).toBe('NOT_FOUND')
  })

  it('构造时不带 status/errorCode', () => {
    const err = new ApiError('generic error')
    expect(err.message).toBe('generic error')
    expect(err.status).toBeUndefined()
    expect(err.errorCode).toBeUndefined()
  })

  it('继承自 Error', () => {
    const err = new ApiError('test')
    expect(err).instanceof(Error)
  })
})

describe('isNotFound', () => {
  it('404 ApiError 返回 true', () => {
    expect(isNotFound(new ApiError('missing', 404))).toBe(true)
  })

  it('非 404 ApiError 返回 false', () => {
    expect(isNotFound(new ApiError('unauthorized', 401))).toBe(false)
  })

  it('非 ApiError 对象返回 false', () => {
    expect(isNotFound(new Error('not found'))).toBe(false)
    expect(isNotFound({ status: 404 })).toBe(false)
    expect(isNotFound(null)).toBe(false)
    expect(isNotFound('not found')).toBe(false)
  })
})

describe('isErrorCode', () => {
  it('匹配的 errorCode 返回 true', () => {
    expect(isErrorCode(new ApiError('err', 500, 'RATE_LIMIT'), 'RATE_LIMIT')).toBe(true)
  })

  it('不匹配的 errorCode 返回 false', () => {
    expect(isErrorCode(new ApiError('err', 500, 'RATE_LIMIT'), 'NOT_FOUND')).toBe(false)
  })

  it('无 errorCode 的 ApiError 返回 false', () => {
    expect(isErrorCode(new ApiError('err'), 'RATE_LIMIT')).toBe(false)
  })

  it('非 ApiError 对象返回 false', () => {
    expect(isErrorCode(new Error('err'), 'RATE_LIMIT')).toBe(false)
  })
})
