// 内容标记的单一真源(此前各模块各自写死 '[上下文摘要' 字面量,属二次写死)。
// 历史摘要消息以该标记开头:再压缩时正文原样并入、条数累加(防嵌套),
// 回收/溢出丢弃则一律把它当"不可再压的产物"整条保护。
//
// 结果信封标记也住在这里,而不是留在 apps/cli 里:依赖方向是
// apps/cli → @ihui/context-compaction,反向 import 结构上不可能;而"这段是信封"
// 恰恰是回收侧必须知道的判据(见 reclaim.ts)—— 判据与格式契约必须在同一层。

/** 摘要消息内容前缀标记(防嵌套检测:后续压缩识别到该前缀时合并重写而非再摘要) */
export const SUMMARY_MARKER = '[上下文摘要'

/** 该消息是否为压缩产物(历史摘要消息) */
export function isSummaryMessage(message: { role: string; content: string }): boolean {
  return message.role === 'user' && message.content.startsWith(SUMMARY_MARKER)
}

// ==================== 结果信封(超限工具结果的结构性替身)====================

/** 信封起始标记(幂等识别的唯一锚点) */
export const ENVELOPE_OPEN_MARKER = '[[结果信封 v1]]'
/** 信封结束标记 */
export const ENVELOPE_CLOSE_MARKER = '[[/结果信封 v1]]'
/** 预览段与收尾说明的分隔行 */
export const ENVELOPE_PREVIEW_FOOTER = '---以上为预览---'

/**
 * 该文本(或其片段)是否已经是信封。
 *
 * 为什么两侧都要认它:
 *   - 封装侧(CLI)靠它避免二次封装;
 *   - 回收侧(reclaim)靠它 **拒绝改写** —— 信封里的"完整输出: <路径>"是模型
 *     找回大输出的唯一线索,换成占位串就等于把线索本身也回收掉了。
 */
export function isEnvelopeContent(text: string): boolean {
  return (
    typeof text === 'string' && text.includes(ENVELOPE_OPEN_MARKER) && text.includes(ENVELOPE_CLOSE_MARKER)
  )
}
