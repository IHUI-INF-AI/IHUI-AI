export function parseTrialCount(raw) {
  if (raw === undefined || raw === null || String(raw).trim() === '') return { ok: true, value: 1 };
  const text = String(raw).trim();
  if (!/^[1-9]\d*$/.test(text)) {
    return { ok: false, error: `BENCH_TRIALS 必须是 >= 1 的整数，实际 ${raw}` };
  }
  return { ok: true, value: Number(text) };
}

/** 登录状态不是 0（含超时 status=null）就中止，调用方不得继续跑任务。 */
export function gateLogin(status) {
  if (status === 0) return { abort: false, code: 0 };
  return { abort: true, code: 1 };
}

/** durationMs 只表示代理进程本身。准备目录和 verify 分开计，不并进模型耗时。 */
export function attemptTiming(trial) {
  return {
    agentExit: trial.agentExit,
    verifyPass: trial.verifyPass,
    prepMs: trial.prepMs,
    agentMs: trial.agentMs,
    verifyMs: trial.verifyMs,
    durationMs: trial.agentMs,
    verifyOutput: trial.verifyPass ? '' : trial.verifyOutput || '',
  };
}

export function assembleReport({ date, cmd, taskRuns }) {
  const results = taskRuns.map((task) => {
    const trials = task.trials.map((trial, index) => ({
      attempt: index + 1,
      ...attemptTiming(trial),
    }));
    const passCount = trials.filter((trial) => trial.verifyPass).length;
    const failCount = trials.length - passCount;
    return { id: task.id, passCount, failCount, trials };
  });
  const trialTotal = results.reduce((sum, row) => sum + row.trials.length, 0);
  const trialPassed = results.reduce((sum, row) => sum + row.passCount, 0);
  const passRate = trialTotal === 0 ? 0 : Number(((trialPassed / trialTotal) * 100).toFixed(1));
  return {
    date,
    cmd,
    total: results.length,
    trialTotal,
    trialPassed,
    passed: trialPassed,
    passRate,
    results,
  };
}

export function exitCodeForPassRate(passRate) {
  return passRate >= 80 ? 0 : 1;
}
