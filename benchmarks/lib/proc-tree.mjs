import { spawn, spawnSync } from 'node:child_process';

/**
 * 杀掉子进程树。Windows 与 scripts/check-typecheck.mjs 的 killChildTree 同法：
 * taskkill /PID <pid> /T /F。其余平台 SIGKILL。
 * 不用 taskkill /IM，避免按镜像名误杀同名进程。
 */
export function killProcessTree(child) {
  if (!child || typeof child.pid !== 'number') return;
  if (child.exitCode !== null || child.signalCode !== null) return;
  try {
    if (process.platform === 'win32') {
      spawnSync('taskkill', ['/PID', String(child.pid), '/T', '/F'], {
        stdio: 'ignore',
        windowsHide: true,
      });
    } else {
      child.kill('SIGKILL');
    }
  } catch {
    try {
      child.kill('SIGKILL');
    } catch {
      /* 进程已经退出 */
    }
  }
}

export function alivePid(pid) {
  if (typeof pid !== 'number') return false;
  try {
    process.kill(pid, 0);
    return true;
  } catch {
    return false;
  }
}

/** spawn 带超时。超时走 killProcessTree，而不是只杀掉 spawnSync 的直接子进程。 */
export function spawnCaptured(command, args, options = {}) {
  const { timeout, cwd, env } = options;
  return new Promise((resolve) => {
    const child = spawn(command, args, {
      cwd,
      env,
      windowsHide: true,
      shell: false,
      stdio: ['ignore', 'pipe', 'pipe'],
    });
    let stdout = '';
    let stderr = '';
    let settled = false;
    let timedOut = false;
    const finish = (result) => {
      if (settled) return;
      settled = true;
      if (timer) clearTimeout(timer);
      resolve({ pid: child.pid, ...result });
    };
    const timer =
      typeof timeout === 'number' && timeout > 0
        ? setTimeout(() => {
            timedOut = true;
            killProcessTree(child);
            finish({ status: null, signal: 'SIGKILL', stdout, stderr, timedOut: true });
          }, timeout)
        : null;
    child.stdout.setEncoding('utf8');
    child.stderr.setEncoding('utf8');
    child.stdout.on('data', (chunk) => {
      stdout += chunk;
    });
    child.stderr.on('data', (chunk) => {
      stderr += chunk;
    });
    child.on('error', (error) => {
      killProcessTree(child);
      finish({ status: null, signal: null, stdout, stderr, timedOut: false, error });
    });
    child.on('close', (status, signal) => {
      finish({
        status: timedOut ? null : status,
        signal: timedOut ? 'SIGKILL' : signal,
        stdout,
        stderr,
        timedOut,
      });
    });
  });
}
