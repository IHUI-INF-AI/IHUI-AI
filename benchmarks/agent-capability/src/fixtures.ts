import * as fs from 'node:fs'
import * as path from 'node:path'

import { validateRecording, type ReplayRecording } from './replay.js'
import { FIXTURES_DIR } from './workspace.js'

/**
 * 仅供评测内部（负控用例）使用的录制覆盖：键为 `loadRecording` 的 rel。
 * 默认 null；为 null 时 `loadRecording` 的行为与直接读文件逐字节等价。
 */
let recordingOverrides: Record<string, unknown> | null = null

export function setRecordingOverrides(overrides: Record<string, unknown> | null): void {
  recordingOverrides = overrides
}

/** 读取 `fixtures/recordings/<rel>.json`（rel 不带扩展名，便于跨平台） */
export function loadRecording(rel: string): ReplayRecording {
  const abs = path.join(FIXTURES_DIR, 'recordings', `${rel}.json`)
  // 有覆盖时返回深拷贝：回放对象带消耗状态，多次运行不能共享同一份引用
  const raw =
    recordingOverrides !== null && Object.hasOwn(recordingOverrides, rel)
      ? structuredClone(recordingOverrides[rel])
      : (JSON.parse(fs.readFileSync(abs, 'utf8')) as unknown)
  return validateRecording(raw, path.relative(FIXTURES_DIR, abs))
}

/** 读取 `fixtures/scenarios/<rel>.json`（结构化场景数据；schema 由各能力 suite 自己校验） */
export function loadScenario<T>(rel: string): T {
  const abs = path.join(FIXTURES_DIR, 'scenarios', `${rel}.json`)
  return JSON.parse(fs.readFileSync(abs, 'utf8')) as T
}

/** 读取 `fixtures/workspaces/<rel>/files.json`（初始工作区：相对路径 → 内容） */
export function loadWorkspaceSeed(rel: string): Record<string, string> {
  const abs = path.join(FIXTURES_DIR, 'workspaces', rel, 'files.json')
  return JSON.parse(fs.readFileSync(abs, 'utf8')) as Record<string, string>
}
