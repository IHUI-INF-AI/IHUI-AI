import * as compaction from './suites/compaction.js'
import * as errorRecovery from './suites/error-recovery.js'
import * as resume from './suites/resume.js'
import * as toolCall from './suites/tool-call.js'
import type { CaseResult } from './types.js'

const SUITES = [toolCall, errorRecovery, compaction, resume]

/** 顺序执行：用例共享进程级工具注册表与 fetch stub，并发会互相污染 */
export async function runAllCases(): Promise<CaseResult[]> {
  const results: CaseResult[] = []
  for (const suite of SUITES) {
    results.push(...(await suite.run()))
  }
  return results
}
