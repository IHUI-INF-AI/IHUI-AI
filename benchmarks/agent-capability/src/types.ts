export type Capability = 'tool-call' | 'compaction' | 'resume' | 'error-recovery'

export type MetricValue = number | string | boolean

/** 单条固定任务的结果。metrics/evidence 必须确定性（无时间、无随机、无绝对路径） */
export interface CaseResult {
  id: string
  capability: Capability
  passed: boolean
  metrics: Record<string, MetricValue>
  /** 支撑结论的机械证据（工具序列、文件快照、哈希等）；参与"变了/没变"的判定 */
  evidence: Record<string, unknown>
  /** 失败点（passed=false 时非空，逐条可读） */
  failures: string[]
}

export interface EvalSnapshot {
  schemaVersion: 1
  /** 夹具（录制 + 场景数据）的内容哈希：夹具一改，旧基线立即失效 */
  fixtureHash: string
  /** 生成基线的被测代码提交 */
  commit: string
  cases: CaseResult[]
}

export type CaseStatus = 'unchanged' | 'improved' | 'regressed' | 'changed' | 'added' | 'removed'

export interface CaseDiff {
  id: string
  status: CaseStatus
  /** 逐条变化说明（指标名: 基线 → 当前） */
  details: string[]
}

export interface Comparison {
  status: 'unchanged' | 'improved' | 'regressed' | 'changed'
  cases: CaseDiff[]
}
