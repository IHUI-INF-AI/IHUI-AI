import { strict as assert } from 'node:assert';
import { pathToFileURL } from 'node:url';
import { resolve } from 'node:path';
import { setTimeout as sleep } from 'node:timers/promises';
const svc = await import(pathToFileURL(resolve('service.mjs')).href);
svc.setCached('k1', 'v1', 1000);
assert.equal(svc.getCached('k1'), 'v1', '未过期条目应命中');
await sleep(30);
assert.equal(svc.getCached('k1'), 'v1', '30ms 后(ttl=1000)仍应命中');
console.log('PASS');
