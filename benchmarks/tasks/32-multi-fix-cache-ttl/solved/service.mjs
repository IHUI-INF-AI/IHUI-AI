import { isExpired } from './cache.mjs';

const store = new Map();
let seq = 0;

export function setCached(key, value, ttl) {
  store.set(key, { value, ttl, createdAt: Date.now(), id: ++seq });
}

export function getCached(key) {
  const e = store.get(key);
  if (!e || isExpired(e)) return null;
  return e.value;
}
