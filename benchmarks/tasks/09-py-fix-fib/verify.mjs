import { spawnSync } from 'node:child_process';
import { pythonCandidatesFrom, resolvePinnedPython, probePython } from '../../lib/python-pin.mjs';
const resolved = resolvePinnedPython(pythonCandidatesFrom(import.meta.url), probePython);
if (!resolved.ok) {
  console.error(resolved.message);
  process.exit(1);
}
const py = resolved.python;
const code = [
  'import sys; sys.path.insert(0, ".")',
  'from fib import fib',
  'assert fib(0) == 0',
  'assert fib(1) == 1',
  'assert fib(7) == 13',
  'assert fib(10) == 55',
  'print("OK")',
].join('\n');
const r = spawnSync(py, ['-c', code], { encoding: 'utf8', cwd: process.cwd(), windowsHide: true });
if (r.status !== 0) {
  console.error(r.stdout || ''); console.error(r.stderr || '');
  process.exit(1);
}
console.log('PASS');
