import { strict as assert } from 'node:assert';
import { pathToFileURL } from 'node:url';
import { resolve } from 'node:path';
const q = await import(pathToFileURL(resolve('queue.mjs')).href);
const w = await import(pathToFileURL(resolve('worker.mjs')).href);
const queue = new q.Queue();
queue.enqueue(1); queue.enqueue(2); queue.enqueue(3);
assert.deepEqual(queue.drain(), [1, 2, 3]);
assert.deepEqual(queue.drain(), []);
assert.deepEqual(w.processAll([7, 8]), ['job-7', 'job-8']);
console.log('PASS');
