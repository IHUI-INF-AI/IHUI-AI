import { test } from 'node:test';
import { strict as assert } from 'node:assert';
import { debounce } from './debounce.mjs';

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

test('等待期内不执行', async () => {
  let calls = 0;
  const d = debounce(() => calls++, 30);
  d(); d(); d();
  assert.equal(calls, 0, '同步阶段不应执行');
  await sleep(20);
  assert.equal(calls, 0, 'wait 内不应执行');
});

test('停止触发后只执行一次', async () => {
  let calls = 0;
  const d = debounce(() => calls++, 30);
  d(); d(); d();
  await sleep(70);
  assert.equal(calls, 1, `应恰好执行 1 次,实际 ${calls}`);
});

test('以最后一次调用的参数执行', async () => {
  let got = null;
  const d = debounce((v) => { got = v; }, 30);
  d('first');
  d('last');
  await sleep(70);
  assert.equal(got, 'last');
});
