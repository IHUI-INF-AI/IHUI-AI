import { test } from 'node:test';
import { strict as assert } from 'node:assert';
import { retry } from './retry.mjs';

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

test('失败后重试直至成功', async () => {
  let calls = 0;
  const val = await retry(async () => {
    calls++;
    if (calls < 3) throw new Error('flaky');
    return 'ok';
  }, 5, 5);
  assert.equal(val, 'ok');
  assert.equal(calls, 3);
});

test('超过次数后抛出最后一次错误', async () => {
  let calls = 0;
  await assert.rejects(
    () => retry(async () => { calls++; throw new Error('boom-' + calls); }, 3, 5),
    /boom-3/,
  );
  assert.equal(calls, 3, `应恰好尝试 3 次,实际 ${calls}`);
});

test('首次成功不重试', async () => {
  let calls = 0;
  const val = await retry(async () => { calls++; return 42; }, 3, 5);
  assert.equal(val, 42);
  assert.equal(calls, 1);
});
