import { readFileSync, writeFileSync } from 'node:fs'

const lines = readFileSync('PROJECT_PLAN.md', 'utf8').split(/\r?\n/)
const cands = []
lines.forEach((ln, i) => {
  if (!/^\s*- \[ \]/.test(ln) || /（进行中）/.test(ln)) return
  const body = ln.replace(/^\s*- \[ \]\s*/, '')
  const m = body.match(/^(?:\*\*)?(D\d{1,3}|O\d{1,3}[a-z]?\d*|WP-\d+)\b/)
  if (!m) return
  cands.push({ n: i + 1, id: m[1], body })
})
const seen = new Set()
const uniq = cands.filter((r) => {
  if (seen.has(r.id)) return false
  seen.add(r.id)
  return true
})
// 票面全文 = 条目行 + 紧随其后的 3 行缩进说明(票的验收口径常写在续行)
const out = uniq.map((r) => {
  let full = r.body
  for (let k = r.n; k < r.n + 4; k++) {
    const ln = lines[k] || ''
    if (/^\s{2,}\S/.test(ln) && !/^\s*- \[/.test(ln)) full += '\n' + ln.trim()
    else break
  }
  return { id: r.id, line: r.n, text: full }
})
out.sort((a, b) => {
  const ka = a.id.match(/^([A-Z]+)-?(\d+)/)
  const kb = b.id.match(/^([A-Z]+)-?(\d+)/)
  return ka[1].localeCompare(kb[1]) || Number(ka[2]) - Number(kb[2])
})
writeFileSync('.ihui-agent/tmp/plan-audit/tickets.json', JSON.stringify(out, null, 1), 'utf8')
console.log(`生成 ${out.length} 张票 -> .ihui-agent/tmp/plan-audit/tickets.json`)
