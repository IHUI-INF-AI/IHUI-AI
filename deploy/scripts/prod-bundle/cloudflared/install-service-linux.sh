# =============================================================================
# Cloudflared Linux systemd 服务安装(开机自启)
# =============================================================================
# 用法(root):
#   sudo chmod +x deploy/prod-bundle/cloudflared/install-service-linux.sh
#   sudo ./deploy/prod-bundle/cloudflared/install-service-linux.sh
# =============================================================================
set -euo pipefail

# 从 .env.production 读取 TUNNEL_TOKEN
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_ROOT="$(cd "$SCRIPT_DIR/../.." && pwd)"
ENV_FILE="$PROJECT_ROOT/.env.production"

TUNNEL_TOKEN=""
if [[ -f "$ENV_FILE" ]]; then
    TUNNEL_TOKEN=$(grep -E "^TUNNEL_TOKEN=" "$ENV_FILE" | head -1 | cut -d= -f2-)
fi

if [[ -z "$TUNNEL_TOKEN" ]]; then
    echo "[ERROR] 未在 $ENV_FILE 找到 TUNNEL_TOKEN"
    exit 1
fi
echo "[INFO] Token 已加载(长度: ${#TUNNEL_TOKEN})"

# 检查 cloudflared
if ! command -v cloudflared >/dev/null 2>&1; then
    echo "[INFO] cloudflared 未安装,下载安装..."
    ARCH=$(uname -m)
    case "$ARCH" in
        x86_64)  BIN_ARCH="amd64" ;;
        aarch64) BIN_ARCH="arm64" ;;
        *) echo "[ERROR] 不支持的架构: $ARCH"; exit 1 ;;
    esac
    curl -L "https://github.com/cloudflare/cloudflared/releases/latest/download/cloudflared-linux-${BIN_ARCH}" \
        -o /usr/local/bin/cloudflared
    chmod +x /usr/local/bin/cloudflared
fi
echo "[INFO] cloudflared: $(cloudflared --version)"

# 安装为 systemd 服务
cloudflared service install "$TUNNEL_TOKEN"

# 启用并启动
systemctl daemon-reload
systemctl enable cloudflared
systemctl start cloudflared
sleep 3

if systemctl is-active --quiet cloudflared; then
    echo "[OK] Cloudflared 服务已安装并启动(开机自启)"
    echo ""
    echo "管理命令:"
    echo "  查看状态:  sudo systemctl status cloudflared"
    echo "  停止:      sudo systemctl stop cloudflared"
    echo "  启动:      sudo systemctl start cloudflared"
    echo "  重启:      sudo systemctl restart cloudflared"
    echo "  卸载:      sudo cloudflared service uninstall"
    echo ""
    echo "查看日志: sudo journalctl -u cloudflared -f"
else
    echo "[ERROR] 服务启动失败"
    echo "查看日志: sudo journalctl -u cloudflared -n 50"
    exit 1
fi
