$TaskName = 'IHUI-Mobile-AutoRelease'

# ---- 计划任务注册档 ---------------------------------------------------------------
# 为什么用 Interactive 登录态:构建要读 ~/.gradle/gradle.properties 与 keystore,发布要读
# 用户级 git 凭据(gitee.com)与 ~/.ssh 里的部署密钥 —— 这些都在用户配置文件里,换成
# SYSTEM/服务账户会全部取不到。代价是"用户没登录时不跑",已写进头注边界。
# 但 Interactive 会话直跑 pwsh.exe 会弹可见控制台窗 ⇒ action 一律经 wscript.exe +
# SW_HIDE 隐藏 VBS 包装(见下),窗口从创建起就不可见。
if ($RegisterTask) {
  if (-not (Test-Path -LiteralPath $RepoRoot)) { throw "工作树不存在: $RepoRoot" }
  $pwshPath = (Get-Command pwsh.exe -ErrorAction Stop).Source
  $arguments = "-NoProfile -ExecutionPolicy Bypass -File `"$PSCommandPath`""
  # 隐藏包装:Interactive 主体下 action 直指控制台程序(pwsh.exe)必弹可见黑窗。
  # wscript.exe 是 GUI 子系统(本身不开控制台),VBS 内 shell.Run 第 2 参 0 = SW_HIDE。
  # wscript 按 ANSI 代码页解码 .vbs ⇒ 正文必须纯 ASCII(非 ASCII 会编译失败并弹 WSH 对话框)。
  $VbsLauncher = Join-Path $PSScriptRoot 'mobile-auto-release-hidden.vbs'
  $innerCmd = '"' + $pwshPath + '" ' + $arguments
  # 单独成行构造:VBS 里双引号必须双写(""),否则 wscript 编译失败
  $shellRunLine = 'shell.Run "' + $innerCmd.Replace('"', '""') + '", 0, False'
  $vbsBody = @(
    "' Hidden launcher for IHUI-Mobile-AutoRelease (SW_HIDE, zero visible console window).",
    "' Auto-generated by scripts/mobile-auto-release.ps1 -RegisterTask -- do not edit.",
    "' ASCII-only by design: wscript decodes .vbs via the ANSI codepage.",
    "Option Explicit",
    "Dim shell",
    'Set shell = CreateObject("WScript.Shell")',
    $shellRunLine,
    ""
  ) -join "`r`n"
  if ($vbsBody -match '[^\x00-\x7F]') {
    throw "隐藏启动器含非 ASCII 字符(wscript 按 ANSI 解码会编译失败): $VbsLauncher"
  }
  [System.IO.File]::WriteAllText($VbsLauncher, $vbsBody, (New-Object System.Text.ASCIIEncoding))
  $action = New-ScheduledTaskAction -Execute 'C:\Windows\System32\wscript.exe' `
    -Argument ('//B "' + $VbsLauncher + '"') -WorkingDirectory $PSScriptRoot
  $trigger = New-ScheduledTaskTrigger -Once -At (Get-Date).AddMinutes(3) `
    -RepetitionInterval (New-TimeSpan -Minutes $IntervalMinutes)
  $settings = New-ScheduledTaskSettingsSet `
    -MultipleInstances IgnoreNew `
    -StartWhenAvailable `
    -AllowStartIfOnBatteries `
    -DontStopIfGoingOnBatteries `
    -ExecutionTimeLimit (New-TimeSpan -Hours 4)
  $principal = New-ScheduledTaskPrincipal -UserId "$env:USERDOMAIN\$env:USERNAME" -LogonType Interactive
  Register-ScheduledTask -TaskName $TaskName -Action $action -Trigger $trigger -Settings $settings `
    -Principal $principal -Force `
    -Description 'IHUI mobile-rn 全自动发版:检测 origin/main 移动端改动 → 出正式签名包 → Gitee 分片腿 + 站点腿 + app_versions 登记' | Out-Null
  Write-Host "[register] 已注册计划任务 $TaskName(每 $IntervalMinutes 分钟;登录后生效;单实例)" -ForegroundColor Green
  Write-Host "[register] 隐藏启动器: $VbsLauncher(wscript.exe + SW_HIDE,桌面零弹窗)"
  Write-Host "[register] 查看: Get-ScheduledTask -TaskName $TaskName | Get-ScheduledTaskInfo"
  return
}

