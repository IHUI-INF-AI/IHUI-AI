    'packages/app/tests/post-create-screen-ui-fields.test.tsx',
    # 出包门链并发下 git 子进程打穿默认 5s 时限(2026-11-06 实测 5.9s 超时,单跑 1.8s 绿)
    'packages/app/tests/login-screen-hardcoded-zh.test.tsx',
