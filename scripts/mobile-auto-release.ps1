    # 主干自身红:SecuritySettingsScreenProps 的逐项可写性注记被薄壳化提交冲掉,
    # app-account-security-doc-truth 的 ① 判红(2026-11-06)。只补注记,不动类型形状。
    'packages/types/src/app-account.ts',
