#requires -Version 7
<#
.SYNOPSIS
  重建「WorkBuddy 一键切号」桌面快捷方式。

.DESCRIPTION
  快捷方式本身不进版本库（它落在用户桌面），丢了或换机就重跑本脚本。
  双击效果 = 关闭客户端 -> 交互选号 -> 切登录态 + 会话换桶 -> 重启客户端。
  实现全在 scripts/relay-oneclick.cmd + apps/api/scripts/relay-account-switch.ts。

.EXAMPLE
  pwsh -NoProfile -File scripts/install-relay-shortcut.ps1
#>
$ErrorActionPreference = 'Stop'

$repo = Split-Path -Parent $PSScriptRoot
$cmd = Join-Path $repo 'scripts\relay-oneclick.cmd'
if (-not (Test-Path $cmd)) { throw "缺少启动器: $cmd" }

$desktop = [Environment]::GetFolderPath('Desktop')
$lnk = Join-Path $desktop 'WorkBuddy 一键切号.lnk'

$icon = $null
foreach ($root in @(
    'HKCU:\Software\Microsoft\Windows\CurrentVersion\Uninstall\*',
    'HKLM:\Software\Microsoft\Windows\CurrentVersion\Uninstall\*',
    'HKLM:\Software\WOW6432Node\Microsoft\Windows\CurrentVersion\Uninstall\*'
  )) {
  try {
    $hit = Get-ItemProperty $root -ErrorAction SilentlyContinue |
      Where-Object { $_.DisplayName -like 'WorkBuddy*' -and $_.DisplayIcon } |
      Select-Object -First 1
    if ($hit) { $icon = $hit.DisplayIcon; break }
  } catch { }
}

$ws = New-Object -ComObject WScript.Shell
$sc = $ws.CreateShortcut($lnk)
$sc.TargetPath = $cmd
$sc.WorkingDirectory = $repo
if ($icon) { $sc.IconLocation = ($icon -replace ',\s*-?\d+$', '') + ',0' }
$sc.Description = 'WorkBuddy 一键切号:关闭客户端 -> 选号 -> 切号+会话换桶 -> 重启客户端'
$sc.WindowStyle = 1
$sc.Save()

if (-not (Test-Path $lnk)) { throw "创建失败: $lnk" }
Write-Output "OK $lnk"
Write-Output "Target=$($sc.TargetPath)"
Write-Output "Icon=$($sc.IconLocation)"
