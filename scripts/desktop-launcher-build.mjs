// 构建稳定 Launcher 并放到 Tauri 资源目录，供 NSIS 首装写到安装根。
// 用法：node scripts/desktop-launcher-build.mjs
// CI 必须在 `tauri build` 之前执行；否则 tauri.conf.json 的
// bundle.resources["binaries/ihui-launcher.exe"] 不存在，打包会失败（这是故意的：
// 宁可构建失败，也不发布一个没有 Launcher 的安装包）。

import { spawnSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const launcherDir = path.join(root, "apps", "desktop", "launcher");
const outDir = path.join(root, "apps", "desktop", "src-tauri", "binaries");
const outFile = path.join(outDir, "ihui-launcher.exe");
const cargo = process.env.CARGO || "cargo";

function run(args, cwd) {
  const result = spawnSync(cargo, args, {
    cwd,
    stdio: "inherit",
    shell: false,
    // 只有本脚本直接构建 Launcher 时才允许把 VERSION 资源嵌进 exe；
    // Tauri 构建把 launcher 当 path 依赖时不会有这个 env，避免 app 链接重复资源。
    env: { ...process.env, IHUI_LAUNCHER_EMBED_RESOURCE: "1" },
  });
  if (result.error) throw result.error;
  if (result.status !== 0) {
    throw new Error(`cargo ${args.join(" ")} exited ${result.status}`);
  }
}

const metadata = spawnSync(cargo, ["metadata", "--format-version=1", "--no-deps"], {
  cwd: launcherDir,
  encoding: "utf8",
  shell: false,
});
if (metadata.error) throw metadata.error;
if (metadata.status !== 0) throw new Error(`cargo metadata exited ${metadata.status}`);
const targetDirectory = JSON.parse(metadata.stdout).target_directory;

run(["build", "--release"], launcherDir);
const profileDir = path.join(targetDirectory, "release");
const artifact = path.join(profileDir, process.platform === "win32" ? "ihui-launcher.exe" : "ihui-launcher");
if (!fs.existsSync(artifact)) {
  throw new Error(`launcher artifact missing: ${artifact}`);
}
fs.mkdirSync(outDir, { recursive: true });
fs.copyFileSync(artifact, outFile);
const size = fs.statSync(outFile).size;
if (size > 2 * 1024 * 1024) {
  throw new Error(`launcher too large: ${size} bytes (expected <= 2MB)`);
}
console.log(`[launcher] ${outFile} (${(size / 1024).toFixed(1)} KiB)`);
