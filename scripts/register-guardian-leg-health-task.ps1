# Y-72 注册哨兵计划任务(每 15 分钟)。由 SSH 推送后在本机执行,避开 SSH 引号转义。
$ErrorActionPreference = 'Continue'
$taskName = '\IHUI-AI-Guardian-Leg-Health'
$vbs = 'D:\IHUI-AI\scripts\check-guardian-leg-health-hidden.vbs'

Write-Output "=== remove existing (idempotent) ==="
schtasks /delete /tn $taskName /f 2>&1 | Out-Null

Write-Output "=== create task: every 15 min, run vbs hidden ==="
$action  = "wscript.exe `"$vbs`""
$r = schtasks /create /tn $taskName /tr $action /sc minute /mo 15 /ru Administrator /f 2>&1
Write-Output ($r | Out-String)

Write-Output "=== verify ==="
$v = schtasks /query /tn $taskName /fo list /v 2>&1
$v | Select-String -Pattern 'TaskName','Task To Run','Repeat: Every','Status','Run As User','Schedule Type' | ForEach-Object { $_.Line }

Write-Output "=== test run once ==="
schtasks /run /tn $taskName 2>&1 | Out-String
Start-Sleep -Seconds 6
$last = schtasks /query /tn $taskName /fo list /v 2>&1 | Select-String 'Last Run Time','Last Result'
$last | ForEach-Object { $_.Line }
