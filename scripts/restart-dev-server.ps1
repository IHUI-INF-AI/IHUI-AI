#requires -Version 7
# 重启 web dev server:停 8801 端口进程 + 清 .next 缓存
$conns = Get-NetTCPConnection -LocalPort 8801 -State Listen -ErrorAction SilentlyContinue
if ($conns) {
    $pids = $conns.OwningProcess | Sort-Object -Unique
    foreach ($p in $pids) {
        try {
            Stop-Process -Id $p -Force -ErrorAction Stop
            Write-Host "Killed PID $p"
        } catch {
            $msg = $_.Exception.Message
            Write-Host "Failed to kill PID $p : $msg"
        }
    }
    Start-Sleep -Seconds 3
} else {
    Write-Host "No process listening on 8801"
}

# 仓库根从脚本自身位置推导($PSScriptRoot = <仓根>\scripts ⇒ 其父目录即仓根),不写死盘符:
# 原值 'g:\IHUI-AI\apps\web\.next' 是另一台机的仓位置。在本机(仓在 D:\IHUI-AI)上,
# Test-Path 恒为 false ⇒ 清理分支静默空转,而 else 分支照样打印一句话、退出码仍是 0,
# 调用方看到"重启完成"却一个字节的 .next 缓存都没删(盘符属当次实测机器事实,§0.1;
# 不得留下跑不通/空转的出路,§0.8)。此处只改路径推导,杀 8801 端口进程与日志行为不变。
$repoRoot = Split-Path -Parent $PSScriptRoot
$nextPath = Join-Path $repoRoot 'apps\web\.next'
if (Test-Path $nextPath) {
    Remove-Item -Recurse -Force $nextPath
    Write-Host ".next cache cleared"
} else {
    Write-Host ".next cache not present"
}
