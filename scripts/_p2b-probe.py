import importlib.util, json, tempfile
from pathlib import Path

here = Path(__file__).resolve().parent
spec = importlib.util.spec_from_file_location("p2", here / "phase2-local-engine-smoke.py")
p2 = importlib.util.module_from_spec(spec); spec.loader.exec_module(p2)

specb = importlib.util.spec_from_file_location("p2b", here / "phase2b-ollama-adapter.py")
p2b = importlib.util.module_from_spec(specb); specb.loader.exec_module(p2b)

# 验证1:适配器实例化 + as_complete_fn 可调用(假端口,不真连)
adapter = p2b.OllamaLLMAdapter(model="qwen2.5-coder:7b", base_url="http://localhost:9999")
fn = adapter.as_complete_fn()
print("适配器实例化 + as_complete_fn:", callable(fn))

# 验证2:ollama tool_call 形态 → 真实 LocalTools.execute 消费
d = tempfile.mkdtemp(prefix="p2b-probe-")
ws = Path(d)
(ws / "app.py").write_text("def main():\n    return 1\n", encoding="utf-8")
lt = p2.LocalTools(ws)
fake_call = {"id": "c1", "function": {"name": "read_file", "arguments": json.dumps({"path": "app.py"})}}
name = fake_call["function"]["name"]
args = json.loads(fake_call["function"]["arguments"])
assert name in p2.TOOL_WHITELIST, name
result = lt.execute(name, args)
print("read_file 经 ollama tool_call 形态执行:", repr(result))

# 验证3:帧产出过契约
sink = p2.FrameSink()
sink.emit(p2.ev("TOOL_CALL_START"), {"id": "c1", "name": name, "arguments": args})
sink.emit(p2.ev("TOOL_RESULT"), {"id": "c1", "content": result, "isError": False})
print("帧契约 fault:", sink.validate() or "无")
print("\n阶段2b 非ollama腿 全部确定性验证通过")
