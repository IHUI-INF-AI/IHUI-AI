/**
 * 攻防态势守门:只读 posture 报告。
 * 唯一判红条件 = 有实体越过边界(breached>0);报告过期落未判定,不拿旧数字判绿。
 */
import { existsSync, readFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..')
const REPORT = join(ROOT, '.ihui-agent', 'state', 'defense-posture.json')
const MAX_AGE_H = 26

function main() {
  if (!existsSync(REPORT)) {
    console.log('未判定: 尚无态势报告,先跑 node scripts/security/defense-posture.mjs')
    return 2
  }
  let p
  try {
    p = JSON.parse(readFileSync(REPORT, 'utf8'))
  } catch (err) {
    console.log(`未判定: 报告无法解析 ${err?.message ?? err}`)
    return 2
  }
  const ageH = (Date.now() - Date.parse(p.generatedAt ?? '')) / 3600_000
  if (!Number.isFinite(ageH) || ageH > MAX_AGE_H) {
    console.log(`未判定: 态势报告已 ${Number.isFinite(ageH) ? ageH.toFixed(1) : '?'}h 未更新(阈值 ${MAX_AGE_H}h)`)
    return 2
  }
  const breached = p.chain?.breached ?? null
  console.log(`态势: IP ${p.totals?.ips ?? '?'} 封 ${p.totals?.banned ?? '?'} 越界 ${breached ?? '?'} 主机 ${p.triageVerdict ?? '未判定'}`)
  if (breached === null) return 2
  if (breached > 0) {
    console.log(`判红: ${breached} 个实体越过边界,按 kill-chain 阶段立即处置`)
    return 1
  }
  return 0
}

process.exit(main())
