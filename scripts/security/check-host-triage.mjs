/**
 * 主机失陷面守门。读 host-triage 报告,不复算判据(§0.6)。
 * 三态:clean=0 / 有高置信失陷=1 / 未判定或过期=2。
 */
import { existsSync, readFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..')
const REPORT = join(ROOT, '.ihui-agent', 'state', 'host-triage.json')
const MAX_AGE_H = 48

function main() {
  if (!existsSync(REPORT)) {
    console.log('未判定: 尚无主机三查报告,先跑 node scripts/security/host-triage.mjs')
    return 2
  }
  let r
  try {
    r = JSON.parse(readFileSync(REPORT, 'utf8'))
  } catch (err) {
    console.log(`未判定: 报告无法解析 ${err?.message ?? err}`)
    return 2
  }
  const ageH = (Date.now() - Date.parse(r.generatedAt ?? '')) / 3600_000
  if (!Number.isFinite(ageH) || ageH > MAX_AGE_H) {
    console.log(`未判定: 报告已 ${Number.isFinite(ageH) ? ageH.toFixed(1) : '?'}h 未更新(阈值 ${MAX_AGE_H}h)`)
    return 2
  }
  console.log(`主机三查 ${r.verdict}: high=${r.counts?.high ?? '?'} webshell=${r.counts?.webshell ?? '?'} c2=${r.counts?.c2 ?? '?'} persistence=${r.counts?.persistence ?? '?'}`)
  for (const u of (r.unjudged ?? []).slice(0, 5)) console.log(`  未判定 ${u.source}: ${u.path ?? ''} ${u.reason ?? ''}`)
  if (r.verdict === 'breach-suspect') {
    console.log('判红: 发现高置信失陷迹象,立即人工核查')
    return 1
  }
  return r.verdict === 'partial' ? 2 : 0
}

process.exit(main())
