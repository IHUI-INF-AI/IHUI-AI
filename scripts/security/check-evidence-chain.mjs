/**
 * 证据链完整性守门:任何一条被改过/断链/坏行都判红。
 * 无链文件 = 未判定(未启用),不是「干净」。
 */
import { existsSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { readChain, verifyChain } from './lib/evidence-chain.mjs'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..')
const CHAIN = join(ROOT, '.ihui-agent', 'state', 'evidence-chain.jsonl')

function main() {
  if (!existsSync(CHAIN)) {
    console.log('未判定: 证据链尚未建立(跑一次 defense-posture 会自动追加首条)')
    return 2
  }
  const { entries, error } = readChain(CHAIN)
  if (error) {
    console.log(`判红: ${error} —— 链文件被破坏或写入中断`)
    return 1
  }
  const v = verifyChain(entries)
  console.log(`证据链 ${v.count} 条, head=${String(v.head).slice(0, 12)}…`)
  if (!v.ok) {
    console.log(`判红: ${v.reason}(第 ${v.brokenAt} 条起断链)`)
    return 1
  }
  return 0
}

process.exit(main())
