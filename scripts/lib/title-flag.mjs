/**
 * 列表项上的标题旗标在取证里是数字，不是布尔。
 * 布尔值按类型谎报拒绝，不得折成「是用户起的标题」。
 * 数字只原样留下，不解释每个取值的含义。
 */

export function judgeTitleFlag(value) {
  if (typeof value === 'boolean') {
    return { disposition: 'refused', reason: 'boolean-lie', flag: null }
  }
  if (typeof value !== 'number' || !Number.isInteger(value) || !Number.isFinite(value)) {
    return { disposition: 'unjudged', reason: 'title-unmeasured', flag: null }
  }
  return { disposition: 'recorded', reason: 'numeric-flag', flag: value }
}
