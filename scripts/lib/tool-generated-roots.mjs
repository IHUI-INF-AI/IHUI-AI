/**
 * 水印覆盖面的「上游工具生成物」豁免判据 —— 唯一实现(§0.6:同类判据在仓里只许有一份)。
 *
 * 为什么需要这一档(2026-10-16 立项实测):CI `lint-typecheck-test` 的 watermark 步在 HEAD 面判红,
 * 未覆盖 107 份里有 87 份是 `apps/desktop/src-tauri/permissions/autogenerated/*.toml` ——
 * 每份首行写着 `# Automatically generated - DO NOT EDIT!`,且字符串 `permissions/autogenerated`
 * 出现在 `apps/desktop/src-tauri/target/debug/build/‹哈希目录›/build-script-build.exe` 内:写它的是上游
 * Rust build script,不是本仓任何生成器。往里 inject 零宽载荷会被下一次 `tauri build` 洗掉
 * ⇒ 覆盖面从此恒红,而它拦的不是谁的改动,是「跑过一次桌面构建」(§12e 恒红门的定义)。
 *
 * 但豁免绝不能写成"信一句文案":
 *   · 免的是「载荷」这一项,不免前提 —— 落在登记 root 内、却**不自述**为工具产物的文件,
 *     照旧进覆盖面(AGENTS §0.7「验过才免」);
 *   · 每条登记带 expires,到期即整条失效并报名(§0.7「豁免族必须登记存活期」);
 *   · 台账形状不合法(缺 root / markerRegex 编译不过 / 非数组)⇒ 抛 ToolLedgerUnavailable,
 *     由调用方折成「未判定」,**既不冒绿也不冒红** —— 算不出前提时继续判,就是把没量到写成量到了。
 */
import { existsSync, readFileSync } from 'node:fs'
import path from 'node:path'

export const LEDGER_REL = 'scripts/data/watermark-tool-generated.json'

export class ToolLedgerUnavailable extends Error {}

/**
 * 读台账并校形状。返回 entries(数组);文件不在 ⇒ 空数组(该档不存在 = 没有豁免,
 * 覆盖面照旧全量判,这是安全的默认,不是"跳过判定")。
 */
export function loadToolGeneratedEntries(repoRoot) {
  const abs = path.join(repoRoot, LEDGER_REL)
  if (!existsSync(abs)) return []
  let raw
  try {
    raw = JSON.parse(readFileSync(abs, 'utf8'))
  } catch (e) {
    throw new ToolLedgerUnavailable(`${LEDGER_REL} 解析失败:${e.message}`)
  }
  const entries = raw?.entries
  if (!Array.isArray(entries)) {
    throw new ToolLedgerUnavailable(`${LEDGER_REL} 缺 entries 数组(形状不合法 ⇒ 不猜)`)
  }
  const problems = []
  const ok = []
  for (const [i, e] of entries.entries()) {
    const where = `${LEDGER_REL}#entries[${i}]${e?.id ? `(${e.id})` : ''}`
    if (typeof e?.id !== 'string' || !e.id) problems.push(`${where}:id 必须是非空字符串`)
    if (typeof e?.root !== 'string' || !e.root.endsWith('/'))
      problems.push(`${where}:root 必须是目录前缀且以 / 收尾(前缀逐字节比,不做"像不像"的模糊匹配)`)
    if (typeof e?.markerRegex !== 'string' || !e.markerRegex)
      problems.push(
        `${where}:markerRegex 必须是非空字符串 —— 「验过才免」的那一验没有尺就等于整条豁免无人看守`,
      )
    else {
      try {
        new RegExp(e.markerRegex, 'm')
      } catch (err) {
        problems.push(`${where}:markerRegex 编译不过:${err.message}`)
        continue
      }
    }
    if (typeof e?.expires !== 'string' || !/^\d{4}-\d{2}-\d{2}$/.test(e.expires))
      problems.push(`${where}:expires 必须写成 YYYY-MM-DD(§0.7:豁免会到期)`)
    if (!Array.isArray(e?.evidence) || e.evidence.length === 0)
      problems.push(`${where}:evidence 至少一条(能在被审面核验的内容锚点:文件 + 须含文本)`)
    if (typeof e?.reason !== 'string' || e.reason.trim().length < 12)
      problems.push(`${where}:reason 必须写清"为什么免"与"免到什么程度"`)
    ok.push(e)
  }
  if (problems.length > 0) {
    throw new ToolLedgerUnavailable(
      `${LEDGER_REL} 形状不合法 ${problems.length} 处:\n  - ${problems.join('\n  - ')}`,
    )
  }
  return ok
}

/**
 * 判定单份文件是否落在「上游工具生成物」豁免内。
 *
 * @param {{rel:string, text:string|null, entries:Array, today?:string}} p
 *   text = **被审面上**的正文(HEAD blob / 索引 blob —— 与调用方判载荷用的是同一面同一轮);
 *   取不到正文 ⇒ 一律不豁免(算不出前提就不免,方向永远倒向严的一侧)。
 * @returns {{exempt:boolean, why:string|null, entryId:string|null, state:'exempt'|'premise-missing'|'expired'|'not-registered'|'no-content'}}
 */
export function judgeToolGenerated({ rel, text, entries, today }) {
  const norm = String(rel ?? '')
    .split(path.sep)
    .join('/')
  const hit = (entries ?? []).find((e) => norm.startsWith(e.root))
  if (!hit) return { exempt: false, why: null, entryId: null, state: 'not-registered' }
  const day =
    typeof today === 'string' && /^\d{4}-\d{2}-\d{2}$/.test(today)
      ? today
      : new Date().toISOString().slice(0, 10)
  if (day > hit.expires)
    return {
      exempt: false,
      why: `豁免已到期未清:${hit.id} 登记 expires=${hit.expires},现读 ${day}(§0.7)`,
      entryId: hit.id,
      state: 'expired',
    }
  if (typeof text !== 'string')
    return {
      exempt: false,
      why: `落在登记 root(${hit.id})内但被审面取不到正文 ⇒ 前提无法核验,不豁免`,
      entryId: hit.id,
      state: 'no-content',
    }
  const re = new RegExp(hit.markerRegex, 'm')
  if (!re.test(text))
    return {
      exempt: false,
      why: `落在登记 root(${hit.id})内,**但该面不自述为工具产物**(缺 ${JSON.stringify(hit.markerRegex)})⇒ 回到覆盖面按缺载荷判`,
      entryId: hit.id,
      state: 'premise-missing',
    }
  return { exempt: true, why: null, entryId: hit.id, state: 'exempt' }
}

