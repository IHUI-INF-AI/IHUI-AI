/**
 * 圆角豁免标记族的**识别式**(2026-09-29 O81 票㊵ 立)。
 *
 * 为什么单独立一个叶子模块,而不是放进 `radius-tokens.mjs`:
 *  - 该族的"放行"语义已**整体废除**(项目定档「不允许有任何豁免」),剩下的只有一件事 ——
 *    认出哪里写过它。它既不属于单位折算层,也不属于档位表层,把它塞进任何一层都会让那一层的
 *    依赖闭包变大(门 77 本来不引 `radius-tokens`,为了一个正则把整层拖进它的夹具闭包就是这种代价)。
 *  - 识别只能有一份:门 77 用它**判红**(写标记即违规),门 150 用它**报名**(标记不改变任何结论)。
 *    两处各写一遍正则,同一枚标记就会一边被判红、一边被当成不存在 —— 本仓记过最多次的那一型。
 */

/**
 * 两个族名 + **必须带冒号**:
 *  - 冒号是"这是一条指令"的形态。散文里提这个族名(不带冒号)因此不会被判成违规 ——
 *    与本仓"注释里不得出现所描述语言的字法执行字符"那条教训同源:判据不能吃自己的说明文字。
 *  - 判它的必须是**原文行**:标记活在注释里,遮罩之后就永远匹配不到,等于把出口和自己一起抹掉
 *    (门 102 的 GA 族、门 131 的遮罩面同一条)。
 */
export const RADIUS_EXEMPT_MARKER_RE = /\bradius-(?:role-)?exempt\s*:/

/**
 * 第 i 行(0 基)是否带着该族标记。与旧豁免口径同形(本行或紧邻上一行),因为要数的就是
 * "作者想让它管这一处"的那些行。**只用于报名与判红,不构成任何放行。**
 */
export function radiusExemptMarkerAt(lines, i) {
  if (RADIUS_EXEMPT_MARKER_RE.test(lines[i] || '')) return true
  return i > 0 && RADIUS_EXEMPT_MARKER_RE.test(lines[i - 1] || '')
}
