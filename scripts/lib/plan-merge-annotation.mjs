/**
 * plan-merge-annotation.mjs —— 归并器"翻勾注记"形态的**唯一**定义层(2026-09-28 G-307 立)
 *
 * 为什么要有这一层(循环的真实形态,不是假想):
 * 归并器 `plan-tasks-merge.mjs` 把 F1 分叉的未勾副本翻成已完成时,会在行上追加一段
 * `**[归并]** 本行与已完成登记同题…` 注记,而旧实现把这段注记**前置**在正文之前
 * (`- [x] ✅(日期) **[归并]** …。 <正文>`)。看守侧 `check-plan-line-loss.mjs`(守门 71)
 * 的"行首编号"判活路径要求编号落在剥掉复选框与状态装饰后的**正文开头** —— 于是被合法
 * 翻勾的那一行不再算"仍登记",防丢层把归并层的正当改写读成"整行消失",回捞原行(未勾形态),
 * F1 又红,归并层又翻勾…… 2026-09-27 实测两小时内产出 24 枚"恢复型"提交,3/3 复现。
 *
 * 因此"注记长什么样"与"怎么把注记剥回去"**必须只有一份实现**,由生产侧与看守侧共同 import
 * (AGENTS §22c"两处算同一件事必须共用一份实现";本仓记过最多次的失效型就是两处各写一遍必漂)。
 *
 * 两代形态:
 *  - **legacy 前置式**(2026-09-26..27 产出,HEAD 存量):`- [x] ✅(日期) **[归并]** 本行… ⇒ …不重复计账。 <正文逐字>`
 *  - **现行后置式**(G-307 修法):`- [x] ✅(日期) <正文逐字> （[归并] 本行… ⇒ …不重复计账）`
 *    正文回到行首 ⇒ 守门 71 的行首编号判活与标题前缀主键**天然命中**,无需改写任何既有判据语义;
 *    注记以全角括号包裹且以 `（` 起头 ⇒ `titleOf` 在第一个分界符截断,短正文也不会把注记读进主键。
 *
 * 三条不可动摇的纪律:
 *  1. 剥注记只认**本层生成的那一句固定形状**(含 `本行与已完成登记同题` / `本行正文自带作废` 两族
 *     措辞),不做"任意以 ** 包裹的句子"这类泛化 —— 否则"整段登记被删、只在别处留一句引用"
 *     会被洗成"合法改写"(守门 71 的 `headIdOf` 收紧史:1273/1305 两条自检同一课)。
 *  2. 翻勾**不得动正文**:复选框与状态装饰可改,注记可加,租约标记 `（进行中…）` 必须摘
 *     (守门 109 CL3 判"同 `[x]` 又挂租约"),其余逐字保留。`forkPreserved` 是这条纪律的
 *     成对判据,被 `verifyMerge` 用作落地闸(红在落地那一刻,而不是留给下一个人)。
 *  3. 注记文本里**不得出现 `。` 与全角 `）`**(前/后置剥取分别以它们为终止锚)。
 *
 * §5c 溯源水印:本文件受 `scripts/watermark.mjs` 管理。
 */

/** 复选框前缀(与守门 71 的 `checkboxBody`、索引层的 `CHECKBOX_RE` 同形;两处历史各自持有,本层只服务注记剥取)。 */
const CHECKBOX_PREFIX_RE = /^\s*[-*]\s\[[ xX]\]\s*/
/** 复选框后可连续出现的状态装饰:`✅(日期)` / `⏳(…)` / 裸 `(已完成)` 等(形状同守门 71 的循环剥取)。 */
const STATE_DECOR_RE = /^[✅⏳☑✔✓🕐⚠]?\s*[（(][^）)]*[）)]\s*/
/** 认领租约标记(旧裸形与新租约形)。翻勾摘牌与"翻勾前后等价比较"共用这一条,不得两处各抄。 */
export const LEASE_RE = /（进行中(?:@[^）]*)?）\s*/g

/**
 * legacy 前置式注记(2026-09-26 起至 G-307 修法落地前由归并器产出,HEAD 存量大族)。
 * 锚点 = `**[归并]**`/`**【归并】**` + `本行` 开头的两族固定措辞,终止于第一个 `。`。
 * ⚠ 刻意不写成"任意 `**…**` 前缀"——见文件头纪律 1。
 */
export const FORK_PREFIX_RE =
  /^\*\*[【\[]归并[】\]]\*\*\s*本行(?:与已完成登记同题|正文自带作废)[^。]*。\s*/
/** 现行后置式注记(行尾、全角括号包裹、内部只用半角括号)。 */
export const FORK_SUFFIX_RE = /（\[归并\] 本行(?:与已完成登记同题|正文自带作废)[^（）]*）$/
/** 后置式的"任意位置"形状,只用于幂等检测(不改写已带注记的行)。2026-09-30 起另被归并器的"完成被打断的翻勾"消费 ⇒ 导出(两处算同一件事必须同一份实现)。 */
export const FORK_SUFFIX_ANY_RE = /（\[归并\] 本行(?:与已完成登记同题|正文自带作废)[^（）]*）/

/** 内容锚点(主键 → 「G-256 · 一条…」):编号重复时剥掉一份,读起来不是自复制。形状沿用归并器旧出口。 */
export function anchorOf(key) {
  const [id, rest = ''] = String(key).split('#')
  return `「${id}${rest && !rest.startsWith(id) ? ' · ' + rest : ''}」`
}

/** 注记的"为什么"句(两族措辞都不含 `。` 与全角 `）`,满足纪律 3)。 */
function whyOf(key) {
  return key
    ? `本行与已完成登记同题(主键 ${anchorOf(key)}),是被并发并集留下的未翻勾副本`
    : '本行正文自带作废/已完成声明,却仍挂着未勾选,状态与正文两相矛盾'
}

/**
 * 生产侧唯一出口:把一条 `- [ ]` 登记行翻成已完成。
 * 只改复选框、只摘租约、只在**行尾**追加注记;正文保持逐字并留在行首(见文件头"现行后置式")。
 * 已经是 `[x]` 的行原样返回(不得二次改写已完成登记)。
 */
export function buildForkedLine(line, key, today) {
  if (!/^\s*[-*]\s\[ \]/.test(line)) return line
  const raw = line.replace(/^\s*[-*]\s\[ \]\s*/, '')
  if (hasForkAnnotation(raw)) return line
  const body = raw.replace(LEASE_RE, '')
  return `- [x] ✅(${today}) ${body} （[归并] ${whyOf(key)} ⇒ 只落状态、正文逐字保留于前、不删行、不重复计账）`
}

/**
 * 幂等判据必须认**自己的标记形态**,不能认裸词"归并":HEAD 里有一整批
 * `- [ ] **本行是并发 union 归并留下的裸副本**…` 行,正文天然含"归并"二字却**根本没落账**
 * (勾还是空的)。按裸词判"已处理"会把这些行判成"无可施加的改写"——恰好把本工具要修的
 * 那一型当成已完成。故只认:前置式形状 / 后置式形状 / 裸标记 token `**[归并]**``**【归并】**`。
 */
const TAG_TOKEN_RE = /\*\*[【\[]归并[】\]]\*\*/

/** 这行(任意一形态的注记,或裸文本里出现注记)是否已带翻勾注记 —— 幂等检测用。 */
export function hasForkAnnotation(text) {
  return FORK_PREFIX_RE.test(text) || FORK_SUFFIX_ANY_RE.test(text) || TAG_TOKEN_RE.test(text)
}

/** 剥掉 legacy 前置注记(看守侧 `checkboxBody` 在装饰剥取之后调用一次)。 */
export function stripForkPrefix(body) {
  return body.replace(FORK_PREFIX_RE, '')
}

/**
 * 取一行"翻勾前后的共同正文":剥复选框、剥状态装饰、摘租约、剥两族注记。
 * 非复选框行返回 null(调用方不得拿它当"已确认相等")。
 */
export function forkBodyOf(line) {
  const m = CHECKBOX_PREFIX_RE.exec(line)
  if (!m) return null
  let body = line.slice(m[0].length)
  for (;;) {
    const before = body
    body = body.replace(STATE_DECOR_RE, '')
    if (body === before) break
  }
  body = body.replace(FORK_PREFIX_RE, '')
  body = body.replace(FORK_SUFFIX_RE, '')
  // 注记与正文之间的单个分隔空格由本层生成 ⇒ 剥除后一并去掉行尾空白("追加注记"不得算改正文)
  return body.replace(LEASE_RE, '').replace(/\s+$/, '')
}

/**
 * 成对判据(纪律 2 的可执行形态):`before` 是未勾登记行时,`after` 的正文必须与其
 * **逐字相等**(剥复选框/装饰/租约/本层注记后)。非翻勾改写(before 不是 `[ ]`)恒真,
 * 由调用方限定适用范围;是 `[ ]` 而 after 给不出可剥正文 ⇒ 判假。
 */
export function forkPreserved(beforeLine, afterLine) {
  if (!/^\s*[-*]\s\[ \]/.test(beforeLine)) return true
  const b = forkBodyOf(beforeLine)
  const a = forkBodyOf(afterLine)
  if (b === null || a === null) return false
  return a === b
}
