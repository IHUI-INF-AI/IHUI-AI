/**
 * 启动画像的开关与输出路径。
 * 未开启时 write 恒为 false，调用方不得落盘。
 * 路径里的控制字符直接拒绝，不回显该路径。
 * 开了开关但没给出路径，记为未判定，不替调用方挑一个目录。
 */

const ENABLE = '--startup-prof'
const MARKDOWN = '--startup-prof-md'
const DIR = '--startup-prof-dir'
const NAME = '--startup-prof-name'

function blank(reason) {
  return { disposition: 'unjudged', reason, write: false, format: null, dir: null, name: null }
}

function hasControlCharacter(value) {
  for (let i = 0; i < value.length; i += 1) {
    const code = value.charCodeAt(i)
    if (code < 32 || code === 127) return true
  }
  return false
}

function takeValue(argv, index) {
  const value = argv[index + 1]
  if (typeof value !== 'string' || value.length === 0 || value.startsWith('--')) return null
  return value
}

export function planStartupOutput(input) {
  const argv = input?.argv
  const enabled = input?.enabled
  if (!Array.isArray(argv) || argv.some((item) => typeof item !== 'string')) return blank('argv-unmeasured')
  if (typeof enabled !== 'boolean') return blank('switch-unmeasured')

  let on = enabled
  let format = 'text'
  let dir = null
  let name = null
  for (let i = 0; i < argv.length; i += 1) {
    const token = argv[i]
    if (!token.startsWith('--startup-prof')) continue
    if (token === ENABLE) {
      on = true
      continue
    }
    if (token === MARKDOWN) {
      on = true
      format = 'markdown'
      continue
    }
    if (token === DIR || token === NAME) {
      on = true
      const value = takeValue(argv, i)
      if (value === null) return blank('value-unmeasured')
      if (hasControlCharacter(value)) {
        return { disposition: 'refused', reason: 'control-character', write: false, format: null, dir: null, name: null }
      }
      if (token === DIR) dir = value
      else name = value
      i += 1
      continue
    }
    return blank('flag-unknown')
  }

  if (!on) {
    return { disposition: 'off', reason: 'not-enabled', write: false, format: null, dir: null, name: null }
  }
  if (dir === null && name === null) return blank('path-unmeasured')
  return { disposition: 'on', reason: 'opt-in', write: true, format, dir, name }
}
