/**
 * 日志包只收龄期已经量到、并且不老于调用方给出的天数的文件。
 * 天数、当前时刻或任一文件的修改时间没量到，整包未判定，不交出一份悄悄缺了文件的包。
 */

const DAY_MS = 86_400_000

function finiteNumber(value) {
  return typeof value === 'number' && Number.isFinite(value)
}

export function judgeLogPack(input) {
  const empty = (reason) => ({ disposition: 'unjudged', reason, files: null })
  if (!Number.isInteger(input?.maxAgeDays) || input.maxAgeDays <= 0) return empty('age-unmeasured')
  if (!finiteNumber(input.nowMs)) return empty('time-unmeasured')
  if (!Array.isArray(input.files)) return empty('files-unmeasured')
  const kept = []
  for (const file of input.files) {
    if (file === null || typeof file !== 'object') return empty('mtime-unmeasured')
    if (typeof file.path !== 'string' || file.path.trim() === '') return empty('path-unmeasured')
    if (!finiteNumber(file.mtimeMs)) return empty('mtime-unmeasured')
    if (file.mtimeMs > input.nowMs) return empty('time-inverted')
    if (input.nowMs - file.mtimeMs <= input.maxAgeDays * DAY_MS) kept.push(file.path)
  }
  return { disposition: 'packed', reason: 'within-age', files: kept }
}
