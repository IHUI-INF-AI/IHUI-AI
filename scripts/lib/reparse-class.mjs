/**
 * 重解析点只区分已取证的挂载点与符号链接。
 * 标签或替代名没量到是未判定，不得把该路径说成文件丢失，也不得跟着跳进去。
 */

const MOUNT_POINT = 0xa0000003
const SYMLINK = 0xa000000c

function kindOf(tag) {
  if (tag === MOUNT_POINT || tag === 'MOUNT_POINT') return 'mount-point'
  if (tag === SYMLINK || tag === 'SYMLINK') return 'symlink'
  return null
}

export function classifyReparse(input) {
  const tag = input?.tag
  if (tag === null || tag === undefined) {
    return { disposition: 'unjudged', reason: 'tag-unmeasured', kind: null }
  }
  const kind = kindOf(tag)
  if (!kind) return { disposition: 'unjudged', reason: 'tag-unknown', kind: null }
  if (typeof input.substitute !== 'string' || input.substitute.trim() === '') {
    return { disposition: 'unjudged', reason: 'substitute-unmeasured', kind }
  }
  return { disposition: 'classified', reason: 'reparse', kind, substitute: input.substitute }
}
