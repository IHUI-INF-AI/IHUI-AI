/**
 * 活文档行相似度的**唯一实现**(纯函数,零副作用)。
 *
 * 为什么要单独成库:`merge-live-doc.mjs` 的顶层就是 CLI 主流程且**没有** §22d 的 `isDirectRun`
 * 守卫 —— 直接 `import { jaccard } from './merge-live-doc.mjs'` 会把它的参数校验跑一遍并
 * `process.exit(2)`(2026-09-25 我给 `check-task-claims.mjs` 加孪生判据时实测撞上:扫描器
 * 一 import 就死,`--json` 输出变成"✗ 必须给 --file")。而这份相似度**必须只有一处实现** ——
 * 两处各算一次,迟早分叉成"一边判孪生、一边判真丢失",那正是本仓最怕的"两套真相"。
 *
 * 相似度取**字符二元组**而不是"词":台账/文档里的行是中日混排,按空格/标点切词会把整段中文
 * 切成 1-2 个巨块 token,一改写 Jaccard 就断崖下跌(实测同一句话的两种写法只剩 0.357 ⇒
 * 被判成"两件事",老版本被插回 ⇒ 文档里同时留下两行,正是这类工具要防的"新老并存")。
 * 字符二元组对 CJK 与拉丁都稳定,且不依赖分词器。
 */
export const SIM_THRESHOLD = 0.6

/** 非空白字符下界:再短的裸标记行(`- [ ]` 等)在满屏清单里必然互含,会把无关项判成同一条。 */
export const CONTAIN_MIN = 20

export function tokenize(s) {
  const norm = s.replace(/[\s]+/g, '').replace(/[、。（）「」]/g, (c) => (c === '、' ? '' : c))
  const out = new Set()
  for (let i = 0; i < norm.length - 1; i += 1) out.add(norm.slice(i, i + 2))
  if (norm.length === 1) out.add(norm)
  return out
}

export function jaccard(a, b) {
  let inter = 0
  for (const t of a) if (b.has(t)) inter += 1
  const union = a.size + b.size - inter
  return union === 0 ? 0 : inter / union
}

/** 抹掉全部空白 —— 用于"逐字包含"这条补充通道(追加取证会让 Jaccard 单调下降,只靠阈值会漏)。 */
export const squash = (s) => s.replace(/\s+/g, '')

/**
 * 行首"勾选态 + 认领括号"前缀 —— 比较逐字包含前必须先剥掉它。
 *
 * 不剥会出什么事(2026-09-25 实测两次):本仓翻勾的写法是 `- [ ]（进行中） X` →
 * `- [x] ✅(日期) X + 追加证据`,**行首状态标记本身就变了**,于是 HEAD 那行永远不可能
 * "原样"存在于新行里 ⇒ 容器通道整条失效 ⇒ 判真丢失 ⇒ `--apply` 把改写前那行插回 ⇒
 * 同一条目"未勾 + 已勾"两行并存。只剥状态标记与认领括号,**正文一字不动**,所以
 * "真被删掉的行"依然不会被洗绿(自检 ⑫ 钉住这条边界)。
 *
 * **第二次于同日补刀**:第一版只剥了 `- [x]` 与 `（进行中）`,漏了翻勾同时加的 `✅(日期)` 戳
 * —— 于是带日期戳的那条仍然"不逐字包含",容器通道照样失效,守卫照样拦下一次合法提交。
 * 教训:**给"就地改写 vs 真删除"分类的判据,必须枚举本项目所有合法编辑形态**
 * (延长 / 换状态标记 / 加完成日期戳 / 改指针前缀),只补眼前那一种,下次就换个触发条件再咬一遍。
 */
export const STATE_PREFIX =
  /^\s*- \[[x ]]\s*(?:（进行中(?:@[^）]*)?）|\(进行中(?:@[^)]*)?\))?\s*(?:✅\s*(?:\([^)]*\)|（[^）]*）)\s*)?/
export const stripState = (s) => s.replace(STATE_PREFIX, '')
