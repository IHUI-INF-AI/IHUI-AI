/**
 * 代理文件系统只接纳已取证的十二个入口。
 * 钩子开关或沙箱档有一个明确为真才拦截。两个都没量全，不得当成关闭后直通。
 * 拦截开启后会话号缺失是未判定，不得静默放行。
 * 本层只决定要不要发令牌，不决定字节能不能写。
 */

export const BROKERED_FS_OPS = Object.freeze([
  'readFile',
  'writeFile',
  'appendFile',
  'open',
  'copyFile',
  'mkdir',
  'rmdir',
  'rm',
  'unlink',
  'rename',
  'symlink',
  'chmod',
])

function stopped(disposition, reason) {
  return { disposition, reason, intercept: false, issueToken: false }
}

function switchOf(hookEnabled, sandboxOn) {
  if (hookEnabled === true || sandboxOn === true) return 'on'
  if (hookEnabled === false && sandboxOn === false) return 'off'
  return 'unmeasured'
}

export function admitBrokeredFs(input) {
  const record = input !== null && typeof input === 'object' ? input : {}
  const mode = switchOf(record.hookEnabled, record.sandboxOn)
  if (mode === 'unmeasured') return stopped('unjudged', 'switch-unmeasured')
  if (mode === 'off') return stopped('off', 'hook-off')
  if (typeof record.op !== 'string' || !BROKERED_FS_OPS.includes(record.op)) {
    return { disposition: 'unjudged', reason: 'op-unknown', intercept: true, issueToken: false }
  }
  if (typeof record.sessionId !== 'string' || record.sessionId.trim() === '') {
    return { disposition: 'unjudged', reason: 'session-absent', intercept: true, issueToken: false }
  }
  return { disposition: 'admitted', reason: 'needs-token', intercept: true, issueToken: true }
}
