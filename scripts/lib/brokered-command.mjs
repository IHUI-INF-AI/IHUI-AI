/**
 * 只承认取证目录里点名的那些命令。
 * 目录说明写了 30 条，点名清单对不上这个数，所以没点名的命令保持未判定，不执行，也不判成禁用。
 * 本函数不启动任何程序。
 */

export const BROKERED_COMMANDS = Object.freeze([
  '7z',
  'cat',
  'chmod',
  'cp',
  'dd',
  'find',
  'grep',
  'head',
  'ln',
  'ls',
  'mkdir',
  'mv',
  'rar',
  'readlink',
  'realpath',
  'rm',
  'rmdir',
  'sed',
  'tail',
  'tar',
  'tee',
  'touch',
  'truncate',
  'unlink',
  'wc',
  'zip',
  'codebuddy-toybox-dispatch',
])

function baseName(name) {
  const leaf = name.split(/[/\\]/).pop() ?? name
  return leaf.replace(/\.exe$/i, '')
}

export function admitBrokeredCommand(name) {
  if (typeof name !== 'string' || name.trim() === '') {
    return { disposition: 'unjudged', reason: 'name-unmeasured', broker: false }
  }
  const base = baseName(name.trim())
  if (BROKERED_COMMANDS.includes(base)) {
    return { disposition: 'admitted', reason: 'known-command', broker: true }
  }
  return { disposition: 'unjudged', reason: 'name-unlisted', broker: false }
}
