/**
 * 强制 Windows 控制台按 UTF-8(65001)渲染中文(治乱码,2026-11-15 立)。
 *
 * 真因(实测取证,非猜):切号脚本一律 process.stdout.write 中文(UTF-8 字节),而写回腿
 * spawn 下游用 stdio:'inherit' —— 子进程**直接往共享控制台**写字节。控制台代码页若不是
 * 65001(直接 `node scripts/x.mjs` 那路仍是默认 936/GBK),UTF-8 被 GBK 渲染 = 乱码
 * (实测:`代关` → `ä»£å…³`)。双击 .cmd 那路因 .cmd 里有 `chcp 65001` 所以正常。
 *
 * 为什么不是 setEncoding:process.stdout.setEncoding 只设 Node 流的**读方向解码**;
 * 乱码在**写方向**(代码页渲染),setEncoding 碰不到。唯一有效的是改**控制台代码页**。
 *
 * 修法:进程起来时同步执行 `chcp 65001`,把当前控制台切成 UTF-8。仅在 win32 且
 * process.stdout.isTTY(真终端直写)时做 —— pipe/重定向不经代码页渲染,不必也不该改。
 * 取不到/chcp 失败一律静默跳过(尽力而为,不阻断主链;此时最坏退回原乱码,不会更差)。
 *
 * 副作用:会改变调用者终端的代码页(切号本就是用户主动跑的短命 CLI,可接受)。
 * 这是唯一实现,各入口 import 复用,不另写第二份(§0.6)。
 */
import { execFileSync } from 'node:child_process'

export function forceUtf8Stdio() {
  // 仅 Windows 真终端直写才需要改代码页;pipe/非 win32 不经代码页渲染,跳过
  if (process.platform !== 'win32' || !process.stdout?.isTTY) return
  try {
    execFileSync('chcp.com', ['65001'], { stdio: 'ignore', timeout: 4000 })
  } catch {
    /* 改不动代码页就退回原状(最坏仍是乱码,不会更差;不阻断主链) */
  }
  // 附带把 Node 流编码也钉 utf8:对读方向无害,写方向交给上面的 chcp 保证
  try {
    process.stdout?.setEncoding?.('utf8')
  } catch {
    /* 尽力而为 */
  }
  try {
    process.stderr?.setEncoding?.('utf8')
  } catch {
    /* 尽力而为 */
  }
}

export const __test__ = { forceUtf8Stdio }
