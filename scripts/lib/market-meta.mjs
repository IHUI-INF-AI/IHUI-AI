/**
 * 市场元数据必须同时有 etag、内容哈希和来源身份。缺任何一件都是未判定。
 */

const SHA256_RE = /^[0-9a-f]{64}$/

export function judgeMarketMeta(input) {
  const etag = input?.etag
  const sourceKey = input?.sourceKey
  const sha256 = input?.sha256
  if (typeof etag !== 'string' || etag.length === 0) {
    return { disposition: 'unjudged', reason: 'etag-unmeasured' }
  }
  if (typeof sourceKey !== 'string' || sourceKey.length === 0) {
    return { disposition: 'unjudged', reason: 'source-unmeasured' }
  }
  if (typeof sha256 !== 'string' || !SHA256_RE.test(sha256)) {
    return { disposition: 'unjudged', reason: 'hash-unmeasured' }
  }
  return { disposition: 'sealed', reason: 'etag-and-hash' }
}
