/**
 * git grep 枚举参数(只列文件名、不取正文)的唯一构造函数,供门 251 与夹具共用一把尺。
 *
 * 立因(2026-11-07 实测):`git grep -l -E <pattern> --cached` 里 `--cached` 落在 pattern
 * 之后 ⇒ git 把它当成 revision 名 → `fatal: unable to resolve revision: --cached`,rc=2。
 * 调用方若把「跑不起来」读成「无命中」,就会得到一道**永远绿、却从未检查过任何东西**的假门
 * (门 251 的 staged 面此前正是如此)。参数顺序不是风格问题,是判据存亡问题。
 *
 * `scripts/tests/git-grep-arg-order.test.mjs` 锁住三件事:
 *  ① `--cached` 必须在 `-E`/pattern 之前;② 旧顺序对 git 必须 rc=2(可见错误);
 *  ③ 正确顺序只能是 0(有命中)/1(无命中),绝不能是 2。
 */
export const RN_GREP_PATTERN = "from '(react-native|lucide-react-native)'"

const FACES = new Set(['staged', 'head', 'worktree'])

export function buildGrepListArgs(face, pattern, paths) {
  if (!FACES.has(face)) throw new Error(`buildGrepListArgs: 未知面 ${face}`)
  if (typeof pattern !== 'string' || pattern.length === 0) throw new Error('buildGrepListArgs: pattern 不能为空')
  if (!Array.isArray(paths) || paths.length === 0) throw new Error('buildGrepListArgs: paths 不能为空')
  return [
    'grep',
    ...(face === 'staged' ? ['--cached'] : []),
    '-l',
    '-E',
    pattern,
    ...(face === 'head' ? ['HEAD'] : []),
    '--',
    ...paths,
  ]
}
