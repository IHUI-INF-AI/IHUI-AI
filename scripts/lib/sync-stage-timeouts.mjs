/**
 * 客户端会话回灌腿的节拍常量与失败身份判据(2026-11-05 立,单源 §0.6)。
 *
 * 为什么要有这一份:三条同型腿(qoder/trae/minimax)此前各自写死 `120_000`,而 120 秒这个数
 * 是 2026-10-28 随手定的(`0efd05ef9ee4`,文档里没有定值依据)。生产实测才是依据:
 *   - 合成加压(CPU 打满 99-100%)80 轮整轮 **0 次超时**,最慢 45.7 秒;
 *   - 同期生产日志 30 轮却有 **6 轮超时(20%)**,其中捕获段最慢的一次**完成**值是 107 秒。
 *   ⇒ 长尾不来自 CPU 占用本身,而来自 pwsh/node 冷启动排队(生产那几轮正是任务腿与队列腿
 *     撞在同一分钟里);合成夹具量不出可信 p99,所以窗口只能锚生产读数,不能锚实验值。
 * 取值口径(逐档都给得出算式,不是"翻个倍"):
 *   - 捕获段 240s = 已完成的单段最慢值 107s × 2.2(常态 p90 的 160 倍);
 *   - 落库段 240s = 生产有 4 轮在 120s 处被杀,右删失 ⇒ 拿不到真值,与捕获段对称取同档,
 *     **不另造一个没量过的数**;
 *   - worker 外层 540s = 两段之和 480s + 启动与心跳探测 60s,且刻意 <600s 的每 10 分钟节拍,
 *     不让一轮跨拍。原值 180s 比两段之和还小,它自己的注释写着"比内层(120s)宽"——那个前提
 *     从立那天起就不成立;外层杀父在 Windows 上不杀孙,实测留下过孤儿子进程,把外层抬到
 *     两段之和以上即是这一格的结构性收口(不引入 taskkill /T 这类新依赖)。
 */

/** 捕获段:pwsh 解 DPAPI + 读会话(spawnSync timeout) */
export const CAPTURE_TIMEOUT_MS = 240_000
/** 落库段:tsx 跑判据脚本并写库(自管定时器 kill) */
export const DB_WRITE_TIMEOUT_MS = 240_000
/** worker 外层:必须 ≥ 两段之和,且小于派发节拍,避免跨拍叠罗汉 */
export const WORKER_OUTER_TIMEOUT_MS = 540_000

/**
 * 失败身份文案(纯函数,可测)——把「超时」从"反推信号"改成一等读数。
 *
 * 旧形态是 `stderr || \`退出码 … 信号 …\``:子进程只要往 stderr 写过任何东西(本仓的 ts 脚本
 * 常态会打 db/连接噪音),超时这件事就被 stderr 顶掉,于是"我们把它等死了"和"它自己崩了"
 * 在账面上是同一句话。AGENTS §0.3 的口径是两桶必须分开 —— 失效方向必须是"多要一次定向说明",
 * 不能是"合并成一个模糊读数"。
 *
 * @param p.timedOut   本方定时器真的把它杀了(调用方必须在 kill 前置真)
 * @param p.signal     子进程退出时的信号(可能由别人发,不能当超时的证据)
 * @param p.code       退出码(null = 被信号终止)
 * @param p.stderr     子进程 stderr 原文
 * @param p.limitMs    本方窗口,写进文案好让人判断该不该调
 */
export function stageFailureText({ timedOut, signal, code, stderr, limitMs }) {
  if (timedOut) {
    // 超时优先于 stderr:这是"我们等死了它",不是"它报错了"
    return `超时被杀(本方窗口 ${limitMs}ms 到点 kill;信号 ${signal ?? 'n/a'})${
      stderr ? `;子进程 stderr 尾部: ${stderr.slice(0, 160)}` : ''
    }`
  }
  const detail = stderr
    ? stderr.slice(0, 300)
    : `退出码 ${code ?? '?'}${signal ? ` 信号 ${signal}` : ''}`
  return detail
}

/** 是否属于「未判定」(取不到结论),与「判过且失败」分桶用 */
export function isUndeterminedOutcome({ timedOut, code }) {
  return timedOut === true || code === null || code === 2
}
