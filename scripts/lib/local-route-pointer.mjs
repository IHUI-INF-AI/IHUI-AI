/**
 * 本机多客户端路由只留回环地址、进程号、启动时刻和指纹引用。
 * 凭据字段出现在指针里就拒绝；指纹没量到是未判定，不退回“没有密钥”。
 */

const SECRET_FIELDS = ['apiKey', 'token', 'secret', 'password', 'accessToken']
const LOOPBACK = new Set(['127.0.0.1', 'localhost'])

function nonEmpty(value) {
  return typeof value === 'string' && value.trim() !== ''
}

export function judgeLocalRoute(record) {
  if (record === null || typeof record !== 'object' || Array.isArray(record)) {
    return { disposition: 'unjudged', reason: 'record-unmeasured' }
  }
  for (const field of SECRET_FIELDS) {
    if (nonEmpty(record[field])) {
      return { disposition: 'refused', reason: 'secret-on-disk' }
    }
  }
  if (!Number.isInteger(record.pid) || record.pid <= 0) {
    return { disposition: 'unjudged', reason: 'pid-unmeasured' }
  }
  if (typeof record.startedAt !== 'number' || !Number.isFinite(record.startedAt)) {
    return { disposition: 'unjudged', reason: 'time-unmeasured' }
  }
  let url
  try {
    url = new URL(record.baseUrl)
  } catch {
    return { disposition: 'unjudged', reason: 'url-unmeasured' }
  }
  if (url.protocol !== 'http:' || !LOOPBACK.has(url.hostname) || url.port === '') {
    return { disposition: 'refused', reason: 'host-not-local' }
  }
  if (!nonEmpty(record.keyRef)) {
    return { disposition: 'unjudged', reason: 'key-unmeasured' }
  }
  if (record.keyRef.length > 64 || !/^[A-Za-z0-9_-]+$/.test(record.keyRef)) {
    return { disposition: 'refused', reason: 'secret-shaped' }
  }
  return { disposition: 'admitted', reason: 'loopback-pointer' }
}
