/**
 * rn-shell-target.mjs —— 「共享屏 → RN 壳路径」的唯一约定(2026-11-03 抽出)。
 *
 * 覆盖门(check-rn-host-shell-coverage.mjs)与造壳器(gen-rn-shell-scaffold.mjs)共用这一把尺,
 * 避免两处按 basename 各猜一次、把登记表里改过名的屏判成"无壳"。
 * 在册优先(scripts/data/cross-end-screen-registry.json 的 shared→rn),否则 basename 约定。
 */

import { basename } from 'node:path'

export const RN_DIR = 'apps/mobile-rn/src/screens'

/** @param {string} specRel 共享屏相对路径 @param {Array<{shared:string,rn?:string}>} registryRows */
export function targetPathOf(specRel, registryRows = []) {
  const hit = (registryRows || []).find(
    (r) => r && r.shared === specRel && typeof r.rn === 'string' && r.rn,
  )
  if (hit) return hit.rn
  return `${RN_DIR}/${basename(specRel)}`
}
