// 票键的唯一实现(台账行 → 票键)。
//
// 为什么抽出来:台账上的行在三处被取键(建单台账 / 派单台账 / 审计台账),三处各自算一次
// SHA-256 前 16 位 ⇒ 同一张票在三处变成三个键 ⇒ “票→提交环”永远串不上。
// 本文件是唯一实现;已有消费方一律 import 它,不得再拄一份。

import { createHash } from 'node:crypto'

/**
 * 票键:台账行文本 → 稳定的 16 位协议指纹(同一张票在不同处理者台账里得到同一个键)。
 *
 * 剥除顺序固定:先项目前缀 → 再租约标 → 再旁边标头。
 * 剥掉的都是“会变的外壳”(项目状态、租约、归属标签),不剥的都是“题目本身”。
 *
 * ⚠ 不得把时刻/计数/轨迹号拼进去:同一个缺陷换了时刻换了轨迹就必须变成另一个键
 *   ⇒ 同一件事每次都像新缺陷。
 */
export function ticketKeyOf(rowText) {
  const stripped = String(rowText)
    .replace(/^[-*]\s*\[[ x]\]\s*/, '')
    .replace(/^（进行中@[^）]*）\s*/, '')
    .replace(/（进行中@[^）]*）\s*$/, '')
    .replace(/〔[^〕]*〕/g, '')
    .replace(/\s+/g, ' ')
    .trim()
  return createHash('sha256').update(stripped).digest('hex').slice(0, 16)
}

