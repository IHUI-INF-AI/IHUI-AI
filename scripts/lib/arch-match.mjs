/**
 * 用公开的 COFF 机器号对照当前进程架构。
 * 机器号或“是否允许 32 位兼容”没量到都是未判定，不得当成匹配。
 */

const MACHINE_NAMES = new Map([
  [0x014c, 'x86'],
  [0x8664, 'x64'],
  [0xaa64, 'arm64'],
  ['I386', 'x86'],
  ['AMD64', 'x64'],
  ['ARM64', 'arm64'],
])

export function judgeArchMatch(input) {
  const processArch = input?.processArch
  if (processArch !== 'x86' && processArch !== 'x64' && processArch !== 'arm64') {
    return { disposition: 'unjudged', reason: 'process-unmeasured' }
  }
  const fileArch = MACHINE_NAMES.get(input?.fileMachine)
  if (!fileArch) return { disposition: 'unjudged', reason: 'machine-unmeasured' }
  if (fileArch === processArch) return { disposition: 'match', reason: 'same-arch' }
  if (typeof input.wow64 !== 'boolean') {
    return { disposition: 'unjudged', reason: 'wow64-unmeasured' }
  }
  if (input.wow64 === true && processArch === 'x64' && fileArch === 'x86') {
    return { disposition: 'match', reason: 'wow64-x86' }
  }
  return { disposition: 'foreign', reason: 'arch-mismatch' }
}
