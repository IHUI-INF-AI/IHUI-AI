/**
 * 守门批的「地基探针」—— 整批开跑之前先问一句:这个仓库此刻**答不答得上话**。
 *
 * 为什么单独成一个 lib(而不是住在 runner 里):`scripts/guardian-runner.mjs` 顶层就是
 * 执行体(没有 §22d 的 `isDirectRun` 守卫 —— 给它加那道守卫要动 4000+ 行的入口结构,
 * 不属本票范围),所以任何判据只要住在 runner 里就**无法被测试 import**;而这条判据
 * 恰恰是"量不到 vs 量到了健康"这种三态逻辑,没有纯函数面就只能靠真把 .git 弄坏一次来取证。
 *
 * 立因(2026-09-29 05:16–05:19 实测):gitdir 的 `core.bare` 在外部清工作树期间漂成
 * `true`,约 90 秒后守护自愈(`.workbuddy/git-guardian.log` 有整条流水)。那个窗口里五道门
 * (137 / 140 / 141 / 146 / 149)各自打印
 * `❌ 无法判定:git rev-parse 失败: fatal: this operation must be run in a work tree`,
 * 而分发循环把任何非零码一律计成「blocking 失败,提交已阻止」——
 * **一场与任何提交都无关的仓库瞬时故障,于是变成全队每次提交要么被挡、要么 `--no-verify`**
 * (一次绕过 = 该枚提交上全部守门作废,§12e/§12f 记过多次)。
 *
 * 为什么不顺手把「门返回 exit 2」改成不阻塞:本仓 exit 2 有**两义** —— 多数门用它表示
 * "取不到 ⇒ 无法判定",而 §22d 的脚本入口用它表示"脚本自身异常"。一刀切会把"门自己崩了"
 * 洗成绿灯,那是更坏的方向。所以只判**唯一能确定**的那一格:地基问不到就是问不到,
 * 与具体哪道门、与门自己的写法都无关。
 *
 * 失效方向:一律**偏向"不可用"**(宁可少跑一轮,也不把"没判"写成"判过了")。
 */

/**
 * @param {() => string} ask 一次只读 git 问话(返回 stdout;抛错即"问不到")
 * @returns {{usable: boolean, reason: string}}
 */
export function substrateVerdict(ask) {
  let out
  try {
    // 注意是**调用** ask 之后再取字符串:写成 `String(ask ?? …)` 会把函数源码当回答,
    // 于是任何输入都落"不是布尔形态"—— S1/S2/S5 三条同时红就是这一型,已由测试钉死。
    out = String((ask ?? (() => ''))()).trim()
  } catch (e) {
    const msg = String((e && e.message) || e)
    return { usable: false, reason: `git 问不到:${msg.slice(0, 120) || '(空)'}` }
  }
  if (out === 'true') return { usable: true, reason: '' }
  if (out === 'false')
    return {
      usable: false,
      reason: '工作树不可用(gitdir 的 core.bare 漂成 true / .git 正被外部重建)—— 整批门都取不到被审面',
    }
  return { usable: false, reason: `git 的回答不是布尔形态:${out.slice(0, 80) || '(空输出)'}` }
}

/**
 * 真问话那一层,抽出来是为了能被测试喂假实现:
 * `run` 必须是**同步**且自带 timeout 的只读调用(守门 80 口径:热路径只读 git 调用必须封顶)。
 *
 * @param {{run: () => string}} deps
 */
export function probeSubstrate({ run }) {
  return substrateVerdict(run)
}
