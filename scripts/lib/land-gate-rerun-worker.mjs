/**
 * 受影响门并发执行器(2026-10-28 立):`land-gate-rerun.mjs` 的注册表臂串行跑 26 道门耗时分钟级,
 * 而单臂耗时从 0.3s(check-api-key-leak)到 34s(check-rounded-full)差两个数量级 ⇒ 串行的墙钟
 * 时间几乎全花在等最慢那几臂。本器只改"等谁",不改任何判据:每臂仍以同一 argv、同一 cwd、
 * 同一 timeout 与同一 env 真跑一次,结果按**输入下标**回填,顺序与分级由调用方按原样归类。
 *
 * 为什么是独立子进程而不是改写 lib 为 async:两个调用方(object-space-land 是 async、
 * strip-stale-closed-rows 的 main 是同步)与 7 处镜像测试都按同步 API 调 `rerunAffectedGates`;
 * 把并发藏在 worker 里 ⇒ API 与调用方零改动,回归面只在本器与其自身测试。
 *
 * 协议:stdin 读 `{tasks:[{script,args,timeoutMs}],root,concurrency}`;stdout 只写 JSON 数组。
 * 门自己的 stdout/stderr 全部被 spawnGateAsync 收进 `out`,不会混进本器的 stdout。
 */
import { readFileSync } from 'node:fs'

import { spawnGateAsync } from './land-gate-rerun.mjs'

const payload = JSON.parse(readFileSync(0, 'utf8'))
const tasks = Array.isArray(payload.tasks) ? payload.tasks : []
const limit = Math.max(1, Math.floor(Number(payload.concurrency) || 1))
const results = new Array(tasks.length)
let next = 0

async function drain() {
  for (;;) {
    const i = next
    next += 1
    if (i >= tasks.length) return
    const t = tasks[i] ?? {}
    results[i] = await spawnGateAsync(t.script, t.args ?? [], payload.root, t.timeoutMs ?? 300000)
  }
}

await Promise.all(Array.from({ length: Math.min(limit, tasks.length) }, drain))
process.stdout.write(JSON.stringify(results))
