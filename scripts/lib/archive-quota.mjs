/**
 * 随包资源按「最低版本保证」决定装或跳过，解压条数与展开字节必须事先量到。
 * 配额没给就未判定，不得当成不限额。
 */

const SHA256_RE = /^[0-9a-f]{64}$/

function finiteCount(value) {
  return Number.isInteger(value) && value >= 0
}

export function judgeArchiveInstall(input) {
  const presence = input?.presence
  if (presence !== 'ensure-minimum') {
    return { disposition: 'unjudged', reason: 'presence-unmeasured', action: null }
  }
  if (!finiteCount(input.revision)) {
    return { disposition: 'unjudged', reason: 'revision-unmeasured', action: null }
  }
  if (typeof input.archiveSha256 !== 'string' || !SHA256_RE.test(input.archiveSha256)) {
    return { disposition: 'unjudged', reason: 'hash-unmeasured', action: null }
  }
  if (!finiteCount(input.maxEntries) || !finiteCount(input.maxExpandedBytes)) {
    return { disposition: 'unjudged', reason: 'quota-unmeasured', action: null }
  }
  if (!finiteCount(input.entryCount) || !finiteCount(input.expandedBytes)) {
    return { disposition: 'unjudged', reason: 'size-unmeasured', action: null }
  }
  if (input.entryCount > input.maxEntries) {
    return { disposition: 'refused', reason: 'entry-quota', action: 'none' }
  }
  if (input.expandedBytes > input.maxExpandedBytes) {
    return { disposition: 'refused', reason: 'byte-quota', action: 'none' }
  }
  if (!finiteCount(input.installedRevision)) {
    return { disposition: 'unjudged', reason: 'installed-unmeasured', action: null }
  }
  if (input.installedRevision >= input.revision) {
    return { disposition: 'skip', reason: 'minimum-met', action: 'none' }
  }
  return { disposition: 'install', reason: 'below-minimum', action: 'extract' }
}
