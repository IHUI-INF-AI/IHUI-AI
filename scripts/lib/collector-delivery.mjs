/**
 * 采集回调不自带调度。取消之后既无错误也无样本，记为正在退出，不得记成失败。
 */

function measured(value) {
  return value !== null && value !== undefined
}

export function judgeCollectorDelivery(input) {
  const cancelled = input?.cancelled
  if (typeof cancelled !== 'boolean') {
    return { disposition: 'unjudged', reason: 'cancel-unmeasured' }
  }
  if (cancelled) {
    if (measured(input.error) || measured(input.sample)) {
      return { disposition: 'unjudged', reason: 'cancel-not-quiet' }
    }
    return { disposition: 'exiting', reason: 'cancel-quiet' }
  }
  if (!Object.hasOwn(input, 'error')) {
    return { disposition: 'unjudged', reason: 'error-unmeasured' }
  }
  if (measured(input.error)) {
    return { disposition: 'failed', reason: 'sample-error' }
  }
  if (!measured(input.sample)) {
    return { disposition: 'unjudged', reason: 'sample-absent' }
  }
  return { disposition: 'sampled', reason: 'sample-ready' }
}
