/**
 * tsx CLI 的定位(2026-10-29 收口为单源)。
 *
 * 三条客户端会话回灌腿(qoder/trae/workbuddy)都要以 `node <tsx cli> <script.ts>` 起一个
 * 被 tsx 转译的落库脚本。此前这份取值在两个编排器里各抄了一遍(§0.6 禁止),第三个消费者
 * 一来必然出现第三份漂移。候选序固定:包内 → 仓根。取不到返回 null,由调用方按「未判定」
 * 处理(exit 2),绝不静默回落到别的解释器。
 */
import fs from 'node:fs'
import path from 'node:path'

/**
 * @param {string} root 仓根(绝对路径)
 * @returns {string | null} tsx CLI 的绝对路径,找不到即 null
 */
export function resolveTsxCli(root) {
  const apiDir = path.join(root, 'apps', 'api')
  for (const candidate of [
    path.join(apiDir, 'node_modules', 'tsx', 'dist', 'cli.mjs'),
    path.join(root, 'node_modules', 'tsx', 'dist', 'cli.mjs'),
  ]) {
    if (fs.existsSync(candidate)) return candidate
  }
  return null
}
