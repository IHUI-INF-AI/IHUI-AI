/**
 * 父进程已经在作业里时，决定子进程怎么进作业。
 * 嵌套是否被允许没量到，就不启动，也不走脱离作业。
 */
export function decideJobNesting(input) {
  if (!input || typeof input !== 'object') {
    return { action: 'unjudged', reason: 'input-absent' }
  }
  if (typeof input.parentInJob !== 'boolean') {
    return { action: 'unjudged', reason: 'parent-unmeasured' }
  }
  if (!input.parentInJob) return { action: 'create-new', reason: 'parent-free' }
  if (typeof input.nestedAllowed !== 'boolean') {
    return { action: 'unjudged', reason: 'nest-unmeasured' }
  }
  if (!input.nestedAllowed) return { action: 'stay-in-parent', reason: 'breakaway-refused' }
  return { action: 'nest', reason: 'nested-allowed' }
}
