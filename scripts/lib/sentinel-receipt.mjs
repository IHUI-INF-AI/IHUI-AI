const STATUSES = new Set(['ok', 'breach', 'unjudged'])

function countOf(value) {
  return Number.isInteger(value) && value >= 0 ? value : null
}

/**
 * 哨兵回执必须带上量到的计数。缺一格就是未判定，不用 0 填。
 * truncated 为 true 时不得记 ok。
 */
export function planSentinelReceipt(input) {
  if (!input || typeof input !== 'object' || Array.isArray(input)) {
    return { ok: false, reason: 'receipt-absent', receipt: null }
  }
  const status = input.status
  if (!STATUSES.has(status)) return { ok: false, reason: 'status-invalid', receipt: null }
  if (typeof input.reason !== 'string' || input.reason.trim() === '') {
    return { ok: false, reason: 'reason-absent', receipt: null }
  }
  const scanned = countOf(input.scanned)
  const linked = countOf(input.linked)
  const reclaimedBytes = countOf(input.reclaimedBytes)
  if (scanned === null || linked === null || reclaimedBytes === null) {
    return { ok: false, reason: 'count-unmeasured', receipt: null }
  }
  if (typeof input.truncated !== 'boolean') {
    return { ok: false, reason: 'truncated-unmeasured', receipt: null }
  }
  if (typeof input.scannedAt !== 'string' || Number.isNaN(Date.parse(input.scannedAt))) {
    return { ok: false, reason: 'time-unmeasured', receipt: null }
  }
  if (input.truncated && status === 'ok') {
    return { ok: false, reason: 'truncated-not-ok', receipt: null }
  }
  return {
    ok: true,
    reason: 'planned',
    receipt: {
      status,
      reason: input.reason.trim(),
      scanned,
      linked,
      reclaimedBytes,
      scannedAt: input.scannedAt,
      truncated: input.truncated,
    },
  }
}
