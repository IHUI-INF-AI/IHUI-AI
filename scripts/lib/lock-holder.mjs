/**
 * 锁持有者判定。持有者必须带会话短名和可解析时刻。
 * 是否仍在持有只跟调用方给的 TTL 比：超过就不再算持有。
 * TTL 没量到、时刻解析不出、或时刻落在未来，都是未判定——
 * 既不是仍在持有，也不是已空闲。本函数不写死默认 TTL。
 */
export function judgeLockHolder(input) {
  if (input === null || typeof input !== 'object') {
    return { verdict: 'unjudged', reason: 'holder-unreadable' }
  }
  const { holder, nowMs, ttlMs } = input
  if (holder === null) return { verdict: 'free', reason: 'no-holder' }
  if (typeof holder !== 'object') {
    return { verdict: 'unjudged', reason: 'holder-unreadable' }
  }
  if (typeof holder.name !== 'string' || holder.name.length === 0) {
    return { verdict: 'unjudged', reason: 'name-absent' }
  }
  const atMs = typeof holder.at === 'string' ? Date.parse(holder.at) : Number.NaN
  if (!Number.isFinite(atMs)) {
    return { verdict: 'unjudged', reason: 'time-unmeasured' }
  }
  if (typeof nowMs !== 'number' || !Number.isFinite(nowMs)) {
    return { verdict: 'unjudged', reason: 'now-unmeasured' }
  }
  if (typeof ttlMs !== 'number' || !Number.isFinite(ttlMs) || ttlMs <= 0) {
    return { verdict: 'unjudged', reason: 'ttl-unmeasured' }
  }
  const ageMs = nowMs - atMs
  if (ageMs < 0) return { verdict: 'unjudged', reason: 'time-inverted' }
  if (ageMs > ttlMs) {
    return { verdict: 'expired', reason: 'ttl-exceeded', name: holder.name }
  }
  return { verdict: 'held', reason: 'within-ttl', name: holder.name }
}
