/**
 * 静态写入失败和恢复成功都必须是量到的数组。
 * 缺阵不是空账。恢复行缺身份或时刻时，整本未判定，不把坏行跳过当成已核对。
 */

function nonEmpty(value) {
  return typeof value === 'string' && value.trim() !== ''
}

function finiteNumber(value) {
  return typeof value === 'number' && Number.isFinite(value)
}

export function judgeRecoveryLedger(input) {
  const unread = (reason) => ({ disposition: 'unjudged', reason, failures: null, recoveries: null })
  if (input?.version !== 1) return unread('version-unmeasured')
  if (!Array.isArray(input.entries)) return unread('entries-unmeasured')
  if (!Array.isArray(input.recoveries)) return unread('recoveries-unmeasured')
  for (const entry of input.entries) {
    if (entry === null || typeof entry !== 'object' || !nonEmpty(entry.resourceId)) {
      return unread('row-unmeasured')
    }
  }
  const recoveries = []
  for (const entry of input.recoveries) {
    if (
      entry === null ||
      typeof entry !== 'object' ||
      !nonEmpty(entry.resourceId) ||
      !nonEmpty(entry.adapter) ||
      !nonEmpty(entry.operation) ||
      !finiteNumber(entry.recoveredAt)
    ) {
      return unread('row-unmeasured')
    }
    recoveries.push({
      resourceId: entry.resourceId,
      adapter: entry.adapter,
      operation: entry.operation,
      recoveredAt: entry.recoveredAt,
    })
  }
  return {
    disposition: 'recorded',
    reason: 'both-columns',
    failures: input.entries.length,
    recoveries,
  }
}
