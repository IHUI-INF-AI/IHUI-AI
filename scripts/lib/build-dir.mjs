/**
 * 构建产物目录单源:Windows 上 Cargo 目标目录一律落在**系统盘**的 `IHUI-Build\target`。
 *
 * 立因(2026-11-22 实报):`CARGO_TARGET_DIR` 曾写成 `D:\IHUI-Build\target`,换成只有 C 盘的机器、
 * 或旧终端仍持旧值再拉起 `tauri dev` 时,cargo 会按旧盘重建一整份 11GB 的 target —— 盘符是
 * 当次机器事实,不能进任何入库件的默认值。仓里只留一条判据,桌面端 build/dev 两个入口共用它。
 *
 * 覆盖出口:`IHUI_CARGO_TARGET_DIR`(显式指定,原样采用);非 Windows 不介入(保持调用方 env)。
 */

/** 该系统应使用的 Cargo 目标目录;非 Windows 返回 null(调用方保持原 env)。 */
export function buildTargetFor(env = process.env, platform = process.platform) {
  const override = String(env.IHUI_CARGO_TARGET_DIR ?? '').trim()
  if (override) return override
  if (platform !== 'win32') return null
  const sys = String(env.SystemDrive || 'C:').replace(/[\\/]+$/, '')
  return `${sys}\\IHUI-Build\\target`
}

/**
 * 把 `env.CARGO_TARGET_DIR` 钉到 `buildTargetFor` 的结果(原地改并返回同一个对象)。
 * 与现值不同才写,并把旧值打进日志 —— 静默改写会让"这次编去哪了"无从查起。
 */
export function pinCargoTarget(env, { log = () => {}, platform = process.platform } = {}) {
  const want = buildTargetFor(env, platform)
  if (!want) return env
  const prev = String(env.CARGO_TARGET_DIR ?? '').trim()
  if (prev && prev.toLowerCase() === want.toLowerCase()) return env
  env.CARGO_TARGET_DIR = want
  if (prev)
    log(
      `CARGO_TARGET_DIR 由 ${prev} 纠正为 ${want}(构建产物统一落系统盘,不随旧 shell 环境漂到别的盘)`,
    )
  return env
}

export const __test__ = { buildTargetFor, pinCargoTarget }
