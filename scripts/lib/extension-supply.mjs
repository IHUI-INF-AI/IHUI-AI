/**
 * 扩展供应必须同时钉住版本、https 地址、扩展 ID、声明哈希和实测哈希。
 * 只承认已观察到的公钥模式；没实测到内容就未判定，不得拿声明哈希当成已核对。
 */

const SHA256_RE = /^[0-9a-f]{64}$/
const OBSERVED_KEY_MODE = 'fixed_dev'

function nonEmpty(value) {
  return typeof value === 'string' && value.trim() !== ''
}

export function judgeExtensionSupply(record, measuredSha) {
  if (record === null || typeof record !== 'object' || Array.isArray(record)) {
    return { disposition: 'unjudged', reason: 'record-unmeasured', action: null }
  }
  if (!nonEmpty(record.version) || !nonEmpty(record.extensionId)) {
    return { disposition: 'unjudged', reason: 'identity-unmeasured', action: null }
  }
  if (record.publicKeyMode !== OBSERVED_KEY_MODE) {
    return { disposition: 'unjudged', reason: 'mode-unmeasured', action: null }
  }
  if (typeof record.url !== 'string' || !record.url.startsWith('https://')) {
    return { disposition: 'unjudged', reason: 'url-unmeasured', action: null }
  }
  if (typeof record.sha256 !== 'string' || !SHA256_RE.test(record.sha256)) {
    return { disposition: 'unjudged', reason: 'hash-unmeasured', action: null }
  }
  if (measuredSha === null || measuredSha === undefined) {
    return { disposition: 'unjudged', reason: 'measure-absent', action: null }
  }
  if (typeof measuredSha !== 'string' || !SHA256_RE.test(measuredSha)) {
    return { disposition: 'unjudged', reason: 'measure-absent', action: null }
  }
  if (measuredSha !== record.sha256) {
    return { disposition: 'refused', reason: 'content-mismatch', action: 'none' }
  }
  return { disposition: 'sealed', reason: 'id-and-hash', action: 'install' }
}
