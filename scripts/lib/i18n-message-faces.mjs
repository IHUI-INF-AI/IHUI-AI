/**
 * 语言包「面(face)」的唯一取面实现(2026-10-05 立)。
 *
 * 为什么单拎一份:扫描器 `scan-i18n-zh-residue.mjs` 与修复器 `fix-zh-tw-residue.mjs`
 * 是同一件事的两头(一个判、一个修),此前各带一份面清单与路径拼法 —— 2026-10-05 实测:
 * 扫描器已认全部 7 面并指向 `packages/i18n/messages/<face>/<locale>.json`,
 * 而修复器仍指向 2026-07-25 迁移前的 `apps/web/messages/`、`apps/extension/messages/`、
 * `apps/miniapp-taro/src/i18n/zh-TW.ts` ⇒ `--target=web/extension/miniapp-taro` 三条
 * 全部"跳过(不存在)",末行却打"总计: 0 个文件, 0 行改动",读起来与"无残留"同形。
 * 后果:zh-TW 残留只能靠人手改,而修复器这台正牌出口静默失效了三个月。
 *
 * 收敛口径:面清单与路径拼法只此一份,两头都从这里取;面集是**封闭**的,
 * 新增语言包目录必须同时改这里(与扫描器"未知 target 直接报错、不静默回落"同一条纪律)。
 */

/** 全部语言包面(与 packages/i18n/messages/ 下的一级目录逐一同名)。 */
export const I18N_MESSAGE_FACES = [
  'web',
  'extension',
  'shared',
  'api',
  'cli',
  'miniapp-taro',
  'mobile-rn',
]

/** 面名是否合法。未知面一律 false ⇒ 调用方必须显式报错,不得回落成默认面。 */
export function isKnownFace(face) {
  return I18N_MESSAGE_FACES.includes(face)
}

/**
 * 某面某语言的语言包相对仓库根的路径。
 * 七面同构(2026-07-25 i18n 单一来源迁移后已无 apps/* 侧的散落副本);
 * `web` 不再有单独分支 —— 它与其他六面拼法逐字相同,特例分支正是两头漂开的成因。
 */
export function faceMessageRelPath(face, locale) {
  return `packages/i18n/messages/${face}/${locale}.json`
}
