/**
 * 票面指纹(单一真源,2026-11-05 立)。
 * 立因:`refreshAutonomyCandidates` 原先只按 mtime 年龄判"候选文件新鲜"(6h 窗口),于是就地改写一张票之后,
 * 环在整个窗口里看不见那张票 —— 当日实测读数 `L2066 不入本轮:未评估(候选文件未收录本票)`,挡了 227 分钟。
 * 生成侧(autonomy-candidates)与消费侧(auto-evolve)必须用同一把尺,否则比对永远不等 ⇒ 谁都不敢判过期。
 * 刻意不放进任一侧脚本:两侧互相 import 会成环(实测 ReferenceError: Cannot access 'ROOT' before initialization)。
 */
import { createHash } from 'node:crypto'
import { gitRaw } from './face-reader.mjs'

/** 对台账文本取短指纹;取不到输入 ⇒ null(不猜、不返回空串冒充"一样")。 */
export function planFaceDigest(lines) {
  if (!Array.isArray(lines)) return null
  return createHash('sha256').update(lines.join('\n')).digest('hex').slice(0, 16)
}

/**
 * **被审面(HEAD blob)**的票面指纹 —— 两侧都必须用它,不能用工作树副本。
 * 立因(2026-11-05 自伤):我第一版两侧都读工作树 `PROJECT_PLAN.md`,而这台多会话共享树上
 * 那份副本常是别席的滞后拷贝(不含刚落账的新行)⇒ 缓存指纹与"当下指纹"相等,`--once` 判新鲜,
 * 刚登记的 8 枚考勤单文件票进不了候选面。§0.4:清单与内容必须同面同轮,取不到不回落另一个面。
 * 取不到 HEAD ⇒ null,由调用方按"未判定 ⇒ 保守重算"处理。
 */
export function planFaceDigestFromHead(root, doc = 'PROJECT_PLAN.md') {
  let out
  try {
    out = gitRaw(['show', `HEAD:${doc}`], root, { timeout: 60_000, maxBuffer: 1 << 26 })
  } catch {
    return null
  }
  if (typeof out !== 'string') return null
  return planFaceDigest(out.split(/\r?\n/))
}
