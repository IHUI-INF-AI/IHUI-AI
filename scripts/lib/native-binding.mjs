/**
 * 可选原生件的加载态。
 * 加载失败只记下错误并标成不可用，调用前不抛。
 * 还没加载过不等于加载失败。失败却没有错误文本，也不得标成不可用。
 * 本函数不加载任何二进制。
 */

function unread() {
  return { disposition: 'unjudged', reason: 'attempt-unmeasured', supported: null, usable: false }
}

export function judgeNativeBinding(input) {
  const record = input !== null && typeof input === 'object' ? input : {}
  const { attempted, bindingPresent, loadError } = record
  if (typeof attempted !== 'boolean') return unread()
  if (attempted === false) {
    return { disposition: 'unjudged', reason: 'not-loaded', supported: null, usable: false }
  }
  if (typeof bindingPresent !== 'boolean') {
    return { disposition: 'unjudged', reason: 'binding-unmeasured', supported: null, usable: false }
  }
  if (bindingPresent === true) {
    if (loadError !== null) {
      return { disposition: 'unjudged', reason: 'error-unexpected', supported: null, usable: false }
    }
    return { disposition: 'supported', reason: 'loaded', supported: true, usable: true }
  }
  if (typeof loadError !== 'string' || loadError.length === 0) {
    return { disposition: 'unjudged', reason: 'error-unmeasured', supported: null, usable: false }
  }
  return { disposition: 'unsupported', reason: 'load-failed', supported: false, usable: false }
}

export function decideRequireBinding(verdict) {
  if (verdict?.usable === true && verdict.supported === true) {
    return { disposition: 'admitted', reason: 'loaded', throwError: false }
  }
  if (verdict?.supported === false && verdict.reason === 'load-failed') {
    return { disposition: 'refused', reason: 'load-failed', throwError: true }
  }
  return { disposition: 'unjudged', reason: 'not-usable', throwError: false }
}
