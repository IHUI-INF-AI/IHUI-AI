/**
 * 工具钩子只接纳已取证的三个阶段，并且必须带 matcher。
 * 阶段不认识或 matcher 没量到都不运行，不得默认套到全部工具上。
 */

export const HOOK_PHASES = Object.freeze(['PreToolUse', 'PostToolUse', 'PostToolUseFailure'])

export function admitHookBinding(input) {
  const phase = input?.phase
  if (typeof phase !== 'string' || !HOOK_PHASES.includes(phase)) {
    return { disposition: 'unjudged', reason: 'phase-unknown', phase: null }
  }
  const matcher = input?.matcher
  if (typeof matcher !== 'string' || matcher.trim() === '') {
    return { disposition: 'unjudged', reason: 'matcher-unmeasured', phase: null }
  }
  return { disposition: 'admitted', reason: 'matched', phase }
}
