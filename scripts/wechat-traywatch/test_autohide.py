import ctypes, ctypes.wintypes as wt, time

u = ctypes.windll.user32
TARGET = "Qt51514WxTrayIconMessageWindowClass"
SW_SHOW, SW_HIDE = 5, 0
E = ctypes.WINFUNCTYPE(ctypes.c_bool, wt.HWND, wt.LPARAM)

def cls(h):
    b = ctypes.create_unicode_buffer(300)
    u.GetClassNameW(h, b, 300)
    return b.value

wins = []
def cb(h, l):
    if cls(h) == TARGET:
        wins.append(h)
    return True
u.EnumWindows(E(cb), 0)

print("目标窗口数量:", len(wins))
if not wins:
    print("RESULT: 无目标窗口（微信 taskbarpins 子进程可能未创建该窗口）")
else:
    h = wins[0]
    print("强制显示 hwnd=%d ..." % h)
    u.ShowWindow(h, SW_SHOW)
    print("显示后 visible=", bool(u.IsWindowVisible(h)))
    print("等待 3 秒让看门狗介入...")
    time.sleep(3)
    vis = bool(u.IsWindowVisible(h))
    print("3 秒后 visible=", vis)
    if not vis:
        print("RESULT: PASS —— 看门狗已自动隐藏该窗口")
    else:
        print("RESULT: FAIL —— 窗口仍可见，看门狗未生效")
