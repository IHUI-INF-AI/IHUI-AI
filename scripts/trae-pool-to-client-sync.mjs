//
//   node scripts/trae-pool-to-client-sync.mjs [--dry-run] [--json]
import { spawn } from 'node:child_process'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { resolveTsxCli } from './lib/tsx-cli.mjs'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const BRIDGE = path.join(ROOT, 'apps', 'api', 'scripts', 'relay-trae-pool-to-client.ts')

const tsx = resolveTsxCli(ROOT)
if (!tsx) {
  console.error('❌ 未找到 tsx(apps/api/node_modules/tsx);先 pnpm install')
  process.exit(2)
}

const args = [tsx, BRIDGE, ...process.argv.slice(2).filter((a) => a !== '--')]
const child = spawn(process.execPath, args, {
  cwd: ROOT,
  stdio: 'inherit',
  windowsHide: true,
})
child.on('error', (e) => {
  console.error(`❌ 启动回写失败: ${e.message}`)
  process.exit(2)
})
child.on('close', (code) => process.exit(code ?? 2))
