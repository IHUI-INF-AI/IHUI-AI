# purge-ihui-scheduled-tasks.ps1 — 本机回归护栏(2026-11-18 立)
#
# 机主铁律:项目禁止使用 Windows 计划任务做自动化。19 个历史作业已迁到
# scripts/local-scheduler.mjs(登录常驻守护)。本脚本是"防回潮"那一层:
# 任何会话/工具又往任务计划程序里塞 IHUI* 任务时,每小时把它导出入档并注销掉。
#
# 纪律:先导出 XML 再注销(可回滚),每一步都写日志,不在桌面弹窗。
$ErrorActionPreference = 'Continue'
$log = 'D:\DevEnv\logs\scheduled-task-purge.log'
$bak = 'D:\DevEnv\backups\scheduled-tasks-purged'
New-Item -ItemType Directory -Force -Path $bak | Out-Null
New-Item -ItemType Directory -Force -Path (Split-Path $log) | Out-Null

$stamp = Get-Date -Format 's'
$tasks = @(Get-ScheduledTask | Where-Object { $_.TaskName -like 'IHUI*' })
if ($tasks.Count -eq 0) {
  "$stamp clean" | Add-Content -LiteralPath $log -Encoding utf8
  exit 0
}

foreach ($t in $tasks) {
  try {
    Export-ScheduledTask -TaskName $t.TaskName |
      Set-Content -LiteralPath (Join-Path $bak ($t.TaskName + '.xml')) -Encoding UTF8
    Unregister-ScheduledTask -TaskName $t.TaskName -Confirm:$false -ErrorAction Stop
    "$stamp purged '$($t.TaskName)'" | Add-Content -LiteralPath $log -Encoding utf8
  } catch {
    "$stamp FAILED '$($t.TaskName)': $($_.Exception.Message)" | Add-Content -LiteralPath $log -Encoding utf8
  }
}
exit 0
