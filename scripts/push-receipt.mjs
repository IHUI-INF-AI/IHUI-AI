/**
 * 推送门凭据 CLI（薄入口）。
 * 判定与签发实现全部在 scripts/lib/push-receipt.mjs（受 scripts/lib/ 保护面覆盖），
 * 本文件只负责进程退出码：0 = 凭据有效可直接推；非 0 = 调用方必须回落真跑门。
 */

import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { EXPECTED_GATES, verifyPushReceipt } from './lib/push-receipt.mjs'

// 本文件在 scripts/ 下（不是 scripts/lib/），不能复用 lib 版 `../..` 的根推导（会多退一级）。
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const mode = process.argv[2]

if (mode === '--verify') {
  const result = verifyPushReceipt(root)
  if (result.ok) {
    process.stdout.write('[push-receipt] ok：凭据校验通过，跳过推送侧门求值\n')
    process.exit(0)
  }
  process.stdout.write(`[push-receipt] fallback：${result.code}${result.detail ? ` (${result.detail})` : ''}\n`)
  process.exit(1)
}

if (mode === '--gate-set') {
  process.stdout.write(JSON.stringify(EXPECTED_GATES, null, 2) + '\n')
  process.exit(0)
}

process.stderr.write('用法: node scripts/push-receipt.mjs <--verify|--gate-set>\n')
process.exit(2)
