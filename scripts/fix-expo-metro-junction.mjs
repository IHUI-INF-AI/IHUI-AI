// 修复 pnpm 重装后公共提升目录 .pnpm\node_modules 丢失 @expo\metro-config 的问题。
// 背景(2026-09-22):pnpm store 修复重装后公共提升目录被按现行 hoist 规则重建,
// @expo scope 整体丢失 → react-native-svg-transformer 的四连 babel fallback 全解析失败
// → Metro 所有 bundle 请求 500 "Cannot read properties of undefined (reading 'transformFile')"。
// 本脚本幂等:目标 junction 已有效则跳过;悬空/缺失则重建。由根 package.json postinstall 调用。
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const PNPM_DIR = path.join(ROOT, 'node_modules', '.pnpm')
const PUBLIC_NM = path.join(PNPM_DIR, 'node_modules')
const TARGET = path.join(PUBLIC_NM, '@expo', 'metro-config')

function findRealMetroConfig() {
  if (!fs.existsSync(PNPM_DIR)) return null
  return (
    fs
      .readdirSync(PNPM_DIR)
      .filter((d) => d.startsWith('@expo+metro-config@'))
      .map((d) => path.join(PNPM_DIR, d, 'node_modules', '@expo', 'metro-config'))
      .find((p) => fs.existsSync(path.join(p, 'package.json'))) || null
  )
}

function main() {
  const real = findRealMetroConfig()
  if (!real) {
    console.warn('[fix-expo-metro-junction] 未找到 @expo+metro-config@* 隔离目录,跳过')
    return
  }
  if (fs.existsSync(path.join(TARGET, 'package.json'))) {
    return // 已就绪,幂等退出
  }
  // 清理悬空项(目录/junction/损坏 reparse point 都可能存在但内部无 package.json)
  try {
    fs.rmSync(TARGET, { recursive: true, force: true })
  } catch {}
  fs.mkdirSync(path.dirname(TARGET), { recursive: true })
  fs.symlinkSync(real, TARGET, 'junction')
  console.log(`[fix-expo-metro-junction] 已重建公共提升 junction: ${TARGET} -> ${real}`)
}

main()
