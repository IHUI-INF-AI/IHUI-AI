/**
 * 从命令安全策略权威源生成前端 TS 常量(统一安全 C4)。
 *
 * 权威源: apps/ai-service/app/data/command_policy.json(ai-service run_command 直接读取)
 * 生成物: packages/shared/src/constants/command-policy.generated.ts(dangerous-command-detector 引用)
 * 用法:   node scripts/generate-command-policy-ts.mjs [--dry-run]
 *
 * 修改 command_policy.json 后运行本脚本,前后端即同步生效。
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const POLICY = join(ROOT, 'apps/ai-service/app/data/command_policy.json')
const OUT = join(ROOT, 'packages/shared/src/constants/command-policy.generated.ts')
const DRY_RUN = process.argv.includes('--dry-run')

const policy = JSON.parse(readFileSync(POLICY, 'utf-8'))

const ts = `// @generated by scripts/generate-command-policy-ts.mjs — DO NOT EDIT BY HAND.
// 命令安全策略单一权威源(统一安全 C4):修改 apps/ai-service/app/data/command_policy.json
// 后运行 \`node scripts/generate-command-policy-ts.mjs\` 重新生成,前后端同步生效。
// 与 ai-service mcp_server._load_command_policy() 读取同一 JSON。

export const COMMAND_POLICY_VERSION = ${policy.version ?? 1}

export const DANGEROUS_COMMAND_PATTERNS: readonly string[] = ${JSON.stringify(policy.dangerous_patterns, null, 2)}

export const ALLOWED_COMMAND_PREFIXES: readonly string[] = ${JSON.stringify(policy.allowed_prefixes, null, 2)}

export const SENSITIVE_FILE_MARKERS: readonly string[] = ${JSON.stringify(policy.sensitive_file_markers, null, 2)}

export function isDangerousCommand(command: string): boolean {
  return DANGEROUS_COMMAND_PATTERNS.some((pat) => new RegExp(pat).test(command))
}

export function isAllowedCommandPrefix(command: string): boolean {
  const first = command.trim().split(/[\\/\\s]+/)[0] ?? ''
  return ALLOWED_COMMAND_PREFIXES.includes(first.toLowerCase())
}
`

if (DRY_RUN) {
  console.log(`[dry-run] 将写入 ${OUT}(${ts.length} chars)`)
  process.exit(0)
}

mkdirSync(dirname(OUT), { recursive: true })
writeFileSync(OUT, ts, 'utf-8')
console.log(`已生成 ${OUT}(${ts.length} chars)`)
