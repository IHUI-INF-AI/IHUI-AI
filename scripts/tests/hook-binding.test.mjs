import { test } from 'node:test'
import assert from 'node:assert/strict'

import { admitHookBinding } from '../lib/hook-binding.mjs'

test('三个已取证阶段且带 matcher 才放行', () => {
  assert.deepEqual(admitHookBinding({ phase: 'PostToolUse', matcher: 'Write' }), {
    disposition: 'admitted',
    reason: 'matched',
    phase: 'PostToolUse',
  })
  assert.equal(admitHookBinding({ phase: 'PostToolUseFailure', matcher: 'Bash' }).disposition, 'admitted')
})

test('不认识的阶段或空 matcher 不运行', () => {
  assert.equal(admitHookBinding({ phase: 'Stop', matcher: 'Write' }).reason, 'phase-unknown')
  assert.equal(admitHookBinding({ phase: 'PreToolUse', matcher: '   ' }).reason, 'matcher-unmeasured')
  assert.equal(admitHookBinding({ phase: null, matcher: 'Write' }).phase, null)
})
