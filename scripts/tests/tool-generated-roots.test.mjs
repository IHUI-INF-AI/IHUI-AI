/**
 * 水印「上游工具生成物」豁免判据的镜像测试(§22c:判据只有一份,本文件 import 生产实现)。
 *
 * 立因:覆盖面把 87 份 tauri build script 再生的 .toml 判成缺载荷 ⇒ 恒红门(§12e)。
 * 修法不能只是"开一扇豁免门":每条豁免都必须被**量到**前提(文件自述为工具产物)、会到期、
 * 形状不合法就整档判「未判定」。所以这里既验放行,也验四处不放行的方向:
 *   ① root 内但不自述为工具产物;② 到期;③ 面上取不到正文;④ 台账形状坏掉。
 *
 * 运行:node --test scripts/tests/tool-generated-roots.test.mjs
 */
import { test } from 'node:test'
import assert from 'node:assert/strict'
import fs from 'node:fs'
import path from 'node:path'
import { execFileSync } from 'node:child_process'
import { fileURLToPath } from 'node:url'
import { resolveGitBin } from '../lib/gitdir.mjs'
import { mkScratch, rmScratch } from '../lib/scratch-dir.mjs'
import { __test__ as T } from '../lib/tool-generated-roots.mjs'

const HERE = path.dirname(fileURLToPath(import.meta.url))
const ROOT = path.resolve(HERE, '..', '..')
const MARKED = '# Automatically generated - DO NOT EDIT!\n\n[[permission]]\nidentifier = "x"\n'
const HANDWRITTEN = '[[permission]]\nidentifier = "hand-written"\n'
const ROOT_DIR = 'apps/desktop/src-tauri/permissions/autogenerated/'
const SAMPLE = ROOT_DIR + 'active_window.toml'
const ENTRIES = [
  {
    id: 'fixture-tauri',
    root: ROOT_DIR,
    markerRegex: '^#[ \\t]*Automatically generated - DO NOT EDIT![ \\t]*$',
    expires: '2099-01-01',
    evidence: [{ file: 'x.toml', contains: 'Automatically generated' }],
    reason: '夹具用:上游构建脚本每枚都重写这批权限文档,inject 会被洗掉',
  },
]

const headBlobOf = (rel) =>
  execFileSync(
    process.env.IHUI_GIT_BIN || resolveGitBin() || 'git',
    ['-c', 'safe.directory=*', '-C', ROOT, 'show', `HEAD:${rel}`],
    { encoding: 'utf8', maxBuffer: 1 << 26, windowsHide: true, stdio: ['ignore', 'pipe', 'pipe'] },
  )

test('装车证明:真台账形状合法,且真被它免的那份文件在 HEAD 面前提实测成立', () => {
  const entries = T.loadToolGeneratedEntries(ROOT)
  assert.ok(entries.length >= 1, '台账必须存在且至少一条(缺档 = 豁免不存在)')
  const r = T.judgeToolGenerated({
    rel: SAMPLE,
    text: headBlobOf(SAMPLE),
    entries,
    today: '2026-10-16',
  })
  assert.equal(r.state, 'exempt', `HEAD 面上这份工具产物必须被免(实得 ${r.state}:${r.why ?? ''})`)
})

test('①root 内但不自述为工具产物 ⇒ 不豁免(「验过才免」不能被一句登记替掉)', () => {
  const r = T.judgeToolGenerated({
    rel: ROOT_DIR + 'sneaky.toml',
    text: HANDWRITTEN,
    entries: ENTRIES,
    today: '2026-10-16',
  })
  assert.equal(r.exempt, false)
  assert.equal(r.state, 'premise-missing')
  assert.match(r.why, /不自述为工具产物/)
})

test('②到期与③面上取不到正文 ⇒ 都不豁免,并各自报名', () => {
  const expired = T.judgeToolGenerated({
    rel: ROOT_DIR + 'active.toml',
    text: MARKED,
    entries: ENTRIES,
    today: '2099-01-02',
  })
  assert.equal(expired.exempt, false)
  assert.equal(expired.state, 'expired')
  assert.match(expired.why, /已到期/)

  const noContent = T.judgeToolGenerated({
    rel: ROOT_DIR + 'active.toml',
    text: null,
    entries: ENTRIES,
    today: '2026-10-16',
  })
  assert.equal(noContent.exempt, false, '算不出前提时必须不豁免 —— 方向永远倒向严的一侧')
  assert.equal(noContent.state, 'no-content')
})

test('正例期内放行;root 之外一律不沾(前缀逐字节比,不做相似匹配)', () => {
  const hit = T.judgeToolGenerated({
    rel: ROOT_DIR + 'active.toml',
    text: MARKED,
    entries: ENTRIES,
    today: '2026-10-16',
  })
  assert.equal(hit.exempt, true)
  const out = T.judgeToolGenerated({
    rel: 'apps/web/src/page.tsx',
    text: MARKED,
    entries: ENTRIES,
    today: '2026-10-16',
  })
  assert.equal(out.state, 'not-registered', '内容长得像工具产物不等于它在登记 root 内')
})

test('接线锁:水印层必须真的在数分母之前问这一档(造好没装车 = 没有)', () => {
  const src = fs.readFileSync(path.join(ROOT, 'scripts/watermark.mjs'), 'utf8')
  assert.match(
    src,
    /from '\.\/lib\/tool-generated-roots\.mjs'/,
    '水印层必须 import 判据(只 copy 一份实现就回到 §22c 禁止的老路)',
  )
  assert.match(src, /judgeToolGenerated\(\{ rel, text, entries/, '必须按被审面正文逐文件判定')
  const atJudge = src.indexOf('judgeToolGenerated({ rel, text, entries')
  const atTotal = src.indexOf('total++', atJudge)
  assert.ok(
    atJudge > 0 && atTotal > atJudge,
    '豁免必须在 total++ 之前 —— 进了分母就会把覆盖率读成暴跌',
  )
  assert.match(src, /toolGenIssues\.length > 0/, '前提失效必须逐条点名,不得静默回到缺载荷判定')
})

test('端到端:list-uncovered(HEAD 面)里不得再出现这 89 份工具再生文件', () => {
  const out = execFileSync(
    process.execPath,
    [path.join(ROOT, 'scripts/watermark.mjs'), 'list-uncovered'],
    {
      encoding: 'utf8',
      cwd: ROOT,
      windowsHide: true,
      timeout: 300_000,
      stdio: ['ignore', 'pipe', 'pipe'],
    },
  )
  const lines = out
    .split(/\r?\n/)
    .map((l) => l.trim())
    .filter(Boolean)
  const hits = lines.filter((l) => l.startsWith(ROOT_DIR))
  assert.deepEqual(hits, [], `工具再生文件被豁免后不该出现在缺口清单里(实得 ${hits.length} 条)`)
})

test('④台账形状:九类不合格各判一处;坏档抛 ToolLedgerUnavailable,绝不退化成「这条没豁免」', () => {
  const tmp = mkScratch('toolgen-shape-')
  try {
    fs.mkdirSync(path.join(tmp, path.dirname(T.LEDGER_REL)), { recursive: true })
    const ledgerAbs = path.join(tmp, T.LEDGER_REL)
    const write = (entries) =>
      fs.writeFileSync(ledgerAbs, JSON.stringify({ schemaVersion: 1, entries }, null, 2), 'utf8')

    const OK = {
      id: 'x',
      root: 'a/b/',
      markerRegex: '^a$',
      expires: '2099-01-01',
      evidence: [{ file: 'a', contains: 'a' }],
      reason: '理由足够长的一行(过最短门槛)',
    }
    const badCases = [
      [{ ...OK, root: 'no/trailing/slash' }, 'root 必须以 / 收尾'],
      [{ ...OK, root: 'a/b' }, 'root 缺尾斜杠'],
      [{ ...OK, markerRegex: '([' }, 'markerRegex 编译不过'],
      [{ ...OK, markerRegex: '' }, 'markerRegex 为空'],
      [{ ...OK, expires: '2099-1-1' }, 'expires 月日未补零'],
      [{ ...OK, expires: '2099-01-01T00:00:00' }, 'expires 带时间'],
      [{ ...OK, evidence: [] }, 'evidence 为空'],
      [{ ...OK, reason: '短' }, 'reason 太短'],
      [{ ...OK, id: '' }, 'id 为空'],
    ]
    for (const [entry, label] of badCases) {
      write([entry])
      let threw = null
      try {
        T.loadToolGeneratedEntries(tmp)
      } catch (e) {
        threw = e
      }
      assert.ok(
        threw instanceof T.ToolLedgerUnavailable,
        `${label}:必须抛 ToolLedgerUnavailable(实得 ${threw === null ? '没有抛' : threw.constructor.name})`,
      )
    }

    write([OK])
    assert.deepEqual(
      T.loadToolGeneratedEntries(tmp).map((e) => e.id),
      ['x'],
      '合格条目必须原样读出来(形状校验不能一律拒)',
    )

    fs.rmSync(ledgerAbs, { force: true })
    assert.deepEqual(T.loadToolGeneratedEntries(tmp), [], '缺台账 = 该档不存在 ⇒ 覆盖面照旧全量判')
  } finally {
    rmScratch(tmp)
  }
})
