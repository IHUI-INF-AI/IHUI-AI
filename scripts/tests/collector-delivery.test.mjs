import { test } from 'node:test'
import assert from 'node:assert/strict'

import { judgeCollectorDelivery } from '../lib/collector-delivery.mjs'

test('取消且没有错误也没有样本，是正在退出', () => {
  assert.deepEqual(judgeCollectorDelivery({ cancelled: true, error: null, sample: null }), {
    disposition: 'exiting',
    reason: 'cancel-quiet',
  })
})

test('取消同时又带来样本或错误，不能当成退出或失败', () => {
  assert.equal(
    judgeCollectorDelivery({ cancelled: true, error: null, sample: { n: 1 } }).reason,
    'cancel-not-quiet',
  )
  assert.equal(
    judgeCollectorDelivery({ cancelled: null, error: null, sample: null }).reason,
    'cancel-unmeasured',
  )
})

test('未取消时缺样本是未判定，有错误才是失败', () => {
  assert.equal(
    judgeCollectorDelivery({ cancelled: false, error: null, sample: null }).reason,
    'sample-absent',
  )
  assert.equal(
    judgeCollectorDelivery({ cancelled: false, error: new Error('x'), sample: null }).reason,
    'sample-error',
  )
  assert.equal(
    judgeCollectorDelivery({ cancelled: false, error: null, sample: { n: 1 } }).reason,
    'sample-ready',
  )
})
