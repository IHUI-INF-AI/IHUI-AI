import { test } from 'node:test'
import assert from 'node:assert/strict'

import { judgeLockHolder } from '../lib/lock-holder.mjs'

const ttlMs = 60_000
const at = '2026-11-07T02:00:00.000Z'
const atMs = Date.parse(at)

test('holder null 是 free', () => {
  assert.deepEqual(judgeLockHolder({ holder: null, nowMs: atMs, ttlMs }), {
    verdict: 'free',
    reason: 'no-holder',
  })
})

test('TTL 内是 held', () => {
  assert.deepEqual(
    judgeLockHolder({
      holder: { name: 'sess-a', at },
      nowMs: atMs + 1_000,
      ttlMs,
    }),
    { verdict: 'held', reason: 'within-ttl', name: 'sess-a' },
  )
})

test('超过 TTL 是 expired', () => {
  assert.deepEqual(
    judgeLockHolder({
      holder: { name: 'sess-a', at },
      nowMs: atMs + ttlMs + 1,
      ttlMs,
    }),
    { verdict: 'expired', reason: 'ttl-exceeded', name: 'sess-a' },
  )
})

test('ttlMs 缺失是 unjudged 不是 held', () => {
  const verdict = judgeLockHolder({
    holder: { name: 'sess-a', at },
    nowMs: atMs + 1_000,
  })
  assert.deepEqual(verdict, { verdict: 'unjudged', reason: 'ttl-unmeasured' })
  assert.notEqual(verdict.verdict, 'held')
  assert.notEqual(verdict.verdict, 'free')
})

test('时刻在未来是 time-inverted', () => {
  assert.deepEqual(
    judgeLockHolder({
      holder: { name: 'sess-a', at },
      nowMs: atMs - 1,
      ttlMs,
    }),
    { verdict: 'unjudged', reason: 'time-inverted' },
  )
})
