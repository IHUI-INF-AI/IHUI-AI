import { test } from 'node:test'
import assert from 'node:assert/strict'

import { admitBrokeredCommand, BROKERED_COMMANDS } from '../lib/brokered-command.mjs'

test('命令名没量到不执行', () => {
  for (const name of [null, undefined, '', '   ']) {
    const verdict = admitBrokeredCommand(name)
    assert.equal(verdict.disposition, 'unjudged')
    assert.equal(verdict.reason, 'name-unmeasured')
    assert.equal(verdict.broker, false)
  }
})

test('点名清单里的命令只交给代理，不在这里执行', () => {
  assert.equal(BROKERED_COMMANDS.includes('rm'), true)
  const verdict = admitBrokeredCommand('C:\\tools\\rm.exe')
  assert.equal(verdict.disposition, 'admitted')
  assert.equal(verdict.reason, 'known-command')
  assert.equal(verdict.broker, true)
  assert.equal(Object.hasOwn(verdict, 'execute'), false)
})

test('没点名的命令不判成禁用', () => {
  const verdict = admitBrokeredCommand('bash')
  assert.equal(verdict.disposition, 'unjudged')
  assert.equal(verdict.reason, 'name-unlisted')
  assert.equal(verdict.broker, false)
})

test('点名清单原样冻结', () => {
  assert.equal(BROKERED_COMMANDS.length, 27)
  assert.equal(Object.isFrozen(BROKERED_COMMANDS), true)
  assert.equal(BROKERED_COMMANDS.includes('codebuddy-toybox-dispatch'), true)
})
