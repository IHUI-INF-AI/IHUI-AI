import { test } from 'node:test'
import assert from 'node:assert/strict'

import { judgeTitleFlag } from '../lib/title-flag.mjs'

test('布尔值按类型谎报拒绝', () => {
  for (const value of [true, false]) {
    const verdict = judgeTitleFlag(value)
    assert.equal(verdict.disposition, 'refused')
    assert.equal(verdict.reason, 'boolean-lie')
    assert.equal(verdict.flag, null)
  }
})

test('缺席或非整数不解释成未自定义', () => {
  for (const value of [undefined, null, '2', 2.5, Number.NaN]) {
    const verdict = judgeTitleFlag(value)
    assert.equal(verdict.disposition, 'unjudged')
    assert.equal(verdict.reason, 'title-unmeasured')
    assert.equal(verdict.flag, null)
  }
})

test('数字原样留下且不附加含义', () => {
  const verdict = judgeTitleFlag(2)
  assert.deepEqual(verdict, { disposition: 'recorded', reason: 'numeric-flag', flag: 2 })
  assert.equal(Object.hasOwn(verdict, 'userDefined'), false)
})
