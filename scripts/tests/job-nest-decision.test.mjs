import { test } from 'node:test'
import assert from 'node:assert/strict'

import { decideJobNesting } from '../lib/job-nest-decision.mjs'

test('父进程不在作业里就新建', () => {
  assert.deepEqual(decideJobNesting({ parentInJob: false, nestedAllowed: false }), {
    action: 'create-new',
    reason: 'parent-free',
  })
})

test('禁止嵌套时不脱离作业', () => {
  assert.deepEqual(
    decideJobNesting({ parentInJob: true, nestedAllowed: false, breakawayRequested: true }),
    { action: 'stay-in-parent', reason: 'breakaway-refused' },
  )
})

test('嵌套许可没量到就不启动', () => {
  assert.equal(decideJobNesting({ parentInJob: true, nestedAllowed: null }).action, 'unjudged')
})

test('允许嵌套才进入子作业', () => {
  assert.equal(decideJobNesting({ parentInJob: true, nestedAllowed: true }).action, 'nest')
})
