/**
 * `packages/api-client` 请求腿的两条**源码面**锁(2026-10-23 自该端包 vitest 的 W6/W7 搬来,判据一字未改)。
 *
 * 为什么必须住在脚本层:端包测试 import 仓库工具 `scripts/lib/code-mask.mjs` 构成
 * api-client(rank 20)→ repo-tooling(rank 90)的反向依赖,并把
 * `shared → api-client → repo-tooling → shared` 的成环坐实成现实 —— 架构契约门 D1/D2/D4 三条同红,
 * 而 D4(`module-cycle`)既不登记表级 exceptions 也不认行内 `arch-exempt`,除环只有一条路:搬文件。
 * 行为用例(W1–W5)留在 `packages/api-client/tests/weapp-no-abortcontroller.test.ts`,那才是端包该测的。
 */
import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { test } from 'node:test'
import { fileURLToPath } from 'node:url'

import { maskComments } from '../lib/code-mask.mjs'

const HERE = dirname(fileURLToPath(import.meta.url))
const SRC = resolve(HERE, '../../packages/api-client/src/client.ts')

test('W6 client.ts 里 new AbortController() 只剩 mergeAbortSignals 那一处(它只在有中止能力时被调)', () => {
  const masked = String(maskComments(readFileSync(SRC, 'utf8')))
  const sites = masked.split('\n').filter((l) => l.includes('new AbortController()'))
  assert.equal(sites.length, 1)
  assert.match(sites[0], /const controller = new AbortController\(\)/)
})

test('W7 超时看门狗的实现全仓只住 transport.ts 一处', () => {
  const face = readFileSync(SRC, 'utf8')
  assert.equal(/setTimeout\(\(\)\s*=>\s*timeoutController\.abort/.test(face), false)
  assert.match(face, /startTimeoutWatchdog\(/)
})
