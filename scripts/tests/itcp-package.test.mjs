// ITCP 独立包的同步锁(2026-11-27):protocol/ 产物必须与源逐字节一致,
// 且类型文件保持"零 import 可单独编译"。测试即协议的第一道采用者。
import { execFileSync } from 'node:child_process';
import { readFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { describe, test } from 'node:test';
import assert from 'node:assert/strict';

const HERE = dirname(fileURLToPath(import.meta.url));
const REPO = resolve(HERE, '../..');
const SYNC = resolve(REPO, 'scripts/sync-itcp-package.mjs');

function run(args) {
  try {
    const out = execFileSync(process.execPath, [SYNC, ...args], { cwd: REPO, encoding: 'utf8' });
    return { code: 0, out };
  } catch (error) {
    const stderr = typeof error?.stderr === 'string' ? error.stderr : '';
    const stdout = typeof error?.stdout === 'string' ? error.stdout : '';
    return { code: typeof error?.status === 'number' ? error.status : 99, out: stdout + stderr };
  }
}

describe('ITCP 独立包(protocol/)同步与自包含', () => {
  test('① 产物与源同步(--check 退出码 0)', () => {
    const r = run(['--check']);
    assert.equal(r.code, 0, r.out);
    assert.match(r.out, /同步一致\(2\/2\)/);
  });

  test('② 类型产物零 import(可脱离本仓单独编译)', () => {
    const text = readFileSync(resolve(REPO, 'protocol/src/tool-contract.ts'), 'utf8');
    const importLines = text.split('\n').filter((line) => /^\s*import\b/.test(line));
    assert.deepEqual(importLines, [], 'tool-contract.ts 不得有 import 行');
    assert.match(text, /AUTO-SYNCED/);
    assert.match(text, /export interface ToolContract/);
  });

  test('③ 规范正文与源一致,且含三态章节', () => {
    const text = readFileSync(resolve(REPO, 'protocol/docs/tool-contract-protocol.md'), 'utf8');
    assert.match(text, /5\.1 三态与跨代/);
    assert.match(text, /unknown/);
  });

  test('④ 包清单可发布:无运行时依赖,files 覆盖 src/docs', () => {
    const pkg = JSON.parse(readFileSync(resolve(REPO, 'protocol/package.json'), 'utf8'));
    assert.equal(pkg.name, '@ihui/tool-contract');
    assert.equal(pkg.version, '0.1.0');
    assert.equal(pkg.dependencies, undefined);
    assert.deepEqual(pkg.files, ['src', 'docs', 'README.md']);
  });
});
