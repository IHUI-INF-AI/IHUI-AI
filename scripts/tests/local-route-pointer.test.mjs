import { test } from 'node:test'
import assert from 'node:assert/strict'

import { judgeLocalRoute } from '../lib/local-route-pointer.mjs'

function record(over) {
  return {
    pid: 1200,
    baseUrl: 'http://127.0.0.1:8890',
    startedAt: 1_700_000_000_000,
    keyRef: 'ab12cd34',
    ...over,
  }
}

test('回环地址加短指纹引用才接纳', () => {
  assert.deepEqual(judgeLocalRoute(record()), {
    disposition: 'admitted',
    reason: 'loopback-pointer',
  })
})

test('指针里出现密钥原文就拒绝，指纹缺失是未判定', () => {
  assert.equal(judgeLocalRoute(record({ apiKey: 'sk-live' })).reason, 'secret-on-disk')
  assert.equal(judgeLocalRoute(record({ keyRef: '' })).reason, 'key-unmeasured')
  assert.equal(judgeLocalRoute(record({ keyRef: 'raw secret with spaces' })).reason, 'secret-shaped')
})

test('非回环或没有端口的地址拒绝', () => {
  assert.equal(judgeLocalRoute(record({ baseUrl: 'https://example.com/mcp' })).reason, 'host-not-local')
  assert.equal(judgeLocalRoute(record({ baseUrl: 'http://127.0.0.1' })).reason, 'host-not-local')
})
