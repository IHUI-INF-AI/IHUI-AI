import { test } from 'node:test'
import assert from 'node:assert/strict'

import { judgeArchMatch } from '../lib/arch-match.mjs'

test('同架构匹配，x64 进程在明确允许时可以跑 x86 件', () => {
  assert.equal(judgeArchMatch({ processArch: 'x64', fileMachine: 0x8664, wow64: false }).reason, 'same-arch')
  assert.equal(judgeArchMatch({ processArch: 'x64', fileMachine: 'I386', wow64: true }).reason, 'wow64-x86')
})

test('机器号读不出，或兼容位没量到，都是未判定', () => {
  assert.equal(judgeArchMatch({ processArch: 'x64', fileMachine: null, wow64: false }).reason, 'machine-unmeasured')
  assert.equal(judgeArchMatch({ processArch: 'x64', fileMachine: 0x014c, wow64: null }).reason, 'wow64-unmeasured')
})

test('不兼容的架构组合判为外来件', () => {
  assert.equal(judgeArchMatch({ processArch: 'arm64', fileMachine: 'AMD64', wow64: true }).reason, 'arch-mismatch')
  assert.equal(judgeArchMatch({ processArch: 'x64', fileMachine: 0x014c, wow64: false }).reason, 'arch-mismatch')
})
