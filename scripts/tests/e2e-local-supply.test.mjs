import assert from 'node:assert/strict'
import test from 'node:test'

import { __test__ as supply } from '../e2e-local-supply.mjs'
import { sanitizeDsn } from '../lib/db-probe-client.mjs'

const DSN = 'postgres://ihui_user:S3cr3t-pw@127.0.0.1:5432/ihui_e2e'

test('PASSWORD 型键整枚遮罩,只报有无与长度', () => {
  const shown = supply.shownValueOf('E2E_ADMIN_PASSWORD', 'hunter2')
  assert.equal(shown, '<set len=7>')
  assert.ok(!shown.includes('hunter2'))
})

test('DSN 型键只脱口令段,host 与库名可辨识', () => {
  const shown = supply.shownValueOf('E2E_DATABASE_URL', DSN)
  assert.equal(shown, 'postgres://ihui_user:***@127.0.0.1:5432/ihui_e2e')
  assert.ok(!shown.includes('S3cr3t-pw'))
  assert.ok(shown.includes('ihui_e2e'))
})

test('DSN 脱敏与唯一出口同源(不另写第二份正则)', () => {
  assert.equal(supply.shownValueOf('E2E_DATABASE_URL', DSN), sanitizeDsn(DSN))
})

test('其余键直显;缺值报 <absent> 而不吞成空串', () => {
  assert.equal(supply.shownValueOf('PLAYWRIGHT_BASE_URL', 'http://localhost:8801'), 'http://localhost:8801')
  assert.equal(supply.shownValueOf('E2E_SKIP_SEED', undefined), '<absent>')
  assert.equal(supply.shownValueOf('E2E_SKIP_SEED', ''), '<absent>')
})

test('供给面里所有 DSN/PASSWORD 型键都过脱敏面(防新增键漏判)', () => {
  const risky = supply.SUPPLY_FACE.filter((s) => /(PASSWORD|_URL|_DSN|_URI)$/.test(s.key))
  assert.ok(risky.length >= 2, '供给面应至少含一枚 PASSWORD 与一枚 DSN 键')
  for (const spec of risky) {
    const shown = supply.shownValueOf(spec.key, DSN)
    assert.ok(!shown.includes('S3cr3t-pw'), `${spec.key} 回显了口令段`)
  }
})
