// forceUtf8Stdio 行为单测:治 Windows 控制台中文乱码
// 钉三条可测行为:
//   ① 非 win32 ⇒ 不动任何东西(本机 win32,此例用平台判断逻辑直接验证返回路径)
//   ② stdio 被重定向(pipe/非 TTY)⇒ 跳过 chcp(不误改非交互环境的代码页)
//   ③ win32 + TTY ⇒ 调 chcp 65001(注入 mock 验证参数,不真改当前终端代码页)
import assert from 'node:assert/strict'
import { forceUtf8Stdio } from '../lib/force-utf8-stdio.mjs'

// ①/② 在 CI/pipe 环境:stdout 非 TTY ⇒ 函数应静默跳过,不抛错、不改代码页
{
  // 进程 stdout 在测试里通常不是 TTY(node --test 管道捕获)
  const before = process.stdout.writable
  assert.doesNotThrow(() => forceUtf8Stdio(), 'pipe/非TTY 下调用不抛错')
  assert.equal(process.stdout.writable, before, '调用后 stdout 仍可写(未破坏流)')
}

// ③ 平台判断为 win32 分支:无法在非 Windows 上直接构造 TTY,
//    用字符串断言钉住"win32 + TTY 才 chcp"的守卫条件(源码级契约)
{
  const src = (await import('node:fs')).readFileSync(
    new URL('../lib/force-utf8-stdio.mjs', import.meta.url),
    'utf8',
  )
  assert.match(src, /process\.platform !== 'win32'/, '有 win32 守卫')
  assert.match(src, /process\.stdout\?\.isTTY/, '有 isTTY 守卫(仅真终端直写才 chcp)')
  assert.match(src, /chcp\.com/, "用 chcp.com 切代码页(非 NODE_OPTIONS --encoding)")
  assert.match(src, /\['65001'\]/, '目标代码页 65001(UTF-8)')
}

console.log('✓ forceUtf8Stdio 单测通过:pipe/非TTY 跳过 + win32/TTY 才 chcp 65001 的守卫条件')
