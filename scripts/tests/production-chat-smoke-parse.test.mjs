// 生产冒烟脚本的解析腿自证。
//
// 为什么值得钉:冒烟的价值全在"假绿"的反面 —— 如果上下文注入帧里的 prompt 正文
// 被当成模型输出,空响应也会报通过,这条每日检查就失去意义。下面五档分别钉住:
// delta 正文计、finish 空帧不计、prompt 帧不计、error 帧必识别、死档判定同口径。

import { describe, it } from 'node:test'
import assert from 'node:assert/strict'

import { collectText, findError, isDeadModel } from '../smoke/production-chat-smoke.mjs'

describe('生产冒烟 SSE 解析', () => {
  it('OpenAI 兼容 delta.content 计为正文', () => {
    assert.deepEqual(collectText({ choices: [{ delta: { content: '你' } }] }), ['你'])
  })

  it('finish 帧(空 delta)不计正文', () => {
    assert.deepEqual(collectText({ choices: [{ delta: {}, finish_reason: 'stop' }] }), [])
  })

  it('上下文/提示词帧不算模型输出(防假绿)', () => {
    assert.deepEqual(collectText({ role: 'user', content: '只回复两个字：正常' }), [])
    assert.deepEqual(collectText({ data: { role: 'system', content: 'long prompt' } }), [])
  })

  it('error 帧必须被识别', () => {
    assert.equal(findError({ error: { message: 'upstream 500' } }), 'upstream 500')
    assert.equal(findError({ type: 'error', message: 'boom' }), 'boom')
    assert.equal(findError({ choices: [{ delta: { content: 'ok' } }] }), null)
  })

  it('死档判定与兜底表同口径', () => {
    assert.equal(isDeadModel('ihui/Auto-Model'), true)
    assert.equal(isDeadModel('stepfun/step-3.7-flash'), true)
    assert.equal(isDeadModel('auto'), false)
    assert.equal(isDeadModel(''), false)
  })
})
