// =============================================================================
// RECENT UPDATES 归并键的形状锁(2026-11-21 第 107 项)
// =============================================================================
// 病灶(实测):README 的自动块里 `**2026-11-21**` 被记成 10 个组、`**2026-11-16**` 12 个,
// 块内 43 枚日期头只对应 7 个真日期;`MAX_GROUPS=15` 写的是"最多 15 组",实际按
// "\n\n" 切段计数,于是既没合并同日、也从没裁过旧组。根因:旧实现把**既有整块**当一整段
// 追加,再切前 15 段 —— 结构上不可能合并同一天。
//
// 这一档钉四件:**同日必须合并**、**同 sha 只留一条**、**封顶单位是真日期组**、
// **无日期组原样跟随且不参与封顶**(块里可能有人写的小节,刷新器不许动它)。
//
// 跑法:node --test scripts/tests/auto-update-readme-recent-merge.test.mjs
// =============================================================================
import assert from 'node:assert/strict'
import test from 'node:test'

const { parseGroups, buildInner } = (await import('../auto-update-readme-recent.mjs')).__test__

const g = (date, ...bullets) => [`**${date}**`, ...bullets].join('\n')

test('107-① 同日已有组 ⇒ 新条目并入同一个组,不再出现第二枚同日日期头', () => {
  const out = buildInner([g('2026-11-21', '- a 条目 (aaaaaaaaaa)')], g('2026-11-21', '- b 条目 (bbbbbbbbbb)'))
  const heads = out.split('\n').filter((x) => /^\*\*20/.test(x))
  assert.deepEqual(heads, ['**2026-11-21**'], '同日日期头必须只有一枚')
  const idxNew = out.indexOf('- a 条目')
  const idxOld = out.indexOf('- b 条目')
  assert.ok(idxNew >= 0 && idxOld > idxNew, '新条目前置:同日组里新条目必须在既有条目之前')
})

test('107-② 同一条提交被两个日期组各记一次 ⇒ 只留最新那一组的一条', () => {
  const out = buildInner(
    [g('2026-11-21', '- 修复:x (cccccccccc)')],
    [g('2026-11-21', '- 修复:x (cccccccccc)'), g('2026-11-20', '- 修复:x (cccccccccc)')].join('\n\n'),
  )
  const hits = out.split('\n').filter((x) => x.includes('(cccccccccc)'))
  assert.equal(hits.length, 1, '同 sha 在块内只许留一条(否则同一枚提交被记两次)')
  assert.match(out, /^\*\*2026-11-21\*\*/m, '被留下的那条应在最新的日期组里')
})

test('107-③ 封顶单位是真日期组:组数超 MAX_GROUPS 时丢最旧,且不留下半天日期头', () => {
  const existing = Array.from({ length: 20 }, (_, i) => g(`2026-11-${String(20 - i).padStart(2, '0')}`, `- e${i} 条目 (${String(i).repeat(10)})`)).join('\n\n')
  const out = buildInner([], existing)
  const heads = out.split('\n').filter((x) => /^\*\*20/.test(x))
  assert.equal(heads.length, 15, '封顶单位 = 真日期组(MAX_GROUPS=15),20 组只留 15 组')
  assert.match(heads[0], /2026-11-20/, '最旧的组被丢,最新的组排在最前')
  assert.match(heads[14], /2026-11-06/, '留下的最后一组是第 15 新的日期(不是第 15 个文本段)')
})

test('107-④ 无日期组原样跟随、不参与封顶也不被裁', () => {
  const out = buildInner([g('2026-11-21', '- 新条目 (dddddddddd)')], '人写的小节\n第一行\n第二行')
  assert.match(out, /人写的小节/, '无日期组必须原样保留')
  assert.ok(out.endsWith('人写的小节\n第一行\n第二行'), '无日期组跟随在日期组之后,内容逐行不动')
})

test('107-⑤ 解析-重排幂等:同一份块再过一遍必须逐字节不变', () => {
  const once = buildInner([g('2026-11-21', '- x (eeeeeeeeee)')], g('2026-11-20', '- y (ffffffffff)'))
  const twice = buildInner([], once)
  assert.equal(twice, once, '归并必须幂等(否则每次提交都会重写 README 制造噪声)')
  assert.equal(parseGroups(once).length, 2)
})
