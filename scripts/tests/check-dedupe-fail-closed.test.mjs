import { spawnSync } from 'node:child_process'
import { resolve } from 'node:path'
import { test } from 'node:test'
import assert from 'node:assert/strict'

/**
 * check-dedupe(守门 7)取材失败必须 fail-closed(2026-11-05 立)。
 *
 * 改前:catch 后 `return process.exit(0)` ⇒ git 派生失败被洗成「pnpm-lock.yaml 未变更」放行,
 * 而本门是 blocking。改后按 §0.3 判「未判定」exit 2,并点名原因。
 *
 * 夹具手法:把 GIT_BIN 指向 node 自身 —— resolveGitBin 的 `--version` 探针会通过(拿到 vX.Y.Z),
 * 但后续 `git diff --cached --name-only` 由 node 执行必然失败 ⇒ 精确命中 catch 分支。
 */

const ROOT = resolve(import.meta.dirname, '../..')
const SCRIPT = resolve(ROOT, 'scripts/check-dedupe.mjs')
const RUN_OPTS = {
  cwd: ROOT,
  encoding: 'utf8',
  windowsHide: true,
  timeout: 60_000,
  maxBuffer: 64 << 20,
}

function runBrokenGit() {
  return spawnSync(process.execPath, [SCRIPT, '--staged'], {
    ...RUN_OPTS,
    env: { ...process.env, GIT_BIN: process.execPath },
  })
}

test('T1 阳性对照:git 派生失败 ⇒ exit 2 未判定,不再 exit 0 放行', () => {
  const r = runBrokenGit()
  assert.equal(
    r.status,
    2,
    `期望 exit 2,实得 status=${r.status};stdout=${r.stdout};stderr=${r.stderr}`,
  )
  assert.match(r.stderr, /未判定/)
  assert.match(r.stderr, /git 派生失败/)
})

test('T2 对照:脚本自身健康(--self-test 通过),修复未把整门改坏', () => {
  const r = spawnSync(process.execPath, [SCRIPT, '--self-test'], RUN_OPTS)
  assert.equal(r.status, 0, `--self-test 应通过,实得 status=${r.status};stderr=${r.stderr}`)
})
