import { test } from 'node:test'
import assert from 'node:assert/strict'

import { judgeExtensionSupply } from '../lib/extension-supply.mjs'

const HASH = 'ab'.repeat(32)

function record(over) {
  return {
    version: '1.2.3',
    url: 'https://example.com/ext.crx',
    publicKeyMode: 'fixed_dev',
    extensionId: 'abcdefghijklmnop',
    sha256: HASH,
    ...over,
  }
}

test('声明与实测一致才允许安装', () => {
  assert.deepEqual(judgeExtensionSupply(record(), HASH), {
    disposition: 'sealed',
    reason: 'id-and-hash',
    action: 'install',
  })
})

test('没实测、模式不认识或地址不是 https 都是未判定', () => {
  assert.equal(judgeExtensionSupply(record(), null).reason, 'measure-absent')
  assert.equal(judgeExtensionSupply(record({ publicKeyMode: 'rotating' }), HASH).reason, 'mode-unmeasured')
  assert.equal(judgeExtensionSupply(record({ url: 'http://example.com/a' }), HASH).reason, 'url-unmeasured')
})

test('实测哈希对不上就拒绝，且不给出安装动作', () => {
  assert.deepEqual(judgeExtensionSupply(record(), 'cd'.repeat(32)), {
    disposition: 'refused',
    reason: 'content-mismatch',
    action: 'none',
  })
})
