// 门 240 判据镜像测试:直接 import 源脚本 __test__(§22c,判据零复制)
import assert from 'node:assert/strict'
import { test } from 'node:test'
import { __test__ as gate } from '../check-token-literal-debt.mjs'

test('literalDebtOf:恰在档的裸数字计数', () => {
  assert.equal(gate.literalDebtOf('padding: 16'), 1)
  assert.equal(gate.literalDebtOf('fontSize: 14'), 1)
  assert.equal(gate.literalDebtOf('gap: 8, rowGap: 12'), 2)
  assert.equal(gate.literalDebtOf('padding: 10'), 0, '杂值无档可对,不计(不做成只有作者能猜的恒红门)')
  assert.equal(gate.literalDebtOf('marginTop: -16'), 0, '负值不转')
  assert.equal(gate.literalDebtOf('padding: rnSpacing.lg'), 0)
  assert.equal(gate.literalDebtOf(null), 0)
})

test('addedDebt:只拦变大', () => {
  assert.equal(gate.addedDebt(3, 3), 0)
  assert.equal(gate.addedDebt(3, 5), 2)
  assert.equal(gate.addedDebt(0, 1), 1)
  assert.equal(gate.addedDebt(5, 3), 0, '减少不算回潮')
})

test('阳性对照:把档位改回裸数字必须被抓', () => {
  const before = 'const s = { padding: rnSpacing.lg }'
  const after = 'const s = { padding: 16 }'
  assert.equal(gate.literalDebtOf(before), 0)
  assert.equal(gate.addedDebt(gate.literalDebtOf(before), gate.literalDebtOf(after)), 1)
})
