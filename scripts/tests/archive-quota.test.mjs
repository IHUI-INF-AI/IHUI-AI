import { test } from 'node:test'
import assert from 'node:assert/strict'

import { judgeArchiveInstall } from '../lib/archive-quota.mjs'

const HASH = 'a'.repeat(64)

function base(over) {
  return {
    presence: 'ensure-minimum',
    revision: 3,
    archiveSha256: HASH,
    entryCount: 2,
    expandedBytes: 100,
    maxEntries: 10,
    maxExpandedBytes: 1000,
    installedRevision: 1,
    ...over,
  }
}

test('已达最低修订就跳过，低于才解压', () => {
  assert.deepEqual(judgeArchiveInstall(base({ installedRevision: 3 })), {
    disposition: 'skip',
    reason: 'minimum-met',
    action: 'none',
  })
  assert.equal(judgeArchiveInstall(base({ installedRevision: 2 })).reason, 'below-minimum')
})

test('配额或哈希没量到是未判定，不得当成不限额放行', () => {
  assert.equal(judgeArchiveInstall(base({ maxEntries: null })).reason, 'quota-unmeasured')
  assert.equal(judgeArchiveInstall(base({ archiveSha256: 'AA' })).reason, 'hash-unmeasured')
  assert.equal(judgeArchiveInstall(base({ presence: 'always' })).reason, 'presence-unmeasured')
})

test('超出条数或展开字节拒绝，且不给出解压动作', () => {
  assert.deepEqual(judgeArchiveInstall(base({ entryCount: 11 })), {
    disposition: 'refused',
    reason: 'entry-quota',
    action: 'none',
  })
  assert.equal(judgeArchiveInstall(base({ expandedBytes: 1001 })).reason, 'byte-quota')
})
