import { test } from 'node:test'
import assert from 'node:assert/strict'

import { decideRequireBinding, judgeNativeBinding } from '../lib/native-binding.mjs'

test('还没加载过不得标成不可用', () => {
  const verdict = judgeNativeBinding({ attempted: false, bindingPresent: false, loadError: null })
  assert.equal(verdict.disposition, 'unjudged')
  assert.equal(verdict.reason, 'not-loaded')
  assert.equal(verdict.supported, null)
  assert.equal(decideRequireBinding(verdict).throwError, false)
})

test('加载尝试没量到不得使用', () => {
  const verdict = judgeNativeBinding({ bindingPresent: true, loadError: null })
  assert.equal(verdict.reason, 'attempt-unmeasured')
  assert.equal(verdict.usable, false)
})

test('失败但没有错误文本不得标成不可用', () => {
  const verdict = judgeNativeBinding({ attempted: true, bindingPresent: false, loadError: '' })
  assert.equal(verdict.reason, 'error-unmeasured')
  assert.equal(verdict.supported, null)
  assert.equal(decideRequireBinding(verdict).throwError, false)
})

test('加载失败只有在真正调用时才要求抛错', () => {
  const verdict = judgeNativeBinding({ attempted: true, bindingPresent: false, loadError: 'missing' })
  assert.equal(verdict.disposition, 'unsupported')
  assert.equal(verdict.supported, false)
  assert.deepEqual(decideRequireBinding(verdict), {
    disposition: 'refused',
    reason: 'load-failed',
    throwError: true,
  })
})

test('加载成功才可使用', () => {
  const verdict = judgeNativeBinding({ attempted: true, bindingPresent: true, loadError: null })
  assert.equal(verdict.usable, true)
  assert.equal(decideRequireBinding(verdict).throwError, false)
  assert.equal(decideRequireBinding(verdict).disposition, 'admitted')
})

test('成功却带着错误文本时不采用', () => {
  const verdict = judgeNativeBinding({ attempted: true, bindingPresent: true, loadError: 'stale' })
  assert.equal(verdict.reason, 'error-unexpected')
  assert.equal(verdict.usable, false)
})
