/**
 * DB-14 镜像测试：`check-migrations-landed` 的 hash 校验必须能判红。
 *
 * 旧判据只要 `created_at == entry.when` 就短路，文件字节后被改也永远判 landed；
 * 这里钉死：when 命中但文件 sha256 与账本 hash 都不符 ⇒ verdict=missing / exit 1。
 */
import { describe, it } from 'node:test'
import assert from 'node:assert/strict'

import { __test__ as L } from '../check-migrations-landed.mjs'

const HEX = (c) => c.repeat(64)

describe('DB-14 landed hash 校验失败必须非 0', () => {
  it('when 命中但文件 hash 与账本不符 ⇒ missing / exit 1（不再是 undetermined/2）', () => {
    const text = 'ALTER TABLE t ADD COLUMN c int;\n'
    const r = L.evaluate({
      entries: [{ idx: 1, tag: 'drifted', when: 100 }],
      dsn: 'x',
      runner: () => `100|${HEX('f')}`,
      sqlTextOf: () => text,
    })
    assert.equal(r.verdict, 'missing')
    assert.equal(L.exitCodeOf(r), 1)
    assert.match(r.missing[0], /hash/)
  })

  it('hash 逐字命中 ⇒ landed（when 漂移时内容归属仍成立）', () => {
    const text = 'ALTER TABLE t ADD COLUMN c int;\n'
    const r = L.evaluate({
      entries: [{ idx: 1, tag: 'legacy', when: 77 }],
      dsn: 'x',
      runner: () => `1|${L.sha256Hex(text)}`,
      sqlTextOf: () => text,
    })
    assert.equal(r.verdict, 'landed')
    assert.equal(L.exitCodeOf(r), 0)
  })

  it('取不到 .sql 正文时仍按 when 兜底，不误报', () => {
    const r = L.evaluate({
      entries: [{ idx: 1, tag: 'no-file', when: 100 }],
      dsn: 'x',
      runner: () => `100|${HEX('a')}`,
      sqlTextOf: () => null,
    })
    assert.equal(r.verdict, 'landed')
  })
})
