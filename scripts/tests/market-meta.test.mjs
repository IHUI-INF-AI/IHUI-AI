import { test } from 'node:test'
import assert from 'node:assert/strict'

import { judgeMarketMeta } from '../lib/market-meta.mjs'

const HASH = 'ab'.repeat(32)

test('三件齐才封存', () => {
  assert.deepEqual(judgeMarketMeta({ etag: 'W/"1"', sha256: HASH, sourceKey: 'market' }), {
    disposition: 'sealed',
    reason: 'etag-and-hash',
  })
})

test('缺 etag、缺来源或哈希不是小写 64 位都是未判定', () => {
  assert.equal(judgeMarketMeta({ etag: '', sha256: HASH, sourceKey: 'market' }).reason, 'etag-unmeasured')
  assert.equal(judgeMarketMeta({ etag: 'W/"1"', sha256: HASH, sourceKey: '' }).reason, 'source-unmeasured')
  assert.equal(judgeMarketMeta({ etag: 'W/"1"', sha256: HASH.toUpperCase(), sourceKey: 'market' }).reason, 'hash-unmeasured')
})
