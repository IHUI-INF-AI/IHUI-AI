import { test } from 'node:test'
import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import { execFileSync } from 'node:child_process'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..')
const GUARDIAN = readFileSync(join(ROOT, 'scripts', 'git-guardian.mjs'), 'utf8')

test('main 面必须派发 sweepGiteeAssetBackfill', () => {
  assert.match(GUARDIAN, /if \(!CHECK_ONLY\) sweepGiteeAssetBackfill\(\)/)
})

test('daemon tick 面也必须有它(只挂 main ⇒ 常驻持轮级锁时那趟永远让路)', () => {
  // 形状锁:daemon 段按字母序排在 sweepExposedCredentialRotation 与 sweepHeadRecallRows 之间。
  assert.match(
    GUARDIAN,
    /sweepExposedCredentialRotation\(\)[\s\S]{0,260}sweepGiteeAssetBackfill\(\)[\s\S]{0,260}sweepHeadRecallRows\(\)/,
  )
})

test('接线锁:此刻真跑背离巡检,dispatch-parity 不得再因该腿判 stalled', () => {
  let out = ''
  try {
    out = execFileSync(process.execPath, ['scripts/check-sweeper-liveness.mjs'], {
      cwd: ROOT,
      encoding: 'utf8',
      windowsHide: true,
      stdio: ['ignore', 'pipe', 'pipe'],
    })
  } catch (e) {
    // rc=1 有 stalled、rc=2 有未判定 —— 两者都要读结论行,不能因非零码丢掉输出。
    out = `${e?.stdout ?? ''}${e?.stderr ?? ''}`
  }
  const m = out.match(/dispatch-parity[^\n]*state=([a-z-]+)/)
  assert.ok(m, '未取到 dispatch-parity 结论行 ⇒ 同一把尺子没在判这一面')
  assert.notEqual(m[1], 'stalled')
})
