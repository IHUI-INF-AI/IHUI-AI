import { test } from 'node:test'
import assert from 'node:assert/strict'
import { join } from 'node:path'

import {
  BROWSER_REGISTRY_ROOTS,
  buildManifest,
  registryArgs,
  resolveRegExe,
  validateExtensionId,
} from '../install-extension-native-host.mjs'

const ID = 'abcdefghijklmnopabcdefghijklmnop'
const EXE = join(process.cwd(), 'apps', 'extension', 'fake-host.exe')

test('扩展 ID 只接受 32 位 a-p', () => {
  assert.equal(validateExtensionId(ID), true)
  assert.equal(validateExtensionId('ABCDEFGHIJKLMNOPABCDEFGHIJKLMNOP'), false)
  assert.equal(validateExtensionId('abcdefghijklmnopabcdefghijklmno'), false)
  assert.equal(validateExtensionId('abcdefghijklmnopabcdefghijklmnopq'), false)
})

test('manifest 只放指定扩展 origin', () => {
  assert.throws(() => buildManifest('not-an-id', EXE), /invalid extension id/)
  assert.throws(() => buildManifest(ID, 'relative-host.exe'), /absolute .exe/)
  assert.throws(() => buildManifest(ID, 'C:\\missing\\host.exe'), /does not exist/)
})

test('Chrome 与 Edge 写不同注册表根', () => {
  const manifest = 'C:\\IHUI-AI\\apps\\extension\\native-host\\ai.ihui.bridge.json'
  assert.ok(
    registryArgs(manifest, 'chrome').includes(`${BROWSER_REGISTRY_ROOTS.chrome}\\ai.ihui.bridge`),
  )
  assert.ok(
    registryArgs(manifest, 'edge').includes(`${BROWSER_REGISTRY_ROOTS.edge}\\ai.ihui.bridge`),
  )
  assert.throws(() => registryArgs(manifest, 'safari'), /unsupported browser/)
})

test('reg.exe 用绝对 System32 路径，不依赖调用方 PATH', () => {
  assert.equal(resolveRegExe({ SystemRoot: 'C:\\Windows' }), 'C:\\Windows\\System32\\reg.exe')
  assert.equal(resolveRegExe({ windir: 'D:\\Win' }), 'D:\\Win\\System32\\reg.exe')
})
