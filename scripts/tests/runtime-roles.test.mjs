import { test } from 'node:test'
import assert from 'node:assert/strict'

import {
  REQUIRED_RUNTIME_ROLES,
  OBSERVED_NAPI_ABI,
  judgeRuntimeRoles,
} from '../lib/runtime-roles.mjs'

const HASH = 'ab'.repeat(32)

function sealedFiles(over = {}) {
  const files = { spare: { sha256: HASH } }
  for (const role of REQUIRED_RUNTIME_ROLES) {
    files[role] = { sha256: HASH }
  }
  return { ...files, ...over }
}

test('八角色哈希齐且 ABI 为 10 则放行', () => {
  assert.equal(OBSERVED_NAPI_ABI, 10)
  assert.deepEqual(REQUIRED_RUNTIME_ROLES, [
    'entry',
    'scanWorker',
    'legacyMigrationWorker',
    'mtreeLoader',
    'mtreeBinary',
    'ripgrep',
    'assetModule',
    'assetBinary',
  ])
  assert.deepEqual(judgeRuntimeRoles({ abiVersion: 10, files: sealedFiles() }), {
    disposition: 'admitted',
    reason: 'roles-sealed',
    missing: [],
  })
})

test('缺一个角色则拒绝并点名', () => {
  const files = sealedFiles()
  delete files.scanWorker
  assert.deepEqual(judgeRuntimeRoles({ abiVersion: 10, files }), {
    disposition: 'refused',
    reason: 'role-absent',
    missing: ['scanWorker'],
  })
})

test('ABI 为 11 或哈希大写则未判定', () => {
  assert.deepEqual(judgeRuntimeRoles({ abiVersion: 11, files: sealedFiles() }), {
    disposition: 'unjudged',
    reason: 'abi-unknown',
    missing: null,
  })
  const files = sealedFiles()
  files.entry = { sha256: HASH.toUpperCase() }
  assert.deepEqual(judgeRuntimeRoles({ abiVersion: 10, files }), {
    disposition: 'unjudged',
    reason: 'hash-unmeasured',
    missing: null,
  })
})
