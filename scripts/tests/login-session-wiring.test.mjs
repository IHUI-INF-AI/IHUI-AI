/**
 * 登录会话接线锁（从 apps/miniapp-taro/tests/login-session-guard.test.ts 拆出，消门 103 端→repo-tooling 反向依赖）。
 * 判据本体仍由小程序 vitest 测；本文件只做源码文本形态锁，用 node:test + repo-tooling 层同一份遮罩。
 */
import { describe, it } from 'node:test'
import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { maskComments } from '../lib/code-mask.mjs'

const HERE = dirname(fileURLToPath(import.meta.url))
const SRC = resolve(HERE, '../../apps/miniapp-taro/src')
const codeFace = (rel) => maskComments(readFileSync(resolve(SRC, rel), 'utf8'))

describe('两条微信登录路径的接线锁', () => {
  const sites = ['utils/wechat-login.ts', 'utils/miniapp-login.ts']

  for (const rel of sites) {
    it(`${rel} 必须调用 requireLoginSession(注释掉的形态不算)`, () => {
      assert.match(codeFace(rel), /requireLoginSession\(/)
    })
  }

  it('判据全仓只住一处,两条路径不得各自再写一份 needPhone 判定', () => {
    const implementers = sites.filter((rel) => /needPhone\s*[:=]/.test(codeFace(rel)))
    assert.deepEqual(implementers, [])
  })
})
