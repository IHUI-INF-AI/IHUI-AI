// App Paths 注册表兜底(2026-11-26 立):豆包装在 D:\Huorong\doubao\app 这类
// 非标准目录、进程又没开时,靠 HKCU/HKLM App Paths 定 exe。判据 import 源函数,零复刻。
import assert from 'node:assert/strict'
import test from 'node:test'

import { __test__ as tpc } from '../lib/trae-client-process.mjs'

test('exePathsFromAppPathsRegistry:解析多行输出并去空/去重外杂行', () => {
  const calls = []
  const execFn = (cmd, args) => {
    calls.push({ cmd, args })
    return 'D:\\Huorong\\doubao\\app\\Doubao.exe\r\n\r\n  C:\\x\\Doubao.exe  \r\n'
  }
  const out = tpc.exePathsFromAppPathsRegistry('Doubao', {}, { execFn })
  assert.deepEqual(out, ['D:\\Huorong\\doubao\\app\\Doubao.exe', 'C:\\x\\Doubao.exe'])
  const joined = calls[0].args.join(' ')
  assert.ok(joined.includes('App Paths\\'), '脚本必须查 App Paths 基键')
  assert.ok(joined.includes("'Doubao.exe'"), 'image 必须作为子键名进脚本')
  assert.ok(joined.includes("'(default)'"))
})

test('product 含单引号按 PS 规则转义(不吞入命令)', () => {
  let script = ''
  const out = tpc.exePathsFromAppPathsRegistry("A'B", {}, {
    execFn: (_c, args) => {
      script = args.at(-1)
      return ''
    },
  })
  assert.deepEqual(out, [])
  assert.ok(script.includes("'A''B.exe'"), `转义结果应进子键名引号串:${script.slice(0, 400)}`)
})

test('execFn 抛错 ⇒ 空数组兜底,不炸 resolveProductExe 链', () => {
  const out = tpc.exePathsFromAppPathsRegistry('Doubao', {}, {
    execFn: () => {
      throw new Error('pwsh 不存在')
    },
  })
  assert.deepEqual(out, [])
})
