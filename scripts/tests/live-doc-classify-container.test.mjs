/**
 * `classifyMissing` 容器短路使用**全量候选**骨架的镜像测试(2026-10-17 立)。
 *
 * 失效形态(实测于 README 尾部碎片清理):
 *   HEAD 里回残着旧版生成块的**宽对齐**行 `| schema 文件    | 229   | \`dbSchemaFiles\`    |`；
 *   候选面正文里是**紧凑**行 `| schema 文件 | 229 | \`dbSchemaFiles\` |`，二者 `squash` 后逐字相等。
 *   但紧凑行**在 HEAD 里也存在** ⇒ 它不进 `localOnly`(候选面独有行) ⇒ 旧判据在 `localOnly`
 *   里找不到容器 ⇒ 判 `lost` ⇒ `merge-live-doc --apply` 把宽版原样插回 ⇒ 同键两行。
 *
 * 修法:容器短路的 `sq` 包含判断增加一支**全量候选**骨架池(`allSquashed`)，只抹空白不抹字符。
 *
 * 本测试钉两件事(一正一反，缺一不可):
 *   P1 正向:HEAD 宽对齐行 + 候选紧凑行(且紧凑行 HEAD 里也有)⇒ 判 superseded，**不是 lost**；
 *   P2 反向:内容真被换掉(字符真变了，不是只差空白)⇒ 仍判 lost，不得被洗绿。
 */
import test from 'node:test'
import assert from 'node:assert/strict'

import { classifyMissing } from '../lib/live-doc-classify.mjs'

const WIDE = '| schema 文件    | 229   | `dbSchemaFiles`    |'
const TIGHT = '| schema 文件 | 229 | `dbSchemaFiles` |'

test('P1 正向:HEAD 宽对齐行 + 候选紧凑行(紧凑行 HEAD 里也有)⇒ superseded 不是 lost', () => {
  // HEAD 同时含宽版(碎片)与紧凑版 ⇒ 紧凑版被 localOnly 排除,正是失效条件
  const head = ['# 文档', WIDE, TIGHT, '无关的一行正文内容让行数看起来正常']
  // 候选面只保留紧凑版(清理掉宽版碎片后的形态)
  const cand = ['# 文档', TIGHT, '无关的一行正文内容让行数看起来正常']

  const v = classifyMissing(head, cand)
  const verdict = v.get(WIDE)
  assert.equal(
    verdict,
    'superseded',
    `宽版应判 superseded(内容仍在,只差空白对齐),实判 ${verdict} —— 判 lost 会让 --apply 把宽版插回造成同键两行`,
  )
})

test('P2 反向:内容真被换掉(字符真变了)⇒ 仍判 lost,不得被洗绿', () => {
  const head = ['# 文档', '这是一条独一无二的登记行，它讲的是甲方案的实施细节与验收判据。']
  const cand = ['# 文档', '这完全是另一件事，讲乙方案的完全不同内容，没有任何字面重合。']

  const v = classifyMissing(head, cand)
  const verdict = v.get('这是一条独一无二的登记行，它讲的是甲方案的实施细节与验收判据。')
  assert.equal(verdict, 'lost', `内容被换掉必须仍判 lost,实判 ${verdict} —— 洗绿就是放行了一次真删除`)
})

test('P3 反向:只差数字的行仍按内容判定(数字不是"空白",不得被骨架短路洗绿)', () => {
  // 这一条锁住"只抹空白、不抹数字":若实现里误把数字也抹掉,这条会变成 superseded 而失败。
  const head = ['# 文档', '工程守门一共 203 道，全部在提交链上生效并各有镜像测试覆盖。']
  const cand = ['# 文档', '工程守门一共 999 道，全部在提交链上生效并各有镜像测试覆盖。']

  const v = classifyMissing(head, cand)
  const verdict = v.get('工程守门一共 203 道，全部在提交链上生效并各有镜像测试覆盖。')
  // 仅数字不同时 Jaccard 很高 ⇒ superseded 是正确结论(内容仍在);关键是**不能判 lost**。
  assert.notEqual(verdict, 'lost', `仅数字变化不该判 lost,实判 ${verdict}`)
})
