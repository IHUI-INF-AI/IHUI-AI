import { test } from 'node:test'
import assert from 'node:assert/strict'

import { admitBrokeredFs, BROKERED_FS_OPS } from '../lib/brokered-fs-gate.mjs'

test('开关没量全时不直通', () => {
  const verdict = admitBrokeredFs({ hookEnabled: false, sandboxOn: null, op: 'readFile', sessionId: 's' })
  assert.equal(verdict.reason, 'switch-unmeasured')
  assert.equal(verdict.issueToken, false)
})

test('两个开关都关闭时不拦截', () => {
  const verdict = admitBrokeredFs({ hookEnabled: false, sandboxOn: false, op: 'unlink', sessionId: '' })
  assert.equal(verdict.disposition, 'off')
  assert.equal(verdict.intercept, false)
})

test('任一开关为真就拦截，会话缺失不放行', () => {
  const verdict = admitBrokeredFs({ hookEnabled: true, sandboxOn: null, op: 'rm', sessionId: '  ' })
  assert.equal(verdict.disposition, 'unjudged')
  assert.equal(verdict.reason, 'session-absent')
  assert.equal(verdict.intercept, true)
  assert.equal(verdict.issueToken, false)
})

test('不认识的入口不发令牌', () => {
  const verdict = admitBrokeredFs({ hookEnabled: false, sandboxOn: true, op: 'stat', sessionId: 's1' })
  assert.equal(verdict.reason, 'op-unknown')
  assert.equal(verdict.issueToken, false)
})

test('十二个入口在会话齐备时都只发令牌', () => {
  assert.equal(BROKERED_FS_OPS.length, 12)
  for (const op of BROKERED_FS_OPS) {
    const verdict = admitBrokeredFs({ hookEnabled: true, sandboxOn: false, op, sessionId: 'sess' })
    assert.equal(verdict.disposition, 'admitted')
    assert.equal(verdict.reason, 'needs-token')
    assert.equal(verdict.issueToken, true)
  }
})
