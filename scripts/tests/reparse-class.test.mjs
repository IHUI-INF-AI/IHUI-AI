import { test } from 'node:test'
import assert from 'node:assert/strict'

import { classifyReparse } from '../lib/reparse-class.mjs'

test('挂载点与符号链接分开归类', () => {
  assert.equal(classifyReparse({ tag: 0xa0000003, substitute: 'D:\\data' }).kind, 'mount-point')
  assert.equal(classifyReparse({ tag: 'SYMLINK', substitute: 'C:\\link' }).kind, 'symlink')
})

test('标签或替代名没量到是未判定', () => {
  assert.equal(classifyReparse({ tag: null, substitute: 'D:\\data' }).reason, 'tag-unmeasured')
  assert.equal(classifyReparse({ tag: 0xa000000c, substitute: '' }).reason, 'substitute-unmeasured')
  assert.equal(classifyReparse({ tag: 0x80000000, substitute: 'D:\\data' }).reason, 'tag-unknown')
})
