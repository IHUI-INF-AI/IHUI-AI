import { test } from 'node:test'
import assert from 'node:assert/strict'

import { judgeRecoveryLedger } from '../lib/recovery-ledger.mjs'

test('失败列和恢复列都量到才入账，空数组是已量到的空', () => {
  assert.deepEqual(
    judgeRecoveryLedger({
      version: 1,
      entries: [],
      recoveries: [
        { resourceId: 'r1', adapter: 'file', operation: 'write', recoveredAt: 10 },
      ],
    }),
    {
      disposition: 'recorded',
      reason: 'both-columns',
      failures: 0,
      recoveries: [{ resourceId: 'r1', adapter: 'file', operation: 'write', recoveredAt: 10 }],
    },
  )
})

test('缺列不是空账，坏的恢复行不会被跳过', () => {
  assert.equal(judgeRecoveryLedger({ version: 1, entries: null, recoveries: [] }).reason, 'entries-unmeasured')
  assert.equal(
    judgeRecoveryLedger({
      version: 1,
      entries: [],
      recoveries: [{ resourceId: 'r1', adapter: 'file', operation: '', recoveredAt: 10 }],
    }).reason,
    'row-unmeasured',
  )
  assert.equal(judgeRecoveryLedger({ version: 2, entries: [], recoveries: [] }).reason, 'version-unmeasured')
})
