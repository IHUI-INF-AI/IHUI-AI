import { test } from 'node:test'
import assert from 'node:assert/strict'

import { planSentinelReceipt } from '../lib/sentinel-receipt.mjs'

const base = {
  status: 'ok',
  reason: '扫完',
  scanned: 4,
  linked: 4,
  reclaimedBytes: 0,
  scannedAt: '2026-11-07T02:00:00.000Z',
  truncated: false,
}

test('计数齐才出回执', () => {
  const planned = planSentinelReceipt(base)
  assert.equal(planned.ok, true)
  assert.equal(planned.receipt.scanned, 4)
})

test('缺扫描数不是 0', () => {
  const input = { ...base }
  delete input.scanned
  const planned = planSentinelReceipt(input)
  assert.equal(planned.reason, 'count-unmeasured')
  assert.equal(planned.receipt, null)
})

test('截断了不能记成功', () => {
  const planned = planSentinelReceipt({ ...base, truncated: true })
  assert.equal(planned.reason, 'truncated-not-ok')
})
