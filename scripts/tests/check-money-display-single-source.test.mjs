import assert from 'node:assert/strict'
import { execFileSync } from 'node:child_process'
import { readFileSync } from 'node:fs'
import test from 'node:test'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

import { __test__ as G } from '../check-money-display-single-source.mjs'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..')
const run = (name, fn) => test(name, () => assert.deepEqual(fn(), []))

run('selfTest 10 例全绿', () => G.selfTest())

test('__test__ 键齐备(源搬家报错红)', () => {
  for (const k of ['findLocalCentsYuanFormats', 'countInlineCentsFormats', 'evaluate', 'selfTest'])
    assert.equal(typeof G[k], 'function')
})

function grepSurf(surf) {
  try {
    return execFileSync(
      'git',
      ['grep', '-l', '-E', '(const|function) \\w*[Yy]uan\\w*\\s*[=(]', '--', surf],
      { encoding: 'utf8', maxBuffer: 1024 * 1024 * 32, cwd: ROOT, stdio: ['ignore', 'pipe', 'pipe'] },
    ).toString()
  } catch {
    return ''
  }
}

test('M1:真同形副本定义全灭(显示层现读 0 自算函数)', () => {
  const offenders = []
  for (const surf of ['apps/web', 'apps/miniapp-taro', 'apps/mobile-rn', 'packages/app']) {
    for (const rel of grepSurf(surf)
      .split('\n')
      .filter((s) => s && !/\.test\.|__tests__|\.stories\.|e2e\//.test(s))) {
      const src = readFileSync(path.join(ROOT, rel), 'utf8')
      for (const h of G.findLocalCentsYuanFormats(src)) offenders.push(`${rel}:${h.line} ${h.name}`)
    }
  }
  assert.deepEqual(offenders, [])
})
