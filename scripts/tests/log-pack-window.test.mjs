import { test } from 'node:test'
import assert from 'node:assert/strict'

import { judgeLogPack } from '../lib/log-pack-window.mjs'

const NOW = 1_700_000_000_000

test('龄期内的留下，更老的不进包', () => {
  const verdict = judgeLogPack({
    maxAgeDays: 1,
    nowMs: NOW,
    files: [
      { path: 'fresh.log', mtimeMs: NOW - 3_600_000 },
      { path: 'old.log', mtimeMs: NOW - 2 * 86_400_000 },
    ],
  })
  assert.deepEqual(verdict, { disposition: 'packed', reason: 'within-age', files: ['fresh.log'] })
})

test('天数或某个修改时间没量到时整包未判定', () => {
  assert.equal(judgeLogPack({ maxAgeDays: null, nowMs: NOW, files: [] }).reason, 'age-unmeasured')
  assert.equal(
    judgeLogPack({
      maxAgeDays: 7,
      nowMs: NOW,
      files: [{ path: 'a.log', mtimeMs: null }],
    }).files,
    null,
  )
})

test('修改时间在未来则未判定，不把该文件算进包', () => {
  assert.equal(
    judgeLogPack({
      maxAgeDays: 7,
      nowMs: NOW,
      files: [{ path: 'a.log', mtimeMs: NOW + 1 }],
    }).reason,
    'time-inverted',
  )
})
