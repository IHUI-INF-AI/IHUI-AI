/* eslint-disable no-console -- 校验器为 CLI 工具,需 console 输出诊断信息 */
/**
 * 技能包格式校验器(P3 3-5 专项 v1,2026-09-17 立)。
 *
 * 校验 SKILL.md(规范见 docs/SKILL_PACKAGE_SPEC.md,字段对齐 SkillFrontmatter):
 *   ERROR:frontmatter 缺失/name-description 必填违反/version 非语义化/source 非枚举/
 *         tags·tools 非数组/正文为空/正文引用的相对路径文件不存在
 *   WARNING:progressiveDisclosure=true 但正文 >5k 字/license 缺失/未识别字段(仅提示)
 *
 * 用法:
 *   node scripts/lint-skill-package.mjs <dir|SKILL.md> [...more]
 *   目录 = 找其下 SKILL.md;目录含子目录时递归扫描全部 SKILL.md。
 * 退出码:任一 ERROR → 1,否则 0。
 */
import { existsSync, readdirSync, readFileSync, statSync } from 'node:fs'
import { join, relative, dirname, resolve } from 'node:path'

const C = { red: '\x1b[31m', yellow: '\x1b[33m', green: '\x1b[32m', dim: '\x1b[2m', reset: '\x1b[0m' }
const SOURCES = new Set(['builtin', 'user', 'auto', 'hub'])
const ARRAY_FIELDS = ['tags', 'tools', 'allowedTools', 'relatedSkills']
const KNOWN_FIELDS = new Set([
  'name', 'description', 'allowedTools', 'tools', 'model', 'tags', 'version',
  'license', 'prerequisites', 'relatedSkills', 'progressiveDisclosure',
  'source', 'autoGeneratedAt', 'autoGeneratedFromTask',
])
const BODY_SOFT_LIMIT = 5000

let errCount = 0
let warnCount = 0
let checked = 0

function fail(file, msg) {
  errCount++
  console.error(`${C.red}ERROR${C.reset} [${file}] ${msg}`)
}
function warn(file, msg) {
  warnCount++
  console.warn(`${C.yellow}WARN${C.reset} [${file}] ${msg}`)
}
function ok(file) {
  console.log(`${C.green}PASS${C.reset} ${file}`)
}

/** 极简 YAML 子集解析(键: 值 / 键: [a, b] / 键: 多行 - item);嵌套 map 用一层缩进。 */
function parseFrontmatter(text) {
  const m = text.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n?/)
  if (!m) return null
  const fields = {}
  let currentArrayKey = null
  for (const raw of m[1].split(/\r?\n/)) {
    if (!raw.trim() || raw.trim().startsWith('#')) continue
    const listItem = raw.match(/^\s+-\s+(.*)$/)
    if (listItem && currentArrayKey) {
      if (!Array.isArray(fields[currentArrayKey])) fields[currentArrayKey] = []
      fields[currentArrayKey].push(listItem[1].trim().replace(/^['"]|['"]$/g, ''))
      continue
    }
    const kv = raw.match(/^([A-Za-z_][\w-]*):\s*(.*)$/)
    if (!kv) continue
    const key = kv[1]
    const value = kv[2].trim()
    currentArrayKey = null
    if (value === '') {
      // 可能是块数组或嵌套,先置空数组占位
      fields[key] = []
      currentArrayKey = key
      continue
    }
    if (value.startsWith('[') && value.endsWith(']')) {
      const inner = value.slice(1, -1).trim()
      fields[key] = inner
        ? inner.split(',').map((s) => s.trim().replace(/^['"]|['"]$/g, ''))
        : []
      continue
    }
    fields[key] = value.replace(/^['"]|['"]$/g, '')
  }
  return { fields, raw: m[1] }
}

function lintSkill(file) {
  checked++
  if (!existsSync(file)) {
    fail(file, '文件不存在')
    return
  }
  const text = readFileSync(file, 'utf-8')
  const fm = parseFrontmatter(text)
  if (!fm) {
    fail(file, '缺少 frontmatter(文件需以 --- 开头界定元数据块)')
    return
  }
  const { fields } = fm

  // 必填
  if (!fields.name || !String(fields.name).trim()) fail(file, 'frontmatter.name 必填')
  else if (String(fields.name).length > 64) fail(file, 'frontmatter.name 超过 64 字符')
  if (!fields.description || !String(fields.description).trim()) fail(file, 'frontmatter.description 必填(做什么 + 何时触发)')
  else if (String(fields.description).length > 1024) fail(file, 'frontmatter.description 超过 1024 字符')

  // 类型与取值
  if (fields.version !== undefined && fields.version !== '') {
    if (!/^\d+\.\d+\.\d+(-[\w.]+)?$/.test(String(fields.version))) {
      fail(file, `frontmatter.version 非语义化版本: ${fields.version}`)
    }
  }
  if (fields.source !== undefined && fields.source !== '' && !SOURCES.has(String(fields.source))) {
    fail(file, `frontmatter.source 非法: ${fields.source}(允许 builtin/user/auto/hub)`)
  }
  for (const key of ARRAY_FIELDS) {
    if (fields[key] !== undefined && !Array.isArray(fields[key])) {
      fail(file, `frontmatter.${key} 应为数组`)
    }
  }
  if (fields.progressiveDisclosure !== undefined && fields.progressiveDisclosure !== '') {
    if (!['true', 'false'].includes(String(fields.progressiveDisclosure))) {
      fail(file, `frontmatter.progressiveDisclosure 应为 true/false`)
    }
  }

  // 未知字段提示
  for (const key of Object.keys(fields)) {
    if (!KNOWN_FIELDS.has(key)) warn(file, `未识别字段 "${key}"(已忽略,确认拼写或属未来版本)`)
  }

  // 正文
  const bodyStart = text.indexOf('---', 3)
  const body = bodyStart >= 0 ? text.slice(text.indexOf('\n', bodyStart) + 1) : text
  if (!body.trim()) {
    fail(file, '正文为空(SKILL.md 需包含指令内容)')
    return
  }
  if (String(fields.progressiveDisclosure) === 'true' && body.length > BODY_SOFT_LIMIT) {
    warn(file, `progressiveDisclosure=true 但正文 ${body.length} 字 >${BODY_SOFT_LIMIT},大块内容应移至 references/`)
  }
  if (fields.license === undefined || fields.license === '') {
    warn(file, '未声明 license(默认视为「保留所有权利」,建议显式 MIT/Apache-2.0)')
  }

  // 正文引用的相对路径文件存在性(references/、scripts/、assets/ 开头的路径)
  const refRe = /\b((?:references|scripts|assets)\/[\w./-]+\.[\w-]+)/g
  const seen = new Set()
  for (const match of body.matchAll(refRe)) {
    const rel = match[1]
    if (seen.has(rel)) continue
    seen.add(rel)
    const abs = resolve(dirname(file), rel)
    if (!existsSync(abs)) fail(file, `正文引用的文件不存在: ${rel}`)
  }

  if (errCount === 0) ok(file)
}

/** 收集目标:文件直接用;目录找本层 SKILL.md,否则递归扫全部 SKILL.md */
function collect(target) {
  const abs = resolve(target)
  if (!existsSync(abs)) return []
  if (statSync(abs).isFile()) return [abs]
  const out = []
  const direct = join(abs, 'SKILL.md')
  if (existsSync(direct)) {
    out.push(direct)
    return out
  }
  const walk = (dir) => {
    for (const name of readdirSync(dir)) {
      const full = join(dir, name)
      if (!statSync(full).isDirectory()) {
        if (name === 'SKILL.md') out.push(full)
        continue
      }
      if (name === 'node_modules' || name === '.git') continue
      walk(full)
    }
  }
  walk(abs)
  return out
}

function main() {
  const targets = process.argv.slice(2)
  if (targets.length === 0) {
    console.log('用法: node scripts/lint-skill-package.mjs <dir|SKILL.md> [...more]')
    console.log('规范: docs/SKILL_PACKAGE_SPEC.md')
    process.exit(0)
  }
  const files = new Set()
  for (const t of targets) {
    for (const f of collect(t)) files.add(f)
  }
  if (files.size === 0) {
    console.error('未找到任何 SKILL.md')
    process.exit(1)
  }
  for (const f of files) lintSkill(f)
  console.log('')
  console.log(`校验完成: ${files.size} 个技能包, ERROR ${errCount}, WARNING ${warnCount}`)
  process.exit(errCount > 0 ? 1 : 0)
}

main()
