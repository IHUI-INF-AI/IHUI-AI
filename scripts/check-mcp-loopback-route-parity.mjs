/**
 * L08 路由表一致性门:
 *  - `routes/mcp-extended.ts` 里每个 `server.<method>('<path>')` 都必须在
 *    `services/mcp-business-routes.ts` 的 `MCP_BUSINESS_ROUTES` 有对应项;
 *  - 反向也查,防止适配器保留已删除路由;
 *  - 计数、重复、缺失、多余全部打印,任一不为零 exit 1。
 *
 * 用法: node scripts/check-mcp-loopback-route-parity.mjs
 */

import { readFileSync } from 'node:fs'
import { resolve } from 'node:path'

const root = resolve(import.meta.dirname, '..')
const fastifyPath = resolve(root, 'apps/api/src/routes/mcp-extended.ts')
const adapterPath = resolve(root, 'apps/api/src/services/mcp-business-routes.ts')

const fastifySource = readFileSync(fastifyPath, 'utf8')
const adapterSource = readFileSync(adapterPath, 'utf8')

const fastifyRoutes = [...fastifySource.matchAll(/server\.(get|post|delete|put|patch)\('([^']+)'/g)]
  .map((match) => `${match[1].toUpperCase()} ${match[2]}`)
  .sort()

const adapterRoutes = []
for (const match of adapterSource.matchAll(
  /{ pattern: '([^']+)', methods: \[([^\]]+)\] }/g,
)) {
  const pattern = match[1]
  const methods = [...match[2].matchAll(/'([A-Z]+)'/g)].map((item) => item[1])
  for (const method of methods) adapterRoutes.push(`${method} ${pattern}`)
}
adapterRoutes.sort()

const fastifySet = new Set(fastifyRoutes)
const adapterSet = new Set(adapterRoutes)
const missing = fastifyRoutes.filter((route) => !adapterSet.has(route))
const extra = adapterRoutes.filter((route) => !fastifySet.has(route))
const duplicate =
  adapterRoutes.length - adapterSet.size + (fastifyRoutes.length - fastifySet.size)

const report = {
  fastifyRoutes: fastifyRoutes.length,
  adapterRoutes: adapterRoutes.length,
  missing,
  extra,
  duplicate,
}
process.stdout.write(`mcp-loopback-route-parity ${JSON.stringify(report)}\n`)

if (missing.length > 0 || extra.length > 0 || duplicate !== 0) process.exit(1)
