/**
 * scripts/lib/home-heal-lock.mjs —— 家目录改道自愈的"单实例锁"判定(纯函数,无副作用)。
 *
 * 为什么不直接放在 git-guardian.mjs 里再 import 来测:守护是 CLI 脚本,`import` 它会把
 * 整轮巡检跑起来(§22d 讲的正是这个)。判定必须能在**不触发任何副作用**的前提下取证。
 *
 * 它防的事故(2026-09-24 实测):守护每 2 分钟一趟,而修复器单轮要搬 371MB/1.4 万文件
 * (旧超时 240s 根本搬不完)⇒ 要么被掐死后下一轮从头再搬,要么两轮并发搬同一批目录,
 * 现场就停在"源已改名、链接已建、结论没落"的半完成态上。
 */

export const HOME_HEAL_TTL_MS = 31 * 60 * 1000
export const HOME_HEAL_FIXER_TIMEOUT_MS = 25 * 60 * 1000

/** 进程是否还在。`EPERM` 算活着(存在但无权限探问)。 */
export function pidAlive(pid) {
  if (!pid || !Number.isFinite(pid)) return false
  try {
    process.kill(pid, 0)
    return true
  } catch (e) {
    return Boolean(e && e.code === 'EPERM')
  }
}

/**
 * 锁判定:`'free'`(无锁)/ `'skip'`(另有活轮次,本轮不得并发)/ `'take'`(接管)。
 * 规则取向:**锁绝不能把自愈永久冻住** —— 内容坏、时间戳坏、超 TTL 一律接管;
 * 只有"新鲜 ∧ 持锁进程还活着"才跳过。
 * @param raw 锁文件内容(`pid\n起始毫秒`),null/'' 表示无锁
 * @param alive 注入点(取证用),默认真实探活
 */
export function healLockDecision(raw, now, ttlMs = HOME_HEAL_TTL_MS, alive = pidAlive) {
  if (raw === null || raw === undefined) return 'free'
  const [pidS, startS] = String(raw).split('\n')
  const pid = Number(pidS)
  const started = Number(startS)
  if (!Number.isFinite(pid) || !pid || !Number.isFinite(started) || !started) return 'take'
  if (now - started >= ttlMs) return 'take'
  return alive(pid) ? 'skip' : 'take'
}

/** 锁文件内容(写给自己看即可:pid + 起始毫秒) */
export function healLockText(pid, now) {
  return `${pid}\n${now}\n`
}
