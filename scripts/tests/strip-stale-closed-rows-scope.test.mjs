/**
 * 清扫器留痕段作用域回归锁(2026-10-23 立)。
 *
 * 实测崩点:`headBefore` 声明在落地 `try` 内,而留痕段在 `try/finally` 之后读取它
 * ⇒ 落地成功也 `ReferenceError`,留痕永远写不进 = "摘一次、回一次"的根因。
 * 这里只锁"声明在落地 try 之前且全文件唯一",不复制任何业务判据。
 */
import { test } from 'node:test'
import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const SRC = readFileSync(
  fileURLToPath(new URL('../strip-stale-closed-rows.mjs', import.meta.url)),
  'utf8',
)

test('headBefore 必须在落地 try 之外声明(否则留痕段必 ReferenceError)', () => {
  const needle = "const headBefore = git(['rev-parse', 'HEAD']).trim()"
  assert.equal(SRC.split(needle).length - 1, 1, '只许一处声明')
  const decl = SRC.indexOf(needle)
  assert.ok(decl >= 0, '声明必须存在')
  const spawnAt = SRC.indexOf('object-space-land.mjs', decl)
  assert.ok(spawnAt > decl, '落地 spawn 必须在声明之后')
  const tryAt = SRC.lastIndexOf('try {', spawnAt)
  assert.ok(tryAt >= 0, '必须找到落地 try 块')
  assert.ok(decl < tryAt, 'headBefore 必须声明在该 try 块之前(声明在 try 内 ⇒ 留痕段读不到)')
})
