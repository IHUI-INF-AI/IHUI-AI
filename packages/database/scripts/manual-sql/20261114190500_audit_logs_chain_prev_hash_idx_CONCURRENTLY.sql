-- 幂等:索引已存在则跳过;若存在但 indisvalid=false(上次并发建索引中断),先 DROP 再重建。
DO $$
DECLARE
  invalid_idx boolean;
BEGIN
  SELECT NOT i.indisvalid INTO invalid_idx
  FROM pg_index i
  JOIN pg_class c ON c.oid = i.indexrelid
  WHERE c.relname = 'idx_audit_chain_prev_hash';

  IF invalid_idx THEN
    EXECUTE 'DROP INDEX IF EXISTS idx_audit_chain_prev_hash';
  END IF;
END $$;

CREATE INDEX CONCURRENTLY IF NOT EXISTS idx_audit_chain_prev_hash
  ON audit_logs_chain (prev_hash);

-- 校验:必须返回 indisvalid = true
SELECT c.relname AS index_name, i.indisvalid
FROM pg_index i
JOIN pg_class c ON c.oid = i.indexrelid
WHERE c.relname = 'idx_audit_chain_prev_hash';

