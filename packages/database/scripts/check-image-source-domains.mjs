/**
 * 转发壳(不是判据本体)—— 判据已搬到仓库根 `scripts/check-image-source-domains.mjs`。
 *
 * 为什么留一个壳而不是直接删这个路径:
 *  ① `scripts/check-*` 属守门 30c 的保护区(防"历史 blob 被当新内容交回去"),删它要在枚提交里
 *     与全部在飞改动争一次判定;留转发壳把"删除"换成"内容改写",代价小得多且行为等价。
 *  ② `pnpm --filter @ihui/database check:image-domains` 是已发布过的问责入口,删了它会让
 *     按旧命令派单的人拿到 MODULE_NOT_FOUND —— 那正是本仓记过多次的"文档/命令指向不存在的东西"。
 *  ③ 这个包(platform, rank 20)**不得** import packages/shared(composite, rank 30),
 *     而判据需要同时读 shared 的图源池与各端源码 ⇒ 本体必须住在 tooling 层。
 *     壳里不留任何 import,层序判据(守门 103)对本文件因此恒不适用。
 *
 * 行为:原样转发 argv,退出码透传(0 通过 / 1 判红 / 2 无法判定),不改写输出内容。
 */
import { spawnSync } from 'node:child_process'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const REPO_ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..', '..')
const REAL = join(REPO_ROOT, 'scripts', 'check-image-source-domains.mjs')

const r = spawnSync(process.execPath, [REAL, ...process.argv.slice(2)], {
  cwd: REPO_ROOT,
  stdio: 'inherit',
  windowsHide: true,
  timeout: 300_000,
})

if (r.error) {
  console.error('转发失败(无法判定,不当"通过"):' + String(r.error.message || r.error).slice(0, 200))
  process.exit(2)
}
process.exit(r.status === null ? 2 : r.status)
