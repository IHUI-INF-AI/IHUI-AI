import { pgTable, uuid, varchar, timestamp, index, uniqueIndex, jsonb } from 'drizzle-orm/pg-core'
import { users } from './users.js'

/**
 * 用户浏览历史表(/member/history 页的载体)。
 * - targetType: 'project' | 'file' | 'doc' | 'post'(varchar,避免 pg enum 兼容问题)。
 * - targetId: **varchar 而非 uuid** —— 这几类目标的对外标识形态不统一:article/post
 *   走 uuid,但 doc 走 slug(docs.slug / help_articles.slug,feature-center 即
 *   eq(docs.slug, dbSlug) 这样查)。用 uuid 列会把 doc 那一档挡在门外。
 *   128 覆盖 docs.slug varchar(128) 与 idParamSchema 的 .max(128) 上限。
 * - (user_id, target_id, target_type) 联合唯一:同一用户对同一目标只留一行,
 *   重复上报走 ON CONFLICT 改 visited_at(visit 端点幂等的地基)。
 * - userId ON DELETE CASCADE:浏览历史是从属数据,账号注销不该留孤儿行
 *   (同 resource_likes.user_id 口径)。
 */
export const userBrowseHistory = pgTable(
  'user_browse_history',
  {
    id: uuid('id').defaultRandom().primaryKey(),
    userId: uuid('user_id')
      .references(() => users.id, { onDelete: 'cascade' })
      .notNull(),
    targetId: varchar('target_id', { length: 128 }).notNull(),
    targetType: varchar('target_type', { length: 50 }).notNull(),
    title: varchar('title', { length: 200 }),
    visitedAt: timestamp('visited_at', { withTimezone: true }).defaultNow().notNull(),
    metadata: jsonb('metadata'),
  },
  (t) => ({
    userTargetUnique: uniqueIndex('user_browse_history_unique').on(t.userId, t.targetId, t.targetType),
    userIdIdx: index('user_browse_history_user_id_idx').on(t.userId),
    userVisitedAtIdx: index('user_browse_history_visited_at_idx').on(t.userId, t.visitedAt),
  }),
)

export type UserBrowseHistory = typeof userBrowseHistory.$inferSelect
export type NewUserBrowseHistory = typeof userBrowseHistory.$inferInsert
