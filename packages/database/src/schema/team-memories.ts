/**
 * 团队共享记忆表 (2026-09-08 新增,对标竞品团队知识引擎)
 *
 * 与单用户长程记忆(ai-service 的 session_summaries / key_facts)不同,
 * team_memories 是跨用户共享的项目知识层:
 * - decision   团队达成的技术/产品决策(为何这么做)
 * - convention 团队约定(命名/目录结构/代码规范)
 * - pitfall    踩坑记录(某依赖/某接口的坑与规避)
 * - fingerprint 关键产物指纹(构建哈希/配置快照/索引指纹)
 *
 * 隔离维度是 scopeId(teamId 或 workspaceKey),而非 userId:
 * 同一 scope 内的所有登录成员共享读写这些记忆。
 * sourceUserId 仅记录"是谁写下的",用于溯源,不构成隔离边界。
 */

import { pgTable, uuid, varchar, text, timestamp, index } from 'drizzle-orm/pg-core'

/** 记忆类型枚举 */
export const TEAM_MEMORY_KINDS = ['decision', 'convention', 'pitfall', 'fingerprint'] as const
export type TeamMemoryKind = (typeof TEAM_MEMORY_KINDS)[number]

export const teamMemories = pgTable(
  'team_memories',
  {
    id: uuid('id').defaultRandom().primaryKey(),
    /** 隔离维度:teamId 或 workspaceKey(同一 scope 内成员共享) */
    scopeId: varchar('scope_id', { length: 128 }).notNull(),
    /** 记忆类型:decision | convention | pitfall | fingerprint */
    kind: varchar('kind', { length: 20 }).notNull(),
    title: varchar('title', { length: 300 }).notNull(),
    content: text('content').notNull(),
    /** 逗号分隔的标签(检索过滤用),默认空串 */
    tags: text('tags').notNull().default(''),
    /** 写下这条记忆的用户(溯源用,非隔离边界);可空以兼容系统写入 */
    sourceUserId: uuid('source_user_id'),
    createdAt: timestamp('created_at', { withTimezone: true }).defaultNow().notNull(),
    updatedAt: timestamp('updated_at', { withTimezone: true }).defaultNow().notNull(),
  },
  (t) => ({
    scopeIdx: index('ix_team_memories_scope').on(t.scopeId),
    scopeKindIdx: index('ix_team_memories_scope_kind').on(t.scopeId, t.kind),
  }),
)

export type TeamMemory = typeof teamMemories.$inferSelect
export type TeamMemoryInsert = typeof teamMemories.$inferInsert
