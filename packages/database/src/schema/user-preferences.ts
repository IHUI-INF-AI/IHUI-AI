import { pgTable, uuid, varchar, text, timestamp, unique } from 'drizzle-orm/pg-core'
import { users } from './users.js'

/**
 * 用户偏好设置表 (user_preferences) - 按用户隔离的键值对配置,按 group 分组。
 * 与 edu_settings 区分:本表存储登录用户个人偏好(notifications/privacy/preferences/devices 等)。
 * - group: 配置分组(notifications/privacy/preferences/devices/sidebar)
 * - key: 配置键(同 user + group 内唯一)
 * - value: 字符串值(数字/布尔/json 也以字符串存储,业务层自行解析)
 *
 * group 取值的具名唯一出口在消费侧 `apps/api/src/db/user-preferences-queries.ts` 的
 * `USER_PREFERENCE_GROUPS`(§0.6 单一真相源;本包不 import app 层,故此处仅登记词表)。
 * 通知偏好一律用复数 'notifications' —— compat 单数别名路由曾写单数 'notification' 把同一份
 * 偏好劈成两堆,2026-10-18 已收口,存量由迁移
 * `20261018150000_user_preferences_notification_group_plural` 并入复数。
 */
export const userPreferences = pgTable(
  'user_preferences',
  {
    id: uuid('id').defaultRandom().primaryKey(),
    userId: uuid('user_id')
      .notNull()
      .references(() => users.id, { onDelete: 'cascade' }),
    group: varchar('group', { length: 50 }).notNull(),
    key: varchar('key', { length: 100 }).notNull(),
    value: text('value'),
    updatedAt: timestamp('updated_at', { withTimezone: true }).defaultNow().notNull(),
  },
  (t) => ({
    userGroupKeyIdx: unique('user_preferences_user_group_key_unique').on(t.userId, t.group, t.key),
  }),
)

export type UserPreference = typeof userPreferences.$inferSelect
export type NewUserPreference = typeof userPreferences.$inferInsert
