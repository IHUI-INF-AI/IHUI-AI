import { pgTable, uuid, varchar, timestamp, index } from 'drizzle-orm/pg-core'
import { relayAlertRules } from './relay-alert-rules.js'

/**
 * 告警静默表(relay_alert_silences,2026-09-16 立,五轮对标补强,对标竞品 /alert-silences)。
 *
 * 用途:维护窗口/已知故障期内抑制指定规则(或全部规则)的告警,避免告警风暴与
 * "狼来了"效应。评估引擎(relay-alert-rules-service.evaluateAllAlertRules)在
 * 触发前先查未过期的静默:命中则跳过触发并记录 skippedCooldown。
 *
 * scope:rule(仅该规则) | all(全部规则,ruleId 可空)
 */
export const relayAlertSilences = pgTable(
  'relay_alert_silences',
  {
    id: uuid('id').defaultRandom().primaryKey(),
    /** 静默范围:rule | all */
    scope: varchar('scope', { length: 8 }).default('rule').notNull(),
    /** scope=rule 时指向的规则;scope=all 时为 null */
    ruleId: uuid('rule_id').references(() => relayAlertRules.id, { onDelete: 'cascade' }),
    /** 静默原因(展示在管理端,便于交接) */
    reason: varchar('reason', { length: 255 }),
    /** 静默生效时间(默认现在) */
    startsAt: timestamp('starts_at', { withTimezone: true }).defaultNow().notNull(),
    /** 静默结束时间(到期自动失效) */
    endsAt: timestamp('ends_at', { withTimezone: true }).notNull(),
    createdBy: varchar('created_by', { length: 64 }),
    createdAt: timestamp('created_at', { withTimezone: true }).defaultNow().notNull(),
  },
  (t) => ({
    endsIdx: index('relay_alert_silences_ends_at_idx').on(t.endsAt),
    ruleIdx: index('relay_alert_silences_rule_idx').on(t.ruleId),
  }),
)

export type RelayAlertSilence = typeof relayAlertSilences.$inferSelect
export type NewRelayAlertSilence = typeof relayAlertSilences.$inferInsert
