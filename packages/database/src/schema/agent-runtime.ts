import { pgTable, varchar, jsonb, index, timestamp } from 'drizzle-orm/pg-core'

// agent-runtime 会话消息(与 apps/api SessionManager.SessionMessage 结构对齐)
export interface AgentRuntimeSessionMessage {
  id: string
  role: 'user' | 'assistant' | 'system'
  content: string
  timestamp: number
  /**
   * 会话内单调序号(2026-11-02 B1 起写路径落库)。
   * 可选:旧行里没有这个键 —— 读路径按数组下标惰性回填,不因此改表结构。
   */
  seq?: number
}

// agent-runtime 运行时会话持久化表。
// 背景:agent-runtime 路由此前只用内存 SessionManager,进程重启即丢上下文(P0 实证缺陷)。
// 不能复用 clawdbot_sessions:其 bot_id 是 uuid 外键,而 agent-runtime 的 botId 是任意字符串
// (默认 'default')。本表用 varchar 主键/外键自由列,专供 agent-runtime 域。
export const agentRuntimeSessions = pgTable(
  'agent_runtime_sessions',
  {
    // 'sess_<uuid>' 形式的业务 id,保持 varchar 不受 uuid 列约束
    id: varchar('id', { length: 80 }).primaryKey(),
    botId: varchar('bot_id', { length: 128 }).notNull(),
    userId: varchar('user_id', { length: 128 }).notNull(),
    status: varchar('status', { length: 20 }).default('active').notNull(),
    messages: jsonb('messages').$type<AgentRuntimeSessionMessage[]>().default([]).notNull(),
    metadata: jsonb('metadata').$type<Record<string, unknown>>().default({}).notNull(),
    createdAt: timestamp('created_at', { withTimezone: true }).defaultNow().notNull(),
    updatedAt: timestamp('updated_at', { withTimezone: true }).defaultNow().notNull(),
  },
  (t) => ({
    botIdx: index('agent_runtime_sessions_bot_idx').on(t.botId),
    userIdx: index('agent_runtime_sessions_user_idx').on(t.userId),
    statusIdx: index('agent_runtime_sessions_status_idx').on(t.status),
    // B1(2026-11-02):读路径「按 bot+user+status 取最近会话」的复合索引,
    // 排序键与 findLatestSession 的 ORDER BY updated_at DESC, id DESC 前两列对齐。
    lookupIdx: index('ix_agent_runtime_sessions_lookup').on(
      t.botId,
      t.userId,
      t.status,
      t.updatedAt.desc(),
    ),
  }),
)

export type AgentRuntimeSessionRow = typeof agentRuntimeSessions.$inferSelect
export type NewAgentRuntimeSessionRow = typeof agentRuntimeSessions.$inferInsert
