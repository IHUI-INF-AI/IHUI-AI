import { pgTable, uuid, varchar, text, timestamp, jsonb, index } from 'drizzle-orm/pg-core'
import { agentTasks } from './agent-tasks.js'
import { users } from './users.js'

/**
 * 任务消息表(D25 统一任务运行时看板):
 *   - 支撑 @任务引用跨任务发消息:消息挂在任务上,mentions 记录 @ 引用解析结果
 *   - fromType: user(用户在 dashboard 手输) | agent(dispatch 编排侧注入) | system(状态迁移自动留痕)
 *   - mentions 为自由引用(不设 FK):允许引用未创建/已删除任务,存在性校验在应用层完成
 */
export interface TaskMention {
  type: 'task'
  taskId: string
  name?: string
}

export const taskMessages = pgTable(
  'task_messages',
  {
    id: uuid('id').defaultRandom().primaryKey(),
    taskId: uuid('task_id')
      .references(() => agentTasks.id, { onDelete: 'cascade' })
      .notNull(),
    fromType: varchar('from_type', { length: 16 }).notNull(),
    fromId: varchar('from_id', { length: 128 }),
    content: text('content').notNull(),
    mentions: jsonb('mentions').$type<TaskMention[]>().default([]).notNull(),
    createdBy: uuid('created_by').references(() => users.id, { onDelete: 'set null' }),
    createdAt: timestamp('created_at', { withTimezone: true }).defaultNow().notNull(),
  },
  (t) => ({
    taskIdx: index('task_messages_task_idx').on(t.taskId),
    createdIdx: index('task_messages_created_idx').on(t.createdAt),
    fromIdx: index('task_messages_from_idx').on(t.fromType, t.fromId),
  }),
)

export type TaskMessage = typeof taskMessages.$inferSelect
export type NewTaskMessage = typeof taskMessages.$inferInsert
