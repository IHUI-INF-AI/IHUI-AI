import {
  pgTable,
  uuid,
  varchar,
  text,
  boolean,
  timestamp,
  index,
  unique,
} from 'drizzle-orm/pg-core'
import { users } from './users.js'

/**
 * 设备推送 token 注册表 (device_tokens) — 统一的推送设备令牌登记(2026-09-06 立)。
 *
 * 集中管理各端(FCM / APNS / Web Push)上报的推送令牌,替代 push.ts 中
 * 直接写 edu_notification_device 的散落逻辑。同一条 token 在系统中唯一
 * (token 列唯一约束),同一用户重连时 upsert 更新 lastUsedAt / isActive。
 *
 * - token: 推送令牌(原样存储,FCM 可达数百字符,用 text)
 * - platform: ios / android / web
 * - deviceType: 设备型号/名称(如 "iPhone15,2"),可选
 * - appVersion: 客户端版本号,可选
 * - locale: 客户端语言区域(如 "zh-CN"),可选
 * - isActive: 是否有效(注销/卸载后置 false)
 * - lastUsedAt: 最近一次上报/使用时间
 */
export const deviceTokens = pgTable(
  'device_tokens',
  {
    id: uuid('id').defaultRandom().primaryKey(),
    userId: uuid('user_id')
      .notNull()
      .references(() => users.id, { onDelete: 'cascade' }),
    token: text('token').notNull(),
    platform: varchar('platform', { length: 20 }).notNull(),
    deviceType: varchar('device_type', { length: 100 }),
    appVersion: varchar('app_version', { length: 50 }),
    locale: varchar('locale', { length: 20 }),
    isActive: boolean('is_active').default(true).notNull(),
    lastUsedAt: timestamp('last_used_at', { withTimezone: true }).defaultNow().notNull(),
    createdAt: timestamp('created_at', { withTimezone: true }).defaultNow().notNull(),
    updatedAt: timestamp('updated_at', { withTimezone: true }).defaultNow().notNull(),
  },
  (t) => ({
    userIdx: index('device_tokens_user_id_idx').on(t.userId),
    platformIdx: index('device_tokens_platform_idx').on(t.platform),
    isActiveIdx: index('device_tokens_is_active_idx').on(t.isActive),
    tokenUnique: unique('device_tokens_token_unique').on(t.token),
  }),
)

export type DeviceToken = typeof deviceTokens.$inferSelect
export type NewDeviceToken = typeof deviceTokens.$inferInsert
