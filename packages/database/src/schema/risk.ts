import { pgTable, uuid, text, jsonb, timestamp, index } from 'drizzle-orm/pg-core'
import { users } from './users.js'

/**
 * 风控规则命中记录表 (risk_hits)。
 *
 * P0 资金安全修复(2026-09-06):原风控引擎 RiskRuleEngine.hits 仅存内存 Map,
 * 进程重启即丢失,且无法跨实例/跨进程追溯。改为每次 evaluateRisk 命中后落库,
 * 供规则评判(如同 IP 近期命中次数)、人工复核、审计追溯使用。
 *
 * 字段:
 * - ruleCode: 命中的规则 ID(R001_REMOTE_LOGIN / R002_HIGH_FREQ_REFUND /
 *   R003_ABNORMAL_IP / R004_BATCH_REGISTER / R005_LARGE_WITHDRAWAL)
 * - action: 建议动作(DENY / REVIEW / CHALLENGE / SCORE)
 * - score: 该规则命中累加的分
 * - ip: 命中时的客户端 IP(可空)
 * - context: 命中时的风控上下文快照(jsonb,如 amount/orderNo/deviceFingerprint 等)
 */
export const riskHits = pgTable(
  'risk_hits',
  {
    id: uuid('id').defaultRandom().primaryKey(),
    userId: uuid('user_id').references(() => users.id, { onDelete: 'cascade' }),
    ip: text('ip'),
    ruleCode: text('rule_code').notNull(),
    ruleName: text('rule_name').notNull(),
    action: text('action').notNull(),
    score: text('score').notNull(),
    reason: text('reason').notNull(),
    hitAt: timestamp('hit_at', { withTimezone: true }).defaultNow().notNull(),
    context: jsonb('context').default({}),
  },
  (t) => ({
    userIdx: index('risk_hits_user_idx').on(t.userId),
    ipIdx: index('risk_hits_ip_idx').on(t.ip),
    ruleCodeIdx: index('risk_hits_rule_code_idx').on(t.ruleCode),
    hitAtIdx: index('risk_hits_hit_at_idx').on(t.hitAt),
  }),
)

export type RiskHit = typeof riskHits.$inferSelect
export type NewRiskHit = typeof riskHits.$inferInsert
