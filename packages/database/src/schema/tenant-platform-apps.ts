import {
  pgTable,
  uuid,
  varchar,
  boolean,
  text,
  jsonb,
  timestamp,
  unique,
  index,
} from 'drizzle-orm/pg-core'
import { tenants } from './tenant.js'
import { users } from './users.js'

/**
 * 租户级平台应用凭据（2026-11-23 立）。
 *
 * 单企业私有化部署时，飞书/钉钉/企微/微信应用凭据可以放在进程环境里；
 * 多企业 SaaS 下这套凭据只属于创建它的那家企业，必须按租户隔离：
 * 每个租户一行、每个平台一行，secret 以 enc:v1 密文落库，永不进响应体。
 *
 * 唯一键 (tenant_id, platform)：同一租户同一平台只能有一套应用凭据，
 * 避免同一租户里两个管理员各配一套、运行期随机命中。
 */
export const tenantPlatformApps = pgTable(
  'tenant_platform_apps',
  {
    id: uuid('id').defaultRandom().primaryKey(),
    tenantId: uuid('tenant_id')
      .references(() => tenants.id, { onDelete: 'cascade' })
      .notNull(),
    /** feishu | dingtalk | wecom | wechat | wechat_mp */
    platform: varchar('platform', { length: 32 }).notNull(),
    enabled: boolean('enabled').default(true).notNull(),
    /** 非秘密应用标识：飞书 app_id / 钉钉 app_key / 企微 corp_id / 微信 app_id */
    appId: varchar('app_id', { length: 255 }).default('').notNull(),
    /** 应用密钥：enc:v1 AES-256-GCM 密文；空串表示尚未配置 */
    appSecret: text('app_secret').default('').notNull(),
    /** 平台附加字段：agent_id / redirect_uri / scope 等，不含密钥 */
    extra: jsonb('extra').default({}).notNull(),
    createdBy: uuid('created_by').references(() => users.id, { onDelete: 'set null' }),
    createdAt: timestamp('created_at', { withTimezone: true }).defaultNow().notNull(),
    updatedAt: timestamp('updated_at', { withTimezone: true }).defaultNow().notNull(),
  },
  (t) => ({
    tenantPlatformUnique: unique('tenant_platform_apps_tenant_platform_uidx').on(
      t.tenantId,
      t.platform,
    ),
    tenantIdx: index('tenant_platform_apps_tenant_idx').on(t.tenantId),
  }),
)

export type TenantPlatformApp = typeof tenantPlatformApps.$inferSelect
export type NewTenantPlatformApp = typeof tenantPlatformApps.$inferInsert
