import { pgTable, varchar, integer, uuid, timestamp, index, text } from 'drizzle-orm/pg-core'

/**
 * 外部会话导入批次表(conversation_imports)。
 *
 * D28「外部会话导入」(2026-09-20 立):web 上传 Claude Code / Codex / Cursor / Aider
 * 会话导出文件 → api 转发 ai-service 解析(/parse)→ web 预览后逐会话调 /commit
 * → api 落 chat_conversations + chat_messages(保留原始时间戳)→ 写本表记录批次。
 *
 * 每次 commit 导入一个会话写一条记录,用于:
 * - 用户查询导入历史(/api/user/conversation-import/history)
 * - 审计 + 故障排查(conversation_id 回溯导入生成的会话,无外键,会话删除不影响本记录)
 */
export const conversationImports = pgTable(
  'conversation_imports',
  {
    /** uuid,由应用层生成 */
    id: varchar('id', { length: 64 }).primaryKey(),
    /** 用户 id(关联 users.id) */
    ownerUuid: varchar('owner_uuid', { length: 64 }).notNull(),
    /** 导入来源: claude_code | codex | cursor | aider */
    source: varchar('source', { length: 32 }).notNull(),
    /** 导入生成的 chat_conversations.id(审计回溯,无外键) */
    conversationId: uuid('conversation_id'),
    /** 上传的会话导出文件名 */
    fileName: varchar('file_name', { length: 500 }),
    /** 解析出的消息条数 */
    parsedCount: integer('parsed_count').notNull().default(0),
    importedCount: integer('imported_count').notNull().default(0),
    failedCount: integer('failed_count').notNull().default(0),
    /** success | partial | failed */
    status: varchar('status', { length: 16 }).notNull(),
    errorMessage: text('error_message'),
    importedAt: timestamp('imported_at', { withTimezone: true }).defaultNow().notNull(),
  },
  (t) => ({
    ownerIdx: index('ix_conversation_imports_owner').on(t.ownerUuid),
    importedAtIdx: index('ix_conversation_imports_imported_at').on(t.importedAt),
  }),
)

export type ConversationImport = typeof conversationImports.$inferSelect
export type NewConversationImport = typeof conversationImports.$inferInsert
