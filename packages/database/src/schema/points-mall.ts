import { pgTable, uuid, integer, timestamp, index } from 'drizzle-orm/pg-core'
import { users } from './users.js'
import { pointsMallProducts } from './admin-console.js'

/**
 * 积分商城兑换订单(2026-09-30 立,G-978078)。
 * 商品表 points_mall_products 与 admin CRUD 原已存在,但用户端 GET/POST /points/redeem
 * 此前不存在(RN PointsMallScreen 悬空调用)——本表是兑换动作的持久化载体:
 * 限购判定(count where userId+productId)与对账流水全靠它。
 * 积分扣减流水在 point_transactions(spendPoints 写入,source='mall-redeem'),
 * 本表只记"谁在何时用多少分兑了哪件商品"。
 */
export const pointsMallOrders = pgTable(
  'points_mall_orders',
  {
    id: uuid('id').defaultRandom().primaryKey(),
    userId: uuid('user_id')
      .references(() => users.id, { onDelete: 'cascade' })
      .notNull(),
    productId: uuid('product_id')
      .references(() => pointsMallProducts.id, { onDelete: 'cascade' })
      .notNull(),
    pointsCost: integer('points_cost').notNull(),
    createdAt: timestamp('created_at', { withTimezone: true }).defaultNow().notNull(),
  },
  (t) => [index('points_mall_orders_user_product_idx').on(t.userId, t.productId)],
)
