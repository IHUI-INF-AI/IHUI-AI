import { pgTable, uuid, boolean, jsonb, timestamp, unique } from 'drizzle-orm/pg-core'
import { users } from './users.js'

/**
 * 桌面端偏好跨设备漫游表(desktop_prefs)。
 *
 * 一行一人:唯一键是 user_id,PUT 走 `onConflictDoUpdate` 的幂等 upsert。
 * - enabled:该用户是否**选择**让桌面偏好跟随账号。关掉之后 prefs 一律写 null,
 *   读取侧也据此把载荷判成非权威(见 @ihui/types 的 projectDesktopPrefsPayload)。
 * - prefs:桌面端那份本地偏好的原样搬运,服务端不解释其语义,故不带 `$type` ——
 *   形状的唯一真相源在 `packages/types/src/desktop-prefs.ts`,读回来时过它的校验函数。
 *   在这里再抄一份类型就是第二个真相源(AGENTS §3 共享层优先)。
 */
export const desktopPrefs = pgTable(
  'desktop_prefs',
  {
    id: uuid('id').defaultRandom().primaryKey(),
    userId: uuid('user_id')
      .notNull()
      .references(() => users.id, { onDelete: 'cascade' }),
    enabled: boolean('enabled').default(false).notNull(),
    prefs: jsonb('prefs'),
    createdAt: timestamp('created_at', { withTimezone: true }).defaultNow().notNull(),
    updatedAt: timestamp('updated_at', { withTimezone: true }).defaultNow().notNull(),
  },
  (t) => ({
    userUniq: unique('desktop_prefs_user_id_unique').on(t.userId),
  }),
)

export type DesktopPrefsRow = typeof desktopPrefs.$inferSelect
export type NewDesktopPrefsRow = typeof desktopPrefs.$inferInsert
