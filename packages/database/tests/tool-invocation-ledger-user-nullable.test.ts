/**
 * F-433 夹具：`user_id` NOT NULL 与 `ON DELETE SET NULL` 互斥。
 * 删用户时外键动作要写 NULL，列上的 NOT NULL 会让整个删除事务失败；
 * 迁移必须真的把该列放宽为可空，且 journal 有登记（否则线上不生效）。
 */
import { existsSync, readFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { join } from 'node:path'
import { describe, it, expect } from 'vitest'

const pkgDir = fileURLToPath(new URL('..', import.meta.url))
const SCHEMA = join(pkgDir, 'src', 'schema', 'tool-invocation-ledger.ts')
const MIGRATION = join(pkgDir, 'drizzle', '20261108180000_tool_invocation_ledger_user_nullable.sql')
const JOURNAL = join(pkgDir, 'drizzle', 'meta', '_journal.json')

describe('F-433 tool_invocation_ledger.user_id 可空', () => {
  it('schema 的 user_id 引用 users 且 ON DELETE SET NULL，不再 notNull', () => {
    const src = readFileSync(SCHEMA, 'utf-8')
    const start = src.indexOf("userId: uuid('user_id')")
    expect(start).toBeGreaterThan(-1)
    const block = src.slice(start, start + 220)
    expect(block).toContain("onDelete: 'set null'")
    expect(block).not.toContain('.notNull()')
  })

  it('迁移 SQL 已落地：DROP NOT NULL', () => {
    expect(existsSync(MIGRATION)).toBe(true)
    const sql = readFileSync(MIGRATION, 'utf-8')
    expect(sql).toContain(
      'ALTER TABLE "tool_invocation_ledger" ALTER COLUMN "user_id" DROP NOT NULL',
    )
  })

  it('journal 已登记该迁移（idx 与 entries 实际位置一致）', () => {
    const journal = JSON.parse(readFileSync(JOURNAL, 'utf-8'))
    const pos = journal.entries.findIndex(
      (e: { tag: string }) => e.tag === '20261108180000_tool_invocation_ledger_user_nullable',
    )
    expect(pos).toBeGreaterThan(-1)
    expect(journal.entries[pos].idx).toBe(pos)
  })
})
