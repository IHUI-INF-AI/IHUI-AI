/**
 * DB-42 夹具。
 *
 * 缺陷：dbReader/readerClient 在工厂创建时固定为「第一个副本」，副本失效后
 * 默认读仍指向坏节点，只有显式 getReader() 才转移。
 * 判据：dbReader/readerClient 跟随健康状态动态返回最优副本，全坏回主库。
 */
import { describe, expect, it, vi } from 'vitest'

const { postgresMock } = vi.hoisted(() => ({ postgresMock: vi.fn() }))

vi.mock('postgres', () => ({
  default: (url: string) => postgresMock(url),
}))
vi.mock('drizzle-orm/postgres-js', () => ({
  drizzle: (client: { url: string }) => ({ __url: client.url }),
}))

describe('DB-42 默认 reader 故障转移', () => {
  it('第一个副本不健康后，dbReader/readerClient 切到次优健康副本', async () => {
    postgresMock.mockImplementation((url: string) => ({ url, end: vi.fn(async () => {}) }))
    const mod = await import('../src/read-replica.js')
    const rw = mod.createReadWriteDb({
      url: 'postgres://writer',
      replicas: [
        { id: 'r1', url: 'postgres://r1', priority: 100 },
        { id: 'r2', url: 'postgres://r2', priority: 90 },
      ],
    })

    // DB-28:首轮探测前 healthy=false ⇒ 回退主库；先上报一轮健康再断言。
    rw.reportReplicaHealth('r1', true, 0)
    rw.reportReplicaHealth('r2', true, 0)
    expect(rw.dbReader).toMatchObject({ __url: 'postgres://r1' })
    expect(rw.readerClient).toMatchObject({ url: 'postgres://r1' })

    for (let i = 0; i < 3; i++) rw.reportReplicaHealth('r1', false)

    expect(rw.dbReader).toMatchObject({ __url: 'postgres://r2' })
    expect(rw.readerClient).toMatchObject({ url: 'postgres://r2' })

    for (let i = 0; i < 3; i++) rw.reportReplicaHealth('r2', false)
    expect(rw.dbReader).toMatchObject({ __url: 'postgres://writer' })
    expect(rw.readerClient).toMatchObject({ url: 'postgres://writer' })
  })
})
