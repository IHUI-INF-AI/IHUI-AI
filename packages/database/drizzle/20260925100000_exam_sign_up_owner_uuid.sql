-- 20260925100000: exam_sign_up 归属列(user_id uuid,可空) —— 报名域 C 方案
-- 背景: 前序票(2026-09-25)实测证明 member_id(integer,旧 Java ID 空间)与 users.id(uuid)
--   之间不存在服务端可推导的映射,报名域 7 处闸门只能 fail-close 到管理员档。
--   owner 定 C 方案: 加一列指向 users.id 的 uuid 归属列,闸门改为按归属放行。
-- 设计前提(不得违反):
--   1) 列可空 —— 历史行没有可信映射可回填(按手机号/姓名回填 = 制造假归属,禁止回填)。
--   2) 新报名由服务端按 request.userId 写入;历史 NULL 行继续只走管理员显式 memberId 路径。
--   3) 授权判据只认 eq(user_id, request.userId),禁止 `IS NULL OR =` 一并放行。
-- FK ON DELETE SET NULL: 用户注销不连坐删除报名记录(历史数据保全)。
-- 索引非 CONCURRENTLY: 单事务迁移内 CONCURRENTLY 会失败(本仓记过 drizzle 整批回滚事故)。

ALTER TABLE "exam_sign_up" ADD COLUMN IF NOT EXISTS "user_id" uuid
  REFERENCES "users"("id") ON DELETE SET NULL;
CREATE INDEX IF NOT EXISTS "idx_esu_user" ON "exam_sign_up" ("user_id");
