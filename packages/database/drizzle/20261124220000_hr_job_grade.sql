-- 职级体系(2026-11-24 六波):职级字典 + 员工职级生效史(调岗/晋升时间线)

CREATE TABLE IF NOT EXISTS "hr_job_grade" (
  "id" uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  "code" varchar(40) NOT NULL,
  "name" varchar(100) NOT NULL,
  "level" integer NOT NULL,
  "note" text,
  "status" varchar(20) NOT NULL DEFAULT 'active',
  "created_at" timestamptz NOT NULL DEFAULT now(),
  "updated_at" timestamptz NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS "uq_hr_job_grade_code" ON "hr_job_grade" ("code");
CREATE INDEX IF NOT EXISTS "ix_hr_job_grade_level" ON "hr_job_grade" ("level");

CREATE TABLE IF NOT EXISTS "hr_employee_grade" (
  "id" uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  "employee_id" uuid NOT NULL REFERENCES "hr_employee"("id") ON DELETE RESTRICT,
  "grade_id" uuid NOT NULL REFERENCES "hr_job_grade"("id") ON DELETE RESTRICT,
  "grade_code" varchar(40) NOT NULL,
  "effective_from" date NOT NULL,
  "reason" varchar(20) NOT NULL,
  "note" text,
  "operator_id" uuid REFERENCES "users"("id") ON DELETE SET NULL,
  "created_at" timestamptz NOT NULL DEFAULT now(),
  "ended_at" timestamptz
);

CREATE UNIQUE INDEX IF NOT EXISTS "uq_hr_employee_grade_open"
  ON "hr_employee_grade" ("employee_id")
  WHERE "ended_at" IS NULL;
CREATE INDEX IF NOT EXISTS "ix_hr_employee_grade_emp" ON "hr_employee_grade" ("employee_id", "effective_from");
