-- 幂等:CREATE TABLE/INDEX IF NOT EXISTS,重复执行安全,生产回放不改变已有归档关系。

CREATE TABLE IF NOT EXISTS "wechat_hub_moments" (
  "id" uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  "account_id" uuid NOT NULL REFERENCES "wechat_hub_accounts"("id") ON DELETE CASCADE,
  "moment_key" varchar(255) NOT NULL,
  "author_id" varchar(255),
  "author_name" varchar(255) NOT NULL DEFAULT '',
  "author_resolved" boolean NOT NULL DEFAULT false,
  "content" text NOT NULL DEFAULT '',
  "media_urls" jsonb NOT NULL DEFAULT '[]'::jsonb,
  "created_at" integer,
  "source" varchar(32) NOT NULL DEFAULT 'bridge',
  "page" integer,
  "first_seen_at" timestamptz NOT NULL DEFAULT now(),
  "last_seen_at" timestamptz NOT NULL DEFAULT now(),
  "seen_count" integer NOT NULL DEFAULT 1,
  "metadata" jsonb NOT NULL DEFAULT '{}'::jsonb
);

CREATE UNIQUE INDEX IF NOT EXISTS "wechat_hub_moments_account_key_uniq"
  ON "wechat_hub_moments" ("account_id", "moment_key");
CREATE INDEX IF NOT EXISTS "wechat_hub_moments_account_last_idx"
  ON "wechat_hub_moments" ("account_id", "last_seen_at");
