--
-- 348(20261027090000_default_user_avatar)的前置解药。
--
-- 348 的存量回填 `UPDATE users SET avatar=... WHERE avatar IS NULL OR btrim(avatar)=''`
-- 未排除系统管理员行,而 0071 起该行受 users_system_admin_immutable_update 保护
-- (任何字段变更都被拒),按链从零建库在 348 必炸。已入 journal 的迁移正文不可变,
-- 故本迁移在 journal 数组序上插到 348 之前(idx 351,when 落在 347 与 348 之间):
-- 先走 349/0071 已在仓内用过的受控通道(同一 DO 块内临时禁用不可变触发器 → 回填 →
-- 立即恢复,不留禁用态),把管理员行 avatar 置为非空非空白,348 的 WHERE 从此
-- 不再命中该行,348 本体一行不用改。
--
-- 全语句幂等:管理员行 avatar 已非空非空白时 0 行直接返回;触发器禁用/启用在同一
-- DO 块内成对出现。本迁移写入的 aizhs.top 地址与 348 的默认值一致,后续 349 会把
-- 存量与管理员行一并收敛到 www.aizhs.top。
--

DO $$
DECLARE
  v_ids uuid[];
  v_id uuid;
BEGIN
  SELECT array_agg(id)
    INTO v_ids
    FROM users
   WHERE is_system_admin = true
     AND (avatar IS NULL OR btrim(avatar) = '');

  IF v_ids IS NULL OR array_length(v_ids, 1) IS NULL THEN
    RETURN;
  END IF;

  ALTER TABLE users DISABLE TRIGGER users_system_admin_immutable_update;
  FOREACH v_id IN ARRAY v_ids LOOP
    UPDATE users
       SET avatar = 'https://aizhs.top/images/default-avatar.jpg'
     WHERE id = v_id;
  END LOOP;
  ALTER TABLE users ENABLE TRIGGER users_system_admin_immutable_update;
END $$;
