-- DB-35 收敛(2026-11-20):users.phone/email 列宽对齐 TS schema 的 text。
--
-- 背景:盲索引迁移(20261116174441_users_contact_blind_index)把 phone/email 改存
--   `enc:v1:iv:tag:ct` 紧凑密文(AES-256-GCM),但迁移链从未放宽两列:phone 仍
--   varchar(20)、email 仍 varchar(255);TS schema(packages/database/src/schema/users.ts)
--   早已声明 text。密文长度超出 phone(20) ⇒ 22001 value too long,全新库上
--   createUser/updateUser/管理端建号写库即失败(real-db CI auth-queries / admin-missing-routes)。
--
-- 本迁移只把两列 ALTER 到 text,与 schema 对齐;不动 lookup 列、唯一索引与任何查询语义。
-- 幂等:ALTER COLUMN TYPE 重复执行无副作用;varchar 扩宽不重写表,瞬间完成。
-- 回滚:不能直接改回窄 varchar(已有密文行会因超长按 22001 失败);须先解密回写、
--   复核最大长度后再收窄。
ALTER TABLE "users"
  ALTER COLUMN "phone" TYPE text,
  ALTER COLUMN "email" TYPE text;
