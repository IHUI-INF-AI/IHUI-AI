-- 创建时间: 2026-11-16
-- 描述: 用户之间数据默认隔离。HR 只发起「关联邀请」,被邀请账号本人在自助页同意后,
--       才由服务层写入 hr_employee.user_id。手机号/邮箱仅用于找人,不做自动认领。
-- 幂等安全:IF NOT EXISTS,可安全重复执行。
-- 与 packages/database/src/schema/hr-ai-management.ts 逐字对齐。

CREATE TABLE IF NOT EXISTS "hr_employee_link_request" (
  "id" uuid PRIMARY KEY DEFAULT gen_random_uuid() NOT NULL,
  "employee_id" uuid NOT NULL,
  "user_id" uuid NOT NULL,
  "status" varchar(20) DEFAULT 'pending' NOT NULL,
  "invited_by" uuid,
  "decided_at" timestamptz,
  "created_at" timestamptz DEFAULT now() NOT NULL,
  "updated_at" timestamptz DEFAULT now() NOT NULL,
  CONSTRAINT "hr_employee_link_request_employee_id_fkey" FOREIGN KEY ("employee_id") REFERENCES "hr_employee" ("id") ON DELETE CASCADE,
  CONSTRAINT "hr_employee_link_request_user_id_fkey" FOREIGN KEY ("user_id") REFERENCES "users" ("id") ON DELETE CASCADE,
  CONSTRAINT "hr_employee_link_request_invited_by_fkey" FOREIGN KEY ("invited_by") REFERENCES "users" ("id") ON DELETE SET NULL
);
CREATE INDEX IF NOT EXISTS "ix_hr_link_req_user" ON "hr_employee_link_request" ("user_id", "status");
CREATE INDEX IF NOT EXISTS "ix_hr_link_req_emp" ON "hr_employee_link_request" ("employee_id", "status");
-- 同一员工同一时刻只允许一条待确认邀请
CREATE UNIQUE INDEX IF NOT EXISTS "uq_hr_link_req_pending_emp" ON "hr_employee_link_request" ("employee_id") WHERE status = 'pending';
