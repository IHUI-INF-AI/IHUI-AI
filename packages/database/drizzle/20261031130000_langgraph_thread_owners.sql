-- LangGraph 线程归属持久表(2026-10-31 安全强化第 26 批)。
--
-- 背景:线程图状态(values 含整段对话与工具结果)住在 LangGraph saver 自己的表里,
-- 而归属此前只存在进程内存(canvas_graph 的 owner 账)—— 进程重启即失忆,重启后
-- 任何人拿到 threadId 都能经 /api/langgraph/{id}/state 读走 graphState。
--
-- 本表是归属的持久真相源:执行类入口(canvas/run、stream、interrupt、resume)首次
-- 接触时登记,读取类入口(state、history)只比对、不登记。user_id 取 uuid 而不是
-- varchar:系统身份(system-worker)与开发占位(dev-anonymous)不是 uuid,写入即被
-- 数据库拒绝 —— 这是应用层判据之外的第二道防线。
CREATE TABLE IF NOT EXISTS "langgraph_thread_owners" (
	"thread_id" varchar(100) PRIMARY KEY NOT NULL,
	"user_id" uuid NOT NULL,
	"created_at" timestamp with time zone DEFAULT now() NOT NULL
);
