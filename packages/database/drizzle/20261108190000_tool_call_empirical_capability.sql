-- 立因:supports_tool_call 来自上游元数据(厂商"声称"),实测端点可能完全不返回原生
-- tool_calls 而把调用写成正文,导致配额故障转移静默退化成"零工具执行却 completed"。
-- 本迁移新增两个只由实证探针/线上判据写入的列,以及一条审计表。
ALTER TABLE "ai_model_config_models"
  ADD COLUMN IF NOT EXISTS "tool_call_empirical" boolean,
  ADD COLUMN IF NOT EXISTS "tool_call_verified_at" timestamp with time zone;

CREATE TABLE IF NOT EXISTS "ai_model_tool_call_verifications" (
  "id" bigserial PRIMARY KEY NOT NULL,
  "model_id" varchar(128) NOT NULL,
  "provider_code" varchar(64) NOT NULL,
  "verdict" varchar(24) NOT NULL,
  "criterion_version" varchar(64) NOT NULL,
  "trace_kind" varchar(64),
  "source" varchar(16) NOT NULL,
  "observed_at" timestamp with time zone DEFAULT now() NOT NULL
);

CREATE INDEX IF NOT EXISTS "ai_model_tool_call_verifications_model_observed_idx"
  ON "ai_model_tool_call_verifications" ("model_id", "observed_at");
