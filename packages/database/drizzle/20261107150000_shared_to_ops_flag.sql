-- 2026-11-07 立(李总指令):账号池"共享到运营池"全局开放标记。
-- 模型:首次导入强制落个人池(owner = 本人);运营池仅由用户主动"共享"动作填充。
-- shared_to_ops=true 表示:该号在保留个人池归属(本人可用)的同时,对所有用户/匿名开放(转发选路纳入);
-- false 表示仅个人池可见可用,绝不服务他人请求。
-- 注:调度器(scheduler)不按 owner 过滤(所有号全局刷新保活),本标记仅影响转发选路层。

ALTER TABLE "ai_relay_account_pool"
  ADD COLUMN "shared_to_ops" boolean NOT NULL DEFAULT false;

-- 转发选路常用过滤:(provider_code, shared_to_ops) — 部分索引仅覆盖已共享账号,加速"跨 owner 取共享号"。
CREATE INDEX IF NOT EXISTS "ai_relay_account_pool_shared_to_ops_idx"
  ON "ai_relay_account_pool" ("provider_code")
  WHERE "shared_to_ops" = true;
