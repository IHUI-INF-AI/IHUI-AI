-- F-397:zhs_exchange_rate.rate 用 real(float4) 只有约 6 位十进制有效数字,
-- 折算金额会随汇率精度漂移;改 numeric(20,8) 保住 8 位小数。
-- 同时把 (from_currency, to_currency) 收敛成唯一索引(0111 已建同名索引,
-- 这里 IF NOT EXISTS 兜底,保证 schema 声明与库终态一致),否则 findRate 的
-- LIMIT 1 仍会在重复行之间漂移。
-- 去重保留规则:updated_at 最新 → id 最大(与 findRate 的取行口径一致)。
-- 幂等:去重 + IF NOT EXISTS 可重复执行。回滚:
--   ALTER TABLE "zhs_exchange_rate" ALTER COLUMN "rate" TYPE real USING "rate"::real;
--   DROP INDEX IF EXISTS "zhs_exchange_rate_pair_uq";
ALTER TABLE "zhs_exchange_rate"
  ALTER COLUMN "rate" TYPE numeric(20,8) USING "rate"::numeric(20,8);
-- statement-breakpoint
WITH ranked AS (
  SELECT id,
         row_number() OVER (
           PARTITION BY "from_currency", "to_currency"
           ORDER BY "updated_at" DESC, "id" DESC
         ) AS rn
  FROM "zhs_exchange_rate"
)
DELETE FROM "zhs_exchange_rate" t
USING ranked r
WHERE t.id = r.id
  AND r.rn > 1;
-- statement-breakpoint
CREATE UNIQUE INDEX IF NOT EXISTS "zhs_exchange_rate_pair_uq"
  ON "zhs_exchange_rate" USING btree ("from_currency", "to_currency");
