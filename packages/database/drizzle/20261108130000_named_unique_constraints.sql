--
-- DB-37 (P3): 两处内联 UNIQUE(...) 由 PostgreSQL 自动命名，与 Drizzle/TS 约定名不一致。
-- 先删自动名约束（ai_relay_channel_daily_usage_key_pool_id_usage_date_key /
-- api_key_minute_usage_api_key_id_usage_minute_key），再按约定名 ADD CONSTRAINT，
-- 使后续迁移可稳定按名 DROP/校验。DO 块内 IF NOT EXISTS 保证重复执行幂等。
--
-- 锁表说明：DROP/ADD UNIQUE 约束都会重建索引并取 SHARE ROW EXCLUSIVE 级锁，
-- 会阻塞该表写入；两张按日/按分钟用量表通常不大，若已很大请在维护窗口执行。

ALTER TABLE "ai_relay_channel_daily_usage"
  DROP CONSTRAINT IF EXISTS "ai_relay_channel_daily_usage_key_pool_id_usage_date_key";

DO $db37_channel_daily$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conname = 'ai_relay_channel_daily_usage_key_pool_id_usage_date_unique'
      AND conrelid = 'ai_relay_channel_daily_usage'::regclass
  ) THEN
    ALTER TABLE "ai_relay_channel_daily_usage"
      ADD CONSTRAINT "ai_relay_channel_daily_usage_key_pool_id_usage_date_unique"
      UNIQUE ("key_pool_id", "usage_date");
  END IF;
END $db37_channel_daily$;

ALTER TABLE "api_key_minute_usage"
  DROP CONSTRAINT IF EXISTS "api_key_minute_usage_api_key_id_usage_minute_key";

DO $db37_minute_usage$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conname = 'api_key_minute_usage_api_key_id_usage_minute_unique'
      AND conrelid = 'api_key_minute_usage'::regclass
  ) THEN
    ALTER TABLE "api_key_minute_usage"
      ADD CONSTRAINT "api_key_minute_usage_api_key_id_usage_minute_unique"
      UNIQUE ("api_key_id", "usage_minute");
  END IF;
END $db37_minute_usage$;
