-- G-790 A7(2026-10-18):llm_call_logs 补 refunded 判别列,并把既有 JSON 键的当前取值回填进列。
--
-- 动机(票面点名的一型):退款资格查询筛的是
--   COALESCE(metadata->>'refunded','false') <> 'true'
-- 而"只有 markTaskRefunded 会写这个顶层键"是**今天的巧合,不是约束** —— 明天任何别的写入者
-- (内部任务 / 新端点 / 补账脚本)给 metadata 打上同名键,就会把已退款行再退一次,
-- 条数与分页读数都"看起来正常"。判别事实必须进列、进谓词;同表 raw_retained 已是这一档。
ALTER TABLE "llm_call_logs" ADD COLUMN IF NOT EXISTS "refunded" boolean NOT NULL DEFAULT false;

-- 回填判定与旧谓词逐字同形(只认真值 'true',其余形态一律按未退款)——
-- 迁移不得顺手改语义:凡是旧读面判"未退款"的行,迁移后必须仍然判"未退款"。
UPDATE "llm_call_logs"
   SET "refunded" = true
 WHERE "refunded" = false
   AND "metadata" ->> 'refunded' = 'true';
