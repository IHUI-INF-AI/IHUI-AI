CREATE TABLE IF NOT EXISTS "ai_relay_model_catalog" (
  "id" uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  "provider_code" varchar(64) NOT NULL,
  "upstream_model" varchar(128) NOT NULL,
  "display_name" varchar(256),
  "alias" varchar(128) NOT NULL,
  "enabled" boolean DEFAULT true NOT NULL,
  "created_at" timestamp with time zone DEFAULT now() NOT NULL,
  "updated_at" timestamp with time zone DEFAULT now() NOT NULL,
  CONSTRAINT "ai_relay_model_catalog_provider_alias_unique" UNIQUE ("provider_code", "alias")
);

CREATE INDEX IF NOT EXISTS "ai_relay_model_catalog_provider_idx" ON "ai_relay_model_catalog" ("provider_code");
