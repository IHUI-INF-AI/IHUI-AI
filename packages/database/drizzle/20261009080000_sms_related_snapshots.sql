-- sms_related_snapshots —— 平台「号码相关短信」快照累积(管理员短信接码 /admin/sms-receive)
--
-- 背景:平台 relatedMsgs 只返回该号最近 12 条滚动窗口(2026-10-09 探针实证:
-- 伪造翻页参数响应逐字不变,服务端硬截断),热门号窗口不足 1 小时即被冲掉。
-- 本表在每次查询时把窗口快照逐条抄进本地,按 (phone, rec_date, rec_time, flag)
-- 幂等去重,本地视野随时间单调增长 —— 唯一能超越平台 12 条上限的全局热度口径。
--
-- 口径说明(逐条都是刻意选择):
--   ① 平台只给 HH:MM 无日期 ⇒ rec_date 由快照时刻归位:记录时刻 > 当前时刻 = 昨日
--     (与 helpers.countRecentRecords 同一归位规则),跨日滚动窗口合并为连续历史。
--   ② 同一分钟同 flag 的两条事件在本响应内不可区分 ⇒ 去重合并,轻微低估可接受。
--   ③ flag(Y/N)语义平台未公开,原样存储不解读。
--   ④ 不关联 user_id:管理员页单管理员场景,与 sms_receive_history 同理。
--   ⑤ 全表幂等:CREATE TABLE IF NOT EXISTS + CREATE INDEX IF NOT EXISTS。
-- ============================================================================

--> statement-breakpoint
CREATE TABLE IF NOT EXISTS "sms_related_snapshots" (
	"id" uuid PRIMARY KEY DEFAULT gen_random_uuid() NOT NULL,
	"phone" varchar(20) NOT NULL,
	"rec_date" date NOT NULL,
	"rec_time" varchar(8) NOT NULL,
	"flag" varchar(1) NOT NULL,
	"first_seen_at" timestamp with time zone DEFAULT now() NOT NULL,
	CONSTRAINT "sms_related_snapshots_phone_rec_unique" UNIQUE ("phone","rec_date","rec_time","flag")
);

--> statement-breakpoint
CREATE INDEX IF NOT EXISTS "sms_related_snapshots_phone_idx" ON "sms_related_snapshots" USING btree ("phone");
