-- 技能市场退款申请：买家提交、运营审核，审核通过后再走既有退款事务。
-- 申请只记流程，不动钱；同一购买同时只允许一条 pending（部分唯一索引）。
CREATE TABLE IF NOT EXISTS "skill_market_refund_requests" (
  "id" uuid PRIMARY KEY DEFAULT gen_random_uuid() NOT NULL,
  "purchase_id" uuid NOT NULL,
  "buyer_user_id" uuid NOT NULL,
  "seller_user_id" uuid,
  "reason" varchar(500) NOT NULL,
  "status" varchar(16) DEFAULT 'pending' NOT NULL,
  "reviewed_by" uuid,
  "review_note" varchar(500),
  "reviewed_at" timestamp with time zone,
  "created_at" timestamp with time zone DEFAULT now() NOT NULL,
  "updated_at" timestamp with time zone DEFAULT now() NOT NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS "skill_market_refund_requests_pending_uniq"
  ON "skill_market_refund_requests" ("purchase_id")
  WHERE "status" = 'pending';

CREATE INDEX IF NOT EXISTS "skill_market_refund_requests_buyer_status_idx"
  ON "skill_market_refund_requests" ("buyer_user_id", "status");

CREATE INDEX IF NOT EXISTS "skill_market_refund_requests_status_created_idx"
  ON "skill_market_refund_requests" ("status", "created_at");

CREATE INDEX IF NOT EXISTS "skill_market_refund_requests_purchase_idx"
  ON "skill_market_refund_requests" ("purchase_id");
