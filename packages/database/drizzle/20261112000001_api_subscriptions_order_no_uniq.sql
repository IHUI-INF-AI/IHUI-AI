-- SDB-02:api_subscriptions.order_no 是订阅创建的幂等键(支付回调重放守卫,
-- 见 apps/api/src/services/subscription-window-service.ts createSubscriptionForOrder),
-- 应用层已有「查到即返回」守卫,但库侧只有普通索引,无唯一约束 —— 并发回调
-- 双查双插仍会落重复订阅行。本迁移补 UNIQUE 作为最后一道闸,新增迁移不改历史迁移。
--
-- 历史脏数据:此前无唯一约束,重放可能已落重复行。建唯一索引前先去重,
-- 保留 end_at 最大的一行(权益不缩短),end_at 相同时保留物理顺序最后一行。
-- order_no 可空:PG 唯一索引允许多个 NULL,不约束手工/无单号订阅。
--
-- 上线运维动作:
-- 1) 去重是不可逆删除,执行前先备份:
--    CREATE TABLE api_subscriptions_bak_20261112 AS SELECT * FROM api_subscriptions;
-- 2) CREATE UNIQUE INDEX 非 CONCURRENTLY,会短暂持表锁,建议低峰执行。
-- 3) 回滚:DROP INDEX IF EXISTS "api_subscriptions_order_no_uniq";
--    再按 20260916170000 原样重建普通索引 api_subscriptions_order_no_idx。
DELETE FROM "api_subscriptions" a
USING "api_subscriptions" b
WHERE a."order_no" IS NOT NULL
  AND a."order_no" = b."order_no"
  AND (a."end_at" < b."end_at"
       OR (a."end_at" = b."end_at" AND a."ctid" > b."ctid"));

DROP INDEX IF EXISTS "api_subscriptions_order_no_idx";

CREATE UNIQUE INDEX IF NOT EXISTS "api_subscriptions_order_no_uniq"
  ON "api_subscriptions" USING btree ("order_no");

