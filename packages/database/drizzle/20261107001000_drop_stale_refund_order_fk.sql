-- 补偿迁移(2026-11-07):清除 0212 遗留的旧退款/发票 order_id 外键(→ edu_orders)。
-- 背景:0212 只按显式名 DROP CONSTRAINT("..._order_id_edu_orders_id_fk"),而真实存量库里
-- 该约束是数据库自动命名("..._order_id_fkey"),于是旧 FK 从未被删除:
--   · edu_refunds.order_id 同时受 edu_orders(id) 与 orders(id) 两套 FK 约束,写入 orders 系退款单
--     会被旧 FK 拦截;
--   · edu_invoice_applications.order_id 同理(旧 FK 为 ON DELETE SET NULL)。
-- 本迁移仅在新 FK("..._order_id_orders_id_fk")确实存在时删除旧的自动命名 FK,空库/已清理库均为 no-op。

DO $$
BEGIN
  IF to_regclass('public.edu_refunds') IS NOT NULL
     AND EXISTS (
       SELECT 1 FROM pg_constraint
       WHERE conname = 'edu_refunds_order_id_orders_id_fk' AND conrelid = 'public.edu_refunds'::regclass
     )
     AND EXISTS (
       SELECT 1 FROM pg_constraint
       WHERE conname = 'edu_refunds_order_id_fkey' AND conrelid = 'public.edu_refunds'::regclass
     )
  THEN
    ALTER TABLE "public"."edu_refunds" DROP CONSTRAINT "edu_refunds_order_id_fkey";
  END IF;
END $$;--> statement-breakpoint

DO $$
BEGIN
  IF to_regclass('public.edu_invoice_applications') IS NOT NULL
     AND EXISTS (
       SELECT 1 FROM pg_constraint
       WHERE conname = 'edu_invoice_applications_order_id_orders_id_fk' AND conrelid = 'public.edu_invoice_applications'::regclass
     )
     AND EXISTS (
       SELECT 1 FROM pg_constraint
       WHERE conname = 'edu_invoice_applications_order_id_fkey' AND conrelid = 'public.edu_invoice_applications'::regclass
     )
  THEN
    ALTER TABLE "public"."edu_invoice_applications" DROP CONSTRAINT "edu_invoice_applications_order_id_fkey";
  END IF;
END $$;
