-- 固定资产卡片台账(2026-11-24 补口):月折旧按直线法现算并以凭证入账,本表只存卡片事实

CREATE TABLE IF NOT EXISTS "fin_fixed_asset" (
  "id" uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  "ledger_id" uuid NOT NULL REFERENCES "fin_ledger"("id") ON DELETE CASCADE,
  "code" varchar(40) NOT NULL,
  "name" varchar(200) NOT NULL,
  "category" varchar(40) NOT NULL DEFAULT 'other',
  "original_cost" numeric(16,2) NOT NULL,
  "start_period" varchar(7) NOT NULL,
  "useful_months" integer NOT NULL,
  "salvage_rate" numeric(6,4) NOT NULL DEFAULT '0.0500',
  "expense_account_code" varchar(16) NOT NULL DEFAULT '5502',
  "depreciation_account_code" varchar(16) NOT NULL DEFAULT '1602',
  "status" varchar(20) NOT NULL DEFAULT 'active',
  "disposal_period" varchar(7),
  "note" text,
  "created_at" timestamptz NOT NULL DEFAULT now(),
  "updated_at" timestamptz NOT NULL DEFAULT now(),
  "deleted_at" timestamptz
);

CREATE UNIQUE INDEX IF NOT EXISTS "uq_fin_fixed_asset_ledger_code"
  ON "fin_fixed_asset" ("ledger_id", "code")
  WHERE "deleted_at" IS NULL;
CREATE INDEX IF NOT EXISTS "ix_fin_fixed_asset_ledger"
  ON "fin_fixed_asset" ("ledger_id", "status");
