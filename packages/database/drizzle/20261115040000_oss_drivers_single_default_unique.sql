-- F-640:oss_drivers.is_default 只有"业务层保证全局唯一",没有库级约束。
-- 并发/手工改库可落下多条 is_default=true,"默认驱动"读取就取决于扫描顺序。
-- 本迁移先收敛存量(保留 sort 最小 → created_at 最早 → id 最小的一条为默认),
-- 再建部分唯一索引(仅约束 is_default=true 的行,false 行不受限)。
-- 幂等:去重 + IF NOT EXISTS 可重复执行。回滚:
--   DROP INDEX IF EXISTS "oss_drivers_single_default_uq";
WITH ranked AS (
  SELECT id,
         row_number() OVER (
           ORDER BY "sort" ASC, "created_at" ASC, "id" ASC
         ) AS rn
  FROM "oss_drivers"
  WHERE "is_default" = true
)
UPDATE "oss_drivers" d
SET "is_default" = false,
    "updated_at" = now()
FROM ranked r
WHERE d.id = r.id
  AND r.rn > 1;
-- statement-breakpoint
CREATE UNIQUE INDEX IF NOT EXISTS "oss_drivers_single_default_uq"
  ON "oss_drivers" USING btree ("is_default")
  WHERE "is_default" = true;
