-- 中转站告警规则引擎(2026-09-16 立,深度对标补强 U,对标竞品 /alert-rules + /alert-events)。
--
-- 两表:relay_alert_rules(规则:指标+比较符+阈值+冷却)与 relay_alert_events(触发事件流)。
-- 评估由 jobs/relay-alert-rules-evaluation.ts(node-cron 每 5 分钟)驱动,
-- 触发走既有 pushAlert 推送通道(PagerDuty/webhook),事件落表供管理端查询。
--
-- 向后兼容:纯新增表,无既有对象改动。幂等:IF NOT EXISTS。

CREATE TABLE IF NOT EXISTS "relay_alert_rules" (
  "id" uuid PRIMARY KEY DEFAULT gen_random_uuid() NOT NULL,
  "name" varchar(100) NOT NULL,
  "metric" varchar(32) NOT NULL,
  "comparison" varchar(4) DEFAULT 'gt' NOT NULL,
  "threshold" numeric(18, 4) NOT NULL,
  "cooldown_minutes" integer DEFAULT 30 NOT NULL,
  "enabled" boolean DEFAULT true NOT NULL,
  "remark" varchar(255),
  "created_at" timestamp with time zone DEFAULT now() NOT NULL,
  "updated_at" timestamp with time zone DEFAULT now() NOT NULL
);

CREATE INDEX IF NOT EXISTS "relay_alert_rules_enabled_idx" ON "relay_alert_rules" ("enabled");

CREATE TABLE IF NOT EXISTS "relay_alert_events" (
  "id" uuid PRIMARY KEY DEFAULT gen_random_uuid() NOT NULL,
  "rule_id" uuid NOT NULL REFERENCES "relay_alert_rules" ("id") ON DELETE CASCADE,
  "observed_value" numeric(18, 4) NOT NULL,
  "threshold" numeric(18, 4) NOT NULL,
  "message" varchar(500) NOT NULL,
  "push_status" varchar(24) DEFAULT 'pushed' NOT NULL,
  "created_at" timestamp with time zone DEFAULT now() NOT NULL
);

CREATE INDEX IF NOT EXISTS "relay_alert_events_rule_time_idx" ON "relay_alert_events" ("rule_id", "created_at");
