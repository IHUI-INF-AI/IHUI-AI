-- 模型进价列 integer → numeric(18,6)(2026-09-13 立):
--   背景:ai_model_config_models.input/output_price_per_1k 为 integer,
--   而分/千 token 进价实为小数(如 swiftapi glm-5.3 到手 0.04 分/千)。
--   integer 列导致:
--     1. seed 回填 ::int 全部归零 → 公开价目(/api/relay/models/public)恒 0;
--     2. discovery 审批落库的上游小数价丢失精度。
--   计费主源 ai_pricing 早已是 numeric(18,6),本迁移仅对齐展示/回填列。
-- ============================================================================

ALTER TABLE ai_model_config_models
  ALTER COLUMN input_price_per_1k TYPE numeric(18,6) USING input_price_per_1k::numeric,
  ALTER COLUMN output_price_per_1k TYPE numeric(18,6) USING output_price_per_1k::numeric;
