-- Key 级出口绑定（2026-11-17 立）
--
-- 立因：对标 qoder2api 系网关的「多 API Key 出口绑定」——每把 Key 自己指定走
-- 国际区还是国内区，不写区的跟随全局。
--
-- 本仓原状：出口由「模型名三段前缀（<平台>/<区>/<模型>）」与「账号行 extraMetadata.region
-- 推断出的亲和域」共同决定，粒度是"每次请求"，用户想整把 Key 锁一个区无处可写。
--
-- 形态要点：
--   ① 只加一列，可空 ⇒ 存量 Key 一律 null，行为零变化；
--   ② 取值只有 cn / global / null 三态，null 与既有"跟随全局"完全等价；
--   ③ 模型名三段前缀优先于本列 —— 临时意图盖过 Key 默认，这是刻意的。

alter table "developer_api_keys" add column if not exists "egress_region" varchar(16);
