-- 中转站插件系统(2026-09-17 立,补强 59,对标竞品 /plugins 路由组)。
-- 声明式插件注册表:零任意代码执行,内置插件类型由服务层解释执行,杜绝供应链风险。
-- 幂等:IF NOT EXISTS。plugin_key 唯一,重复安装为覆盖(upsert)。

CREATE TABLE IF NOT EXISTS "relay_plugins" (
  "id" uuid PRIMARY KEY DEFAULT gen_random_uuid() NOT NULL,
  "plugin_key" varchar(64) NOT NULL,
  "name" varchar(200) NOT NULL,
  "description" varchar(500),
  "plugin_type" varchar(32) NOT NULL,
  "config" jsonb DEFAULT '{}' NOT NULL,
  "priority" integer DEFAULT 100 NOT NULL,
  "status" varchar(16) DEFAULT 'disabled' NOT NULL,
  "created_by" varchar(64),
  "created_at" timestamp with time zone DEFAULT now() NOT NULL,
  "updated_at" timestamp with time zone DEFAULT now() NOT NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS "relay_plugins_key_uniq_idx" ON "relay_plugins" ("plugin_key");
CREATE INDEX IF NOT EXISTS "relay_plugins_status_idx" ON "relay_plugins" ("status");
