--
-- 背景:
--   plugins/api-key-auth.ts 的 checkPerModelRateLimit(Redis 滑动窗口 Lua)自 2026-07-31
--   起就按 developer_api_keys.perModelRpmLimit / perModelTpmLimit 读取单模型 RPM/TPM 上限,
--   但两列从未建表(代码自述 578-581 "字段未落地前 as 断言读取 → 恒 undefined → 恒跳过"),
--   导致 per-model 限流形同虚设。本次补列,鉴权链路去掉死分支后 Lua 窗口真正生效。
--
-- 形态:jsonb 映射 {"gpt-4o": 60}(模型名 → 上限),NULL = 全模型不限;
--   与 allowed_models 白名单同用 jsonb(该表既有惯例),不建关联表。
--
-- 向后兼容:两列均可空(NULL = 不限),既有 Key 行为完全不变。
-- 幂等:全部 IF NOT EXISTS。

ALTER TABLE "developer_api_keys" ADD COLUMN IF NOT EXISTS "per_model_rpm_limit" jsonb;
ALTER TABLE "developer_api_keys" ADD COLUMN IF NOT EXISTS "per_model_tpm_limit" jsonb;
