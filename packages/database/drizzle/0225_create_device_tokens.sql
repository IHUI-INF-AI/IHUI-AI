-- 设备推送 token 注册表(2026-09-06 立)：集中登记各端(FCM/APNS/Web Push)推送令牌
CREATE TABLE IF NOT EXISTS "device_tokens" (
  "id" uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  "user_id" uuid NOT NULL REFERENCES "users"("id") ON DELETE CASCADE,
  "token" text NOT NULL,
  "platform" varchar(20) NOT NULL,
  "device_type" varchar(100),
  "app_version" varchar(50),
  "locale" varchar(20),
  "is_active" boolean DEFAULT true NOT NULL,
  "last_used_at" timestamp with time zone DEFAULT now() NOT NULL,
  "created_at" timestamp with time zone DEFAULT now() NOT NULL,
  "updated_at" timestamp with time zone DEFAULT now() NOT NULL
);

CREATE INDEX IF NOT EXISTS "device_tokens_user_id_idx" ON "device_tokens" ("user_id");
CREATE INDEX IF NOT EXISTS "device_tokens_platform_idx" ON "device_tokens" ("platform");
CREATE INDEX IF NOT EXISTS "device_tokens_is_active_idx" ON "device_tokens" ("is_active");
CREATE UNIQUE INDEX IF NOT EXISTS "device_tokens_token_unique" ON "device_tokens" ("token");
