-- P0 修复(2026-09-13):llm_call_logs.config_id 列类型 uuid → bigint
-- 背景:config_id 注释声明「关联 ai_model_config.id」,而 ai_model_config.id 是 bigserial(数字主键)。
--   渠道直连(relay-channel-router)成功路径 recordCall 传入 configId = String(aiModelConfig.id),
--   如 "3" 这类数字字符串写入 uuid 列 → PostgreSQL 抛 invalid input syntax for type uuid
--   → recordCall 顶层 try/catch 吞错(fire-and-forget)→ 所有渠道直连成功调用无流水、无计费统计。
--   (错误路径 usedChannel=null → configId=null → 插入成功,所以只有 error 流水落库——与线上观察吻合。)
-- 数据安全:历史 config_id 值要么为 NULL(此前无调用方写入),要么是无效 uuid 尝试(未插入成功),
--   USING 子句把纯数字字符串安全转为 bigint,其余一律置 NULL,不阻塞迁移。
-- 幂等性:PostgreSQL 对相同类型的 ALTER TYPE 重执行会报错,但 drizzle-kit migrate 按 journal 记录只执行一次。

ALTER TABLE llm_call_logs ALTER COLUMN config_id DROP DEFAULT;
ALTER TABLE llm_call_logs
  ALTER COLUMN config_id TYPE bigint
  USING CASE WHEN config_id::text ~ '^\d{1,18}$' THEN (config_id::text)::bigint ELSE NULL END;

COMMENT ON COLUMN llm_call_logs.config_id IS '所用模型配置 id(关联 ai_model_config.id,bigint 主键;2026-09-13 从 uuid 修正)';
