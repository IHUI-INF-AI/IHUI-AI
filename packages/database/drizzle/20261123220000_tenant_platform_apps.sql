-- 租户级平台应用凭据（2026-11-23）
--
-- 单企业部署可从进程环境读一套飞书/钉钉/企微/微信应用凭据；
-- 多企业 SaaS 下这套凭据只属于创建它的那家企业，必须按 tenant_id 隔离。
-- secret 在应用层以 enc:v1 AES-256-GCM 密文写入，本表不存明文。
--
-- 唯一键 (tenant_id, platform)：同一租户同一平台只能有一套应用凭据。

CREATE TABLE IF NOT EXISTS "tenant_platform_apps" (
  "id" uuid PRIMARY KEY DEFAULT gen_random_uuid() NOT NULL,
  "tenant_id" uuid NOT NULL REFERENCES "tenants"("id") ON DELETE CASCADE,
  "platform" varchar(32) NOT NULL,
  "enabled" boolean DEFAULT true NOT NULL,
  "app_id" varchar(255) DEFAULT '' NOT NULL,
  "app_secret" text DEFAULT '' NOT NULL,
  "extra" jsonb DEFAULT '{}' NOT NULL,
  "created_by" uuid REFERENCES "users"("id") ON DELETE SET NULL,
  "created_at" timestamp with time zone DEFAULT now() NOT NULL,
  "updated_at" timestamp with time zone DEFAULT now() NOT NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS "tenant_platform_apps_tenant_platform_uidx"
  ON "tenant_platform_apps" ("tenant_id", "platform");

CREATE INDEX IF NOT EXISTS "tenant_platform_apps_tenant_idx"
  ON "tenant_platform_apps" ("tenant_id");

COMMENT ON TABLE "tenant_platform_apps" IS '租户级平台应用凭据；secret 为 enc:v1 密文';
COMMENT ON COLUMN "tenant_platform_apps"."platform" IS 'feishu | dingtalk | wecom | wechat | wechat_mp';
