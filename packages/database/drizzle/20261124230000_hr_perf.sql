-- 绩效考核(2026-11-24 七波):周期 + 评估单(自评→上级评→确认,含 refuse 重评)

CREATE TABLE IF NOT EXISTS "hr_perf_cycle" (
  "id" uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  "name" varchar(100) NOT NULL,
  "cycle_type" varchar(10) NOT NULL,
  "start_from" date NOT NULL,
  "end_to" date NOT NULL,
  "status" varchar(20) NOT NULL DEFAULT 'draft',
  "note" text,
  "created_at" timestamptz NOT NULL DEFAULT now(),
  "updated_at" timestamptz NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS "uq_hr_perf_cycle_name" ON "hr_perf_cycle" ("name");
CREATE INDEX IF NOT EXISTS "ix_hr_perf_cycle_status" ON "hr_perf_cycle" ("status");

CREATE TABLE IF NOT EXISTS "hr_perf_review" (
  "id" uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  "cycle_id" uuid NOT NULL REFERENCES "hr_perf_cycle"("id") ON DELETE RESTRICT,
  "employee_id" uuid NOT NULL REFERENCES "hr_employee"("id") ON DELETE RESTRICT,
  "reviewer_id" uuid NOT NULL REFERENCES "users"("id") ON DELETE SET NULL,
  "status" varchar(20) NOT NULL DEFAULT 'pending',
  "self_score" integer,
  "self_comment" text,
  "manager_score" integer,
  "manager_comment" text,
  "final_score" integer,
  "grade" varchar(4),
  "rounds" integer NOT NULL DEFAULT 1,
  "note" text,
  "created_at" timestamptz NOT NULL DEFAULT now(),
  "updated_at" timestamptz NOT NULL DEFAULT now(),
  "deleted_at" timestamptz
);

CREATE UNIQUE INDEX IF NOT EXISTS "uq_hr_perf_review_emp_cycle"
  ON "hr_perf_review" ("cycle_id", "employee_id")
  WHERE "deleted_at" IS NULL;
CREATE INDEX IF NOT EXISTS "ix_hr_perf_review_cycle" ON "hr_perf_review" ("cycle_id", "status");
CREATE INDEX IF NOT EXISTS "ix_hr_perf_review_reviewer" ON "hr_perf_review" ("reviewer_id", "status");
