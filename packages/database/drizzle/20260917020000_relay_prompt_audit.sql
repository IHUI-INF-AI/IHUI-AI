-- 提示词审计(2026-09-17 立,补强 54,对标竞品 /prompt-audit)。
-- 规则表(关键字子串匹配,大小写不敏感;刻意不支持正则以规避 ReDoS)与命中记录表。
-- 命中动作:log(仅记录) / warn(记录+告警) / block(拒绝调用)。
-- 幂等:IF NOT EXISTS。

CREATE TABLE IF NOT EXISTS "relay_prompt_audit_rules" (
  "id" uuid PRIMARY KEY DEFAULT gen_random_uuid() NOT NULL,
  "name" varchar(100) NOT NULL,
  "keyword" varchar(200) NOT NULL,
  "action" varchar(8) DEFAULT 'log' NOT NULL,
  "severity" integer DEFAULT 3 NOT NULL,
  "enabled" boolean DEFAULT true NOT NULL,
  "remark" varchar(255),
  "created_at" timestamp with time zone DEFAULT now() NOT NULL,
  "updated_at" timestamp with time zone DEFAULT now() NOT NULL
);

CREATE INDEX IF NOT EXISTS "relay_prompt_audit_rules_enabled_idx" ON "relay_prompt_audit_rules" ("enabled");

CREATE TABLE IF NOT EXISTS "relay_prompt_audit_hits" (
  "id" uuid PRIMARY KEY DEFAULT gen_random_uuid() NOT NULL,
  "rule_id" uuid REFERENCES "relay_prompt_audit_rules" ("id") ON DELETE CASCADE,
  "rule_name" varchar(100),
  "user_id" varchar(64),
  "api_key_id" varchar(64),
  "model" varchar(128),
  "keyword" varchar(200),
  "action_taken" varchar(8) NOT NULL,
  "snippet" text,
  "created_at" timestamp with time zone DEFAULT now() NOT NULL
);

CREATE INDEX IF NOT EXISTS "relay_prompt_audit_hits_created_at_idx" ON "relay_prompt_audit_hits" ("created_at");
CREATE INDEX IF NOT EXISTS "relay_prompt_audit_hits_rule_idx" ON "relay_prompt_audit_hits" ("rule_id");
