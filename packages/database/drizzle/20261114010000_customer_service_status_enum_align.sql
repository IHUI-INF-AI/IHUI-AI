-- F-434:customer_service_sessions.status 默认值 waiting 与「唯一真相源」枚举互斥
-- 根因见 PROJECT_PLAN.md「缺陷普查 API F-434」与 docs/tickets/2026-11/findings-api.md#F-434。
-- 唯一真相源 CUSTOMER_SERVICE_STATUSES = pending/open/resolved/closed/rejected
--   (packages/types/src/notification.ts)。
-- 本迁移把存量旧词汇收敛到枚举:waiting→pending、active→open,并修正列 default。
-- 幂等安全:UPDATE 仅命中旧值行,重复执行无副作用;default 用 IF NOT EXISTS 语义的
--   条件改列(PostgreSQL ALTER COLUMN SET DEFAULT 幂等)。

-- ============ ① 存量 waiting → pending ============
UPDATE "customer_service_sessions"
SET "status" = 'pending'
WHERE "status" = 'waiting';

-- ============ ② 存量 active → open ============
UPDATE "customer_service_sessions"
SET "status" = 'open'
WHERE "status" = 'active';

-- ============ ③ 列 default 对齐枚举(waiting → pending) ============
ALTER TABLE "customer_service_sessions"
  ALTER COLUMN "status" SET DEFAULT 'pending';
