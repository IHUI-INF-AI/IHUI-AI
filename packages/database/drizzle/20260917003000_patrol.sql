-- P3 #40 主动巡逻 Agent 阶段1(2026-09-17 立):巡检任务表 + 巡检执行历史表。
-- 背景:Codex 自动化只执行排程任务,不主动发起对话;本表支撑定时巡检
--   (CI/依赖/日志/死链/自定义)+ 发现问题主动建会话注入诊断(阶段2)+
--   会话内一键授权执行修复(阶段3,复用既有工具审批流)。
-- 调度器:apps/api/src/services/patrol-scheduler.ts(60s tick 轮询 next_run_at)。
-- 复用:rrule 语义与 user_automations 一致;告警会话复用 chat_conversations
--   (notify_conversation_id 回存,同一任务告警注入同一会话防刷屏)。

CREATE TABLE IF NOT EXISTS patrol_tasks (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  name varchar(200) NOT NULL,
  patrol_type varchar(20) NOT NULL DEFAULT 'custom',
  target text,
  prompt text,
  rrule varchar(500) NOT NULL,
  timezone varchar(64) NOT NULL DEFAULT 'Asia/Shanghai',
  status varchar(20) NOT NULL DEFAULT 'active',
  notify_conversation_id uuid,
  last_run_at timestamptz,
  next_run_at timestamptz,
  last_result jsonb,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS patrol_tasks_user_idx ON patrol_tasks(user_id);
CREATE INDEX IF NOT EXISTS patrol_tasks_status_idx ON patrol_tasks(status);
CREATE INDEX IF NOT EXISTS patrol_tasks_next_run_idx ON patrol_tasks(next_run_at);

CREATE TABLE IF NOT EXISTS patrol_runs (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  task_id uuid NOT NULL REFERENCES patrol_tasks(id) ON DELETE CASCADE,
  status varchar(16) NOT NULL,
  summary text NOT NULL,
  conversation_id uuid,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS patrol_runs_task_idx ON patrol_runs(task_id);
