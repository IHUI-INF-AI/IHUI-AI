-- 催缴回执持久化(2026-09-29)
--
-- 为什么要有:`GET /fee-reminder/stats` 只能数"留痕"(登记了几条催缴),数不出"送达几条" ——
-- 因为通道级四档回执(sent / failed / not_configured / no_phone,微信另有 user_refused)
-- 当时只回给调用方并写日志,库里没有。于是"催缴 sent=120"很容易被读成"120 个家长收到了",
-- 而真实情况可能是 120 条里微信一条都没发出去(未配置或额度耗尽)。这正是"把没判写成判过了"。
--
-- 形态:jsonb 数组,每元素 {userId, role, channel, bucket, detail?, at}。
-- 不另立表的原因:回执与催缴留痕是 1:1 附属信息、永不独立查询、随留痕一起删,
-- 建表会带来一个只服务一张表的外键与一次额外往返;列可空 ⇒ 历史行保持 NULL,
-- 统计端点把 NULL 归入 `unknownDelivery` 计数而不是当作"没送达"或"已送达"(两向都不猜)。
ALTER TABLE "edu_fee_reminder" ADD COLUMN IF NOT EXISTS "delivery" jsonb;
