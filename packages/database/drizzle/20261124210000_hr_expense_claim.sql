-- 费用报销闭环(2026-11-24 四波):报销单 + 固化审批链快照 + 付款/入账留痕

CREATE TABLE IF NOT EXISTS "hr_expense_claim" (
  "id" uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  "employee_id" uuid NOT NULL REFERENCES "hr_employee"("id") ON DELETE RESTRICT,
  "ledger_id" uuid REFERENCES "fin_ledger"("id") ON DELETE SET NULL,
  "category" varchar(20) NOT NULL,
  "title" varchar(200) NOT NULL,
  "amount" numeric(14,2) NOT NULL,
  "vouchers" jsonb NOT NULL,
  "approver_chain" jsonb NOT NULL,
  "current_step" integer NOT NULL DEFAULT 0,
  "steps" jsonb NOT NULL DEFAULT '[]',
  "status" varchar(20) NOT NULL DEFAULT 'submitted',
  "payment_method" varchar(20),
  "paid_at" timestamptz,
  "voucher_id" uuid REFERENCES "fin_voucher"("id") ON DELETE SET NULL,
  "voucher_no" varchar(30),
  "note" text,
  "submitted_by" uuid REFERENCES "users"("id") ON DELETE SET NULL,
  "created_at" timestamptz NOT NULL DEFAULT now(),
  "updated_at" timestamptz NOT NULL DEFAULT now(),
  "deleted_at" timestamptz
);

CREATE INDEX IF NOT EXISTS "ix_hr_expense_claim_emp" ON "hr_expense_claim" ("employee_id", "status");
CREATE INDEX IF NOT EXISTS "ix_hr_expense_claim_ledger" ON "hr_expense_claim" ("ledger_id", "status");
CREATE INDEX IF NOT EXISTS "ix_hr_expense_claim_active" ON "hr_expense_claim" ("status") WHERE "deleted_at" IS NULL;
