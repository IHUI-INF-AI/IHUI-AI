-- F-175:技能同步 upsert 是 check-then-write,(author_id, slug) 无唯一约束 ⇒
-- 同用户两台设备并发 POST /api/skills/push 或 /api/skills/db-sync 同一 slug 会落重复行。
-- 修法:先去重,再建唯一索引;应用层改 ON CONFLICT DO UPDATE 原子 upsert。
--
-- 去重取舍:同一 (author_id, slug) 只留一行 ——
--   ① 活行(deleted_at IS NULL)优先于软删 tombstone;
--   ② 同活/同删时留 updated_at 最新的一行;
--   ③ updated_at 相同再按 id 最小的一行。
-- 幂等:去重语句在唯一索引已存在时命中 0 行;CREATE UNIQUE INDEX IF NOT EXISTS 可重复执行。
DELETE FROM "skills" a
USING "skills" b
WHERE a."author_id" IS NOT NULL
  AND a."slug" IS NOT NULL
  AND a."author_id" = b."author_id"
  AND a."slug" = b."slug"
  AND (
    (a."deleted_at" IS NOT NULL AND b."deleted_at" IS NULL)
    OR (
      (a."deleted_at" IS NULL) = (b."deleted_at" IS NULL)
      AND (
        a."updated_at" < b."updated_at"
        OR (a."updated_at" = b."updated_at" AND a."id" > b."id")
      )
    )
  );

CREATE UNIQUE INDEX IF NOT EXISTS "skills_author_slug_uniq"
  ON "skills" USING btree ("author_id", "slug");
