-- 数据库备份作业系统(2026-09-16 立,深度对标补强 V,对标竞品 /backups + /s3/profiles)。
-- 两表:backup_jobs(作业记录:running→succeeded/failed,产物路径/大小/耗时)与
-- backup_settings(单行配置:enabled+cronExpr+keepCount 保留份数+backupDir)。
-- 保留策略在应用层(成功后删超额文件+记录);S3 远端上传留扩展点。
-- 幂等:IF NOT EXISTS。

CREATE TABLE IF NOT EXISTS "backup_jobs" (
  "id" uuid PRIMARY KEY DEFAULT gen_random_uuid() NOT NULL,
  "name" varchar(100) NOT NULL,
  "type" varchar(16) DEFAULT 'manual' NOT NULL,
  "status" varchar(16) DEFAULT 'pending' NOT NULL,
  "file_path" varchar(500),
  "file_size_bytes" bigint,
  "duration_ms" integer,
  "error" varchar(500),
  "created_by" varchar(64),
  "created_at" timestamp with time zone DEFAULT now() NOT NULL,
  "updated_at" timestamp with time zone DEFAULT now() NOT NULL
);

CREATE INDEX IF NOT EXISTS "backup_jobs_created_at_idx" ON "backup_jobs" ("created_at");

CREATE TABLE IF NOT EXISTS "backup_settings" (
  "id" uuid PRIMARY KEY DEFAULT gen_random_uuid() NOT NULL,
  "enabled" boolean DEFAULT false NOT NULL,
  "cron_expr" varchar(32) DEFAULT '0 3 * * *' NOT NULL,
  "keep_count" integer DEFAULT 7 NOT NULL,
  "backup_dir" varchar(500) DEFAULT './backups' NOT NULL,
  "updated_at" timestamp with time zone DEFAULT now() NOT NULL
);
