-- Agent loop checkpoints 表(2026-09-20 立,D26 双轨收敛:主链路 checkpoint PG 持久层)。
--
-- 背景:
--   agent_loop_v2 主链路 checkpoint 此前仅「内存 LRU + Redis 缓存」,
--   升级为「内存 LRU + Redis 缓存 + PG 持久」三层(复用 langgraph 双表
--   「Drizzle 定义 + Python 裸 SQL CRUD」协作模式,见 schema/p3-deep-layer.ts)。
--   checkpoint_id 为 uuid4 hex 主键,UPSERT 幂等;expires_at 供 TTL 清理。
--
-- 向后兼容:纯新增表,既有链路行为不变。
-- 幂等:全部 IF NOT EXISTS。

CREATE TABLE IF NOT EXISTS "agent_checkpoints" (
  "checkpoint_id" varchar(64) PRIMARY KEY NOT NULL,
  "session_id" varchar(100) NOT NULL,
  "status" varchar(20) NOT NULL,
  "iteration" integer NOT NULL,
  "payload" jsonb NOT NULL,
  "created_at" timestamp with time zone DEFAULT now() NOT NULL,
  "expires_at" timestamp with time zone NOT NULL
);

CREATE INDEX IF NOT EXISTS "agent_checkpoints_session_idx" ON "agent_checkpoints" ("session_id");
CREATE INDEX IF NOT EXISTS "agent_checkpoints_expires_idx" ON "agent_checkpoints" ("expires_at");
