-- MAGI-2 视频定价(2026-11-25 立)。
--
-- 口径: `ai_pricing.billing_mode='per_video'` + `video_unit='second'` +
-- `per_unit_price` 单位=分/秒。1 积分 = 1 分钱,因此 74 分/秒即 74 积分/秒。
--
-- 取价依据: Sand.ai 官方 0.08 USD/秒(MAGI-2 原生 30s 1080P 有声)。
-- 按 1 USD ≈ 7.1 CNY 折算 ≈ ¥0.568/秒;取 ¥0.74/秒,30 秒约 2220 积分(¥22.20),
-- 对上游 ¥17.04 留约 30% 毛利。价格写入 ai_pricing 后,media-billing 会直接读取,
-- 不在代码里再写一份常量;后续按真实账单校准应新增生效行并给旧行 expires_at。
--
-- 幂等: ai_pricing 对 model_id 没有唯一约束,沿用 20261030193000 的
-- `WHERE NOT EXISTS` 写法,仅当该 model 当前无生效行才 INSERT。

INSERT INTO ai_pricing (
  model_id, input_token_price, output_token_price,
  billing_mode, per_unit_price, video_unit, region_pricing, currency
)
SELECT v.model_id, 0, 0, 'per_video', 74.000000::numeric, 'second'::text, '{"cn":1.0}'::jsonb, 'CNY'
FROM (VALUES
  ('magi-2'),
  ('magi-2-preview'),
  ('magi-2-preview-latest')
) AS v(model_id)
WHERE NOT EXISTS (
  SELECT 1 FROM ai_pricing p
  WHERE p.model_id = v.model_id
    AND p.effective_at <= now()
    AND (p.expires_at IS NULL OR p.expires_at > now())
);
