-- chat-sync 修订号账本(票 B02 第三切片,2026-10-25 立):
-- rev 唯一权威源,每消息一行,UPSERT 原子递增。替代已退役的两档
-- (Redis INCR chat-sync:rev:<messageId> / 壁钟回落):Redis 被清或无持久化时重启归零、
-- 壁钟值进链后重启必回退,两端都让端侧把新内容全判 stale("停在半截回复而账面全绿")。
-- 与消息本体同库 ⇒ 快照端点"内容 + rev"同库同读,天然一致。
-- 不冗余存 conversation_id:会话归属单源在 chat_messages,快照读 JOIN 一次即可。
-- 幂等写法(本仓手写迁移口径,同 20261024160000_announcement_platforms.sql)。

CREATE TABLE IF NOT EXISTS "chat_message_sync_revs" (
    "message_id" uuid PRIMARY KEY REFERENCES "chat_messages"("id") ON DELETE CASCADE,
    "rev" integer DEFAULT 0 NOT NULL,
    "updated_at" timestamp with time zone DEFAULT now() NOT NULL
);
