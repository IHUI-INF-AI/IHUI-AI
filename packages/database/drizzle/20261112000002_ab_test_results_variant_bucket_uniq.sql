-- F-448:ab_test_results 的 UNIQUE(variant_id,bucket) 只在首定义迁移
-- 0043_neat_the_spike.sql(首定义胜出)里存在;20260831000000_feature_gap_tables.sql
-- 的重复建表与 TS schema 都把它丢了(bucket 可空、无唯一约束)。routes/ab-testing.ts
-- 两处 onConflictDoUpdate({ target: [variantId, bucket] }) 在按 20260831 重建/
-- drizzle-kit push 的库上必撞 42P10,同一 variant+bucket 还会重复计数。
-- 约束名与 0043 既成事实一致:ab_test_results_variant_bucket_uniq。
--
-- 兼容修复:bucket 为事件桶(exposure/conversion/click),历史 NULL 行收敛到
-- exposure 桶;回填后再按 (variant_id,bucket) 去重(保留 samples 最大、平局保
-- 物理顺序最后一行),最后 SET NOT NULL + 幂等补约束。
-- 上线运维:回填/去重为不可逆写操作,执行前先备份:
--   CREATE TABLE ab_test_results_bak_20261112 AS SELECT * FROM ab_test_results;
UPDATE "ab_test_results" SET "bucket" = 'exposure' WHERE "bucket" IS NULL;

DELETE FROM "ab_test_results" a
USING "ab_test_results" b
WHERE a."variant_id" = b."variant_id"
  AND a."bucket" = b."bucket"
  AND (a."samples" < b."samples"
       OR (a."samples" = b."samples" AND a."ctid" > b."ctid"));

ALTER TABLE "ab_test_results" ALTER COLUMN "bucket" SET NOT NULL;

DO $f448_variant_bucket$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conname = 'ab_test_results_variant_bucket_uniq'
      AND conrelid = 'ab_test_results'::regclass
  ) THEN
    ALTER TABLE "ab_test_results"
      ADD CONSTRAINT "ab_test_results_variant_bucket_uniq"
      UNIQUE ("variant_id", "bucket");
  END IF;
END $f448_variant_bucket$;

