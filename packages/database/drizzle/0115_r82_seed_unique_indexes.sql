-- 0115_r82_seed_unique_indexes.sql
-- R82: 为 ai-fresh-2026.ts seed 6 处 `if (ex) continue` 升级为 `onConflictDoNothing` 所需 unique 索引
-- circles.slug 已有 unique 约束(原 schema),此迁移仅补 4 张表:
--   live_channels.title, news_articles.title, asks.title, resources.title

-- BUG-88: 4 张内容表均为更早迁移建的既有表，存量 title 可能重复。
-- IF NOT EXISTS 只保证重放不撞名字；重复行会用 23505 中断迁移，故逐条包 EXCEPTION 守卫。
DO $$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_class WHERE relname = 'live_channels_title_uniq') THEN
    BEGIN
      CREATE UNIQUE INDEX "live_channels_title_uniq" ON "live_channels" ("title");
    EXCEPTION WHEN unique_violation THEN
      RAISE NOTICE 'BUG-88: live_channels 存量 title 重复，跳过唯一索引';
    END;
  END IF;
END $$;
DO $$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_class WHERE relname = 'news_articles_title_uniq') THEN
    BEGIN
      CREATE UNIQUE INDEX "news_articles_title_uniq" ON "news_articles" ("title");
    EXCEPTION WHEN unique_violation THEN
      RAISE NOTICE 'BUG-88: news_articles 存量 title 重复，跳过唯一索引';
    END;
  END IF;
END $$;
DO $$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_class WHERE relname = 'asks_title_uniq') THEN
    BEGIN
      CREATE UNIQUE INDEX "asks_title_uniq" ON "asks" ("title");
    EXCEPTION WHEN unique_violation THEN
      RAISE NOTICE 'BUG-88: asks 存量 title 重复，跳过唯一索引';
    END;
  END IF;
END $$;
DO $$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_class WHERE relname = 'resources_title_uniq') THEN
    BEGIN
      CREATE UNIQUE INDEX "resources_title_uniq" ON "resources" ("title");
    EXCEPTION WHEN unique_violation THEN
      RAISE NOTICE 'BUG-88: resources 存量 title 重复，跳过唯一索引';
    END;
  END IF;
END $$;
