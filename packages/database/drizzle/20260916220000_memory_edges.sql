-- P3 #41 记忆图谱阶段1a(2026-09-16 立):记忆条目关系边表。
-- 背景:竞品记忆全部平铺列表;本表把 agent_memory_semantic 的条目升级为
--   知识图谱节点 + 有向关系边,支撑子图查询(阶段2)与前端可视化(阶段3)。
-- 关系来源:memory_graph.py 的 LLM 关系抽取(每轮记忆写入后异步触发)。
-- 幂等:唯一约束 (user_id, source_id, target_id, relation) → ON CONFLICT DO NOTHING。
-- 级联:semantic 条目删除时边自动清理(onDelete cascade),不留悬挂边。

CREATE TABLE IF NOT EXISTS agent_memory_edges (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  source_id uuid NOT NULL REFERENCES agent_memory_semantic(id) ON DELETE CASCADE,
  target_id uuid NOT NULL REFERENCES agent_memory_semantic(id) ON DELETE CASCADE,
  relation varchar(64) NOT NULL DEFAULT 'relates_to',
  weight numeric NOT NULL DEFAULT 1,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT uq_agent_memory_edges UNIQUE (user_id, source_id, target_id, relation),
  CONSTRAINT ck_agent_memory_edges_not_self CHECK (source_id <> target_id)
);

CREATE INDEX IF NOT EXISTS ix_agent_memory_edges_user ON agent_memory_edges(user_id);
CREATE INDEX IF NOT EXISTS ix_agent_memory_edges_source ON agent_memory_edges(source_id);
CREATE INDEX IF NOT EXISTS ix_agent_memory_edges_target ON agent_memory_edges(target_id);
