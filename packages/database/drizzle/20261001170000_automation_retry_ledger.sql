-- G-669(2026-10-01 立):给 user_automations 补"重试台账"两列。
--
-- 立因(两处都在 apps/api/src/services/agent-automation-scheduler.ts):
--   A. 执行失败的 catch 只 log.warn + return null,**不写任何时间戳** ⇒ tick 的到期查询
--      (once: last_run_at IS NULL / recurring: next_run_at <= now)必然再次命中同一行
--      ⇒ 抛穿路径每 60 秒无限重放;
--   B. 上游非 2xx(401/403/400 = 缺凭据形状)被 consumeAgentStream 吞成 errorMessage 后
--      **正常返回** ⇒ 调用方按成功落 last_run_at 并重排、status 留 active
--      ⇒ 缺凭据根本走不到 catch。
-- 分流需要两个落点列:
--   attempt    —— transient 连续重试计数(成功结算即归零);>0 同时是"这一行在重试队列里"
--                 的唯一标记(tick 的 once 重试分支必须带 attempt > 0,否则历史 once 行里
--                 next_run_at = scheduled_at 那份值会被当成重试位反复捞起)。
--   last_error —— 最后一次失败的可读原因(含档位与命中判据),供 UI 展示与人工接管。
-- 全部为加列(default 0 / NULL),无 DROP、无既有列变更;两条都 IF NOT EXISTS ⇒ 可重放。

--> statement-breakpoint
ALTER TABLE "user_automations" ADD COLUMN IF NOT EXISTS "attempt" integer DEFAULT 0 NOT NULL;
--> statement-breakpoint
ALTER TABLE "user_automations" ADD COLUMN IF NOT EXISTS "last_error" text;
