-- Migration 20261112210000: 外出/外勤记录表(HR-5 第 3 期)
-- 创建时间: 2026-11-12
-- 描述: 外出是「离开办公地点但仍算出勤」,与请假(不算出勤)、加班(超时工作)都不是一回事。
--         打卡记录只能证明「打了卡」,证明不了「因公外出」,月结时会被误判成旷工/缺卡。
--       本表保留飞书/钉钉外出单的原始凭据(起止时刻、目的地、事由、外部单号),
--       并作为考勤核算把 absent 修正为 present 的依据。
--
-- 幂等安全:CREATE TABLE IF NOT EXISTS,可安全重复执行。
-- 与 packages/database/src/schema/hr-outgoing.ts 逐字对齐。
--
-- 执行方式:
--   pnpm tsx packages/database/scripts/apply-migration.mjs drizzle/20261112210000_hr_outgoing.sql

CREATE TABLE IF NOT EXISTS "hr_outgoing_record" (
  "id" uuid PRIMARY KEY DEFAULT gen_random_uuid() NOT NULL,
  "employee_id" uuid NOT NULL REFERENCES "hr_employee"("id") ON DELETE CASCADE,
  "department_id" uuid NOT NULL REFERENCES "hr_department"("id") ON DELETE CASCADE,
  "start_date" date NOT NULL,
  "end_date" date NOT NULL,
  "start_time" time,
  "end_time" time,
  "minutes" integer DEFAULT 0 NOT NULL,
  "destination" varchar(200),
  "reason" text,
  "status" varchar(20) DEFAULT 'pending' NOT NULL,
  "source" varchar(20) DEFAULT 'manual' NOT NULL,
  "external_id" varchar(120),
  "operated_by" uuid REFERENCES "users"("id"),
  "deleted_at" timestamptz,
  "created_at" timestamptz DEFAULT now() NOT NULL,
  "updated_at" timestamptz DEFAULT now() NOT NULL
);
CREATE INDEX IF NOT EXISTS "ix_hr_out_emp_date" ON "hr_outgoing_record" ("employee_id", "start_date");
CREATE INDEX IF NOT EXISTS "ix_hr_out_dept_date" ON "hr_outgoing_record" ("department_id", "start_date");
CREATE INDEX IF NOT EXISTS "ix_hr_out_status" ON "hr_outgoing_record" ("status");
CREATE INDEX IF NOT EXISTS "ix_hr_out_external" ON "hr_outgoing_record" ("external_id");
