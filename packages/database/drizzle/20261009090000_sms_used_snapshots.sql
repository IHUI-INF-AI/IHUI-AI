-- sms_used_snapshots —— 平台「查询历史」快照累积(管理员短信接码 /admin/sms-receive)
--
-- 背景:平台 queryUsed 只回本账号 24h 内流水且最多 100 条、限频 1 次/分钟
-- (2026-10-09 定性)。本表在每次 /used 查询时把流水逐条抄进本地,按
-- (phone, text_hash) 幂等去重 —— 短信原文含一次性验证码,天然唯一;
-- text_hash = sha256(phone\nfee\ntext)。本地视野随时间单调增长,
-- 攻破平台 24h + 100 条上限(与 sms_related_snapshots 同一打法)。
--
-- 口径说明(逐条都是刻意选择):
--   ① 平台行无时间字段 ⇒ first_seen_at 是"本系统首次见到该条"的时刻(入库时间),
--     不是短信到达时刻 —— 展示时按"入库时间"口径标注。
--   ② platform/usage_kind 在快照时从短信原文提取,与 sms_receive_history 同一提取链。
--   ③ 不关联 user_id:管理员页单管理员场景,与 sms_receive_history 同理。
--   ④ 全表幂等:CREATE TABLE IF NOT EXISTS + CREATE INDEX IF NOT EXISTS。
-- ============================================================================

--> statement-breakpoint
CREATE TABLE IF NOT EXISTS "sms_used_snapshots" (
	"id" uuid PRIMARY KEY DEFAULT gen_random_uuid() NOT NULL,
	"phone" varchar(20) NOT NULL,
	"fee" varchar(16) NOT NULL,
	"platform" varchar(64),
	"usage_kind" varchar(16) DEFAULT 'other' NOT NULL,
	"text" text NOT NULL,
	"text_hash" varchar(64) NOT NULL,
	"first_seen_at" timestamp with time zone DEFAULT now() NOT NULL,
	CONSTRAINT "sms_used_snapshots_phone_text_unique" UNIQUE ("phone","text_hash")
);

