CREATE INDEX IF NOT EXISTS "sms_used_snapshots_phone_idx" ON "sms_used_snapshots" USING btree ("phone","first_seen_at" DESC);

--> statement-breakpoint
CREATE INDEX IF NOT EXISTS "sms_used_snapshots_platform_idx" ON "sms_used_snapshots" USING btree ("platform");
