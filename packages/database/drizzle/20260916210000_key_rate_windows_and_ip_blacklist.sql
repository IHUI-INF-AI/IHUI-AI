-- Key 级限流窗口 + IP 黑名单(2026-09-16 立,深度对标补强 B/C)。
--
-- 背景:
--   B. 竞品 Sub2API 的 Key 支持 5h/1d/7d 三级滚动窗口请求数上限
--      (对齐 Claude/OpenAI 订阅上游的窗口形态);本项目 Key 此前只有静态
--      rate_limit(QPM),无法表达"每 5 小时最多 N 次"。
--   C. allowed_ips 白名单此前从未在运行时校验;且缺 IP 黑名单。
--      本次一并补齐:黑名单命中 403,白名单存在时不在名单内 403。
--
-- 新表 key_rate_window_counts:每个 Key × 窗口类型 × 窗口起点一行,
-- 记录请求数;唯一索引保证并发下单行,UPSERT 累加。
-- 窗口起点口径:5h = epoch 固定对齐;1d/7d = UTC+8(与订阅窗口一致)。
--
-- 向后兼容:四列均可空(NULL = 不限),既有 Key 行为完全不变。
-- 幂等:全部 IF NOT EXISTS。

ALTER TABLE "developer_api_keys" ADD COLUMN IF NOT EXISTS "blocked_ips" jsonb DEFAULT '[]'::jsonb;
ALTER TABLE "developer_api_keys" ADD COLUMN IF NOT EXISTS "rate_limit_5h" integer;
ALTER TABLE "developer_api_keys" ADD COLUMN IF NOT EXISTS "rate_limit_1d" integer;
ALTER TABLE "developer_api_keys" ADD COLUMN IF NOT EXISTS "rate_limit_7d" integer;

CREATE TABLE IF NOT EXISTS "key_rate_window_counts" (
  "id" uuid PRIMARY KEY DEFAULT gen_random_uuid() NOT NULL,
  "key_id" uuid NOT NULL REFERENCES "developer_api_keys" ("id") ON DELETE CASCADE,
  "window_type" varchar(8) NOT NULL,
  "window_start" timestamp with time zone NOT NULL,
  "request_count" bigint DEFAULT 0 NOT NULL,
  "created_at" timestamp with time zone DEFAULT now() NOT NULL,
  "updated_at" timestamp with time zone DEFAULT now() NOT NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS "key_rate_window_counts_uniq_idx" ON "key_rate_window_counts" ("key_id", "window_type", "window_start");
CREATE INDEX IF NOT EXISTS "key_rate_window_counts_key_idx" ON "key_rate_window_counts" ("key_id", "window_type");
