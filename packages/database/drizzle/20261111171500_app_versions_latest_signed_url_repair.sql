-- **临时签名直链**(...?OSSAccessKeyId=&Expires=&Signature=)。签名过期且 apk.aizhs.top
-- bucket 已被禁用后,系统安装器拿到的是 XML 错误页而不是 APK ⇒ (33) packageinfo is null,
-- 端内更新流程随即停在 installing,首页「正在打开安装程序…」关不掉。
