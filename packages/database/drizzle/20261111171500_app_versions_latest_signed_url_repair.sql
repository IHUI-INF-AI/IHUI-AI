-- 稳定件取 scripts/data/mobile-download-leg.json 的 downloadUrl(全仓唯一真源;
-- scripts/lib/mobile-download-leg.mjs 与登记器物的 DEFAULTS 都读它)。这里必须写字面量:
-- 迁移 SQL 无法 import JSON,故以注释钉住出处,改址时两处同笔。
--
-- 刻意**不动 version / build_number / status**:线上 latest=0.0.20 是已发布包,而手机上
-- 0.0.21 是本机手工构建、从未走发布腿。把它写成 latest 会造出「表里说有新包、实际
-- 下载不到」的新谎言。版本号的分裂由构建期 fail-closed(app.config.js)根治,与数据面无关。
--
-- 幂等:WHERE 只命中带签名参数的行,跑第二遍 0 行;不碰 history / 其它平台 / 其它渠道。
-- 防复发由 scripts/register-app-version-latest.mjs 的 validateDesired 拒绝签名 URL 承担。

UPDATE app_versions
SET download_url = 'https://www.aizhs.top/remote-images/download/ihui-ai-latest.apk',
    updated_at = now()
WHERE platform = 'android'
  AND status = 'latest'
  AND (
    download_url LIKE '%OSSAccessKeyId=%'
    OR download_url LIKE '%Signature=%'
    OR download_url LIKE '%X-Amz-Signature=%'
  );
