-- pgvector RAG(D8,2026-09-19 立):向量块表(幂等;扩展缺失时表也不建,
-- 由 ai-service pgvector_store 首用时自建,见 apps/ai-service/app/services/pgvector_store.py)
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_extension WHERE extname = 'vector') THEN
        CREATE TABLE IF NOT EXISTS rag_chunks (
            id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
            namespace text NOT NULL,
            source text,
            ref_id text NOT NULL,
            content text NOT NULL,
            embedding vector,
            dims integer NOT NULL DEFAULT 0,
            metadata jsonb NOT NULL DEFAULT '{}'::jsonb,
            created_at timestamptz NOT NULL DEFAULT now()
        );
        CREATE UNIQUE INDEX IF NOT EXISTS rag_chunks_ns_ref_uidx ON rag_chunks (namespace, source, ref_id);
    END IF;
EXCEPTION WHEN OTHERS THEN
    RAISE NOTICE 'rag_chunks 建表跳过: %', SQLERRM;
END $$;
