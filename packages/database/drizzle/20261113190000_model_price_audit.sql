-- 模型调价审计(2026-11-13 立)
-- 动机:定价从"一次性脚本快照"转为"可管理的持续过程"。任何价格变动(自动补价/人工调价/
-- 上游同步)都必须留痕,否则出问题无法回溯是谁、何时、按什么依据改的价。
-- 只追加、不更新、不删除(审计表铁律);查询走 (model_id, created_at desc) 索引。
create table if not exists ai_model_price_audit (
  id bigserial primary key,
  model_id varchar(255) not null,
  config_id integer,
  old_input_per_1k numeric(18, 6),
  old_output_per_1k numeric(18, 6),
  new_input_per_1k numeric(18, 6) not null,
  new_output_per_1k numeric(18, 6) not null,
  -- 变动来源:auto-sweep(定时巡检) / manual(人工调价) / approve(审批上架) / public-sync
  change_source varchar(64) not null,
  -- 定价档位:exact/alias/family/provider-fallback/global-fallback/manual
  change_tier varchar(32),
  -- 兜底时参照的模型(审计复核用)
  ref_model varchar(255),
  operator_id uuid,
  note text,
  created_at timestamptz not null default now()
);

create index if not exists idx_amp_audit_model on ai_model_price_audit (model_id, created_at desc);
create index if not exists idx_amp_audit_created on ai_model_price_audit (created_at desc);
