-- 幂等:IF NOT EXISTS。

CREATE TABLE IF NOT EXISTS "relay_alert_silences" (
  "id" uuid PRIMARY KEY DEFAULT gen_random_uuid() NOT NULL,
  "scope" varchar(8) DEFAULT 'rule' NOT NULL,
  "rule_id" uuid REFERENCES "relay_alert_rules" ("id") ON DELETE CASCADE,
  "reason" varchar(255),
  "starts_at" timestamp with time zone DEFAULT now() NOT NULL,
  "ends_at" timestamp with time zone NOT NULL,
  "created_by" varchar(64),
  "created_at" timestamp with time zone DEFAULT now() NOT NULL
);

CREATE INDEX IF NOT EXISTS "relay_alert_silences_ends_at_idx" ON "relay_alert_silences" ("ends_at");
CREATE INDEX IF NOT EXISTS "relay_alert_silences_rule_idx" ON "relay_alert_silences" ("rule_id");
