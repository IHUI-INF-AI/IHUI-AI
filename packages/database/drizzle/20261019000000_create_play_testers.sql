CREATE TABLE IF NOT EXISTS "play_testers" (
  "id" uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  "email" varchar(255) NOT NULL,
  "locale" varchar(10) NOT NULL DEFAULT 'zh-CN',
  "source" varchar(30) NOT NULL DEFAULT 'web',
  "status" varchar(20) NOT NULL DEFAULT 'pending',
  "agreed_privacy" boolean NOT NULL DEFAULT false,
  "created_at" timestamp DEFAULT now() NOT NULL,
  "updated_at" timestamp DEFAULT now() NOT NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS "play_testers_email_idx" ON "play_testers" ("email");
CREATE INDEX IF NOT EXISTS "play_testers_status_idx" ON "play_testers" ("status");
CREATE INDEX IF NOT EXISTS "play_testers_created_at_idx" ON "play_testers" ("created_at");

