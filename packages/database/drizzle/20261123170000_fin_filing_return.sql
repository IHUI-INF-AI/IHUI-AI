-- 申报表级复核(2026-11-23):把一次申报拆成多张表,每张表记「谁编/谁审/结论」
CREATE TABLE IF NOT EXISTS "fin_filing_return" (
  "id" uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  "task_id" uuid NOT NULL REFERENCES "fin_filing_task"("id") ON DELETE CASCADE,
  "client_id" uuid NOT NULL REFERENCES "fin_client"("id") ON DELETE CASCADE,
  "tax_type" varchar(20) NOT NULL,
  "period" varchar(10) NOT NULL,
  "form_code" varchar(40) NOT NULL,
  "form_name" varchar(100) NOT NULL,
  "payload" jsonb,
  "taxable_base" numeric(16,2),
  "tax_amount" numeric(16,2),
  "status" varchar(20) NOT NULL DEFAULT 'draft',
  "version" integer NOT NULL DEFAULT 1,
  "prepared_by" uuid REFERENCES "users"("id") ON DELETE SET NULL,
  "submitted_by" uuid REFERENCES "users"("id") ON DELETE SET NULL,
  "submitted_at" timestamptz,
  "reviewed_by" uuid REFERENCES "users"("id") ON DELETE SET NULL,
  "reviewed_at" timestamptz,
  "review_remark" text,
  "created_at" timestamptz NOT NULL DEFAULT now(),
  "updated_at" timestamptz NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS "uq_fin_filing_return"
  ON "fin_filing_return" ("task_id", "form_code");

CREATE INDEX IF NOT EXISTS "ix_fin_filing_return_status"
  ON "fin_filing_return" ("client_id", "period", "status");
