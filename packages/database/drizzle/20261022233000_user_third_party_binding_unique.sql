-- 一次微信只能有一条"活绑定":把 (platform, open_id) 的活行钉成唯一。
--
-- 立因(2026-10-22 实测):`user_third_party_accounts` 上只有两条**普通**索引
-- (`user_third_party_platform_idx`、`user_third_party_user_idx`),没有任何唯一约束。
-- 而登录路径的去重靠 `findThirdPartyAccount` 先查后插 —— 那是**跨进程读改写**,
-- 同一次微信被并发扫两次(用户双击、或前端重试)就会插出两条活绑定,
-- 之后 `limit(1)` 命中哪一条由数据库决定 ⇒ 同一枚微信可能稳定登进两个不同账号。
-- 同表另一格 `user_sk` 是有 `user_sk_key_unique` 唯一索引的,这不是风格差异,是这一族漏了。
--
-- 为什么是**部分**唯一索引:`deleted_at` 是软删,解绑留痕要能继续存在;
-- 而 `open_id` 可空(历史行),PG 的唯一索引对 NULL 视为互不相等,
-- 所以谓词里显式把空串/NULL 排除在约束之外 —— 那两型由代码层判据堵
-- (`apps/api` 侧 `requireWechatField` / 回调空主体标识前置闸,均带"副作用没发生"断言)。
--
-- 落地前基线(同一轮现读 `ihui_dev`):活行里同 (platform, open_id) 重复组 = 0,
-- open_id 为空的活行 = 0 ⇒ 建索引不会因存量冲突失败。若哪天在非空库上重放本文件,
-- `IF NOT EXISTS` 保证幂等,而真重复会让 CREATE 明确失败(响亮,不静默降级)。

CREATE UNIQUE INDEX IF NOT EXISTS user_third_party_platform_openid_live_uidx
  ON "user_third_party_accounts" ("platform", "open_id")
  WHERE "deleted_at" IS NULL
    AND "open_id" IS NOT NULL
    AND "open_id" <> '';
