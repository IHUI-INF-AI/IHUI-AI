-- P0-8 第九批(2026-11-23):代码关系边表补过期列。
--
-- 背景:边与切片**同事务写入、同一清除面、同一保留期语义**,但只有 codebase_chunks
-- 有 expires_at。路由层因此刻意不透传 retentionDays(见 v1-codebase-search.ts 第七八批
-- 注释原话"retentionDays 位保持缺省")。一旦透传而边表没有该列,读面过滤只能覆盖切片
-- ⇒ 调用图会持续命中已过期行("设了保留期却不遵守"),比没有保留期更糟。
--
-- 存量边不回填:迁移前的行没有保留期事实,回填等于给它编造一个到期时刻。
-- NULL 按永不过期处理(与 codebase_chunks 列语义一致:仅显式长期保留)。
ALTER TABLE "codebase_edges" ADD COLUMN IF NOT EXISTS "expires_at" timestamp with time zone;

-- 清理任务驱动索引:purgeExpired 只扫已到期那一小撮,不扫全表(与 chunks 同形)。
CREATE INDEX IF NOT EXISTS "ix_codebase_edges_expires_at" ON "codebase_edges" ("expires_at");
