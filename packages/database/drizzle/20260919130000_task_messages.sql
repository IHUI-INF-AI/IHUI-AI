-- D25 统一任务运行时看板:任务消息表(task_messages),支撑 @任务引用跨任务发消息。
-- from_type: user|agent|system;mentions jsonb 存 @任务引用解析结果(自由引用不设 FK,校验在应用层)。
-- 幂等:IF NOT EXISTS。外键 agent_tasks(级联删除)/users(SET NULL)。

CREATE TABLE IF NOT EXISTS "task_messages" (
  "id" uuid PRIMARY KEY DEFAULT gen_random_uuid() NOT NULL,
  "task_id" uuid NOT NULL REFERENCES "agent_tasks" ("id") ON DELETE CASCADE,
  "from_type" varchar(16) NOT NULL,
  "from_id" varchar(128),
  "content" text NOT NULL,
  "mentions" jsonb DEFAULT '[]'::jsonb NOT NULL,
  "created_by" uuid REFERENCES "users" ("id") ON DELETE SET NULL,
  "created_at" timestamp with time zone DEFAULT now() NOT NULL
);
CREATE INDEX IF NOT EXISTS "task_messages_task_idx" ON "task_messages" ("task_id");
CREATE INDEX IF NOT EXISTS "task_messages_created_idx" ON "task_messages" ("created_at");
CREATE INDEX IF NOT EXISTS "task_messages_from_idx" ON "task_messages" ("from_type", "from_id");
