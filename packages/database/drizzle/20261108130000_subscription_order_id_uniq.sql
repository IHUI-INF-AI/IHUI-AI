-- F-147 + F-689:支付回调/主动查单重放时,同一订单只允许发一张 VIP 卡 / 一条开发者订阅。
-- 应用层已改为 INSERT ... ON CONFLICT (order_id) DO NOTHING,并带 fromStatus(pending→paid) 守卫;
-- 这里补库侧唯一约束作为最后一道闸。新增迁移,不改历史迁移。
--
-- 历史脏数据:此前无唯一约束,重放可能已落重复行。建唯一索引前先去重,
-- 保留 end_time 最大的一行(权益不缩短),end_time 相同时保留物理顺序最后一行。
--
-- 上线运维动作:
-- 1) 去重是不可逆删除,执行前先备份:
--    CREATE TABLE user_vips_bak_20261108 AS SELECT * FROM user_vips;
--    CREATE TABLE developer_subscriptions_bak_20261108 AS SELECT * FROM developer_subscriptions;
-- 2) CREATE UNIQUE INDEX 非 CONCURRENTLY,会短暂持表锁,建议低峰执行。
-- 3) 回滚:DROP INDEX IF EXISTS "user_vips_order_id_uniq";
--    DROP INDEX IF EXISTS "ix_developer_subscriptions_order_id_uniq";
DELETE FROM "user_vips" a
USING "user_vips" b
WHERE a."order_id" IS NOT NULL
  AND a."order_id" = b."order_id"
  AND (a."end_time" < b."end_time"
       OR (a."end_time" = b."end_time" AND a."ctid" > b."ctid"));

DELETE FROM "developer_subscriptions" a
USING "developer_subscriptions" b
WHERE a."order_id" IS NOT NULL
  AND a."order_id" = b."order_id"
  AND (a."end_time" < b."end_time"
       OR (a."end_time" = b."end_time" AND a."ctid" > b."ctid"));

CREATE UNIQUE INDEX IF NOT EXISTS "user_vips_order_id_uniq"
  ON "user_vips" USING btree ("order_id");

CREATE UNIQUE INDEX IF NOT EXISTS "ix_developer_subscriptions_order_id_uniq"
  ON "developer_subscriptions" USING btree ("order_id");
