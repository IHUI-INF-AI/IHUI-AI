-- Migration 20261109010000: 人事考勤板块补齐(部门树外键 + RBAC 权限点)
-- 创建时间: 2026-11-09
-- 描述: 20261109000000_hr_attendance 落表时漏了两处,本迁移前向补齐(不改已入库那份):
--       1) hr_department.parent_id 在 schema(hr-ai-management.ts)里声明了自引用外键
--          (onDelete: 'set null'),迁移里只建了普通 uuid 列 ⇒ 库层缺引用完整性,
--          且与那份迁移头注「逐字对齐」言行不符。
--       2) apps/api/src/routes/hr-attendance.ts 的两档闸门只认 hr:attendance:view|manage,
--          而这两个权限点从未写入 permissions 表(后台只有角色关联的全量替换端点,
--          没有创建权限点的入口)⇒ 非系统管理员角色无法被授予,HR 端点恒 403。
--
-- 幂等安全:外键用 pg_constraint 守门;权限点用 ON CONFLICT (name) DO NOTHING。
-- 只补权限点,不建角色、不绑定用户(与 seed-rbac-teacher.ts 的分工一致)。

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conname = 'hr_department_parent_id_fkey'
      AND conrelid = 'hr_department'::regclass
  ) THEN
    ALTER TABLE "hr_department"
      ADD CONSTRAINT "hr_department_parent_id_fkey"
      FOREIGN KEY ("parent_id") REFERENCES "hr_department" ("id") ON DELETE SET NULL;
  END IF;
END $$;

INSERT INTO "permissions" ("name", "display_name", "resource", "action", "description")
VALUES
  ('hr:attendance:view', '人事考勤只读', 'hr:attendance', 'view',
   '人事考勤读面:部门/员工/考勤规则/考勤记录/统计/请假列表'),
  ('hr:attendance:manage', '人事考勤管理', 'hr:attendance', 'manage',
   '人事考勤写面:部门与员工建档/规则 upsert/缺勤补录/请假审批')
ON CONFLICT ("name") DO NOTHING;
