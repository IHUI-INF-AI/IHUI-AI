-- 号池签到历史表（2026-11-17 立）
--
-- 立因：对标 qoder2api-hub 的「签到连续天数」那一格。本仓此前只留最近一条签到记录
-- （ai-service pool_status.lastRecord / relay-account-pool-reconcile 的 CheckinLastRecord），
-- 没有历史序列 ⇒ 连续天数无从算起。
--
-- 形态要点：
--   ① 一天一条，(account_id, day) 唯一 —— 10:05 主跑 + 11:00/12:30 补跑不会记三条；
--   ② day 是 UTC+8 归属日（官方活动 10:00 才开放，跨午间的补跑归同一自然日）；
--   ③ 不建外键：账号删除后历史保留（删号不该抹掉「这台机器签过几天」的事实）。
create table if not exists "ai_relay_checkin_history" (
	"id" uuid PRIMARY KEY DEFAULT gen_random_uuid() not null,
	"account_id" uuid not null,
	"provider_code" varchar(64) not null,
	"day" varchar(10) not null,
	"status" varchar(16) not null,
	"message" text,
	"created_at" timestamp with time zone DEFAULT now() not null
);
