-- 上游错误透传规则(2026-09-16 立,五轮补强,对标竞品 /error-passthrough-rules)。
-- 定义上游错误如何呈现给下游:按 upstream_status(+keyword)匹配,输出 downstream_status
-- 与 message_template(含 {upstream} 占位符);priority 大者优先,取首条启用规则。
-- 幂等:IF NOT EXISTS。

CREATE TABLE IF NOT EXISTS "relay_error_passthrough_rules" (
  "id" uuid PRIMARY KEY DEFAULT gen_random_uuid() NOT NULL,
  "upstream_status" integer NOT NULL,
  "keyword" varchar(128),
  "downstream_status" integer NOT NULL,
  "message_template" varchar(500) NOT NULL,
  "expose_upstream_message" boolean DEFAULT false NOT NULL,
  "priority" integer DEFAULT 0 NOT NULL,
  "enabled" boolean DEFAULT true NOT NULL,
  "remark" varchar(255),
  "created_at" timestamp with time zone DEFAULT now() NOT NULL,
  "updated_at" timestamp with time zone DEFAULT now() NOT NULL
);

CREATE INDEX IF NOT EXISTS "relay_error_passthrough_rules_enabled_idx" ON "relay_error_passthrough_rules" ("enabled");
CREATE INDEX IF NOT EXISTS "relay_error_passthrough_rules_status_idx" ON "relay_error_passthrough_rules" ("upstream_status");
