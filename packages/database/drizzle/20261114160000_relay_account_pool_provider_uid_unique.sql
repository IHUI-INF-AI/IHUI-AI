-- 号池唯一性不变量:同一个上游账号只允许存在一条续期链(2026-11-14 立)
--
-- 立因:两套部分唯一索引只约束「同一归属内」,跨归属(运营池 vs 个人池)在结构上允许同一
-- (provider_code, uid) 存在两行。轮换式 refreshToken(trae / codearts 等)是一次性票,两行
-- 各自续期必互相消费:先刷的吃掉票,后刷的必然 401 被摘除,随后每 24h 报一封「号池保活摘除」;
-- 非轮换平台(qoder)则被两行重复计额度。
-- 实证:2026-11-12 22:19 与 2026-11-14 15:40 两次自动入池,为 6 枚已在个人池的账号各造了
-- 一份运营池副本。
--
-- 本索引把「一个上游账号 = 一条续期链」提升为数据库不变量:任何写入方(未升级的旧二进制、
-- 手工 SQL、将来新代码)都插不进第二条,冲突一律 23505 失败闭合 —— 宁可导入报错,也不再有
-- 静默的跨池重复。
-- 与应用侧的分工:relay-account-pool-dedupe 负责「历史重复逐轮收敛」,本索引负责「收敛后
-- 永不复发」。两套部分唯一索引保留(已被本索引覆盖,写入开销可忽略,保留即零风险:生产可能
-- 仍跑着只认它们的旧二进制)。
--
-- 前置:建索引前必须无重复。发现重复即 fail-closed 并点名组数,由运维先跑收敛器;绝不在迁移
-- 里静默删行 —— 凭证搬运判据在应用侧单源,迁移不抄第二份(抄了必漂移)。
do $$
declare
  dup_groups int;
begin
  select count(*) into dup_groups
    from (
      select provider_code, uid
        from ai_relay_account_pool
       group by provider_code, uid
      having count(*) > 1
    ) d;
  if dup_groups > 0 then
    raise exception '号池存在 % 组跨池重复,拒绝建唯一索引;先用 relay-account-pool-dedupe 收敛再迁移', dup_groups;
  end if;
end $$;

create unique index if not exists ai_relay_account_pool_provider_uid_uniq
  on ai_relay_account_pool (provider_code, uid);
