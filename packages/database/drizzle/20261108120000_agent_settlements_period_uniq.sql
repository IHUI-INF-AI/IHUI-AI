-- F-228:结算记录补真实账期,并用 (order_no, period) 唯一约束承担幂等。
--
-- 背景:此前一个订单跨月只落一条(旧实现同 order_no 预读去重),或重复回调落多行,
-- 金额也没有按期切分。应用层已改为按自然月切分并把账期写入 period;
-- 幂等改为 INSERT ... ON CONFLICT (order_no, period) DO NOTHING。
-- 历史行的 period 保持 NULL(不回溯编造账期):唯一索引对 NULL 不冲突,不影响新写入。
--
-- 上线运维动作:
-- 1) 本 DDL 为普通 ALTER/CREATE INDEX(非 CONCURRENTLY),会短暂持表锁,建议低峰执行。
-- 2) 回滚:DROP INDEX IF EXISTS "agent_settlements_order_period_uniq";
--    ALTER TABLE "agent_settlements" DROP COLUMN IF EXISTS "period";
ALTER TABLE "agent_settlements"
  ADD COLUMN IF NOT EXISTS "period" varchar(7);

CREATE UNIQUE INDEX IF NOT EXISTS "agent_settlements_order_period_uniq"
  ON "agent_settlements" USING btree ("order_no", "period");
