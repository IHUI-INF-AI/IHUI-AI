-- 用户多邮箱表(2026-09-19 立,低余额通知多邮箱支持)。
--
-- 背景:
--   余额不足邮件通知此前只发 users.email 单邮箱;用户存在配置多个
--   接收邮箱的需求。新增 user_emails 存附加邮箱,
--   应用层将 users.email 与本表合并去重后发送(主邮箱优先)。
--
-- 向后兼容:纯新增表,既有链路行为不变;表为空时通知行为与单邮箱完全一致。
-- 幂等:全部 IF NOT EXISTS。

CREATE TABLE IF NOT EXISTS "user_emails" (
  "id" uuid PRIMARY KEY DEFAULT gen_random_uuid() NOT NULL,
  "user_id" uuid NOT NULL REFERENCES "users" ("id") ON DELETE CASCADE,
  "email" varchar(255) NOT NULL,
  "is_primary" boolean DEFAULT false NOT NULL,
  "created_at" timestamp with time zone DEFAULT now() NOT NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS "user_emails_email_key" ON "user_emails" ("email");
CREATE INDEX IF NOT EXISTS "user_emails_user_idx" ON "user_emails" ("user_id");
