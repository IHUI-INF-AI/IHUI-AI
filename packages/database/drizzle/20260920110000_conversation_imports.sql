-- 外部会话导入功能(2026-09-20,D28)
-- 支持 Claude Code / Codex / Cursor / Aider 会话导出文件迁入站内聊天(迁入即用)
--
-- 1. 新建 conversation_imports 表(导入批次记录,每次 commit 导入一个会话写一条)
-- 2. 创建索引(owner / 时间维度查询导入历史)

-- 1. 新建 conversation_imports 表
CREATE TABLE IF NOT EXISTS "conversation_imports" (
  "id" VARCHAR(64) PRIMARY KEY,
  "owner_uuid" VARCHAR(64) NOT NULL,
  "source" VARCHAR(32) NOT NULL,          -- claude_code | codex | cursor | aider
  "conversation_id" UUID,
  "file_name" VARCHAR(500),
  "parsed_count" INTEGER NOT NULL DEFAULT 0,
  "imported_count" INTEGER NOT NULL DEFAULT 0,
  "failed_count" INTEGER NOT NULL DEFAULT 0,
  "status" VARCHAR(16) NOT NULL,
  "error_message" TEXT,
  "imported_at" TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS "ix_conversation_imports_owner"
  ON "conversation_imports"("owner_uuid");
CREATE INDEX IF NOT EXISTS "ix_conversation_imports_imported_at"
  ON "conversation_imports"("imported_at");

COMMENT ON TABLE "conversation_imports" IS '外部会话导入批次记录(每次 commit 导入一个会话写一条)';
COMMENT ON COLUMN "conversation_imports"."source" IS '导入来源: claude_code | codex | cursor | aider';
COMMENT ON COLUMN "conversation_imports"."conversation_id" IS '导入生成的 chat_conversations.id(审计回溯,无外键,会话删除不影响本记录)';
COMMENT ON COLUMN "conversation_imports"."parsed_count" IS '本次解析出的消息条数';
COMMENT ON COLUMN "conversation_imports"."status" IS 'success | partial | failed';
