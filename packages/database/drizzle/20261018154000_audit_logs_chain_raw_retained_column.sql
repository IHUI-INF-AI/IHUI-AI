-- G-790 A5(2026-10-18):audit_logs_chain 补 raw_retained 判别列,并按既有 JSON 真值回填。
--
-- 为什么这张**哈希链表**可以安全加列(票面点名的前置,本轮已用代码证掉):
--   apps/api/src/utils/audit-chain.ts:51  computeHash(prevHash, JSON.stringify(AuditEntry))
--   —— 哈希输入只有 prev_hash 与 entry 的 action/resourceType/resourceId/userId/details/ip/occurredAt;
--   表里 user_agent、result 两列本来就在哈希输入之外。新列同理不进哈希 ⇒ 既有行的 current_hash 一字不改。
--   且本迁移只 ADD COLUMN + 读 metadata 回填,**不写 metadata** ⇒ 不触发本 job 的 rechain 路径。
--
-- 默认 true 是把"缺键"当作"原文仍在",与旧谓词 COALESCE(metadata->>'rawRetained','true') <> 'false' 同形;
-- 若默认 false,新入库的行会永远不被候选筛选中,原文清除会**静默失效**(比判错更坏)。
ALTER TABLE "audit_logs_chain" ADD COLUMN IF NOT EXISTS "raw_retained" boolean NOT NULL DEFAULT true;

-- 回填判定与旧谓词逐字同形:只有"metadata 是对象且 rawRetained 显式为 'false'"的行才算已清除。
UPDATE "audit_logs_chain"
   SET "raw_retained" = false
 WHERE "raw_retained" = true
   AND jsonb_typeof("metadata") = 'object'
   AND "metadata" ->> 'rawRetained' = 'false';
