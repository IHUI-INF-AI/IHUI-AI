-- 号池双池并存(2026-10-23 立):ai_relay_account_pool.owner_user_id
-- NULL = 运营级全局池(存量行全部归此档,行为零变化);
-- 非 NULL = 平台用户个人号池,只服务本人(转发选号按 owner 过滤、签到同步同 owner)。
-- 唯一性拆成两个部分唯一索引:运营池内 (provider_code, uid) 唯一;
-- 个人池内 (owner_user_id, provider_code, uid) 唯一 —— 不同用户可各自持有同一上游账号。
-- 幂等写法(本仓手写迁移口径,同 20261023121500_relay_account_pool_cred_version.sql)。

ALTER TABLE ai_relay_account_pool
    ADD COLUMN IF NOT EXISTS owner_user_id varchar(64);

ALTER TABLE ai_relay_account_pool
    DROP CONSTRAINT IF EXISTS ai_relay_account_pool_provider_uid_unique;

CREATE UNIQUE INDEX IF NOT EXISTS ai_relay_account_pool_ops_provider_uid_uniq
    ON ai_relay_account_pool (provider_code, uid)
    WHERE owner_user_id IS NULL;

CREATE UNIQUE INDEX IF NOT EXISTS ai_relay_account_pool_user_provider_uid_uniq
    ON ai_relay_account_pool (owner_user_id, provider_code, uid)
    WHERE owner_user_id IS NOT NULL;

CREATE INDEX IF NOT EXISTS ai_relay_account_pool_owner_idx
    ON ai_relay_account_pool (owner_user_id);
