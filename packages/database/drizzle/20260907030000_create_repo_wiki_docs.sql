-- 新增 Repo Wiki 文档表 repo_wiki_docs(2026-09-07 立,Repo Wiki MVP)。
--
-- 背景:对标 Qoder 的 Repo Wiki——自动把代码仓库生成架构/模块知识库文档。
-- 前端从用户工作区收集文件清单与关键文件内容 → 后端调 LLM 生成
-- "仓库总览 + 模块文档"并落库到本表 → 前端浏览生成的 Wiki(markdown 渲染)。
--
-- 设计要点:
-- 1. user_id 可空:NULL 表示全局 wiki(登录用户均可见);个人 wiki 按用户隔离。
-- 2. kind 区分文档粒度:'overview'(仓库总览,module_path 为 NULL) / 'module'(模块文档,module_path 存模块名)。
-- 3. 全程幂等(CREATE TABLE IF NOT EXISTS / CREATE INDEX IF NOT EXISTS),重复执行安全;无数据迁移。

CREATE TABLE IF NOT EXISTS "repo_wiki_docs" (
	"id" uuid PRIMARY KEY DEFAULT gen_random_uuid() NOT NULL,
	"user_id" uuid,
	"repo_name" varchar(200) NOT NULL,
	"kind" varchar(20) DEFAULT 'overview' NOT NULL,
	"module_path" varchar(500),
	"title" varchar(300) NOT NULL,
	"content" text NOT NULL,
	"model" varchar(128),
	"file_count" integer DEFAULT 0 NOT NULL,
	"generated_at" timestamp with time zone DEFAULT now() NOT NULL,
	"created_at" timestamp with time zone DEFAULT now() NOT NULL,
	"updated_at" timestamp with time zone DEFAULT now() NOT NULL
);
