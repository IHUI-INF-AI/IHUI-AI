-- 出口代理池表(2026-10-22 立):共享代理轮换池,账号自带 proxyUrl 优先,否则从池轮换取 active 代理。
-- status:active/exhausted/dead;fail_count 连续失败计数;bound_account_id 绑定账号;last_picked_at 轮换游标。
-- 幂等写法(本仓手写迁移口径,同 20261022220000_create_ai_relay_account_pool.sql)。

CREATE TABLE IF NOT EXISTS "ai_relay_proxy_pool" (
  "id" uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  "proxy_url" text NOT NULL,
  "provider_code" varchar(64),
  "status" varchar(16) DEFAULT 'active' NOT NULL,
  "fail_count" integer DEFAULT 0 NOT NULL,
  "last_checked_at" timestamp with time zone,
  "bound_account_id" uuid,
  "last_picked_at" timestamp with time zone,
  "created_at" timestamp with time zone DEFAULT now() NOT NULL,
  "updated_at" timestamp with time zone DEFAULT now() NOT NULL,
  CONSTRAINT "ai_relay_proxy_pool_proxy_url_unique" UNIQUE ("proxy_url")
);

CREATE INDEX IF NOT EXISTS "ai_relay_proxy_pool_status_idx" ON "ai_relay_proxy_pool" ("status");
