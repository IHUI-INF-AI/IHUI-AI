-- 补偿迁移(2026-11-07): 补 crash_reports.user_id → users(id) 外键
-- 证据: packages/database/src/schema/crash-reports.ts:26 声明 onDelete set null,库内 pg_constraint 只有 pkey/notnull;
-- dev 实测 total=85 with_uid=0 orphan=0,故先清孤儿再 ADD CONSTRAINT,存量库可安全执行。
DO $$
BEGIN
  IF to_regclass('public.crash_reports') IS NOT NULL
     AND to_regclass('public.users') IS NOT NULL
     AND NOT EXISTS (
       SELECT 1 FROM pg_constraint
       WHERE conname = 'crash_reports_user_id_users_id_fk'
         AND conrelid = 'public.crash_reports'::regclass
     )
  THEN
    UPDATE "public"."crash_reports" c
       SET "user_id" = NULL
     WHERE c."user_id" IS NOT NULL
       AND NOT EXISTS (SELECT 1 FROM "public"."users" u WHERE u.id = c."user_id");
    ALTER TABLE "public"."crash_reports"
      ADD CONSTRAINT "crash_reports_user_id_users_id_fk"
      FOREIGN KEY ("user_id") REFERENCES "public"."users"("id") ON DELETE SET NULL;
  END IF;
END $$;--> statement-breakpoint
