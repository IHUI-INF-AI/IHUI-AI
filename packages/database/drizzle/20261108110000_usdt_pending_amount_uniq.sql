-- SDB-27:同一收款地址下,同一网络 + 同一应收金额同时只允许存在一个 pending 充值订单。
--
-- 背景:平台全站共用一个 USDT 收款地址(TRC20/ERC20),到账只能靠「金额」归属到订单。
-- 若允许两笔 pending 订单同额,他人付款会被先被轮询到的订单抢绑(支付了却记到别人账上)。
-- 应用层 createUsdtPayment 给每笔订单叠加 0.00025 USDT × 1..39 档尾差,本索引是并发兜底:
-- 两个并发创建请求撞同一档时,后者 INSERT 触发 23505,应用层换下一档重试。
-- pending 行一旦 confirmed / expired 即离开部分索引,金额槽位自动释放,不影响后续订单。
--
-- 上线运维动作(必须):
-- 1) 执行前确认没有重复 pending 金额,否则本 DDL 会失败:
--      SELECT network, amount, count(*) FROM usdt_payments
--       WHERE status = 'pending' GROUP BY 1,2 HAVING count(*) > 1;
--    若存在重复:等 30 分钟过期窗口后由轮询置 expired,或人工把这些行置 expired,
--    再执行本迁移(不要删行,历史订单要留证据)。
-- 2) 本索引为事务内普通 CREATE INDEX(非 CONCURRENTLY),会短暂持表锁;建议低峰执行。
-- 3) 回滚:DROP INDEX IF EXISTS "usdt_payments_pending_amount_uniq";(仅索引,不动数据)
CREATE UNIQUE INDEX IF NOT EXISTS "usdt_payments_pending_amount_uniq"
  ON "usdt_payments" USING btree ("network", "amount")
  WHERE "status" = 'pending';
