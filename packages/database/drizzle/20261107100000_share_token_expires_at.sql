-- BUG-50 补记迁移(2026-11-07):`chat_conversations.share_token_expires_at` 在 TS schema
-- (packages/database/src/schema/chat.ts)与 apps/api/src/db/chat-queries.ts 已被读写,
-- 但 drizzle 迁移链此前没有它的出处 —— ihui_dev 库里的列是 2026-11-05 一份未入库的
-- 临时迁移件同事务建列并记账(hash 44ef71cb757e…)留下的;journal 无对应条目。
-- 后果:任何按迁移链新建的库都会在分享链接读写处 500。此处按迁移链正路补建。
--
-- ① 建列:IF NOT EXISTS 保证已存在该列的环境(含 ihui_dev)重复执行为 no-op。
-- ② 回填:历史存量 share_token 的过期时间为 NULL(= 旧行为下永久可读),按 apps/api 的
--    默认有效期 30 天(chat-queries.ts 的 setConversationShareToken 默认 expiresInDays=30)
--    统一回填为有限期,与 findConversationByShareToken 的 `expiresAt > now()` 判据对齐
--    (该判据本就把 NULL 视为过期,回填只是把"静默失效"改成明确的 30 天窗口)。
-- 不删除、不覆盖任何既有列/索引,share_token 值本身不动。
ALTER TABLE "chat_conversations"
  ADD COLUMN IF NOT EXISTS "share_token_expires_at" timestamp with time zone;

UPDATE "chat_conversations"
   SET "share_token_expires_at" = now() + interval '30 days'
 WHERE "share_token" IS NOT NULL
   AND "share_token_expires_at" IS NULL;
