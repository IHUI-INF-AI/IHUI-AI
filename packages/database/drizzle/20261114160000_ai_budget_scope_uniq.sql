-- F-588:AI 预算 upsert 无唯一约束，并发激活产生重复预算行
-- 根因见 PROJECT_PLAN.md「缺陷普查 API F-588」与 docs/tickets/2026-11/findings-api.md#F-588。
-- upsertUserAiBudget 原为先查后插,无事务/无 ON CONFLICT;ai_budget_scope_idx 是普通 index。
-- schema 已把 (scope, scope_key, model) 提为唯一索引(nullsNotDistinct)。
-- 本迁移:① 清理存量重复行(同 scope+scope_key+model 保留 id 最小一条);② 把普通索引
--   替换为唯一索引。幂等安全:去重 WHERE 守门;索引 IF NOT EXISTS,可安全重复执行。
-- 与 packages/database/src/schema/ai-cost.ts 的 ai_budget_scope_idx 逐字对齐。

-- ============ ① 清理存量重复(保留 id 最小一条) ============
DELETE FROM "ai_budgets" a
USING "ai_budgets" b
WHERE a."scope" IS NOT DISTINCT FROM b."scope"
  AND a."scope_key" IS NOT DISTINCT FROM b."scope_key"
  AND a."model" IS NOT DISTINCT FROM b."model"
  AND a."id" > b."id";

-- ============ ② 删除旧普通索引(若存在),避免与唯一索引重复 ============
DROP INDEX IF EXISTS "ai_budget_scope_idx";

-- ============ ③ 建唯一索引(nullsNotDistinct,与 schema 逐字一致) ============
CREATE UNIQUE INDEX IF NOT EXISTS "ai_budget_scope_idx"
  ON "ai_budgets" ("scope", "scope_key", "model")
  NULLS NOT DISTINCT;
