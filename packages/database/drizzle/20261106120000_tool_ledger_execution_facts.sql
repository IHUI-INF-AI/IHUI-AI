-- 批次 2(2026-11-06):工具账执行事实四列(cwd / exitCode / outputComplete / terminalReason)。
-- 背景:批次 1 已有「谁、哪次会话、哪个工具、权限怎么走、结果如何」,但缺执行环境与收尾原因,
-- 无法回答"这条账为什么结束、在哪个目录跑、输出是否完整"。
-- 取舍:
--   1) 只加列不改既有列语义;新列全部可空 = 未观测(不把 NULL 解释成 0/成功);
--   2) terminalReason 用 CHECK 封闭 8 档(TS zod enum 为权威,Python 镜像同集);
--   3) cwd 存原样声明/回报值(1024 上限),不从路径反推。

ALTER TABLE "tool_invocation_ledger" ADD COLUMN "cwd" varchar(1024);
ALTER TABLE "tool_invocation_ledger" ADD COLUMN "exit_code" integer;
ALTER TABLE "tool_invocation_ledger" ADD COLUMN "output_complete" boolean;
ALTER TABLE "tool_invocation_ledger" ADD COLUMN "terminal_reason" varchar(24);

ALTER TABLE "tool_invocation_ledger"
  ADD CONSTRAINT "tool_invocation_ledger_terminal_reason_check"
  CHECK (
    "terminal_reason" is null
    OR "terminal_reason" in (
      'completed', 'error', 'rejected_by_user', 'approval_timeout',
      'blocked', 'cancelled', 'timeout', 'unknown'
    )
  );
