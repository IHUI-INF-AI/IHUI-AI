-- sms_receive_history —— 短信接码历史台账(管理员短信接码 /admin/sms-receive)
--
-- 背景:需要回答"取到的手机号有没有接过某平台的码/是否已在该平台注册过"。
-- d1jiema 平台 queryUsed 只返回 24h 内最多 100 条且限频 1 次/分钟,无法长期留痕;
-- 因此收码成功时本地落一条流水,取号后按号码回查历史。
--
-- 口径说明(逐条都是刻意选择):
--   ① platform 从短信原文的【】提取(如【trae】→ trae),不建枚举:平台名开放集合。
--   ② usage_kind varchar(16) 不建 pg enum:register/login/other,避免加值要改类型。
--   ③ 不关联 user_id:这是管理员页的接码台账,单管理员场景,无多租户归属。
--   ④ phone+received_at 复合索引:唯一的查询模式是"某号码的最近历史"。
--   ⑤ 全表幂等:CREATE TABLE IF NOT EXISTS + CREATE INDEX IF NOT EXISTS。
-- ============================================================================

--> statement-breakpoint
CREATE TABLE IF NOT EXISTS "sms_receive_history" (
	"id" uuid PRIMARY KEY DEFAULT gen_random_uuid() NOT NULL,
	"phone" varchar(20) NOT NULL,
	"keyword" varchar(64),
	"platform" varchar(64),
	"usage_kind" varchar(16) DEFAULT 'other' NOT NULL,
	"sms_code" varchar(16),
	"sms_raw" text NOT NULL,
	"received_at" timestamp with time zone DEFAULT now() NOT NULL
);

--> statement-breakpoint
CREATE INDEX IF NOT EXISTS "sms_receive_history_phone_received_idx" ON "sms_receive_history" USING btree ("phone","received_at" DESC);

--> statement-breakpoint
CREATE INDEX IF NOT EXISTS "sms_receive_history_platform_idx" ON "sms_receive_history" USING btree ("platform");
