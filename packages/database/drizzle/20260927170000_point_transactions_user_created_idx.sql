-- D64 ① Credits 热力图日聚合(GET /api/credits/usage/daily)的必要索引补齐。
-- 聚合口径:WHERE user_id = ? AND type = 'spend' AND created_at >= ? GROUP BY UTC 日
--   (apps/api/src/services/credits-usage-service.ts);
-- 积分流水端点同形态:WHERE user_id [AND type/source] ORDER BY created_at DESC
--   (apps/api/src/db/gamification-queries.ts:324-333)。
-- 立门前实测:point_transactions 除主键外零索引(0004/0043 两处迁移只建表与外键约束;
--   Postgres 不为 REFERENCES 自动建索引),上述两类查询均为全表扫描。
-- (user_id, created_at) 联合一次覆盖两种形态:user_id 等值命中后,区间谓词与倒序都
--   直接吃索引序;type/source 谓词逐行过滤(单用户流水体量有限,不再为 type 加一档,
--   以免流水端点少了 type 条件时用不上同一索引)。
-- 幂等:CREATE INDEX IF NOT EXISTS,可重复执行零副作用。
-- 锁提示同 20260906210000_add_perf_indexes.sql 头注:生产在线建索引建议 CONCURRENTLY,
--   但该语法不可在事务内执行,drizzle-kit migrate 走普通 CREATE INDEX。
CREATE INDEX IF NOT EXISTS "ix_point_transactions_user_created_at"
  ON "point_transactions" ("user_id", "created_at");
