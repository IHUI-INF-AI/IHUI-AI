-- F-588:AI 预算 upsert 无唯一约束，并发激活产生重复预算行。
-- 收敛迁移:把 ai_budgets 的定位键 (scope, scope_key, model) 统一为一条
-- NULLS NOT DISTINCT 唯一索引 "ai_budget_scope_idx",与
-- packages/database/src/schema/ai-cost.ts 声明按行为规格。
--
-- 背景:历史上有两套 F-588 方案 ——
--   · 20261114100000 走两条部分唯一索引(no_model / model);
--   · 20261114160000 走单条 NULLS NOT DISTINCT 唯一索引。
-- schema 现以单条 NULLS NOT DISTINCT 为准(用户/租户级预算 model 多为 null,
-- 普通唯一索引对 NULL 不去重,防不住并发激活)。本迁移保证无论此前跑到哪一版,
-- 最终态都收敛到 schema 声明的那一条唯一索引,并清掉已废弃的部分索引避免漂移。
-- 幂等:去重 WHERE 守门;全部 IF EXISTS / IF NOT EXISTS,可安全重复执行。

-- ============ ① 清理存量重复(同 scope+scope_key+model 保留 id 最小一条) ============
DELETE FROM "ai_budgets" a
USING "ai_budgets" b
WHERE a."scope" IS NOT DISTINCT FROM b."scope"
  AND a."scope_key" IS NOT DISTINCT FROM b."scope_key"
  AND a."model" IS NOT DISTINCT FROM b."model"
  AND a."id" > b."id";

-- ============ ② 移除历史部分唯一索引(schema 已不再声明,避免漂移) ============
DROP INDEX IF EXISTS "ai_budget_scope_no_model_uniq";
DROP INDEX IF EXISTS "ai_budget_scope_model_uniq";

-- ============ ③ 建唯一索引(nullsNotDistinct,与 schema 逐字一致) ============
-- 先删同名普通索引(极早期 ai_budget_scope_idx 为普通 index),再建唯一索引。
DROP INDEX IF EXISTS "ai_budget_scope_idx";
CREATE UNIQUE INDEX IF NOT EXISTS "ai_budget_scope_idx"
  ON "ai_budgets" ("scope", "scope_key", "model")
  NULLS NOT DISTINCT;
