-- 20261023053000_api_logs_created_at_idx
--
-- 立因(2026-10-23 现读本机生产库 ihui_dev):
--   `api_logs` 是"谁来过"的唯一服务端真值底表(每条请求带 ip + user_agent),
--   现读 198082 行 / 46 MB,而 `pg_indexes` 里**只有主键** `api_logs_pkey` ——
--   一条二级索引都没有(建表迁移只写了列与外键;Postgres 不为 REFERENCES 自动建索引)。
--   后果全部按时间窗取数,却每一次都是全表扫:
--     · 访客指标小时任务:`WHERE created_at >= now() - make_interval(...)`
--       (apps/api/src/services/traffic-stats-service.ts);
--     · PII 保留期清理:`WHERE created_at < cutoff`
--       (apps/api/src/jobs/pii-retention-cleanup.ts 同族形态);
--     · 管理端「访客追踪 / 接口日志」按时间窗分页与 Top UA。
--   建门实测(EXPLAIN ANALYZE,24h 窗口):
--     Seq Scan on api_logs, actual time=23.1ms、Rows Removed by Filter=156108、
--     整条聚合 31.4ms、shared read=2072 buffers —— 读 15 万行只为丢掉。
--
-- 只建 created_at 一档,不顺手加别的:三处查询的公共谓词只有时间窗;按 status/user/UA
-- 的过滤都发生在时间窗**之内**(先缩窗再逐行判),再为它们各建一档是凭想象加索引。
--
-- 为什么是普通 CREATE INDEX 而不是 CONCURRENTLY:
--   1) CONCURRENTLY 在 PostgreSQL 里不可在事务/函数内执行,而 drizzle-kit migrate 把
--      每条 journal 化迁移包进一个事务 ⇒ 写成 CONCURRENTLY 会让整条迁移链卡死在这一条。
--      仓内已有专职通道处理这类:`scripts/manual-sql/*_CONCURRENTLY.sql`(不进 journal)。
--   2) 本表现读 46 MB / 19.8 万行,建索引是亚秒级、只在构建期持写锁;部署环在低峰跑,
--      锁窗可忽略。将来表到千万行级再要重建时,按 `scripts/manual-sql/` 的先例走
--      CONCURRENTLY,不要就地改本文件(已进 journal 的正文不可变)。
--
-- 幂等:IF NOT EXISTS,重复执行零副作用。
-- ============================================================================

CREATE INDEX IF NOT EXISTS "api_logs_created_at_idx" ON "api_logs" USING btree ("created_at");
