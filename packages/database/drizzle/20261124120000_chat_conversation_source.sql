-- 2026-11-24 立(机主令「所有接口所有功能全部多端互通,但要分好是从哪个端操作录入的」):
-- chat_conversations 增加来源端与源记录 id,作为三端统一会话表的「录入端」维度。
-- source 三值白名单 web / rn / miniapp;存量会话全部为 web 录入,故 DEFAULT 'web' 即正确回填。
-- source_ref:小程序收编时存 zhs_ai_user_model_chat_history.id;web/rn 自建会话为 NULL。
-- 幂等键 (user_id, source, source_ref) 用部分唯一索引,只约束 source_ref 非空的行,
-- 保证收编脚本/双写重跑不产生副本,同时不影响 web/rn 未带 ref 的自建会话。

ALTER TABLE "chat_conversations"
  ADD COLUMN IF NOT EXISTS "source" varchar(16) DEFAULT 'web' NOT NULL;

ALTER TABLE "chat_conversations"
  ADD COLUMN IF NOT EXISTS "source_ref" varchar(64);

CREATE UNIQUE INDEX IF NOT EXISTS "uq_chat_conversations_user_source_ref"
  ON "chat_conversations" ("user_id", "source", "source_ref")
  WHERE "source_ref" IS NOT NULL;

COMMENT ON COLUMN "chat_conversations"."source" IS
  '录入端:web / rn / miniapp(白名单,未知回填 web);只作展示与筛选,归属鉴权恒取 user_id';
COMMENT ON COLUMN "chat_conversations"."source_ref" IS
  '源系统记录 id(小程序 = zhs_ai_user_model_chat_history.id);与 source 组成收编幂等键,自建会话为 NULL';
