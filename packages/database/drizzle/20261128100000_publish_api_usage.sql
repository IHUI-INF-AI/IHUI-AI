CREATE TABLE IF NOT EXISTS "publish_api_usage_records" (
  "id" uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  "api_key_id" uuid NOT NULL,
  "user_id" uuid NOT NULL,
  "capability_scope" varchar(64) NOT NULL DEFAULT 'publish:submit',
  "action" varchar(32) NOT NULL,
  "task_id" varchar(64),
  "status_code" integer NOT NULL,
  "units" integer NOT NULL DEFAULT 1,
  "created_at" timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS "publish_api_usage_records_key_time_idx"
  ON "publish_api_usage_records" ("api_key_id", "created_at");

CREATE UNIQUE INDEX IF NOT EXISTS "publish_api_usage_records_task_action_uniq"
  ON "publish_api_usage_records" ("api_key_id", "action", "task_id");
