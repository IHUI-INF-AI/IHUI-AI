-- 根因见 PROJECT_PLAN.md「缺陷普查 API F-354」与 docs/tickets/2026-11/findings-api.md#F-354。
-- 本迁移:① 清理存量重复行(同一 news_id 保留最早 id 一条);② 补 news_id 唯一索引。
-- 幂等安全:去重用 WHERE 守门(仅删重复);索引用 IF NOT EXISTS,可安全重复执行。
-- 与 packages/database/src/schema/misc-extended-2.ts 的 .unique('news_tops_news_id_unique')
--   / .unique('news_recommends_news_id_unique') 逐字对齐(约束名一致)。
--
-- 执行方式:
--   pnpm tsx packages/database/scripts/apply-migration.mjs drizzle/20261113230000_news_top_recommend_uniq.sql

-- ============ ① news_tops 清理重复(news_id 重复时保留 id 最小的一条) ============
DELETE FROM "news_tops" a
USING "news_tops" b
WHERE a."news_id" = b."news_id"
  AND a."id" > b."id";

-- ============ ② news_recommends 清理重复 ============
DELETE FROM "news_recommends" a
USING "news_recommends" b
WHERE a."news_id" = b."news_id"
  AND a."id" > b."id";

-- ============ ③ 补唯一索引(与 schema 约束名逐字一致) ============
CREATE UNIQUE INDEX IF NOT EXISTS "news_tops_news_id_unique"
  ON "news_tops" ("news_id");
CREATE UNIQUE INDEX IF NOT EXISTS "news_recommends_news_id_unique"
  ON "news_recommends" ("news_id");
