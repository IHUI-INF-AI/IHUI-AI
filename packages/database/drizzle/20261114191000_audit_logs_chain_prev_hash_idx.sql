-- 病灶:SELECT_CHAIN_TAIL_SQL 用"未被任何行当 prev_hash 引用"取叶:
--   SELECT c.current_hash FROM audit_logs_chain c
--   WHERE NOT EXISTS (SELECT 1 FROM audit_logs_chain k WHERE k.prev_hash = c.current_hash)
--   ORDER BY c.seq DESC LIMIT 1
-- 该查询在 pg_advisory_xact_lock('audit_log_chain') 内执行(写入必须串行)。
-- 表上没有 prev_hash 索引时,执行计划退化为 Nested Loop Anti Join + Seq Scan(12 万行),
-- 每次写审计都要扫全表;写入速率低于到达速率 ⇒ advisory lock 队列无限增长
-- (实测 36 个会话排队 79s+),每个等待者都占一条池连接 ⇒ 连接池(max 40)耗尽
-- ⇒ 整个 API 的 DB 请求一起排队,表现为"进程周期性卡死"。
--
-- 补索引后反连接变成 Index Only Scan(实测链尾查询 1ms,队列立即排空)。
-- 锁与耗时:普通 CREATE INDEX 会短暂阻塞写(ACCESS EXCLUSIVE);12 万行实测 0.8s。
-- 大表请改用 manual-sql/20261114190500_audit_logs_chain_prev_hash_idx_CONCURRENTLY.sql
-- (CONCURRENTLY 必须在事务外执行,drizzle-kit 的事务会拒绝)。
-- 回滚:DROP INDEX IF EXISTS "idx_audit_chain_prev_hash";
CREATE INDEX IF NOT EXISTS "idx_audit_chain_prev_hash"
  ON "audit_logs_chain" USING btree ("prev_hash");
