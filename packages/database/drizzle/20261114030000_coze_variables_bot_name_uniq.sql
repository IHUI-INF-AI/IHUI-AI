-- F-355:coze_variables 缺 (bot_id, variable_name) 唯一约束，先查后插竞态
-- 根因见 PROJECT_PLAN.md「缺陷普查 API F-355」与 docs/tickets/2026-11/findings-api.md#F-355。
-- 本迁移:① 清理存量重复行(bot_id+variable_name 重复时保留 id 最小一条);② 补复合唯一索引。
-- 幂等安全:去重用 WHERE 守门(仅删重复);索引用 IF NOT EXISTS,可安全重复执行。
-- 与 packages/database/src/schema/misc-extended.ts 的
--   unique('coze_variables_bot_id_variable_name_unique') 约束名逐字对齐。

-- ============ ① 清理重复(同 bot 下同名变量保留 id 最小的一条) ============
DELETE FROM "coze_variables" a
USING "coze_variables" b
WHERE a."bot_id" = b."bot_id"
  AND a."variable_name" = b."variable_name"
  AND a."id" > b."id";

-- ============ ② 补复合唯一索引(与 schema 约束名逐字一致) ============
CREATE UNIQUE INDEX IF NOT EXISTS "coze_variables_bot_id_variable_name_unique"
  ON "coze_variables" ("bot_id", "variable_name");
