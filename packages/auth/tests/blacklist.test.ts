/**
 * DBG-26(2026-11-11 bug-hunt)回归锁:
 * TokenBlacklist.has 默认必须 fail-closed —— Redis 抖动/宕机时把 token 视为
 * 已吊销(拒绝放行),防止登出/踢下线吊销的 token 在故障期"复活"。
 * fail-open 只允许调用面显式传 failClosed=false。
 */
import { describe, it, expect } from 'vitest'
import type IORedis from 'ioredis'
import { TokenBlacklist } from '../src/blacklist'

const downRedis = {
  exists: async () => {
    throw new Error('ECONNREFUSED redis')
  },
} as unknown as IORedis

function redisReturning(existsResult: number): IORedis {
  return { exists: async () => existsResult } as unknown as IORedis
}

describe('TokenBlacklist.has 失败模式(DBG-26)', () => {
  it('默认 fail-closed:Redis 异常 ⇒ 视为已吊销(true,拒绝放行)', async () => {
    const bl = new TokenBlacklist(downRedis)
    expect(await bl.has('some-token')).toBe(true)
  })

  it('显式 failClosed=false:Redis 异常 ⇒ fail-open(false)', async () => {
    const bl = new TokenBlacklist(downRedis)
    expect(await bl.has('some-token', false)).toBe(false)
  })

  it('空 token 恒未吊销(即使默认 fail-closed 也不因空串拒绝)', async () => {
    const bl = new TokenBlacklist(downRedis)
    expect(await bl.has('')).toBe(false)
  })

  it('Redis 正常路径不受失败模式影响:exists=1→true,=0→false', async () => {
    expect(await new TokenBlacklist(redisReturning(1)).has('tok')).toBe(true)
    expect(await new TokenBlacklist(redisReturning(0)).has('tok')).toBe(false)
  })
})
