'use client'

/**
 * IconButton — 全项目统一图标按钮
 *
 * 样式 token 单一来源 = @ihui/design-tokens 的 icon-button.ts。
 *
 * 2026-09-17 用户指令:全项目图标按钮只有 **一种尺寸**(32×32),
 * 本组件不接受 size prop,禁止任何多档尺寸回潮。
 * 尺寸之外的自定义类(定位/状态高亮等)走 className 合并。
 */
import * as React from 'react'
import { iconButtonClasses, iconButtonIconClasses } from '@ihui/design-tokens'
import { cn } from '../lib/utils'

export type IconButtonProps = React.ButtonHTMLAttributes<HTMLButtonElement>

export const IconButton = React.forwardRef<HTMLButtonElement, IconButtonProps>(
  ({ className, children, type = 'button', ...props }, ref) => (
    <button ref={ref} type={type} className={cn(iconButtonClasses(), className)} {...props}>
      {React.Children.map(children, (child) => {
        if (React.isValidElement<{ className?: string }>(child)) {
          const cls = child.props.className
          return React.cloneElement(child as React.ReactElement<{ className?: string }>, {
            className: cn(iconButtonIconClasses(), cls),
          })
        }
        return child
      }) ?? null}
    </button>
  ),
)
IconButton.displayName = 'IconButton'
