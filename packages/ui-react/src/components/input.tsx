import * as React from 'react'
import { cn } from '../lib/utils'
import {
  INPUT_BORDER_WIDTH_PX,
  INPUT_HEIGHT_PX,
  INPUT_PADDING_X_PX,
  INPUT_RADIUS_TIER,
  INPUT_TEXT_TIER,
} from '@ihui/shared/ui/input-spec'

/**
 * 平台专属项(不下沉 input-spec,两端允许不同形,逐条登记):
 *  - `py-1` / `shadow-sm`:web 的纵向承载补偿与控件级投影通道;RN 的高度已由 INPUT_HEIGHT_PX
 *    单点定档(再给纵向内边距等于把同一段纵向空间定两次),RN 也没有控件投影通道;
 *  - `w-full`:web 的块级宽度承载;RN 的 TextInput 宽度由父容器决定,无此通道;
 *  - `transition-colors` / `focus-visible:*` / `file:*` / `disabled:*`:CSS 伪类 / 伪元素通道,仅 web;
 *  - `border-input`:边框**色**(web 走 CSS 变量,RN 走 nativewind 主题)⇒ 色值不下沉,只沉宽度;
 *  - 类名字面量:必须留在本文件 —— Tailwind 只扫本仓 ui-react 源,spec 文件不在扫描面内,
 *    拼串产不出规则;且必须是标准类,调用方的 className 覆盖才能经 cn 正常生效。
 *  ⇒ 取值档一律取自 input-spec,本文件只做"档 → 本端承载类"的映射。
 */
const HEIGHT_CLASS: Record<number, string> = { 36: 'h-9' }
const RADIUS_CLASS: Record<typeof INPUT_RADIUS_TIER, string> = { sm: 'rounded-sm' }
const PADDING_X_CLASS: Record<number, string> = { 12: 'px-3' }
const TEXT_CLASS: Record<typeof INPUT_TEXT_TIER, string> = { sm: 'text-sm' }
const BORDER_WIDTH_CLASS: Record<number, string> = { 1: 'border' }

const Input = React.forwardRef<HTMLInputElement, React.ComponentProps<'input'>>(
  ({ className, type, ...props }, ref) => {
    return (
      <input
        type={type}
        className={cn(
          'flex w-full bg-transparent py-1 shadow-sm transition-colors file:border-0 file:bg-transparent file:text-sm file:font-medium file:text-foreground placeholder:text-muted-foreground focus-visible:outline-none focus-visible:border-primary disabled:cursor-not-allowed disabled:opacity-50',
          HEIGHT_CLASS[INPUT_HEIGHT_PX],
          RADIUS_CLASS[INPUT_RADIUS_TIER],
          BORDER_WIDTH_CLASS[INPUT_BORDER_WIDTH_PX],
          PADDING_X_CLASS[INPUT_PADDING_X_PX],
          TEXT_CLASS[INPUT_TEXT_TIER],
          'border-input',
          className,
        )}
        ref={ref}
        {...props}
      />
    )
  },
)
Input.displayName = 'Input'

export { Input }
