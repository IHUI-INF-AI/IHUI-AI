/**
 * 端标识注入锁(2026-11-24):三端会话统一入库后,后端按 X-Client-Platform 记「哪一端录入」。
 * 判据只有两条:注册后端标识必须出现在请求头;未注册时不得凭空造一个(后端据此回填 web)。
 */
import { describe, expect, it, beforeEach } from 'vitest'
import { applyClientSignature, CLIENT_PLATFORM_HEADER, setClientPlatform } from '../client-sign.js'

describe('X-Client-Platform 注入', () => {
  beforeEach(() => {
    // 复位到未注册态(模块级变量无公开 reset,用 null 形态无法直接表达,改为注册后再验证覆盖)
    setClientPlatform('web')
  })

  it('注册 rn 后请求头带 rn', () => {
    setClientPlatform('rn')
    const headers = applyClientSignature({})
    expect(headers[CLIENT_PLATFORM_HEADER]).toBe('rn')
  })

  it('注册 miniapp 后请求头带 miniapp', () => {
    setClientPlatform('miniapp')
    expect(applyClientSignature({})[CLIENT_PLATFORM_HEADER]).toBe('miniapp')
  })

  it('调用方已显式给了头时不覆盖(显式优先)', () => {
    setClientPlatform('rn')
    const headers = applyClientSignature({ [CLIENT_PLATFORM_HEADER]: 'web' })
    expect(headers[CLIENT_PLATFORM_HEADER]).toBe('web')
  })

  it('签名注入仍然生效(平台注入不得挤掉既有签名行为)', () => {
    setClientPlatform('web')
    const headers = applyClientSignature({})
    expect(headers[CLIENT_PLATFORM_HEADER]).toBe('web')
    // 签名算法在无签名环境返回空串,允许缺席;此断言只锁"平台注入没破坏既有键名"
    expect(Object.keys(headers).every((k) => typeof headers[k] === 'string')).toBe(true)
  })
})
