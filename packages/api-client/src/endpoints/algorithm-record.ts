import type { ApiResult } from '@ihui/types'

import { fetchApi } from '../client.js'
import { buildQs } from '../utils.js'

export interface AlgorithmRecordItem {
  id: string
  kind: string
  algName: string
  category: string | null
  provider: string
  product: string | null
  purpose: string | null
  recordNo: string
  batch: string | null
  sourceUrl: string | null
}

export interface AlgorithmRecordStats {
  totalAll: number
  updatedAt: string | null
}

export interface AlgorithmKindCount {
  kind: string
  count: number
}

export interface AlgorithmRecordQueryResult {
  items: AlgorithmRecordItem[]
  total: number
  stats: AlgorithmRecordStats
  kindCounts: AlgorithmKindCount[]
  batches: string[]
}

export interface AlgorithmRecordSearchQuery {
  /** 关键字:算法名称/主体名称/备案编号/算法类别/应用产品 */
  q?: string
  /** algorithm_recommend | deep_synthesis */
  kind?: string
  batch?: string
  category?: string
  page?: number
  pageSize?: number
}

/** GET /algorithm-record/search —— 公开免登录,返回结构对齐 apps/api/src/services/algorithm-record-service.ts */
export async function searchAlgorithmRecords(
  query: AlgorithmRecordSearchQuery = {},
): Promise<ApiResult<AlgorithmRecordQueryResult>> {
  return fetchApi<AlgorithmRecordQueryResult>(`/algorithm-record/search${buildQs(query)}`)
}
