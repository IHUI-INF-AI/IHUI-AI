import type { ApiResult } from '@ihui/types'

import { fetchApi } from '../client'

/** 规格模板(对齐 @ihui/shared SpecTemplate,本地声明避免跨包依赖) */
export interface SpecTemplate {
  id: string
  name: string
  description: string
  sections: string[]
}

/** GET /api/spec/templates — 预置模板列表 */
export async function listSpecTemplates(): Promise<ApiResult<{ templates: SpecTemplate[] }>> {
  return fetchApi('/api/spec/templates')
}
