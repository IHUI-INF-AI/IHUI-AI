/**
 * 公开状态页端点(2026-10-21 立,守门 73 + AGENTS §3 共享层优先)
 *
 * 后端契约:`GET /api/public/status/models`(apps/api/src/routes/public-status.ts:270)。
 * 匿名可访问,后端带 30s Redis 缓存 + IP 限流;响应信封
 * `{ code, message, data: { models: PublicStatusModelItem[] } }`。
 *
 * 消费方:web `/status` 页「展开全部」按全量取数 —— 端内不得再裸 fetch 该路径。
 */
import type { ApiResult } from '@ihui/types'

import { fetchApi } from '../client.js'

/** 单模型可用性档位(与后端 ServiceStatus 逐值对齐) */
export type PublicStatusServiceStatus = 'operational' | 'degraded' | 'outage'

export interface PublicStatusModelItem {
  modelId: string
  displayName: string | null
  providerCode: string
  status: PublicStatusServiceStatus
  p95LatencyMs: number
  errorRate: number
  lastIncidentAt: string | null
}

export interface PublicStatusModelsPayload {
  models: PublicStatusModelItem[]
}

/** 获取公开模型可用性列表(匿名端点) */
export async function getPublicStatusModels(): Promise<ApiResult<PublicStatusModelsPayload>> {
  return fetchApi<PublicStatusModelsPayload>('/api/public/status/models')
}
