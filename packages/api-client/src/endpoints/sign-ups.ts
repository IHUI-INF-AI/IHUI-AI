/**
 * 报名记录端点 —— GET /api/sign-ups?userId=
 *
 * 后端事实源:apps/api/src/routes/sign-ups.ts:41-95(经 routes/index.ts:868 以 prefix '/api/sign-ups' 注册)。
 * 形状是"课程报名 + 试卷报名"两路聚合:lessonSignUps ⨝ lessons 与 examSignups ⨝ examPapers,
 * 各自过 LESSON_STATUS_MAP / EXAM_STATUS_MAP 归一到 draft|published|rejected|completed,
 * 再按 createdAt 倒序合并,返回 success({ list, total: list.length })。
 * 授权:非本人且非 admin 一律拒(sign-ups.ts:45-47),所以消费方必须显式传当前登录用户 id。
 */
import type { ApiResult } from '@ihui/types'

import { fetchApi } from '../client.js'

export type SignUpTargetType = 'lesson' | 'exam'
export type SignUpStatus = 'draft' | 'published' | 'rejected' | 'completed'

export interface SignUpRow {
  id: string
  targetTitle: string
  targetType?: SignUpTargetType
  status?: SignUpStatus
  createdAt?: string
}

export interface SignUpListData {
  list: SignUpRow[]
  total: number
}

/** 本人报名记录聚合列表 —— GET /api/sign-ups?userId= */
export async function getMySignUps(userId: string): Promise<ApiResult<SignUpListData>> {
  return fetchApi<SignUpListData>(`/api/sign-ups?userId=${encodeURIComponent(userId)}`)
}
