/**
 * 行为埋点上报端点(2026-10-26 立)。
 *
 * 端内(RN / 小程序 / 插件)上报 `page_time` 等事件必须走这里,不得手拼 baseUrl 直连后端
 * (守门 184)。批次形状与 web 端 `use-analytics` 完全一致 —— 服务端 `/analytics/track`
 * 只认 `{ events: [...] }`(顶层单事件那条分支是历史兼容面),两处必须同形。
 */

import { fetchApi } from '../client.js'

/** 与 web 端 AnalyticsEvent 同形;`value` 是数值型指标(如停留秒数),`label` 是页面路径。 */
export interface AnalyticsEventInput {
  name: string
  category?: string
  label?: string
  value?: number
  props?: Record<string, unknown>
}

export interface AnalyticsTrackResult {
  inserted?: number
}

/** 上报一批行为事件(匿名可用;服务端按请求头观测身份,客户端自报的 ip/UA 一律不收)。 */
export function recordAnalyticsEvents(events: AnalyticsEventInput[]) {
  return fetchApi<AnalyticsTrackResult>('/analytics/track', {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({ events }),
  })
}
