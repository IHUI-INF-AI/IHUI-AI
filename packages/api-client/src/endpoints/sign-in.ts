/**
 * 签到域端点(2026-11-02 立,web→RN P1-5 对齐):
 * - GET /api/sign-in/history?page=&pageSize=[&yearMonth=] → {list,total,page,pageSize}
 *
 * 积分是整数,消费侧不得除以 100(与钱包金额分单位是两回事)。
 */
import type { ApiResult } from '@ihui/types'

import { fetchApi } from '../client.js'
import { buildQs } from '../utils.js'

/** 签到记录行(来源 sign_in_records) */
export interface SignInHistoryItem {
  /** YYYY-MM-DD */
  signInDate: string
  rewardPoints: number
  consecutiveDays: number
}

export interface SignInHistoryData {
  list: SignInHistoryItem[]
  total: number
  page: number
  pageSize: number
}

/** 签到历史(分页;yearMonth 形如 YYYY-MM,不传则不按月过滤) */
export async function getSignInHistory(query: {
  page: number
  pageSize: number
  yearMonth?: string
}): Promise<ApiResult<SignInHistoryData>> {
  return fetchApi<SignInHistoryData>(`/api/sign-in/history${buildQs(query)}`)
}
