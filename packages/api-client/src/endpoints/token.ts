import type { ApiResult } from '@ihui/types'

import { fetchApi } from '../client.js'
import { buildQs, type PageData } from '../utils.js'

export interface TokenBalance {
  /** 当前余额(user_margins.tokenQuantity,Redis 缓存 5 分钟) */
  balance: number
  /** 累计获得(token_flows op_type 0/3/4/5/6 聚合,2026-09-13 矩阵 A #26 补齐端点) */
  totalEarned: number
  /** 累计消耗(token_flows op_type 1 聚合) */
  totalUsed: number
  /** VIP 等级(-1 游客/0 普通/1-4 VIP) */
  vipLevel?: number
  /** VIP 月配额(token-balance-service VIP_TOKEN_BENEFITS) */
  monthlyQuota?: number
  /** VIP 折扣率(1.0 无折扣) */
  discountRate?: number
  /** 促销期(每月 1-7 号额外 8 折) */
  isPromotionPeriod?: boolean
}

export interface TokenFlowItem {
  id: string
  agentName: string
  modelName: string
  token: number
  amount: number
  createdAt: string
}

export type TokenFlowQuery = {
  range?: string
  page?: number
  pageSize?: number
  from?: string
  to?: string
}

export async function getTokenBalance(): Promise<ApiResult<TokenBalance>> {
  return fetchApi<TokenBalance>('/api/user/token-balance')
}

export async function getTokenFlows(
  query: TokenFlowQuery = {},
): Promise<ApiResult<PageData<TokenFlowItem>>> {
  return fetchApi<PageData<TokenFlowItem>>(`/api/user/token-flow${buildQs(query)}`)
}
