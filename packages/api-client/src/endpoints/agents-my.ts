/**
 * 「我的智能体」端点(补 RN 承载用,2026-10-27 后端契约现读)。
 *
 *  - GET /api/agents/my?page&pageSize&status
 *    路由 apps/api/src/routes/agents.ts:404-425(未登录 401，按 request.userId 过滤)。
 *    信封 success({ list, total, page, pageSize }) —— 形状源头
 *    apps/api/src/db/agents-queries.ts:37-77(findAgentsList 返回值)。
 *    page 默认 1、pageSize 默认 20(agents-queries.ts:39-40);status 打在 agents.status。
 *  - web 同参数消费方 apps/web/app/(main)/agents/my/page.tsx:69-77(page=1&pageSize=100)。
 *  - 与 endpoints/agent.ts:62 getAgents(GET /api/agents,市场列表)是两条不同路由:
 *    前者按当前登录用户过滤且要求鉴权,后者是公开市场列表,不可互换。
 */
import type { ApiResult } from '@ihui/types'

import { fetchApi } from '../client.js'
import { buildQs, type PageData } from '../utils.js'

/** agents 表行(GET /api/agents/my → data.list),只声明展示层实际消费的列 */
export interface MyAgentRow {
  agentId: string
  name: string
  description: string | null
  avatar: string | null
  /** varchar(16);web 筛选项见 pending/published/rejected/offline(page.tsx:37-43) */
  status: string
  price: number
  isFree: boolean
  createdAt: string
  updatedAt: string
}

export interface MyAgentQuery {
  page?: number
  pageSize?: number
  /** 省略 = 全部(web page.tsx:73 仅在非 all 时下发) */
  status?: string
}

/** 我的智能体列表(GET /api/agents/my,apps/api/src/routes/agents.ts:404) */
export async function getMyAgents(
  query: MyAgentQuery = {},
): Promise<ApiResult<PageData<MyAgentRow>>> {
  return fetchApi<PageData<MyAgentRow>>(`/api/agents/my${buildQs(query)}`)
}
