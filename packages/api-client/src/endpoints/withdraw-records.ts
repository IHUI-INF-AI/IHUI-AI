/**
 * 提现记录端点封装(补 RN 承载用,2026-10-27 后端契约现读)
 *
 *  - GET /api/finance/withdrawal/list?page&limit
 *    → 信封 success({ items, total })(apps/api/src/routes/finance.ts:288-293,authenticate)
 *    financeRoutes 挂 prefix /api(apps/api/src/routes/index.ts:741),
 *    行来自 listWithdrawals(apps/api/src/db/commission-queries.ts:529-547,withdrawalFlows 全列)。
 *  - 行形状:amount/fee/originalAmount 单位为「分」,status 0=待审核 1=处理中 2=已完成 3=失败,
 *    method 取 wechat/alipay/bank,processedAt 可空
 *    (web 同表 apps/web/app/(main)/distribution/withdraw/records/page.tsx:23-46)。
 *  - 与既有 endpoints/wallet.ts 的 getWithdrawRecords(GET /api/wallet/withdraw/records)
 *    是两个数据源,不可互相顶替。
 *  - web 消费方:apps/web/app/(main)/distribution/withdraw/records/page.tsx:98-101。
 */
import type { ApiResult } from '@ihui/types'

import { fetchApi } from '../client.js'
import { buildQs } from '../utils.js'

/** withdrawal_flows 行(GET /api/finance/withdrawal/list → data.items) */
export interface WithdrawalItem {
  id: string
  /** 实际到账(分) */
  amount: number
  /** 手续费(分) */
  fee: number
  /** 原始金额(分) */
  originalAmount: number
  /** 0=待审核 1=处理中 2=已完成 3=失败 */
  status: number
  /** wechat | alipay | bank */
  method: string
  createdAt: string
  processedAt: string | null
}

export interface WithdrawalListResult {
  items: WithdrawalItem[]
  total: number
}

export interface WithdrawalQuery {
  page?: number
  /** 后端上限 100(apps/api/src/routes/finance.ts:31) */
  limit?: number
}

export async function getWithdrawalRecords(
  query: WithdrawalQuery = {},
): Promise<ApiResult<WithdrawalListResult>> {
  return fetchApi<WithdrawalListResult>(`/api/finance/withdrawal/list${buildQs(query)}`)
}
