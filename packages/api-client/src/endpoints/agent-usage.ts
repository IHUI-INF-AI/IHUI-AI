/**
 * Agent 会话 Token 用量端点封装(2026-09-07 工作线 A 立)。
 *
 * 后端:apps/ai-service/app/routers/agents.py `GET /agents/{agent_id}/token-usage`,
 * web 经 8802 网关代理路径 /api/agents/{agent_id}/token-usage。
 * 数据源:agent checkpoint 按轮估算(字符数/4),缺失时降级 _trace_store;
 * 响应为裸 JSON(code===undefined 由 fetchApi 归一化为 data)。
 */
import { fetchApi } from '../client'

/** 单轮用量条目(后端 checkpoint/trace 逐轮估算) */
export interface AgentTokenUsageItem {
  /** 轮次标签(如 "I3" 或 session id 前 8 位) */
  sessionLabel: string
  /** 输入 token(user/tool/system 消息估算) */
  prompt: number
  /** 输出 token(assistant 消息 + tool_calls 参数估算) */
  completion: number
}

/** 聚合后的会话用量(徽章展示用) */
export interface AgentTokenUsageSummary {
  promptTokens: number
  completionTokens: number
  totalTokens: number
  /** 请求数 = 有用量记录的轮次数 */
  requests: number
}

/** 获取会话累计 Token 用量并聚合为徽章摘要(GET /api/agents/{id}/token-usage) */
export async function getAgentTokenUsage(agentId: string): Promise<AgentTokenUsageSummary> {
  const res = await fetchApi<{ tokenUsage?: AgentTokenUsageItem[] }>(
    `/agents/${encodeURIComponent(agentId)}/token-usage`,
  )
  const items = (res.success ? res.data?.tokenUsage : undefined) ?? []
  const promptTokens = items.reduce((acc, it) => acc + (Number(it.prompt) || 0), 0)
  const completionTokens = items.reduce((acc, it) => acc + (Number(it.completion) || 0), 0)
  return {
    promptTokens,
    completionTokens,
    totalTokens: promptTokens + completionTokens,
    requests: items.length,
  }
}
