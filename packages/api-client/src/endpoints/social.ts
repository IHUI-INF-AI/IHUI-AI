import type { ApiResult } from '@ihui/types'

import { fetchApi } from '../client.js'
import { buildQs, type PageData, type PageQuery } from '../utils.js'

/** 订阅项(收藏/关注/订阅列表通用) */
export interface SubscriptionItem {
  id: string
  targetType: string
  targetId: string
  createdAt: string
}

/** 获取订阅列表 — GET /subscriptions */
export async function getSubscriptions(
  query: PageQuery = {},
): Promise<ApiResult<PageData<SubscriptionItem>>> {
  return fetchApi<PageData<SubscriptionItem>>(`/subscriptions${buildQs(query)}`)
}

/** 收藏资源 — POST /favorites(幂等;resourceType 枚举与后端 favoriteBody 对齐) */
export async function addFavorite(
  resourceType: 'project' | 'file' | 'doc' | 'post' | 'comment' | 'aiworld' | 'agent',
  resourceId: string,
): Promise<ApiResult<{ favorited: true }>> {
  return fetchApi<{ favorited: true }>('/favorites', {
    method: 'POST',
    body: JSON.stringify({ resourceType, resourceId }),
  })
}

/** 检查是否已收藏 — GET /favorites/check/:resourceType/:resourceId */
export async function checkFavorite(
  resourceType: string,
  resourceId: string,
): Promise<ApiResult<{ favorited: boolean }>> {
  return fetchApi<{ favorited: boolean }>(
    `/favorites/check/${encodeURIComponent(resourceType)}/${encodeURIComponent(resourceId)}`,
  )
}

/** 取消收藏 — DELETE /favorites/:resourceType/:resourceId */
export async function deleteFavorite(
  resourceType: string,
  resourceId: string,
): Promise<ApiResult<{ favorited: false }>> {
  return fetchApi<{ favorited: false }>(`/favorites/${resourceType}/${resourceId}`, {
    method: 'DELETE',
  })
}

/** 取消关注 — DELETE /follows/:userId */
export async function unfollowUser(userId: string): Promise<ApiResult<{ followed: false }>> {
  return fetchApi<{ followed: false }>(`/follows/${userId}`, {
    method: 'DELETE',
  })
}

/** 取消订阅 — DELETE /subscriptions/:targetType/:targetId */
export async function cancelSubscription(
  targetType: string,
  targetId: string,
): Promise<ApiResult<{ subscribed: false }>> {
  return fetchApi<{ subscribed: false }>(`/subscriptions/${targetType}/${targetId}`, {
    method: 'DELETE',
  })
}
