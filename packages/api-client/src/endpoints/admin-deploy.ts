/**
 * 部署运维 AI 化 API(P2-13)
 * 对接后端 deploy-diagnosis.ts:POST /api/admin/deploy-diagnosis
 */
import type { ApiResult } from '@ihui/types'

import { fetchApi } from '../client'

// ===================== 类型定义 =====================

export interface DeployDiagnosisReport {
  rootCause: string
  impact: string
  fixCommands: string[]
  summary: string
  /** false = AI 返回无法解析为 JSON,raw 字段带原文 */
  parseOk: boolean
  raw?: string
}

export interface DeployDiagnosisResult {
  report: DeployDiagnosisReport
  model?: string | null
  durationMs: number
}

export interface DeployDiagnosisInput {
  /** logs/.last-deploy-result.json 内容 */
  deployResult?: string
  /** health-check 脚本输出 */
  healthJson?: string
  /** 最新部署日志尾部 */
  logTail?: string
  /** docker compose logs 输出 */
  containerLogs?: string
}

// ===================== 端点 =====================

/** 提交部署诊断输入,由 AI 分析根因并返回修复建议 */
export async function runDeployDiagnosis(
  input: DeployDiagnosisInput,
): Promise<ApiResult<DeployDiagnosisResult>> {
  return fetchApi<DeployDiagnosisResult>('/api/admin/deploy-diagnosis', {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify(input),
    timeoutMs: 180_000,
  })
}
