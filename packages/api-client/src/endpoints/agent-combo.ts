/**
 * Agent 参数组合 API 客户端(跨端共享,2026-11-13 立)
 *
 * 端点:
 *  - GET    /api/agent-combos        当前用户全部组合
 *  - PUT    /api/agent-combos/:id    新建/覆盖(服务端重跑共享校验器)
 *  - DELETE /api/agent-combos/:id    删除
 */

import type {
  AgentComboDeleteResponse,
  AgentComboDetailResponse,
  AgentComboDraft,
  AgentComboListResponse,
} from '@ihui/types'

import { fetchApi } from '../client.js'

export async function listAgentCombos(): Promise<AgentComboListResponse> {
  const res = await fetchApi<AgentComboListResponse>('/agent-combos')
  if (!res.success) throw new Error(res.error)
  return res.data
}

export async function saveAgentCombo(combo: AgentComboDraft): Promise<AgentComboDetailResponse> {
  const res = await fetchApi<AgentComboDetailResponse>(
    `/agent-combos/${encodeURIComponent(combo.id)}`,
    { method: 'PUT', body: JSON.stringify(combo) },
  )
  if (!res.success) throw new Error(res.error)
  return res.data
}

export async function deleteAgentCombo(id: string): Promise<AgentComboDeleteResponse> {
  const res = await fetchApi<AgentComboDeleteResponse>(`/agent-combos/${encodeURIComponent(id)}`, {
    method: 'DELETE',
  })
  if (!res.success) throw new Error(res.error)
  return res.data
}

export type {
  AgentComboDeleteResponse,
  AgentComboDetailResponse,
  AgentComboDraft,
  AgentComboListResponse,
}
