/**
 * 思维链翻译 API 客户端(跨端共享,2026-11-13 立)
 *
 * 端点:POST /api/ai/reasoning/translate
 * 语义:只取译文,原文由调用方自己持有;失败抛错,由 UI 静默降级为「只有原文」。
 */

import type { ReasoningTranslationLang, ReasoningTranslationResponse } from '@ihui/types'

import { fetchApi } from '../client.js'

export async function translateReasoningText(
  text: string,
  targetLang: ReasoningTranslationLang,
): Promise<ReasoningTranslationResponse> {
  const res = await fetchApi<ReasoningTranslationResponse>('/ai/reasoning/translate', {
    method: 'POST',
    body: JSON.stringify({ text, targetLang }),
  })
  if (!res.success) throw new Error(res.error)
  return res.data
}

export type { ReasoningTranslationLang, ReasoningTranslationResponse }
