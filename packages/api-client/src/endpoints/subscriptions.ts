import type { ApiResult } from '@ihui/types'

import { fetchApi } from '../client.js'

/** 会员订阅状态 — GET /api/subscriptions */
export async function getMembershipSubscription<T = { subscription: unknown }>(
  params?: Record<string, string | number | boolean | undefined | null>,
): Promise<ApiResult<T>> {
  return fetchApi<T>('/api/subscriptions', { params })
}

/** 取消续订 — POST /api/subscriptions/cancel */
export async function cancelSubscriptionRenewal<T = { subscription: unknown }>(): Promise<ApiResult<T>> {
  return fetchApi<T>('/api/subscriptions/cancel', { method: 'POST' })
}

/** 续订 — POST /api/subscriptions/renew */
export async function renewSubscription<T = { subscription: unknown }>(): Promise<ApiResult<T>> {
  return fetchApi<T>('/api/subscriptions/renew', { method: 'POST' })
}
