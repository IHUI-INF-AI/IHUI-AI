/**
 * 会话消息检索 API 客户端(跨端共享,2026-11-13 立)
 *
 * 端点:GET /api/search/messages?q=&limit=&conversationId=
 * 返回的命中已带 snippet,调用方只负责渲染与高亮。
 */

import type { ChatMessageSearchResponse } from '@ihui/types'

import { fetchApi } from '../client.js'

export interface ChatMessageSearchOptions {
  limit?: number
  conversationId?: string
}

export async function searchChatMessages(
  query: string,
  options: ChatMessageSearchOptions = {},
): Promise<ChatMessageSearchResponse> {
  const params = new URLSearchParams({ q: query })
  if (options.limit !== undefined) params.set('limit', String(options.limit))
  if (options.conversationId !== undefined) params.set('conversationId', options.conversationId)
  const res = await fetchApi<ChatMessageSearchResponse>(`/search/messages?${params.toString()}`)
  if (!res.success) throw new Error(res.error)
  return res.data
}

export type { ChatMessageSearchResponse }
