import type { ApiResult } from '@ihui/types'

import { fetchApi } from '../client.js'

/** MCP 资源条目(GET /api/ai/mcp/resources → data,字段对齐 mcp-resource-viewer.tsx:21-26) */
export interface McpResourceRecord {
  uri: string
  name: string
  mimeType?: string
  content?: string
}

/** GET /api/ai/mcp/resources —— data 为裸数组(ai-frontend-routes.ts:325) */
export async function getMcpResources(): Promise<ApiResult<McpResourceRecord[]>> {
  return fetchApi<McpResourceRecord[]>('/api/ai/mcp/resources')
}
