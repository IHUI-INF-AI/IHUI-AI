/**
 * 401 分型回归锁(2026-11-23 立)。
 *
 * 病灶:桌面端 `/api/subagents/active|topology` 缺租户豁免,带有效 admin Bearer 仍 401;
 * api-client 把这条 401 当成"access token 过期"反复续期,按 10s 节拍轮转 refresh token,
 * 旧 token 迟到重放超 30s 触发 reuse ⇒ 整族 revoke ⇒ 用户"登录态莫名消失"。
 *
 * 判据:`TENANT_REQUIRED`(机器码)与租户闸文案都必须判"不可续期";
 * 普通 401(凭据类)仍必须判"可续期",不得把真过期也放掉。
 */
import { describe, expect, it } from 'vitest'
import { isRefreshableUnauthorized } from '../src/client.js'

function failure(error: string, errorCode?: string) {
  return { success: false as const, error, status: 401, ...(errorCode ? { errorCode } : {}) }
}

describe('401 分型:策略类不触发 refresh', () => {
  it('TENANT_REQUIRED 机器码 ⇒ 不续期', () => {
    expect(
      isRefreshableUnauthorized(
        failure('多租户严格模式已启用,请求必须携带租户标识', 'TENANT_REQUIRED'),
      ),
    ).toBe(false)
  })

  it('老响应只有租户闸文案、没有机器码 ⇒ 不续期(兜底)', () => {
    expect(
      isRefreshableUnauthorized(
        failure('多租户严格模式已启用,请求必须携带租户标识;path=/api/subagents/active'),
      ),
    ).toBe(false)
  })

  it('普通 401(凭据失效)⇒ 仍必须续期', () => {
    expect(isRefreshableUnauthorized(failure('未授权'))).toBe(true)
    expect(isRefreshableUnauthorized(failure('登录已过期', 'TOKEN_EXPIRED'))).toBe(true)
  })
})
