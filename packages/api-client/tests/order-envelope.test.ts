// XUI-002 夹具:GET /api/orders/:id 真实响应是 { order: Order } 包络,
// getOrderById 必须在端点层拆包;调用方拿到 res.data.id 才是订单 id。
// 改前必红:旧实现把整个包络当 Order,res.data.id === undefined。
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import { getOrderById } from '../src/endpoints/order.js'

function jsonResponse(data: unknown): Response {
  return {
    ok: true,
    status: 200,
    headers: new Headers({ 'content-type': 'application/json' }),
    json: async () => ({ code: 0, message: 'ok', data }),
    text: async () => JSON.stringify({ code: 0, message: 'ok', data }),
    body: null,
  } as unknown as Response
}

describe('XUI-002 getOrderById 包络拆解', () => {
  let fetchMock: ReturnType<typeof vi.fn>
  const originalFetch = globalThis.fetch

  beforeEach(() => {
    fetchMock = vi.fn()
    globalThis.fetch = fetchMock as unknown as typeof fetch
  })

  afterEach(() => {
    globalThis.fetch = originalFetch
  })

  it('把 { order } 拆成 Order 本体', async () => {
    fetchMock.mockResolvedValue(
      jsonResponse({
        order: {
          id: 'ord-1',
          orderNo: 'N20261108001',
          userId: 'u1',
          type: 'course',
          targetId: 'c1',
          targetTitle: '课程A',
          amount: 100,
          discountAmount: 0,
          payAmount: 100,
          status: 'pending',
          payMethod: null,
          paidAt: null,
          refundedAt: null,
          remark: null,
          createdAt: '2026-11-08T00:00:00.000Z',
          updatedAt: '2026-11-08T00:00:00.000Z',
        },
      }),
    )

    const res = await getOrderById('ord-1')

    expect(res.success).toBe(true)
    if (!res.success) return
    expect(res.data.id).toBe('ord-1')
    expect(res.data.orderNo).toBe('N20261108001')
    expect(res.data.targetTitle).toBe('课程A')
    expect((res.data as unknown as { order?: unknown }).order).toBeUndefined()
  })

  it('失败响应原样透传,不二次包装', async () => {
    fetchMock.mockResolvedValue({
      ok: false,
      status: 404,
      headers: new Headers({ 'content-type': 'application/json' }),
      json: async () => ({ code: 404, message: '订单不存在', data: null }),
      text: async () => JSON.stringify({ code: 404, message: '订单不存在', data: null }),
      body: null,
    } as unknown as Response)

    const res = await getOrderById('missing')

    expect(res.success).toBe(false)
  })
})
