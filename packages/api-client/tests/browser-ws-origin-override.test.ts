import { afterEach, describe, expect, it } from 'vitest'

import { buildBrowserWsUrl, setBrowserWsToken } from '../src/endpoints/browser-hub.js'

/**
 * 生产 web/WS 异源时,必须能显式指定 ai-service 的 WS origin。
 *
 * 立因(2026-11-26 线上实测):`wss://www.aizhs.top/api/browser/ws/{sid}` 被边缘回 404,
 * 而 `wss://api.aizhs.top/api/browser/ws/{sid}` 可正常 upgrade 并收到 navigation/task/frame。
 * 画中画页仍在 web origin,因此只换 WS 目标;未配置时保持原同源行为。
 */

afterEach(() => {
  delete process.env.NEXT_PUBLIC_BROWSER_WS_ORIGIN
  setBrowserWsToken('')
})

describe('buildBrowserWsUrl 的异源覆盖', () => {
  it('配置 origin 后固定指向该 host,并保留 token 查询参数', () => {
    process.env.NEXT_PUBLIC_BROWSER_WS_ORIGIN = 'wss://api.aizhs.top/'
    setBrowserWsToken('a+b/c')
    expect(buildBrowserWsUrl('sess-01')).toBe(
      'wss://api.aizhs.top/api/browser/ws/sess-01?token=a%2Bb%2Fc',
    )
  })

  it('尾斜杠归一,不产生双斜杠', () => {
    process.env.NEXT_PUBLIC_BROWSER_WS_ORIGIN = 'wss://api.aizhs.top///'
    setBrowserWsToken('t')
    expect(buildBrowserWsUrl('s')).toBe('wss://api.aizhs.top/api/browser/ws/s?token=t')
  })

  it('未配置时保持旧行为(Node 侧回环占位)', () => {
    setBrowserWsToken('t')
    expect(buildBrowserWsUrl('s')).toBe('ws://localhost:8803/api/browser/ws/s?token=t')
  })
})
