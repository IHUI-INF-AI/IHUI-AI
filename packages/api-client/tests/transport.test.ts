import { describe, it, expect, vi, afterEach } from 'vitest'
import {
  setTransport,
  getTransport,
  type Transport,
  type TransportInit,
  type TransportResponse,
} from '../src/transport.js'

describe('Transport', () => {
  afterEach(() => {
    // 恢复默认 transport
    setTransport(undefined as unknown as Transport)
  })

  it('setTransport 注入后 getTransport 返回同一实例', () => {
    const custom: Transport = vi.fn() as unknown as Transport
    setTransport(custom)
    expect(getTransport()).toBe(custom)
  })

  it('getTransport 返回当前注入的 transport', () => {
    const custom: Transport = vi.fn() as unknown as Transport
    setTransport(custom)
    expect(getTransport()).toBe(custom)
  })

  it('TransportResponse 类型定义包含必要方法', () => {
    const response: TransportResponse = {
      ok: true,
      status: 200,
      headers: { get: () => null },
      text: async () => 'hello',
      json: async () => ({ message: 'hello' }),
    }
    expect(response.ok).toBe(true)
    expect(response.status).toBe(200)
  })

  it('TransportInit 类型定义支持 method/headers/body/signal', () => {
    const controller = new AbortController()
    const init: TransportInit = {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: '{"test":true}',
      signal: controller.signal,
      credentials: 'include',
    }
    expect(init.method).toBe('POST')
    expect(init.body).toBe('{"test":true}')
    expect(init.credentials).toBe('include')
  })
})
