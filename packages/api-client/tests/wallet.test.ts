import { describe, it, expect, vi, afterEach } from 'vitest'

import { setTransport, type Transport } from '../src/transport.js'
import { getDailyCreditsUsage } from '../src/endpoints/wallet.js'

describe('getDailyCreditsUsage(GET /api/credits/usage/daily)', () => {
  afterEach(() => {
    setTransport(undefined as unknown as Transport)
  })

  function okTransport(payload: unknown) {
    return vi.fn(async () => ({
      ok: true,
      status: 200,
      headers: { get: () => null },
      text: async () => '',
      json: async () => ({ code: 0, data: payload }),
    })) as unknown as Transport
  }

  it('days 传入时拼进 query string 并回传聚合桶', async () => {
    const transport = okTransport({
      days: 4,
      startDate: '2026-08-30',
      endDate: '2026-09-02',
      timezone: 'UTC',
      buckets: [
        { date: '2026-08-30', count: 0, points: 0 },
        { date: '2026-08-31', count: 2, points: 30 },
      ],
    })
    setTransport(transport)

    const res = await getDailyCreditsUsage({ days: 4 })
    expect(res.success).toBe(true)
    expect(res.data?.timezone).toBe('UTC')
    expect(res.data?.buckets[1]?.count).toBe(2)
    const url = (transport.mock.calls[0] as [string, unknown] | undefined)?.[0]
    expect(url).toBe('/api/credits/usage/daily?days=4')
  })

  it('不传 days 时不带 query string(服务端默认 90)', async () => {
    const transport = okTransport({
      days: 90,
      startDate: '',
      endDate: '',
      timezone: 'UTC',
      buckets: [],
    })
    setTransport(transport)

    const res = await getDailyCreditsUsage()
    expect(res.success).toBe(true)
    const url = (transport.mock.calls[0] as [string, unknown] | undefined)?.[0]
    expect(url).toBe('/api/credits/usage/daily')
  })
})
