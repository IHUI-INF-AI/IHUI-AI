import { describe, expect, it } from 'vitest'

import { humanizeToolText } from '../src/chat/tool-display'

// 2026-11-22 回归:后端子代理 step 的 stepAction 可能直接给带命名空间的 i18n 键
// (`taskStatus.toolDispatchSubagent`)。调用方的 translate 只认裸键,不剥前缀就会把
// 键名原样显示到界面上(实测生产 8801 出现过 `taskStatus.toolDispatchSuba…`)。
describe('humanizeToolText 命名空间剥离', () => {
  const tStatus = (key: string) =>
    ({ toolDispatchSubagent: '派遣子代理', toolCallCount: '{n} 次工具调用' })[key] ?? key

  it('带 taskStatus. 前缀的键按裸键翻译', () => {
    expect(humanizeToolText('taskStatus.toolDispatchSubagent', tStatus)).toBe('派遣子代理')
  })

  it('不带前缀的裸键同样命中词条(不再被子串替换改写)', () => {
    // 旧实现里 `patch` 是工具码名,而它嵌在 `Dispatch` 里 ⇒ 键会被改写成
    // `toolDistoolEditFileSubagent`。整串即键时必须先翻译。
    expect(humanizeToolText('toolDispatchSubagent', tStatus)).toBe('派遣子代理')
  })

  it('非键形态的自由文本不被误剥前缀', () => {
    expect(humanizeToolText('taskStatus.xxx.yyy', tStatus)).toBe('taskStatus.xxx.yyy')
    expect(humanizeToolText('已列出目录文件 .', tStatus)).toBe('已列出目录文件 .')
  })
})
