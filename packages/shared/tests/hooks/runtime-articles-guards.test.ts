/**
 * XUI-023 / XUI-024 结构锁(两个 hook 无法在 node 环境渲染)。
 * 判据是"旧流回调是否被代次挡住""load 是否脱离 page 依赖",用源码级断言钉住。
 */
import { readFileSync } from 'node:fs'
import { join } from 'node:path'
import { describe, expect, it } from 'vitest'

const ROOT = join(__dirname, '..', '..')
const read = (p: string) => readFileSync(join(ROOT, p), 'utf8')

const RUNTIME = read('src/hooks/use-agent-runtime.ts')
const ARTICLES = read('src/hooks/use-articles.ts')

describe('XUI-023 useAgentRuntime:旧流不得改写新一轮状态', () => {
  it('每次 send 推进 runEpochRef,回调按代次过滤', () => {
    expect(RUNTIME).toMatch(/const runEpochRef = React\.useRef\(0\)/)
    expect(RUNTIME).toMatch(/const epoch = \+\+runEpochRef\.current/)
    expect(RUNTIME).toMatch(/if \(isCurrent\(\)\) setOutput/)
    expect(RUNTIME).toMatch(/onDone: \(data\) => \{\s*if \(!isCurrent\(\)\) return/)
    expect(RUNTIME).toMatch(/catch \(err\) \{\s*[\s\S]*?if \(!isCurrent\(\)\) return/)
  })
})

describe('XUI-024 useArticles:load 不得依赖 page', () => {
  it('buildParams 依赖里没有 page,也不再用 `?? page` 兜底', () => {
    expect(ARTICLES).not.toContain('overridePage ?? page')
    expect(ARTICLES).toMatch(/\[pageSize, categoryId, status, search\],/)
  })

  it('loadMore 仍显式推进下一页(阴性对照)', () => {
    expect(ARTICLES).toMatch(/buildParams\(nextPage\)/)
  })
})
