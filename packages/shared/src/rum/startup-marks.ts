export type StartupMarksJudgement =
  | {
      disposition: 'unjudged'
      reason: 'schema-unmeasured' | 'schema-empty' | 'marks-unmeasured'
      missing: null
      extra: null
    }
  | {
      disposition: 'closed'
      reason: 'complete'
      missing: readonly string[]
      extra: readonly string[]
    }
  | {
      disposition: 'open'
      reason: 'incomplete'
      missing: readonly string[]
      extra: readonly string[]
    }

function unjudged(
  reason: 'schema-unmeasured' | 'schema-empty' | 'marks-unmeasured',
): StartupMarksJudgement {
  return { disposition: 'unjudged', reason, missing: null, extra: null }
}

/** 空串与非字符串不算打点；同名只留首次出现，顺序不变。 */
function distinctMarks(values: readonly string[]): string[] {
  const seen = new Set<string>()
  const kept: string[] = []
  for (const value of values) {
    if (typeof value !== 'string' || value === '') continue
    if (seen.has(value)) continue
    seen.add(value)
    kept.push(value)
  }
  return kept
}

/**
 * 对照声明集与已观测打点。
 * 声明集为空或没量到都是未判定，不得把没打到的点说成全部完成。
 */
export function judgeStartupMarks(input: {
  declared: readonly string[] | null
  observed: readonly string[] | null
}): StartupMarksJudgement {
  if (!Array.isArray(input.declared)) return unjudged('schema-unmeasured')
  if (input.declared.length === 0) return unjudged('schema-empty')
  if (!Array.isArray(input.observed)) return unjudged('marks-unmeasured')

  const declared = distinctMarks(input.declared)
  if (declared.length === 0) return unjudged('schema-empty')
  const observed = distinctMarks(input.observed)
  const declaredSet = new Set(declared)
  const observedSet = new Set(observed)
  const missing = declared.filter((mark) => !observedSet.has(mark))
  const extra = observed.filter((mark) => !declaredSet.has(mark))
  if (missing.length === 0 && extra.length === 0) {
    return { disposition: 'closed', reason: 'complete', missing, extra }
  }
  return { disposition: 'open', reason: 'incomplete', missing, extra }
}
