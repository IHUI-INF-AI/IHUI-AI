import { describe, expect, it } from 'vitest'

import { judgeStartupMarks } from './startup-marks'

describe('judgeStartupMarks', () => {
  it('声明集没量到是未判定', () => {
    expect(judgeStartupMarks({ declared: null, observed: ['a'] })).toEqual({
      disposition: 'unjudged',
      reason: 'schema-unmeasured',
      missing: null,
      extra: null,
    })
  })

  it('声明集为空即使观测有值也是未判定', () => {
    expect(judgeStartupMarks({ declared: [], observed: ['a'] })).toEqual({
      disposition: 'unjudged',
      reason: 'schema-empty',
      missing: null,
      extra: null,
    })
  })

  it('声明集里只有空串时按空清单未判定', () => {
    expect(judgeStartupMarks({ declared: [''], observed: [] })).toEqual({
      disposition: 'unjudged',
      reason: 'schema-empty',
      missing: null,
      extra: null,
    })
  })

  it('缺了声明点又多出观测点时仍开着', () => {
    expect(judgeStartupMarks({ declared: ['a', 'b'], observed: ['b', 'c'] })).toEqual({
      disposition: 'open',
      reason: 'incomplete',
      missing: ['a'],
      extra: ['c'],
    })
  })
})
