import { describe, expect, it } from 'vitest'

import {
  emptyDeliveryBook,
  receiveDelivery,
  settleDelivery,
  shiftSubscribers,
} from './delivery-ack'

describe('receiveDelivery', () => {
  it('第一次见到就收下，同一 id 再次到达不另开一份', () => {
    const first = receiveDelivery(emptyDeliveryBook(), 'd1')
    expect(first.disposition).toBe('accept')
    const again = receiveDelivery(first.book, 'd1')
    expect(again).toEqual({ disposition: 'duplicate', reason: 'already-pending', book: first.book })
    expect(receiveDelivery(first.book, null).reason).toBe('id-unmeasured')
  })

  it('处理成功才 ack，失败则离开在途集合以便重投', () => {
    const accepted = receiveDelivery(emptyDeliveryBook(), 'd1')
    const rejected = settleDelivery(accepted.book, 'd1', false)
    expect(rejected.disposition).toBe('retry')
    expect(rejected.book.pending).toEqual([])
    expect(rejected.book.acked).toEqual([])
    const again = receiveDelivery(rejected.book, 'd1')
    const done = settleDelivery(again.book, 'd1', true)
    expect(done.book.acked).toEqual(['d1'])
    expect(receiveDelivery(done.book, 'd1').reason).toBe('already-acked')
  })

  it('没量到处理结果时保持在途，订阅数不会减成负数', () => {
    const accepted = receiveDelivery(emptyDeliveryBook(), 'd1')
    const held = settleDelivery(accepted.book, 'd1', null)
    expect(held.reason).toBe('handled-unmeasured')
    expect(held.book.pending).toEqual(['d1'])
    expect(shiftSubscribers(1, -1)).toBe(0)
    expect(shiftSubscribers(0, -1)).toBe(0)
    expect(shiftSubscribers(null, -1)).toBeNull()
  })
})
