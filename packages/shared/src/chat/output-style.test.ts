import { describe, expect, it } from 'vitest'

import { admitOutputStyle } from './output-style'

describe('admitOutputStyle', () => {
  it('Default 被接纳', () => {
    expect(admitOutputStyle('Default')).toEqual({
      disposition: 'admitted',
      reason: 'registered',
      style: 'Default',
    })
  })

  it('null 与空串是 style-unmeasured', () => {
    expect(admitOutputStyle(null)).toEqual({
      disposition: 'unjudged',
      reason: 'style-unmeasured',
      style: null,
    })
    expect(admitOutputStyle('')).toEqual({
      disposition: 'unjudged',
      reason: 'style-unmeasured',
      style: null,
    })
  })

  it('Friendly 是 style-unknown 且 style 为 null', () => {
    expect(admitOutputStyle('Friendly')).toEqual({
      disposition: 'unjudged',
      reason: 'style-unknown',
      style: null,
    })
  })
})
