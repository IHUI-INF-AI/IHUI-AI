export type EvictionPair =
  | { disposition: 'open'; reason: 'warning-unrecovered' }
  | { disposition: 'closed'; reason: 'recovered' }
  | { disposition: 'unjudged'; reason: 'warning-unmeasured' | 'time-unmeasured' | 'time-inverted' }

function parsed(value: string | null): number | null | undefined {
  if (value === null) return null
  if (typeof value !== 'string' || value.trim() === '') return undefined
  const time = Date.parse(value)
  return Number.isFinite(time) ? time : undefined
}

/**
 * 驱逐警告和恢复必须成对。只有警告时不得渲染成完成。
 * 没有警告却有恢复，或时刻对不上，都是未判定。
 */
export function judgeEvictionPair(input: {
  warningAt: string | null
  recoveredAt: string | null
}): EvictionPair {
  const warning = parsed(input.warningAt)
  const recovered = parsed(input.recoveredAt)
  if (warning === undefined || recovered === undefined) {
    return { disposition: 'unjudged', reason: 'time-unmeasured' }
  }
  if (warning === null) return { disposition: 'unjudged', reason: 'warning-unmeasured' }
  if (recovered === null) return { disposition: 'open', reason: 'warning-unrecovered' }
  if (recovered < warning) return { disposition: 'unjudged', reason: 'time-inverted' }
  return { disposition: 'closed', reason: 'recovered' }
}
