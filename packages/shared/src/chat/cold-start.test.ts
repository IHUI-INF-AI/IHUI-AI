import { describe, expect, it } from 'vitest'

import { judgeColdStart } from './cold-start'

describe('judgeColdStart', () => {
  it('列表没读到时不显示成空列表', () => {
    const result = judgeColdStart({ list: null, route: null })
    expect(result.list).toBe('unjudged')
    expect(result.listReason).toBe('list-unmeasured')
    expect(result.items).toBeNull()
  })

  it('合格列表加合法路径则显示列表并恢复路径', () => {
    expect(
      judgeColdStart({
        list: {
          version: 3,
          savedAt: 1700000000000,
          items: [{ id: 'c1', title: '第一项', note: '不带出去' }],
        },
        route: { path: '/chat/c1', savedAt: 1700000000001 },
      }),
    ).toEqual({
      list: 'shown',
      listReason: 'ready',
      items: [{ id: 'c1', title: '第一项' }],
      route: 'restore',
      routeReason: 'ready',
      path: '/chat/c1',
    })
  })

  it('列表没显示且深链时刻没量到时不恢复路径', () => {
    const result = judgeColdStart({
      list: null,
      route: { path: '/chat/c1', savedAt: null },
    })
    expect(result.path).toBeNull()
    expect(result.route).toBe('unjudged')
    expect(result.listReason).toBe('list-unmeasured')
  })

  it('任一行缺标题则整表未判定，不留下其余行', () => {
    const result = judgeColdStart({
      list: {
        version: 3,
        savedAt: 10,
        items: [{ id: 'c1', title: '第一项' }, { id: 'c2' }],
      },
      route: { path: '/chat/c1', savedAt: 10 },
    })
    expect(result.list).toBe('unjudged')
    expect(result.listReason).toBe('row-unmeasured')
    expect(result.items).toBeNull()
  })
})
