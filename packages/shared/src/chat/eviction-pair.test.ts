import { describe, expect, it } from 'vitest'

import { judgeEvictionPair } from './eviction-pair'

describe('judgeEvictionPair', () => {
  it('只有警告时还开着，不能当成完成', () => {
    expect(judgeEvictionPair({ warningAt: '2026-11-07T00:00:00.000Z', recoveredAt: null })).toEqual(
      {
        disposition: 'open',
        reason: 'warning-unrecovered',
      },
    )
  })

  it('恢复早于警告，或根本没有警告，都是未判定', () => {
    expect(
      judgeEvictionPair({
        warningAt: '2026-11-07T00:00:02.000Z',
        recoveredAt: '2026-11-07T00:00:01.000Z',
      }).reason,
    ).toBe('time-inverted')
    expect(judgeEvictionPair({ warningAt: null, recoveredAt: '2026-11-07T00:00:01.000Z' })).toEqual(
      {
        disposition: 'unjudged',
        reason: 'warning-unmeasured',
      },
    )
  })

  it('恢复不早于警告才关闭', () => {
    expect(
      judgeEvictionPair({
        warningAt: '2026-11-07T00:00:01.000Z',
        recoveredAt: '2026-11-07T00:00:01.000Z',
      }),
    ).toEqual({ disposition: 'closed', reason: 'recovered' })
  })
})
