export const OUTPUT_STYLES = ['Default', 'Proactive', 'Concise', 'Explanatory', 'Learning'] as const

export type OutputStyle = (typeof OUTPUT_STYLES)[number]

const REGISTERED = new Set<string>(OUTPUT_STYLES)

function isOutputStyle(id: string): id is OutputStyle {
  return REGISTERED.has(id)
}

/**
 * 输出风格只接纳已注册的五档。
 * 空值、空白，以及未注册的标识，都不回落默认档。
 */
export function admitOutputStyle(
  id: string | null,
):
  | { disposition: 'admitted'; reason: 'registered'; style: OutputStyle }
  | { disposition: 'unjudged'; reason: 'style-unmeasured' | 'style-unknown'; style: null } {
  if (typeof id !== 'string' || id.trim() === '') {
    return { disposition: 'unjudged', reason: 'style-unmeasured', style: null }
  }
  if (!isOutputStyle(id)) {
    return { disposition: 'unjudged', reason: 'style-unknown', style: null }
  }
  return { disposition: 'admitted', reason: 'registered', style: id }
}
