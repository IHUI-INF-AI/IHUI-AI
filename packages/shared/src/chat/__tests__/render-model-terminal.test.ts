// 共享渲染模型必须把终端截断交代透传到块上(D40 跨端)。
// extension 的终端块直接消费 buildRenderModel,这里不传,各端就再也拿不到 truncated/totalChars。
import { describe, expect, it } from 'vitest'

import { buildRenderModel } from '../render-model'
import type { ChatMessage } from '@ihui/types'

function msgWithTerminal(
  task: Partial<NonNullable<ChatMessage['terminalTasks']>[number]> & { id: string },
): ChatMessage {
  return {
    id: 'm1',
    role: 'assistant',
    content: '',
    terminalTasks: [
      {
        command: 'pnpm build',
        status: 'completed',
        startedAt: '2026-09-22T00:00:00.000Z',
        ...task,
      },
    ],
  }
}

function terminalBlock(message: ChatMessage) {
  const block = buildRenderModel(message, { streaming: false }).blocks.find(
    (b) => b.kind === 'terminal',
  )
  if (!block || block.kind !== 'terminal') throw new Error('未产出 terminal 块')
  return block
}

describe('终端截断交代透传到渲染块(D40 跨端)', () => {
  it('truncated + totalChars 必须原样带到块上', () => {
    const block = terminalBlock(
      msgWithTerminal({
        id: 't1',
        output: 'x'.repeat(8000),
        truncated: true,
        totalChars: 42000,
      }),
    )
    expect(block.truncated).toBe(true)
    expect(block.totalChars).toBe(42000)
  })

  it('未截断时不得凭空造出截断标志', () => {
    const block = terminalBlock(msgWithTerminal({ id: 't2', output: 'ok' }))
    expect(block.truncated).toBeUndefined()
    expect(block.totalChars).toBeUndefined()
  })

  it('落库回放路径同样靠这两个字段(旧记录缺失时保持 undefined 而非 false)', () => {
    const block = terminalBlock(
      msgWithTerminal({ id: 't3', output: 'y'.repeat(8000), totalChars: 8000 }),
    )
    expect(block.truncated).toBeUndefined()
    expect(block.totalChars).toBe(8000)
  })
})
