// E-P3 接线钉:applyStreamError 第三参透传 errorCode。
// 此前三参调用堵死端侧 disposition 接线——markStreamError 支持 errorCode,
// 但 applyStreamError 不收、不透传,导致 miniapp/mobile-rn 走 applyStreamError
// 落错误的端拿不到 errorCode,resolveStreamErrorDisposition 永远 null。
import { describe, expect, it } from 'vitest'

import { applyStreamError, isErrorTurn, resendTargetText } from '../stream-error'
import type { ErrorAwareMessage } from '../stream-error'

function assistant(content = ''): ErrorAwareMessage {
  return { role: 'assistant', content }
}

describe('applyStreamError errorCode 透传(E-P3)', () => {
  it('三参调用把 errorCode 写到末条 assistant 消息上', () => {
    const msgs = [assistant('partial')]
    const next = applyStreamError(msgs, '服务异常', 'MODEL_REFUSED')
    expect(next[0]?.error).toBe(true)
    expect(next[0]?.errorCode).toBe('MODEL_REFUSED')
    // 已产出的半句必须留在气泡里(共享层同一标记规则)
    expect(next[0]?.content).toBe('partial')
    expect(isErrorTurn(next[0])).toBe(true)
  })

  it('不传第三参时不写 errorCode 字段(既有两参调用零行为影响)', () => {
    const next = applyStreamError([assistant()], '服务异常')
    expect(next[0]?.error).toBe(true)
    expect(next[0]?.errorCode).toBeUndefined()
  })

  it('末条非 assistant 时原样返回,不误标', () => {
    const user: ErrorAwareMessage = { role: 'user', content: 'q' }
    const next = applyStreamError([user], '服务异常', 'MODEL_REFUSED')
    expect(next[0]?.error).toBeUndefined()
    expect(resendTargetText(next)).toBe('q')
  })
})
