import { describe, expect, it } from 'vitest'

import {
  foldHistoryPageIntoProjection,
  type HistoryPageWire,
  type HistoryProjection,
} from '../history-projection'

const previous: HistoryProjection<string> = {
  turns: [
    { turnOrdinal: 1, messages: ['a'] },
    { turnOrdinal: 2, messages: ['b'] },
  ],
  droppedUnordained: 0,
  replacedTurns: 0,
  boundary: {
    hasOlder: true,
    hasNewer: true,
    olderCursor: 'older-cursor',
    newerCursor: 'newer-cursor',
    oldestTurnOrdinal: 1,
    newestTurnOrdinal: 2,
  },
}

const newerPage: HistoryPageWire<string> = {
  turns: [{ turnOrdinal: 3, messages: ['c'] }],
  limit: 20,
  hasMore: false,
  nextCursor: null,
  projectionState: null,
  cursorState: { status: 'ok' },
}

const olderPage: HistoryPageWire<string> = {
  turns: [{ turnOrdinal: 0, messages: ['z'] }],
  limit: 20,
  hasMore: true,
  nextCursor: 'older-prev',
  projectionState: null,
  cursorState: { status: 'ok' },
}

describe('XUI-033 续读只更新本方向边,不得清掉另一侧游标', () => {
  it('direction=newer ⇒ 保留旧的 olderCursor/hasOlder', () => {
    const next = foldHistoryPageIntoProjection(previous, newerPage, 'newer')
    expect(next.boundary.olderCursor).toBe('older-cursor')
    expect(next.boundary.hasOlder).toBe(true)
    expect(next.boundary.newestTurnOrdinal).toBe(3)
  })

  it('direction=older ⇒ 保留旧的 newerCursor/hasNewer', () => {
    const next = foldHistoryPageIntoProjection(previous, olderPage, 'older')
    expect(next.boundary.newerCursor).toBe('newer-cursor')
    expect(next.boundary.hasNewer).toBe(true)
    expect(next.boundary.olderCursor).toBe('older-prev')
    expect(next.boundary.oldestTurnOrdinal).toBe(0)
  })
})
