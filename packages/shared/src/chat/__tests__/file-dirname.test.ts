/**
 * `fileDirname` 行为锁(2026-10-29 立)。
 *
 * 立因:工具摘要的「涉及目录」维度要按**唯一目录集合**计数,而路径来自各家工具的
 * 五花八门写法(`file_path` / `path` / `filePath`,正斜杠 / 反斜杠混用)。归一与切段
 * 必须与 `fileBasename` 同一份实现,否则同一个文件会在"目录数"和"文件名"两处得出
 * 互相矛盾的读数。本件锁三件事:正反斜杠等价、裸文件名不算目录、盘根不算目录。
 */
import { describe, expect, it } from 'vitest'
import { fileBasename, fileDirname } from '../task-status'

describe('fileDirname — 目录段归一', () => {
  it('正斜杠与反斜杠等价(Windows 路径与 POSIX 路径同判)', () => {
    expect(fileDirname('apps/web/src/a.ts')).toBe('apps/web/src')
    expect(fileDirname('apps\\web\\src\\a.ts')).toBe('apps/web/src')
    expect(fileDirname('apps\\web/src\\a.ts')).toBe('apps/web/src')
  })

  it('同一目录的不同文件 ⇒ 同一目录键(目录数是唯一集合)', () => {
    expect(fileDirname('apps/web/src/a.ts')).toBe(fileDirname('apps/web/src/b.ts'))
  })

  it('裸文件名没有目录 ⇒ 空串(不得造出 "/" 这种假目录)', () => {
    expect(fileDirname('a.ts')).toBe('')
    expect(fileDirname('')).toBe('')
  })

  it('盘根 / 根不算目录(截到根就没有"目录"可言)', () => {
    expect(fileDirname('C:/a.ts')).toBe('')
    expect(fileDirname('/a.ts')).toBe('')
  })

  it('与 fileBasename 同源:dir + "/" + base 还原原路径(末段口径不漂移)', () => {
    for (const path of ['apps/web/src/a.ts', 'a.ts', 'D:/proj/x/y.ts']) {
      const dir = fileDirname(path)
      const base = fileBasename(path)
      expect(dir === '' ? base : `${dir}/${base}`).toBe(path.replace(/\\/g, '/'))
    }
  })
})
