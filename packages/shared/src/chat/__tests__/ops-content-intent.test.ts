import { describe, expect, it } from 'vitest'

import {
  OPS_CONTENT_READ_INTENT_TOOLS,
  OPS_CONTENT_WRITE_INTENT_TOOLS,
  opsContentToolsFor,
} from '../ops-content-intent'
import { ADMIN_CONTENT_TOOL_NAMES } from '../workspace-tool-executor'

describe('ops-content-intent(G-17)', () => {
  it('意图表与执行器 admin 清单成员一致(两处名单不许漂;序可异)', () => {
    expect([...OPS_CONTENT_READ_INTENT_TOOLS, ...OPS_CONTENT_WRITE_INTENT_TOOLS].sort()).toEqual(
      [...ADMIN_CONTENT_TOOL_NAMES].sort(),
    )
  })

  it('无文本 / 无资源词 ⇒ 空数组(保住打字机流式)', () => {
    expect(opsContentToolsFor('')).toEqual([])
    expect(opsContentToolsFor(null)).toEqual([])
    expect(opsContentToolsFor(undefined)).toEqual([])
    expect(opsContentToolsFor('帮我写个周报')).toEqual([])
  })

  it('只出现资源词 ⇒ 仅读工具(宽松召回)', () => {
    for (const text of [
      '看一下现在的公告',
      '轮播图有哪些',
      '运营位配置在哪',
      'show me the banner list',
    ]) {
      expect(opsContentToolsFor(text)).toEqual([...OPS_CONTENT_READ_INTENT_TOOLS])
    }
  })

  it('资源词 + 动作词同现 ⇒ 读 + 写工具全带', () => {
    for (const text of [
      '发一条公告说今晚维护',
      '新建一个首页轮播图',
      '把那个轮播图下架',
      '更新公告内容',
    ]) {
      const got = opsContentToolsFor(text)
      expect(got).toContain('announce_create')
      expect(got).toContain('carousel_update')
    }
  })

  it('删除类话术不携带写工具(删除走后台,不进对话)', () => {
    expect(opsContentToolsFor('删掉那条公告')).toEqual([...OPS_CONTENT_READ_INTENT_TOOLS])
    expect(opsContentToolsFor('移除这个轮播图')).toEqual([...OPS_CONTENT_READ_INTENT_TOOLS])
  })
})
