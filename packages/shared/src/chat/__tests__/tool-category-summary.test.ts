import { describe, expect, it } from 'vitest'

import { ACTIVITY_CATEGORIES, summarizeToolActivity, toolCategory } from '../tool-category'

describe('summarizeToolActivity', () => {
  it('空集返回全零，不抛错', () => {
    expect(summarizeToolActivity([])).toEqual({
      total: 0,
      running: 0,
      failed: 0,
      byCategory: { file: 0, image: 0, search: 0, thinking: 0, custom: 0 },
    })
  })

  it('分类只走 toolCategory：五类各计一枚', () => {
    const items = [
      { toolName: 'read_file', status: 'success' as const },
      { toolName: 'image_generation', status: 'success' as const },
      { toolName: 'web_search', status: 'success' as const },
      { toolName: 'analyze_code', status: 'success' as const },
      { toolName: 'some_plugin_dynamic_tool', status: 'success' as const },
    ]
    const summary = summarizeToolActivity(items)
    expect(summary.total).toBe(5)
    expect(summary.byCategory).toEqual({
      file: 1,
      image: 1,
      search: 1,
      thinking: 1,
      custom: 1,
    })
    for (const item of items) {
      expect(summary.byCategory[toolCategory(item.toolName)]).toBeGreaterThan(0)
    }
  })

  it('running / error 计数，cancelled 不算失败也不算运行', () => {
    const summary = summarizeToolActivity([
      { toolName: 'read_file', status: 'running' },
      { toolName: 'read_file', status: 'success' },
      { toolName: 'web_search', status: 'error' },
      { toolName: 'web_search', status: 'cancelled' },
    ])
    expect(summary.total).toBe(4)
    expect(summary.running).toBe(1)
    expect(summary.failed).toBe(1)
    expect(summary.byCategory.file).toBe(2)
    expect(summary.byCategory.search).toBe(2)
  })

  it('类目全集与分类函数输出域一致（新增类目必须同批进 ACTIVITY_CATEGORIES）', () => {
    const names = [
      'read_file',
      'image_generation',
      'web_search',
      'analyze_code',
      'unknown_tool_xyz',
    ]
    const seen = new Set(names.map((name) => toolCategory(name)))
    expect([...seen].sort()).toEqual([...ACTIVITY_CATEGORIES].sort())
  })
})
