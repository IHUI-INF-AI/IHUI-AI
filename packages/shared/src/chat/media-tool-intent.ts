/**
 * 媒体类工具的**意图→工具集**策略(单一源)。
 *
 * 为什么放共享层:这张表决定"哪些话术会让模型看见 `video_generation` 这个会花钱的工具"。
 * 第二个真相源迟早会漂(一端放宽、另一端没跟),而漂了不体现在报错上,只体现在
 * "同样一句话在这个端能出片、在那个端不行"。与 `./file-tool-intent` 同一条口径。
 *
 * 一条实测边界(2026-10-29):`video_generation` 的工具实现与渲染早就在仓里
 * (mcp_server 的 handler + web `tool-call-card.tsx` 的 VideoResultBlock),
 * 但**普通对话从来不携带它** —— `tool-config.ts` 的 AGENT_TOOLS 里没有任何媒体工具,
 * 而后端 `llm.py` 没有 agentTools 就不进 tool loop。于是"渲染能力齐备但模型看不见",
 * 表现为用户说"给我做段视频"时模型只能回文字。本表就是补这一格。
 *
 * 消费方(走子路径 `@ihui/shared/chat/media-tool-intent`,**不进 `./chat` barrel**:
 * 与 file-tool-intent 同一约定,避免 `export *` 产出的名字歧义):
 *  - `apps/web/src/hooks/use-chat/tool-config.ts`(re-export)
 */

/** 视频族:只有明确"生成一段视频"的意图才携带 —— 它是计费工具,宁可少给不可多给。 */
export const VIDEO_INTENT_TOOLS: readonly string[] = ['video_generation']

/**
 * 命中条件二选一:
 *  1. 生成动词 + 视频名词(允许中间夹"一段/一个5秒的/竖屏"这类限定);
 *  2. 消息里出现 `task_xxx` 任务号 —— 那是"我上次那条视频好了吗"的取件追问,
 *     工具层的查询模式(传 task_id 不传 prompt)就是为这句话准备的。
 */
const VIDEO_INTENT_RE =
  /(生成|制作|做|拍|出|合成|渲染|剪辑)[^。\n]{0,12}(视频|短片|动画|mv|视频片段)|(视频|短片|动画)[^。\n]{0,12}(生成|制作|拍一段|来一段)|文生视频|图生视频|text2video|image2video|video generation|(?:make|generate|create)\s+(?:a|an)?\s*(?:short\s+)?video|task_[A-Za-z0-9]{6,}/i

/** 按用户输入挑视频族工具;无匹配返回空数组,保住"无工具→打字机逐 token"的流式效果。 */
export function videoToolsFor(content: string): string[] {
  if (!content) return []
  return VIDEO_INTENT_RE.test(content) ? [...VIDEO_INTENT_TOOLS] : []
}
