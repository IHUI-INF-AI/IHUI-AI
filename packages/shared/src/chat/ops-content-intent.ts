/**
 * 运营内容工具(公告/轮播)的**意图→工具集**策略(单一源,G-17,2026-11-28 立)。
 *
 * 与 `file-tool-intent.ts` 同一范式与同一条安全纪律:这张表决定"哪些用户话术会让
 * 模型拿到 `announce_create` 这类写工具",第二份真相迟早漂(一端放宽正则、另一端没跟),
 * 且漂了不体现在报错上,只体现在"同样的话在这个端能发公告、在那个端不能"。
 *
 * 一条**实测边界**(写给下一个想扩消费方的人,与 file-tool-intent 同型):
 * 这张表只在"该端有委托执行面"时才等于能力。运营内容工具由 llm.py 的
 * `_ADMIN_DELEGATE_TOOLS` 分支发 tool-delegate 帧,由端侧执行器用**用户本人会话**
 * 调既有 admin 端点 —— 没有 `onToolDelegate` + tool-result 回传的端(RN/桌面 Tauri
 * 当前不宣告这些名字)不要 import 本表;误宣告的后果是模型调了、没人执行、60s 超时。
 *
 * 口径:读操作宽松召回(出现资源词即带读工具);写操作仅明确动作词与资源词**同现**
 * 才携带(与 file-tool-intent 的"写族仅明确修改动词"同档)。没有删除类工具,
 * 所以"删掉公告"类话术不携带写工具 —— 模型会得到明确的意图不匹配,这是刻意的:
 * 删除走后台管理界面,误删面不进对话。
 */

/** 读族:出现公告/轮播类资源词即携带(供模型查列表、拿 id、看现状)。 */
export const OPS_CONTENT_READ_INTENT_TOOLS: readonly string[] = ['announce_list', 'carousel_list']

/** 写族:资源词 + 明确动作词同现才携带(执行前另有 tool-approval 审批卡兜一道)。 */
export const OPS_CONTENT_WRITE_INTENT_TOOLS: readonly string[] = [
  'announce_create',
  'announce_update',
  'carousel_create',
  'carousel_update',
]

const RESOURCE_PATTERN = /(公告|轮播|运营位|横幅|banner|Banner|首页推荐位|活动位)/

/** 写动词刻意不含"删除/移除/撤稿"——删除类操作不进对话,走后台管理界面。 */
const WRITE_VERB_PATTERN =
  /(发布|创建|新建|新增|发一条|发个|发一篇|上架|下架|撤下|隐藏|置顶|取消置顶|修改|编辑|更新|添加|建一个|加一个|换个|改一下|改一改)/

/**
 * 按消息内容返回应携带的运营内容工具名(无命中返回空数组,保住打字机流式)。
 * 消费方:apps/web/src/hooks/use-chat/tool-config.ts(re-export)→
 * send-message.ts / send-answer.ts 合并进 agentTools。
 */
export function opsContentToolsFor(text: string | null | undefined): string[] {
  if (!text) return []
  if (!RESOURCE_PATTERN.test(text)) return []
  if (WRITE_VERB_PATTERN.test(text)) {
    return [...OPS_CONTENT_READ_INTENT_TOOLS, ...OPS_CONTENT_WRITE_INTENT_TOOLS]
  }
  return [...OPS_CONTENT_READ_INTENT_TOOLS]
}
