/**
 * 跨端支付结果三态契约（2026-11-27）。
 *
 * 立因（台账 I-08）：Web 充值结果页、RN PayResultScreen、小程序 pkg-shop/pay/result 各自
 * 维护状态映射，同一后端 order.status 在不同端会出现 paid/pending/failed 之外的分支。
 * 这里只保留三端都认的三态，并把所有非成功、非等待状态统一收成 failed。
 *
 * 纪律：只做纯映射，不读平台 API；订单查询端点仍是 `GET /api/payment/orders/:orderNo`，
 * 三端共用同一份服务端订单状态，不在客户端猜支付结果。
 */

export type PaymentResultStatus = 'pending' | 'paid' | 'failed'

/** 结果页轮询间隔（2s）与上限（30 次 = 60s），与 RN/小程序现状一致。 */
export const PAYMENT_RESULT_POLL_INTERVAL_MS = 2000
export const PAYMENT_RESULT_MAX_POLLS = 30

/**
 * 服务端订单状态 → 结果页三态。
 * paid 只认字面量 paid；pending/processing 归等待；其余（cancelled/closed/refunded/failed/
 * 空值/未知）按 failed 处理，避免把未支付订单显示成成功。
 */
export function normalizePaymentResultStatus(status: string | null | undefined): PaymentResultStatus {
  if (status === 'paid') return 'paid'
  if (status === 'pending' || status === 'processing') return 'pending'
  return 'failed'
}

/** 是否终态（可以停止轮询）。 */
export function isPaymentResultTerminal(status: PaymentResultStatus): boolean {
  return status !== 'pending'
}
