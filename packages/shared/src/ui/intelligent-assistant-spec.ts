/**
 * 智汇值卡片(IntelligentAssistant)的几何单一源(小程序端与 RN 端共用),模式同 `back-chevron-spec.ts`。
 *
 * 收编前两端的分叉(同一元素各留一份,且都没有 web 既有值可参照):
 *  - 卡片外边距:小程序 `margin: 16rpx`(8px)vs RN `marginHorizontal: 4 / marginBottom: 4`(仅顶 8);
 *  - 卡片内边距:小程序 `padding: 24rpx`(12px)vs RN `padding: 4`;
 *  - 问候语字号/字重:小程序 28rpx(14px)/500 vs RN 19/700;
 *  - 副标题字号:两端同为 12,但字重 400 vs 700;
 *  - 智汇值行字号:小程序 24rpx(12)vs RN 13;行间距:小程序 12rpx(6)vs RN 实际视觉 4+2+5=11;
 *  - 充值可点块:小程序裸文字(≈17px)/ RN 胶囊(≈22px),都低于移动端触控下限。
 *
 * 裁决依据(本票规则 2 —— 本卡在 `apps/web` 无既有值):间距取两端较大者(外边距 8、内边距 12、
 * 行间距 11),字号 ≥12 且取较大的一档(问候语 19、智汇值行 13),命中块 ≥44(充值文字按钮按本表
 * 换算补到 44)。字重随"被采纳字号的同端"成套取 700,不再另造一档 —— 拆开取会把一次定档
 * 变成两次裁决,漂移面积翻倍。
 *
 * 不进本表的东西(平台机制差异,登记在交付报告 waivers,不是待偿债务):
 *  - 圆角:裁决为 2xl 档,但两端各自的落点是 CSS `var(--radius-2xl)` 与 `rnRadius['2xl']`,
 *    同引 `packages/design-tokens/src/radius.js` 一张表 —— 这里若再存第三个数字就是第二份真相;
 *  - 悬浮动画:小程序 CSS keyframes 在位,RN 无对应通道(要接 Animated),数值对齐≠机制接通;
 *  - 充值按钮观感:小程序纯文字链 vs RN 实底胶囊 —— 设计定夺项,本票不动外观。
 *
 * 机器人装饰与胶囊内衬的**取值**(墨迹 32 / 位图 107×110 等)自票④起数字住进本表(单端档,
 * 见下方登记块),但**异形的结论一字未改**:小程序行内矢量与 RN 可选位图是不同媒介、不同布局
 * 角色,不构成同一元素,不为对齐去把一端改成另一端的形态。本表对它们兑现的是"数字只有一个
 * 存放处",不是"两端同档"。
 *
 * 消费方式只能是子路径 `@ihui/shared/ui/intelligent-assistant-spec`,**禁止挂根桶**(§根桶教训:
 * 会把他人在途 chat/* 拉进消费端编译面)。本表只存逻辑 px;小程序侧换算 `(px)=>rpx(px*TARO_RPX_PER_PX)`,
 * RN 侧 1:1(dp)。
 *
 * 票⑤复裁取证(现读核对后**本卡一个数值都没改**):两端共用的 9 枚档(margin 8 / padding 12 /
 * 字号 19·12·13·12 / 行距 4·11 / 顶偏移 4)全部已引本表且同值,即**不存在"同一元素两端取不同值"**
 * 可收敛;其余单侧档逐条都是"另一腿不渲染该元素或该通道",按裁决规则既不造它、也不删档凑数、
 * 更不给单端补裸数字:
 *  - 装饰图层:小程序走行内矢量(`IA_ROBOT_ICON_INK_PX`),RN 走 absolute 位图(`IA_ROBOT_DECOR_*`),
 *    而 `robotImage` 这个 prop 在 HEAD 面上**没有任何生产调用方** —— 四处 `<IntelligentAssistant/>`
 *    调用点(AgentScreen / AiAssistantN8nScreen / ChatScreen / HomeScreen)都没传它,只有
 *    `apps/mobile-rn/tests/intelligent-assistant.test.tsx` 传。RN 那一层在生产里根本不渲染,
 *    把它的数对到小程序侧等于凭空新增一个渲染元素(§24 需用户批准)。
 *  - 充值胶囊(`IA_RECHARGE_CAPSULE_PAD_*`)与值行间距(`IA_RECHARGE_GAP_PX`):小程序的充值是纯文字链、
 *    值行走 `justify-content: space-between`,这两格在本端不存在。
 *  - `IA_TEXT_INDENT_PX`:RN 避让的正是上面那层不渲染的装饰;本端文本左缘由行内矢量加
 *    `IntelligentAssistant.css` 里 `.ia-robot` 的流内间隙撑出 —— 版面结构差异,不是取数分叉。
 *  - `IA_RECHARGE_HIT_PX`:"命中块 ≥44"这一裁决两端**同源且同通道**(2026-09-27 收口)。此前本端
 *    以派生档 `IA_RECHARGE_TOUCH_PAD_PX`(=(44−16)/2 的上下内衬)兑现同一裁决 —— 派生式让 SL 尺子
 *    把它读成"仅 RN 引用"(派生档不具名入档表),而内衬补量与 RN 的 `minHeight` 是同一裁决的两种
 *    落点。现两端都走可点外壳 `minHeight: IA_RECHARGE_HIT_PX`、可见文字不补量,派生档与其减数
 *    `IA_RECHARGE_LINE_BOX_PX` 随本次退役(已无消费方)。观感不变:旧"文字行盒 16 + 上下衬 14"
 *    与新"44 高外壳垂直居行盒 16"落位同像素,故这是几何通道统一,不是单端补数字消账 —— 消账型
 *    改法(在旧内衬之上再加 minHeight)仍属禁止。
 * 一条覆盖面事实留给判据持有者(不是本票的处置范围):同名配对只吃两端的 `.tsx`,`.css` 因规范化名
 * 多出 `css` 后缀而永不配对,所以 `.ia-robot` 那类留在 CSS 里的端侧字面量对本门不可见;把它迁进本表
 * 反而会让本族单侧档读数从 9 涨到 10 而当场判红(构造面实测)—— 修法是该门补 CSS 腿,
 * 不该由端侧把数字留在暗处换取绿灯。
 *
 * ── O02 票④(第 ④ 格)收口证据:本族逐条归属(2026-10-28 现读)──────────────────
 * 读数(`node scripts/check-cross-end-ui-parity.mjs --json`,HEAD 5121f499d0c309ba419e61edd3092667867845df):
 *   findings[IntelligentAssistant] = diffCount 6 / radiusCount 1 / elementRadiusCount 0;
 *   几何仅小程序 32;几何仅 RN 3·9·16·107·110;RD 仅 RN 4(端上实取 4/8);
 *   SL IntelligentAssistant(8)= 仅小程序 IA_ROBOT_ICON_INK_PX + 仅 RN IA_ROBOT_DECOR_W/H/RIGHT、
 *   IA_TEXT_INDENT、IA_RECHARGE_GAP、IA_RECHARGE_CAPSULE_PAD_X/Y。
 *   负值档 IA_ROBOT_DECOR_TOP_PX(-8) 不进几何读数,归属仍是 RN 单端 ⇒ 本族**单端档实为 9 枚**
 *   (门点名 8 + 负值 1;上面"9 涨到 10"那句数的是这 9 枚,不是 SL 的 8)。
 *
 * 20 枚导出档(19 枚 `_PX` + `IA_HEADING_FONT_WEIGHT`)逐条归属,三类:
 *  A 一端根本没有该元素(往另一端补引用 = 往屏幕上加一个不存在的节点):
 *    小程序 32        IA_ROBOT_ICON_INK_PX        行内矢量;RN 同一位置是 absolute 位图装饰,不同媒介
 *    RN 107/110/9/-8  IA_ROBOT_DECOR_*            位图装饰布局盒与贴位;小程序无 absolute 装饰层
 *    RN 10/3          IA_RECHARGE_CAPSULE_PAD_*   实底胶囊可见内衬;小程序是纯文字链,无胶囊本体
 *    RN 4(圆角)      tokenButton `rnRadius.sm`    同上,胶囊本体小程序没有 ⇒ radiusCount 1
 *  B 同一元素两端按**已裁决**的变体契约取不同档:本族 **0 枚** —— 11 枚两端共用档(10 枚 `_PX`
 *    + IA_HEADING_FONT_WEIGHT)已全部引本表且同值,不存在"同元素取不同值"可收敛的档。
 *    (充值"纯文字链 vs 实底胶囊"是设计定夺项,已登记在头注 waivers,不是 B 的取值分叉。)
 *  C 同槽位留白,两端各由自身机制决定(量纲/机制不同,不是同一个量的两条写法):
 *    RN 16  IA_TEXT_INDENT_PX   避让 absolute 装饰;小程序文本左缘由行内矢量 + `.ia-robot`
 *                               `margin-right: 20rpx`(=10)的流内间隙撑出
 *    RN 10  IA_RECHARGE_GAP_PX  值行左聚拢的固定间距;小程序 `.ia-token-row` 用
 *                               `justify-content: space-between` 由容器宽度动态决定
 *
 * ⇒ 结论:本族**无可继续收敛项(0 处)**。两处"两端同值"的相邻数字都不是同一元素:小程序
 *   `.ia-robot` 的 10 与 RN 的 10(胶囊内衬 / 值行间距)是三个不同槽位;小程序行距/顶偏移的 4
 *   与 RN 胶囊圆角的 4,前者两端已同源、后者是胶囊独有。9 枚单端档**不得入表**:入表即新增 SL
 *   单侧引用当场判红(本门 `specLegAudit` 只把基线已登记的单侧档降为只报数;input-area 族
 *   2026-10-28 实测 `SL 36→37`)。单端档的正确去处 = 端内裸数字 + 本头注清单,归属由
 *   `__tests__/intelligent-assistant-wiring.test.ts` 的登记表机器钉住(补引用 / 脱线都会红)。
 */

