/**
 * 智汇值卡片(IntelligentAssistant)的几何单一源(小程序端与 RN 端共用),模式同 `back-chevron-spec.ts`。
 *
 * 收编前两端的分叉(同一元素各留一份,且都没有 web 既有值可参照):
 *  - 卡片外边距:小程序 `margin: 16rpx`(8px)vs RN `marginHorizontal: 4 / marginBottom: 4`(仅顶 8);
 *  - 卡片内边距:小程序 `padding: 24rpx`(12px)vs RN `padding: 4`;
 *  - 问候语字号/字重:小程序 28rpx(14px)/500 vs RN 19/700;
 *  - 副标题字号:两端同为 12,但字重 400 vs 700;
 *  - 智汇值行字号:小程序 24rpx(12)vs RN 13;行间距:小程序 12rpx(6)vs RN 实际视觉 4+2+5=11;
 *  - 充值可点块:小程序裸文字(≈17px)/ RN 胶囊(≈22px),都低于移动端触控下限。
 *
 * 裁决依据(本票规则 2 —— 本卡在 `apps/web` 无既有值):间距取两端较大者(外边距 8、内边距 12、
 * 行间距 11),字号 ≥12 且取较大的一档(问候语 19、智汇值行 13),命中块 ≥44(充值文字按钮按本表
 * 换算补到 44)。字重随"被采纳字号的同端"成套取 700,不再另造一档 —— 拆开取会把一次定档
 * 变成两次裁决,漂移面积翻倍。
 *
 * 不进本表的东西(平台机制差异,登记在交付报告 waivers,不是待偿债务):
 *  - 圆角:裁决为 2xl 档,但两端各自的落点是 CSS `var(--radius-2xl)` 与 `rnRadius['2xl']`,
 *    同引 `packages/design-tokens/src/radius.js` 一张表 —— 这里若再存第三个数字就是第二份真相;
 *  - 机器人装饰:小程序是行内 LineIcon 矢量(墨迹 64rpx=32px),RN 是可选位图装饰
 *    (107×110,absolute 压在卡上)—— 不同媒介、不同布局角色,不构成同一元素;
 *  - 悬浮动画:小程序 CSS keyframes 在位,RN 无对应通道(要接 Animated),数值对齐≠机制接通;
 *  - 充值按钮观感:小程序纯文字链 vs RN 实底胶囊 —— 设计定夺项,本票不动外观,只统一字号与命中。
 *
 * 消费方式只能是子路径 `@ihui/shared/ui/intelligent-assistant-spec`,**禁止挂根桶**(§根桶教训:
 * 会把他人在途 chat/* 拉进消费端编译面)。本表只存逻辑 px;小程序侧换算 `(px)=>rpx(px*TARO_RPX_PER_PX)`,
 * RN 侧 1:1(dp)。
 */

/** 卡片外边距(四周,逻辑 px)。取值依据:规则 2 间距取较大端 —— max(小程序 8, RN 8/4/4)。 */
export const IA_MARGIN_PX = 8

/** 卡片内边距(逻辑 px)。取值依据:规则 2 间距取较大端 —— max(小程序 12, RN 4)。 */
export const IA_PADDING_PX = 12

/** 问候语字号(逻辑 px)。取值依据:规则 2 字号 ≥12 取较大端 —— max(14, 19)=19。 */
export const IA_GREETING_FONT_PX = 19

/** 副标题字号(逻辑 px)。两端收编前已同值(12),且恰等于规则 2 的字号下限。 */
export const IA_SUBTITLE_FONT_PX = 12

/** 智汇值行("剩余智汇值: N")字号(逻辑 px)。取值依据:max(12, 13)=13。 */
export const IA_TOKEN_FONT_PX = 13

/** 充值按钮文字字号(逻辑 px)。两端收编前已同值(12)。 */
export const IA_RECHARGE_FONT_PX = 12

/**
 * 卡内文字的统一字重。字符串形态是刻意的:RN `TextStyle.fontWeight` 只接字面量联合,
 * number 700 编译不过;CSS 侧 `'700'` 同值合法。随被采纳字号(19/12/13/12 均来自 RN 侧组合)
 * 成套取 700,小程序侧字重 500/400 一并升档 —— 这是可见变化,由"两端逐档同值"的验收标准背书。
 */
export const IA_HEADING_FONT_WEIGHT = '700' as const

/** 问候语 → 副标题 的行距(逻辑 px)。两端收编前已同值(小程序 8rpx / RN paddingTop 4)。 */
export const IA_TEXT_GAP_PX = 4

/**
 * 副标题 → 智汇值行 的行距(逻辑 px)。取值依据:规则 2 间距取较大端 ——
 * max(小程序 12rpx=6, RN 实际视觉 4+2+5=11)= 11。RN 侧原先由三段 padding/margin 拼出 11,
 * 收编后由本常数单点承担(那三段随收编删除,不留组合式第二真相)。
 */
export const IA_TOKEN_ROW_GAP_PX = 11

/** 充值命中的最小方块(逻辑 px)。规则 2:命中块 ≥44。 */
export const IA_RECHARGE_HIT_PX = 44

/** 12px 字号 + `line-height:1.34` 的声明行盒(逻辑 px),命中补量的减数;两端同声明值。 */
export const IA_RECHARGE_LINE_BOX_PX = 16

/**
 * 小程序侧充值文字的内衬补量(上下各这么多,逻辑 px)。派生式 =(命中块 − 行盒)/2:
 * 小程序没有 hitSlop 通道,只能把可见盒撑到 ≥44;RN 侧可见胶囊不放大、命中走
 * `minHeight: IA_RECHARGE_HIT_PX`(见端内注释)—— 数值同源,通道各端保留。
 */
export const IA_RECHARGE_TOUCH_PAD_PX = (IA_RECHARGE_HIT_PX - IA_RECHARGE_LINE_BOX_PX) / 2
