/**
 * Input 族的结构与几何单一源(web 薄壳与 RN 薄壳共用),形状照 card-spec / badge-spec / tooltip-spec。
 *
 * 两端真实实现坐标:
 *  - web 端 = packages/ui-react/src/components/input.tsx(forwardRef<HTMLInputElement>,
 *    `ComponentProps<'input'>`,:14 一条 `cn` 串是几何的唯一落点,26 行纯薄壳);
 *  - RN 端  = packages/ui-native/src/input.tsx(`ComponentProps<typeof TextInput>` +
 *    **123 行 AI 可填注册逻辑**(:20-31 的契约注释 + :38-119 的 register / useEffect:
 *    受控与非受控分流、结构性敏感字段屏蔽、UiFieldHandle 生命周期);
 *    几何落点只有 :123-126 那一条 `cn` 串,149 行)。
 *
 * ⚠️ 本票**只沉几何**:RN 端那 123 行注册逻辑一行未动 —— 它是「AI 能看见/能写哪些输入框」
 * 的行为契约(`registerUiField` 的 kind/label/value/writable/write 五件套),不是视觉几何;
 * 动它等于改另一族的契约。同理,「两端壳都消费每个常量」这条硬要求的**判定范围**
 * 也只到几何常量,不扩到逻辑面(wiring 判据读的是两端壳源码里的常量消费)。
 *
 * 本表只存**取值档**,不存承载形式;承载形式(类名 / 样式表)留在两端薄壳里。
 * 代价是两端壳必须把本表的**每一个**导出常量都接走并真用 —— 挂了常量却没人消费就是"造好没装车",
 * 由同族判据 packages/shared/src/ui/__tests__/input-wiring.test.ts 逐条判红。
 *
 * 本族要收的**核心档** = 输入框高度:
 *  - web:14 `h-9` = 36;
 *  - RN :124 `h-10` = 40。
 *  由 `INPUT_HEIGHT_PX` 收口(裁定见该常量注释)。
 *  其余已同值的四档(圆角 / 横向内边距 / 字号 / 边框宽)两端**同义同值** ⇒ 本票的作用是**回归锁**。
 *
 * 承载机制差异(规则6:机制,非取值分叉,逐条登记 —— 允许不同形,**不下沉**):
 *  - `py-1`(web:14):仅 web。RN 的 `TextInput` 纵向由平台自带行高撑开,再加纵向内边距会与
 *    单点定档的 INPUT_HEIGHT_PX 打架(高度已经被定死,再给 py 是把同一段纵向空间定两次)。
 *    ⇒ 它是 web 的**承载补偿**,不是与 RN 同义的档,按规则6 登记,不下沉。
 *  - `shadow-sm`(web:14):仅 web。控件级投影是 web 视觉通道(见 card.tsx:29-31 的定档注释:
 *    「控件(button/input 的 shadow-sm)与浮层(dialog 的 shadow-lg)不在此列」),
 *    RN 端输入框不带投影通道。
 *  - `w-full`(web:14):web 的块级宽度承载;RN 的 `TextInput` 宽度由父容器决定,无此通道。
 *  - `transition-colors` / `focus-visible:*` / `file:*` / `disabled:*`(web:14):仅 web,
 *    依赖 CSS 伪类 / 伪元素通道。
 *  - focus 边框色:web 走 `focus-visible:border-primary`(CSS 通道);RN 走 **style prop**
 *    (RN:127 `style={[style, focused ? { borderColor: primaryColor } : null]}`)。
 *    ⚠️ 这一条**不是**"web 薄壳可以用内联 style"的例外:内联 style 的禁令只针对 **web 端**
 *    (调用方大量用 `className` 覆盖,内联会盖死覆盖);RN 端之所以走 style,是 2026-07-28 修
 *    NativeWind 4.x + React 19 的 setState 警告 —— 动态 className 会触发样式订阅,
 *    必须把动态边框色迁到 style 让 className 保持稳定(见 input.tsx:33-37 原注释)。
 *    本票没有触碰这条:它管的是**色**,本票管的是**几何**。
 *  - `placeholderTextColor="#9ca3af"`(RN:128):RN 端没有 `placeholder:text-*` 伪元素通道。
 *  - `border-input` 两端同名但取值来源不同(web 走 CSS 变量,RN 走 nativewind 主题)
 *    ⇒ 同 badge-spec 的色值裁定:**色值不下沉**,本表只沉几何(边框**宽度**)。
 *  - AI 可填注册(RN:20-31,:38-119):仅 RN,web 端没有 field-host 通道 ⇒ 规则6。
 *  - 类名字面量:两端都写 Tailwind 风格类,但**字面量必须留在两端壳里** —— spec 文件不在
 *    Tailwind / nativewind 的扫描面内,把类名搬进 spec 会让规则根本不产出。
 *  ⇒ 上述不同形由 parity 基线入账(waivers 之外的锚点登记),不算欠债。
 *
 * 单端档(本票**不收**,逐条登记留痕 —— 免得被"已下沉"的账盖掉):
 *  - `py-1` / `shadow-sm` / `w-full`:见上「承载机制差异」,是 web 的承载补偿与视觉通道,不是同义档。
 *  - `placeholderTextColor` / `secureTextEntry` / `keyboardType` / `multiline` / `maxLength`:
 *    RN 端的输入**行为**档,web 端走 HTML input 的原生属性另一条通道 ⇒ 规则6。
 *
 * 消费方式:子路径 `@ihui/shared/ui/input-spec`(禁挂根桶:同 card-spec:30-31,
 * 根桶出口会把整棵 src/chat 拉进被检程序,rn-app typecheck 从 0 错变 8 错,O81 实测)。
 * spec 内只存逻辑 px;web 端 1:1(CSS px),RN 端 1:1(逻辑 pt)。
 * 圆角**只给档名不给 px**:px 归 packages/design-tokens/src/radius.js 的 RADIUS_STEPS 与守门 77
 * 单源;本表只记"输入框取哪一档"。
 *
 * 裁定规则(同 card-spec:36-38):规则1 两端现值已同,收一处防再分叉;规则2 同义不同值取 compact
 * 较小档(取小会贴边/裁切才取较大档并写明);规则3 一端有档、另一端没这处留白 → 取较大者并让缺失端
 * 补同档;规则6 平台承载机制差异 → 允许不同形,注明理由。
 */

/**
 * 输入框高度 36(规则2:同义不同值取 compact 较小档)。
 * 分歧现场:web:14 `h-9` = 36 vs RN:124 `h-10` = 40。
 * 取 36 的理由:
 *  - web 的 36 是全站既有表单行高的排布基准(表单栅格、按钮 `h-9`、标签行都按它对齐),
 *    抬到 40 会让 web 端所有表单行整体胀 4px;
 *  - 取小**不裁切**:36 装 `text-sm`(20px 行高)+ `px-3` 横向内边距绰绰有余,两端都不产生截断;
 *  - RN 的 40 是端内写死的类(`h-10`),无对外契约;40 → 36 只动高度这一格,不动那 123 行注册逻辑。
 * ⇒ RN 端由 40 收敛到 36(承载类随之 `h-10` → `h-9`),web 端保持 36。
 * 注:36 仍低于移动端 44pt 触摸目标建议值,但**两端现值(36 / 40)本来就都不达标**,
 * 把触摸目标抬到 44 是另一张产品定档票,不是本票"取值收口"能定的事 ⇒ 登记在此,不许被本票的账盖掉。
 */
export const INPUT_HEIGHT_PX = 36

/**
 * 圆角档 'sm'(规则1):两端现值均已 `rounded-sm`(web:14 / RN:124)。
 * 只给档名不给 px —— px 由 radius.js 单源产出;两端各自把档名映射成本端承载类名。
 */
export const INPUT_RADIUS_TIER = 'sm'

/**
 * 横向内边距 12(规则1):两端同为 `px-3` = 12(web:14 / RN:124)。已同值 ⇒ 回归锁。
 * 纵向内边距**不下沉**:web 有 `py-1` 而 RN 没有,且 RN 的高度已由 INPUT_HEIGHT_PX 单点定档
 * ⇒ 那是 web 的承载补偿(规则6),不是两端同义的档(见头注)。
 */
export const INPUT_PADDING_X_PX = 12

/**
 * 字号档 'sm'(规则1):两端同为 `text-sm` = 14(web:14 / RN:124)。
 * 只给档名不给 px —— 字号档由两端各自的 Tailwind / nativewind 尺度产出,本表不复制一份 px,
 * 免得同一语义出现两个可改点。
 */
export const INPUT_TEXT_TIER = 'sm'

/**
 * 边框宽度 1(规则1):两端同为 `border` = 1(web:14 / RN:124)。已同值 ⇒ 回归锁。
 * 只收**宽度**不收**色**:`border-input` 两端同名但取值来源不同(web CSS 变量 / RN nativewind 主题),
 * 色值是 token 消费,搬进 spec 会脱离扫描面 ⇒ 同 badge-spec 的色值裁定。
 */
export const INPUT_BORDER_WIDTH_PX = 1
