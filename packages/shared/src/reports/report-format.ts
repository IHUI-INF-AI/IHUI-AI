/**
 * 报告的读数格式化(纯格式化,零 IO)。
 *
 * 为什么把三件格式化收在一处:Intl 构造子在 locale/timeZone 取值坏时会抛 RangeError,
 * 而一份诊断报告不能因为"时区写错了"就整份出不来 ⇒ 每处都有回落档,且回落是**可见的**(带标注),
 * 不是静默换个 locale 猜一遍。
 */
import { roundPercent } from './trace-metrics'
import type { createCopyCollector } from './report-copy'
import { AGENT_REPORT_COPY_KEYS as K } from './report-copy'

type Copy = ReturnType<typeof createCopyCollector>

export type NumberFormatter = (value: number) => string

export function makeNumberFormatter(locale?: string): NumberFormatter {
  let formatter: Intl.NumberFormat | null = null
  try {
    formatter = new Intl.NumberFormat(locale ?? 'en', { maximumFractionDigits: 2 })
  } catch {
    formatter = null
  }
  return (value) => (formatter ? formatter.format(value) : String(value))
}

/** ms/s 两档:技术单位不成句,故不进取词表(否则会为了 "ms" 拉五语言同批) */
export function formatDurationMs(ms: number): string {
  if (ms < 1000) return `${Math.round(ms)} ms`
  return `${(ms / 1000).toFixed(2)} s`
}

export function formatShare(ratio: number, nf: NumberFormatter): string {
  return `${nf(roundPercent(ratio))}%`
}

/** 轨迹导出的那一刻;坏值回显原串并显式标注,不折成"未知时刻"这种丢信息的说法 */
export function formatTraceInstant(
  exportedAt: string,
  locale: string | undefined,
  timeZone: string | undefined,
  copy: Copy,
): string {
  try {
    const date = new Date(exportedAt)
    if (Number.isNaN(date.getTime())) throw new RangeError('unparsable instant')
    const options: Intl.DateTimeFormatOptions = { dateStyle: 'medium', timeStyle: 'medium' }
    if (timeZone) options.timeZone = timeZone
    return new Intl.DateTimeFormat(locale ?? 'en', options).format(date)
  } catch {
    return `${exportedAt} (${copy.copy(K.timeFallback)})`
  }
}
