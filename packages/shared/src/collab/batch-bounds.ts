/**
 * 一批协作写入最多 100 项，附件最多 10 个且每个不超过 50 MiB。
 * 没量到的计数不是 0，超限时只报告多出来的部分，不把请求长度当成已写入数。
 */

export const BATCH_ITEM_CAP = 100
export const ATTACHMENT_COUNT_CAP = 10
export const ATTACHMENT_BYTE_CAP = 50 * 1024 * 1024

export interface BatchAttachment {
  bytes: number | null
}

export type BatchVerdict =
  | { disposition: 'admitted'; reason: 'within-bounds'; missedIds: readonly string[] }
  | {
      disposition: 'refused'
      reason: 'item-cap' | 'attachment-count' | 'attachment-bytes'
      missedIds: readonly string[]
    }
  | {
      disposition: 'unjudged'
      reason: 'count-unmeasured' | 'attachments-unmeasured' | 'bytes-unmeasured'
      missedIds: null
    }

function finiteSize(value: number | null): value is number {
  return typeof value === 'number' && Number.isFinite(value) && value >= 0
}

export function judgeBatch(input: {
  itemIds: readonly string[] | null
  attachments: readonly BatchAttachment[] | null
}): BatchVerdict {
  if (input.itemIds === null) {
    return { disposition: 'unjudged', reason: 'count-unmeasured', missedIds: null }
  }
  if (input.attachments === null) {
    return { disposition: 'unjudged', reason: 'attachments-unmeasured', missedIds: null }
  }
  if (input.attachments.some((item) => !finiteSize(item.bytes))) {
    return { disposition: 'unjudged', reason: 'bytes-unmeasured', missedIds: null }
  }
  if (input.itemIds.length > BATCH_ITEM_CAP) {
    return {
      disposition: 'refused',
      reason: 'item-cap',
      missedIds: input.itemIds.slice(BATCH_ITEM_CAP),
    }
  }
  if (input.attachments.length > ATTACHMENT_COUNT_CAP) {
    return { disposition: 'refused', reason: 'attachment-count', missedIds: [] }
  }
  if (input.attachments.some((item) => (item.bytes as number) > ATTACHMENT_BYTE_CAP)) {
    return { disposition: 'refused', reason: 'attachment-bytes', missedIds: [] }
  }
  return { disposition: 'admitted', reason: 'within-bounds', missedIds: [] }
}
