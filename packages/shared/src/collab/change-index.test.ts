import { describe, expect, it } from 'vitest'

import { projectChangeIndex } from './change-index'

describe('projectChangeIndex', () => {
  it('只留下摘要、明细指针和路径', () => {
    expect(
      projectChangeIndex({
        id: 'c1',
        summary: '改了两处',
        detailRef: 'cd_c1.r1',
        fileCount: 1,
        files: [{ path: 'src/a.ts' }],
        conversationId: 's1',
      }),
    ).toEqual({
      disposition: 'projected',
      reason: 'summary-only',
      row: {
        id: 'c1',
        summary: '改了两处',
        detailRef: 'cd_c1.r1',
        fileCount: 1,
        paths: ['src/a.ts'],
      },
    })
  })

  it('没有明细指针是未判定，夹了正文则拒绝', () => {
    expect(projectChangeIndex({ id: 'c1', summary: 'x', fileCount: 0, files: [] }).reason).toBe(
      'detail-unmeasured',
    )
    expect(
      projectChangeIndex({
        id: 'c1',
        summary: 'x',
        detailRef: 'cd',
        fileCount: 1,
        files: [{ path: 'a.ts', content: 'secret' }],
      }).reason,
    ).toBe('detail-inlined')
  })
})
