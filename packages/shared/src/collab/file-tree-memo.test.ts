import { describe, expect, it } from 'vitest'

import { projectFileTree } from './file-tree-memo'

const KEY = 'ab'.repeat(16)

describe('projectFileTree', () => {
  it('只留下路径和尺寸', () => {
    expect(
      projectFileTree({
        requestKey: KEY,
        createdAt: 10,
        files: [{ path: 'src/a.ts', name: 'a.ts', type: 'file', size: 4, conversationId: 's' }],
      }),
    ).toEqual({
      disposition: 'projected',
      reason: 'paths-only',
      entries: [{ path: 'src/a.ts', name: 'a.ts', type: 'file', size: 4 }],
    })
  })

  it('请求键或文件清单没量到是未判定，夹了正文则拒绝', () => {
    expect(projectFileTree({ requestKey: 'ABC', createdAt: 10, files: [] }).reason).toBe(
      'key-unmeasured',
    )
    expect(projectFileTree({ requestKey: KEY, createdAt: 10, files: null }).reason).toBe(
      'files-unmeasured',
    )
    expect(
      projectFileTree({
        requestKey: KEY,
        createdAt: 10,
        files: [{ path: 'a.ts', name: 'a.ts', type: 'file', size: 1, content: 'x' }],
      }).reason,
    ).toBe('body-inlined')
  })
})
