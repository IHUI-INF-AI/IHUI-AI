import { describe, expect, it } from 'vitest'

import { ATTACHMENT_BYTE_CAP, judgeBatch } from './batch-bounds'

describe('judgeBatch', () => {
  it('计数没量到是未判定，不把缺席当成空批放行', () => {
    expect(judgeBatch({ itemIds: null, attachments: [] }).reason).toBe('count-unmeasured')
    expect(judgeBatch({ itemIds: ['a'], attachments: [{ bytes: null }] }).reason).toBe(
      'bytes-unmeasured',
    )
  })

  it('超过 100 项时只把多出来的 id 记为未写入', () => {
    const itemIds = Array.from({ length: 101 }, (_, index) => `id-${index}`)
    const verdict = judgeBatch({ itemIds, attachments: [] })
    expect(verdict).toEqual({ disposition: 'refused', reason: 'item-cap', missedIds: ['id-100'] })
  })

  it('附件超过 10 个或单件超过 50 MiB 则拒绝', () => {
    const many = Array.from({ length: 11 }, () => ({ bytes: 1 }))
    expect(judgeBatch({ itemIds: ['a'], attachments: many }).reason).toBe('attachment-count')
    expect(
      judgeBatch({ itemIds: ['a'], attachments: [{ bytes: ATTACHMENT_BYTE_CAP + 1 }] }).reason,
    ).toBe('attachment-bytes')
    expect(
      judgeBatch({ itemIds: ['a'], attachments: [{ bytes: ATTACHMENT_BYTE_CAP }] }).disposition,
    ).toBe('admitted')
  })
})
