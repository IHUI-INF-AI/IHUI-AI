import { describe, expect, it } from 'vitest'

import { decideIdentityAttempt } from './identity-retry'

describe('decideIdentityAttempt', () => {
  it('宿主与尝试同为 User 且尚未拒绝时放行', () => {
    expect(
      decideIdentityAttempt({
        hostIdentity: 'User',
        attemptedIdentity: 'User',
        deniedHostIdentity: null,
      }),
    ).toEqual({ disposition: 'admitted', reason: 'host-selected', identity: 'User' })
  })

  it('尚未拒绝时不得用别的身份顶替宿主', () => {
    expect(
      decideIdentityAttempt({
        hostIdentity: 'User',
        attemptedIdentity: 'RuntimeOwner',
        deniedHostIdentity: null,
      }),
    ).toEqual({ disposition: 'refused', reason: 'identity-mismatch', identity: null })
  })

  it('拒绝后再换身份重试', () => {
    expect(
      decideIdentityAttempt({
        hostIdentity: 'User',
        attemptedIdentity: 'RuntimeAgent',
        deniedHostIdentity: 'User',
      }),
    ).toEqual({ disposition: 'refused', reason: 'identity-switch', identity: null })
  })

  it('同一身份的拒绝仍然有效', () => {
    expect(
      decideIdentityAttempt({
        hostIdentity: 'User',
        attemptedIdentity: 'User',
        deniedHostIdentity: 'User',
      }),
    ).toEqual({ disposition: 'refused', reason: 'denial-stands', identity: null })
  })

  it('拒绝记录不在三档时未判定', () => {
    expect(
      decideIdentityAttempt({
        hostIdentity: 'User',
        attemptedIdentity: 'User',
        deniedHostIdentity: 'Guest',
      }),
    ).toEqual({ disposition: 'unjudged', reason: 'denial-unmeasured', identity: null })
  })
})
