import { describe, expect, it } from 'vitest'

import { CATALOG_EMPTY_STABLE, signCatalog } from './catalog-signature'

const HASH_A = '11'.repeat(32)
const HASH_B = '22'.repeat(32)
const XOR_AB = '33'.repeat(32)

describe('signCatalog', () => {
  it('两条合法哈希换顺序后 xor 相同', () => {
    const first = { path: 'skills/zeta', present: true, hash: HASH_A }
    const second = { path: 'skills/alpha', present: true, hash: HASH_B }
    const forward = signCatalog({ entries: [first, second] })
    const reversed = signCatalog({ entries: [second, first] })
    expect(forward).toEqual(reversed)
    expect(forward).toEqual({
      ok: true,
      reason: 'signed',
      signature: { ok: true, missing: [], sum: 2, xor: XOR_AB },
    })
  })

  it('空数组没有具名件是 empty-unmarked', () => {
    expect(signCatalog({ entries: [] })).toEqual({
      ok: false,
      reason: 'empty-unmarked',
      signature: null,
    })
    expect(signCatalog({ entries: [], emptyMarker: 'not-the-named-artifact' })).toEqual({
      ok: false,
      reason: 'empty-unmarked',
      signature: null,
    })
  })

  it('带 catalog-empty-stable 是 empty-stable 且 xor 为 0', () => {
    expect(signCatalog({ entries: [], emptyMarker: CATALOG_EMPTY_STABLE })).toEqual({
      ok: true,
      reason: 'empty-stable',
      signature: { ok: true, missing: [], sum: 0, xor: '0' },
    })
  })

  it('有一条 present false 是 missing-entries 且 signature 为 null', () => {
    expect(
      signCatalog({
        entries: [
          { path: 'skills/kept', present: true, hash: HASH_A },
          { path: 'skills/gone', present: false, hash: null },
        ],
      }),
    ).toEqual({
      ok: false,
      reason: 'missing-entries',
      signature: null,
      missing: ['skills/gone'],
    })
  })

  it('hash 大写是 hash-unmeasured', () => {
    expect(
      signCatalog({
        entries: [{ path: 'skills/kept', present: true, hash: 'AA'.repeat(32) }],
      }),
    ).toEqual({
      ok: false,
      reason: 'hash-unmeasured',
      signature: null,
    })
  })
})
