/**
 * 行级归因(Line Attribution)的**唯一形状定义**。
 *
 * 目标问题:「这个文件里哪几行是 AI 写的、哪几行是人改过的、哪几行是 AI 写后被人改的」。
 * 与 `apps/cli/src/checkpoints/hunk-tracker.ts` 的区别:
 *   - HunkTracker 只记录「某 agent 在某次调用里碰过哪个行范围」,是**冲突检测**用的事件流;
 *   - 本模块记录**每一行当前的归属状态**,是**可查询的最终事实**,且必须能随人工编辑翻转。
 *
 * 三态判据(不可合并):
 *   - `ai`            AI 写入后至今无人改动
 *   - `ai-then-human` AI 写过,但该行内容已被人工改动过
 *   - `human`         人工写入(或来源未知,按保守默认)
 * 「来源未知按 human」是**安全方向**:宁可少报 AI 行,不可把人工代码认领成 AI 生成。
 */

/** 行归属三态。 */
export type AttributionSource = 'ai' | 'human' | 'ai-then-human'

/** 一次写入的溯源信息(缺哪个字段就省略,不写 null)。 */
export interface AttributionOrigin {
  /** 发起改动的 agent(主 agent 为 'main',subagent 为 subagentId) */
  agentId?: string
  /** 会话 id(跨会话查询时用于可见性判断) */
  sessionId?: string
  /** 产生该写入的工具调用 id */
  toolCallId?: string
  /** 生成该内容的模型标识 */
  model?: string
  /** 写入时刻(ISO 8601 字符串,便于 JSON 落盘) */
  at: string
}

/**
 * 一条行级归因记录。
 * `startLine` / `endLine` 均为 **1-based 闭区间**; 单行记录 startLine === endLine。
 */
export interface LineAttribution {
  /** 工作区相对路径(POSIX 风格,反斜杠已归一为 '/') */
  filePath: string
  startLine: number
  endLine: number
  source: AttributionSource
  origin: AttributionOrigin
  /** 归属版本:每次写入/翻转 +1,用于识别陈旧快照 */
  revision: number
}

/** 压缩后对外返回的区间(与 LineAttribution 同形,语义即"该区间同源")。 */
export type AttributionRange = LineAttribution
