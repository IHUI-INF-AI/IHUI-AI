import { useState, useRef, useCallback } from 'react'
import type { PaginatedResponse } from '@ihui/types'

interface UseSocialListOptions<T> {
  pageSize?: number
  fetch: (params: { page: number; pageSize: number }) => Promise<PaginatedResponse<T>>
}

export function useSocialList<T extends { id: string }>(options: UseSocialListOptions<T>) {
  const { fetch, pageSize = 20 } = options
  const [items, setItems] = useState<T[]>([])
  const [loading, setLoading] = useState(false)
  const [hasMore, setHasMore] = useState(true)
  // BUG-54:state 是异步的,不能当"这一轮还能不能加载"的同步闸门 ——
  // reset 里的 setHasMore(true) 要等重渲染才生效,而消费方常在 reset 后立即触底
  // 再调 load(),此时闭包捕获的仍是上一次的 false ⇒ 首屏被直接挡掉、翻不了页。
  // 闸门下沉到 ref:reset 分支同步清它,判据与 UI 展示同源但不再被 React 批处理拖住。
  const hasMoreRef = useRef(true)
  const pageRef = useRef(1)
  const loadingRef = useRef(false)

  const load = useCallback(
    async (reset = false) => {
      if (loadingRef.current) return
      if (reset) {
        pageRef.current = 1
        hasMoreRef.current = true
        setHasMore(true)
        setItems([])
      }
      if (!hasMoreRef.current) return
      loadingRef.current = true
      setLoading(true)
      try {
        const res = await fetch({ page: pageRef.current, pageSize })
        const list = res.list || []
        setItems((prev) => (reset ? list : [...prev, ...list]))
        const more = pageRef.current * pageSize < res.total
        hasMoreRef.current = more
        setHasMore(more)
        if (more) pageRef.current++
      } finally {
        loadingRef.current = false
        setLoading(false)
      }
    },
    [fetch, pageSize],
  )

  const removeItem = useCallback((id: string) => {
    setItems((prev) => prev.filter((item) => item.id !== id))
  }, [])

  return { items, loading, hasMore, load, removeItem }
}

export type { UseSocialListOptions }
