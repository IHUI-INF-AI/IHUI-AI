/**
 * G-425(2026-10-07 立,默认档"只提示"):done 帧 finishReason 是否表示
 * "输出被 max_tokens 截断"。
 *
 * 判据口径逐字取自 shared sse contract 的 done 帧 `finishReason` 字段注释 ——
 * 小写归一后 ∈ {length, max_tokens};其余值(stop/tool_calls/SAFETY/RECITATION…)
 * 与缺席/非串一律 false(缺席 = 上游没给,绝不折成"正常结束")。
 *
 * 五端(web / extension / mobile-rn / miniapp-taro / cli)共用这一份;各端的差异只在
 * "提示往哪放",不各写一遍判据。cli 的续写档口径更宽(还认 model_context_window_exceeded),
 * 属于续写策略而非提示判定,在 apps/cli 自持,不并进这里。
 */
export function isMaxTokensTruncatedFinishReason(finishReason: string | undefined | null): boolean {
  const fr = (finishReason ?? '').toLowerCase()
  return fr === 'length' || fr === 'max_tokens'
}
