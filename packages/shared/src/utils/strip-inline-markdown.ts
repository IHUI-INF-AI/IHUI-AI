/**
 * 行内 Markdown 标记的**去标记**处理 —— 只服务"没有富文本渲染器"的纯文本气泡。
 *
 * 为什么必须有:这个气泡是无富文本腿的宿主(首页对话小窗、群聊、直播聊天)共用的展示面,
 * 只吐 Text 节点。`**加粗**`、`~~删除线~~`、`` `行内代码` `` 的标记符号会原样露出来 ——
 * 用户看到的是 `**重点**` 而不是「重点」,这是可感知的显示缺陷,不是"简化渲染"。
 *
 * 边界(刻意只做这一档):
 * - 只处理**能安全退化成纯文本**的行内标记;块级结构(标题/列表/表格/代码围栏)不在这里解析,
 *   那需要真解析器,端内已有富文本腿(web 的 markdown-stream、小程序 pkg-ai 的 ChatMessageItem)。
 * - **先保护再剥符号,最后还原**:URL 与行内代码里的 `_` / `*` 是内容不是标记,直接跑替换
 *   会把 `a_b_c` 吃成 `abc`、把链接打坏(实测:`https://x.test/a_b_c` → `https://x.test/abc`)。
 *   这正是"去标记"最容易造成的**内容破坏**,比留几个星号严重得多。
 * - 不逃逸、不递归:输入是模型输出,不是可执行内容;这里只剥符号,不构造任何标记。
 */

/** 占位符用私用区字符:正文里不会自然出现,还原时不会与真实内容碰撞。 */
const PH_OPEN = '\uE000'
const PH_CLOSE = '\uE001'

/** 受保护片段:URL 与行内代码 —— 它们内部的标记字符属于内容。 */
const PROTECT_PATTERNS: readonly RegExp[] = [
  // 裸 URL(含协议),止于空白或全角标点
  /\b(?:https?:\/\/|www\.)[^\s\u3000-\u303f\uff00-\uffef]+/g,
  // 行内代码(反引号包裹,不跨行)
  /`[^`\n]+`/g,
]

export function stripInlineMarkdown(text: string): string {
  if (!text) return ''
  const stash: string[] = []
  let work = text

  // ① 保护:把不该动的片段换成占位符
  for (const pattern of PROTECT_PATTERNS) {
    work = work.replace(pattern, (match) => {
      const idx = stash.push(match) - 1
      return `${PH_OPEN}${idx}${PH_CLOSE}`
    })
  }

  // ② 剥符号(占位符里只剩数字,不会被这些规则命中)
  work = work
    // **bold** / __bold__ → bold(必须在单星/单下划线之前)
    .replace(/\*\*([^*\n]+)\*\*/g, '$1')
    .replace(/__([^_\n]+)__/g, '$1')
    // *italic* / _italic_ → italic
    .replace(/(^|[^*])\*([^*\n]+)\*(?!\*)/g, '$1$2')
    .replace(/(^|[^_])_([^_\n]+)_(?!_)/g, '$1$2')
    // ~~strike~~ → strike
    .replace(/~~([^~\n]+)~~/g, '$1')

  // ③ 还原:行内代码去掉包裹的反引号,URL 原样
  return work.replace(new RegExp(`${PH_OPEN}(\\d+)${PH_CLOSE}`, 'g'), (_m, idx: string) => {
    const original = stash[Number(idx)] ?? ''
    return original.startsWith('`') ? original.slice(1, -1) : original
  })
}
