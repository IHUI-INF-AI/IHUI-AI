/**
 * 深拷贝:优先使用原生 structuredClone,不可用/抛错时降级到手写递归。
 * BUG-28⑥:手写降级必须保留 Date/Map/Set/RegExp 语义 —— 旧实现把它们当普通对象
 * 递归成空壳(Date 变 {}、Map/Set 丢条目),静默吞字段。
 */
function manualClone<T>(obj: T): T {
  if (obj === null || typeof obj !== 'object') return obj
  if (obj instanceof Date) return new Date(obj.getTime()) as T
  if (obj instanceof RegExp) return new RegExp(obj.source, obj.flags) as T
  if (obj instanceof Map) {
    return new Map(
      Array.from(obj, ([k, v]) => [manualClone(k), manualClone(v)] as [unknown, unknown]),
    ) as T
  }
  if (obj instanceof Set) {
    return new Set(Array.from(obj, (v) => manualClone(v))) as T
  }
  const clone = (Array.isArray(obj) ? [] : {}) as T
  for (const key in obj) {
    if (Object.prototype.hasOwnProperty.call(obj, key)) {
      ;(clone as Record<string, unknown>)[key] = manualClone((obj as Record<string, unknown>)[key])
    }
  }
  return clone
}

export function deepClone<T>(obj: T): T {
  if (obj === null || typeof obj !== 'object') return obj
  if (typeof structuredClone === 'function') {
    try {
      return structuredClone(obj)
    } catch {
      // 含不可克隆值(如 function)时降级到手写递归,不把整份快照丢掉
    }
  }
  return manualClone(obj)
}

/** 判空:null/undefined/空字符串/空数组/空对象 */
export function isEmpty(value: unknown): boolean {
  if (value === null || value === undefined) return true
  if (typeof value === 'string' && value.trim() === '') return true
  if (Array.isArray(value) && value.length === 0) return true
  if (typeof value === 'object' && Object.keys(value as object).length === 0) return true
  return false
}
