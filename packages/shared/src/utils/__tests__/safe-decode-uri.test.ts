import { describe, expect, it } from 'vitest'

import { safeDecodeURIComponent } from '../safe-decode-uri'

describe('safeDecodeURIComponent(跨端唯一容错解码出口)', () => {
  it('合法百分号编码正常解码(与原生 decodeURIComponent 同值)', () => {
    expect(safeDecodeURIComponent('%E4%BD%A0%E5%A5%BD')).toBe('你好')
    expect(safeDecodeURIComponent('a%20b')).toBe('a b')
    expect(safeDecodeURIComponent('%25')).toBe('%')
  })

  it('孤立 % 不再抛 URIError,原样返回(框架已解码过时的正确降级)', () => {
    // 这是本工具立因的那一炸:二次解码「50%好评」在裸 decode 下当场 URIError 崩页
    const raw = '50%好评'
    expect(() => decodeURIComponent(raw)).toThrow(URIError)
    expect(safeDecodeURIComponent(raw)).toBe(raw)
  })

  it('% 后随非法 hex 也原样返回,绝不抛', () => {
    expect(safeDecodeURIComponent('100%zz 通过')).toBe('100%zz 通过')
    expect(safeDecodeURIComponent('%')).toBe('%')
    expect(safeDecodeURIComponent('%g1%')).toBe('%g1%')
  })

  it('空串与纯文本恒等', () => {
    expect(safeDecodeURIComponent('')).toBe('')
    expect(safeDecodeURIComponent('plain-string-no-percent')).toBe('plain-string-no-percent')
  })

  it('真机链路模拟:分享文案「100%」经 encodeURIComponent 一次 → 解码回原文;框架自动解过一次后再手解 → 原样不再崩', () => {
    const once = encodeURIComponent('房间 100% 满')
    expect(safeDecodeURIComponent(once)).toBe('房间 100% 满')
    const already = '房间 100% 满' // router.params 在小程序里多已被自动解一次
    expect(safeDecodeURIComponent(already)).toBe(already)
  })
})
