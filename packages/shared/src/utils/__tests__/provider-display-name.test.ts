import { describe, expect, it } from 'vitest'
import {
  prettifyProviderCode,
  providerDisplayName,
  stripInternalRelaySuffix,
} from '../provider-display-name'

describe('providerDisplayName', () => {
  it('WorkBuddy 两种接入形态落同一个展示名', () => {
    expect(providerDisplayName('workbuddy')).toBe('WorkBuddy')
    expect(providerDisplayName('workbuddy_relay')).toBe('WorkBuddy')
    expect(providerDisplayName('workbuddy-relay')).toBe('WorkBuddy')
    expect(providerDisplayName('WorkBuddy_Relay')).toBe('WorkBuddy')
  })

  it('内部后缀永不外露(未知厂商同样剥)', () => {
    expect(providerDisplayName('somevendor_relay')).toBe('Somevendor')
    expect(providerDisplayName('foo-relay')).toBe('Foo')
  })

  it('已知厂商走中文/品牌名,未知走美化兜底', () => {
    expect(providerDisplayName('moonshot')).toBe('月之暗面 Moonshot')
    expect(providerDisplayName('nvidia_nim')).toBe('NVIDIA NIM')
    expect(providerDisplayName('brand_new_vendor')).toBe('Brand New Vendor')
    expect(providerDisplayName('')).toBe('')
    expect(providerDisplayName(null)).toBe('')
  })

  it('剥后缀幂等,且不误伤正常厂商名', () => {
    expect(stripInternalRelaySuffix(stripInternalRelaySuffix('workbuddy_relay'))).toBe('workbuddy')
    expect(stripInternalRelaySuffix('relay')).toBe('relay')
    expect(prettifyProviderCode('workbuddy_relay')).toBe('Workbuddy')
  })
})
