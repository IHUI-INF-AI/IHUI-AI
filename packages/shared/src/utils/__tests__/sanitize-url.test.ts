import { describe, expect, it } from 'vitest'

import { stripUrlCredentialSegments } from '../sanitize-url'

const SIGNED = 'https://u:***@cdn.example.com/v/lesson.mp4?X-Amz-Signature=abc123&exp=1&t=2#frag'

describe('stripUrlCredentialSegments —— 上报面前的凭据段剥离唯一出口', () => {
  it('① userinfo + query + hash 一并剥掉,只留 scheme://host + path', () => {
    expect(stripUrlCredentialSegments(SIGNED)).toBe('https://cdn.example.com/v/lesson.mp4')
  })

  it('② 已剥过的值再剥幂等(重复经过上报链不得改形)', () => {
    const once = stripUrlCredentialSegments(SIGNED)
    expect(stripUrlCredentialSegments(once)).toBe(once)
  })

  it('③ 反向对照:普通无凭据 URL 逐字不变', () => {
    for (const plain of [
      'https://aizhs.top/pricing',
      '/admin/visit-tracking',
      '//cdn.example.com/a/b.png',
      'mailto:hi@aizhs.top',
      '注册成功',
    ]) {
      expect(stripUrlCredentialSegments(plain)).toBe(plain)
    }
  })

  it('④ 站内相对路径带 query(VisitTracker 的真实入参形态)也剥', () => {
    expect(stripUrlCredentialSegments('/callback?code=otp&state=xyz')).toBe('/callback')
    expect(stripUrlCredentialSegments('/d/a.csv#page=2')).toBe('/d/a.csv')
  })

  it('⑤ 协议相对 URL 的 userinfo/query 同样剥(不得因为没有 scheme 就整条放过)', () => {
    expect(stripUrlCredentialSegments('//u:***@cdn.example.com/x?sig=1')).toBe(
      '//cdn.example.com/x',
    )
  })

  it('⑥ 路径里出现 @ 不得被当成 userinfo 截断(mailto 与 /user@id 两型)', () => {
    expect(stripUrlCredentialSegments('https://aizhs.top/u@42')).toBe('https://aizhs.top/u@42')
  })

  it('⑦ 空串与缺省入参原样返回(调用方的 || undefined 语义依赖这一点)', () => {
    expect(stripUrlCredentialSegments('')).toBe('')
  })
})
