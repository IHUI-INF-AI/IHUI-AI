import { describe, expect, it } from 'vitest'
import { formatTokenCount } from '../format.js'

/**
 * 深化U(2026-11-17):AI 面板工具步骤 token 计数流式显示的唯一出口。
 *
 * 核心钉:tokens < 1000 时返回原始数字字符串,不得走 K 分支
 * (旧 bug:912 → "0.9K" 或 "1K",流式累积初期几乎全程虚假显示;
 * 修复后 912 → "912",和 token/1_000 向下取整为 0 的语义一致)。
 */
describe('formatTokenCount(深化U token 计数唯一出口)', () => {
  it('零值显示 "0",不产生 "0K"', () => {
    expect(formatTokenCount(0)).toBe('0')
  })

  it('< 1000 显示原始数字,禁止假精确 "0.9K"', () => {
    expect(formatTokenCount(1)).toBe('1')
    expect(formatTokenCount(128)).toBe('128')
    expect(formatTokenCount(912)).toBe('912')
    expect(formatTokenCount(999)).toBe('999')
  })

  it('恰好 1000 跨入 K 区间,显示 "1K"', () => {
    expect(formatTokenCount(1_000)).toBe('1K')
  })

  it('K 区间四舍五入到 1 位小数,整数后缀不带 ".0"', () => {
    expect(formatTokenCount(1_500)).toBe('1.5K')
    expect(formatTokenCount(32_000)).toBe('32K')
    expect(formatTokenCount(128_000)).toBe('128K')
  })

  it('K 支 BUG-28④:1500 不得畸形成 "2K"', () => {
    // 旧 bug:K 支用 toFixed(0) 把 1500 → "2K"
    expect(formatTokenCount(1_500)).toBe('1.5K')
  })

  it('恰好达到 1000K 阈值升入 M 区间,不产出 "1000K" 畸形值', () => {
    // 999_999 / 1_000 = 999.999 → Math.round(999.999 * 10) / 10 = 1000.0
    // 达到 1000K 阈值 → 走 M 支:999_999 / 1_000_000 = 0.999999 → formatUnitValue(0.999999)
    //   = Math.round(0.999999 * 10) / 10 = 10 / 10 = 1 → "1M"
    expect(formatTokenCount(999_999)).toBe('1M')
  })

  it('M 区间整数不带 ".0"', () => {
    expect(formatTokenCount(1_000_000)).toBe('1M')
    expect(formatTokenCount(2_000_000)).toBe('2M')
  })

  it('M 区间带 1 位小数', () => {
    expect(formatTokenCount(1_500_000)).toBe('1.5M')
  })
})
