/**
 * 删除保护链 — 常量档(复现对方 safe-delete-bulk-guard 的参数族,取证见
 * W1-workbuddy-main.md §2 表 #9:`阈值 20 / 锁 2000ms / 陈旧锁 5min / 回合态 TTL 7d / 样本 5 / 显示上限 9999`)。
 * 超越点:对方阈值埋在 shell 与 exe 里不可单测,本层全部具名导出可被 vitest 直接钉住。
 */

/** check/approve 两阶段凭据的固定 kind 判别键 */
export const SCAN_TICKET_KIND = 'ihui.delete-guard.scan-ticket'

/** 回收站清单的固定 kind 判别键 */
export const TRASH_MANIFEST_KIND = 'ihui.delete-guard.trash-manifest'

/** 批量删除阈值:候选数 >= 该值即进入 approve 相(对方为 20,含边界取更严档) */
export const DEFAULT_BULK_DELETE_THRESHOLD = 20

/** 扫描凭据有效期(对方"回合态 TTL 7d"档):过期即作废,必须重新 check */
export const DEFAULT_SCAN_TICKET_TTL_MS = 7 * 24 * 60 * 60 * 1000

/** 锁抢占窗口:窗口内的他席持锁 ⇒ busy(对方 2000ms 档) */
export const DEFAULT_LOCK_ACQUIRE_WINDOW_MS = 2000

/** 陈旧锁回收线:超过即视为持锁方已死,可回收(对方 5min 档) */
export const DEFAULT_STALE_LOCK_TTL_MS = 5 * 60 * 1000

/** 展示样本条数(对方 5 档):blocked 结论里给前 N 条候选供人过目 */
export const DEFAULT_SAMPLE_SIZE = 5

/** 样本显示上限(对方 9999 档):防止极端计数撑爆展示面 */
export const DEFAULT_DISPLAY_CAP = 9999

// ==================== 回收站到期清理档(goal-b49 W7) ====================

/**
 * 回收站条目默认保留期:既无条目档也无清单档时按此判到期。
 * 取 30 天档 —— 与对方"回合态 TTL 7d"不同轴(那条是 check 凭据的寿命,这条是**已回收数据**的可恢复窗口),
 * 30d 覆盖"跨月项目 + 一个月度假期"的最短可接受后悔窗,再短就失去回收站的意义。
 */
export const DEFAULT_TRASH_RETENTION_MS = 30 * 24 * 60 * 60 * 1000

/** 单次清理最多摘除的条目数(超限只报数,不硬删) */
export const DEFAULT_TRASH_CLEANUP_MAX_ENTRIES = 15

/**
 * 单次清理最多摘除的字节数(256 MiB 档)。
 * 超限条目落 overBudget 桶并报数,绝不"为了清完而突破上限"。
 */
export const DEFAULT_TRASH_CLEANUP_MAX_BYTES = 256 * 1024 * 1024

/**
 * 到期清理的单次条目**硬顶** = 两阶段阈值 - 1。
 * 为什么存在:清理器自己就是一次批量删除,若一次能摘 ≥ DEFAULT_BULK_DELETE_THRESHOLD 枚,
 * 它就绕过了本链的两阶段护栏。把上限钉在阈值以下 ⇒ 清理腿在结构上不可能成为"无人对账的批量删除"。
 */
export const TRASH_CLEANUP_ENTRY_HARD_CEILING = DEFAULT_BULK_DELETE_THRESHOLD - 1

/** 清理器两次运行之间的最小间隔(节流;调度器另有自己的节律,这一档是器物自带的第二道闸) */
export const DEFAULT_EXPIRY_RUN_MIN_INTERVAL_MS = 6 * 60 * 60 * 1000

/** 清理器连败后的封票基线时长(第 n 次连败按 quarantineMs * 2^(n-1) 递增,上限见下条) */
export const DEFAULT_EXPIRY_QUARANTINE_MS = 24 * 60 * 60 * 1000

/** 封票时长递增上限(7 天):防指数退避把窗口撑到"永不重试"却不退休 */
export const MAX_EXPIRY_QUARANTINE_MS = 7 * 24 * 60 * 60 * 1000

/** 连败到该次数即**永久封票(retired)**,器物自身死亡;出路只有人工复位账目 */
export const DEFAULT_EXPIRY_MAX_STRIKES = 8
