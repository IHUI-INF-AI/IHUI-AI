import type { GuardVerdict } from './types'

/**
 * 三态结论聚合(对齐 AGENTS.md §0.3:「未判定」不得被记成绿,也不得被记成红)。
 * 优先级 undetermined > blocked > clean —— 只要有一维判不出,整体就是判不出。
 */
const VERDICT_RANK: Readonly<Record<GuardVerdict, number>> = {
  clean: 0,
  blocked: 1,
  undetermined: 2,
}

export function aggregateGuardVerdict(states: readonly GuardVerdict[]): GuardVerdict {
  if (states.length === 0) {
    // 枚举到 0 个候选判死不记绿(§0.3):没有任何一维被判定过 ⇒ 未判定
    return 'undetermined'
  }
  let worst: GuardVerdict = 'clean'
  for (const s of states) {
    if (VERDICT_RANK[s] > VERDICT_RANK[worst]) worst = s
  }
  return worst
}

/** 判定是否放行(clean 才算放行;blocked/undetermined 都必须出声并拒绝执行) */
export function isCleared(verdict: GuardVerdict): boolean {
  return verdict === 'clean'
}
