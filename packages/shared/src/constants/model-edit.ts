/**
 * 模型编辑页(ModelEdit)的只读字段清单 —— 跨端唯一真相源。
 *
 * 立因(2026-11-03):这份清单原本只住在 RN 数据层 `packages/app/src/features/model-edit/model-edit-save.ts`,
 * 于是 RN 屏据此把 6 个控件置灰并提示"暂不支持修改",而小程序端同名页一个字都没接 ⇒
 * 端内用户能改、能点提交,库里却没有归宿(可落库的只有 price/isFree 两列)= 「能改但不生效」。
 * 门面对齐的正确出路不是把提示抄一份,而是让两端读同一份清单(AGENTS §3 共享层优先 / §0.6 单一真相源)。
 *
 * 后端没有对应列,或形态无法忠实表达(categories 多选 vs 单值 categoryId)。
 * UI 据此置灰,驱动层 payload 只出现 price/isFree —— 两边共用同一份清单,避免「能改但不生效」。
 * saleType 不在清单内:它由 buildModelEditBillingPayload 映射为真实列 isFree。
 */
export const MODEL_EDIT_READ_ONLY_FIELDS = [
  'categories',
  'dept',
  'cycle',
  'freeDur',
  'audience',
  'discount',
] as const

export type ModelEditReadOnlyField = (typeof MODEL_EDIT_READ_ONLY_FIELDS)[number]

/** 供两端 UI 复用同一句判定,不各自写 `includes(...)` 的同义复制。 */
export function isModelEditFieldReadOnly(field: ModelEditReadOnlyField): boolean {
  return (MODEL_EDIT_READ_ONLY_FIELDS as readonly string[]).includes(field)
}
