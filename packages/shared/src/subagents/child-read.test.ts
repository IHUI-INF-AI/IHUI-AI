import { describe, expect, it } from 'vitest'

import { readChildSurface, type ChildRecord } from './child-read'

const children: ChildRecord[] = [
  {
    id: 'a',
    status: 'running',
    requests: [{ id: 'r1', summary: '读文件' }],
    tools: [{ name: 'read', detail: { path: 'secret' } }],
  },
]

describe('readChildSurface', () => {
  it('快照只有计数，不带工具明细', () => {
    const plan = readChildSurface({ children, surface: 'snapshots' })
    expect(plan).toEqual({
      disposition: 'ok',
      surface: 'snapshots',
      snapshots: [{ id: 'a', status: 'running', requestCount: 1, toolCount: 1 }],
    })
    expect(JSON.stringify(plan)).not.toContain('secret')
  })

  it('不点名子代理就不把全部请求倒出来', () => {
    expect(readChildSurface({ children, surface: 'requests' })).toEqual({
      disposition: 'unjudged',
      reason: 'child-unmeasured',
    })
  })

  it('点了名才给这一个的请求，点了工具才给明细', () => {
    expect(readChildSurface({ children, surface: 'requests', childId: 'a' })).toMatchObject({
      disposition: 'ok',
      requests: [{ id: 'r1', summary: '读文件' }],
    })
    expect(readChildSurface({ children, surface: 'tool', childId: 'a' })).toEqual({
      disposition: 'unjudged',
      reason: 'tool-unmeasured',
    })
    expect(
      readChildSurface({ children, surface: 'tool', childId: 'a', toolName: 'read' }),
    ).toMatchObject({
      disposition: 'ok',
      tool: { name: 'read', detail: { path: 'secret' } },
    })
  })

  it('名单没量到不是空快照', () => {
    expect(readChildSurface({ children: null, surface: 'snapshots' })).toEqual({
      disposition: 'unjudged',
      reason: 'children-unmeasured',
    })
  })
})
