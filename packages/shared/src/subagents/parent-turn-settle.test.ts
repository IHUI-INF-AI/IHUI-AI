import { describe, expect, it } from 'vitest'

import {
  isSubagentTerminalStatus,
  settleSubagentOnParentTurnEnd,
  subagentGroupStillActive,
} from './parent-turn-settle'

describe('settleSubagentOnParentTurnEnd', () => {
  it('进行中在父轮次收场时落取消，不写成完成', () => {
    for (const status of [
      'idle',
      'pending',
      'thinking',
      'acting',
      'reflecting',
      'waiting',
      'running',
    ]) {
      expect(settleSubagentOnParentTurnEnd(status)).toEqual({
        status: 'cancelled',
        streamingDone: true,
      })
    }
  })

  it('已有终态保持原状', () => {
    expect(settleSubagentOnParentTurnEnd('completed').status).toBe('completed')
    expect(settleSubagentOnParentTurnEnd('failed').status).toBe('failed')
    expect(settleSubagentOnParentTurnEnd('cancelled').status).toBe('cancelled')
  })

  it('未知状态按非终态处理，收场时取消', () => {
    expect(isSubagentTerminalStatus('paused')).toBe(false)
    expect(settleSubagentOnParentTurnEnd('paused').status).toBe('cancelled')
  })
})

describe('subagentGroupStillActive', () => {
  it('还有进行中的子代理时，父轮次已收场组头仍算进行中', () => {
    expect(subagentGroupStillActive(['running', 'completed'], true)).toBe(true)
  })

  it('全部终态且父轮次已收场，组头不再进行中', () => {
    expect(subagentGroupStillActive(['completed', 'failed', 'cancelled'], true)).toBe(false)
  })

  it('子代理都已结束但父轮次还在流，组头仍进行中', () => {
    expect(subagentGroupStillActive(['completed'], false)).toBe(true)
  })
})
