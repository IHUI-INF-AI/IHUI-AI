/**
 * PC 端「App 扫码登录」二维码内容的解析判据(全仓唯一实现)。
 *
 * Web 端 `qrContent` 当前就是纯 ticket(`qr_<uuid>`),但扫码器可能原样返回整段 URL
 * (平台深链、粘贴板、外部扫码组件)。两端(小程序 / RN)都从这里取,不在端内各写一份
 * 正则 —— 两把尺子必然漂移(AGENTS §0.6)。
 */

const TICKET_PATTERN = /qr_[A-Za-z0-9-]{6,}/

/** 从扫码结果里取出登录 ticket;取不出返回 null(调用方按"不是本站的码"提示)。 */
export function parseQrLoginTicket(raw: string | null | undefined): string | null {
  if (typeof raw !== 'string') return null
  const text = raw.trim()
  if (!text) return null

  // URL 形态:优先取显式 ticket 参数,其次再在整串里找 ticket 片段
  const param = /[?&]ticket=([^&#\s]+)/.exec(text)
  if (param) {
    const rawParam = param[1]
    if (typeof rawParam !== 'string') return null
    try {
      const decoded = decodeURIComponent(rawParam)
      const hit = TICKET_PATTERN.exec(decoded)
      return hit ? hit[0] : null
    } catch {
      return null
    }
  }

  const hit = TICKET_PATTERN.exec(text)
  return hit ? hit[0] : null
}
