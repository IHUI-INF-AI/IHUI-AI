/**
 * 路由席与工人的分工。
 *
 * 路由席只决定接单、并单、停止或忽略，不改授权范围，也不拿实现工具。
 * 工人在工单自己的会话和目录里做，范围只来自原始请求。
 */

export const ROUTER_TOOLS = ['search_codebase', 'read_file'] as const

export const WORKER_TOOLS = ['search_codebase', 'read_file', 'write_file', 'run_command'] as const

export type AgentRole = 'router' | 'worker'

export function toolsFor(role: AgentRole): readonly string[] {
  return role === 'router' ? ROUTER_TOOLS : WORKER_TOOLS
}

/** 路由席写下的计划不得进入授权范围。范围只保留原始请求。 */
export function scopeFromRequest(originalText: string, routerNotes: string): string {
  void routerNotes
  return originalText
}

export interface WorkerAssignment {
  sessionId: string
  directory: string
  goal: string
  constraints: string
  deliverables: string
  role: 'worker'
  /** 归属的登录主体；宿主派发与心跳反查都以它为准，禁止另建第二份账。 */
  ownerUserId?: string
}

export function workerAssignment(ticket: {
  id: string
  ownerUserId: string
  scope: string
  execution: { sessionId: string; directory: string }
}): WorkerAssignment {
  return {
    sessionId: ticket.execution.sessionId,
    directory: ticket.execution.directory,
    goal: ticket.scope,
    role: 'worker',
    ownerUserId: ticket.ownerUserId,
    constraints: [
      `只在目录 ${ticket.execution.directory} 里改文件。`,
      `会话 ${ticket.execution.sessionId} 不与其他工单混用。`,
      '不要扩大授权范围，也不要替路由席决定接单或停止。',
    ].join(''),
    deliverables: '可复核的结果。做不完就提出一个具体问题。',
  }
}

export function executionFor(
  ticketId: string,
  ownerUserId: string,
): {
  sessionId: string
  directory: string
} {
  return {
    sessionId: `worker-${ticketId}`,
    directory: `super-agent/${ownerUserId}/${ticketId}`,
  }
}
