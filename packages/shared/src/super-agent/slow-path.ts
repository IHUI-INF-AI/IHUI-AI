/**
 * 慢路径判定环（recorded 积压 → 模型批量判定 → 三值注记）。
 * 行为对照 DeepSeek dsh-superagent「两级过滤的第二级：模型判断」设计；
 * 本文件为自写实现。超越点：判定不越权开工——record 档只注记；auto 档 act 也只走
 * 与人工 acceptRecorded 同一条语义通道（inferred∧auto∧规则名），机器人条目永不被自动开工。
 *
 * 零 IO：适配器由宿主注入；本层只定义契约与批装配/拆解的纯判据。
 */

export type SlowVerdict = 'act' | 'ignore' | 'unclear'

export interface SlowDecision {
  verdict: SlowVerdict
  reason: string
  at: number
}

export interface SlowJudgeInput {
  id: string
  text: string
  observedAt: number
  requesters: string[]
}

/** 注入的模型判定通道（宿主接到 ai-service /api/super-agent/slow-path）。 */
export type SlowJudgeCall = (
  inputs: SlowJudgeInput[],
) => Promise<Partial<Record<string, SlowDecision>>>

export const VERDICT_VALUES: readonly SlowVerdict[] = ['act', 'ignore', 'unclear']

export function isSlowVerdict(v: unknown): v is SlowVerdict {
  return v === 'act' || v === 'ignore' || v === 'unclear'
}

/** 把判定响应拆成逐条注记；无该 id 结果 ⇒ 该条不落注记（判不出 ≠ 判过，§0.3）。 */
export function pickDecisions(
  response: Partial<Record<string, SlowDecision>>,
  ids: string[],
): { id: string; decision: SlowDecision }[] {
  const rows: { id: string; decision: SlowDecision }[] = []
  for (const id of ids) {
    const d = response[id]
    if (
      !d ||
      !isSlowVerdict(d.verdict) ||
      typeof d.reason !== 'string' ||
      typeof d.at !== 'number'
    ) {
      continue
    }
    rows.push({ id, decision: { verdict: d.verdict, reason: d.reason, at: d.at } })
  }
  return rows
}
