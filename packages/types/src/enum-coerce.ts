/**
 * G-815963(2026-10-01):未知枚举值的兜底唯一出口。
 *
 * 旧形态:`as XxxStatus` 直转让未来值直接透传(列值闭集既无 DB 约束也无读侧校验),
 * 或"兜到初始态"把已终态的账放回可写集合(上游 session-inputs 的反例:未知
 * status→'admitted' 使已终态行重新进入可 settle 集合,与状态前置 CAS 相互拆台)。
 *
 * 纪律(调用点必须遵守,本出口只保证机制):
 *   - `safe` 档逐枚举**显式声明**为终态/只读/禁用那一档 —— "不再产生副作用"的那一档;
 *   - 禁止把初始态(pending/running 之类)当 safe 传;
 *   - 全集用 `as const` 元组传入,值域由类型层闭合。
 */

/** 值 ∈ 全集时原样返回(收窄为字面量联合);不在全集 ⇒ 返回显式声明的安全档。 */
export function coerceKnownOr<T extends string>(
  value: unknown,
  known: readonly T[],
  safe: T,
): T {
  return typeof value === 'string' && (known as readonly string[]).includes(value)
    ? (value as T)
    : safe
}

/**
 * 读侧(纯呈现域) narrowing:值 ∈ 全集 ⇒ 收窄为字面量联合;不在全集 ⇒ `null`,由调用方走**独立档**。
 *
 * 与 `coerceKnownOr` 是同一份值域判据的两个投影,不是第二套实现:
 *   · 写侧/决策域要知道"未知就落到我显式声明的那一安全档" ⇒ `coerceKnownOr`;
 *   · 呈现域**不许把未知冒充成已知**(资金类状态猜成 completed / pending 都是对用户谎报,
 *     且猜成 pending 会把它放回可操作集合)⇒ 这里只回 `T | null`,兜哪一档由调用方自己写。
 */
export function narrowKnown<T extends string>(
  value: unknown,
  known: readonly T[],
): T | null {
  return typeof value === 'string' && (known as readonly string[]).includes(value)
    ? (value as T)
    : null
}

/** `as const` 元组 → 其成员联合的便捷别名(全集声明处用,避免重复抄联合)。 */
export type KnownValues<T extends readonly string[]> = T[number]
