/** Skill 同步请求(跨端同步) */
export interface SkillSyncRequest {
  /** 用户 ID */
  userId: string
  /** 操作类型 */
  action: 'push' | 'pull' | 'list'
  /** push:本地 skill 推到 api;pull:从 api 拉到本地 */
  skills?: Array<{
    name: string
    description?: string
    content: string
    frontmatter?: SkillFrontmatter
  }>
  /** pull 时指定要拉的 skill 名(缺省拉全部) */
  skillNames?: string[]
}

/** Skill 同步响应 */
export interface SkillSyncResponse {
  /** 操作结果 */
  action: 'push' | 'pull' | 'list'
  /** 同步的 skill 列表 */
  skills: Array<{
    name: string
    description?: string
    content: string
    frontmatter?: SkillFrontmatter
    source?: SkillSource
  }>
  /** 同步数量 */
  count: number
  /** 同步时间(ISO) */
  syncedAt: string
}

