/** Skill 测试用例 */
export interface SkillTestCase {
  /** 测试名 */
  name: string
  /** 测试输入 */
  input: string
  /** 期望输出(包含的关键词或正则) */
  expectedPattern: string
  /** 是否正则匹配(默认 false,字符串包含) */
  isRegex?: boolean
}

/** Skill 测试请求 */
export interface SkillTestRequest {
  /** skill 名 */
  skillName: string
  /** skill 内容(SKILL.md 正文) */
  skillContent: string
  /** 测试用例列表 */
  testCases: SkillTestCase[]
  /** 测试超时(秒,默认 30) */
  timeoutSeconds?: number
}

/** 单个测试用例结果 */
export interface SkillTestCaseResult {
  /** 测试名 */
  name: string
  /** 实际输出 */
  actualOutput: string
  /** 是否通过 */
  passed: boolean
  /** 失败原因(passed=false 时) */
  failureReason?: string
  /** 执行时长(ms) */
  durationMs: number
}

/** Skill 测试结果 */
export interface SkillTestResult {
  /** skill 名 */
  skillName: string
  /** 测试用例结果列表 */
  results: SkillTestCaseResult[]
  /** 通过数 */
  passed: number
  /** 总数 */
  total: number
  /** 通过率(0-1) */
  passRate: number
  /** 总耗时(ms) */
  totalDurationMs: number
  /** 是否全部通过 */
  allPassed: boolean
}

/** Skill 使用反馈(单次使用记录) */
export interface SkillUsageFeedback {
  /** skill 名 */
  skillName: string
  /** 使用任务 ID */
  taskId: string
  /** 使用时间(ISO) */
  usedAt: string
  /** 是否成功完成 */
  success: boolean
  /** 用户满意度(0-1,可选,来自用户反馈) */
  userSatisfaction?: number
  /** 执行时长(ms) */
  durationMs: number
  /** 失败原因(success=false 时) */
  failureReason?: string
}

/** Skill 使用统计 */
export interface SkillUsageStats {
  /** skill 名 */
  skillName: string
  /** 总使用次数 */
  totalUses: number
  /** 成功次数 */
  successCount: number
  /** 成功率(0-1) */
  successRate: number
  /** 平均满意度(0-1) */
  avgSatisfaction: number
  /** 平均执行时长(ms) */
  avgDurationMs: number
  /** 最后使用时间(ISO) */
  lastUsedAt: string
  /** 当前版本 */
  currentVersion: string
  /** 迭代历史 */
  iterationHistory: Array<{
    version: string
    iteratedAt: string
    reason: string
    previousPassRate: number
    newPassRate: number
  }>
}

/** Skill 迭代请求(基于反馈优化 skill) */
export interface SkillIterationRequest {
  /** skill 名 */
  skillName: string
  /** 当前 skill 内容 */
  currentContent: string
  /** 使用统计 */
  usageStats: SkillUsageStats
  /** 失败案例(用于改进) */
  failureCases: Array<{ input: string; actualOutput: string; failureReason: string }>
  /** 当前测试结果 */
  currentTestResult: SkillTestResult
}

/** Skill 迭代结果 */
export interface SkillIterationResult {
  /** 是否生成新版本 */
  shouldIterate: boolean
  /** 新版本号(shouldIterate=true 时) */
  newVersion?: string
  /** 新 skill 内容 */
  newContent?: string
  /** 迭代理由 */
  reason: string
  /** 预期改进点 */
  expectedImprovements: string[]
}
