export type CapabilityMode = 'read-only' | 'read-write' | 'execute' | 'all'

export type IsolationMode = 'none' | 'worktree'

export interface SkillFrontmatter {
  name?: string
  description?: string
  /**
   * 工具白名单(声明面)。三值(G-428,2026-10-07 拍板):undefined=键缺席 /
   * null=块状 mapping 判非法(上游 subagent/profile-frontmatter.ts:76-80 原注:
   * "不能被空数组吞掉后扩大 child MCP scope",吞成 [] 或折成缺席都会让
   * "声明了约束"与"什么都没说"在消费面同形) / []=显式空表。
   * 仍是声明面:无执行层按它拦工具调用(G-427 拍板 enforce 默认 off)。
   */
  allowedTools?: string[] | null
  /** allowed-tools 的解析别名,三值语义与 allowedTools 相同 */
  tools?: string[] | null
  model?: string
  tags?: string[]
  /** Skill 版本(语义化,对齐 agentskills.io 开放标准) */
  version?: string
  /** 许可证(MIT/Apache-2.0 等) */
  license?: string
  /** 前置依赖(命令/环境变量) */
  prerequisites?: SkillPrerequisites
  /** 关联 skill 名(用于渐进式加载的引用层) */
  relatedSkills?: string[]
  /** 是否启用渐进式加载(元数据→指令→引用 3 层),默认 false */
  progressiveDisclosure?: boolean
  /** 来源:builtin(预置)/ user(用户编写)/ auto(自进化生成)/ hub(Skills Hub) */
  source?: SkillSource
  /**
   * 权限模式(声明面,frontmatter 原样字符串,未经校验;消费方必须先过
   * permission-mode.ts 归一才可 honour)。加载面分流(G-428,2026-10-07 拍板,
   * 对齐上游 subagent/profile.ts:183-185):仓库内(project)来源一律丢弃 ——
   * 仓库输入不得把运行时抬到 bypass;仅用户主目录来源保留。
   */
  permissionMode?: string
  /** 自进化生成时间(ISO,仅 source=auto 时有值) */
  autoGeneratedAt?: string
  /** 自进化触发任务 ID(仅 source=auto 时有值,用于追溯) */
  autoGeneratedFromTask?: string
}

export interface SkillPrerequisites {
  /** 依赖的系统命令(如 ["curl", "jq"]) */
  commands?: string[]
  /** 依赖的环境变量名(如 ["GITHUB_TOKEN"]) */
  env?: string[]
}

export type SkillSource = 'builtin' | 'user' | 'auto' | 'hub'

export interface SkillDefinition {
  filePath: string
  sourceDir: string
  frontmatter: SkillFrontmatter
  content: string
  hasFrontmatter: boolean
}

