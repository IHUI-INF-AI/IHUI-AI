/** Skill 自进化评估请求(任务结束后 LLM 自评是否提炼可复用模式) */
export interface SkillEvolutionRequest {
  /** 触发任务 ID */
  taskId: string
  /** 会话 ID */
  sessionId: string
  /** 任务目标 */
  goal: string
  /** 任务执行步骤(含 LLM 输出 + 工具调用) */
  steps: Array<{
    iteration: number
    type: 'llm' | 'tool'
    content: string
    toolName?: string
    toolArgs?: unknown
    toolResult?: unknown
  }>
  /** 最终结果 */
  finalResult: string
  /** 现有 skill 名列表(避免重复生成) */
  existingSkills: string[]
}

/** Skill 自进化评估结果 */
export interface SkillEvolutionResult {
  /** 是否提炼出新 skill */
  shouldCreate: boolean
  /** 新 skill 名(shouldCreate=true 时有值) */
  skillName?: string
  /** 新 skill 描述 */
  description?: string
  /** 生成的 SKILL.md 完整内容(含 frontmatter) */
  skillContent?: string
  /** 提炼理由(为何值得沉淀为 skill) */
  reason?: string
  /** 关联的现有 skill(用于 relatedSkills 字段) */
  relatedSkills?: string[]
}

