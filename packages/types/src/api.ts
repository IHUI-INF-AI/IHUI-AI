export interface ApiResponse<T = unknown> {
  code: number
  message: string
  data: T
  errorCode?: string
}

export interface PaginatedResponse<T> {
  list: T[]
  total: number
  page: number
  pageSize: number
}

export type ApiResult<T> =
  // 2026-09-09 0-5 迁移:success 分支补可选 status(如 upsert 场景需区分 200 更新/201 新建),
  // 非破坏性增强——不读该字段的调用方不受影响。
  | { success: true; data: T; error?: undefined; status?: number }
  | { success: false; error: string; status?: number; errorCode?: string; retryAfter?: number }
