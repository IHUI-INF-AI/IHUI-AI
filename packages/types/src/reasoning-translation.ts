/**
 * 思维链翻译跨端契约(2026-11-13 立)
 *
 * 服务端路由 = POST /api/ai/reasoning/translate;客户端只取译文,原文由调用方持有。
 * 语言枚举与长度上限是前后端共用判据,必须留在 @ihui/types,禁止端内各写一份。
 */

/** 支持的目标语言(顺序即 UI 展示顺序) */
export const REASONING_TRANSLATION_LANGS = ['zh-CN', 'zh-TW', 'en', 'ja', 'ko'] as const

export type ReasoningTranslationLang = (typeof REASONING_TRANSLATION_LANGS)[number]

/** 单次可翻译的最大字符数(超出由服务端 400 / 客户端降级,不截断原文) */
export const REASONING_TRANSLATION_MAX_CHARS = 8_000

/** 翻译结果:同语跳过时 translated 为空串且 skipped=true */
export interface ReasoningTranslationResponse {
  translated: string
  targetLang: ReasoningTranslationLang
  model: string
  /** 命中服务端 LRU 缓存 */
  cached: boolean
  /** 原文已是目标语言,未调用模型 */
  skipped: boolean
}
