// 上下文压缩共享包的公共类型(从 index.ts 抽出为叶子模块:
// 让 token 估算 / 回收 / 有效性守卫三个子模块单向依赖它,避免任何运行期循环 import)

/** OpenAI 兼容的工具调用描述(压缩配对保护按 id 匹配) */
export interface ChatMessageToolCall {
  id: string
  type?: string
  function?: { name?: string; arguments?: string }
}

/** 跨端共享的聊天消息结构(与 @ihui/types/message-repair 的 RepairableMessage 兼容) */
export interface ChatMessage {
  role: 'system' | 'user' | 'assistant' | 'tool'
  content: string
  /** assistant 发起的工具调用列表(存在时与其后的 tool 结果消息构成配对组,压缩不拆散) */
  tool_calls?: ChatMessageToolCall[]
  /** tool 结果消息对应的 tool_call id(与前面 assistant 的 tool_calls[].id 配对) */
  tool_call_id?: string
  /** 推理过程(思考)文本 —— **只供估算面投影读取**(见 token-estimate.ts 的 projectForEstimation)。
   *  语义与 `content` 严格分离:绝不并进 `content`,否则 reasoning 会漏进可见正文 / UI 文案 / 记忆 / 错误信息。
   *  缺省 = 这条消息没有推理通道;跨端实际载荷形状不一(字符串 / 分块数组 / 对象),
   *  读不出文本的那些**不静默按 0 计**,按哨兵文本计入估算(票 G-816015)。 */
  reasoning?: string | null
}
