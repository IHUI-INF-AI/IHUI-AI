import { readFileSync, writeFileSync } from 'node:fs'
import { resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import { buildStructuredSummary, estimateMessagesTokens } from '../src/index.js'

const here = dirname(fileURLToPath(import.meta.url))
const fixturesPath = resolve(here, 'consistency-fixtures.json')
const doc = JSON.parse(readFileSync(fixturesPath, 'utf-8'))

for (const fx of doc.fixtures) {
  fx.expect_tokens_ts = estimateMessagesTokens(fx.messages)
  const summary = buildStructuredSummary(fx.messages)
  fx.expect_struct_summary_lines_ts_actual = summary.split('\n')
}
writeFileSync(fixturesPath, JSON.stringify(doc, null, 2) + '\n', 'utf-8')
console.log('fixtures updated with TS actuals')
