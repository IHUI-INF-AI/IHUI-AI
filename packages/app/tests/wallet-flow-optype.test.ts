// XUI-086: RN / 小程序两腿共用 packages/app 钱包屏，屏内不得再留第二套 opType 映射。
import { readFileSync } from 'node:fs'
import { join } from 'node:path'
import { describe, expect, it } from 'vitest'

const APP_ROOT = process.cwd()
const REPO_ROOT = join(APP_ROOT, '..', '..')
const read = (...p: string[]) => readFileSync(join(REPO_ROOT, ...p), 'utf8')

const SHARED_SCREEN = ['packages', 'app', 'src', 'features', 'wallet', 'WalletScreen.tsx']

describe('XUI-086 共享钱包屏 opType 单源', () => {
  it('共享屏只从 @ihui/shared 唯一表取语义，不再自带映射', () => {
    const src = read(...SHARED_SCREEN)
    expect(src).toContain("from '@ihui/shared/utils/wallet-flow-meta'")
    expect(src).toContain('resolveWalletFlowMeta')
    expect(src).not.toContain('POSITIVE_OP_TYPES')
    expect(src).not.toMatch(/OP_TYPE_KEY\s*:/)
    expect(src).toContain('meta.isMoney')
    expect(src).toContain("meta.sign === 'positive'")
    expect(src).toContain("meta.sign === 'negative'")
    expect(src).toContain('flowNeutral')
  })

  it('RN 宿主不自己判断正负号，只把数据交给共享屏', () => {
    const src = read('apps', 'mobile-rn', 'src', 'screens', 'WalletScreen.tsx')
    expect(src).toContain('WalletScreen as SharedWalletScreen')
    expect(src).not.toContain('POSITIVE_OP_TYPES')
    expect(src).not.toMatch(/opType\s*===\s*\d\s*[?:]/)
  })

  it('小程序腿是共享屏镜像，不自己写 opType 映射', () => {
    const src = read('apps', 'miniapp-taro', 'src', 'pkg-shop', 'wallet', 'index.tsx')
    expect(src).toContain('@rn-shells/WalletScreen')
    expect(src).not.toContain('POSITIVE_OP_TYPES')
    expect(src).not.toMatch(/opType\s*===\s*\d\s*[?:]/)
  })
})
