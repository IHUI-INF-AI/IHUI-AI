// 帮助列表搜索过滤的形态锁:web 帮助页有搜索框而共享屏长期没有,
// RN/小程序接到同一份过滤实现后,行为必须逐条钉住(空词/命中问题/命中答案/大小写/空白)。
import { describe, expect, it } from 'vitest'
import { filterHelpItems } from '../src/features/help/filter-help-items'

const ITEMS = [
  { id: 'a', question: '如何退款', answer: '在订单页申请' },
  { id: 'b', question: 'Recharge failed', answer: 'Check the payment method' },
]

describe('filterHelpItems', () => {
  it('空词 / 纯空白 ⇒ 原样返回同一引用(不做无谓重排)', () => {
    expect(filterHelpItems(ITEMS, '')).toBe(ITEMS)
    expect(filterHelpItems(ITEMS, undefined)).toBe(ITEMS)
    expect(filterHelpItems(ITEMS, '   ')).toBe(ITEMS)
  })

  it('命中问题', () => {
    expect(filterHelpItems(ITEMS, '退款').map((i) => i.id)).toEqual(['a'])
  })

  it('命中答案(不只搜标题)', () => {
    expect(filterHelpItems(ITEMS, 'payment').map((i) => i.id)).toEqual(['b'])
  })

  it('大小写不敏感 + 前后空白被裁', () => {
    expect(filterHelpItems(ITEMS, '  RECHARGE  ').map((i) => i.id)).toEqual(['b'])
  })

  it('无命中 ⇒ 空数组(调用方据空态渲染,不得回落成全量)', () => {
    expect(filterHelpItems(ITEMS, '不存在的词')).toEqual([])
  })
})
