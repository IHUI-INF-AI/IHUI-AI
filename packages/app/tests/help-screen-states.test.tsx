// 帮助屏状态回归锁：FAQ 首屏加载失败必须是“错误态 + 重试”，
// 不得把 error 和 EmptyState 同时渲染成“加载失败 + 暂无帮助”两个互相矛盾的结论。

import { createElement } from 'react'
import { afterEach, describe, expect, it, vi } from 'vitest'
import { cleanup, fireEvent, render, screen } from '@testing-library/react'

vi.mock('../src/components/BackChevron', () => ({
  BackChevron: (p: { label: string }) => createElement('button', { 'data-back': p.label }),
}))

vi.mock('../src/components/ScreenStates', () => ({
  ScreenSkeleton: () => createElement('div', { 'data-testid': 'help-skeleton' }),
  EmptyState: (p: { title: string; testID?: string }) =>
    createElement('div', { 'data-testid': p.testID }, p.title),
  ErrorState: (p: {
    message: string
    onRetry?: () => void
    retryLabel?: string
    testID?: string
  }) =>
    createElement(
      'div',
      { 'data-testid': p.testID },
      createElement('span', null, p.message),
      p.onRetry
        ? createElement('button', { 'data-testid': 'help-retry', onClick: p.onRetry }, p.retryLabel)
        : null,
    ),
}))

import { HelpScreen } from '../src/features/help/HelpScreen'

const baseProps = {
  t: (key: string) => key,
  loading: false,
  refreshing: false,
  expandedId: null,
  onRefresh: vi.fn(),
  onToggle: vi.fn(),
  onBack: vi.fn(),
  onToast: vi.fn(),
}

describe('帮助屏错误态', () => {
  afterEach(cleanup)
  it('首屏失败且无数据:只出 ErrorState,重试真回调,不出 EmptyState', () => {
    const onRefresh = vi.fn()
    render(
      createElement(HelpScreen, {
        ...baseProps,
        items: [],
        error: '加载失败',
        onRefresh,
      }),
    )

    expect(screen.getByTestId('help-error')).toBeTruthy()
    expect(screen.queryByTestId('help-empty')).toBeNull()
    fireEvent.click(screen.getByTestId('help-retry'))
    expect(onRefresh).toHaveBeenCalledTimes(1)
  })

  it('已有数据时遇错:保留列表与内联错误条,不再整屏错误态', () => {
    render(
      createElement(HelpScreen, {
        ...baseProps,
        items: [{ id: 'h1', question: '怎么退款', answer: '在订单里申请' }],
        error: '刷新失败',
      }),
    )

    expect(screen.queryByTestId('help-error')).toBeNull()
    expect(screen.getByText('刷新失败')).toBeTruthy()
    expect(screen.getByText('怎么退款')).toBeTruthy()
  })
})
