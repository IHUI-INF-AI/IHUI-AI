/**
 * XUI-020 结构锁:修改密码提交必须 try/catch/finally,失败也要复位 changingPwd。
 * 共享屏被 web/RN/小程序三端复用,任一端 API 抛错都会经这里;用源码级断言钉住收尾语义。
 */
import { readFileSync } from 'node:fs'
import { join } from 'node:path'
import { describe, expect, it } from 'vitest'

const SRC = readFileSync(
  join(__dirname, '..', '..', 'settings', 'SettingsScreen.tsx'),
  'utf8',
)

describe('XUI-020 修改密码失败不得卡死按钮', () => {
  it('onChangePassword 调用被 try 包住,并带 catch 兜底', () => {
    expect(SRC).toMatch(/try \{\s*const ok = await onChangePassword\(oldPwd, newPwd\)/)
    expect(SRC).toMatch(/catch \{\s*onAlert\(t\('settings\.pwdChangeFailed'\)\)/)
  })

  it('changingPwd 复位写在 finally 里(成功/失败/抛错都复位)', () => {
    expect(SRC).toMatch(/finally \{\s*setChangingPwd\(false\)/)
  })
})
