import { rnRadius, rnSpacing, rnType } from '@ihui/design-tokens'

import { useMemo } from 'react'
import { FlatList, RefreshControl, Text, View, StyleSheet } from 'react-native'
import { getTokens, type AppThemeTokens } from '../../theme/tokens'
import type { AgentReviewListScreenProps } from '../../types'
import { BackChevron } from '../../components/BackChevron'
import { EmptyState, ScreenSkeleton } from '../../components/ScreenStates'

/** Agent 评价列表共享屏 — props 注入式跨端组件(纯 UI,不依赖平台 API) */
export type { AgentReviewListScreenProps }

export function AgentReviewListScreen({
  t,
  items,
  loading,
  refreshing,
  error,
  onRefresh,
  onBack,
  colorScheme = 'light',
}: AgentReviewListScreenProps) {
  const tk = getTokens(colorScheme)
  const styles = useMemo(() => createStyles(tk), [tk])

  return (
    <View style={styles.container}>
      <View style={styles.header}>
        <BackChevron onPress={onBack} label={t('common.back')} colorScheme={colorScheme} />
        <Text style={styles.title}>{t('agentReviewList.title')}</Text>
      </View>
      {error ? <Text style={styles.errorText}>{error}</Text> : null}
      {loading && items.length === 0 ? (
        <ScreenSkeleton variant="list" count={4} colorScheme={colorScheme} />
      ) : (
        <FlatList
          data={items}
          keyExtractor={(item) => item.id}
          contentContainerStyle={styles.listContent}
          ItemSeparatorComponent={() => <View style={styles.separator} />}
          refreshControl={<RefreshControl refreshing={refreshing} onRefresh={onRefresh} />}
          ListEmptyComponent={
            <EmptyState title={t('agentReviewList.empty')} colorScheme={colorScheme} />
          }
          renderItem={({ item }) => (
            <View style={styles.card}>
              <View style={styles.cardHead}>
                <Text style={styles.agentName} numberOfLines={1}>
                  {item.agentName}
                </Text>
                <Text style={styles.stars}>
                  {'★'.repeat(Math.max(1, Math.min(5, item.rating || 0)))}
                </Text>
              </View>
              <Text style={styles.content} numberOfLines={2}>
                {item.content}
              </Text>
              <Text style={styles.author}>
                {t('agentReviewList.author')}: {item.author} · {item.createdAt}
              </Text>
            </View>
          )}
        />
      )}
    </View>
  )
}

function createStyles(tk: AppThemeTokens) {
  return StyleSheet.create({
    container: { flex: 1, backgroundColor: tk.surface.bg },
    header: {
      flexDirection: 'row',
      alignItems: 'center',
      gap: rnSpacing.md,
      paddingHorizontal: 10,
      paddingVertical: rnSpacing.md,
    },
    title: { fontSize: rnType.heading.size, fontWeight: '700', color: tk.text.primary },
    errorText: { paddingHorizontal: 10, fontSize: rnType.body.size, color: tk.danger.DEFAULT },
    listContent: { padding: 14 },
    separator: { height: 8 },
    card: {
      padding: 14,
      borderRadius: rnRadius.lg,
      borderWidth: 1,
      borderColor: tk.border.light,
      backgroundColor: tk.surface.light,
    },
    cardHead: {
      flexDirection: 'row',
      alignItems: 'center',
      justifyContent: 'space-between',
    },
    agentName: {
      flex: 1,
      marginRight: rnSpacing.sm,
      fontSize: rnType.title.size,
      fontWeight: '700',
      color: tk.text.primary,
    },
    stars: { fontSize: rnType.body.size, color: tk.warning.amber },
    content: { marginTop: rnSpacing.sm, fontSize: rnType.body.size, color: tk.text.secondary },
    author: { marginTop: rnSpacing.sm, fontSize: rnType.caption.size, color: tk.text.tertiary },
  })
}
