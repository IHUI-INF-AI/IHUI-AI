import { cleanup, fireEvent, render, screen } from '@testing-library/react'
import { afterEach, describe, expect, it, vi } from 'vitest'
import type { AgentReviewListItem, TFunction } from '@ihui/types'
import { AgentReviewListScreen } from '../AgentReviewListScreen'

const t = ((key: string) => key) as unknown as TFunction

/**
 * 测试桩:共享屏只消费调用方解析好的明暗档案(真机值来自 ThemeContext.resolvedTheme);
 * 单测固定浅色,避免组件静默落回形参默认值。
 */
const TEST_COLOR_SCHEME: 'light' | 'dark' = 'light'

const items: AgentReviewListItem[] = [
  {
    id: 'r1',
    agentName: '写作助手',
    author: '用户A',
    rating: 5,
    content: '很好用',
    createdAt: '2026-10-01',
  },
]

const baseProps = {
  t,
  items,
  loading: false,
  refreshing: false,
  error: '',
  onRefresh: vi.fn(),
  onBack: vi.fn(),
  colorScheme: TEST_COLOR_SCHEME,
}

afterEach(cleanup)

describe('AgentReviewListScreen 条目点击', () => {
  it('缺省保持纯 View（没有可点 affordance）', () => {
    render(<AgentReviewListScreen {...baseProps} />)
    expect(screen.getByText('写作助手')).toBeTruthy()
    expect(screen.queryByLabelText('写作助手')).toBeNull()
  })

  it('注入 onItemPress 后点击回调携带该项', () => {
    const onItemPress = vi.fn()
    render(<AgentReviewListScreen {...baseProps} onItemPress={onItemPress} />)
    fireEvent.click(screen.getByLabelText('写作助手'))
    expect(onItemPress).toHaveBeenCalledWith(items[0])
  })
})
