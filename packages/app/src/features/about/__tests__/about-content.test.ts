// M4 api-B(2026-11-03):About 数据层判据。
// web 端 apps/web/app/(main)/about/ 只消费 useI18n,无任何请求 ⇒ 本屏断言「0 请求 + 本地静态配置」。
import { afterEach, describe, expect, it, vi } from 'vitest'
import { ABOUT_CONTENT_ENDPOINT, ABOUT_DATA_SOURCE, loadAboutContent } from '../about-content'

afterEach(() => {
  vi.unstubAllGlobals()
})

describe('About 数据层 — 无远端接口', () => {
  it('显式声明静态来源与无端点(不编造 URL)', () => {
    expect(ABOUT_DATA_SOURCE).toBe('static')
    expect(ABOUT_CONTENT_ENDPOINT).toBeNull()
  })

  it('读取内容全程不发请求', () => {
    const fetchSpy = vi.fn()
    vi.stubGlobal('fetch', fetchSpy)

    const content = loadAboutContent()

    expect(fetchSpy).not.toHaveBeenCalled()
    expect(content.values.length).toBeGreaterThan(0)
    expect(content.platforms.length).toBeGreaterThan(0)
    expect(content.stats.length).toBeGreaterThan(0)
  })
})
