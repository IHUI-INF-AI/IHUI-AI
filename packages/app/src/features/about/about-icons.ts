import {
  Blocks,
  CircleDollarSign,
  Cpu,
  Database,
  Globe,
  Plug,
  ShieldCheck,
  Users,
  Workflow,
  type LucideIcon,
} from 'lucide-react-native'

/**
 * RN 侧的字形解析:分段表里的 `icon` 是 lucide kebab-case 名(跨端单一源),
 * 这里映射成组件句柄。小程序端走本端 LineIcon 注册表,同一张表、不同解析。
 */
const ICONS: Record<string, LucideIcon> = {
  globe: Globe,
  blocks: Blocks,
  'circle-dollar-sign': CircleDollarSign,
  'shield-check': ShieldCheck,
  database: Database,
  cpu: Cpu,
  plug: Plug,
  workflow: Workflow,
  users: Users,
}

export function aboutIcon(name: string): LucideIcon {
  return ICONS[name] ?? Globe
}
