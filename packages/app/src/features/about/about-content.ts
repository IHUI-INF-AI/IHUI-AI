import {
  ABOUT_PLATFORMS,
  ABOUT_STATS,
  ABOUT_VALUES,
  type AboutFeatureEntry,
  type AboutStatEntry,
} from '@ihui/shared/constants'

/**
 * About 屏数据层(2026-11-03 M4 api-B)。
 *
 * **明确声明:本屏无需远端接口。**
 * 真源核对:web 端 `apps/web/app/(main)/about/`(page.tsx + AboutContent.tsx)整屏只消费
 * `useI18n`,没有任何 `api` / `fetch` / `useQuery` 调用;文案与段落表来自本地静态配置。
 * 因此这里不编造端点,只把 RN 共享屏原先内联引用的三段静态数据收进单一数据层入口,
 * `ABOUT_CONTENT_ENDPOINT = null` 是给后续维护者的显式判据(不是遗漏)。
 */

export const ABOUT_DATA_SOURCE = 'static' as const
/** 无远端接口:null 为真实结论,不是未填 */
export const ABOUT_CONTENT_ENDPOINT = null

export interface AboutContent {
  values: readonly AboutFeatureEntry[]
  platforms: readonly AboutFeatureEntry[]
  stats: readonly AboutStatEntry[]
}

/** 纯同步读取本地配置(不发请求,可在渲染期直接调用) */
export function loadAboutContent(): AboutContent {
  return {
    values: ABOUT_VALUES,
    platforms: ABOUT_PLATFORMS,
    stats: ABOUT_STATS,
  }
}
