/** 计费方式标签:仅收录可确认值,其余原样返回 */
const PAY_MODE_LABELS: Record<string, string> = {
  free: '免费',
  paid: '付费',
}

/** 厂商显示名:仅收录本仓取证可确认的 id,其余原样返回 */
const PROVIDER_DISPLAY_NAMES: Record<string, string> = {
  ihui_relay: '智汇AI',
  cloudflare_workers_ai: 'Cloudflare Workers AI',
}

/** 计费方式展示文案:未知值原样返回,不臆造 */
export function payModeLabel(mode: string): string {
  return PAY_MODE_LABELS[mode] ?? mode
}

/** 厂商显示名:未知 providerId 原样返回 */
export function providerDisplayName(providerId: string): string {
  return PROVIDER_DISPLAY_NAMES[providerId] ?? providerId
}
