import { useMemo } from 'react'
import { View, Text, TouchableOpacity, StyleSheet } from 'react-native'
import { XCircle } from 'lucide-react-native'
import { getTokens, type AppThemeTokens } from '../../theme/tokens'
import type { TopupFailScreenProps } from '../../types'

import { rnRadius, rnSpacing, rnType } from '@ihui/design-tokens'
import { BackChevron } from '../../components/BackChevron'

/** Props 类型 re-export(单一来源 @ihui/types) */
export type { TopupFailScreenProps }

/**
 * 充值失败共享屏 — 纯 UI 渲染,平台无关
 *
 * 渲染失败图标 + 原因 + 重试/联系客服按钮
 * 导航/数据由 wrapper 通过 props 注入
 */
export function TopupFailScreen({
  t,
  reason = '充值未完成,请稍后重试',
  onRetry,
  onContactService,
  onBack,
  colorScheme = 'light',
}: TopupFailScreenProps) {
  const tk = getTokens(colorScheme)
  const styles = useMemo(() => createStyles(tk), [tk])

  return (
    <View style={styles.container}>
      <View style={styles.header}>
        <BackChevron onPress={onBack} label={t('common.back')} colorScheme={colorScheme} />
        <Text style={styles.title}>充值结果</Text>
      </View>
      <View style={styles.body}>
        <XCircle size={64} color={tk.danger.DEFAULT} />
        <Text style={styles.titleText}>充值失败</Text>
        <View style={styles.card}>
          <Text style={styles.reason}>{reason}</Text>
        </View>
        <View style={styles.actions}>
          <TouchableOpacity style={styles.primaryBtn} activeOpacity={0.7} onPress={onRetry}>
            <Text style={styles.primaryText}>重试</Text>
          </TouchableOpacity>
          <TouchableOpacity
            style={styles.secondaryBtn}
            activeOpacity={0.7}
            onPress={onContactService}
          >
            <Text style={styles.secondaryText}>联系客服</Text>
          </TouchableOpacity>
        </View>
      </View>
    </View>
  )
}

function createStyles(tk: AppThemeTokens) {
  return StyleSheet.create({
    container: { flex: 1, backgroundColor: tk.surface.bg },
    header: {
      flexDirection: 'row',
      alignItems: 'center',
      paddingHorizontal: 10,
      paddingVertical: rnSpacing.md,
      gap: rnSpacing.md,
    },
    title: { fontSize: rnType.heading.size, fontWeight: '600', color: tk.text.primary },
    body: { flex: 1, alignItems: 'center', padding: rnSpacing['2xl'], gap: rnSpacing.md },
    icon: { fontSize: 64, marginTop: rnSpacing.md },
    titleText: { fontSize: 22, fontWeight: '700', color: tk.danger.DEFAULT },
    card: {
      width: '100%',
      backgroundColor: tk.danger.light,
      borderRadius: rnRadius.lg,
      padding: rnSpacing.md,
    },
    reason: { fontSize: rnType.title.size, color: tk.danger.DEFAULT, textAlign: 'center' },
    actions: { width: '100%', gap: rnSpacing.md, marginTop: rnSpacing.sm },
    primaryBtn: {
      borderRadius: rnRadius.sm,
      height: 50,
      alignItems: 'center',
      justifyContent: 'center',
      backgroundColor: tk.brand.cta,
    },
    primaryText: { fontSize: rnType.title.size, fontWeight: '600', color: tk.surface.light },
    secondaryBtn: {
      borderRadius: rnRadius.sm,
      height: 44,
      alignItems: 'center',
      justifyContent: 'center',
      backgroundColor: tk.surface.card,
    },
    secondaryText: { fontSize: rnType.title.size, color: tk.text.primary },
  })
}
