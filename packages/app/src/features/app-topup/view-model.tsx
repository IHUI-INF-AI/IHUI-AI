import type { AppTopupRateTier, AppTopupScreenTexts, AppTopupUserInfo } from '@ihui/types'

/**
 * 三档充值比例(每 1 元对应的智汇值,硬编码沿用原项目 top-up/index.vue
 * data 初始值:denomination 20000 / denominationVip 40000 / denominationOperate 80000,
 * 不做后台配置)。
 */
export const TOPUP_TIERS: AppTopupRateTier[] = [
  { key: 'normal', label: '普通用户', tokens: 20000 },
  { key: 'vip', label: '会员', tokens: 40000 },
  { key: 'trader', label: '操盘手', tokens: 80000 },
]

export interface AppTopupSegmentInput {
  user?: AppTopupUserInfo
  balance?: number
  rateTiers?: AppTopupRateTier[]
  texts?: AppTopupScreenTexts
  selectedId: string
  customAmount: string
  submitting?: boolean
}

export interface AppTopupSegments {
  showUser: boolean
  showBalance: boolean
  tiers: AppTopupRateTier[]
  canSubmit: boolean
  submitting: boolean
}

export function resolveAppTopupSegments(p: AppTopupSegmentInput): AppTopupSegments {
  return {
    showUser: !!p.user,
    showBalance: p.balance !== undefined && p.balance !== null,
    tiers: p.rateTiers && p.rateTiers.length > 0 ? p.rateTiers : TOPUP_TIERS,
    canSubmit: p.selectedId.length > 0 || p.customAmount.trim().length > 0,
    submitting: !!p.submitting,
  }
}
