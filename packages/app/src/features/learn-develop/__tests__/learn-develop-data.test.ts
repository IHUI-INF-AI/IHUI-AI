// M4 api-B(2026-11-03):LearnDevelop 数据层判据。
// web 无 learn-develop 页(learn 页是课程列表,非本屏) ⇒ 入口为本地静态配置,0 请求。
import { afterEach, describe, expect, it, vi } from 'vitest'
import {
  LEARN_DEVELOP_DATA_SOURCE,
  LEARN_DEVELOP_ENDPOINT,
  LEARN_DEVELOP_ENTRY_SPECS,
} from '../learn-develop-data'

afterEach(() => {
  vi.unstubAllGlobals()
})

describe('LearnDevelop 数据层 — 无远端接口', () => {
  it('显式声明静态来源与无端点(不挪用 learn 课程列表接口)', () => {
    expect(LEARN_DEVELOP_DATA_SOURCE).toBe('static')
    expect(LEARN_DEVELOP_ENDPOINT).toBeNull()
  })

  it('入口集合为本地静态配置,读取全程不发请求', () => {
    const fetchSpy = vi.fn()
    vi.stubGlobal('fetch', fetchSpy)

    expect(LEARN_DEVELOP_ENTRY_SPECS.map((entry) => entry.id)).toEqual([
      'coursePlanet',
      'studyPlan',
      'knowledgePlanet',
      'studyIndex',
      'learnCenter',
    ])
    for (const entry of LEARN_DEVELOP_ENTRY_SPECS) {
      expect(entry.titleKey).toMatch(/^learnDevelop\.|^studyPlan\./)
      expect(entry.target).not.toMatch(/^\//)
    }
    expect(fetchSpy).not.toHaveBeenCalled()
  })
})
