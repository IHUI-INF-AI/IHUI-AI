import { useMemo } from 'react'
import { View, Text, TouchableOpacity, ActivityIndicator, StyleSheet } from 'react-native'
import { getTokens, type AppThemeTokens } from '../../theme/tokens'
import type { CourseQAAskScreenProps } from '../../types'

import { rnRadius, rnSpacing, rnType } from '@ihui/design-tokens'
import { BackChevron } from '../../components/BackChevron'
import { TextField } from '../../components/TextField'

/** 课程问答提问共享屏 — props 注入式跨端组件 */
export type { CourseQAAskScreenProps }

export function CourseQAAskScreen({
  t,
  question,
  submitting,
  error,
  success,
  onQuestionChange,
  onSubmit,
  onBack,
  colorScheme = 'light',
}: CourseQAAskScreenProps) {
  const tk = getTokens(colorScheme)
  const styles = useMemo(() => createStyles(tk), [tk])

  return (
    <View style={styles.container}>
      <View style={styles.header}>
        <BackChevron onPress={onBack} label={t('common.back')} colorScheme={colorScheme} />
        <Text style={styles.title}>{t('courseQAAsk.title')}</Text>
      </View>

      <View style={styles.body}>
        <Text style={styles.label}>{t('courseQAAsk.question')}</Text>
        <TextField
          colorScheme={colorScheme}
          style={styles.textarea}
          value={question}
          onChangeText={onQuestionChange}
          placeholder={t('courseQAAsk.placeholder')}
          placeholderTextColor={tk.text.tertiary}
          multiline
          textAlignVertical="top"
        />
        {error ? <Text style={styles.error}>{error}</Text> : null}
        {success ? <Text style={styles.toast}>{t('courseQAAsk.success')}</Text> : null}
        <TouchableOpacity
          style={[styles.btn, submitting && styles.btnDisabled]}
          onPress={onSubmit}
          disabled={submitting}
          hitSlop={{ top: 4, bottom: 4, left: 4, right: 4 }}
        >
          {submitting ? (
            <ActivityIndicator color={tk.brand.ctaForeground} />
          ) : (
            <Text style={styles.btnText}>{t('courseQAAsk.submit')}</Text>
          )}
        </TouchableOpacity>
      </View>
    </View>
  )
}

function createStyles(tk: AppThemeTokens) {
  return StyleSheet.create({
    container: { flex: 1, backgroundColor: tk.surface.bg },
    header: {
      flexDirection: 'row',
      alignItems: 'center',
      paddingHorizontal: 10,
      paddingVertical: rnSpacing.md,
      gap: rnSpacing.md,
    },
    body: { padding: 10 },
    title: { fontSize: rnType.heading.size, fontWeight: '600', color: tk.text.primary },
    label: { fontSize: rnType.body.size, color: tk.text.secondary },
    textarea: {
      marginTop: 6,
      minHeight: 120,
      paddingHorizontal: rnSpacing.md,
      paddingVertical: 10,
      borderRadius: rnRadius.sm,
      borderWidth: 1,
      borderColor: tk.border.light,
      backgroundColor: tk.surface.muted,
      fontSize: rnType.title.size,
      color: tk.text.primary,
    },
    error: { fontSize: rnType.body.size, color: tk.danger.DEFAULT, marginTop: rnSpacing.sm },
    toast: { fontSize: rnType.body.size, color: tk.success.DEFAULT, marginTop: rnSpacing.sm },
    btn: {
      marginTop: rnSpacing.lg,
      backgroundColor: tk.brand.cta,
      paddingVertical: rnSpacing.md,
      borderRadius: rnRadius.sm,
      alignItems: 'center',
    },
    btnDisabled: { opacity: 0.6 },
    btnText: { color: tk.brand.ctaForeground, fontSize: rnType.title.size, fontWeight: '600' },
  })
}
