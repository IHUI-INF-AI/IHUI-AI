/** 帮助列表搜索过滤的唯一实现(问题或答案命中即保留,大小写不敏感,空词原样返回) */
export function filterHelpItems<T extends { question: string; answer: string }>(
  items: T[],
  query: string | undefined,
): T[] {
  const q = (query ?? '').trim().toLowerCase()
  if (!q) return items
  return items.filter(
    (i) => i.question.toLowerCase().includes(q) || i.answer.toLowerCase().includes(q),
  )
}
