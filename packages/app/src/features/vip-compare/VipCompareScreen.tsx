import { rnSpacing, rnType } from '@ihui/design-tokens'

import { useMemo } from 'react'
import { ScrollView, Text, TouchableOpacity, View, StyleSheet } from 'react-native'
import { ChevronLeft } from 'lucide-react-native'
import { getTokens, type AppThemeTokens } from '../../theme/tokens'
import type { VipCompareScreenProps } from '../../types'
import { BackChevron } from '../../components/BackChevron'
import { ScreenSkeleton } from '../../components/ScreenStates'
import { assertRequiredPort } from '../../host/ports'
import { VipMatrix } from './VipMatrix'

/** VIP 对比共享屏 — props 注入式跨端组件 */
export type { VipCompareScreenProps }

export function VipCompareScreen({
  t,
  rows,
  loading,
  error,
  onBack,
  colorScheme = 'light',
  onNavigate,
}: VipCompareScreenProps) {
  assertRequiredPort('onNavigate', onNavigate)

  const tk = getTokens(colorScheme)
  const styles = useMemo(() => createStyles(tk), [tk])

  if (loading) {
    return <ScreenSkeleton variant="card" count={3} colorScheme={colorScheme} />
  }
  if (error) {
    return (
      <View style={styles.center}>
        <Text style={styles.error}>{error}</Text>
        <TouchableOpacity
          style={styles.backBtn}
          onPress={onBack}
          accessibilityLabel={t('common.back')}
        >
          <ChevronLeft size={16} color={tk.text.medium} />
        </TouchableOpacity>
      </View>
    )
  }
  if (rows.length === 0) {
    return (
      <View style={styles.center}>
        <Text style={styles.muted}>{t('common.empty')}</Text>
        <TouchableOpacity
          style={styles.backBtn}
          onPress={onBack}
          accessibilityLabel={t('common.back')}
        >
          <ChevronLeft size={16} color={tk.text.medium} />
        </TouchableOpacity>
      </View>
    )
  }

  return (
    <ScrollView style={styles.container}>
      <View style={styles.header}>
        <BackChevron onPress={onBack} label={t('common.back')} colorScheme={colorScheme} />
        <Text style={styles.title}>{t('vipCompare.title')}</Text>
      </View>
      <View style={styles.tableWrap}>
        <VipMatrix
          columns={[
            t('vipCompare.feature'),
            t('vipCompare.basic'),
            t('vipCompare.premium'),
            t('vipCompare.enterprise'),
          ]}
          rows={rows.map((row) => ({
            label: row.feature,
            values: [row.basic, row.premium, row.enterprise],
          }))}
          colorScheme={colorScheme}
        />
      </View>
    </ScrollView>
  )
}

function createStyles(tk: AppThemeTokens) {
  return StyleSheet.create({
    container: { flex: 1, backgroundColor: tk.surface.bg },
    header: {
      flexDirection: 'row',
      alignItems: 'center',
      paddingHorizontal: rnSpacing['sm-loose'],
      paddingVertical: rnSpacing.md,
      gap: rnSpacing.md,
    },
    title: { fontSize: rnType.heading.size, fontWeight: '700', color: tk.text.primary },
    tableWrap: { margin: rnSpacing.lg },
    center: {
      flex: 1,
      alignItems: 'center',
      justifyContent: 'center',
      padding: rnSpacing['md-loose'],
      backgroundColor: tk.surface.bg,
    },
    muted: { fontSize: rnType.body.size, color: tk.text.secondary, marginTop: rnSpacing.sm },
    error: { fontSize: rnType.body.size, color: tk.danger.DEFAULT, textAlign: 'center' },
    backBtn: { marginTop: rnSpacing.md },
  })
}
