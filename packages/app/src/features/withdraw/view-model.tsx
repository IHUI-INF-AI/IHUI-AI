// 提现屏纯段逻辑(无 react-native 依赖,供共享屏与单测共用)。

export interface WithdrawSegmentInput {
  methods?: { id: string }[]
  accountInfo?: string
  onAccountInfoChange?: (text: string) => void
  onFillAll?: () => void
  recordsLabel?: string
  onRecords?: () => void
}

export interface WithdrawSegments {
  showMethods: boolean
  showAccount: boolean
  showFillAll: boolean
  showRecords: boolean
}

export function resolveWithdrawSegments(p: WithdrawSegmentInput): WithdrawSegments {
  return {
    showMethods: !!p.methods && p.methods.length > 0,
    showAccount: p.accountInfo !== undefined && typeof p.onAccountInfoChange === 'function',
    showFillAll: typeof p.onFillAll === 'function',
    showRecords: typeof p.onRecords === 'function' && !!p.recordsLabel,
  }
}
