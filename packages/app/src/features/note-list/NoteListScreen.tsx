import { rnRadius } from '@ihui/design-tokens'

import { useMemo } from 'react'
import { View, Text, TouchableOpacity, FlatList, RefreshControl, StyleSheet } from 'react-native'
import { getTokens, type AppThemeTokens } from '../../theme/tokens'
import { Heart } from 'lucide-react-native'
import type { NoteListItem, NoteListScreenProps } from '../../types'
import { BackChevron } from '../../components/BackChevron'
import { EmptyState, PressableCard, ScreenSkeleton } from '../../components/ScreenStates'

/** 笔记列表/Props 类型 re-export(单一来源 @ihui/types) */
export type { NoteListItem, NoteListScreenProps }

/**
 * 笔记列表共享屏 — props 注入式跨端组件
 *
 * 平台无关:负责渲染 header(返回 + 标题 + 可选 "+")+ 错误提示(可选)
 * + loading 态 + 笔记卡片列表(title + summary[2行] + author + likes + createdAt)
 * + 下拉刷新 + 空态。
 * 平台特定(导航 / API 调用)由 wrapper 通过 props 注入。
 */
export function NoteListScreen({
  t,
  items,
  loading,
  refreshing,
  error,
  onRefresh,
  onPressItem,
  onCreate,
  onBack,
  colorScheme = 'light',
}: NoteListScreenProps) {
  const tk = getTokens(colorScheme)
  const styles = useMemo(() => createStyles(tk), [tk])

  return (
    <View style={styles.container}>
      <View style={styles.header}>
        <BackChevron onPress={onBack} label={t('common.back')} colorScheme={colorScheme} />
        <Text style={styles.title}>{t('noteList.title')}</Text>
        {onCreate ? (
          <TouchableOpacity onPress={onCreate} hitSlop={{ top: 8, bottom: 8, left: 8, right: 8 }}>
            <Text style={styles.createText}>+</Text>
          </TouchableOpacity>
        ) : null}
      </View>

      {error ? <Text style={styles.errorText}>{error}</Text> : null}

      {loading && items.length === 0 ? (
        <ScreenSkeleton variant="list" count={4} colorScheme={colorScheme} />
      ) : (
        <FlatList<NoteListItem>
          data={items}
          keyExtractor={(item) => item.id}
          contentContainerStyle={styles.listBody}
          ItemSeparatorComponent={() => <View style={styles.separator} />}
          refreshControl={<RefreshControl refreshing={refreshing} onRefresh={onRefresh} />}
          ListEmptyComponent={<EmptyState title={t('noteList.empty')} colorScheme={colorScheme} />}
          renderItem={({ item }) => (
            <PressableCard
              style={styles.card}
              onPress={() => onPressItem(item)}
              colorScheme={colorScheme}
            >
              <Text style={styles.cardTitle} numberOfLines={1}>
                {item.title}
              </Text>
              <Text style={styles.cardSummary} numberOfLines={2}>
                {item.summary}
              </Text>
              <View style={styles.metaRow}>
                <Text style={styles.author}>{item.author}</Text>
                <View style={{ flexDirection: 'row', alignItems: 'center', gap: 4 }}>
                  <Heart size={11} color={tk.text.tertiary} />
                  <Text style={styles.meta}>
                    {' '}
                    {item.likes} · {item.createdAt}
                  </Text>
                </View>
              </View>
            </PressableCard>
          )}
        />
      )}
    </View>
  )
}

function createStyles(tk: AppThemeTokens) {
  return StyleSheet.create({
    container: { flex: 1, backgroundColor: tk.surface.bg },
    header: {
      flexDirection: 'row',
      alignItems: 'center',
      paddingHorizontal: 10,
      paddingVertical: 12,
      gap: 12,
    },
    title: { flex: 1, fontSize: 20, fontWeight: '700', color: tk.text.primary },
    createText: { fontSize: 24, fontWeight: '600', color: tk.brand.DEFAULT },
    errorText: { paddingHorizontal: 10, fontSize: 14, color: tk.danger.DEFAULT },
    listBody: { padding: 10 },
    separator: { height: 12 },
    card: {
      padding: 14,
      borderRadius: rnRadius.lg,
      borderWidth: 1,
      borderColor: tk.border.light,
      backgroundColor: tk.surface.light,
    },
    cardTitle: { fontSize: 16, fontWeight: '600', color: tk.text.primary },
    cardSummary: {
      marginTop: 8,
      fontSize: 14,
      color: tk.text.medium,
    },
    metaRow: {
      flexDirection: 'row',
      justifyContent: 'space-between',
      alignItems: 'center',
      marginTop: 8,
    },
    author: { fontSize: 11, color: tk.text.tertiary },
    meta: { fontSize: 11, color: tk.text.tertiary },
  })
}
