import { rnRadius } from '@ihui/design-tokens'

import { useMemo } from 'react'
import { View, Text, FlatList, RefreshControl, StyleSheet } from 'react-native'
import { getTokens, type AppThemeTokens } from '../../theme/tokens'
import type { OrderLogItem, OrderLogScreenProps } from '../../types'
import { BackChevron } from '../../components/BackChevron'
import { EmptyState, ScreenSkeleton } from '../../components/ScreenStates'

/** 订单日志共享屏 — props 注入式跨端组件 */
export type { OrderLogItem, OrderLogScreenProps }

export function OrderLogScreen({
  t,
  items,
  loading,
  refreshing,
  error,
  onRefresh,
  onBack,
  colorScheme = 'light',
}: OrderLogScreenProps) {
  const tk = getTokens(colorScheme)
  const styles = useMemo(() => createStyles(tk), [tk])

  return (
    <View style={styles.container}>
      <View style={styles.header}>
        <BackChevron onPress={onBack} label={t('common.back')} colorScheme={colorScheme} />
        <Text style={styles.title}>{t('orderLog.title')}</Text>
      </View>

      {error ? <Text style={styles.error}>{error}</Text> : null}

      {loading && items.length === 0 ? (
        <ScreenSkeleton variant="list" count={4} colorScheme={colorScheme} />
      ) : (
        <FlatList<OrderLogItem>
          data={items}
          keyExtractor={(item) => item.id}
          contentContainerStyle={styles.listBody}
          refreshControl={<RefreshControl refreshing={refreshing} onRefresh={onRefresh} />}
          ListEmptyComponent={<EmptyState title={t('orderLog.empty')} colorScheme={colorScheme} />}
          renderItem={({ item }) => (
            <View style={styles.card}>
              <View style={styles.titleRow}>
                <Text style={styles.cardTitle}>
                  {t('orderLog.action')}: {item.action}
                </Text>
                <Text style={styles.cardTime}>{item.time}</Text>
              </View>
              <Text style={styles.cardMeta}>
                {t('orderLog.operator')}: {item.operator}
              </Text>
              {item.note ? (
                <Text style={styles.cardNote} numberOfLines={2}>
                  {item.note}
                </Text>
              ) : null}
            </View>
          )}
        />
      )}
    </View>
  )
}

function createStyles(tk: AppThemeTokens) {
  return StyleSheet.create({
    container: { flex: 1, backgroundColor: tk.surface.bg },
    header: {
      flexDirection: 'row',
      alignItems: 'center',
      paddingHorizontal: 10,
      paddingVertical: 12,
      gap: 12,
    },
    title: { fontSize: 20, fontWeight: '600', color: tk.text.primary },
    error: { paddingHorizontal: 10, fontSize: 14, color: tk.danger.DEFAULT },
    listBody: { padding: 10, gap: 8 }, // §4 禁分割线:卡片整圈描边 + 间距分隔
    card: {
      padding: 12,
      borderRadius: rnRadius.lg,
      borderWidth: 1,
      borderColor: tk.border.light,
      backgroundColor: tk.surface.light,
    },
    titleRow: {
      flexDirection: 'row',
      justifyContent: 'space-between',
      alignItems: 'center',
    },
    cardTitle: { fontSize: 16, fontWeight: '600', color: tk.text.primary },
    cardTime: { fontSize: 11, color: tk.text.tertiary },
    cardMeta: { marginTop: 8, fontSize: 14, color: tk.text.secondary },
    cardNote: { marginTop: 8, fontSize: 14, color: tk.text.tertiary },
  })
}
