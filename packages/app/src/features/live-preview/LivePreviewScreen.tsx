import { useMemo } from 'react'
import { ScrollView, StyleSheet, Text, TouchableOpacity, View } from 'react-native'
import { getTokens, type AppThemeTokens } from '../../theme/tokens'
import type { LivePreviewItem, LivePreviewScreenProps } from '../../types'

import { rnRadius, rnSpacing, rnType } from '@ihui/design-tokens'
import { BackChevron } from '../../components/BackChevron'
import { EmptyState, ErrorState, ScreenSkeleton } from '../../components/ScreenStates'

/** 直播预告共享屏 — props 注入式跨端组件(纯 UI,API 调用由 wrapper 注入) */
export type { LivePreviewItem, LivePreviewScreenProps }

export function LivePreviewScreen({
  t,
  item,
  loading,
  error,
  subscribing,
  onSubscribe,
  onBack,
  colorScheme = 'light',
}: LivePreviewScreenProps) {
  const tk = getTokens(colorScheme)
  const styles = useMemo(() => createStyles(tk), [tk])

  if (loading) {
    return (
      <View style={styles.container}>
        <ScreenSkeleton variant="card" count={3} colorScheme={colorScheme} />
      </View>
    )
  }
  if (error || !item) {
    return (
      <View style={styles.container}>
        {error ? (
          <ErrorState
            message={error}
            onRetry={onBack}
            retryLabel={t('common.back')}
            colorScheme={colorScheme}
          />
        ) : (
          <EmptyState
            title={t('livePreview.empty')}
            actionLabel={t('common.back')}
            onAction={onBack}
            colorScheme={colorScheme}
          />
        )}
      </View>
    )
  }

  const btnDisabled = item.subscribed || subscribing

  return (
    <ScrollView style={styles.container}>
      <View style={styles.header}>
        <BackChevron onPress={onBack} label={t('common.back')} colorScheme={colorScheme} />
        <Text style={styles.title}>{t('livePreview.title')}</Text>
      </View>
      <View style={styles.body}>
        <Text style={styles.liveTitle}>{item.title}</Text>
        <Text style={styles.meta}>
          {t('livePreview.lecturer')}: {item.lecturer}
        </Text>
        <Text style={styles.meta}>
          {t('livePreview.startAt')}: {item.startAt}
        </Text>
        <Text style={styles.intro}>{item.intro}</Text>
        <TouchableOpacity
          style={[styles.btn, btnDisabled && styles.btnDisabled]}
          onPress={onSubscribe}
          disabled={btnDisabled}
        >
          <Text style={styles.btnText}>
            {item.subscribed
              ? t('livePreview.subscribed')
              : subscribing
                ? t('livePreview.subscribing')
                : t('livePreview.subscribe')}
          </Text>
        </TouchableOpacity>
      </View>
    </ScrollView>
  )
}

function createStyles(tk: AppThemeTokens) {
  return StyleSheet.create({
    container: { flex: 1, backgroundColor: tk.surface.bg },
    header: {
      flexDirection: 'row',
      alignItems: 'center',
      gap: rnSpacing.md,
      paddingHorizontal: 10,
      paddingVertical: rnSpacing.md,
    },
    title: { fontSize: rnType.heading.size, fontWeight: '600', color: tk.text.primary },
    body: { padding: 10 },
    liveTitle: { fontSize: rnType.heading.size, fontWeight: '700', color: tk.text.primary },
    meta: { marginTop: rnSpacing.sm, fontSize: rnType.body.size, color: tk.text.secondary },
    intro: {
      marginTop: rnSpacing.md,
      fontSize: rnType.title.size,
      color: tk.text.medium,
      lineHeight: 22,
    },
    btn: {
      marginTop: rnSpacing.xl,
      backgroundColor: tk.brand.cta,
      paddingVertical: 15,
      borderRadius: rnRadius.sm,
      alignItems: 'center',
    },
    btnDisabled: { opacity: 0.6 },
    btnText: { color: tk.surface.light, fontSize: rnType.title.size, fontWeight: '600' },
  })
}
