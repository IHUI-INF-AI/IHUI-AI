import { rnSpacing, rnType } from '@ihui/design-tokens'
import { useMemo } from 'react'
import { ScrollView, View, Text, StyleSheet } from 'react-native'
import { getTokens, type AppThemeTokens } from '../../theme/tokens'
import type { AgentReviewDetailItem, AgentReviewDetailScreenProps } from '../../types'
import { BackChevron } from '../../components/BackChevron'
import { ErrorState, ScreenSkeleton } from '../../components/ScreenStates'

/** Agent 评价详情共享屏 — props 注入式跨端组件 */
export type { AgentReviewDetailItem, AgentReviewDetailScreenProps }

export function AgentReviewDetailScreen({
  t,
  item,
  loading,
  error,
  onBack,
  colorScheme = 'light',
}: AgentReviewDetailScreenProps) {
  const tk = getTokens(colorScheme)
  const styles = useMemo(() => createStyles(tk), [tk])

  if (loading) {
    return (
      <View style={styles.container}>
        <View style={styles.header}>
          <BackChevron onPress={onBack} label={t('common.back')} colorScheme={colorScheme} />
          <Text style={styles.title}>{t('agentReviewDetail.title')}</Text>
        </View>
        <ScreenSkeleton variant="card" count={3} colorScheme={colorScheme} />
      </View>
    )
  }

  if (error || !item) {
    return (
      <View style={styles.container}>
        <View style={styles.header}>
          <BackChevron onPress={onBack} label={t('common.back')} colorScheme={colorScheme} />
          <Text style={styles.title}>{t('agentReviewDetail.title')}</Text>
        </View>
        <ErrorState
          message={error || t('agentReviewDetail.empty')}
          onRetry={onBack}
          retryLabel={t('common.back')}
          colorScheme={colorScheme}
        />
      </View>
    )
  }

  const stars = '\u2605'.repeat(Math.max(1, Math.min(5, item.rating || 0)))

  return (
    <ScrollView style={styles.container}>
      <View style={styles.header}>
        <BackChevron onPress={onBack} label={t('common.back')} colorScheme={colorScheme} />
        <Text style={styles.title}>{t('agentReviewDetail.title')}</Text>
      </View>
      <View style={styles.body}>
        <Text style={styles.agentName}>{item.agentName}</Text>
        <View style={styles.metaRow}>
          <Text style={styles.author}>
            {t('agentReviewDetail.author')}: {item.author}
          </Text>
          <Text style={styles.rating}>{stars}</Text>
        </View>
        <Text style={styles.content}>{item.content}</Text>
        <Text style={styles.createdAt}>{item.createdAt}</Text>
      </View>
    </ScrollView>
  )
}

function createStyles(tk: AppThemeTokens) {
  return StyleSheet.create({
    container: { flex: 1, backgroundColor: tk.surface.bg },
    header: {
      flexDirection: 'row',
      alignItems: 'center',
      paddingHorizontal: 10,
      paddingVertical: rnSpacing.md,
      gap: rnSpacing.md,
    },
    title: { fontSize: rnType.heading.size, fontWeight: '700', color: tk.text.primary },
    body: { padding: 14 },
    agentName: { fontSize: rnType.heading.size, fontWeight: '700', color: tk.text.primary },
    metaRow: {
      flexDirection: 'row',
      justifyContent: 'space-between',
      alignItems: 'center',
      marginTop: rnSpacing.sm,
    },
    author: { fontSize: rnType.body.size, color: tk.text.secondary },
    rating: { fontSize: rnType.body.size, color: tk.warning.amber },
    content: {
      marginTop: rnSpacing.md,
      fontSize: rnType.title.size,
      lineHeight: 22,
      color: tk.text.primary,
    },
    createdAt: { marginTop: rnSpacing.md, fontSize: rnType.caption.size, color: tk.text.tertiary },
  })
}
