import type { ImageSourcePropType } from 'react-native'
import type { LucideIcon } from 'lucide-react-native'

/**
 * 统一分类项(跨 RN 复用的唯一文案源在调用方,组件内零中文常量)。
 * icon 仅接受 lucide 组件引用或静态图片源,禁止 emoji/手绘品牌图标。
 */
export interface CategoryItem {
  /** 唯一标识(必填) */
  id: string
  /** 显示文案(必填,调用方传入 i18n 取词结果) */
  label: string
  /** 前置图标(选填,lucide 组件引用) */
  icon?: LucideIcon
  /**
   * 图标/图片边长(选填,默认 16)。
   * 需要这一档的原因是有实证的:ChatScreen 的模型类型条用 24px 图标 + 宽 chip,
   * 而组件把尺寸钉死在 16 时,这类站点就无法收口(只能留在手搓实现里)。
   */
  iconSize?: number
  /** 前置图片(选填,与 icon 二选一,icon 优先) */
  image?: ImageSourcePropType
  /** 计数徽章(选填,按确定性居中模板渲染) */
  count?: number
  /** 无障碍标签(选填,默认复用 label,不拼后缀) */
  a11yLabel?: string
}

export type ColorSchemeName = 'light' | 'dark'
