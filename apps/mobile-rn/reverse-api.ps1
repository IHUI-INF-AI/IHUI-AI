# Re-establish the USB reverse tunnel from RN device to local API backend.
# Purpose: after phone replug or app cold start, adb reverse may drop, causing
#   login requests to fail at the network layer ("operation failed, retry later").
# Pre-req: phone connected via USB with USB debugging enabled; API listens on 127.0.0.1:8802.
# Usage (from apps/mobile-rn):  ./reverse-api.ps1
# Remove tunnel: ./reverse-api.ps1 -Remove

param(
  [switch]$Remove
)

$ErrorActionPreference = 'Stop'
$Port = 8802

if ($Remove) {
  adb reverse --remove "tcp:$Port" 2>$null
  Write-Host "Removed reverse tunnel tcp:$Port"
  exit
}

# Confirm an authorized device is connected
$devices = adb devices | Select-String 'device$'
if (-not $devices) {
  Write-Host 'No authorized USB device found. Check USB connection and USB debugging.' -ForegroundColor Red
  exit 1
}

adb reverse "tcp:$Port" "tcp:$Port"
Write-Host "Reverse tunnel established: device localhost:$Port -> host $Port" -ForegroundColor Green

# Verify tunnel by hitting the API health endpoint from the device side
$health = adb shell "curl -s -m 6 http://127.0.0.1:$Port/api/health -w ' [HTTP %{http_code}]'"
Write-Host "Tunnel check: $health"
