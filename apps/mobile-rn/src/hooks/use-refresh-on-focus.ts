// 平台特有:依赖 @react-navigation/native 的焦点事件

import { useCallback, useRef } from 'react'
import { useFocusEffect } from '@react-navigation/native'

/**
 * 回屏即重取(2026-10-28 立)。
 *
 * RN 屏此前只有**挂载期** `useEffect`,而小程序页普遍在 `useDidShow` 里"每次回到页面都刷新" ——
 * 这是同一件事在两个平台的两种写法,也是「86 枚手写页里 41 枚卡在 useDidShow」的结构成因。
 * 本 hook 把"回到该屏时跑一次"固化成一处,**首次挂载跳过**(首屏由各壳既有的 useEffect 负责,
 * 不跳会同一秒打两次请求)。
 *
 * refresh 必须稳定引用(壳里通常就是已有的 load / loadXxx)。
 */
export function useRefreshOnFocus(refresh: () => void): void {
  const skippedFirst = useRef(false)
  useFocusEffect(
    useCallback(() => {
      if (!skippedFirst.current) {
        skippedFirst.current = true
        return
      }
      refresh()
    }, [refresh]),
  )
}
