// 回屏 / 回前台即重取 —— 共享层唯一实现 `useScreenReappear` 的 RN 薄壳
// (平台原语注入见 ./screen-reappear-adapter.ts)。

import { useScreenReappear } from '@ihui/rn-app'

import { rnScreenReappearAdapter } from './screen-reappear-adapter'

/**
 * 回屏 / 回前台即重取(2026-10-28 立,2026-10-30 收口到共享层)。
 *
 * 语义(首次挂载跳过、可见性守卫、回前台只认可见屏、卸载退订)全部在
 * `packages/app/src/hooks/use-screen-reappear.ts`;本文件只保留既有导出名,
 * 20 枚 RN 屏的 `import` 一行未动。新增屏请直接用 `useScreenReappear` + 端侧 adapter。
 *
 * refresh 必须稳定引用(壳里通常就是已有的 load / loadXxx)。
 */
export function useRefreshOnFocus(refresh: () => void): void {
  useScreenReappear(rnScreenReappearAdapter, refresh)
}
