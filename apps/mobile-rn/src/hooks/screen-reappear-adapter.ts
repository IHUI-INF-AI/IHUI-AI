// 平台特有:依赖 react-native 的 AppState 与 @react-navigation/native 的焦点事件

import { useCallback } from 'react'
import { AppState } from 'react-native'
import { useFocusEffect } from '@react-navigation/native'
import type { ScreenReappearAdapter } from '@ihui/rn-app'

/**
 * RN 侧原语注入:导航焦点(回屏)+ AppState(回前台)。
 *
 * 共享语义(首次挂载跳过、可见性守卫、卸载退订)全在 `@ihui/rn-app` 的 `useScreenReappear`,
 * 本文件只做两件纯转换:
 *  - 导航焦点 → `focused` 布尔(挂载即派发 true,失焦/卸载派发 false);
 *  - AppState `'active'` → 一次 `onActive`(后台/inactive 不派发)。
 */
export const rnScreenReappearAdapter: ScreenReappearAdapter = {
  useScreenFocusEffect(onFocusChange) {
    useFocusEffect(
      useCallback(() => {
        onFocusChange(true)
        return () => onFocusChange(false)
      }, [onFocusChange]),
    )
  },
  subscribeAppActive(onActive) {
    const subscription = AppState.addEventListener('change', (state) => {
      if (state === 'active') onActive()
    })
    return () => subscription.remove()
  },
}
