import { useEffect, useRef } from 'react'

/**
 * WebView 加载看门狗(2026-11-23 立)。
 *
 * 真机断网实测:`onError` 在"连接被黑洞、DNS 不返回"时并不触发,页面会永远停在
 * 「加载中…」;失败态与重试按钮因此永远到不了。这里给"进入加载态"起一个硬超时,
 * 到点主动收掉 loading、亮失败态,并让调用方 stopLoading,把控制权交回用户。
 *
 * 单一实现:WebViewScreen(管理后台/门户)与 ChatToolsScreen(Web 对话)共用,
 * 避免两屏各写一份超时后漂移。定时器在 loading 转 false 时立刻清掉,成功路径零副作用。
 */
export const WEBVIEW_LOAD_TIMEOUT_MS = 20_000

export function useWebviewLoadWatchdog(loading: boolean, onTimeout: () => void): void {
  // 用 ref 持有最新回调:调用方每次 render 传新闭包不会重启动定时器
  const callbackRef = useRef(onTimeout)
  callbackRef.current = onTimeout

  useEffect(() => {
    if (!loading) return
    const timer = setTimeout(() => callbackRef.current(), WEBVIEW_LOAD_TIMEOUT_MS)
    return () => clearTimeout(timer)
  }, [loading])
}
