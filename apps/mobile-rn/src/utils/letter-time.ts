/**
 * 私信时间格式化 —— 逐字复刻 web `apps/web/app/(main)/letters/helpers.ts`
 * (zh-CN 固定、MM/DD HH:mm;web 两端共用件,列表屏与会话屏共用本件,零复算)。
 */
const letterTimeFormatter = new Intl.DateTimeFormat('zh-CN', {
  month: '2-digit',
  day: '2-digit',
  hour: '2-digit',
  minute: '2-digit',
})

/** 非法值返回空字符串(与 web formatLetterTime 同口径) */
export function formatLetterTime(value: string | null | undefined): string {
  if (!value) return ''
  const d = new Date(value)
  if (Number.isNaN(d.getTime())) return ''
  return letterTimeFormatter.format(d)
}
