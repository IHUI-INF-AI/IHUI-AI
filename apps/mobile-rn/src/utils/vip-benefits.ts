/**
 * VIP 权益键族的纯投影(不 import React/RN ⇒ 可在 node 面直接构造用例证明形状)
 */
import type { VipBenefitItem } from '@ihui/rn-app'

/** GET /api/vip/benefits 的行:后端把 vip_levels 整列直出(misc-routes.ts 那条在册路由) */
export interface VipLevelRow {
  id: string
  levelName: string
  benefits?: unknown
}

/**
 * `benefits` 存的是**机器键**数组(生产现读:["unlimitedChat","exclusiveModel",
 * "prioritySupport","referral"]),译名表在 `vip.benefitList.*`,五语言齐备。
 * 只有登记过译名的键才走 t() —— 没登记的键原样显示,和 web 权益页同口径,
 * 不在端内拼中文(§19)。
 */
const TRANSLATED_BENEFITS = [
  'unlimitedChat',
  'exclusiveModel',
  'prioritySupport',
  'referral',
] as const

export function toVipBenefitItems(
  rows: VipLevelRow[],
  t: (key: string) => string,
): VipBenefitItem[] {
  return rows.flatMap((lv) => {
    const keys = Array.isArray(lv.benefits)
      ? lv.benefits.filter((b): b is string => typeof b === 'string')
      : []
    return keys.map((k) => ({
      id: `${lv.id}:${k}`,
      name: (TRANSLATED_BENEFITS as readonly string[]).includes(k) ? t(`vip.benefitList.${k}`) : k,
      // 库里权益条目没有第二行说明文字 ⇒ 留空,由共享屏按空不渲染,而不是端内编一句
      desc: '',
      level: lv.levelName,
    }))
  })
}
