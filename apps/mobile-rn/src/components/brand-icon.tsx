/**
 * BrandIcon — 厂商品牌图标(mobile-rn 端,平台分文件)
 *
 * 本文件 = **类型锚点 + native 兜底实现**(Metro 无 .native.tsx 时回落至此):
 *   @lobehub/icons 的 es/<Name> 组件是 react-dom SVG 实现,native 端无法渲染,
 *   故 native 渲染厂商首字母文本兜底(tokens.text.secondary,与 ModelList iconEmoji 同 token)。
 *
 * - brand-icon.web.tsx = web 完整实现:与 apps/web/src/components/ai/brand-icon.tsx
 *   逐一镜像的 ~95 个 @lobehub/icons/es/<Name> 深路径真实矢量(RNW 渲染 DOM SVG),
 *   含 satisfies Record<VendorCode, ...> 编译期锁键,未映射则落回厂商首字母。
 * - 调用方统一 `import BrandIcon from './brand-icon'`,由 Metro 按平台自动选文件。
 */
import { Text } from 'react-native'

import { tokens } from '../theme/active-tokens'

export interface BrandIconProps {
  /** 厂商代码(如 'openai'、'deepseek';与 web vendor-infer.ts VENDOR_CODES 同源) */
  vendor?: string | null
  /** 像素尺寸,默认 16 */
  size?: number
  /** 图标颜色(单色 Mono 矢量走 currentColor;native 字母兜底同色) */
  color?: string
}

/** native 兜底:厂商首字母文本(与 ModelList iconEmoji 同 token 同语义) */
export function BrandIcon({ vendor, size = 16, color }: BrandIconProps): React.ReactElement | null {
  if (!vendor) return null
  const letter = vendor.trim().charAt(0).toUpperCase()
  if (!letter) return null
  return (
    <Text
      style={{
        fontSize: Math.max(10, Math.round(size * 0.8)),
        lineHeight: size,
        color: color ?? tokens.text.secondary,
        fontWeight: '600',
        textAlign: 'center',
      }}
    >
      {letter}
    </Text>
  )
}
