import { Text, View } from 'react-native'

import { tokens } from '../theme/active-tokens'

/**
 * BrandIcon(原生实现)
 *
 * 与 `brand-icon.web.tsx` 成对:RNW 那份渲染 @lobehub/icons 真实厂商矢量(react-dom SVG,
 * 原生端引入即崩),本份是原生回落 —— 厂商首字母。Metro 按平台后缀选文件,调用方一律
 * `import { BrandIcon } from './brand-icon'`,两端对调用方暴露相同 `{ vendor, size, color }` 签名。
 */
export interface BrandIconProps {
  /** 厂商代码(如 'openai'、'deepseek') */
  vendor?: string | null
  /** 像素尺寸,默认 16 */
  size?: number
  /** 图标颜色 */
  color?: string
}

export function BrandIcon({ vendor, size = 16, color }: BrandIconProps): React.ReactElement {
  const letter = (vendor ?? '').trim().charAt(0).toUpperCase()
  return (
    <View style={{ width: size, height: size, alignItems: 'center', justifyContent: 'center' }}>
      <Text
        style={{
          fontSize: Math.max(10, Math.round(size * 0.8)),
          color: color ?? tokens.text.secondary,
          fontWeight: '600',
        }}
      >
        {letter}
      </Text>
    </View>
  )
}
