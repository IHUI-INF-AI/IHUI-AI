import type { ReactNode } from 'react'
import { StyleSheet, View } from 'react-native'
import { tokens } from '../theme/active-tokens'

/**
 * 顶栏底色承载件 —— 全端唯一实现。
 *
 * 为什么需要它:`src/components/NavBar.tsx` 依 2026-09-26 用户裁决**不自绘底色、不画底边线**
 * (`tests/navbar-no-chrome.test.tsx` 钉着),所以导航行的底色必须由**所在屏**给;
 * 而状态栏 inset 带由 `App.tsx` 那枚根 View 按路由给。两处必须是同一档,否则同一屏露出两截色
 * —— 2026-10-10 用户实拍「顶部这个区域为什么是灰色的,怎么还有个灰色带呢」就是这个形态。
 *
 * 取值 `tokens.surface.chrome`:亮 #FFFFFF / 暗 #262626,逐位等于小程序端原生导航栏
 * `apps/miniapp-taro/src/theme.json` 的 `navBgColor`(暗值见 `scripts/sync-miniapp-chrome.mjs`
 * 的 `CHROME_DECLARED_DIVERGENCE`,那是登记过的决策不是漂移)。刻意不用 `surface.card`
 * (暗 #1A1A1A,真机量得与小程序深色 chrome 差 12 级),也不用 `surface.light`
 * (门 93 里挂着 `rnDarkTokens|surface.light` 两侧合同互斥待裁)。
 */
export function NavChrome({ children }: { children: ReactNode }) {
  return <View style={styles.wrap}>{children}</View>
}

const styles = StyleSheet.create({
  wrap: { backgroundColor: tokens.surface.chrome },
})
