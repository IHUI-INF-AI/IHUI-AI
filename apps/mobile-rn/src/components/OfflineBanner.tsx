'use client'

import { StyleSheet, Text, View } from 'react-native'
import { WifiOff } from 'lucide-react-native'
import { rnTokens } from '@ihui/design-tokens'

/**
 * 离线 Banner 组件(2026-07-22 P0 Round 5 鲁棒性加固)。
 *
 * 当网络探测失败时显示顶部红色横条,提示用户网络已断开。
 * 使用 fetch 探测而非 @react-native-community/netinfo,避免引入新原生依赖。
 */
export interface OfflineBannerProps {
  isOnline: boolean
}

export function OfflineBanner({ isOnline }: OfflineBannerProps) {
  if (isOnline) return null
  return (
    <View style={styles.wrapper} accessibilityRole="alert">
      <View style={styles.pill}>
        <WifiOff size={16} color={rnTokens.error.text} />
        <Text style={styles.text}>网络已断开,部分功能不可用</Text>
      </View>
    </View>
  )
}

const styles = StyleSheet.create({
  wrapper: { alignItems: 'center', paddingVertical: 8 },
  pill: {
    flexDirection: 'row',
    alignItems: 'center',
    gap: 8,
    backgroundColor: rnTokens.error.bg,
    borderColor: 'rgba(255, 51, 51, 0.35)',
    borderWidth: 1,
    borderRadius: 8,
    paddingHorizontal: 16,
    paddingVertical: 8,
  },
  text: { color: rnTokens.error.text, fontSize: 14, fontWeight: '500' },
})
