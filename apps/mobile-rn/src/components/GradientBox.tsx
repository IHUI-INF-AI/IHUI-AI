/**
 * GradientBox — CSS 线性渐变背景容器(mobile-rn / react-native-web)
 *
 * 用途:对齐 Uniapp 原版中 RN StyleSheet 不支持的 `background: linear-gradient(...)`,
 * 例如 InputArea.vue 的 .icon-button(135deg 紫黄渐变 + 6rpx 白边)、
 * .gradient-border(input-area-back 239deg 渐变外框)等。
 *
 * web 端通过注入 <div style={{ backgroundImage }}>(react-native-web View 透传
 * 未知样式键到 DOM style)实现真渐变;原生端降级为渐变首色纯色底。
 */
import type { ReactNode } from 'react'
import { View, type ViewStyle } from 'react-native'

export interface GradientBoxProps {
  /** 完整 CSS linear-gradient() 字符串,如 'linear-gradient(135deg, ...)' */
  css: string
  /** 渐变首色(原生端降级纯色底用) */
  fallbackColor: string
  style?: ViewStyle | ViewStyle[]
  children?: ReactNode
}

export function GradientBox({ css, fallbackColor, style, children }: GradientBoxProps) {
  return (
    <View
      style={[
        { backgroundColor: fallbackColor },
        // backgroundImage 仅 web 生效;原生端被忽略,走 fallbackColor
        { backgroundImage: css } as unknown as ViewStyle,
        style,
      ]}
    >
      {children}
    </View>
  )
}

export default GradientBox
