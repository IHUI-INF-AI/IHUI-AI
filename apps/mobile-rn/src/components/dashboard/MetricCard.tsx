import { Text } from 'react-native'
import { Card, CardContent } from '@ihui/ui-native'

export interface MetricCardProps {
  label: string
  value: string
  hint?: string
  className?: string
}

/** 紧凑指标卡:标签 + 大号数值 + 可选副说明。用于看板各分区的只读展示。 */
export function MetricCard({ label, value, hint, className }: MetricCardProps) {
  return (
    <Card className={`mb-3 w-[48%] ${className ?? ''}`}>
      <CardContent>
        <Text className="text-xs text-muted-foreground">{label}</Text>
        <Text className="mt-1 text-xl font-semibold text-foreground">{value}</Text>
        {hint ? <Text className="mt-1 text-xs text-muted-foreground">{hint}</Text> : null}
      </CardContent>
    </Card>
  )
}
