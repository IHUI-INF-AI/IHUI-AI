/**
 * MoreTitles 更多标题 (mobile-rn 端)
 *
 * 对齐历史项目 MoreTitles/index.vue(列表区段头):
 * - 左侧:标题文字(粗体),单行截断
 * - 右侧(仅当 onMore 提供时渲染):「更多」入口
 * - 单行布局,space-between,无分割线
 * - 浅色优雅风,系统字体,无霓虹无渐变
 *
 * 几何/字号不再在本件自持:统一委托 @ihui/rn-app 的 SectionHeader(唯一 RN 渲染腿),
 * 后者从 @ihui/shared/ui/section-header-spec 取值;本件只保留原区块的上下留白。
 *
 * 任务规格:
 *   interface MoreTitlesProps { title: string; moreText?: string; onMore?: () => void }
 */
import { StyleSheet, type ViewStyle } from 'react-native'
import { SectionHeader } from '@ihui/rn-app'
import { currentRnTheme } from '../theme/active-tokens'
import { useI18n } from '../i18n'

export interface MoreTitlesProps {
  title: string
  moreText?: string
  onMore?: () => void
}

const CONTAINER_PADDING_V = 10

export function MoreTitles({ title, moreText, onMore }: MoreTitlesProps) {
  const { t } = useI18n()
  return (
    <SectionHeader
      title={title}
      moreText={moreText ?? t('common.more')}
      onMore={onMore}
      colorScheme={currentRnTheme()}
      style={styles.container}
    />
  )
}

const styles = StyleSheet.create({
  container: {
    paddingVertical: CONTAINER_PADDING_V,
  } as ViewStyle,
})

export default MoreTitles
