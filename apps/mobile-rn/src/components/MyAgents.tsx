/**
 * MyAgents 我的AI APP (mobile-rn 端适配层)
 *
 * UI 已单源化到 features/agent-screen/AgentMyApps;
 * 本文件只注入 RN 端文案 / 主题 / 空态,并保留原有 props API 供 AgentScreen 使用。
 */
import { AgentMyApps } from '@ihui/rn-app/features/agent-screen/AgentMyApps'
import { currentRnTheme } from '../theme/active-tokens'
import { useI18n } from '../i18n'

export interface MyAgentItem {
  /** 智能体 ID(对齐原项目 agentId;兼容短字段 id) */
  agentId?: string
  id?: string
  /** 智能体名称(对齐原项目 agentName;缺失回退 name) */
  agentName?: string
  name?: string
  /** 头像(对齐原项目 agentAvatar;缺失回退 avatar) */
  agentAvatar?: string
  avatar?: string
  /** 类型(原项目 type 3|5 为付费模型,点击由调用方拦截) */
  type?: string | number
  /** 来源(原项目 source === 'n8n' 跳 n8n 助手页) */
  source?: string
}

export interface MyAgentsProps {
  items: MyAgentItem[]
  onItemClick: (item: MyAgentItem) => void
  /** "我的AI员工"入口点击(对齐原项目 goToTeam → /pages/tools/ai_group/index) */
  onTeamPress?: () => void
  /** 默认头像(对齐原项目 defaultAvatar) */
  defaultAvatar?: string
  /** 空态文案 */
  emptyText?: string
}

export default function MyAgents({
  items,
  onItemClick,
  onTeamPress,
  defaultAvatar,
  emptyText: emptyTextProp,
}: MyAgentsProps) {
  const { t } = useI18n()
  return (
    <AgentMyApps
      items={items}
      title={t('myAgents.title')}
      moreText={t('myAgents.staff')}
      onItemClick={(item) => onItemClick(item as MyAgentItem)}
      onMore={onTeamPress}
      showMore={Boolean(onTeamPress)}
      colorScheme={currentRnTheme()}
      defaultAvatar={defaultAvatar ?? null}
      emptyText={emptyTextProp ?? t('home.noAgentsHint')}
    />
  )
}
