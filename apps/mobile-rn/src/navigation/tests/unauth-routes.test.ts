// ChangePhone / ChangePwd;这些路由必须注册在未登录栈里,否则点击即崩。
// 改前必红:未登录分支只有 Login / Register / ChatTools,断言四路由缺失。
import { describe, expect, it } from 'vitest'
import { readFileSync } from 'node:fs'
import { resolve } from 'node:path'

const SOURCE = resolve(__dirname, '../RootNavigator.tsx')

/** 取未登录分支(以 Login 屏为锚点,到该 Fragment 的 </> 为止)注册的路由名。 */
export function unauthenticatedRouteNames(src: string): string[] {
  const start = src.lastIndexOf('<RootStack.Screen name="Login"')
  if (start < 0) return []
  const end = src.indexOf('</>', start)
  if (end < 0) return []
  const block = src.slice(start, end)
  return [...block.matchAll(/<RootStack\.Screen\s+name="([^"]+)"/g)].map((m) => m[1] as string)
}

describe('XUI-004 未登录分支路由注册', () => {
  it('登录/注册可跳转的四条路由必须在未登录栈注册', () => {
    const names = unauthenticatedRouteNames(readFileSync(SOURCE, 'utf8'))
    expect(names).toContain('Login')
    expect(names).toContain('Register')
    expect(names).toEqual(
      expect.arrayContaining(['Privacy', 'Agreement', 'ChangePhone', 'ChangePwd']),
    )
  })
})
