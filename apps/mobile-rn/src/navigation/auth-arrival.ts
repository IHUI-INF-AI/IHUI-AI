/**
 * 「令牌到了,人还站在登录页」这一格的判据(纯函数,零 RN 依赖)。
 *
 * 立因(真机实测,#31):SSO 深链换令牌**成功**、令牌**已落库**(冷启动即已登录),
 * 但界面在 +3s / +8s 两次采样里都还停在登录页。根因不是没换到,而是 2026-09-27 为
 * "会话失效出口"把 `Login` 同时注册进了**已登录分支**(见 RootNavigator 的 `token ? (A) : (B)`),
 * 于是 React Navigation 换树时按**路由名**对齐当前路由 —— 树翻了,当前路由名仍是 `Login`。
 * 而 `LoginScreen` 里那句"无 returnUrl 时 token 生效后 RootNavigator 自动渲染,无需手动导航"
 * 的注释,正是被那次改动悄悄作废的前提。
 *
 * 只认**"无→有"这一次**:带着令牌被送去登录页(401 出口的既定路径)不得被这条判据赶走,
 * 否则就把守门 148 / 锁 A 刚钉死的"会话失效落点"反向破坏掉 —— 那条路要求人停在 Login。
 */
export type AuthArrivalAction = 'reset-to-main' | 'none'

export function authArrivalAction(args: {
  /** 上一次采样时有没有令牌(用于区分"刚到"与"本来就在") */
  hadToken: boolean
  hasToken: boolean
  /** 当前聚焦的路由名;导航器未就绪时为 undefined */
  routeName: string | undefined | null
}): AuthArrivalAction {
  if (args.hadToken || !args.hasToken) return 'none'
  if (args.routeName !== 'Login' && args.routeName !== 'Register') return 'none'
  return 'reset-to-main'
}
