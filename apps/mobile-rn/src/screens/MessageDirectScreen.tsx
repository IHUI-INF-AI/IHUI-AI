import { useCallback, useEffect, useState } from 'react'
import { useTheme } from '../context/ThemeContext'
import { useNavigation } from '@react-navigation/native'
import type { NativeStackNavigationProp } from '@react-navigation/native-stack'
import { fetchApi } from '@ihui/api-client'
import {
  MessageDirectScreen as SharedMessageDirectScreen,
  type MessageDirectItem,
} from '@ihui/rn-app'
import { useI18n } from '../i18n'
import type { RootStackParamList } from '../navigation/RootNavigator'

type Nav = NativeStackNavigationProp<RootStackParamList>

export function MessageDirectScreen() {
  const { resolvedTheme } = useTheme()
  const { t } = useI18n()
  const navigation = useNavigation<Nav>()
  const [items, setItems] = useState<MessageDirectItem[]>([])
  const [loading, setLoading] = useState(true)
  const [refreshing, setRefreshing] = useState(false)
  const [error, setError] = useState('')

  const load = useCallback(async () => {
    setError('')
    try {
      // 后端 /messages/private/conversation/list 已投影 peer_nickname/last_message/
      // last_message_time/unread_count(message.ts),不再拿 peer_id 当昵称占位;
      // 投影字段缺失时回退 peer_id,兼容旧响应。
      const res = await fetchApi<{
        list: Array<{
          peer_id: string
          peer_nickname?: string | null
          last_message?: string | null
          last_message_time?: string | null
          unread_count?: number | null
        }>
      }>('/messages/private/conversation/list')
      if (!res.success) throw new Error()
      const list = res.data?.list ?? []
      setItems(
        list.map((row) => ({
          memberId: row.peer_id,
          nickname: row.peer_nickname || row.peer_id,
          lastMessage: row.last_message ?? '',
          lastMessageTime: row.last_message_time
            ? new Date(row.last_message_time).toLocaleString()
            : '',
          unreadCount: row.unread_count ?? 0,
        })),
      )
    } catch {
      setError(t('messageDirect.loadFailed'))
    } finally {
      setLoading(false)
      setRefreshing(false)
    }
  }, [t])

  useEffect(() => {
    void load()
  }, [load])

  return (
    <SharedMessageDirectScreen
      t={t}
      items={items}
      loading={loading}
      refreshing={refreshing}
      error={error}
      onRefresh={() => {
        setRefreshing(true)
        void load()
      }}
      onPressItem={(item) =>
        navigation.navigate('MessageChat', { peerId: item.memberId, name: item.nickname })
      }
      onBack={() => navigation.goBack()}
      colorScheme={resolvedTheme}
    />
  )
}
