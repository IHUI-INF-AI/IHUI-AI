import { useState } from 'react'
import { useNavigation, useRoute, type RouteProp } from '@react-navigation/native'
import type { NativeStackNavigationProp } from '@react-navigation/native-stack'
import { fetchApi } from '@ihui/api-client'
import { CircleCreateScreen as SharedCircleCreateScreen } from '@ihui/rn-app'
import { useI18n } from '../i18n'
import type { RootStackParamList } from '../navigation/RootNavigator'

type Route = RouteProp<RootStackParamList, 'CircleCreate'>
type NavigationProp = NativeStackNavigationProp<RootStackParamList>

export function CircleCreateScreen() {
  const { t } = useI18n()
  const route = useRoute<Route>()
  const navigation = useNavigation<NavigationProp>()
  // P1(2026-09-04):话题详情发布入口透传 topicId/topicName(对齐小程序 circle/create?topicId=&topicName=)
  const { topicId, topicName } = route.params ?? {}
  const [name, setName] = useState(topicName ?? '')
  const [description, setDescription] = useState('')
  const [saving, setSaving] = useState(false)
  const [error, setError] = useState('')

  const onSubmit = async () => {
    if (!name.trim()) {
      setError(t('circleCreate.nameRequired'))
      return
    }
    setSaving(true)
    setError('')
    const res = await fetchApi<{ id: string }>('/api/circles', {
      method: 'POST',
      body: JSON.stringify({
        name: name.trim(),
        description: description.trim(),
        category: 'general',
        isPublic: true,
        ...(topicId ? { topicId } : {}),
      }),
    })
    setSaving(false)
    if (res.success && res.data) {
      navigation.replace('CircleDetail', { id: res.data.id })
    } else if (!res.success) {
      setError(res.error || t('circleCreate.saveFailed'))
    }
  }

  return (
    <SharedCircleCreateScreen
      t={t}
      name={name}
      description={description}
      saving={saving}
      error={error}
      onNameChange={setName}
      onDescriptionChange={setDescription}
      onSubmit={onSubmit}
      onBack={() => navigation.goBack()}
    />
  )
}
