import { useCallback, useEffect, useState } from 'react'
import { useNavigation } from '@react-navigation/native'
import type { NativeStackNavigationProp } from '@react-navigation/native-stack'
import { createWorkflow, listWorkflows } from '@ihui/api-client'
import type { WorkflowRow } from '@ihui/api-client'
import { WorkflowListScreen as SharedWorkflowListScreen } from '@ihui/rn-app'
import type { WorkflowCreateInput } from '@ihui/rn-app'
import { useI18n } from '../i18n'
import { useTheme } from '../context/ThemeContext'
import type { RootStackParamList } from '../navigation/RootNavigator'

/**
 * 本票三条 Wave1 路由由 manifest 交集成方统一注册(禁改 RootNavigator)。
 * 本地交叉类型让薄壳在注册前也能过 typecheck;注册后与 RootStackParamList 并集等值。
 */
type ShellParams = RootStackParamList & {
  WorkflowList: undefined
  WorkflowDetail: { id: string }
  WorkflowInstanceDetail: { id: string }
}
type NavigationProp = NativeStackNavigationProp<ShellParams>

/**
 * RN 端「工作流列表」薄壳 —— 渲染全部委托共享屏
 * `packages/app/src/features/workflows/WorkflowListScreen.tsx`,本文件只管平台侧:
 * 取词、主题、导航落点,以及 GET/POST /workflows 取数(经 @ihui/api-client)。
 */
export function WorkflowListScreen() {
  const navigation = useNavigation<NavigationProp>()
  const { t } = useI18n()
  const { resolvedTheme } = useTheme()
  const [loading, setLoading] = useState(true)
  const [error, setError] = useState<string | null>(null)
  const [items, setItems] = useState<WorkflowRow[]>([])

  const load = useCallback(async () => {
    setLoading(true)
    setError(null)
    try {
      const res = await listWorkflows()
      if (res.success) {
        setItems(res.data.list ?? [])
      } else {
        setError(res.error || t('workflowsPage.fetchFailed'))
        setItems([])
      }
    } catch {
      setError(t('workflowsPage.fetchFailed'))
      setItems([])
    } finally {
      setLoading(false)
    }
  }, [t])

  useEffect(() => {
    void load()
  }, [load])

  const handleCreate = useCallback(async (input: WorkflowCreateInput): Promise<string | null> => {
    try {
      const res = await createWorkflow({
        name: input.name,
        description: input.description,
        triggerType: input.triggerType,
        steps: input.steps,
      })
      if (res.success) return res.data.workflow?.id ?? null
      return null
    } catch {
      return null
    }
  }, [])

  return (
    <SharedWorkflowListScreen
      t={t}
      colorScheme={resolvedTheme}
      onBack={() => navigation.goBack()}
      onOpen={(id) => navigation.navigate('WorkflowDetail', { id })}
      loading={loading}
      error={error}
      items={items}
      onRefresh={() => void load()}
      onCreate={handleCreate}
    />
  )
}

export default WorkflowListScreen
