/**
 * 提示词库页(mobile-rn 端)—— 薄壳,复用通用控制台列表屏 ConsoleTableScreen。
 * 端点:GET /api/prompts ⇒ PromptSummary[](非分页数组;与 web models/prompts 同源)。
 */
import { useCallback, useEffect, useState } from 'react'
import { useNavigation, type NavigationProp } from '@react-navigation/native'
import { fetchApi } from '@ihui/api-client'
import { ConsoleTableScreen, type ConsoleColumn, type ConsoleRowView } from '@ihui/rn-app'
import { useI18n } from '../i18n'
import { useTheme } from '../context/ThemeContext'
import type { RootStackParamList } from '../navigation/RootNavigator'

interface PromptSummary {
  name: string
  description: string | null
  latest_version: number
  updated_at: string
  created_at: string
}

function ModelsPromptsScreen() {
  const { t, locale } = useI18n()
  const { resolvedTheme } = useTheme()
  const navigation = useNavigation<NavigationProp<RootStackParamList>>()
  const [rows, setRows] = useState<ConsoleRowView[]>([])
  const [loading, setLoading] = useState(true)
  const [error, setError] = useState<string | null>(null)

  const fmtDate = useCallback(
    (iso: string | null) => {
      if (!iso) return ''
      const d = new Date(iso)
      if (Number.isNaN(d.getTime())) return ''
      return new Intl.DateTimeFormat(locale, {
        year: 'numeric',
        month: '2-digit',
        day: '2-digit',
      }).format(d)
    },
    [locale],
  )

  const load = useCallback(async () => {
    setLoading(true)
    setError(null)
    try {
      const res = await fetchApi<PromptSummary[]>('/api/prompts')
      if (!res.success) throw new Error(res.error || 'load failed')
      setRows(
        (res.data ?? []).map((p) => ({
          id: p.name,
          cells: {
            name: p.name,
            desc: p.description ?? '—',
            version: `v${String(p.latest_version)}`,
            updated: fmtDate(p.updated_at),
          },
        })),
      )
    } catch (e) {
      setError(e instanceof Error ? e.message : 'load failed')
    } finally {
      setLoading(false)
    }
  }, [fmtDate])

  useEffect(() => {
    void load()
  }, [load])

  const columns: ConsoleColumn[] = [
    { key: 'name', title: t('modelsPrompts.name'), render: 'mono', flex: 2 },
    { key: 'desc', title: t('modelsPrompts.desc'), flex: 2 },
    { key: 'version', title: t('modelsPrompts.version'), render: 'badge' },
    { key: 'updated', title: t('modelsPrompts.updated') },
  ]

  return (
    <ConsoleTableScreen
      t={t}
      colorScheme={resolvedTheme}
      onBack={() => navigation.goBack()}
      title={t('modelsPrompts.title')}
      columns={columns}
      rows={rows}
      loading={loading}
      error={error}
      onRetry={() => void load()}
      onRefresh={() => void load()}
    />
  )
}

export default ModelsPromptsScreen
