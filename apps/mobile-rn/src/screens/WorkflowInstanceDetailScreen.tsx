import { useCallback, useEffect, useState } from 'react'
import { useNavigation, useRoute } from '@react-navigation/native'
import type { RouteProp } from '@react-navigation/native'
import type { NativeStackNavigationProp } from '@react-navigation/native-stack'
import { getWorkflowInstance, getWorkflowInstanceLogs } from '@ihui/api-client'
import type { WorkflowInstanceRow, WorkflowLogRow, WorkflowTaskRow } from '@ihui/api-client'
import { WorkflowInstanceDetailScreen as SharedInstanceDetailScreen } from '@ihui/rn-app'
import { useI18n } from '../i18n'
import { useTheme } from '../context/ThemeContext'
import type { RootStackParamList } from '../navigation/RootNavigator'

/** 本票三条 Wave1 路由由 manifest 交集成方统一注册(禁改 RootNavigator);本地交叉类型见 WorkflowListScreen 同注释。 */
type ShellParams = RootStackParamList & {
  WorkflowList: undefined
  WorkflowDetail: { id: string }
  WorkflowInstanceDetail: { id: string }
}
type NavigationProp = NativeStackNavigationProp<ShellParams>

/**
 * RN 端「工作流实例详情」薄壳 —— 渲染全部委托共享屏
 * `packages/app/src/features/workflows/WorkflowInstanceDetailScreen.tsx`,本文件只管平台侧:
 * GET /workflows/instances/:id(含 tasks)+ GET /workflows/instances/:id/logs 取数、
 * 取词、主题、导航落点。
 */
export function WorkflowInstanceDetailScreen() {
  const navigation = useNavigation<NavigationProp>()
  const route = useRoute<RouteProp<ShellParams, 'WorkflowInstanceDetail'>>()
  const { t } = useI18n()
  const { resolvedTheme } = useTheme()
  const id = route.params.id

  const [loading, setLoading] = useState(true)
  const [error, setError] = useState<string | null>(null)
  const [instance, setInstance] = useState<WorkflowInstanceRow | null>(null)
  const [tasks, setTasks] = useState<WorkflowTaskRow[]>([])
  const [logs, setLogs] = useState<WorkflowLogRow[]>([])

  const load = useCallback(async () => {
    setLoading(true)
    setError(null)
    try {
      const [instRes, logsRes] = await Promise.all([
        getWorkflowInstance(id),
        getWorkflowInstanceLogs(id),
      ])
      if (instRes.success) {
        setInstance(instRes.data.instance)
        setTasks(instRes.data.tasks ?? [])
      } else {
        setError(instRes.error || t('workflowsPage.instanceNotFound'))
      }
      if (logsRes.success) setLogs(logsRes.data.list ?? [])
    } catch {
      setError(t('workflowsPage.instanceNotFound'))
    } finally {
      setLoading(false)
    }
  }, [id, t])

  useEffect(() => {
    void load()
  }, [load])

  return (
    <SharedInstanceDetailScreen
      t={t}
      colorScheme={resolvedTheme}
      onBack={() => navigation.goBack()}
      loading={loading}
      error={error}
      instance={instance ?? undefined}
      tasks={tasks}
      logs={logs}
      onRefresh={() => void load()}
    />
  )
}

export default WorkflowInstanceDetailScreen
