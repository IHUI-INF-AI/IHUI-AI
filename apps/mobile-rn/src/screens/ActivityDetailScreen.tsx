import { useCallback, useEffect, useState } from 'react'
import { useTheme } from '../context/ThemeContext'
import { useNavigation, useRoute } from '@react-navigation/native'
import type { NativeStackNavigationProp } from '@react-navigation/native-stack'
import { fetchApi } from '@ihui/api-client'
import {
  ActivityDetailScreen as SharedActivityDetailScreen,
  type ActivityDetailItem,
} from '@ihui/rn-app'
import { useI18n } from '../i18n'
import type { RootStackParamList } from '../navigation/RootNavigator'

type NavigationProp = NativeStackNavigationProp<RootStackParamList>

export function ActivityDetailScreen() {
  const { resolvedTheme } = useTheme()
  const { t } = useI18n()
  const navigation = useNavigation<NavigationProp>()
  const route = useRoute<{
    key: string
    name: 'ActivityDetail'
    params: RootStackParamList['ActivityDetail']
  }>()
  const id = route.params?.id ?? ''
  const [item, setItem] = useState<ActivityDetailItem | null>(null)
  const [loading, setLoading] = useState(true)
  const [error, setError] = useState('')

  const load = useCallback(async () => {
    setError('')
    try {
      // 后端 GET /activities/:id 回 success({ activity })(promotions.ts),web 侧读 d.activity。
      const res = await fetchApi<{ activity: ActivityDetailItem }>(`/activities/${id}`)
      if (!res.success) throw new Error('http')
      setItem(res.data?.activity ?? null)
    } catch {
      setError(t('activity.loadFailed'))
    } finally {
      setLoading(false)
    }
  }, [id, t])

  useEffect(() => {
    void load()
  }, [load])

  return (
    <SharedActivityDetailScreen
      t={t}
      item={item}
      loading={loading}
      error={error}
      onBack={() => navigation.goBack()}
      colorScheme={resolvedTheme}
    />
  )
}
