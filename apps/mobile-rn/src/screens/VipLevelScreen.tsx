import { useCallback, useEffect, useState } from 'react'
import { useTheme } from '../context/ThemeContext'
import { useNavigation, useRoute, type RouteProp } from '@react-navigation/native'
import type { NativeStackNavigationProp } from '@react-navigation/native-stack'
import { fetchApi } from '@ihui/api-client'
import { VipLevelScreen as SharedVipLevelScreen, type VipLevelItem } from '@ihui/rn-app'
import { useI18n } from '../i18n'
import type { RootStackParamList } from '../navigation/RootNavigator'

type Nav = NativeStackNavigationProp<RootStackParamList>
type Route = RouteProp<RootStackParamList, 'VipLevel'>

/** GET /api/vip/levels 的行(vip_levels 表投影,benefits 为 jsonb 数组) */
interface VipLevelRow {
  id: string
  levelName: string
  price: number
  durationDays: number
  benefits?: unknown
}

/** benefits 形态归一:后端回数组(string | { name }),共享屏按整段文本渲染;不造内容 */
function toBenefitsText(benefits: unknown): string {
  if (typeof benefits === 'string') return benefits
  if (!Array.isArray(benefits)) return ''
  return benefits
    .map((b) => {
      if (typeof b === 'string') return b
      if (b && typeof b === 'object' && typeof (b as { name?: unknown }).name === 'string')
        return (b as { name: string }).name
      return ''
    })
    .filter(Boolean)
    .join('\n')
}

export function VipLevelScreen() {
  const { resolvedTheme } = useTheme()
  const { t } = useI18n()
  const navigation = useNavigation<Nav>()
  const route = useRoute<Route>()
  const id = route.params.id
  const [item, setItem] = useState<VipLevelItem | null>(null)
  const [loading, setLoading] = useState(true)
  const [error, setError] = useState('')

  const load = useCallback(async () => {
    setError('')
    // 没有 id 就不打注定失败的请求,直接落空态(共享屏 error || !item 时渲染 vipLevel.empty)
    if (!id) {
      setItem(null)
      setLoading(false)
      return
    }
    try {
      // GET /api/vip-level/:id 全仓无注册(vip.ts 只有 /vip/levels 一族) ⇒ 恒 404。
      // 改调公开列表 GET /api/vip/levels(vip.ts:211,web /vip 同源)后在壳里按 id 过滤。
      const res = await fetchApi<{ items: VipLevelRow[] }>('/vip/levels')
      if (!res.success) throw new Error()
      const row = res.data?.items.find((lv) => lv.id === id)
      setItem(
        row
          ? {
              id: row.id,
              levelName: row.levelName,
              price: row.price,
              durationDays: row.durationDays,
              benefits: toBenefitsText(row.benefits),
            }
          : null,
      )
    } catch {
      setError(t('vipLevel.loadFailed'))
    } finally {
      setLoading(false)
    }
  }, [id, t])

  useEffect(() => {
    void load()
  }, [load])

  return (
    <SharedVipLevelScreen
      t={t}
      item={item}
      loading={loading}
      error={error}
      onBack={() => navigation.goBack()}
      colorScheme={resolvedTheme}
    />
  )
}
