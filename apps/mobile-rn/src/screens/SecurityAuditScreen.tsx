import { useCallback, useEffect, useState } from 'react'
import { useNavigation } from '@react-navigation/native'
import type { NativeStackNavigationProp } from '@react-navigation/native-stack'

import { fetchApi } from '@ihui/api-client'
import {
  SecurityAuditScreen as SharedSecurityAuditScreen,
  type SecurityAuditItem,
} from '@ihui/rn-app'
import { apiFailureToText } from '@ihui/shared/utils'

import { useTheme } from '../context/ThemeContext'
import { useI18n } from '../i18n'
import type { RootStackParamList } from '../navigation/RootNavigator'

type NavigationProp = NativeStackNavigationProp<RootStackParamList>

/**
 * 安全审计(mobile-rn 宿主):数据与导航在此,UI 全在共享屏。
 * 端点与形状照 web 现读:`GET /api/security/audit` ⇒ `{list,total,page,pageSize}`,**不是裸数组**。
 */
export function SecurityAuditScreen() {
  const { t } = useI18n()
  const { resolvedTheme } = useTheme()
  const navigation = useNavigation<NavigationProp>()
  const [items, setItems] = useState<SecurityAuditItem[]>([])
  const [loading, setLoading] = useState(true)
  const [refreshing, setRefreshing] = useState(false)
  const [error, setError] = useState('')

  const load = useCallback(async () => {
    setError('')
    const res = await fetchApi<{ list?: SecurityAuditItem[] }>('/api/security/audit')
    if (res.success) setItems(res.data?.list ?? [])
    else setError(apiFailureToText(res, t('securityAudit.loadFailed')))
    setLoading(false)
    setRefreshing(false)
  }, [t])

  useEffect(() => {
    void load()
  }, [load])

  return (
    <SharedSecurityAuditScreen
      t={t}
      items={items}
      loading={loading}
      refreshing={refreshing}
      error={error}
      onRefresh={() => {
        setRefreshing(true)
        void load()
      }}
      onBack={() => navigation.goBack()}
      colorScheme={resolvedTheme}
    />
  )
}
