import { useCallback, useEffect, useState } from 'react'
import { useTheme } from '../context/ThemeContext'
import { useNavigation } from '@react-navigation/native'
import type { NativeStackNavigationProp } from '@react-navigation/native-stack'
import { fetchApi } from '@ihui/api-client'
import { VipBenefitScreen as SharedVipBenefitScreen, type VipBenefitItem } from '@ihui/rn-app'
import { resolveVipBenefitEntries } from '@ihui/rn-app/features/vip-benefit/view-model'
import { useI18n } from '../i18n'
import type { RootStackParamList } from '../navigation/RootNavigator'

type Nav = NativeStackNavigationProp<RootStackParamList>

import { toVipBenefitItems, type VipLevelRow } from '../utils/vip-benefits'

export function VipBenefitScreen() {
  const { resolvedTheme } = useTheme()
  const { t } = useI18n()
  const navigation = useNavigation<Nav>()
  // i18n 缺失键回落(本屏中文文案与小程序同源)
  const tt = useCallback(
    (key: string, fallback: string) => {
      const value = t(key as never) as string
      return value === key ? fallback : value
    },
    [t],
  )
  const [items, setItems] = useState<VipBenefitItem[]>([])
  const [loading, setLoading] = useState(true)
  const [error, setError] = useState('')

  const load = useCallback(async () => {
    setError('')
    try {
      const r = await fetchApi<{ list: VipLevelRow[] }>('/api/vip/benefits')
      if (!r.success) throw new Error()
      setItems(toVipBenefitItems(r.data?.list ?? [], t))
    } catch {
      setError(t('member.benefits.loadFailed'))
    } finally {
      setLoading(false)
    }
  }, [t])

  useEffect(() => {
    void load()
  }, [load])

  return (
    <SharedVipBenefitScreen
      t={t}
      items={items}
      loading={loading}
      error={error}
      onBack={() => navigation.goBack()}
      onRetry={() => {
        void load()
      }}
      colorScheme={resolvedTheme}
      entries={resolveVipBenefitEntries(tt).map((entry) => ({
        ...entry,
        onPress: () => {
          if (entry.id === 'level') navigation.navigate('VipCompare')
          else if (entry.id === 'trader') navigation.navigate('Vip', { type: 'IntroducePopups' })
          else navigation.navigate('Vip', { type: 'PrivateAdvisory' })
        },
      }))}
      upgrade={{
        label: tt('vip.privilege.upgrade', '立即升级'),
        onPress: () => navigation.navigate('Vip'),
      }}
    />
  )
}
