import { useCallback, useEffect, useState } from 'react'
import { useTheme } from '../context/ThemeContext'
import { useNavigation } from '@react-navigation/native'
import type { NativeStackNavigationProp } from '@react-navigation/native-stack'
import { fetchApi } from '@ihui/api-client'
import { CertListScreen as SharedCertListScreen, type CertListItem } from '@ihui/rn-app'
import { useI18n } from '../i18n'
import type { RootStackParamList } from '../navigation/RootNavigator'

type Nav = NativeStackNavigationProp<RootStackParamList>

export function CertListScreen() {
  const { resolvedTheme } = useTheme()
  const { t } = useI18n()
  const navigation = useNavigation<Nav>()
  const [items, setItems] = useState<CertListItem[]>([])
  const [loading, setLoading] = useState(true)
  const [refreshing, setRefreshing] = useState(false)
  const [error, setError] = useState('')

  const load = useCallback(async () => {
    setError('')
    try {
      // 后端 GET /certificates 回 success(findCertificates(...))，其声明返回
      // { list,total,page,pageSize };同端点另一屏 CertificateScreen 读的是分页对象，
      // 本屏把整个信封当数组 ⇒ 列表永远空，不抛错。
      // 后端 GET /certificates 回 findCertificates 行(certificates 表全列 +
      // nickname + templateName):卡片标题来源是 title/templateName/certificateNo
      // (表没有 name 列);issuer/score 是旧架构可空列,score 是 varchar。显式投影;
      // 只留有效证书(status=1),与 web /edu/my-certificates 口径一致。
      type CertRow = {
        id: string
        title?: string | null
        certificateNo?: string
        templateName?: string | null
        issuer?: string | null
        score?: string | null
        issuedAt?: string | null
        status?: number
      }
      const res = await fetchApi<{ list: CertRow[] }>('/certificates')
      if (!res.success) throw new Error()
      setItems(
        (res.data?.list ?? [])
          .filter((row) => row.status === 1)
          .map((row) => {
            const score = Number(row.score)
            return {
              id: row.id,
              name: row.title || row.templateName || row.certificateNo || '',
              issuer: row.issuer ?? '',
              issuedAt: row.issuedAt ? String(row.issuedAt).slice(0, 10) : '',
              score: Number.isFinite(score) ? score : 0,
            }
          }),
      )
    } catch {
      setError(t('certList.loadFailed'))
    } finally {
      setLoading(false)
      setRefreshing(false)
    }
  }, [t])

  useEffect(() => {
    void load()
  }, [load])

  return (
    <SharedCertListScreen
      t={t}
      items={items}
      loading={loading}
      refreshing={refreshing}
      error={error}
      onRefresh={() => {
        setRefreshing(true)
        void load()
      }}
      onPressItem={(id) => navigation.navigate('CertDetail', { id })}
      onBack={() => navigation.goBack()}
      colorScheme={resolvedTheme}
    />
  )
}
