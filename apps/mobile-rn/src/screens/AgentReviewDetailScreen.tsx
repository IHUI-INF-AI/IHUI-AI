import { useCallback } from 'react'
import { useNavigation, useRoute, type RouteProp } from '@react-navigation/native'
import { AgentReviewDetailScreen as SharedAgentReviewDetailScreen } from '@ihui/rn-app'
import { useTheme } from '../context/ThemeContext'
import { useI18n } from '../i18n'
import type { RootStackParamList } from '../navigation/RootNavigator'

type DetailRoute = RouteProp<RootStackParamList, 'AgentReviewDetail'>

/**
 * 评价详情薄壳：路由参数里已带完整条目（列表项与详情项字段等构），
 * 无需再请求详情接口；只把 route item 与导航端口注入共享详情屏。
 */
export function AgentReviewDetailScreen() {
  const { resolvedTheme } = useTheme()
  const { t } = useI18n()
  const navigation = useNavigation()
  const route = useRoute<DetailRoute>()
  const item = route.params?.item
  const onBack = useCallback(() => navigation.goBack(), [navigation])

  return (
    <SharedAgentReviewDetailScreen
      t={t}
      item={item}
      loading={false}
      error={item ? '' : t('agentReviewDetail.empty')}
      onBack={onBack}
      colorScheme={resolvedTheme}
    />
  )
}
