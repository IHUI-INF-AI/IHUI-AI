import { useCallback, useEffect, useState } from 'react'
import { useTheme } from '../context/ThemeContext'
import { useNavigation } from '@react-navigation/native'
import type { NativeStackNavigationProp } from '@react-navigation/native-stack'
import { getCommissionRates, getOverview, type CommissionOverview } from '@ihui/api-client'
import { EarnCommissionScreen as SharedEarnCommissionScreen } from '@ihui/rn-app'
import { appAlert } from '../components/BottomPops'
import { useI18n } from '../i18n'
import type { RootStackParamList } from '../navigation/RootNavigator'

type NavigationProp = NativeStackNavigationProp<RootStackParamList>

function EarnCommissionScreen() {
  const { resolvedTheme } = useTheme()
  const navigation = useNavigation<NavigationProp>()
  const { t } = useI18n()
  const [overview, setOverview] = useState<CommissionOverview | null>(null)
  const [rates, setRates] = useState<{ level: string; rate: string }[]>([])

  const load = useCallback(async () => {
    const [res, ratesRes] = await Promise.all([getOverview(), getCommissionRates()])
    if (res.success) setOverview(res.data ?? null)
    // 分佣比例真值:失败只落 [] (共享屏渲染 earnCommission.rateEmpty),不补默认档位
    setRates(
      ratesRes.success
        ? Object.entries(ratesRes.data.rates ?? {}).map(([level, rate]) => ({
            level,
            rate: String(rate ?? ''),
          }))
        : [],
    )
  }, [])

  useEffect(() => {
    void load()
  }, [load])

  const onOpenVip = (): void => {
    // 对齐端内 Taro.showModal 的开通确认步:标题/正文/确认/取消四键同源,确认后才跳 VIP。
    appAlert(t('distribution.plan.openVipTitle'), t('distribution.plan.openVipContent'), [
      { text: t('distribution.plan.cancel'), style: 'cancel' },
      {
        text: t('distribution.plan.confirm'),
        onPress: () => navigation.navigate('Vip', { type: 'IntroducePopup' }),
      },
    ])
  }

  // 共享屏根容器已等价提供 flex:1 + 主题背景(见 packages/app 共享屏 styles.root),
  // 本壳不再套自己那层 View —— 删一层纯壳 JSX,RN 与小程序腿(经 @rn-shells 执行同一份壳)同时受益。
  return (
    <SharedEarnCommissionScreen
      t={t}
      onBack={() => navigation.goBack()}
      overview={overview}
      onOpenVip={onOpenVip}
      rates={rates}
      colorScheme={resolvedTheme}
    />
  )
}

export default EarnCommissionScreen
