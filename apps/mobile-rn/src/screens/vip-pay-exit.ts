import type { OnNavigate } from '@ihui/types'

/**
 * nav-B Vip 支付链出口语义:
 * - 仅支付确认成功时调用,统一落 PayResult,并用 replace 避免回退到已支付的待付页;
 * - 取消/失败/未确认支付不调用此函数,留在 Vip 页只做提示,不产生跳转;
 * - PayResult 的返回由结果页自身(订单列表/回首页)承担。
 */
export function navigateAfterVipPay(orderNo: string, onNavigate: OnNavigate): void {
  onNavigate('PayResult', { orderNo }, { replace: true })
}
