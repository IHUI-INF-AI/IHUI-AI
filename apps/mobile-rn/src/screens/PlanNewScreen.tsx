import { useEffect, useState } from 'react'
import { useNavigation } from '@react-navigation/native'
import type { NativeStackNavigationProp } from '@react-navigation/native-stack'
import { PlanFormScreen as SharedPlanFormScreen, type PlanFormValues } from '@ihui/rn-app'
import { useI18n } from '../i18n'
import { useTheme } from '../context/ThemeContext'
import type { RootStackParamList } from '../navigation/RootNavigator'
import { rnPlanStore } from './PlanScreen'

/** 本票三条 Wave2 路由由 manifest 交集成方统一注册(禁改 RootNavigator),本地交叉类型补齐。 */
type ShellParams = RootStackParamList & {
  Plan: undefined
  PlanDetail: { id: string }
  PlanNew: undefined
}
type NavigationProp = NativeStackNavigationProp<ShellParams>

/**
 * RN 端「新建计划」薄壳 —— 渲染全部委托共享表单屏
 * `packages/app/src/features/plan/PlanFormScreen.tsx`,本文件只管平台侧:
 * 水合门控(web plan/new 同思路:未水合不渲染可写表单)+ create 后 replace 进详情
 * (对齐 web router.push('/plan/'+id),RN 用 replace 避免返回键退回空表单)。
 */
export function PlanNewScreen() {
  const navigation = useNavigation<NavigationProp>()
  const { t } = useI18n()
  const { resolvedTheme } = useTheme()
  const [ready, setReady] = useState(false)

  useEffect(() => {
    let cancelled = false
    void rnPlanStore.hydrate().finally(() => {
      if (!cancelled) setReady(true)
    })
    return () => {
      cancelled = true
    }
  }, [])

  if (!ready) return null

  const handleSubmit = (values: PlanFormValues): void => {
    const id = rnPlanStore.create({
      title: values.title,
      goal: values.goal,
      scope: values.scope,
      constraints: values.constraints,
      tags: values.tags,
      steps: values.steps,
    })
    navigation.replace('PlanDetail', { id })
  }

  return (
    <SharedPlanFormScreen
      t={t}
      colorScheme={resolvedTheme}
      onBack={() => navigation.goBack()}
      heading={t('planPage.createHeading')}
      submitLabel={t('planPage.createSubmit')}
      onSubmit={handleSubmit}
    />
  )
}

export default PlanNewScreen
