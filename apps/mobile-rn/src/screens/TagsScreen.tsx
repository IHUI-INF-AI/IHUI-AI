import { useCallback, useEffect, useState } from 'react'
import { useNavigation } from '@react-navigation/native'
import type { NativeStackNavigationProp } from '@react-navigation/native-stack'
import { getTags } from '@ihui/api-client'
import { TagsScreen as SharedTagsScreen, type TagCloudItem } from '@ihui/rn-app'
import { useI18n } from '../i18n'
import { useTheme } from '../context/ThemeContext'
import type { RootStackParamList } from '../navigation/RootNavigator'

type NavigationProp = NativeStackNavigationProp<RootStackParamList>

/**
 * RN 端「标签中心」薄壳 —— 渲染全部委托共享屏
 * `packages/app/src/features/tags/TagsScreen.tsx`,本文件只管平台侧:
 * 取词、主题、导航落点,以及 GET /api/tags(web apps/web/app/(main)/tags/page.tsx:42 同址)。
 */
export function TagsScreen() {
  const navigation = useNavigation<NavigationProp>()
  const { t } = useI18n()
  const { resolvedTheme } = useTheme()
  const [loading, setLoading] = useState(true)
  const [error, setError] = useState<string | null>(null)
  const [tags, setTags] = useState<TagCloudItem[] | undefined>(undefined)

  const load = useCallback(async () => {
    setLoading(true)
    setError(null)
    try {
      const res = await getTags()
      if (res.success) {
        setTags(res.data.tags ?? [])
      } else {
        setTags([])
        setError(t('tagsPage.fetchFailed'))
      }
    } catch {
      setTags([])
      setError(t('tagsPage.fetchFailed'))
    } finally {
      setLoading(false)
    }
  }, [t])

  useEffect(() => {
    void load()
  }, [load])

  return (
    <SharedTagsScreen
      t={t}
      colorScheme={resolvedTheme}
      onBack={() => navigation.goBack()}
      loading={loading}
      error={error}
      tags={tags}
      onTagPress={(slug) => navigation.navigate('TagDetail', { slug })}
      onRefresh={() => void load()}
    />
  )
}

export default TagsScreen
