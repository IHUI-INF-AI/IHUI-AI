import { useCallback, useEffect, useState } from 'react'
import { useTheme } from '../context/ThemeContext'
import { useNavigation } from '@react-navigation/native'
import type { NativeStackNavigationProp } from '@react-navigation/native-stack'
import { fetchApi } from '@ihui/api-client'
import { AgentStatScreen as SharedAgentStatScreen, type AgentStatData } from '@ihui/rn-app'
import { useI18n } from '../i18n'
import type { RootStackParamList } from '../navigation/RootNavigator'

type Nav = NativeStackNavigationProp<RootStackParamList>

export function AgentStatScreen() {
  const { resolvedTheme } = useTheme()
  const { t } = useI18n()
  const navigation = useNavigation<Nav>()
  const [stat, setStat] = useState<AgentStatData | null>(null)
  const [loading, setLoading] = useState(true)
  const [error, setError] = useState('')

  const load = useCallback(async () => {
    setError('')
    try {
      // 后端 GET /agents/stats(handleAgentStats,agents.ts)回聚合计数:
      // {totalAgents,totalCalls,totalUsers,avgRating,publishedCount,pendingCount}。
      // 显式投影成共享屏 AgentStatData(全字段可选);conversations/messages/tokens
      // 后端无对应来源,不猜不映射 —— 共享屏只渲染有值指标。
      type StatsRow = {
        totalAgents?: number
        totalUsers?: number
        totalCalls?: number
        publishedCount?: number
        pendingCount?: number
        avgRating?: number
      }
      const res = await fetchApi<StatsRow>('/agents/stats')
      if (!res.success) throw new Error()
      const row = res.data
      setStat(
        row
          ? {
              totalAgents: row.totalAgents ?? 0,
              totalUsers: row.totalUsers ?? 0,
              totalCalls: row.totalCalls ?? 0,
              publishedCount: row.publishedCount ?? 0,
              pendingCount: row.pendingCount ?? 0,
              avgRating: row.avgRating ?? 0,
            }
          : null,
      )
    } catch {
      setError(t('agentStat.loadFailed'))
    } finally {
      setLoading(false)
    }
  }, [t])

  useEffect(() => {
    void load()
  }, [load])

  return (
    <SharedAgentStatScreen
      t={t}
      stat={stat}
      loading={loading}
      error={error}
      onBack={() => navigation.goBack()}
      onRetry={() => { void load(); }}
      colorScheme={resolvedTheme}
    />
  )
}
