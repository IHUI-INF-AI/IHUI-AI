import { useNavigation, useRoute } from '@react-navigation/native'
import type { NativeStackNavigationProp } from '@react-navigation/native-stack'
import { LegalDocsHubScreen, type LegalDocKind } from '@ihui/rn-app'
import { useI18n } from '../i18n'
import { useTheme } from '../context/ThemeContext'
import type { RootStackParamList } from '../navigation/RootNavigator'

type NavigationProp = NativeStackNavigationProp<RootStackParamList>

/**
 * RN 端「法律文档中心」薄壳 —— web /legal/{terms,usage-policy,supported-regions,
 * service-specific-terms} 四路由收进同一路由 LegalDoc,doc 参数区分初始文档,
 * 渲染全部委托共享屏 `packages/app/src/features/legal-doc/LegalDocsHubScreen`
 * (一屏四入口,对齐 web legal/layout 侧栏导航)。
 * 纯静态文档:无端点取数,文案取 shared 消息包 legal.* 五语键。
 */
export function LegalDocScreen() {
  const navigation = useNavigation<NavigationProp>()
  const route = useRoute()
  const { t } = useI18n()
  const { resolvedTheme } = useTheme()
  const params = route.params as { doc?: LegalDocKind } | undefined

  return (
    <LegalDocsHubScreen
      t={t}
      colorScheme={resolvedTheme}
      initialDoc={params?.doc ?? 'terms'}
      onBack={() => navigation.goBack()}
    />
  )
}

