import { useCallback, useEffect, useState } from 'react'
import { useNavigation } from '@react-navigation/native'
import type { NativeStackNavigationProp } from '@react-navigation/native-stack'

import { fetchApi } from '@ihui/api-client'
import { EduDashboardScreen as SharedEduDashboardScreen, type EduDashboardData } from '@ihui/rn-app'
import { apiFailureToText } from '@ihui/shared/utils'

import { useTheme } from '../context/ThemeContext'
import { useI18n } from '../i18n'
import type { RootStackParamList } from '../navigation/RootNavigator'

type NavigationProp = NativeStackNavigationProp<RootStackParamList>

/** 教育看板(mobile-rn 宿主):单端点 GET /api/edu/dashboard(date 字段按 web 现读口径) */
export function EduDashboardScreen() {
  const { t } = useI18n()
  const { resolvedTheme } = useTheme()
  const navigation = useNavigation<NavigationProp>()
  const [data, setData] = useState<EduDashboardData | null>(null)
  const [loading, setLoading] = useState(true)
  const [error, setError] = useState('')

  const load = useCallback(async () => {
    setLoading(true)
    setError('')
    const res = await fetchApi<EduDashboardData>('/api/edu/dashboard')
    if (res.success && res.data) setData(res.data)
    else if (!res.success) setError(apiFailureToText(res, t('eduDashboard.loadFailed')))
    setLoading(false)
  }, [t])

  useEffect(() => {
    void load()
  }, [load])

  return (
    <SharedEduDashboardScreen
      t={t}
      data={data}
      loading={loading}
      error={error}
      onRetry={() => void load()}
      onBack={() => navigation.goBack()}
      colorScheme={resolvedTheme}
    />
  )
}
