/**
 * KnowledgeCreateScreen 知识库新建(mobile-rn 端 wrapper)
 *
 * 2026-09-15 迁移:UI 与展示逻辑已下沉共享层 @ihui/rn-app KnowledgeCreateScreen,
 * 本 wrapper 仅保留平台特定职责:
 * - 数据:ingestKnowledgeText 文本入库(必填校验 + Alert 成功/失败反馈)
 * - 导航:提交成功后 goBack;主题与 i18n 注入
 */
import { useState } from 'react'
import { Alert } from 'react-native'
import { useNavigation } from '@react-navigation/native'
import type { NativeStackNavigationProp } from '@react-navigation/native-stack'
import { useAuthStore } from '../stores/auth-store'
import { ingestKnowledgeText } from '@ihui/api-client'
import { KnowledgeCreateScreen as SharedKnowledgeCreateScreen } from '@ihui/rn-app'
import { useI18n } from '../i18n'
import { useTheme } from '../context/ThemeContext'
import type { RootStackParamList } from '../navigation/RootNavigator'

type NavigationProp = NativeStackNavigationProp<RootStackParamList>

export function KnowledgeCreateScreen() {
  const { t } = useI18n()
  const { resolvedTheme } = useTheme()
  const navigation = useNavigation<NavigationProp>()
  const user = useAuthStore((s) => s.user)
  const [title, setTitle] = useState('')
  const [text, setText] = useState('')
  const [submitting, setSubmitting] = useState(false)

  const onSubmit = async () => {
    if (!title.trim() || !text.trim()) {
      Alert.alert(t('common.hint'), t('knowledgeCreate.required'))
      return
    }
    setSubmitting(true)
    try {
      await ingestKnowledgeText({ ownerUuid: user?.id ?? '', title: title.trim(), text: text })
      Alert.alert(t('knowledgeCreate.successTitle'), t('knowledgeCreate.successMessage'), [
        { text: t('common.confirm'), onPress: () => navigation.goBack() },
      ])
    } catch {
      Alert.alert(t('knowledgeCreate.failedTitle'), t('knowledgeCreate.failedMessage'))
    } finally {
      setSubmitting(false)
    }
  }

  return (
    <SharedKnowledgeCreateScreen
      t={t}
      title={title}
      onTitleChange={setTitle}
      text={text}
      onTextChange={setText}
      submitting={submitting}
      onSubmit={() => void onSubmit()}
      onBack={() => navigation.goBack()}
      colorScheme={resolvedTheme}
    />
  )
}
