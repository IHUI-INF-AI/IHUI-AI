/**
 * ContextScreen 上下文引擎概览(mobile-rn 端 wrapper)
 *
 * 2026-09-15 迁移:UI 与展示逻辑已下沉共享层 @ihui/rn-app ContextScreen,
 * 本 wrapper 仅保留平台特定职责:
 * - 数据:getContextCompressionStats 压缩统计(失败 Alert)+ searchContextMentions
 *   提及检索(400ms 防抖,对齐 AiWorldScreen 搜索模式)
 * - 导航:goBack;主题与 i18n 注入
 */
import { useCallback, useEffect, useState } from 'react'
import { Alert } from 'react-native'
import { useNavigation } from '@react-navigation/native'
import type { NativeStackNavigationProp } from '@react-navigation/native-stack'
import {
  getContextCompressionStats,
  searchContextMentions,
  type ContextCompressionStats,
  type ContextMention,
} from '@ihui/api-client'
import { ContextScreen as SharedContextScreen } from '@ihui/rn-app'
import { useI18n } from '../i18n'
import { useTheme } from '../context/ThemeContext'
import type { RootStackParamList } from '../navigation/RootNavigator'

type NavigationProp = NativeStackNavigationProp<RootStackParamList>

export function ContextScreen() {
  const { t } = useI18n()
  const { resolvedTheme } = useTheme()
  const navigation = useNavigation<NavigationProp>()
  const [stats, setStats] = useState<ContextCompressionStats | null>(null)
  const [query, setQuery] = useState('')
  const [mentions, setMentions] = useState<ContextMention[]>([])
  const [loading, setLoading] = useState(true)
  const [searching, setSearching] = useState(false)

  const loadStats = useCallback(async () => {
    setLoading(true)
    try {
      const res = await getContextCompressionStats()
      if (!res.success || !res.data) throw new Error(res.error)
      setStats(res.data)
    } catch {
      Alert.alert(t('context.loadFailed'))
    } finally {
      setLoading(false)
    }
  }, [t])

  useEffect(() => {
    void loadStats()
  }, [loadStats])

  // 提及检索:400ms 防抖(对齐 AiWorldScreen 搜索模式)
  useEffect(() => {
    const timer = setTimeout(() => {
      void (async () => {
        setSearching(true)
        try {
          const res = await searchContextMentions({ q: query.trim() || undefined, limit: 20 })
          setMentions(res.success && res.data ? res.data.mentions : [])
        } catch {
          setMentions([])
        } finally {
          setSearching(false)
        }
      })()
    }, 400)
    return () => clearTimeout(timer)
  }, [query])

  return (
    <SharedContextScreen
      t={t}
      stats={stats}
      loading={loading}
      searching={searching}
      query={query}
      onQueryChange={setQuery}
      mentions={mentions}
      onRetry={() => void loadStats()}
      onBack={() => navigation.goBack()}
      colorScheme={resolvedTheme}
    />
  )
}
