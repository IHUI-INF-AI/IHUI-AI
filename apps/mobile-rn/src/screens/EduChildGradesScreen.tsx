/**
 * 孩子成绩页(mobile-rn 端)—— 薄壳,复用通用控制台列表屏 ConsoleTableScreen
 * (children 子页批 #2,覆盖 web edu/parent/children/[childId]/grades)。
 * 端点(与 web edu/parent/page.tsx 同源):
 *  - GET /api/edu-ai-management/parent/child/:childId/grades ⇒ { list: GradeItem[] }
 */
import { useCallback, useEffect, useState } from 'react'
import {
  useNavigation,
  useRoute,
  type NavigationProp,
  type RouteProp,
} from '@react-navigation/native'
import { fetchApi } from '@ihui/api-client'
import { ConsoleTableScreen, type ConsoleColumn, type ConsoleRowView } from '@ihui/rn-app'
import { useI18n } from '../i18n'
import { useTheme } from '../context/ThemeContext'
import type { RootStackParamList } from '../navigation/RootNavigator'

interface GradeItem {
  id: string
  subject: string
  examName: string
  score: number
  totalScore: number
  examDate: string
}

export function EduChildGradesScreen() {
  const { t } = useI18n()
  const { resolvedTheme } = useTheme()
  const navigation = useNavigation<NavigationProp<RootStackParamList>>()
  const route = useRoute<RouteProp<RootStackParamList, 'EduChildGrades'>>()
  const childId = route.params?.childId ?? ''
  const [rows, setRows] = useState<ConsoleRowView[]>([])
  const [loading, setLoading] = useState(true)
  const [error, setError] = useState<string | null>(null)

  const load = useCallback(async () => {
    if (!childId) return
    setLoading(true)
    setError(null)
    try {
      const res = await fetchApi<{ list: GradeItem[] }>(
        `/api/edu-ai-management/parent/child/${childId}/grades`,
      )
      if (!res.success) throw new Error(res.error || 'load failed')
      setRows(
        (res.data?.list ?? []).map((g) => ({
          id: g.id,
          cells: {
            subject: g.subject,
            exam: g.examName,
            score: `${String(g.score)}/${String(g.totalScore)}`,
            date: g.examDate?.slice(0, 10) ?? '',
          },
          badgeTone: g.totalScore > 0 && g.score / g.totalScore >= 0.6 ? 'ok' : 'warn',
        })),
      )
    } catch (e) {
      setError(e instanceof Error ? e.message : 'load failed')
    } finally {
      setLoading(false)
    }
  }, [childId])

  useEffect(() => {
    void load()
  }, [load])

  const columns: ConsoleColumn[] = [
    { key: 'subject', title: t('eduGrades.subject'), render: 'badge' },
    { key: 'exam', title: t('eduGrades.exam'), flex: 2 },
    { key: 'score', title: t('eduGrades.score') },
    { key: 'date', title: t('eduGrades.date') },
  ]

  return (
    <ConsoleTableScreen
      t={t}
      colorScheme={resolvedTheme}
      onBack={() => navigation.goBack()}
      title={t('eduChildGrades.title')}
      columns={columns}
      rows={rows}
      loading={loading}
      error={error}
      onRetry={() => void load()}
      onRefresh={() => void load()}
    />
  )
}

export default EduChildGradesScreen
