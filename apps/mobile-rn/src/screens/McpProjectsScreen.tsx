import { useCallback, useEffect, useState } from 'react'
import { useNavigation } from '@react-navigation/native'
import type { NativeStackNavigationProp } from '@react-navigation/native-stack'
import { getMcpResources, type McpResourceRecord } from '@ihui/api-client'
import { McpProjectsScreen as SharedMcpProjectsScreen, type McpResourceRowView } from '@ihui/rn-app'
import { useI18n } from '../i18n'
import { useAuth } from '../context/AuthContext'
import { useTheme } from '../context/ThemeContext'
import type { RootStackParamList } from '../navigation/RootNavigator'

type NavigationProp = NativeStackNavigationProp<RootStackParamList>

const NS = 'mcpProjectsPage'

/** 资源正文预览上限(web 由 McpResourceViewer 全量渲染,RN 列表只给摘录) */
const PREVIEW_LIMIT = 240

/**
 * RN 端「MCP 项目」薄壳 —— 承载 web /mcp-projects。渲染全部委托共享屏,本文件只管:
 * 取数 GET /api/ai/mcp/resources(契约 apps/api/src/routes/ai-frontend-routes.ts:308-330,
 * 代理 ai-service 后拆壳为裸数组)、内容预览截断、登录门(未登录不发注定 401 的查询;
 * web 侧同口径用 useAuthGate,PageClient.tsx:82/106-108)。
 * 口径差:web 的 5 个 Tab 中仅承载 resources 一档;servers 档后端返回 mcpServers 表行、
 * 与 web 期望形状不一致,tools/prompts/usage 档本次未扩,故不渲染 Tab 与对应入口。
 */
export function McpProjectsScreen() {
  const navigation = useNavigation<NavigationProp>()
  const { t } = useI18n()
  const { resolvedTheme } = useTheme()
  const { user } = useAuth()

  const [rows, setRows] = useState<McpResourceRowView[]>([])
  const [loading, setLoading] = useState(false)
  const [error, setError] = useState<string | null>(null)

  const toRow = useCallback((item: McpResourceRecord): McpResourceRowView => {
    const raw = item.content ?? ''
    return {
      uri: item.uri,
      name: item.name,
      mimeType: item.mimeType ?? '',
      preview: raw.length > PREVIEW_LIMIT ? `${raw.slice(0, PREVIEW_LIMIT)}…` : raw,
    }
  }, [])

  const load = useCallback(async () => {
    if (!user) return
    setLoading(true)
    try {
      const res = await getMcpResources()
      if (!res.success || !res.data) {
        setError(res.error ?? t('common.loadFailed'))
        return
      }
      setError(null)
      setRows((res.data ?? []).map(toRow))
    } catch {
      setError(t('common.loadFailed'))
    } finally {
      setLoading(false)
    }
  }, [user, toRow, t])

  useEffect(() => {
    void load()
  }, [load])

  return (
    <SharedMcpProjectsScreen
      t={t}
      colorScheme={resolvedTheme}
      onBack={() => navigation.goBack()}
      loginRequiredText={user ? '' : t(`${NS}.loginRequired`)}
      loading={loading}
      error={error}
      rows={rows}
      onRefresh={() => void load()}
    />
  )
}
