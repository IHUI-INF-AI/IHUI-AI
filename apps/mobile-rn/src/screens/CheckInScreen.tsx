import { useCallback, useEffect, useRef, useState } from 'react'
import { useTheme } from '../context/ThemeContext'
import {} from 'react-native'
import { appAlert } from '../components/BottomPops'
import { useNavigation } from '@react-navigation/native'
import type { NativeStackNavigationProp } from '@react-navigation/native-stack'
import { fetchApi } from '@ihui/api-client'
import { CheckInScreen as SharedCheckInScreen, type CheckInInfo } from '@ihui/rn-app'
import { useI18n } from '../i18n'
import type { RootStackParamList } from '../navigation/RootNavigator'

type NavigationProp = NativeStackNavigationProp<RootStackParamList>

export function CheckInScreen() {
  const { resolvedTheme } = useTheme()
  const { t } = useI18n()
  const navigation = useNavigation<NavigationProp>()
  const [info, setInfo] = useState<CheckInInfo | null>(null)
  const [loading, setLoading] = useState(true)
  const [refreshing, setRefreshing] = useState(false)
  const [error, setError] = useState('')
  const [signing, setSigning] = useState(false)
  // signing state 要等下一轮 render 才生效,同 tick 连点会发出两次 POST,故用 ref 立即互斥
  const signingRef = useRef(false)

  const load = useCallback(
    async (refresh = false) => {
      if (refresh) setRefreshing(true)
      else setLoading(true)
      setError('')
      try {
        const res = await fetchApi<CheckInInfo>('/checkin/today')
        if (!res.success) throw new Error()
        setInfo(res.data ?? null)
      } catch {
        setError(t('checkIn.loadFailed'))
      } finally {
        setLoading(false)
        setRefreshing(false)
      }
    },
    [t],
  )

  useEffect(() => {
    void load()
  }, [load])

  const handleSign = async () => {
    if (!info || info.todaySigned || signingRef.current) return
    signingRef.current = true
    setSigning(true)
    try {
      const res = await fetchApi('/checkin', { method: 'POST' })
      if (res.success) {
        appAlert(t('checkIn.signSuccess'), `+${info.todayReward}`)
        void load(true)
      } else {
        appAlert(t('checkIn.signFailed'))
      }
    } finally {
      // 失败/抛错也必须复位,否则按钮永久卡在 signing 态
      signingRef.current = false
      setSigning(false)
    }
  }

  return (
    <SharedCheckInScreen
      t={t}
      info={info}
      loading={loading}
      refreshing={refreshing}
      signing={signing}
      error={error}
      onSign={handleSign}
      onRefresh={() => load(true)}
      onBack={() => navigation.goBack()}
      onRetry={() => {
        void load()
      }}
      colorScheme={resolvedTheme}
    />
  )
}
