import { useCallback, useEffect, useState } from 'react'
import { useNavigation, useRoute, type RouteProp } from '@react-navigation/native'
import type { NativeStackNavigationProp } from '@react-navigation/native-stack'
import { getCourseCatalog } from '@ihui/api-client'
import {
  CourseCatalogScreen as SharedCourseCatalogScreen,
  type CourseCatalogItem,
} from '@ihui/rn-app'
import { useI18n } from '../i18n'
import { useTheme } from '../context/ThemeContext'
import type { RootStackParamList } from '../navigation/RootNavigator'

type Route = RouteProp<RootStackParamList, 'CourseCatalog'>
type NavigationProp = NativeStackNavigationProp<RootStackParamList>

export function CourseCatalogScreen() {
  const { t } = useI18n()
  const { resolvedTheme } = useTheme()
  const route = useRoute<Route>()
  const navigation = useNavigation<NavigationProp>()
  const { courseId } = route.params
  const [items, setItems] = useState<CourseCatalogItem[]>([])
  const [loading, setLoading] = useState(true)
  const [error, setError] = useState('')

  const load = useCallback(async () => {
    setLoading(true)
    setError('')
    try {
      const res = await getCourseCatalog(courseId)
      if (!res.success) throw new Error(res.error)
      setItems(res.data)
    } catch {
      setError(t('courseCatalog.loadFailed'))
    } finally {
      setLoading(false)
    }
  }, [courseId, t])

  useEffect(() => {
    void load()
  }, [load])

  const onPressItem = () => {
    // CourseChapter 的取数是课程详情的目录投影(= 课程详情数据的 chapters 再投影)
    // ⇒ 必须传**课程 id**(本页路由参数),传章节 id 会把章节当课程查、页面回「找不到对应的资源」。
    navigation.navigate('CourseChapter', { courseId })
  }

  return (
    <SharedCourseCatalogScreen
      t={t}
      items={items}
      loading={loading}
      error={error}
      onPressItem={onPressItem}
      onBack={() => navigation.goBack()}
      colorScheme={resolvedTheme}
    />
  )
}
