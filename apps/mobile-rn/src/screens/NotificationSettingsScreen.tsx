import { useCallback, useEffect, useState } from 'react'
import { useTheme } from '../context/ThemeContext'
import { useNavigation } from '@react-navigation/native'
import type { NativeStackNavigationProp } from '@react-navigation/native-stack'
import { fetchApi } from '@ihui/api-client'
import {
  NotificationSettingsScreen as SharedNotificationSettingsScreen,
  type NotificationSettingsItem,
} from '@ihui/rn-app'
import { useI18n } from '../i18n'
import type { RootStackParamList } from '../navigation/RootNavigator'

type NavigationProp = NativeStackNavigationProp<RootStackParamList>

export function NotificationSettingsScreen() {
  const { resolvedTheme } = useTheme()
  const { t } = useI18n()
  const navigation = useNavigation<NavigationProp>()
  const [settings, setSettings] = useState<NotificationSettingsItem | null>(null)
  const [loading, setLoading] = useState(true)
  const [saving, setSaving] = useState(false)
  const [error, setError] = useState('')
  const [success, setSuccess] = useState('')

  useEffect(() => {
    let cancelled = false
    void (async () => {
      try {
        const res = await fetchApi<{ settings?: NotificationSettingsItem }>(
          '/settings/notifications',
        )
        if (cancelled) return
        if (!res.success) {
          // 透出后端 message,而非一律「加载失败」。
          setError(res.error || t('notificationSettings.loadFailed'))
          return
        }
        setSettings(res.data?.settings ?? null)
      } catch {
        if (!cancelled) setError(t('notificationSettings.loadFailed'))
      } finally {
        if (!cancelled) setLoading(false)
      }
    })()
    return () => {
      cancelled = true
    }
  }, [t])

  const handleToggle = useCallback((key: keyof NotificationSettingsItem, value: boolean) => {
    setSettings((prev) => (prev ? { ...prev, [key]: value } : prev))
  }, [])

  const handleSave = async () => {
    if (!settings) return
    setSaving(true)
    setError('')
    setSuccess('')
    try {
      const res = await fetchApi<unknown>('/settings/notifications', {
        method: 'PUT',
        body: JSON.stringify(settings),
      })
      if (!res.success) {
        // 保存失败要说明原因(未登录/入参非法/服务异常),否则用户只会反复点保存。
        setError(res.error || t('notificationSettings.saveFailed'))
        return
      }
      setSuccess(t('notificationSettings.saved'))
    } catch {
      setError(t('notificationSettings.saveFailed'))
    } finally {
      setSaving(false)
    }
  }

  return (
    <SharedNotificationSettingsScreen
      t={t}
      settings={settings}
      loading={loading}
      saving={saving}
      error={error}
      success={success}
      onToggle={handleToggle}
      onSave={handleSave}
      onBack={() => navigation.goBack()}
      colorScheme={resolvedTheme}
    />
  )
}
