import { useCallback, useEffect, useState } from 'react'
import { ScrollView, RefreshControl } from 'react-native'
import { useNavigation } from '@react-navigation/native'
import type { NativeStackNavigationProp } from '@react-navigation/native-stack'
import { listAutomations, type UserAutomation } from '@ihui/api-client'
import { useI18n } from '../i18n'
import type { RootStackParamList } from '../navigation/RootNavigator'
import { AutomationCard } from '../components/automation/AutomationCard'
import Empty from '../components/common/Empty'
import Loading from '../components/common/Loading'

type NavigationProp = NativeStackNavigationProp<RootStackParamList>

/**
 * 只读「工作流」列表:拉取当前用户的自动化(=工作流)并平铺展示。
 * 点击任一项进入 Automations 详情屏(传 id)。无编辑器、无写入操作。
 */
export function WorkflowsScreen() {
  const { t } = useI18n()
  const navigation = useNavigation<NavigationProp>()
  const [items, setItems] = useState<UserAutomation[]>([])
  const [loading, setLoading] = useState(true)
  const [refreshing, setRefreshing] = useState(false)
  const [error, setError] = useState('')

  const load = useCallback(async () => {
    setError('')
    try {
      const res = await listAutomations({ limit: 50 })
      setItems(res.items)
    } catch (e) {
      setError(e instanceof Error ? e.message : t('workflows.loadFailed'))
    } finally {
      setLoading(false)
      setRefreshing(false)
    }
  }, [t])

  useEffect(() => {
    void load()
  }, [load])

  const handleSelect = useCallback(
    (item: UserAutomation) => {
      navigation.navigate('Automations', { id: item.id })
    },
    [navigation],
  )

  if (loading) return <Loading text={t('common.loading')} />
  if (error) return <Empty text={error} actionText={t('common.retry')} onAction={load} />
  if (items.length === 0) {
    return <Empty text={t('workflows.empty')} actionText={t('common.retry')} onAction={load} />
  }

  return (
    <ScrollView
      className="flex-1 bg-background px-4 pt-4"
      contentContainerStyle={{ paddingBottom: 24 }}
      refreshControl={<RefreshControl refreshing={refreshing} onRefresh={load} />}
    >
      {items.map((item) => (
        <AutomationCard key={item.id} item={item} onSelect={handleSelect} />
      ))}
    </ScrollView>
  )
}
