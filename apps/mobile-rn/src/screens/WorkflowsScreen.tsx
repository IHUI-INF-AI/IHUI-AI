import { useCallback, useEffect, useMemo, useState } from 'react'
import { useNavigation } from '@react-navigation/native'
import type { NativeStackNavigationProp } from '@react-navigation/native-stack'
import { listAutomations, type UserAutomation } from '@ihui/api-client'
import {
  getTokens,
  WorkflowsScreen as SharedWorkflowsScreen,
  type WorkflowItem,
} from '@ihui/rn-app'
import { useTheme } from '../context/ThemeContext'
import { useI18n } from '../i18n'
import type { RootStackParamList } from '../navigation/RootNavigator'

type NavigationProp = NativeStackNavigationProp<RootStackParamList>

const dateTimeFormat = new Intl.DateTimeFormat()

/** 下次运行时间文本:无效/空值统一显示 "—"(§3 时间用 Intl.DateTimeFormat) */
function formatNextRun(value: string | null): string {
  if (!value) return '—'
  const d = new Date(value)
  if (Number.isNaN(d.getTime())) return '—'
  return dateTimeFormat.format(d)
}

/**
 * 「工作流」wrapper:保留 hooks/API/导航/主题,展示文本在此算好后注入共享层
 * WorkflowsScreen(packages/app/src/features/workflows)。
 */
export function WorkflowsScreen() {
  const { t } = useI18n()
  const { resolvedTheme } = useTheme()
  const navigation = useNavigation<NavigationProp>()
  const [raw, setRaw] = useState<UserAutomation[]>([])
  const [loading, setLoading] = useState(true)
  const [refreshing, setRefreshing] = useState(false)
  const [error, setError] = useState('')

  const load = useCallback(async () => {
    setRefreshing(true)
    setError('')
    try {
      const res = await listAutomations({ limit: 50 })
      setRaw(res.items)
    } catch (e) {
      setError(e instanceof Error ? e.message : t('workflows.loadFailed'))
    } finally {
      setLoading(false)
      setRefreshing(false)
    }
  }, [t])

  useEffect(() => {
    void load()
  }, [load])

  const items = useMemo<WorkflowItem[]>(
    () =>
      raw.map((a) => ({
        id: a.id,
        name: a.name,
        status: a.status === 'active' ? 'active' : 'paused',
        statusText: a.status === 'active' ? t('automations.active') : t('automations.paused'),
        scheduleText:
          a.scheduleType === 'recurring'
            ? t('automations.scheduleRecurring')
            : t('automations.scheduleOnce'),
        nextRunText: formatNextRun(a.nextRunAt),
        lastResultText: a.lastResult?.summary ?? '',
      })),
    [raw, t],
  )

  const handleOpen = useCallback(
    (id: string) => {
      navigation.navigate('Automations', { id })
    },
    [navigation],
  )

  return (
    <SharedWorkflowsScreen
      t={t}
      tk={getTokens(resolvedTheme)}
      items={items}
      loading={loading}
      refreshing={refreshing}
      error={error}
      onOpen={handleOpen}
      onRefresh={load}
    />
  )
}
