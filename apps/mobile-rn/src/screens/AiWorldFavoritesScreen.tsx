/**
 * AiWorldFavoritesScreen AI 世界收藏列表(mobile-rn 端 wrapper)
 *
 * 承载 web `/ai-world/favorites`(apps/web/app/(main)/ai-world/favorites/page.tsx):
 * GET /api/ai-world/favorites(需登录,未登录不发注定 401 的请求,与 web useAuthGate 同口径)。
 * UI 下沉共享层 @ihui/rn-app AiWorldCollectionScreen(variant='favorites'),
 * 文案经 t() 注入;条目点击进详情,登录引导跳 Login。
 */
import { useCallback, useEffect, useState } from 'react'
import { useNavigation } from '@react-navigation/native'
import type { NativeStackNavigationProp } from '@react-navigation/native-stack'
import { getAiWorldFavorites } from '@ihui/api-client'
import type { AiWorldCollectionItem } from '@ihui/api-client'
import { apiFailureToText } from '@ihui/shared/utils'
import { AiWorldCollectionScreen } from '@ihui/rn-app'
import { useAuth } from '../context/AuthContext'
import { useI18n } from '../i18n'
import { useTheme } from '../context/ThemeContext'
import type { RootStackParamList } from '../navigation/RootNavigator'

type NavigationProp = NativeStackNavigationProp<RootStackParamList>

export function AiWorldFavoritesScreen() {
  const { t } = useI18n()
  const { resolvedTheme } = useTheme()
  const { user } = useAuth()
  const navigation = useNavigation<NavigationProp>()

  const [items, setItems] = useState<AiWorldCollectionItem[]>([])
  const [loading, setLoading] = useState(false)
  const [refreshing, setRefreshing] = useState(false)
  const [error, setError] = useState('')

  const load = useCallback(
    async (mode: 'initial' | 'refresh') => {
      if (!user) return
      if (mode === 'initial') setLoading(true)
      else setRefreshing(true)
      setError('')
      try {
        const res = await getAiWorldFavorites()
        if (!res.success) {
          setError(apiFailureToText(res, t('aiWorldFavoritesPage.fetchFailed')))
          setItems([])
          return
        }
        setItems(res.data.list ?? [])
      } catch {
        setError(t('aiWorldFavoritesPage.fetchFailed'))
        setItems([])
      } finally {
        setLoading(false)
        setRefreshing(false)
      }
    },
    [t, user],
  )

  useEffect(() => {
    if (!user) return
    void load('initial')
  }, [load, user])

  return (
    <AiWorldCollectionScreen
      t={t}
      colorScheme={resolvedTheme}
      onBack={() => navigation.goBack()}
      variant="favorites"
      title={t('aiWorldFavoritesPage.title')}
      subtitle={t('aiWorldFavoritesPage.subtitle')}
      emptyText={t('aiWorldFavoritesPage.empty')}
      loginRequiredText={user ? '' : t('aiWorldFavoritesPage.loginRequired')}
      loginLabel={t('common.login')}
      onLogin={() => navigation.navigate('Login')}
      loading={loading}
      refreshing={refreshing}
      error={error}
      onRetry={() => void load('initial')}
      items={items.map((item) => ({
        id: item.id,
        title: item.title,
        coverImage: item.coverImage,
        viewCount: item.viewCount,
        date: item.createdAt ?? '',
      }))}
      onPressItem={(id) => navigation.navigate('AiWorldDetail', { id })}
      onRefresh={() => void load('refresh')}
    />
  )
}

export default AiWorldFavoritesScreen
