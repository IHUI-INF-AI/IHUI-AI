import { useCallback, useEffect, useState } from 'react'
import { useNavigation } from '@react-navigation/native'
import type { NativeStackNavigationProp } from '@react-navigation/native-stack'

import { fetchApi } from '@ihui/api-client'
import { MyAgentsScreen as SharedMyAgentsScreen, type MyAgentRow } from '@ihui/rn-app'
import { apiFailureToText, formatPrice } from '@ihui/shared/utils'

import { useTheme } from '../context/ThemeContext'
import { useI18n } from '../i18n'
import type { RootStackParamList } from '../navigation/RootNavigator'

type NavigationProp = NativeStackNavigationProp<RootStackParamList>

interface MyAgentApiRow {
  agentId: string
  name: string
  description: string | null
  status: string
  price: number
  isFree: boolean
}

/** 我的智能体(mobile-rn 宿主):GET /api/agents/my → {list,total} */
export function MyAgentsScreen() {
  const { t } = useI18n()
  const { resolvedTheme } = useTheme()
  const navigation = useNavigation<NavigationProp>()
  const [items, setItems] = useState<MyAgentRow[]>([])
  const [loading, setLoading] = useState(true)
  const [refreshing, setRefreshing] = useState(false)
  const [error, setError] = useState('')

  const load = useCallback(async () => {
    setError('')
    const res = await fetchApi<{ list?: MyAgentApiRow[] }>('/api/agents/my', {
      params: { page: 1, pageSize: 20 },
    })
    if (res.success) {
      setItems(
        (res.data?.list ?? []).map((a) => ({
          id: a.agentId,
          name: a.name,
          description: a.description ?? '',
          status: a.status,
          priceText: a.isFree ? t('myAgentsPage.free') : formatPrice(a.price),
        })),
      )
    } else {
      setError(apiFailureToText(res, t('myAgentsPage.loadFailed')))
    }
    setLoading(false)
    setRefreshing(false)
  }, [t])

  useEffect(() => {
    void load()
  }, [load])

  return (
    <SharedMyAgentsScreen
      t={t}
      items={items}
      loading={loading}
      refreshing={refreshing}
      error={error}
      onRefresh={() => {
        setRefreshing(true)
        void load()
      }}
      onPressItem={(id) => navigation.navigate('AgentDetail', { id })}
      onBack={() => navigation.goBack()}
      colorScheme={resolvedTheme}
    />
  )
}
