import { useCallback, useEffect, useState } from 'react'
import { useNavigation } from '@react-navigation/native'
import type { NativeStackNavigationProp } from '@react-navigation/native-stack'
import { getMyLessons } from '@ihui/api-client'
import type { MyLessonRow } from '@ihui/api-client'
import { MyLessonsScreen as SharedMyLessonsScreen } from '@ihui/rn-app'
import { useI18n } from '../i18n'
import { useTheme } from '../context/ThemeContext'
import type { RootStackParamList } from '../navigation/RootNavigator'

type NavigationProp = NativeStackNavigationProp<RootStackParamList>

const PAGE_SIZE = 20

/**
 * RN 端「我的课程」薄壳 —— 渲染全部委托共享屏
 * `packages/app/src/features/student/MyLessonsScreen.tsx`,本文件只管平台侧:
 * 分页取数(GET /api/edu/my-lessons?page&pageSize,与 web 同 pageSize=20)与主题取词。
 */
export function MyLessonsScreen() {
  const navigation = useNavigation<NavigationProp>()
  const { t } = useI18n()
  const { resolvedTheme } = useTheme()
  const [loading, setLoading] = useState(true)
  const [error, setError] = useState<string | null>(null)
  const [items, setItems] = useState<MyLessonRow[]>([])
  const [total, setTotal] = useState(0)
  const [page, setPage] = useState(1)

  const load = useCallback(async () => {
    setLoading(true)
    setError(null)
    try {
      const res = await getMyLessons({ page, pageSize: PAGE_SIZE })
      if (!res.success || !res.data) {
        setError(t('studentPage.fetchFailed'))
        return
      }
      setItems(res.data.list ?? [])
      setTotal(res.data.total ?? 0)
    } catch {
      setError(t('studentPage.fetchFailed'))
    } finally {
      setLoading(false)
    }
  }, [t, page])

  useEffect(() => {
    void load()
  }, [load])

  return (
    <SharedMyLessonsScreen
      t={t}
      colorScheme={resolvedTheme}
      onBack={() => navigation.goBack()}
      loading={loading}
      error={error}
      items={items}
      page={page}
      totalPages={Math.max(1, Math.ceil(total / PAGE_SIZE))}
      onPageChange={setPage}
      onRefresh={() => void load()}
    />
  )
}

