import { useEffect, useState } from 'react'
import { useTheme } from '../context/ThemeContext'
import { useNavigation, useRoute, type RouteProp } from '@react-navigation/native'
import type { NativeStackNavigationProp } from '@react-navigation/native-stack'
import { getCourseComments } from '@ihui/api-client'
import { apiFailureToText } from '@ihui/shared/utils'
import {
  CourseCommentScreen as SharedCourseCommentScreen,
  type CourseCommentItem,
} from '@ihui/rn-app'
import { useI18n } from '../i18n'
import type { RootStackParamList } from '../navigation/RootNavigator'

type Route = RouteProp<RootStackParamList, 'CourseComment'>
type NavigationProp = NativeStackNavigationProp<RootStackParamList>

export function CourseCommentScreen() {
  const { resolvedTheme } = useTheme()
  const { t } = useI18n()
  const route = useRoute<Route>()
  const navigation = useNavigation<NavigationProp>()
  const { courseId } = route.params
  const [comments, setComments] = useState<CourseCommentItem[]>([])
  const [loading, setLoading] = useState(true)
  const [error, setError] = useState('')

  useEffect(() => {
    let cancelled = false
    void (async () => {
      setLoading(true)
      setError('')
      // 评价列表换源:旧 /api/courses/:id/comments 随 course-mobile-routes 注册面被摘,
      // 打已注册的 /api/learn/lessons/:id/rates(投影同口径,见 api-client getCourseComments)。
      const res = await getCourseComments(courseId)
      if (cancelled) return
      if (res.success) setComments(res.data)
      else setError(apiFailureToText(res, t('courseComment.loadFailed')))
      setLoading(false)
    })()
    return () => {
      cancelled = true
    }
  }, [courseId, t])

  return (
    <SharedCourseCommentScreen
      t={t}
      items={comments}
      loading={loading}
      error={error}
      onBack={() => navigation.goBack()}
      colorScheme={resolvedTheme}
    />
  )
}
