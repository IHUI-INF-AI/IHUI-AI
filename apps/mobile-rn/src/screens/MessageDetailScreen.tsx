import { useCallback, useEffect, useState } from 'react'
import { useTheme } from '../context/ThemeContext'
import { useNavigation, useRoute, type RouteProp } from '@react-navigation/native'
import type { NativeStackNavigationProp } from '@react-navigation/native-stack'
import { fetchApi } from '@ihui/api-client'
import { apiFailureToText } from '@ihui/shared/utils'
import { MessageDetailScreen as SharedMessageDetailScreen } from '@ihui/rn-app'
import type { MessageDetailData } from '@ihui/types'
import { useI18n } from '../i18n'
import type { RootStackParamList } from '../navigation/RootNavigator'

type Route = RouteProp<RootStackParamList, 'MessageDetail'>
type NavigationProp = NativeStackNavigationProp<RootStackParamList>

/** PUT /api/messages/:id/read 回包里的 edu_messages 行(schema: packages/database/src/schema/message.ts) */
interface EduMessageRow {
  id: string
  title: string | null
  content: string | null
  senderId: string | null
  isRead: boolean
  createdAt: string
}

export function MessageDetailScreen() {
  const { resolvedTheme } = useTheme()
  const { t } = useI18n()
  const route = useRoute<Route>()
  const navigation = useNavigation<NavigationProp>()
  const { id } = route.params
  const [message, setMessage] = useState<MessageDetailData | null>(null)
  const [loading, setLoading] = useState(true)
  const [error, setError] = useState('')

  const load = useCallback(async () => {
    setLoading(true)
    setError('')
    try {
      // 站内信详情真数据源 = edu_messages。GET /api/messages/:id(user/misc-routes.ts)查的是
      // chat_messages(AI 会话表),拿不到 title/senderId ⇒ 不能用。这里改走
      // PUT /api/messages/:id/read(message.ts:242,打开详情即已读,web 消息中心同款出口):
      // 回 success({ message: 全行 }),在壳里解包 res.data?.message 并按 MessageDetailData 投影。
      const res = await fetchApi<{ message: EduMessageRow | null }>(
        `/api/messages/${encodeURIComponent(id)}/read`,
        { method: 'PUT' },
      )
      if (!res.success) {
        setError(apiFailureToText(res, t('messageDetail.loadFailed')))
        return
      }
      const row = res.data?.message
      setMessage(
        row
          ? {
              id: row.id,
              subject: row.title ?? '',
              content: row.content ?? '',
              fromUser: row.senderId ?? '',
              createdAt: row.createdAt,
              read: row.isRead,
            }
          : null,
      )
    } catch {
      setError(t('messageDetail.loadFailed'))
    } finally {
      setLoading(false)
    }
  }, [id, t])

  useEffect(() => {
    void load()
  }, [load])

  const handleReply = async () => {
    // senderId 可空(库内 nullable):没有真实发送者就不给回复入口,不用空串冒充 peerId
    if (!message?.fromUser) return
    // 跳单聊标题用真实昵称(2026-11-01 收口):单查公开资料 GET /users/:id(鉴权后可用,
    // limitedPublicUser 亦含 nickname),取不到回落 senderId——昵称缺失不阻塞回复主路径
    let peerName = message.fromUser
    try {
      const pres = await fetchApi<{ user: { nickname?: string | null } }>(
        `/api/users/${encodeURIComponent(message.fromUser)}`,
      )
      const nickname = pres.success ? pres.data?.user?.nickname : null
      if (nickname) peerName = nickname
    } catch {
      // 静默:昵称取不到就用既有回落
    }
    navigation.navigate('MessageChat', { peerId: message.fromUser, name: peerName })
  }

  return (
    <SharedMessageDetailScreen
      t={t}
      message={message}
      loading={loading}
      error={error}
      onReply={handleReply}
      onBack={() => navigation.goBack()}
      onRetry={() => { void load(); }}
      colorScheme={resolvedTheme}
    />
  )
}
