import { useCallback, useEffect, useState } from 'react'
import { useNavigation } from '@react-navigation/native'
import type { NativeStackNavigationProp } from '@react-navigation/native-stack'
import { fetchApi } from '@ihui/api-client'
import { StudyPlanScreen as SharedStudyPlanScreen, type StudyPlanItem } from '@ihui/rn-app'
import { useI18n } from '../i18n'
import { useTheme } from '../context/ThemeContext'
import type { RootStackParamList } from '../navigation/RootNavigator'

type NavigationProp = NativeStackNavigationProp<RootStackParamList>

/**
 * GET /api/study/plans 的权威形状(逐处现读 HEAD):
 * - 注册:apps/api/src/routes/other/study-plan-routes.ts:18 `server.get('/study/plans', ...)`
 *   (同行形态),该文件头注第 7 行写明它就是 mobile-rn StudyPlanScreen 的数据源。
 * - 前缀链:apps/api/src/routes/other/index.ts:79 `await server.register(studyPlanRoutes)` 不给前缀
 *   → apps/api/src/routes/index.ts:1048 `server.register(otherRoutes, { prefix: '/api' })` ⇒ /api/study/plans。
 *   鉴权:other/index.ts:46 的 preHandler(:48 authenticate)⇒ 需登录(本端已带 token)。
 * - 响应:study-plan-routes.ts:68 `success(plans)` ⇒ data 是**裸数组**,不是 { list } 包裹。
 * - 行骨架是报名记录(lesson_sign_ups ⋈ lessons ⟕ study_plans),不是 study_plans 行本身。
 */
interface StudyPlanRow {
  id: string
  title: string
  courseName: string
  totalLessons: number
  completedLessons: number
  progress: number
  /** 后端值域 'pending' | 'inProgress' | 'completed'(study-plan-routes.ts:48) */
  status: string
  /** 'YYYY-MM-DD'(后端由报名时刻 + 30 天算出) */
  deadline: string
}

/** 后端行 → 本屏 StudyPlanItem(逐字段映射,不把后端行整体当本屏类型用) */
function toStudyPlanItem(row: StudyPlanRow): StudyPlanItem {
  return {
    id: row.id,
    title: row.title,
    courseName: row.courseName,
    totalLessons: row.totalLessons,
    completedLessons: row.completedLessons,
    progress: row.progress,
    status: row.status,
    deadline: row.deadline,
  }
}

export function StudyPlanScreen() {
  const { t } = useI18n()
  const { resolvedTheme } = useTheme()
  const navigation = useNavigation<NavigationProp>()
  const [items, setItems] = useState<StudyPlanItem[]>([])
  const [loading, setLoading] = useState(true)
  const [refreshing, setRefreshing] = useState(false)
  const [error, setError] = useState('')

  const load = useCallback(async () => {
    setError('')
    try {
      const res = await fetchApi<StudyPlanRow[]>('/api/study/plans')
      if (!res.success) throw new Error()
      setItems((res.data ?? []).map(toStudyPlanItem))
    } catch {
      setError(t('studyPlan.loadFailed'))
    } finally {
      setLoading(false)
      setRefreshing(false)
    }
  }, [t])

  useEffect(() => {
    void load()
  }, [load])

  const onPressItem = (_item: StudyPlanItem) => {
    // 无独立计划详情页,跳转学习进度页(已注册)承载计划进度查看
    navigation.navigate('StudyProgress')
  }

  return (
    <SharedStudyPlanScreen
      t={t}
      items={items}
      loading={loading}
      refreshing={refreshing}
      error={error}
      onRefresh={() => {
        setRefreshing(true)
        void load()
      }}
      onPressItem={onPressItem}
      onBack={() => navigation.goBack()}
      colorScheme={resolvedTheme}
    />
  )
}
