import { useCallback, useEffect, useState } from 'react'
import { useNavigation } from '@react-navigation/native'
import type { NativeStackNavigationProp } from '@react-navigation/native-stack'
import {
  getPublicStatusIncidents,
  getPublicStatusModels,
  getPublicStatusOverview,
} from '@ihui/api-client'
import type {
  PublicStatusIncident,
  PublicStatusModelRow,
  PublicStatusOverview,
} from '@ihui/api-client'
import { StatusScreen as SharedStatusScreen } from '@ihui/rn-app'
import { useI18n } from '../i18n'
import { useTheme } from '../context/ThemeContext'
import type { RootStackParamList } from '../navigation/RootNavigator'

type NavigationProp = NativeStackNavigationProp<RootStackParamList>

type StatusData = {
  overview: PublicStatusOverview
  models: PublicStatusModelRow[]
  incidents: PublicStatusIncident[] | null
  incidentsDegraded: boolean
}

/**
 * RN 端「系统状态」薄壳 —— 渲染全部委托共享屏
 * `packages/app/src/features/status/StatusScreen.tsx`,本文件只管平台侧:
 * 取词、主题、导航落点,以及同时拉取 overview / models / incidents 三个公开端点。
 *
 * 与 web 端同口径:incidents 查询失败回 HTTP 200 + degraded=true 时,必须渲染降级提示
 * 而非把「没取到」写成「无事件」(否则故障列表消失,用户误以为一切正常)。
 */
export function StatusScreen() {
  const navigation = useNavigation<NavigationProp>()
  const { t } = useI18n()
  const { resolvedTheme } = useTheme()
  const [loading, setLoading] = useState(true)
  const [error, setError] = useState<string | null>(null)
  const [data, setData] = useState<StatusData | null>(null)

  const load = useCallback(async () => {
    setLoading(true)
    setError(null)
    try {
      const [overviewRes, modelsRes, incidentsRes] = await Promise.all([
        getPublicStatusOverview(),
        getPublicStatusModels(),
        getPublicStatusIncidents(),
      ])
      if (!overviewRes.success || !modelsRes.success || !incidentsRes.success) {
        setError(t('statusPage.fetchFailed'))
        setData(null)
        return
      }
      const incidentsPayload = incidentsRes.data
      setData({
        overview: overviewRes.data,
        models: modelsRes.data.models,
        incidents: (incidentsPayload?.incidents ?? null) as PublicStatusIncident[] | null,
        incidentsDegraded: Boolean(incidentsPayload?.degraded),
      })
      setError(null)
    } catch {
      setError(t('statusPage.fetchFailed'))
      setData(null)
    } finally {
      setLoading(false)
    }
  }, [t])

  useEffect(() => {
    void load()
  }, [load])

  return (
    <SharedStatusScreen
      t={t}
      colorScheme={resolvedTheme}
      onBack={() => navigation.goBack()}
      loading={loading}
      error={error}
      data={data ?? undefined}
      onRefresh={() => void load()}
    />
  )
}

