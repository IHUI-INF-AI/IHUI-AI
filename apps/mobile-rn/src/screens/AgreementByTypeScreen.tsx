import { useCallback, useEffect, useState } from 'react'
import { useNavigation, useRoute, type RouteProp } from '@react-navigation/native'
import type { NativeStackNavigationProp } from '@react-navigation/native-stack'
import { getCurrentAgreement, type AgreementType } from '@ihui/api-client'
import {
  AgreementScreen as SharedAgreementScreen,
  agreementTitleKey,
  normalizeAgreementType,
  type AgreementContentView,
} from '@ihui/rn-app'
import { useI18n } from '../i18n'
import { useTheme } from '../context/ThemeContext'
import type { RootStackParamList } from '../navigation/RootNavigator'

type NavigationProp = NativeStackNavigationProp<RootStackParamList>
type Route = RouteProp<RootStackParamList, 'AgreementByType'>

/**
 * RN 端「协议(按类型当前版)」薄壳 — 对齐 web agreement/[type]:
 * 按路由 type 归一化后走 GET /api/agreements/current?type=… 取当前生效协议,
 * title/version/effectiveDate/正文渲染全部委托共享屏
 * `packages/app/src/features/agreement/AgreementScreen.tsx`;
 * 取不到当前版本时回退静态条款(与 web error/!data 分支同口径)。
 */
export function AgreementByTypeScreen() {
  const navigation = useNavigation<NavigationProp>()
  const { t } = useI18n()
  const { resolvedTheme } = useTheme()
  const route = useRoute<Route>()
  const apiType = normalizeAgreementType(route.params?.type ?? '')

  const [agreement, setAgreement] = useState<AgreementContentView | null>(null)
  const [loading, setLoading] = useState(true)

  const load = useCallback(async () => {
    setLoading(true)
    try {
      const res = await getCurrentAgreement(apiType as AgreementType)
      if (res.success && res.data) {
        setAgreement({
          title: res.data.title,
          content: res.data.content,
          version: res.data.version ?? null,
          effectiveDate: (res.data.effectiveDate as string | null | undefined) ?? null,
        })
      } else {
        setAgreement(null)
      }
    } catch {
      setAgreement(null)
    } finally {
      setLoading(false)
    }
  }, [apiType])

  useEffect(() => {
    void load()
  }, [load])

  return (
    <SharedAgreementScreen
      t={t}
      onBack={() => navigation.goBack()}
      colorScheme={resolvedTheme}
      agreement={agreement}
      loading={loading}
      fallbackTitle={t(agreementTitleKey(apiType))}
    />
  )
}

