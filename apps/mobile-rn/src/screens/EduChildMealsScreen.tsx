/**
 * 孩子餐食页(mobile-rn 端)—— 薄壳,复用通用控制台列表屏 ConsoleTableScreen
 * (children 子页批 #3,覆盖 web edu/parent/children/[childId]/meals,家长端收口件)。
 * 端点(与 web edu/parent/page.tsx 同源):
 *  - GET /api/edu-ai-management/parent/children/:childId/meals ⇒ { list: MealItem[] }
 */
import { useCallback, useEffect, useState } from 'react'
import {
  useNavigation,
  useRoute,
  type NavigationProp,
  type RouteProp,
} from '@react-navigation/native'
import { fetchApi } from '@ihui/api-client'
import { ConsoleTableScreen, type ConsoleColumn, type ConsoleRowView } from '@ihui/rn-app'
import { useI18n } from '../i18n'
import { useTheme } from '../context/ThemeContext'
import type { RootStackParamList } from '../navigation/RootNavigator'

interface MealItem {
  id: string
  date: string
  mealType: string
  dishName: string
  ingredients: string | null
  nutrition: string | null
}

function EduChildMealsScreen() {
  const { t } = useI18n()
  const { resolvedTheme } = useTheme()
  const navigation = useNavigation<NavigationProp<RootStackParamList>>()
  const route = useRoute<RouteProp<RootStackParamList, 'EduChildMeals'>>()
  const childId = route.params?.childId ?? ''
  const [rows, setRows] = useState<ConsoleRowView[]>([])
  const [loading, setLoading] = useState(true)
  const [error, setError] = useState<string | null>(null)

  const load = useCallback(async () => {
    if (!childId) return
    setLoading(true)
    setError(null)
    try {
      const res = await fetchApi<{ list: MealItem[] }>(
        `/api/edu-ai-management/parent/children/${childId}/meals`,
      )
      if (!res.success) throw new Error(res.error || 'load failed')
      setRows(
        (res.data?.list ?? []).map((m) => ({
          id: m.id,
          cells: {
            date: m.date?.slice(0, 10) ?? '',
            mealType: m.mealType,
            dish: m.dishName,
            ingredients: m.ingredients ?? '—',
            nutrition: m.nutrition ?? '—',
          },
        })),
      )
    } catch (e) {
      setError(e instanceof Error ? e.message : 'load failed')
    } finally {
      setLoading(false)
    }
  }, [childId])

  useEffect(() => {
    void load()
  }, [load])

  const columns: ConsoleColumn[] = [
    { key: 'date', title: t('eduChildMeals.date'), render: 'mono' },
    { key: 'mealType', title: t('eduChildMeals.mealType'), render: 'badge' },
    { key: 'dish', title: t('eduChildMeals.dish'), flex: 2 },
    { key: 'ingredients', title: t('eduChildMeals.ingredients'), flex: 2 },
    { key: 'nutrition', title: t('eduChildMeals.nutrition') },
  ]

  return (
    <ConsoleTableScreen
      t={t}
      colorScheme={resolvedTheme}
      onBack={() => navigation.goBack()}
      title={t('eduChildMeals.title')}
      columns={columns}
      rows={rows}
      loading={loading}
      error={error}
      onRetry={() => void load()}
      onRefresh={() => void load()}
    />
  )
}

export default EduChildMealsScreen
