import { useState } from 'react'
import { useTheme } from '../context/ThemeContext'
import { useNavigation, useRoute, type RouteProp } from '@react-navigation/native'
import type { NativeStackNavigationProp } from '@react-navigation/native-stack'
import { fetchApi } from '@ihui/api-client'
import { apiFailureToText } from '@ihui/shared/utils'
import { NoteCreateScreen as SharedNoteCreateScreen } from '@ihui/rn-app'
import { useI18n } from '../i18n'
import type { RootStackParamList } from '../navigation/RootNavigator'

type Route = RouteProp<RootStackParamList, 'NoteCreate'>
type NavigationProp = NativeStackNavigationProp<RootStackParamList>

export function NoteCreateScreen() {
  const { resolvedTheme } = useTheme()
  const { t } = useI18n()
  const route = useRoute<Route>()
  const navigation = useNavigation<NavigationProp>()
  const { courseId } = route.params ?? { courseId: '' }
  const [title, setTitle] = useState('')
  const [content, setContent] = useState('')
  const [tags, setTags] = useState('')
  const [isPublic, setIsPublic] = useState(false)
  const [saving, setSaving] = useState(false)
  const [error, setError] = useState('')

  const onSubmit = async () => {
    if (!title.trim() || !content.trim()) {
      setError(t('noteCreate.required'))
      return
    }
    setSaving(true)
    setError('')
    // 对齐 web 口径:笔记存于 edu_notes 表(web 学习页/笔记页同走 /api/edu/notes),
    // courseId 对应 edu 域的 lessonId(仅接受 uuid;tags 两域均不落库,丢弃无损)。
    const lessonId =
      courseId && /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i.test(courseId)
        ? courseId
        : undefined
    const res = await fetchApi<{ note: { id: string } }>('/api/edu/notes', {
      method: 'POST',
      body: JSON.stringify({
        title: title.trim(),
        content: content.trim(),
        lessonId,
        isPublic,
      }),
    })
    setSaving(false)
    // edu 域无单条详情 GET 端点(NoteDetail 仍读 notes 表),创建成功后回"我的笔记"列表
    if (res.success && res.data) navigation.replace('Note')
    else if (!res.success) setError(apiFailureToText(res, t('noteCreate.saveFailed')))
  }

  return (
    <SharedNoteCreateScreen
      t={t}
      title={title}
      content={content}
      tags={tags}
      isPublic={isPublic}
      saving={saving}
      error={error}
      onTitleChange={setTitle}
      onContentChange={setContent}
      onTagsChange={setTags}
      onTogglePublic={() => setIsPublic(!isPublic)}
      onSubmit={onSubmit}
      onBack={() => navigation.goBack()}
      colorScheme={resolvedTheme}
    />
  )
}
