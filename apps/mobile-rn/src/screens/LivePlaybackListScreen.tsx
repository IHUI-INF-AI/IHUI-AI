import { useCallback } from 'react'
import { useNavigation } from '@react-navigation/native'
import type { NativeStackNavigationProp } from '@react-navigation/native-stack'
import { fetchApi, type PageData } from '@ihui/api-client'
import {
  LivePlaybackListScreen as SharedLivePlaybackListScreen,
  type LivePlaybackItem,
} from '@ihui/rn-app'
import { usePaginatedList } from '../hooks'
import { useI18n } from '../i18n'
import { useTheme } from '../context/ThemeContext'
import type { RootStackParamList } from '../navigation/RootNavigator'

type NavigationProp = NativeStackNavigationProp<RootStackParamList>

const PAGE_SIZE = 20

/**
 * 直播回放列表屏 wrapper — 平台特定层
 *
 * 负责:useI18n 取 t、useTheme 取 resolvedTheme、useNavigation 取 navigation、
 * 分页数据层复用 shared 的 usePaginatedList,把依赖通过 props 注入共享组件。
 * 原实现无卡片点击跳转,onPressItem 传 no-op;现改为点击跳转对应直播详情页。
 */
export function LivePlaybackListScreen() {
  const { t } = useI18n()
  const { resolvedTheme } = useTheme()
  const navigation = useNavigation<NavigationProp>()

  // 后端 GET /live/history 回 success({ list, total, page, pageSize })(live.ts),
  // 所以走 usePaginatedList 的 total 支;本屏此前把整个信封当数组用 ⇒ 回放列表永远空。
  const fetcher = useCallback(
    async ({ page, pageSize }: { page: number; pageSize: number }) => {
      try {
        return await fetchApi<PageData<LivePlaybackItem>>(
          `/live/history?page=${page}&pageSize=${pageSize}`,
        )
      } catch {
        return { success: false as const, error: t('livePlaybackList.loadFailed') }
      }
    },
    [t],
  )
  const { items, loading, refreshing, loadingMore, error, refresh, loadMore } =
    usePaginatedList<LivePlaybackItem>(fetcher, PAGE_SIZE)

  return (
    <SharedLivePlaybackListScreen
      t={t}
      items={items}
      loading={loading}
      refreshing={refreshing}
      error={error}
      onRefresh={refresh}
      onEndReached={loadMore}
      loadingMore={loadingMore}
      onPressItem={(item) => {
        // 点击回放卡片跳转对应直播详情页(/live/history 返回已结束直播,详情页展示「已结束」状态)
        navigation.navigate('LiveDetail', { id: item.id })
      }}
      onBack={() => navigation.goBack()}
      colorScheme={resolvedTheme}
    />
  )
}
