/**
 * RN 弹层 / 限高容器高度统一接线口。
 *
 * 把「取屏高 -> 交给 dialog-geometry 产出确定尺寸」收在一个 hook 里:
 * 消费文件只需一行 useDialogHeightStyle(比例) 或 useDialogMaxHeightStyle(比例),
 * 不必各自 import useWindowDimensions / useMemo,也不会再把比例或百分比上限抄回 StyleSheet。
 * 数值与边界仍在 lib/dialog-geometry.ts。
 *
 * 用 useWindowDimensions 而非 Dimensions.get:旋转/分屏后屏高会变,模块级常量不会跟着变。
 */
import { useWindowDimensions } from 'react-native'
import {
  DIALOG_MAX_HEIGHT_RATIO,
  dialogContentHeightStyle,
  dialogMaxHeightStyle,
  type DialogHeightRatio,
} from './dialog-geometry'

/** 有滚动列表的弹层:固定高度 + 上限配对,给子节点确定测量边界 */
export function useDialogHeightStyle(ratio: DialogHeightRatio = DIALOG_MAX_HEIGHT_RATIO) {
  const { height: windowHeight } = useWindowDimensions()
  return dialogContentHeightStyle(windowHeight, ratio)
}

/** 短内容 sheet / 页内限高区:仅数值上限,内容少时仍自适应 */
export function useDialogMaxHeightStyle(ratio: DialogHeightRatio = DIALOG_MAX_HEIGHT_RATIO) {
  const { height: windowHeight } = useWindowDimensions()
  return dialogMaxHeightStyle(windowHeight, ratio)
}
