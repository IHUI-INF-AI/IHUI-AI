/**
 * RN 弹层高度统一接线口。
 *
 * 把「取屏高 -> 交给 dialog-geometry 产出 {height,maxHeight}」收在一个 hook 里:
 * 消费文件只需一行 useDialogHeightStyle(),不必各自 import useWindowDimensions / useMemo,
 * 也不会再把比例或百分比上限抄回 StyleSheet。数值与边界仍在 lib/dialog-geometry.ts。
 *
 * 用 useWindowDimensions 而非 Dimensions.get:旋转/分屏后屏高会变,模块级常量不会跟着变。
 */
import { useWindowDimensions } from 'react-native'
import { dialogContentHeightStyle } from './dialog-geometry'

export function useDialogHeightStyle() {
  const { height: windowHeight } = useWindowDimensions()
  return dialogContentHeightStyle(windowHeight)
}
