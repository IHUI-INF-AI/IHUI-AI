/**
 * 一次性 sso_code 的「同一枚 code 只换一次」出口。
 *
 * 为什么要单独成文件:同一个 code 在 RN 侧有三个并发消费者
 * (冷启动 getInitialSsoCode / 已运行时 subscribeSsoDeepLink / 登录页按钮的 openSsoLogin 返回值),
 * 而服务端 auth-sso.ts 的 code 是一次性(GET+DEL)。竞争时只有一路拿得到令牌,另一路拿到"code 失效"
 * 并把登录页停在原地 —— 令牌其实已经写进 store 了。判据放在 AuthProvider 里就得渲染整屏才能测,
 * 所以判定单独住这里,由宿主注入 exchange 与落库回调。
 */

const inFlight = new Map<string, Promise<boolean>>()
const settled = new Map<string, boolean>()

/** 与 sso_code 的服务端 TTL 同源:结论只需活过这一轮竞争。 */
const SETTLED_TTL_MS = 30_000

export async function exchangeSsoCodeOnce<T>(
  code: string,
  exchange: (code: string) => Promise<T | null>,
  onToken: (data: T) => Promise<void>,
): Promise<boolean> {
  const done = settled.get(code)
  if (done !== undefined) return done

  const pending = inFlight.get(code)
  if (pending) return pending

  const task = (async () => {
    const data = await exchange(code)
    if (!data) return false
    await onToken(data)
    return true
  })().finally(() => {
    inFlight.delete(code)
  })

  inFlight.set(code, task)
  const result = await task
  settled.set(code, result)
  const timer = setTimeout(() => settled.delete(code), SETTLED_TTL_MS)
  if (typeof timer.unref === 'function') timer.unref()
  return result
}

/** 测试出口:清掉进程内状态,避免用例间互相顶账。 */
export function resetSsoCodeOnceState(): void {
  inFlight.clear()
  settled.clear()
}
