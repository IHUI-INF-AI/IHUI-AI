/**
 * 后端静态素材路径 → RN 可渲染 URL。
 *
 * 后端 `agents.avatar` 等字段常返回站内相对路径（如 `/agents/coze/x.webp`）。
 * 浏览器会按页面 origin 自动解析，但 RN `<Image source={{ uri }}>` 只接受绝对 URL：
 * 直接传相对路径时图片静默为空，形成「白块」；`resolveFileUrl` 又会补 `/api`
 * （`/api/agents/coze/...` 实测 404），同样不可用。
 *
 * 唯一正解是拼到 Web 站点底座（静态资源由站点根直出），且绝对 URL / data: 原样透传。
 * 路径拼接复用共享 `joinUrl`，不在端内重写规则。
 */
import { joinUrl } from '@ihui/shared/utils/image-helpers'
import { WEB_BASE_URL } from './webview-portal-config'

export function resolveWebAssetUrl(path?: string | null): string | undefined {
  const raw = path?.trim()
  if (!raw) return undefined
  return joinUrl(WEB_BASE_URL, raw)
}
