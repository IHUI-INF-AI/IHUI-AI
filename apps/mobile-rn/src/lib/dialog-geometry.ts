/**
 * RN 弹层内容高度的单一真相源(mobile-rn 端)。
 *
 * RN 0.86 Fabric 下,StyleSheet 里的百分比 maxHeight 不会给子节点一个确定高度:
 * 内部 ScrollView / FlatList 拿不到可测量的边界 ⇒ 列表无法滚动,配合 overflow:'hidden'
 * 还会把底部内容直接裁掉。ChatScreen 此前只在「模型列表」一处补了确定高度,而比例
 * 与样式表里的百分比上限各写一份、靠人工同步 —— 改一处忘另一处就会出现
 * 「确定 height 与百分比上限不一致」的截断。
 *
 * 现在:比例只在本文件定义一次;height 与 maxHeight 由同一个函数成对产出;
 * 所有弹层统一消费 dialogContentHeightStyle(),样式表里不再出现百分比上限。
 */
export const DIALOG_MAX_HEIGHT_RATIO = 0.7

/** 纯函数,不依赖 React Native 运行时,便于直接单测 */
export function dialogContentHeight(windowHeight: number): number {
  return Math.round(windowHeight * DIALOG_MAX_HEIGHT_RATIO)
}

/**
 * 成对产出 height/maxHeight。两者恒等,杜绝「两处数值不一致 ⇒ overflow 截断」。
 * 取不到有效屏高时返回 null:style 数组里的 falsy 项被 RN 忽略,弹层退回自然高度,
 * 不会塌成 0 高。
 */
export function dialogContentHeightStyle(
  windowHeight: number,
): { height: number; maxHeight: number } | null {
  if (!Number.isFinite(windowHeight) || windowHeight <= 0) return null
  const height = dialogContentHeight(windowHeight)
  return { height, maxHeight: height }
}
