/**
 * 日期时间的统一格式化出口。
 *
 * AGENTS.md 强制规范:时间一律走 `Intl.DateTimeFormat`,不手拼字符串、不硬编码 locale。
 * locale 取 i18n 模块镜像(`getCurrentLocale()`),跟随应用当前语言 —— 早期版本直接写死
 * `'zh-CN'`,英文/日文用户在活动、自动化、巡检等屏看到的仍是中文格式。
 *
 * 解析失败(空串/非法时间)一律回退原值,避免把 `Invalid Date` 渲染到用户脸上。
 *
 * 现状说明:仓内 `automation/AutomationCard`、`UserInfoCard`、`AutomationsScreen`、
 * `PatrolScreen` 仍各自保留同名实现(同一件事写了四份)。把它们一起迁到本文件属于独立票,
 * 本次只在活动链路引入本文件、不搬别人的家,避免把一次页面修复扩散成跨屏回归。
 */
import { getCurrentLocale } from '../i18n'

export function formatDateTime(value: string | null | undefined): string {
  if (value === null || value === undefined || value === '') return ''
  try {
    const d = new Date(value)
    if (Number.isNaN(d.getTime())) return value
    return new Intl.DateTimeFormat(getCurrentLocale(), {
      year: 'numeric',
      month: '2-digit',
      day: '2-digit',
      hour: '2-digit',
      minute: '2-digit',
      hour12: false,
    }).format(d)
  } catch {
    return value
  }
}
