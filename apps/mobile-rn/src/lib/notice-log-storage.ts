/**
 * 对话内「提示留痕」的 RN 存储适配器(2026-11 立)。
 *
 * 职责单一:把 shared 的 `NoticeLogStorage` 契约接到 `@react-native-async-storage/async-storage`。
 * 键名/编解码/去重/上限全部在 `@ihui/shared/chat/notice-log` —— 本文件**不含任何业务规则**,
 * 这样 web(localStorage)与本端(AsyncStorage)共用同一份行为契约,不会各漂一套。
 *
 * 为什么不直接把 AsyncStorage 传给 shared:shared 不能依赖原生模块(小程序/Node 侧一 import 就炸),
 * 故契约留在 shared、实现留在各端。
 */
import AsyncStorage from '@react-native-async-storage/async-storage'
import type { NoticeLogStorage } from '@ihui/shared/chat/notice-log'

export const noticeLogStorage: NoticeLogStorage = {
  getItem: (key) => AsyncStorage.getItem(key),
  setItem: (key, value) => AsyncStorage.setItem(key, value),
  removeItem: (key) => AsyncStorage.removeItem(key),
}
