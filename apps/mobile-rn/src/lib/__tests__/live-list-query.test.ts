import { describe, expect, it } from 'vitest'
import { buildLiveListQuery, LIVE_LIST_TABS } from '../live-list-query'
import type { LiveListTab } from '@ihui/rn-app'

const q = (tab: LiveListTab) => buildLiveListQuery(tab, 1, 20)

describe('直播列表 tab → /live/list 查询串', () => {
  it('all: 只发分页,不发阶段/启用位', () => {
    expect(q('all')).toBe('page=1&pageSize=20')
  })

  it('upcoming: 该端点恒 publishedOnly=true 打不到,不发非法参数', () => {
    // upcoming = 未发布;`/live/list` 恒 publishedOnly ⇒ 行集为空,故 tab 不下发(与小程序三档一致)
    expect(q('upcoming')).toBe('page=1&pageSize=20')
  })

  it('ongoing: 语义键 isLive=true', () => {
    expect(q('ongoing')).toBe('page=1&pageSize=20&isLive=true')
  })

  it('ended: 语义键 isLive=false', () => {
    expect(q('ended')).toBe('page=1&pageSize=20&isLive=false')
  })

  it('阴性对照:任何 tab 都不得出现 status=,否则即回到 400 老路', () => {
    for (const tab of ['all', 'upcoming', 'ongoing', 'ended'] as LiveListTab[]) {
      expect(q(tab)).not.toContain('status=')
    }
    // 直传 tab 字符串(旧实现)必然带 status=,上面的不变量会立即转红
    const naive = new URLSearchParams({ status: 'ongoing' }).toString()
    expect(naive).toContain('status=ongoing')
  })

  it('tab 集合收敛为三档', () => {
    expect(LIVE_LIST_TABS).toEqual(['all', 'ongoing', 'ended'])
  })
})
