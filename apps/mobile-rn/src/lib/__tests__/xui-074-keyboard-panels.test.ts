/**
 * XUI-074:小屏 + 键盘弹出时,审批卡片与标注输入行必须可滚动/避让。
 * 旧码:ToolApprovalSheet 的卡片无 maxHeight、无 ScrollView;ImageAnnotator 的
 * autoFocus 输入行裸放在全屏 Modal,键盘一弹就遮住输入框。
 */
import { readFileSync } from 'node:fs'
import { join } from 'node:path'
import { describe, expect, it } from 'vitest'

const APP_ROOT = join(__dirname, '..', '..', '..')
const read = (p: string) => readFileSync(join(APP_ROOT, p), 'utf8')

describe('XUI-074:审批卡片与标注输入行的键盘/高度处理', () => {
  it('ToolApprovalSheet 卡片有 maxHeight 且整卡可滚动', () => {
    const src = read('src/components/ai/ToolApprovalSheet.tsx')
    expect(src).toContain('ScrollView')
    expect(src).toContain('KeyboardAvoidingView')
    expect(src).toMatch(/maxHeight:\s*'85%'/)
    expect(src).toMatch(/contentContainerStyle=\{styles\.cardContent\}/)
    expect(src).toContain('keyboardShouldPersistTaps="handled"')
  })

  it('ToolApprovalSheet 的 padding/gap 落在滚动内容层而非卡片外壳', () => {
    const src = read('src/components/ai/ToolApprovalSheet.tsx')
    const card = src.match(/card:\s*\{[\s\S]*?\n {2}\}/)
    const content = src.match(/cardContent:\s*\{([\s\S]*?)\n {2}\}/)
    expect(card?.[0]).not.toMatch(/padding:\s*rpx\(32\)/)
    expect(content?.[1]).toContain('padding: rpx(32)')
    expect(content?.[1]).toContain('gap: rpx(16)')
  })

  it('ImageAnnotator 根容器改用 KeyboardAvoidingView(保留 autoFocus 输入行)', () => {
    const src = read('src/components/chat/ImageAnnotator.tsx')
    expect(src).toContain('<KeyboardAvoidingView')
    expect(src).toContain("behavior={Platform.OS === 'ios' ? 'padding' : undefined}")
    expect(src).not.toMatch(/<View style=\{styles\.root\}>/)
    expect(src).toContain('autoFocus')
  })
})
