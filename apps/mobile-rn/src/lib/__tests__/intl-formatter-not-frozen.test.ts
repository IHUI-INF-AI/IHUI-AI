/**
 * XUI-061:模块级 `new Intl.DateTimeFormat()` 会在加载时冻结默认时区/语言,
 * 用户切时区后仍按旧值渲染。本夹具钉住「按调用时创建」。
 */
import { readFileSync } from 'node:fs'
import { join } from 'node:path'
import { describe, expect, it } from 'vitest'

const APP_ROOT = join(__dirname, '..', '..', '..')
const read = (p: string) => readFileSync(join(APP_ROOT, p), 'utf8')

describe('XUI-061:不再复用模块级 Intl 实例', () => {
  it('WorkflowsScreen 的 formatNextRun 按调用时创建', () => {
    const src = read('src/screens/WorkflowsScreen.tsx')
    expect(src).not.toMatch(/const dateTimeFormat = new Intl\./)
    expect(src).toContain('return new Intl.DateTimeFormat().format(d)')
  })

  it('letter-time 仍是刻意的固定 zh-CN(不算本条)', () => {
    const src = read('src/utils/letter-time.ts')
    expect(src).toContain("new Intl.DateTimeFormat('zh-CN'")
  })
})
