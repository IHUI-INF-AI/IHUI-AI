/**
 * XUI-068:登录页「忘记密码」原先跳 `ChangePwd`(需要旧密码),未登录用户永远走不出去 ⇒ 成环。
 * 处置:复用 web 已有的找回密码页(`/forgot-password`),RN 用通用 `WebView` 承载;
 * 改密屏的「忘记旧密码」入口也指同一处,不再兜圈。
 */
import { readFileSync } from 'node:fs'
import { join } from 'node:path'
import { describe, expect, it } from 'vitest'

const APP_ROOT = join(__dirname, '..', '..', '..')
const read = (p: string) => readFileSync(join(APP_ROOT, p), 'utf8')

describe('XUI-068 RN 忘记密码复用 web 找回页', () => {
  it('登录页忘记密码走 WebView(/forgot-password),不再跳改密屏', () => {
    const src = read('src/screens/LoginScreen.tsx')
    const start = src.indexOf('const handleForgotPassword')
    const end = src.indexOf('const handleRegister')
    const handler = src.slice(start, end)
    expect(handler).toContain("navigate('WebView'")
    expect(handler).toContain('/forgot-password')
    expect(handler).not.toContain("navigate('ChangePwd'")
    expect(src).not.toContain("navigation.navigate('ChangePwd')")
    expect(src).toContain("from '../lib/webview-portal-config'")
  })

  it('改密屏「忘记旧密码」指向同一找回页', () => {
    const src = read('src/screens/ChangePwdScreen.tsx')
    expect(src).toContain('onForgotOld={handleForgotOld}')
    expect(src).toContain("forgotLabel={t('auth.forgotPassword')}")
    const start = src.indexOf('const handleForgotOld')
    expect(start).toBeGreaterThan(-1)
    const handler = src.slice(start, start + 220)
    expect(handler).toContain("navigate('WebView'")
    expect(handler).toContain('/forgot-password')
  })

  it('未登录分支也注册 WebView(否则 navigate 到未注册路由直接崩)', () => {
    const nav = read('src/navigation/RootNavigator.tsx')
    const count = nav.match(/name="WebView"/g)?.length ?? 0
    expect(count).toBe(2)
  })
})
