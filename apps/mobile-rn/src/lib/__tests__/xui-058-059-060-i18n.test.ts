// XUI-058 / XUI-060 / XUI-059: mobile-rn 直接 import 源 JSON,缺 key 会回退原始点路径文案。
import { readFileSync } from 'node:fs'
import { join } from 'node:path'
import { describe, expect, it } from 'vitest'

const LOCALES = ['zh-CN', 'en', 'ja', 'ko', 'zh-TW'] as const
const read = (app: string, locale: string) =>
  JSON.parse(readFileSync(join(process.cwd(), '..', '..', 'packages', 'i18n', 'messages', app, `${locale}.json`), 'utf8')) as Record<string, any>

describe('XUI-058/XUI-060/XUI-059 mobile-rn i18n key 补齐', () => {
  it('订单页 order.pay 五语齐全', () => {
    for (const l of LOCALES) expect(read('mobile-rn', l).order?.pay, `order.pay@${l}`).toBeTruthy()
  })

  it('登录页 login.platformLinuxdo 五语齐全', () => {
    for (const l of LOCALES) expect(read('mobile-rn', l).login?.platformLinuxdo, `platformLinuxdo@${l}`).toBeTruthy()
  })

  it('artifacts 命名空间与 web 对齐(共享屏用到的 key 不得在 RN 回落原文)', () => {
    const webKeys = Object.keys(read('web', 'zh-CN').artifacts ?? {})
    expect(webKeys.length).toBeGreaterThan(20)
    for (const l of LOCALES) {
      const rn = read('mobile-rn', l).artifacts ?? {}
      const missing = webKeys.filter((k) => rn[k] === undefined)
      expect(missing, `artifacts missing @${l}`).toEqual([])
    }
  })
})
