/**
 * WebView 站内后退判据(2026-11-23 立)。
 *
 * 管理后台分类页是 Web 承载:`/domains/admin` → 某个分类页 → 再点分类,都是站内 push。
 * 原先头部返回键与安卓返回键一律关掉整个 WebView,用户点进两层后只能"退出重进"。
 * 直接启用 `canGoBack` 又不行:SSO 初始链(`/sso/mobile-auth` → 目标页)也在历史里,
 * 后退会回到已被消费的一次性会话页。
 *
 * 判据因此不靠"有没有历史",只看**当前页与上一页是否都在管理端路径内**:
 * SSO 初始链的上一页是 `/sso/mobile-auth`,天然不命中;真正站内下钻才命中。
 * 纯函数、无 IO,便于单测钉住;不承担鉴权,越权仍由 Web/后端判。
 */
export function isAdminConsoleUrl(raw: string, baseUrl: string): boolean {
  try {
    const target = new URL(raw)
    const base = new URL(baseUrl)
    if (target.origin !== base.origin) return false
    return (
      target.pathname === '/domains/admin' ||
      target.pathname.startsWith('/domains/') ||
      target.pathname === '/admin' ||
      target.pathname.startsWith('/admin/')
    )
  } catch {
    return false
  }
}

/**
 * 是否允许站内后退:历史至少两页,且当前页与上一页都是管理端路径。
 * 只回退一格;每次按键重新判,回到根页后自然失效并交回"关闭整页"。
 */
export function canStepBackInAdminHistory(history: readonly string[], baseUrl: string): boolean {
  if (history.length < 2) return false
  const current = history[history.length - 1]
  const previous = history[history.length - 2]
  if (!current || !previous) return false
  return isAdminConsoleUrl(current, baseUrl) && isAdminConsoleUrl(previous, baseUrl)
}
