import { readFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { describe, expect, it } from 'vitest'

/**
 * 「我的」页只允许一张带昵称的用户卡。
 *
 * 立因:本页曾是迁移半成品 —— 本地 UserInfoCard + UserCard 四宫格与共享 ProfileScreen 同屏,
 * 两个昵称上下叠在一起。共享屏成为唯一用户卡后,本端独有能力只经 userExtra / children 注入;
 * 若将来有人把旧栈加回来,这条用例先红。
 */
const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..', '..')
const SOURCE = readFileSync(resolve(ROOT, 'apps/mobile-rn/src/screens/ProfileScreen.tsx'), 'utf8')

describe('「我的」页用户卡唯一性', () => {
  it('不再挂载本地 UserInfoCard / UserCard 四宫格', () => {
    expect(SOURCE).not.toMatch(/<UserInfoCard\b/)
    expect(SOURCE).not.toMatch(/<UserCard\b/)
    expect(SOURCE).not.toMatch(/from '\.\.\/components\/UserInfoCard'/)
    expect(SOURCE).not.toMatch(/from '\.\.\/components\/UserCard'/)
  })

  it('共享 ProfileScreen 只出现一次,并承载账户动作与内容插槽', () => {
    expect(SOURCE.match(/<SharedProfileScreen\b/g)).toHaveLength(1)
    expect(SOURCE).toMatch(/userExtra=\{/)
    expect(SOURCE).toMatch(/<ProfileContentSection \/>/)
    expect(SOURCE).toMatch(/<UserMembershipBenefits\b/)
  })
})
