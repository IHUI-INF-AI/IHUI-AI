// D34/D106 第 45 轮:mobile-rn 此前对 injection_applied 帧 0 命中(整条回答带了哪些上下文
// 只有 web 用户看得到)。这里锁住两条最容易在后续重构里丢的性质:追加不被覆盖、重复帧不产生重复行。
import { describe, expect, it } from 'vitest'

import { applyInjectionFrame, type MessageInjection } from '../src/utils/chat-render-model'

const base: MessageInjection = {
  kind: 'workspace_memory',
  collapsed: '工作区记忆 3 条',
}

describe('applyInjectionFrame(D34 承接)', () => {
  it('undefined 起点 → 单条', () => {
    expect(applyInjectionFrame(undefined, base)).toEqual([
      {
        kind: 'workspace_memory',
        collapsed: '工作区记忆 3 条',
        fullText: undefined,
        count: undefined,
      },
    ])
  })

  it('不同 kind 追加(流首与流中两批不得互相覆盖)', () => {
    const once = applyInjectionFrame(undefined, base)
    const twice = applyInjectionFrame(once, {
      kind: 'auto_context',
      collapsed: '带入了 5 段上下文',
      count: 5,
    })
    expect(twice.map((x) => x.kind)).toEqual(['workspace_memory', 'auto_context'])
    expect(twice[1]?.count).toBe(5)
  })

  it('同 kind 同 collapsed 的重复帧不产生第二行', () => {
    const once = applyInjectionFrame(undefined, base)
    expect(applyInjectionFrame(once, { ...base, fullText: '重复' })).toHaveLength(1)
  })

  it('同 kind 不同 collapsed 视为两条(不同批次的交代)', () => {
    const once = applyInjectionFrame(undefined, base)
    expect(applyInjectionFrame(once, { ...base, collapsed: '工作区记忆 4 条' })).toHaveLength(2)
  })
})
