import { describe, expect, it } from 'vitest'
import { isMaxTokensTruncatedFinishReason } from '@ihui/shared/utils/finish-reason'

import en from '@ihui/i18n/messages/mobile-rn/en.json'
import ja from '@ihui/i18n/messages/mobile-rn/ja.json'
import ko from '@ihui/i18n/messages/mobile-rn/ko.json'
import zhCN from '@ihui/i18n/messages/mobile-rn/zh-CN.json'
import zhTW from '@ihui/i18n/messages/mobile-rn/zh-TW.json'

/**
 * G-425 mobile-rn 腿:done 帧 finishReason 截断提示。
 *
 * ① 判定走共享层唯一助手(与 web / extension 同一份,端内不留判据副本);
 * ② 提示词五语言齐备 —— 否则 ChatScreen 的 FloatBox 会弹出一个键名。
 * 接线点(streamChat 回调表的 onFinishReason)由守门 90 的注册对账钉住。
 */
describe('G-425 mobile-rn 截断提示', () => {
  it('判定助手来自共享层且口径与 web 一致', () => {
    expect(isMaxTokensTruncatedFinishReason('length')).toBe(true)
    expect(isMaxTokensTruncatedFinishReason('Max_Tokens')).toBe(true)
    expect(isMaxTokensTruncatedFinishReason('tool_calls')).toBe(false)
    expect(isMaxTokensTruncatedFinishReason(null)).toBe(false)
  })

  const locales: Array<[string, { chat: Record<string, unknown> }]> = [
    ['zh-CN', zhCN],
    ['zh-TW', zhTW],
    ['en', en],
    ['ja', ja],
    ['ko', ko],
  ]

  for (const [lang, bundle] of locales) {
    it(`${lang} chat.truncation.maxLengthNotice 有非空译文`, () => {
      const truncation = bundle.chat.truncation as Record<string, string> | undefined
      const text = truncation?.maxLengthNotice
      expect(typeof text).toBe('string')
      expect((text ?? '').trim().length).toBeGreaterThan(0)
    })
  }
})
