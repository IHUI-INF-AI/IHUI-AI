import { readFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { describe, expect, it } from 'vitest'

/**
 * 「全部功能」页必须继续作为长尾入口的唯一收口页存在:
 * 首页只留九宫格高频入口,若该页/路由被删,订单、学习等低频功能会重新无处可去。
 */
const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..', '..')
const SCREEN = readFileSync(
  resolve(ROOT, 'apps/mobile-rn/src/screens/ProfileAllFunctionsScreen.tsx'),
  'utf8',
)
const NAVIGATOR = readFileSync(
  resolve(ROOT, 'apps/mobile-rn/src/navigation/RootNavigator.tsx'),
  'utf8',
)

describe('「全部功能」页与路由', () => {
  it('只读 profileMenuData 的菜单全集,并提供搜索与折叠', () => {
    expect(SCREEN).toMatch(/from '\.\/profileMenuData'/)
    expect(SCREEN).toMatch(/MENU_SECTIONS/)
    expect(SCREEN).toMatch(/profile\.searchFunctions/)
    expect(SCREEN).toMatch(/profile\.noFunctionsFound/)
    expect(SCREEN).toMatch(/setExpanded/)
  })

  it('RootStack 注册了 ProfileAllFunctions', () => {
    expect(NAVIGATOR).toMatch(/ProfileAllFunctions: undefined/)
    expect(NAVIGATOR).toMatch(/name="ProfileAllFunctions"/)
  })
})
