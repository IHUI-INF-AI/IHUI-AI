// FloatBox 的出口守卫:空白文案不得渲成"只有图标、没有文字"的深色方块。
// 真机在「我的」tab 拍到过一枚只有橙色警告三角的方块(截图 crop-toast.png)。
// 这里只测**判据本身**(纯函数),不测 RN 渲染 —— 渲染面依赖 react-test-renderer,
// 而缺陷的成因与修复都在这一个谓词里;把谓词测准,比挂一层脆弱的渲染快照更有价值。
import { describe, expect, it } from 'vitest'

import { floatBoxShouldShow } from '../src/components/FloatBox'

describe('floatBoxShouldShow', () => {
  it('缺陷面:空白文案(空格/制表/换行)一律不出图', () => {
    for (const blank of [' ', '   ', '\t', '\n', ' \n ']) {
      expect(floatBoxShouldShow(true, blank), `实得:${JSON.stringify(blank)}`).toBe(false)
    }
  })

  it('阳性对照:真文案必须照常出图(否则守卫变成"永远不显示")', () => {
    expect(floatBoxShouldShow(true, '登录已过期,请重新登录')).toBe(true)
    expect(floatBoxShouldShow(true, '0')).toBe(true)
  })

  it('visible=false 时不得出图,与文案无关', () => {
    expect(floatBoxShouldShow(false, '有文案')).toBe(false)
    expect(floatBoxShouldShow(false, '')).toBe(false)
  })

  it('非字符串(调用方传进 undefined/null)按"不出图"处理而不是崩', () => {
    expect(floatBoxShouldShow(true, undefined as unknown as string)).toBe(false)
    expect(floatBoxShouldShow(true, null as unknown as string)).toBe(false)
  })
})
