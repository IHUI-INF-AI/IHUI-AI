// RN 端终端截断交代(D40 跨端):applyTerminalEnd 必须把 truncated / totalChars 带进视图项,
// 否则 RN 界面上"被截断的输出"与"完整输出"完全无法区分(该端没有 live 输出缓冲可比对)。
import { describe, expect, it } from 'vitest'

import type { TerminalEndEvent } from '@ihui/types'

import { applyTerminalEnd, type TerminalTaskItem } from '../src/utils/chat-render-model'

const base = {
  id: 't1',
  command: 'pnpm build',
  status: 'running',
  startedAtMs: 1_700_000_000_000,
} satisfies TerminalTaskItem

function endEvent(over: Partial<TerminalEndEvent>): TerminalEndEvent {
  return {
    type: 'terminal_end',
    terminalId: 't1',
    status: 'completed',
    endedAt: '2026-09-22T00:00:05.000Z',
    durationMs: 5000,
    ...over,
  } as TerminalEndEvent
}

describe('RN 终端截断交代透传(D40 跨端)', () => {
  it('截断标志与原始长度必须进入视图项', () => {
    const [item] = applyTerminalEnd(
      [base],
      endEvent({ output: 'x'.repeat(8000), truncated: true, totalChars: 42000 }),
    )
    expect(item?.truncated).toBe(true)
    expect(item?.totalChars).toBe(42000)
  })

  it('未截断时不得凭空造出标志', () => {
    const [item] = applyTerminalEnd([base], endEvent({ output: 'ok' }))
    expect(item?.truncated).toBeUndefined()
    expect(item?.totalChars).toBeUndefined()
  })

  it('结束帧缺字段时保留既有值,不覆盖成 undefined', () => {
    const carried: TerminalTaskItem = { ...base, truncated: true, totalChars: 99999 }
    const [item] = applyTerminalEnd([carried], endEvent({ output: 'later' }))
    expect(item?.truncated).toBe(true)
    expect(item?.totalChars).toBe(99999)
  })
})
