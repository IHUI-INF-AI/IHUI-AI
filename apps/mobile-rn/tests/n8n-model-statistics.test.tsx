// showStatistics 两格运行时对照:共享屏缺省(true)必须渲染计数两行(真 0 也要可见);
// 显式 false 时两行不渲染、updatedAt 仍常显。取材直连共享层源码(不测替身)。
import { render } from '@testing-library/react'
import { describe, expect, it } from 'vitest'
import type { N8nModelItem } from '../../../packages/types/src/app-ai'
import { N8nModelScreen } from '../../../packages/app/src/features/n8n-model/N8nModelScreen'

const t = (key: string) => key

const items: N8nModelItem[] = [
  {
    id: 'w1',
    name: 'Model A',
    desc: 'desc',
    url: 'https://example.com/hook',
    status: 'running',
    calls: 0,
    updatedAt: '2026-11-06 03:00',
    paramsIn: 0,
    paramsOut: 0,
  },
]

const baseProps = {
  t,
  items,
  tab: 'all' as const,
  keyword: '',
  loading: false,
  refreshing: false,
  error: '',
  onSelectTab: () => {},
  onKeywordChange: () => {},
  onRefresh: () => {},
  onRetry: () => {},
  onToggle: () => {},
  onEdit: () => {},
  onCreate: () => {},
  onBack: () => {},
  colorScheme: 'light' as const,
}

describe('N8nModelScreen showStatistics 闸(运行时两格)', () => {
  it('缺省(不传)= true:计数两行渲染,真 0 也可见', () => {
    const { container } = render(<N8nModelScreen {...baseProps} />)
    expect(container.textContent).toContain('n8nModel.calls')
    expect(container.textContent).toContain('n8nModel.params')
  })

  it('显式 false:计数两行整段不渲染,updatedAt 仍常显', () => {
    const { container } = render(<N8nModelScreen {...baseProps} showStatistics={false} />)
    expect(container.textContent).not.toContain('n8nModel.calls')
    expect(container.textContent).not.toContain('n8nModel.params')
    expect(container.textContent).toContain('2026-11-06 03:00')
  })
})
