/**
 * AutoInstallGuide 钩子顺序回归锁(2026-11-06 真机事故)。
 *
 * 事故形态:两个 `React.useCallback` 写在 `if (!visible) return null` **之后** —— 首帧
 * visible=false 只跑 2 个 hook,异步置 true 的那一帧要跑 4 个,React 直接抛
 * "Rendered more hooks than during the previous render";expo-updates 把它记成启动崩溃并回滚,
 * 用户看到的是"打开就闪退"。修复后再发 OTA 才恢复。
 *
 * 为什么用静态顺序而不是渲染级用例:要真渲染这个卡片得拖进整套 RN 替身(AsyncStorage /
 * lucide / @ihui/ui-native),成本高且判据仍是"hook 数与帧序"这件事 —— 直接对源码数位置更稳。
 * 注意源码注释里也写了这句早退(解释为什么必须提前),所以取**最后一次**出现 = 真正的语句。
 */

import { readFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

import { describe, expect, it } from 'vitest'

describe('AutoInstallGuide 钩子顺序', () => {
  it('所有 React.useXxx( 都必须在 `if (!visible) return null` 之前声明', () => {
    const file = join(
      dirname(fileURLToPath(import.meta.url)),
      '..',
      'src',
      'components',
      'AutoInstallGuide.tsx',
    )
    const src = readFileSync(file, 'utf8')

    // 注释里也出现了同一句,取最后一次出现才是真语句
    const earlyReturn = src.lastIndexOf('if (!visible) return null')
    expect(earlyReturn, '源码里找不到早退语句 ⇒ 判据已失效,需同步更新本用例').toBeGreaterThan(-1)

    const hookCalls = [...src.matchAll(/React\.use(?:Callback|State|Effect|Memo|Ref)\s*\(/g)].map(
      (m) => m.index ?? -1,
    )
    expect(hookCalls.length, '一个 hook 都没匹配到 ⇒ 判据已失效').toBeGreaterThan(0)

    expect(
      Math.max(...hookCalls),
      '有 hook 声明在 visible 早退之后 ⇒ 首帧与可见帧 hook 数不同,真机必抛 Rendered more hooks',
    ).toBeLessThan(earlyReturn)
  })
})
