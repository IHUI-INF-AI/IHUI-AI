import { readFileSync } from 'node:fs'
import { join } from 'node:path'
import { describe, expect, it } from 'vitest'

import { buildSharePayload } from '../src/screens/share-payload'

const SHARE_SCREEN = readFileSync(
  join(__dirname, '..', 'src', 'screens', 'ShareScreen.tsx'),
  'utf8',
)

describe('XUI-045 RN 分享:图片 URI 不得混进文本消息', () => {
  it('有图片 ⇒ URI 走 url 字段,message 不含 file://', () => {
    const payload = buildSharePayload({
      remark: '看这个',
      voiceText: '',
      imageUri: 'file:///tmp/a.png',
      fallback: '默认文案',
    })
    expect(payload).toEqual({ message: '看这个', url: 'file:///tmp/a.png' })
    expect(payload.message).not.toContain('file://')
  })

  it('纯文本 ⇒ 不产生 url(阴性对照)', () => {
    const payload = buildSharePayload({
      remark: '',
      voiceText: '语音转写',
      imageUri: null,
      fallback: '默认文案',
    })
    expect(payload).toEqual({ message: '语音转写' })
  })

  it('只有图片 ⇒ message 用兜底文案,不出现原始 URI', () => {
    const payload = buildSharePayload({
      remark: '',
      voiceText: '',
      imageUri: 'file:///tmp/a.png',
      fallback: '默认文案',
    })
    expect(payload.message).toBe('默认文案')
    expect(payload.url).toBe('file:///tmp/a.png')
  })

  it('ShareScreen 用 payload 展开调用 Share.share,不再手工拼 imageUri', () => {
    expect(SHARE_SCREEN).toContain('...payload')
    expect(SHARE_SCREEN).not.toContain('[remark, voiceText, imageUri]')
  })
})
