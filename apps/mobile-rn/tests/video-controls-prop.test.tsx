// 门 285 B 组:VideoPlayer.controls 由「仅小程序声明」收口为两端真实现。
// 断言传 controls 时真的落到原生 Video 的 controls 位;缺省仍为 false(自绘控制条版面不变)。
import { describe, it, expect, vi, beforeEach } from 'vitest'
import { render } from '@testing-library/react'

const videoProps: Array<Record<string, unknown>> = []

vi.mock('react-native-video', () => ({
  default: (props: Record<string, unknown>) => {
    videoProps.push(props)
    return null
  },
}))

vi.mock('../src/i18n', () => ({
  useI18n: () => ({ t: (key: string) => key }),
}))

import { VideoPlayer } from '../src/components/VideoPlayer'

describe('VideoPlayer controls 真消费', () => {
  beforeEach(() => {
    videoProps.length = 0
  })

  it('controls=true 时原生 Video 收到 controls=true', () => {
    render(<VideoPlayer url="https://example.com/a.mp4" controls />)
    expect(videoProps.at(-1)?.controls).toBe(true)
  })

  it('缺省时保持 false,既有自绘控制条版面不变', () => {
    render(<VideoPlayer url="https://example.com/a.mp4" />)
    expect(videoProps.at(-1)?.controls).toBe(false)
  })
})
