import { beforeEach, describe, expect, it, vi } from 'vitest'
import { AppState } from 'react-native'

// adapter 模块会 import 真 @react-navigation/native(拉整套导航栈);本套件只测 AppState 转换腿,
// 焦点腿由 5 个消费屏套件(经 useRefreshOnFocus 挂载)覆盖,这里给一个不加载真包的出口。
vi.mock('@react-navigation/native', () => ({ useFocusEffect: () => {} }))

import { rnScreenReappearAdapter } from '../src/hooks/screen-reappear-adapter'

/** 全局替身(tests/__mocks__/react-native.ts)专有的派发/复位出口,真身 AppState 上没有。 */
const appState = AppState as unknown as { __emit: (state: string) => void; __reset: () => void }

describe('rnScreenReappearAdapter.subscribeAppActive', () => {
  beforeEach(() => {
    appState.__reset()
  })

  it('只在回到 active 时派发一次;background/inactive 不派发', () => {
    const onActive = vi.fn()
    rnScreenReappearAdapter.subscribeAppActive?.(onActive)

    appState.__emit('background')
    appState.__emit('inactive')
    expect(onActive).not.toHaveBeenCalled()

    appState.__emit('active')
    expect(onActive).toHaveBeenCalledTimes(1)
  })

  it('退订后不再派发(防泄漏)', () => {
    const onActive = vi.fn()
    const unsubscribe = rnScreenReappearAdapter.subscribeAppActive?.(onActive)

    unsubscribe?.()
    appState.__emit('active')
    expect(onActive).not.toHaveBeenCalled()
  })
})
