/**
 * expo-blur 测试替身。
 *
 * 为什么必须有:真包 NativeBlurModule 链式 import 'expo-modules-core' 源码,其
 * setUpJsLogger.fx.ts 读裸全局 __DEV__、EventEmitter.ts 读 globalThis.Expo —— jsdom
 * 测试环境两样都没有 ⇒ transitively import 它的测试文件(agent-screen / plaza-screen,
 * 经各自 Screen → TabBar → BlurView)在**收集期**整体加载失败("Test Files N failed",
 * 一条断言都没跑)。收口在配置层(vitest.config.ts alias),与 expo-device /
 * expo-file-system 同型;逐套件加局部 vi.mock 正是要根治的反模式。
 *
 * 覆盖面按 src 里实际用到的成员给(不是全量 API):
 *   BlurView(apps/mobile-rn/src/components/TabBar.tsx:props intensity/tint/style/blurTarget)
 *   BlurTargetView(各 Screen 包裹胶囊背景内容,真包非 Android 端本就渲染普通 View)
 * 测试态不需要真模糊,渲染普通元素即可。
 */
import { createElement, forwardRef, type ReactNode } from 'react'

export interface BlurViewProps {
  intensity?: number
  tint?: 'light' | 'dark' | 'default'
  style?: unknown
  pointerEvents?: 'auto' | 'none' | 'box-none' | 'box-only'
  children?: ReactNode
  [k: string]: unknown
}

export const BlurView = forwardRef<HTMLElement, BlurViewProps>(function BlurView(props, ref) {
  return createElement('div', { ...props, ref }, props.children as ReactNode)
})

export const BlurTargetView = forwardRef<HTMLElement, BlurViewProps>(
  function BlurTargetView(props, ref) {
    return createElement('div', { ...props, ref }, props.children as ReactNode)
  },
)

export default { BlurView, BlurTargetView }
