import { useEffect, useState } from 'react'
import { createNotificationClient } from '@ihui/api-client'

export interface UseWebSocketReturn {
  /** 当前连接状态 */
  connected: boolean
  /** 最近收到的通知(每次更新触发依赖重渲染) */
  lastMessage: unknown | null
}

export interface NotificationWebSocketConfig {
  baseUrl: string
  tokenProvider: () => string | null
}

// 全局客户端列表，供测试通过 vi.hoisted 注入后访问
export const _clients: {
  connect: () => void
  disconnect: () => void
  callbacks: {
    onOpen?: () => void
    onClose?: () => void
    onMessage?: (data: unknown) => void
  }
}[] = []

let _clientIndex = 0

export function useNotificationWebSocket(
  token: string | null,
  config: NotificationWebSocketConfig,
): UseWebSocketReturn {
  const [connected, setConnected] = useState(false)
  const [lastMessage, setLastMessage] = useState<unknown | null>(null)

  useEffect(() => {
    if (!token) return

    const clientIndex = _clientIndex++
    const callbacks = {
      onOpen: () => setConnected(true),
      onClose: () => setConnected(false),
      onMessage: (data: unknown) => setLastMessage(data),
    }

    const client = createNotificationClient(config, callbacks) as unknown as {
      connect: () => void
      disconnect: () => void
    }

    // 将 callbacks 存入全局列表，供测试手动触发
    _clients[clientIndex] = {
      connect: () => client.connect(),
      disconnect: () => client.disconnect(),
      callbacks,
    }

    client.connect()

    return () => {
      client.disconnect()
    }
  }, [token, config.baseUrl, config.tokenProvider])

  return { connected, lastMessage }
}
