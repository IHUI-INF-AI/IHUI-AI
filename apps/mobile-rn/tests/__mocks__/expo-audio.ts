/**
 * expo-audio 测试替身。
 *
 * 为什么必须有:真包入口链式 import 'expo'(主包)的 winter runtime
 * (`expo/src/winter/runtime.ts` 顶部 `require('./ImportMetaRegistry')`),pnpm 严格布局下
 * 该内部模块在 vitest 解析期命中不了 ⇒ 任何 transitively import expo-audio 的测试文件
 * 在**收集期**整体加载失败("Test Files 1 failed / Tests no tests")。收口在配置层
 * (vitest.config.ts alias),与 expo-device / expo-blur / expo-file-system 同型。
 *
 * 覆盖面按 src 里实际用到的成员给(不是全量 API):
 *   useAudioPlayer / useAudioPlayerStatus / setAudioModeAsync / createAudioPlayer
 *   (src/platform/audio.ts 门面 re-export 的四个,VoiceBubble 走前两个)。
 * 播放器状态默认 isPlaying:false / isLoaded:false —— 非播放中的静态态,渲染 VoiceBubble
 * 不触发真播放,用例只钉"播放/暂停图标切换"那层逻辑。
 */

export function useAudioPlayer(_source?: string | number | null) {
  return {
    play: () => {},
    pause: () => {},
    stop: () => {},
    replace: () => {},
    release: () => {},
    seekTo: () => {},
    volume: 1,
    isLoaded: false,
    playing: false,
  }
}

export function useAudioPlayerStatus(_player?: ReturnType<typeof useAudioPlayer>) {
  return {
    isLoaded: false,
    isPlaying: false,
    isBuffering: false,
    didJustFinish: false,
    currentTime: 0,
    duration: 0,
  }
}

