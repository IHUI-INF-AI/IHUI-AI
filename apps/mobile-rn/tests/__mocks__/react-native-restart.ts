/**
 * vitest 替身:react-native-restart 的真实入口走包内 "react-native" 字段(src/index.tsx,
 * TS 语法)或 main(lib/commonjs/index.js,内部 require('react-native') 打到真实 RN 的
 * Flow 源码)⇒ esbuild/Node 报 `SyntaxError: Unexpected token 'typeof'`,于是**整个测试
 * 文件收集期就失败**(一条 it() 都不跑)。src/theme/active-tokens.ts 的 reloadForTheme()
 * 引它,而 active-tokens 被屏/组件/ThemeContext 顶层 import ⇒ 波及面是整端。
 * 与 expo-file-system / react-native-svg / nativewind 同一死法,故同法处理:
 * vitest.config.ts 里 alias 指向本文件(配置层收口,不在逐个测试文件里 vi.mock)。
 *
 * 导出面按真实包 v0.0.29 镜像(restart / Restart(废弃) / getReason),不 invented 出口;
 * 并记录调用以便断言(同 nativewind.ts 的写法)。重启是原生能力,jsdom 下不可能真重启,
 * 替身只保证「被调到」这件事可见。
 */

export const restartCalls: string[] = []

const RNRestart = {
  /** 真机:重启 JS 运行时;此处仅记账(reason 与 active-tokens.ts 传的 'theme' 对齐) */
  restart(reason?: string): void {
    restartCalls.push(reason ?? '')
  },
  /** @deprecated 真实包保留的旧大写出口,镜像它以免有人按旧名调用时静默 undefined */
  Restart(reason?: string): void {
    RNRestart.restart(reason)
  },
  getReason(): Promise<string | null> {
    // `?? null` 不是装饰:数组下标访问在本仓 tsconfig 下推得出 `string | undefined`,
    // 少了它 tsc 直接 TS2322(typecheck 实测抓到过一次,是本人这一处)。
    return Promise.resolve(restartCalls.at(-1) ?? null)
  },
}

export default RNRestart

export function __resetRestartCalls(): void {
  restartCalls.length = 0
}
