/**
 * 圈子详情 RN 端接口口径锁(2026-11-27)。
 *
 * 立因:
 *  ① 后端 `GET /circles/:id` 的 success 体是 `{ circle }`,不是裸 circle。RN 壳若按
 *     `fetchApi<ApiCircle>` 直接 `setCircle(data)`,拿到的是 `{ circle: {...} }`,详情头字段全空。
 *  ② 入圈/退圈后端前端口径是 `POST /circles/:id/join` 与 `POST /circles/:id/leave`
 *     (activity-routes.ts;web `student/my-circles` 也用 `/leave`)。`/members` 是另一组
 *     后台/管理口径(成员数更新语义不同),RN 详情不应改走它。
 * 本测试从 RN 壳与后端路由两处源码现读,防止回潮。
 */
import { readFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { describe, expect, it } from 'vitest'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..', '..')
const read = (rel: string) => readFileSync(join(ROOT, rel), 'utf8')

const RN_CIRCLE_DETAIL = 'apps/mobile-rn/src/screens/CircleDetailScreen.tsx'
const API_CIRCLE_ACTIONS = 'apps/api/src/routes/other/activity-routes.ts'

describe('圈子详情 RN 壳接口口径', () => {
  it('详情取 `{ circle }` 信封,不把信封当业务对象', () => {
    const source = read(RN_CIRCLE_DETAIL)
    expect(source).toContain('interface CircleRes')
    expect(source).toContain('fetchApi<CircleRes>')
    expect(source).toContain('circleRes.data?.circle')
    expect(source).not.toContain('fetchApi<ApiCircle>')
  })

  it('入圈/退圈走 web 同口径 join/leave 端点', () => {
    const source = read(RN_CIRCLE_DETAIL)
    expect(source).toContain(
      "fetchApi<void>(`/api/circles/${encodeURIComponent(id)}/join`, {\n      method: 'POST'",
    )
    expect(source).toContain(
      "fetchApi<void>(`/api/circles/${encodeURIComponent(id)}/leave`, {\n      method: 'POST'",
    )
    expect(source).not.toContain('/members')
  })

  it('后端仍以 POST /circles/:id/join|leave 注册', () => {
    const source = read(API_CIRCLE_ACTIONS)
    expect(source).toContain("server.post('/circles/:id/join'")
    expect(source).toContain("server.post('/circles/:id/leave'")
  })
})
