import { readFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, resolve } from 'node:path'
import { describe, it, expect } from 'vitest'
import { render } from '@testing-library/react'

import { BrandIcon } from '../src/components/brand-icon'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const WEB = resolve(ROOT, 'src/components/brand-icon.web.tsx')
const MODEL_LIST = resolve(ROOT, 'src/components/ModelList.tsx')

/**
 * BrandIcon 成对契约 + 厂商优先级锁
 *
 * 起因:861cd2f8528 只落了 RNW 那份(brand-icon.web.tsx)与首页传下来的 `vendor`,
 * 原生那半和 ModelList 的消费点都不在 ⇒ CI 的 `@ihui/mobile-rn#typecheck` 判红,
 * 且"vendor 有值优先渲染真实厂商矢量"这条语义在两端都无人兑现。
 */
describe('BrandIcon 原生实现(字母兜底)', () => {
  it('取厂商代码首字母并大写,与 web 变体的未映射兜底同语义', () => {
    expect(render(<BrandIcon vendor="deepseek" />).container.textContent?.trim()).toBe('D')
    expect(render(<BrandIcon vendor="  mistral " />).container.textContent?.trim()).toBe('M')
  })

  it('vendor 缺失/为空渲染空字母而不是崩溃或回落到占位图', () => {
    expect(render(<BrandIcon vendor={null} />).container.textContent?.trim()).toBe('')
    expect(render(<BrandIcon />).container.textContent?.trim()).toBe('')
  })
})

describe('成对契约(§0.6 同类声明只许一份)', () => {
  it('入参档只住在原生那份,web 变体 import type 后 re-export,不再抄第二份', () => {
    const web = readFileSync(WEB, 'utf8')
    expect(web).not.toMatch(/export interface BrandIconProps\b/)
    expect(web).toMatch(/import type \{ BrandIconProps \} from '\.\/brand-icon'/)
    expect(web).toMatch(/export type \{ BrandIconProps \}/)
  })

  it('ModelList 确实消费 vendor(声明必须有消费者)', () => {
    const src = readFileSync(MODEL_LIST, 'utf8')
    expect(src).toMatch(/item\.vendor \? \(\s*<BrandIcon vendor=\{item\.vendor\}/)
  })
})
