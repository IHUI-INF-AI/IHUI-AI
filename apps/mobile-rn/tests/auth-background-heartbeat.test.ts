import { describe, expect, it } from 'vitest'
import { readFileSync } from 'node:fs'
import { join } from 'node:path'

/**
 * 后台 60s 能力上报的失败面锁(2026-11-23 立)。
 *
 * 真机事故:真实 admin 登录约 15 分钟后,`POST /api/agent-control/capability` 返回 401,
 * 全局 401 出口直接 `navigateTo('Login')` + `expireAuth()` —— 管理分类页验收被当场打断。
 * 两处必须同时成立:
 * ① 心跳发请求前先走端内唯一续期出口(`ensureFreshToken`),别拿过期 token 硬撞;
 * ② 即便这一拍仍 401,也只能告警,不能由后台心跳裁定整个会话失效。
 */
const APP = process.cwd()
const NAV = readFileSync(join(APP, 'src/navigation/RootNavigator.tsx'), 'utf-8')
const BRIDGE = readFileSync(join(APP, 'src/hooks/use-ui-control-bridge.ts'), 'utf-8')

describe('后台能力上报不结束会话', () => {
  it('心跳前先发起 ensureFreshToken,不拿过期 access token 硬撞', () => {
    expect(BRIDGE).toContain("import { ensureFreshToken } from '../lib/token'")
    expect(BRIDGE).toContain('void ensureFreshToken()')
    const at = BRIDGE.indexOf('void ensureFreshToken()')
    const call = BRIDGE.indexOf('reportAgentControlCapability(buildCapability())')
    expect(at).toBeGreaterThan(-1)
    expect(call).toBeGreaterThan(at)
  })

  it('agent-control 的 401 在全局出口被拦截,不导航登录页也不 expireAuth', () => {
    const guard = NAV.indexOf("ctx.url.includes('/api/agent-control/')")
    const navigate = NAV.indexOf("navigateTo('Login')", guard)
    const expire = NAV.indexOf('expireAuth()', guard)
    expect(guard).toBeGreaterThan(-1)
    expect(navigate).toBeGreaterThan(guard)
    expect(expire).toBeGreaterThan(guard)
  })
})
