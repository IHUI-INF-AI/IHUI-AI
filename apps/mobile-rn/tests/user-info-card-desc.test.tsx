// 门 285 B 组:UserInfoCard.desc 由「仅小程序声明」收口为两端真实现。
// 数字优先、文本兜底:tokenQuantity 缺位时 desc 必须真的渲染到智汇值行。
import { describe, it, expect, vi } from 'vitest'
import { render, screen } from '@testing-library/react'
import type { UserInfo } from '@ihui/types'

vi.mock('../src/i18n', () => ({
  useI18n: () => ({ t: (key: string) => key }),
}))

import UserInfoCard from '../src/components/UserInfoCard'

const baseUser = { uuid: 'u-1', username: '测试用户' } as unknown as UserInfo

describe('UserInfoCard desc 真消费', () => {
  it('tokenQuantity 缺位时渲染 desc 文本', () => {
    render(<UserInfoCard userInfo={baseUser} desc="暂无智汇值" />)
    expect(screen.getByText('暂无智汇值')).toBeTruthy()
  })

  it('tokenQuantity 在位时数字优先,不显示 desc', () => {
    render(
      <UserInfoCard
        userInfo={{ ...baseUser, tokenQuantity: 1200 } as unknown as UserInfo}
        desc="暂无智汇值"
      />,
    )
    expect(screen.getByText('1200')).toBeTruthy()
    expect(screen.queryByText('暂无智汇值')).toBeNull()
  })
})
