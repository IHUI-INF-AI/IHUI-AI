import java.util.Collections;
import java.util.List;

/**
 * AutoInstallStatus 模块的注册入口。
 * 由 plugins/withAutoInstaller.cjs 在 prebuild 期把本文件 + AutoInstallStatusModule.java
 * 写入 android/app/src/main/java/<pkg>/autoinstall/,并注册到 MainApplication。
 */
public class AutoInstallStatusPackage implements ReactPackage {
  @Override
  public List<ViewManager> createViewManagers(ReactApplicationContext reactContext) {
    return Collections.emptyList();
  }

  @Override
  public List<NativeModule> createNativeModules(ReactApplicationContext reactContext) {
    return Collections.singletonList(new AutoInstallStatusModule(reactContext));
  }
}
