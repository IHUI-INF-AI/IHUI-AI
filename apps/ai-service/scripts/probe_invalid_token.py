"""invalid_token 根因探针:用与 MCPClient 完全相同的 httpx 调用形态复现。"""

from __future__ import annotations

import asyncio
import json
import sys
from pathlib import Path

import httpx

PERSIST = Path(__file__).resolve().parent.parent / ".mcp-linear-token.json"
URL = "https://mcp.linear.app/mcp"


async def probe(label: str, headers: dict[str, str]) -> None:
    async with httpx.AsyncClient(timeout=30) as client:
        resp = await client.post(
            URL,
            headers=headers,
            json={
                "jsonrpc": "2.0",
                "id": 1,
                "method": "initialize",
                "params": {
                    "protocolVersion": "2025-03-26",
                    "capabilities": {},
                    "clientInfo": {"name": "ihui-ai", "version": "1.0.0"},
                },
            },
        )
        body = resp.text[:160].replace("\n", " ")
        print(f"{label}: HTTP {resp.status_code}  {body}")


async def main() -> int:
    token_data = json.loads(PERSIST.read_text(encoding="utf-8"))
    access = str(token_data["access_token"])
    ttype = str(token_data.get("token_type") or "Bearer")
    print(f"token_type={ttype!r} len={len(access)}")
    await probe("A 原样(token_type 原大小写)", {"Accept": "application/json, text/event-stream", "Authorization": f"{ttype} {access}", "Content-Type": "application/json"})
    await probe("B 标准大写 Bearer", {"Accept": "application/json, text/event-stream", "Authorization": f"Bearer {access}", "Content-Type": "application/json"})
    await probe("C 仅 Accept: application/json", {"Accept": "application/json", "Authorization": f"Bearer {access}", "Content-Type": "application/json"})
    return 0


if __name__ == "__main__":
    sys.exit(asyncio.run(main()))
