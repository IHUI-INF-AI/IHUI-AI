"""
记忆图谱查询路由(P3 #41 阶段2,2026-09-16 立)。

GET /api/memory/graph?query=xxx
  → 子图 {nodes:[{id,content,importanceScore,hit}], edges:[{source,target,relation,weight}]}
用户身份来自 JWT(request.state.user_id,与 llm.py 同源;metadata.userId 不可信)。
"""

from typing import Any

from fastapi import APIRouter, Request

from ..services.memory_graph import query_graph

router = APIRouter()


@router.get("/memory/graph")
async def memory_graph(request: Request, query: str = "") -> dict[str, Any]:
    owner_uuid = str(getattr(request.state, "user_id", "") or "")
    if not owner_uuid:
        return {"code": 401, "message": "unauthorized", "data": None}
    if not query.strip():
        return {"code": 400, "message": "query required", "data": None}
    subgraph = await query_graph(owner_uuid, query)
    return {"code": 0, "message": "ok", "data": subgraph}
