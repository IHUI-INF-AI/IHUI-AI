"""图片编辑 HTTP 路由(ai-service,内网)。

供应商接入已下线；端点保留以兼容既有客户端，统一返回 503。
"""
from __future__ import annotations

from typing import Any

from fastapi import APIRouter, File, Form, HTTPException, UploadFile

router = APIRouter()


@router.post("/image/edits")
async def image_edits(
    image: UploadFile = File(..., description="待编辑图(png/jpeg/webp,≤25MiB)"),
    prompt: str = Form(..., description="编辑指令(改什么)"),
    mask: UploadFile | None = File(default=None, description="可选遮罩(透明区域=重绘区)"),
    model: str | None = Form(default=None, description="图片模型"),
    n: int = Form(default=1, ge=1, le=50, description="生成数量"),
    size: str | None = Form(default=None, description="像素串(与 aspect_ratio 二选一)"),
    aspect_ratio: str | None = Form(default=None, description="画面比例"),
    quality: str | None = Form(default=None, description="auto/high/medium/low"),
    output_format: str | None = Form(default=None, description="png/jpeg"),
) -> dict[str, Any]:
    """图片编辑入口已停用；保留路由形状，明确返回不可用。"""
    raise HTTPException(
        status_code=503,
        detail="图片编辑供应商已下线，当前不可用",
    )
