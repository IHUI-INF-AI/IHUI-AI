"""Conversation data models — 对话编排核心数据结构。

从 conversation.py 提取(2026-09-13 模块拆分):
- IntentResult:        意图分类结果
- ToolCallRecord:      单次工具调用记录
- ConversationResult:  对话完整结果
- INTENT_LABELS:       意图枚举(对内,LLM 输出 + 后处理)
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Any


# ---------------------------------------------------------------------------
# 意图枚举(对内,LLM 输出 + 后处理)
# ---------------------------------------------------------------------------

INTENT_LABELS = (
    "chat",        # 闲聊 / 一般对话
    "qa",          # 知识问答(基于上下文回答)
    "tool_use",    # 需要调用工具
    "code",        # 写代码 / 代码相关
    "analysis",    # 分析 / 调研
    "creative",    # 创意 / 写作
    "other",       # 其他
)


@dataclass
class IntentResult:
    """意图分类结果。"""

    intent: str
    confidence: float
    entities: dict[str, Any] = field(default_factory=dict)
    reasoning: str = ""
    needs_tool: bool = False
    suggested_tools: list[str] = field(default_factory=list)


@dataclass
class ToolCallRecord:
    """单次工具调用记录。"""

    tool: str
    arguments: dict[str, Any]
    result: dict[str, Any]
    ok: bool
    duration_ms: float = 0.0


@dataclass
class ConversationResult:
    """对话完整结果。"""

    session_id: str
    user_input: str
    intent: IntentResult
    tool_calls: list[ToolCallRecord]
    final_response: str
    model: str
    iterations: int
    duration_ms: float
    stub: bool
    trace: list[dict[str, Any]] = field(default_factory=list)
