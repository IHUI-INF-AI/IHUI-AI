"""AI 代码归属账的**统计族**(2026-11-05,goal-b49)。

把一批账行聚合成归属统计。纯函数:无 IO、无全局状态,可直接单测。

两个占比口径都给(读数侧自选,不许只给一个):
- ``ai_ratio``   = ai / total(**含** unknown)—— 全账视角;
- ``known_ratio`` = ai / (ai + human) —— 只在**归属已判出**的那部分里算。

只给一个就会让人把「没判出来」读成「不是 AI 写的」。
"""

from __future__ import annotations

from collections.abc import Iterable
from dataclasses import dataclass

from app.core.ai_code_attribution_record import AttributionRecord
from app.core.ai_code_attribution_verdict import ATTRIBUTION_AI, ATTRIBUTION_HUMAN


@dataclass(frozen=True)
class AttributionStats:
    """某文件/某会话的归属统计。"""

    total: int
    ai: int
    human: int
    unknown: int
    ai_ratio: float
    known_ratio: float


def compute_stats(records: Iterable[AttributionRecord]) -> AttributionStats:
    """聚合归属统计(纯函数)。"""
    ai = 0
    human = 0
    unknown = 0
    for record in records:
        if record.attribution == ATTRIBUTION_AI:
            ai += 1
        elif record.attribution == ATTRIBUTION_HUMAN:
            human += 1
        else:
            unknown += 1
    total = ai + human + unknown
    known = ai + human
    return AttributionStats(
        total=total,
        ai=ai,
        human=human,
        unknown=unknown,
        ai_ratio=(ai / total) if total else 0.0,
        known_ratio=(ai / known) if known else 0.0,
    )
