# app/core/patch_diff.py
"""补丁应用结果的 unified diff 展示层 — 2026-09-19 第三十四批,对标 Codex
apply-patch/src/file_update.rs 的 unified_diff_from_chunks_with_context_and_mode
(TextDiff::from_lines(...).unified_diff().context_radius(n),similar crate)。

纯算法:original/new 文本进出(由 apply_patch.derive_new_contents_from_chunks
承担应用),用 difflib 生成 unified diff(上下文半径默认 1,Codex 缺省一致);
不触碰文件系统,路径仅作为 diff 头展示。
"""
from __future__ import annotations

import difflib
from dataclasses import dataclass
from typing import Optional

from app.core.apply_patch import UpdateFileChunk, derive_new_contents_from_chunks


@dataclass
class ApplyPatchFileUpdate:
    """Codex ApplyPatchFileUpdate 等价:diff 展示文本 + 原文/新文。"""

    unified_diff: str
    original_content: str
    content: str


def _split_keepends(text: str) -> list[str]:
    return text.splitlines(keepends=True)


def unified_diff_from_chunks(
    path: str,
    chunks: list[UpdateFileChunk],
    original_contents: str,
    context_radius: int = 1,
    normalize_to_lf: bool = True,
) -> ApplyPatchFileUpdate:
    """对 chunks 应用结果生成 unified diff(路径作为 ---/+++ 头,行级上下文半径)。"""
    original, new = derive_new_contents_from_chunks(original_contents, chunks, normalize_to_lf)
    diff_lines = difflib.unified_diff(
        _split_keepends(original),
        _split_keepends(new),
        fromfile=path,
        tofile=path,
        n=context_radius,
    )
    return ApplyPatchFileUpdate(
        unified_diff="".join(diff_lines),
        original_content=original,
        content=new,
    )
