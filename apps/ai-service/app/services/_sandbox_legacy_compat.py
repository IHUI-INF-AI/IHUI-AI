"""过渡态兼容层:sandbox/ 包(D14 在飞)与 sandbox.py 暂共存期间的旧符号出口。

背景:Python 对 `app.services.sandbox` 的解析在包目录存在时**永远命中包**,
同名模块 sandbox.py(仍被跟踪、仍承载 `_DANGEROUS_PATTERNS` / `sandbox_executor`)
被整体遮蔽,导致 `from .sandbox import _DANGEROUS_PATTERNS` 一类导入在启动链
(tool_input_scanner → guarded_tool_pipeline → agent_loop_v2)上直接 ImportError。

本层按**文件路径**显式加载 sandbox.py(它无相对导入,可独立执行),
让新旧两个世界在同一进程内共存:D14 包照常用 queue/cache/board,
旧符号经此处可达。**D14 包正式收编这两个符号(或 sandbox.py 退役)后,
删除本文件并把两处 try/except 导入改回直连。**
"""

from __future__ import annotations

import importlib.util
from pathlib import Path

_SPEC = importlib.util.spec_from_file_location(
    "_ihui_sandbox_legacy", str(Path(__file__).with_name("sandbox.py"))
)
if _SPEC is None or _SPEC.loader is None:  # pragma: no cover - 文件缺失属结构性损坏
    raise ImportError("sandbox.py 缺失:_sandbox_legacy_compat 无法加载旧模块")

_legacy = importlib.util.module_from_spec(_SPEC)
_SPEC.loader.exec_module(_legacy)

_DANGEROUS_PATTERNS = _legacy._DANGEROUS_PATTERNS
sandbox_executor = _legacy.sandbox_executor

__all__ = ["_DANGEROUS_PATTERNS", "sandbox_executor"]
