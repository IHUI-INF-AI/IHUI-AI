"""工作区路径守卫:敏感目录黑名单的**单一权威源**。

为什么需要这个模块(而不是各处各写一份正则)
--------------------------------------------------------------------------
本仓历史上有 4 处彼此独立的路径校验实现(2 号 ``image_saver.validate_save_path`` 系
未接线副本,已于 2026-09-21 按 §7 收敛删除,守卫改由 ``test_save_path_guard_parity_58.py``
直接钉权威源):

1. ``file_editor.validate_path``
3. ``mcp_server._validate_path_in_workspace``  (13 个调用点)
4. ``mcp_server._validate_image_save_path``   (媒体落盘三兄弟之一)

「敏感目录黑名单」这条约束**只有 1 号实现有**,3 号完全没有 —— 于是
``write_file`` / ``file_edit`` / ``resolve_conflict`` 三个**写工具**
在通过白名单根校验后直接写盘,可以写 ``.git/hooks/pre-commit``
(git 钩子 = 任意代码执行)、``node_modules/``、``.venv/``。
而 2 号实现则连落盘后缀防线都没有(已单独修复)。

四处各有各的常量,正是「同一约束、多份真源」的典型:任何一处加固都
不会传导到其它处,而"消除重复实现"的重构又会把加固过的那份换成没加固
的那份(2 号实现就是这个剧本)。

本模块只负责「敏感目录片段」这一条约束,把判定收敛成唯一实现:
所有调用点共享同一常量与同一匹配函数,**新增敏感目录只需改这一个文件**。
"""

from __future__ import annotations

import re
from pathlib import Path

# ---------------------------------------------------------------------------
# 敏感目录片段(单一权威源)
# ---------------------------------------------------------------------------
# 语义:路径中**任一完整路径片段**命中即视为敏感目录。片段边界为路径分隔符
# 或字符串首尾,因此 ``dist`` 命中 ``a/dist/b`` 但**不命中** ``a/dist-extra/b``
# (避免误伤同前缀命名)。
#
# 收录理由:
# - .git              : hooks/ 与 config 被写 = 任意代码执行 / 仓库行为劫持
# - node_modules      : 依赖被写 = 供应链投毒(且会被 npm/pnpm 覆盖或残留)
# - .venv / venv      : 虚拟环境被写 = 运行期代码注入
# - dist / build      : 构建产物,改动会被下次构建覆盖,且来源不可追溯
# - __pycache__       : 字节码缓存,篡改后可在源文件未变时被静默加载
# - .next             : Next.js 构建缓存,同上
SENSITIVE_DIR_SEGMENTS: tuple[str, ...] = (
    ".git",
    "node_modules",
    ".venv",
    "venv",
    "dist",
    "build",
    "__pycache__",
    ".next",
)

# 组合后的匹配正则(大小写不敏感,Windows 路径同样适用)。
# 注意:该正则的字面形态与 file_editor 历史版本逐字一致 —— 收敛实现时
# 刻意保持匹配语义不变,以做到「接管方零行为变化」。
SENSITIVE_DIR_PATTERN: re.Pattern[str] = re.compile(
    r"(^|[\\/])("
    + "|".join(re.escape(seg) for seg in SENSITIVE_DIR_SEGMENTS)
    + r")([\\/]|$)",
    re.IGNORECASE,
)


def find_sensitive_segment(path: str | Path | None) -> str | None:
    """返回路径中命中的敏感目录片段,未命中返回 ``None``。

    Args:
        path: 待判定的路径(字符串或 Path)。空值返回 ``None``。
    """
    if not path:
        return None
    match = SENSITIVE_DIR_PATTERN.search(str(path))
    return match.group(2) if match else None


def has_sensitive_segment(path: str | Path | None) -> bool:
    """路径是否落在敏感目录内。"""
    return find_sensitive_segment(path) is not None


def sensitive_error_message(path: str | Path) -> str:
    """构造统一的拒绝原因文案(与 file_editor 既有文案逐字一致)。"""
    return f"路径在敏感目录黑名单内: {path}"


__all__ = [
    "SENSITIVE_DIR_PATTERN",
    "SENSITIVE_DIR_SEGMENTS",
    "find_sensitive_segment",
    "has_sensitive_segment",
    "sensitive_error_message",
]
