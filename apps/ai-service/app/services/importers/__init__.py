"""外部会话导入解析器组(D28,2026-09-20 立)。

统一入口 `parse_conversation_file(source, filename, data)`,由
`app/routers/session_import.py` 在函数内惰性导入:

    parsed, warnings, truncated = parse_conversation_file("codex", "rollout.jsonl", raw)

约定:
- `source` 不在 `SOURCES` 内 → 抛 `ValueError`(路由映射为 400)
- `parsed` 只含 `conversations` 一个键;单条会话形如
  `{title?, source, model?, sourceCreatedAt?, sourceUpdatedAt?,
  messages:[{role,content,createdAt?}]}`
  —— 与 api 侧 commitSchema、web 预览消费的字段一一对应
- 角色白名单、密钥脱敏、体积截断等跨来源收口全部落在 `ir.finalize`,
  各 parser 只做"自家格式 → IR"的翻译,统一签名 `parse(data, filename) -> ParseResult`

扩展名白名单与 20MiB 上限已在路由层拦下,解析器不重复校验。
"""

from __future__ import annotations

from collections.abc import Callable
from typing import Any

from . import aider, claude_code, codex, cursor
from .ir import ParseResult, finalize

__all__ = ["SOURCES", "parse_conversation_file"]

_Parser = Callable[[bytes, str], ParseResult]

_SOURCES: dict[str, _Parser] = {
    "claude_code": claude_code.parse,
    "codex": codex.parse,
    "cursor": cursor.parse,
    "aider": aider.parse,
}

SOURCES: tuple[str, ...] = tuple(_SOURCES)


def parse_conversation_file(
    source: str, filename: str, data: bytes
) -> tuple[dict[str, Any], list[str], bool]:
    """按来源分派解析并收口成 /parse 响应体。"""
    parser = _SOURCES.get(source)
    if parser is None:
        raise ValueError(f"不支持的数据源: {source}(允许: {', '.join(SOURCES)})")
    if not data or data.isspace():
        raise ValueError("上传的文件内容为空")
    return finalize(parser(data, filename), source=source)
