SEP = "─" * 40

def build():
    import os
    os.makedirs("Output", exist_ok=True)
    lines = ["# 0724", ""]
    for title, tags, body in ARTICLES:
        lines.append(title)
        lines.append(" ".join(f"#{t}" for t in tags))
        lines.append("")
        buf = ""
        out = []
        for ch in body:
            buf += ch
            if ch in "。！？":
                out.append(buf)
                buf = ""
        if buf:
            out.append(buf)
        lines.extend(out)
        lines.append("")
        lines.append(SEP)
        lines.append("")
    text = "\n".join(lines).rstrip() + "\n"
    with open("Output/0724.txt", "w", encoding="utf-8") as f:
        f.write(text)
    return text

def metrics():
    for i, (title, tags, body) in enumerate(ARTICLES, 1):
        print(f"A{i}: 标题{len(title)}字 | 正文{len(body)}字 | 我{body.count('我')}次 | 真正{body.count('真正')}")

if __name__ == "__main__":
    build()
    print("已写入: Output/0724.txt")
    print("篇数:", len(ARTICLES))
    metrics()
