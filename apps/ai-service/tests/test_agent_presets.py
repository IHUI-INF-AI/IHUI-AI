"""agent preset 注册表单测。"""
from __future__ import annotations

import pytest

from app.core.agent_presets import (
    DEFAULT_AGENT_PRESETS,
    AgentPresetError,
    expand_agent_preset,
    resolve_agent_preset,
)


def test_default_catalog_names_and_permissions_are_consistent():
    names = [entry.name for entry in DEFAULT_AGENT_PRESETS.entries]
    assert names == ["general", "researcher", "coder", "reviewer", "architect", "debugger"]
    assert DEFAULT_AGENT_PRESETS.default_preset == "general"
    assert resolve_agent_preset("researcher").permission_preset == "readOnly"
    assert resolve_agent_preset("coder").permission_preset == "auto"
    assert resolve_agent_preset("general").tools is None


def test_persona_preset_carries_tool_subset():
    researcher = resolve_agent_preset("researcher")
    assert researcher.persona == "researcher"
    assert researcher.tools
    assert "read_file" in researcher.tools or "web_search" in researcher.tools


def test_expand_returns_all_runtime_fields():
    expanded = expand_agent_preset("reviewer")
    assert expanded["permission_preset"] == "readOnly"
    assert expanded["max_iterations"] == 8
    assert expanded["persona"] == "reviewer"
    assert isinstance(expanded["tools"], list)


def test_expand_rejects_explicit_conflicts():
    with pytest.raises(AgentPresetError, match="model"):
        expand_agent_preset("coder", model="gpt-5")
    with pytest.raises(AgentPresetError, match="permission_preset"):
        expand_agent_preset("coder", permission_preset="readOnly")


def test_unknown_preset_is_error():
    with pytest.raises(AgentPresetError, match="未知"):
        resolve_agent_preset("nope")
