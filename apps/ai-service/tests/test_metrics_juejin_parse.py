"""掘金 article_info 解析：真实平台字段到统一快照。"""

from __future__ import annotations

from app.services.publish import metrics_collector as mc


def _blank() -> dict:
    return {"views": 0, "likes": 0, "comments": 0, "shares": 0, "source": {}}


def test_apply_juejin_info_maps_real_fields() -> None:
    metrics = _blank()
    mc._apply_juejin_info(
        {
            "view_count": 4,
            "digg_count": 1,
            "comment_count": 2,
            "collect_count": 3,
        },
        metrics,
    )
    assert metrics["views"] == 4
    assert metrics["likes"] == 1
    assert metrics["comments"] == 2
    assert metrics["shares"] == 0
    assert metrics["source"]["collects"].startswith("article_info.collect_count")


def test_apply_juejin_info_tolerates_zero_and_string_counts() -> None:
    metrics = _blank()
    mc._apply_juejin_info(
        {"view_count": "12", "digg_count": None, "comment_count": 0},
        metrics,
    )
    assert metrics["views"] == 12
    assert metrics["likes"] == 0
    assert metrics["comments"] == 0
    assert metrics["shares"] == 0


def test_apply_csdn_html_reads_view_and_like() -> None:
    metrics = _blank()
    html = '<script>var viewCountFormat = 199;</script><span id="sidebar-likeCount">\n 1\n</span>'
    assert mc._apply_csdn_html(html, metrics) is True
    assert metrics["views"] == 199
    assert metrics["likes"] == 1
    assert metrics["source"]["views"] == "csdn.viewCountFormat"


def test_apply_csdn_html_detects_security_verification() -> None:
    metrics = _blank()
    assert mc._apply_csdn_html("<title>安全验证</title>", metrics) is False
    assert metrics["source"]["error"] == "csdn security verification"
    assert metrics["views"] == 0
