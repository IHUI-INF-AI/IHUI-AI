"""R93: the Electron atom store keys and its signed-out branch."""

from __future__ import annotations

import pytest

from app.core import codex_desktop_state_keys as mod


def test_seventeen_keys_all_classifiable() -> None:
    assert mod.KEY_COUNT == 17
    assert len(mod.ELECTRON_KEYS) == 17
    assert len(set(mod.ELECTRON_KEYS)) == 17
    mod.validate_keys()


def test_namespaces() -> None:
    counts = {ns.rstrip("-"): len(mod.keys_in(ns.rstrip("-"))) for ns in mod.NAMESPACES}
    assert counts["electron"] >= 12
    assert counts["desktop"] == 1
    assert counts["local"] == 1
    assert counts["primary-runtime"] == 1


def test_account_scoped_keys_are_partitioned_by_state_not_by_value() -> None:
    assert len(mod.ACCOUNT_SCOPED) == 2
    for k in mod.ACCOUNT_SCOPED:
        assert mod.account_scope_of(k) == "signed-out"
    assert mod.account_scope_of("electron-persisted-atom-state") is None


def test_the_store_is_in_its_logged_out_branch() -> None:
    assert mod.LIVE_ACCOUNT_BRANCH == "signed-out"
    assert mod.SIGNED_IN is False


def test_every_feature_toggle_is_off() -> None:
    assert mod.OTRACES_SAMPLE_RATE == 0
    assert mod.UPDATE_CDN_ENABLED is False
    assert mod.PREFER_MXC is False
    assert mod.WINDOWS_CORE_FRAMEWORKS is False
    assert mod.WINDOWS_PRIMARY_FRAMEWORKS is False


def test_queue_mode_is_steer() -> None:
    assert mod.QUEUE_MODE == "steer"


def test_rejects_unknown_namespace() -> None:
    with pytest.raises(mod.DesktopStateError):
        mod.namespace_of("gtk-something")


def test_validator_rejects_a_duplicate_key(monkeypatch: pytest.MonkeyPatch) -> None:
    monkeypatch.setattr(mod, "ELECTRON_KEYS", mod.ELECTRON_KEYS + (mod.ELECTRON_KEYS[0],))
    with pytest.raises(mod.DesktopStateError, match="duplicate"):
        mod.validate_keys()
