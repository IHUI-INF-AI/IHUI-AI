"""init_agents_md 的 MCP 暴露面守卫单测(D07 残余②)。

工具本体只校验 output_path ∈ 调用方给的 workspace_root;MCP 面若放任
workspace_root 任意指定,等于给普通用户开"任意目录写 AGENTS.md"的口子。
本用例钉 `_init_agents_md_guarded`:根不在进程白名单/会话附加根内 ⇒
PERMISSION_DENIED 且不调用工具本体;根在白名单内 ⇒ 下传解析后的根并产草稿。
"""

from __future__ import annotations

from app.services import mcp_server


async def test_mcp_guard_rejects_root_outside_workspace(tmp_path, monkeypatch):
    allowed = tmp_path / "allowed"
    allowed.mkdir()
    monkeypatch.setattr(mcp_server, "_get_workspace_roots", lambda: [str(allowed)])

    result = await mcp_server._init_agents_md_guarded(
        {"workspace_root": str(tmp_path / "outside")}
    )

    assert result["ok"] is False
    assert result["errorCode"] == "PERMISSION_DENIED"
    assert "白名单" in result["message"]


async def test_mcp_guard_allows_root_inside_workspace(tmp_path, monkeypatch):
    ws = tmp_path / "repo"
    ws.mkdir()
    (ws / "package.json").write_text('{"scripts":{"build":"tsc -b"}}', encoding="utf-8")
    monkeypatch.setattr(mcp_server, "_get_workspace_roots", lambda: [str(ws)])

    result = await mcp_server._init_agents_md_guarded({"workspace_root": str(ws)})

    assert result["ok"] is True, result
    assert result["workspace_root"] == str(ws.resolve())
    assert "npm run build" in result["draft"]


async def test_mcp_guard_delegates_missing_root_to_tool(tmp_path, monkeypatch):
    monkeypatch.setattr(mcp_server, "_get_workspace_roots", lambda: [str(tmp_path)])

    result = await mcp_server._init_agents_md_guarded({})

    assert result["ok"] is False
    assert result["errorCode"] == "INVALID_ARGUMENT"
