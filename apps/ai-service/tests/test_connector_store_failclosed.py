"""connector_store: app_secret 加密不可用必须 fail-closed(绝不落明文)。

R11 收口的 P1 修复:此前加密失败时降级明文落盘,现改为拒绝持久化。
2026-11-24 迁 PG:夹具由 JSON 文件换成内存 fake 会话,不连真实库。
"""

from __future__ import annotations

import pytest

import app.services.connector_store as cs
from app.core.config import settings
from tests._connector_fake import FakeSession

TENANT = "2306401f-4b6d-4436-8f5c-aa36d25da676"


def _no_crypto(monkeypatch: pytest.MonkeyPatch) -> None:
    import app.services.publish.credentials_crypto as cc

    def boom(*_a: object, **_k: object) -> object:
        raise RuntimeError("kms unavailable")

    monkeypatch.setattr(cc, "encrypt", boom)


def test_encrypt_secret_fail_closed(monkeypatch: pytest.MonkeyPatch):
    """加密异常时 _encrypt_secret 必须抛 SecretCryptoUnavailable,而非返回明文。"""
    _no_crypto(monkeypatch)
    with pytest.raises(cs.SecretCryptoUnavailable):
        cs._encrypt_secret("super-secret")


def test_save_fail_closed_when_crypto_unavailable(monkeypatch: pytest.MonkeyPatch):
    """加密不可用时 save 必须返回 None(不落明文),而非静默存明文。"""
    _no_crypto(monkeypatch)
    fake = FakeSession()
    monkeypatch.setattr(cs, "_pg_session", lambda: fake)
    monkeypatch.setattr(settings, "platform_default_tenant_id", TENANT)

    rec = {
        "key": "yuque:docs",
        "type": "yuque",
        "name": "语雀",
        "app_id": "id",
        "app_secret": "super-secret",
        "extra": {},
        "enabled": True,
    }
    result = cs.save("user-1", rec)
    assert result is None
    # fake 原始行一行都没落,更不会含明文
    assert fake.rows == []
