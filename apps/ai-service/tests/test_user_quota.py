import asyncio
import importlib
import os
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

mod = importlib.import_module("app.services.user_quota")


def _fresh(env_limit: str | None):
    os.environ.pop("USER_TRIAL_DAILY_TOKENS", None)
    if env_limit is not None:
        os.environ["USER_TRIAL_DAILY_TOKENS"] = env_limit
    return mod.UserTrialQuota()


def test_disabled_by_default():
    q = _fresh(None)
    assert q.daily_limit == 0
    r = asyncio.run(q.check("u1"))
    assert r["allowed"] is True and r["limit"] == 0


def test_enabled_and_consume_and_exceed():
    q = _fresh("10000")
    r = asyncio.run(q.check("u1"))
    assert r["allowed"] and r["limit"] == 10000 and r["remaining"] == 10000

    async def run():
        await q.consume("u1", 6000)
        r1 = await q.check("u1")
        await q.consume("u1", 5000)
        r2 = await q.check("u1")
        return r1, r2

    r1, r2 = asyncio.run(run())
    assert r1["allowed"] and r1["used"] == 6000 and r1["remaining"] == 4000
    assert r2["allowed"] is False and r2["used"] == 11000 and r2["remaining"] == 0


def test_user_isolation_and_zero_consume():
    q = _fresh("10000")

    async def run():
        await q.consume("u1", 9999)
        await q.consume("u2", 0)
        return await q.check("u1"), await q.check("u2")

    r1, r2 = asyncio.run(run())
    assert r1["allowed"] and r1["used"] == 9999
    assert r2["allowed"] and r2["used"] == 0


def test_invalid_env_falls_back_to_disabled():
    q = _fresh("not-a-number")
    assert q.daily_limit == 0
