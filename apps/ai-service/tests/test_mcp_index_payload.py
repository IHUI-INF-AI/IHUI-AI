"""`index_codebase` 响应面的逐字段完整性钉(goal-b47)。

本仓反复出现同一型自伤:实现层把"这轮到底发生了什么"写进了结果对象(遍历通道 V75、
快照自证、租约档三回),而 MCP 工具用一份手挑的 key 清单组装响应 —— 忘了抄的那一项
不是报错,是**在端上根本没发生过**。所以这里不测某一个字段,测的是
"IndexResult 的每一个字段都必须出现在响应里"。
"""

from __future__ import annotations

import inspect

from app.services import mcp_server as m
from app.services.codebase_indexer import IndexResult


def _payload_keys_in_source() -> set[str]:
    src = inspect.getsource(m._tool_index_codebase)
    return {name for name in IndexResult.__dataclass_fields__ if f'"{name}"' in src}


def test_index_codebase_payload_surfaces_every_index_result_field():
    surfaced = _payload_keys_in_source()
    missing = [f for f in IndexResult.__dataclass_fields__ if f not in surfaced]
    assert missing == [], (
        f"这些字段实现里有、到不了端上(响应面漏发):{missing};"
        "降级/自证失败/被租约挡住 与 一切正常 就会在响应上长得一模一样"
    )


def test_the_three_generations_that_were_dropped_are_now_present():
    """点名这三枚:它们分别由三张不同的票写进 IndexResult,又同一段路被手挑清单吃掉。"""
    src = inspect.getsource(m._tool_index_codebase)
    for key in ("traversal_engine", "snapshot_state", "lock_state"):
        assert f'"{key}"' in src, f"{key} 没接进响应 —— 正是本用例要拦的那一型"
