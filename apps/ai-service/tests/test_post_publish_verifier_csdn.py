"""CSDN 发布后核验：公开页标题/正文/安全验证判定。"""

from __future__ import annotations

import asyncio
from typing import Any

from app.services.publish import post_publish_verifier as verifier


class _FakeResponse:
    def __init__(self, status_code: int, text: str) -> None:
        self.status_code = status_code
        self.text = text


class _FakeClient:
    def __init__(self, response: _FakeResponse) -> None:
        self.response = response

    async def __aenter__(self) -> "_FakeClient":
        return self

    async def __aexit__(self, *args: Any) -> None:
        return None

    async def get(self, *args: Any, **kwargs: Any) -> _FakeResponse:
        return self.response


def _patch_http(monkeypatch: Any, response: _FakeResponse) -> None:
    monkeypatch.setattr(
        verifier.httpx, "AsyncClient", lambda **kwargs: _FakeClient(response)
    )
    # 单测不启动真实浏览器；浏览器复核路径由生产实测覆盖。
    monkeypatch.setattr(verifier, "_HAS_PLAYWRIGHT", False)


def test_csdn_verify_passes_public_article(monkeypatch: Any) -> None:
    body = "正文内容" * 80
    html = (
        "<html><head><title>AI热点日报：GPT-5语音实测 - CSDN博客</title></head>"
        f'<body><div id="content_views"><p>{body}</p><img src="x.png"></div></body></html>'
    )
    _patch_http(monkeypatch, _FakeResponse(200, html))
    result = asyncio.run(
        verifier._verify_csdn(
            {"UserName": "lichunchuan1"},
            "171434050",
            "AI热点日报：GPT-5语音实测",
        )
    )
    assert result["passed"] is True
    assert result["content_length"] >= 200
    assert result["images_total"] == 1


def test_csdn_verify_rejects_missing_article(monkeypatch: Any) -> None:
    _patch_http(monkeypatch, _FakeResponse(404, "<html>404</html>"))
    result = asyncio.run(
        verifier._verify_csdn({"UserName": "lichunchuan1"}, "171434050", "标题")
    )
    assert result["passed"] is False
    assert any("HTTP 404" in issue for issue in result["issues"])


def test_csdn_verify_detects_security_page(monkeypatch: Any) -> None:
    _patch_http(
        monkeypatch,
        _FakeResponse(200, "<html><title>安全验证</title><body>滑块</body></html>"),
    )
    result = asyncio.run(
        verifier._verify_csdn({"UserName": "lichunchuan1"}, "171434050", "标题")
    )
    assert result["passed"] is False
    assert any("安全验证" in issue for issue in result["issues"])


def test_csdn_verify_requires_username() -> None:
    result = asyncio.run(verifier._verify_csdn({}, "171434050", "标题"))
    assert result["passed"] is False
    assert any("UserName" in issue for issue in result["issues"])
