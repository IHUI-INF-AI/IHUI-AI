"""G-815997:csv_safety.sanitize_csv_cell 纯函数判据(ai-service 面唯一出口)。

语义镜像 api 版 sanitizeCsvCell:首字符 ∈ {=,+,-,@} 前缀单引号;
数字/bool 为机器生成正当用法原样直通;普通文本逐字不变;天然幂等。
"""

from __future__ import annotations

from app.services.publish.csv_safety import sanitize_csv_cell


def test_formula_prefix_equals_gets_quote():
    assert sanitize_csv_cell("=SUM(A1)") == "'=SUM(A1)"


def test_formula_prefix_plus_and_at():
    assert sanitize_csv_cell("+1+1") == "'+1+1"
    assert sanitize_csv_cell("@SUM(1,2)") == "'@SUM(1,2)"


def test_formula_prefix_dash_string():
    assert sanitize_csv_cell("-2-3") == "'-2-3"


def test_numbers_and_bool_pass_through():
    assert sanitize_csv_cell(-5) == "-5"
    assert sanitize_csv_cell(0) == "0"
    assert sanitize_csv_cell(3.14) == "3.14"
    assert sanitize_csv_cell(True) == "True"


def test_plain_text_unchanged():
    assert sanitize_csv_cell("gpt-4o") == "gpt-4o"
    assert sanitize_csv_cell("张三,来自中国的用户") == "张三,来自中国的用户"
    assert sanitize_csv_cell("") == ""
    assert sanitize_csv_cell(None) == ""


def test_idempotent():
    once = sanitize_csv_cell("=SUM(A1)")
    assert sanitize_csv_cell(once) == once
