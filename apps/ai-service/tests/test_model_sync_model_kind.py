from app.services.model_sync import is_free_model_variant, is_llm_sellable_model


def test_free_variants_are_not_sellable() -> None:
    assert is_free_model_variant("beam-free")
    assert is_free_model_variant("hy4flash-free")
    assert is_free_model_variant("vendor/model_free")
    assert not is_free_model_variant("freeform-chat")


def test_only_chat_and_non_free_is_sellable() -> None:
    assert is_llm_sellable_model("deepseek-v4-flash", ["chat"])
    assert not is_llm_sellable_model("deepseek-v4-flash", ["embedding"])
    assert not is_llm_sellable_model("beam-free", ["chat"])
    assert not is_llm_sellable_model("kling-video-v3", ["video"])
