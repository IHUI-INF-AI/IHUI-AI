"""凭证形状兼容层回归:扫码的扁平 cookie 对 → 适配器要求的 cookie 头。"""
from __future__ import annotations

from app.services.publish.credential_compat import normalize_credentials


def test_jianshu_flat_cookie_jar_becomes_cookie_header() -> None:
    creds = {
        "_m7e_session_core": "abc",
        "remember_user_token": "xyz",
        "HMACCOUNT": "h",
        "empty": "",
        "ignored": 123,
    }
    out = normalize_credentials("jianshu", creds)
    assert out["cookie"] == "_m7e_session_core=abc; remember_user_token=xyz; HMACCOUNT=h"
    # 原字段保留,发布/刷新逻辑仍可按名取
    assert out["_m7e_session_core"] == "abc"


def test_existing_cookie_header_not_overwritten() -> None:
    creds = {"cookie": "manual=1", "remember_user_token": "x"}
    assert normalize_credentials("jianshu", creds)["cookie"] == "manual=1"


def test_other_platforms_untouched() -> None:
    creds = {"sessionid": "s", "uid_tt": "u"}
    assert normalize_credentials("juejin", creds) == creds
    assert "cookie" not in normalize_credentials("juejin", creds)


def test_shipinhao_flat_cookie_jar_becomes_nested_dict() -> None:
    creds = {"sessionid": "s", "wxuin": "w", "empty": ""}
    out = normalize_credentials("shipinhao", creds)
    assert out["wechat_channels"] == {"sessionid": "s", "wxuin": "w"}
    assert out["sessionid"] == "s"
