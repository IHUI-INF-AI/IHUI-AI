"""delivery_review 纯函数单测。"""
from __future__ import annotations

from app.core.delivery_review import review_delivery_diff


def test_no_diff_no_changes_is_not_reviewed():
    report = review_delivery_diff(None, None)
    assert report.reviewed is False
    assert report.verdict == "approve"


def test_conflict_marker_is_blocker():
    diff = (
        "--- a/x.py\n+++ b/x.py\n@@ -1 +1,3 @@\n"
        "+<<<<<<< HEAD\n+value = 1\n+>>>>>>> branch\n"
    )
    report = review_delivery_diff(diff, [{"path": "x.py", "additions": 3, "deletions": 0}])
    assert report.verdict == "revise"
    assert report.blockers == 1
    assert report.findings[0].code == "conflict-marker"


def test_debug_and_test_delete_are_major_but_todo_is_minor():
    diff = (
        "--- a/x.ts\n+++ b/x.ts\n@@ -1,3 +1,3 @@\n"
        "-it('keeps behavior', () => { expect(1).toBe(1) })\n"
        "+console.log('debug')\n"
        "+// TODO: remove\n"
    )
    report = review_delivery_diff(diff, [{"path": "x.ts", "additions": 2, "deletions": 1}])
    codes = {f.code for f in report.findings}
    assert {"debug-leftover", "test-deleted", "todo-added"} <= codes
    assert report.majors == 2
    assert report.verdict == "revise"
    assert any(f.severity == "minor" and f.code == "todo-added" for f in report.findings)


def test_binary_and_coarse_are_not_claimed_precise():
    report = review_delivery_diff(
        "",
        [{"path": "a.bin", "binary": True}, {"path": "b.py", "coarse": True}],
    )
    assert {f.code for f in report.findings} == {"binary-change", "coarse-stats"}
    assert report.verdict == "revise"
    assert report.reviewed is True


def test_large_diff_is_major():
    report = review_delivery_diff(
        "",
        [{"path": f"f{i}.py", "additions": 10, "deletions": 0} for i in range(501)],
    )
    assert any(f.code == "too-many-files" for f in report.findings)
    assert report.verdict == "revise"
