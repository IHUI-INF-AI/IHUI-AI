"""G-150:compaction 帧必须把"压缩撞到上限(incompressible)"交代出来。

旧行为:`compressed=False` 时**一帧都不发**,用户在界面上只感觉"变慢/变笨",
而竞品会直说"上下文压缩已达上限,建议开新对话或禁用不必要的 MCP 工具/技能"。
纯函数用例,不触网、不碰库。
"""

import json

from app.routers.llm import _compaction_frame


def _info(**overrides):
    base = {
        "compressed": True,
        "original_tokens": 9000,
        "compressed_tokens": 6000,
        "removed_count": 3,
        "usage_ratio": 0.9,
        "trigger": "llm",
    }
    base.update(overrides)
    return base


def _payload(raw):
    assert raw is not None and raw.startswith("data: ")
    return json.loads(raw[len("data: ") :])["compaction"]


def test_compressed_frame_carries_trigger_and_metrics():
    p = _payload(_compaction_frame(_info()))
    assert p["trigger"] == "llm"
    assert p["tokensBefore"] == 9000 and p["tokensAfter"] == 6000
    assert p["removedCount"] == 3 and p["usageRatio"] == 0.9


def test_incompressible_still_emits_so_ui_can_give_action():
    p = _payload(_compaction_frame(_info(compressed=False, trigger="incompressible", compressed_tokens=8800)))
    assert p["trigger"] == "incompressible"
    assert p["triggered"] is True


def test_no_frame_when_nothing_happened():
    assert _compaction_frame(None) is None
    assert _compaction_frame(_info(compressed=False, trigger="none")) is None


def test_missing_trigger_falls_back_to_llm_label():
    info = _info()
    del info["trigger"]
    assert _payload(_compaction_frame(info))["trigger"] == "llm"
