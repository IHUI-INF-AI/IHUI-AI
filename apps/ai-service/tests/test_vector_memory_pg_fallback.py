"""D8 配套测试:pgvector 不可用时 VectorMemoryStore 行为与旧链路一致(降级兼容)。"""

from __future__ import annotations

from unittest.mock import patch

import pytest

from app.services.vector_memory import VectorMemoryStore


@pytest.fixture()
def store(tmp_path: any) -> VectorMemoryStore:  # type: ignore[name-defined]
    return VectorMemoryStore(persist_path=str(tmp_path / "vm.json"))


async def test_pg_unavailable_search_falls_back_to_memory(store: VectorMemoryStore) -> None:
    await store.hydrate()
    emb = [0.1, 0.2, 0.3]
    emb2 = [0.9, 0.9, 0.9]
    with patch("app.core.db_pool.get_shared_pool", side_effect=RuntimeError("no pg")):
        await store.add_entry("e1", {"text": "hello"}, emb)
        await store.add_entry("e2", {"text": "world"}, emb2)
        results = await store.search(emb, top_k=5, threshold=0.5)
    assert results and results[0][0] == "e1"


async def test_pg_unavailable_add_entry_still_persists(store: VectorMemoryStore) -> None:
    with patch("app.core.db_pool.get_shared_pool", side_effect=RuntimeError("no pg")):
        await store.add_entry("e1", {"text": "hello", "session_id": "s1"}, [0.1, 0.2])
    assert len(store) == 1
    await store.delete("e1")
    assert len(store) == 0


async def test_clear_by_session_still_works(store: VectorMemoryStore) -> None:
    with patch("app.core.db_pool.get_shared_pool", side_effect=RuntimeError("no pg")):
        await store.add_entry("e1", {"session_id": "s1"}, [0.1])
        await store.add_entry("e2", {"session_id": "s2"}, [0.2])
        await store.clear(session_id="s1")
    assert store.list_entry_ids() == ["e2"]
