"""R93: the crate tree read from real `tracing` targets."""

from __future__ import annotations

import pytest

from app.core import codex_runtime_module_tree as mod


def test_counts_sum_to_rows() -> None:
    assert sum(mod.TARGETS.values()) == mod.LOG_ROWS == 2361
    assert sum(mod.LEVELS.values()) == 2361
    mod.validate_tree()


def test_twelve_targets_seven_crates() -> None:
    assert mod.DISTINCT_TARGETS == 12
    assert len(mod.TARGETS) == 12
    assert len(mod.CRATES) == 7


def test_the_three_hot_targets_dominate() -> None:
    hot = sum(mod.TARGETS[k] for k in (
        "codex_login::auth::manager",
        "codex_app_server_transport::transport::remote_control::websocket",
        "codex_app_server::message_processor",
    ))
    assert hot == 2326
    assert hot / mod.LOG_ROWS > 0.98


def test_first_separator_split_keeps_sibling_crates_apart() -> None:
    assert mod.crate_of("codex_skills_extension::host_service") == "codex_skills_extension"
    assert mod.crate_of("codex_skills::interface") == "codex_skills"
    assert ("codex_skills", "codex_skills_extension") in mod.SIBLING_CRATES


def test_module_of_strips_only_the_crate() -> None:
    assert mod.module_of("codex_app_server::request_processors::initialize_processor") == (
        "request_processors::initialize_processor")


def test_targets_by_crate_aggregates() -> None:
    by = mod.targets_by_crate()
    assert by["codex_app_server"] == 223
    assert by["codex_login"] == 1402
    assert sum(by.values()) == 2361


def test_rejects_target_without_separator() -> None:
    with pytest.raises(mod.ModuleTreeError):
        mod.crate_of("codelogin")
    with pytest.raises(mod.ModuleTreeError):
        mod.module_of("nocolons")


def test_validator_rejects_a_broken_sum(monkeypatch: pytest.MonkeyPatch) -> None:
    monkeypatch.setattr(mod, "LOG_ROWS", 2360)
    with pytest.raises(mod.ModuleTreeError, match="do not sum"):
        mod.validate_tree()
