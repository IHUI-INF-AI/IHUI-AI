"""agent preset 路由层契约:目录形状、展开、互斥与未知值。"""
from __future__ import annotations

import asyncio

import pytest
from fastapi import HTTPException

from app.routers.agents import (
    AgentExecuteRequest,
    _apply_agent_preset,
    list_agent_presets,
)


def test_catalog_route_lists_expandable_presets():
    response = asyncio.run(list_agent_presets("u1"))
    data = response["data"]
    names = [preset["name"] for preset in data["presets"]]
    assert data["defaultPreset"] == "general"
    assert {"general", "researcher", "coder", "reviewer", "architect", "debugger"} <= set(names)
    for preset in data["presets"]:
        assert preset["maxIterations"] >= 1
        assert preset["permissionPreset"] in {"readOnly", "auto", "fullAccess"}


def test_preset_expands_into_request_fields():
    req = AgentExecuteRequest(goal="修一个 bug", agent_preset="coder")
    applied = _apply_agent_preset(req)
    assert applied.max_iterations == 16
    assert applied.permission_preset == "auto"
    assert applied.agent_preset == "coder"


def test_preset_conflicts_with_explicit_max_iterations():
    req = AgentExecuteRequest(goal="修一个 bug", agent_preset="coder", max_iterations=3)
    with pytest.raises(HTTPException) as exc:
        _apply_agent_preset(req)
    assert exc.value.status_code == 400
    assert "互斥" in str(exc.value.detail)
    assert "max_iterations" in str(exc.value.detail)


def test_preset_conflicts_with_explicit_permission_mode():
    req = AgentExecuteRequest(goal="修一个 bug", agent_preset="coder", permission_mode="plan")
    with pytest.raises(HTTPException) as exc:
        _apply_agent_preset(req)
    assert exc.value.status_code == 400


def test_unknown_preset_rejected():
    req = AgentExecuteRequest(goal="修一个 bug", agent_preset="not-a-preset")
    with pytest.raises(HTTPException) as exc:
        _apply_agent_preset(req)
    assert exc.value.status_code == 400
    assert "not-a-preset" in str(exc.value.detail) or "预设" in str(exc.value.detail)
