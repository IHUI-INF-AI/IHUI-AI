"""Browser Hub 登录态加密存储的单元测试(2026-11-26 立)。"""

from __future__ import annotations

import json

import pytest

from app.services import browser_secret_store as store


@pytest.fixture(autouse=True)
def _isolated_key(monkeypatch, tmp_path):
    monkeypatch.setenv(store._ENV_KEY_PATH, str(tmp_path / "browser-state.key"))


def test_storage_state_roundtrip_without_plaintext():
    state = {
        "cookies": [
            {
                "name": "sid",
                "value": "cookie-secret",
                "domain": ".example.com",
                "path": "/",
                "expires": -1,
                "httpOnly": True,
                "secure": True,
                "sameSite": "Lax",
            }
        ],
        "origins": [
            {
                "origin": "https://example.com",
                "localStorage": [{"name": "token", "value": "local-secret"}],
            }
        ],
    }
    token = store.encrypt_storage_state(state)
    assert "cookie-secret" not in token
    assert "local-secret" not in token
    assert store.decrypt_storage_state(token) == state


def test_storage_state_tamper_is_rejected():
    token = store.encrypt_storage_state({"cookies": [], "origins": []})
    tampered = token[:-1] + ("A" if token[-1] != "A" else "B")
    with pytest.raises(store.StorageStateError):
        store.decrypt_storage_state(tampered)


def test_storage_state_rejects_non_object():
    with pytest.raises(store.StorageStateError):
        store.encrypt_storage_state([])  # type: ignore[arg-type]


def test_storage_state_rejects_oversize():
    huge = {"cookies": [], "origins": [{"origin": "https://x.test", "localStorage": [
        {"name": "a", "value": "x" * (store._MAX_STATE_BYTES + 1)}
    ]}]}
    with pytest.raises(store.StorageStateError):
        store.encrypt_storage_state(huge)
