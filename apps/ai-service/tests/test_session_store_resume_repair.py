"""会话恢复:悬挂 tool_call 的中断占位语(对标 dsh-session/repair.ts)。

钉住两件事:
  A 没有 tool_result 的 tool_call 在 resume 时补一条 role=tool 的占位;
  B 占位语只陈述"结果未落盘、outcome unknown",并给出安全重试判据 ——
    有副作用的操作必须先核对外部状态,不能让模型盲目重放。
"""

from __future__ import annotations

from pathlib import Path

from app.services.session_store import (
    SessionStore,
    ToolCallItem,
    UserMessageItem,
)


def test_resume_appends_outcome_unknown_guidance(tmp_path: Path) -> None:
    store = SessionStore(db_path=tmp_path / "sessions.db")
    try:
        thread = store.create_thread(title="t")
        turn = store.start_turn(thread.thread_id)
        store.append_item(turn.turn_id, UserMessageItem(content="run it"))
        store.append_item(
            turn.turn_id,
            ToolCallItem(
                call_id="call-1",
                tool="run_command",
                arguments={"command": "rm -rf build"},
            ),
        )
        store.end_turn(turn.turn_id, status="interrupted")

        messages = store.resume(thread.thread_id)
    finally:
        store.close()

    tool_messages = [message for message in messages if message.role == "tool"]
    assert len(tool_messages) == 1
    message = tool_messages[0]
    assert message.tool_call_id == "call-1"
    assert "outcome is unknown" in message.content
    assert "read-only or idempotent" in message.content
    assert "verify external state" in message.content
