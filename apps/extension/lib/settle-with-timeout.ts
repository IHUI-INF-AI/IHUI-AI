/**
 * 给一次执行套上超时,并在成功、失败、超时任一结局清掉定时器。
 * onReject 把抛错收成调用方自己的回执,避免 Promise.race 把 reject 甩出去之后只剩定时器空转。
 */
export async function settleWithTimeout<T>(
  exec: Promise<T>,
  timeoutMs: number,
  onTimeout: () => T,
  onReject?: (err: unknown) => T,
): Promise<T> {
  let timer: ReturnType<typeof setTimeout> | undefined
  const timeout = new Promise<T>((resolve) => {
    timer = setTimeout(() => {
      resolve(onTimeout())
    }, timeoutMs)
  })
  const guarded = onReject ? exec.catch((err: unknown) => onReject(err)) : exec
  try {
    return await Promise.race([guarded, timeout])
  } finally {
    if (timer !== undefined) clearTimeout(timer)
  }
}
