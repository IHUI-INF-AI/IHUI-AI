/**
 * 页面高亮的唯一状态:「当前高亮的词」。
 *
 * 工具栏本地布尔和 storage 里的词曾经各记一份,而且 highlight.applied
 * 只改 DOM、不改本地布尔。刷新后词还在 storage 里、DOM 是空的;
 * 别的标签已经高亮时,本页第一次点同一词会再包一层 mark(mark 内不再匹配),看起来没反应。
 */

export const HIGHLIGHT_WORD_STORAGE_KEY = 'ihui_highlight_word'

export interface HighlightDecision {
  /** 点击之后应高亮的词。null = 清除。 */
  word: string | null
  enabled: boolean
}

/**
 * 选区等于当前词 → 关闭;否则换成选区(含当前为空)。
 * 调用方把返回值同时画进 DOM 并交给 highlight.toggle,不再另留布尔旗标。
 */
export function decideHighlightToggle(
  activeWord: string | null,
  selection: string,
): HighlightDecision {
  if (activeWord !== null && activeWord === selection) {
    return { word: null, enabled: false }
  }
  return { word: selection, enabled: true }
}

/** background 广播 highlight.applied:matches 为 0 表示清除,即使 word 字段还在。 */
export function highlightedWordFromApplied(payload: {
  word?: string
  matches?: number
}): string | null {
  if (payload.matches === 0) return null
  if (typeof payload.word !== 'string' || payload.word.length === 0) return null
  return payload.word
}

/**
 * 启动时从 background 取回的词。本页已经有词(用户抢先点过)就不要用存储值覆盖。
 */
export function highlightWordToRestore(current: string | null, stored: unknown): string | null {
  if (current !== null) return null
  if (typeof stored !== 'string' || stored.length === 0) return null
  return stored
}
