/**
 * sidepanel 路由级埋点挂点(2026-10-26 立)。
 *
 * 必须渲染在 Router 内部才能拿到 useLocation;它自己不画任何东西。
 * 侧栏 50 多个页面共用一套路由,逐页加埋点必然漏 —— 挂在路由出口处一次覆盖全部页面。
 */
import { useEffect } from 'react'
import { useLocation } from 'react-router-dom'
import { reportExtensionView } from './visit-tracker'

export function ExtensionViewTracker({ surface = 'sidepanel' }: { surface?: string }) {
  const { pathname } = useLocation()
  useEffect(() => {
    reportExtensionView(`${surface}${pathname}`)
  }, [surface, pathname])
  return null
}
