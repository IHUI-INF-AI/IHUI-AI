/**
 * 选区「发送到 AI」的待发送文本。
 *
 * 生产者:内容脚本与右键菜单写入 chrome.storage.session 的 ihui_pending_prompt,
 * background 再广播 ws.pending_prompt。侧栏可能当时还没挂上,所以消费者必须
 * 同时听广播和在挂载时读一次 session,读完即删,避免下次进入聊天页把旧选区盖掉输入。
 */

export const PENDING_PROMPT_STORAGE_KEY = 'ihui_pending_prompt'
export const PENDING_PROMPT_MESSAGE_TYPE = 'ws.pending_prompt'

function nonempty(value: unknown): string | null {
  if (typeof value !== 'string') return null
  const text = value.trim()
  return text.length > 0 ? text : null
}

/** 从 background 广播里取出待填入输入框的文本。非本消息或空串返回 null。 */
export function pendingPromptTextFromMessage(msg: unknown): string | null {
  if (!msg || typeof msg !== 'object') return null
  const record = msg as { type?: unknown; payload?: unknown }
  if (record.type !== PENDING_PROMPT_MESSAGE_TYPE) return null
  const payload = record.payload
  if (!payload || typeof payload !== 'object') return null
  return nonempty((payload as { text?: unknown }).text)
}

/** 从 chrome.storage.session.get 的结果里取出待填文本。 */
export function pendingPromptTextFromStorage(bag: unknown): string | null {
  if (!bag || typeof bag !== 'object') return null
  return nonempty((bag as Record<string, unknown>)[PENDING_PROMPT_STORAGE_KEY])
}
