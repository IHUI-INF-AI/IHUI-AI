/**
 * vitest 档前置:把 happy-dom 那份 window.localStorage 挂到 globalThis(2026-10-29 立)。
 *
 * 成因是量出来的,不是猜的:本包 `environment: 'node'` + 逐档 `@vitest-environment happy-dom`。
 * 同包用 `document`/`render` 的用例(conversation-import-page、model-switch-extension 等)全绿,
 * 唯独直接读写 `localStorage` 的两枚红在 `Cannot read properties of undefined (reading 'setItem')`
 * ⇒ 环境本身进来了,是这份全局没被复制过来。
 *
 * 产品代码与用例都按浏览器语义裸用 `localStorage`(扩展端 popup/sidepanel 里它就是全局),
 * 所以这里只补介质,不改任何判据、不动包级默认(其余 node 档用例零影响)。
 * 已存在时一条都不写 —— 换 vitest 版本后若它自己挂上了,本文件自动退化为 no-op。
 */
const win = globalThis.window as unknown as { localStorage?: Storage } | undefined

/** 内存版 Storage:用例只用到 setItem/getItem/removeItem/clear,与浏览器同语义(同步)。 */
function memoryStorage(): Storage {
  const store = new Map<string, string>()
  return {
    getItem: (k: string) => store.get(k) ?? null,
    setItem: (k: string, v: string) => {
      store.set(k, String(v))
    },
    removeItem: (k: string) => {
      store.delete(k)
    },
    clear: () => {
      store.clear()
    },
    key: (i: number) => [...store.keys()][i] ?? null,
    get length() {
      return store.size
    },
  } as unknown as Storage
}

if (typeof globalThis.localStorage === 'undefined') {
  Object.defineProperty(globalThis, 'localStorage', {
    value: win?.localStorage ?? memoryStorage(),
    configurable: true,
    writable: true,
  })
}
