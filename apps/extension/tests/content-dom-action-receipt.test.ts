/**
 * DBG-64 回归锁: content.ts 的 agent.action.dom 分支 sendResponse 必达。
 * 原实现 `void executeDomAction(...).then(sendResponse)` 无 .catch ——
 * AI 下发非法 selector 时 document.querySelector 抛 SyntaxError ⇒ reject 无人接,
 * sendResponse 永不调用,background 只能等满 30s 报 TIMEOUT。
 * 现在必须:成功/失败两条路都回执,且监听器为异步响应 return true。
 */
import { readFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { describe, expect, it } from 'vitest'

const content = readFileSync(
  fileURLToPath(new URL('../entrypoints/content.ts', import.meta.url)),
  'utf8',
)

function domActionBranch(): string {
  const start = content.indexOf("m.type === 'agent.action.dom'")
  expect(start).toBeGreaterThan(-1)
  const end = content.indexOf("m.type === 'highlight.applied'", start)
  expect(end).toBeGreaterThan(start)
  return content.slice(start, end)
}

describe('agent.action.dom 错误回执 (DBG-64)', () => {
  it('executeDomAction 链上必须有 .catch 且失败也 sendResponse', () => {
    const branch = domActionBranch()
    expect(branch).toContain('.then((result) => sendResponse(result))')
    expect(branch).toContain('.catch(')
    expect(branch).toContain('sendResponse({ ok: false')
  })

  it('失败回执携带错误文本(SyntaxError 之类能被 background 直接呈现)', () => {
    const branch = domActionBranch()
    expect(branch).toContain('err instanceof Error ? err.message : String(err)')
  })

  it('分支以 return true 收尾,保住宿主消息端口等异步回执', () => {
    const branch = domActionBranch()
    expect(branch).toContain('return true')
  })
})
