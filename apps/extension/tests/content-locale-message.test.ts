/**
 * content script 取语言的通道锁(2026-11-08,同型根因 E 类第 2 条的配套改动)。
 *
 * 收紧 storage.local 到 TRUSTED_CONTEXTS 后,内容脚本不能再直读 `ihui_locale`。
 * 若只收紧不改读取通道,非中文用户的内容脚本会静默回退 zh-CN(比不收紧更糟)。
 * 因此 locale 改走 `locale.get` 消息:background 读 local 后回包,内容脚本仍拿到用户语言。
 */
import { readFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { describe, it, expect } from 'vitest'

const content = readFileSync(
  fileURLToPath(new URL('../entrypoints/content.ts', import.meta.url)),
  'utf8',
)
const router = readFileSync(
  fileURLToPath(new URL('../lib/message-router.ts', import.meta.url)),
  'utf8',
)
const background = readFileSync(
  fileURLToPath(new URL('../entrypoints/background.ts', import.meta.url)),
  'utf8',
)

describe('content locale 通道', () => {
  it('content 不再直读 storage.local,改走 locale.get 消息', () => {
    expect(content).toContain("type: 'locale.get'")
    expect(content).not.toMatch(/chrome\.storage\.local\.get\(\s*LOCALE_STORAGE_KEY\s*\)/)
  })

  it('消息契约注册 locale.get', () => {
    expect(router).toContain("type: 'locale.get'")
  })

  it('background 实现 locale.get 回包', () => {
    expect(background).toContain("case 'locale.get'")
  })
})
