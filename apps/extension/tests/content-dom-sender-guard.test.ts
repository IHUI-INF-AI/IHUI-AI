/**
 * content.ts 的 agent.action.dom 来源闸接线锁(2026-11-08,同型根因 D 类)。
 *
 * content script 是唯一能直接改宿主 DOM 的执行端,消息只应由 background 下发。
 * 该入口被 WXT 的 defineContentScript 包裹,行为难以直驱,故用源码接线锁钉死:
 * `agent.action.dom` 分支必须先过共享来源判据,才允许调用 executeDomAction,
 * 防止后续改动把闸门挪走或删掉。
 */
import { readFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { describe, it, expect } from 'vitest'

const source = readFileSync(fileURLToPath(new URL('../entrypoints/content.ts', import.meta.url)), 'utf8')

describe('content.ts DOM 动作来源闸', () => {
  it('onMessage 监听器内、executeDomAction 之前必须先校验 sender 来源', () => {
    const listenerStart = source.indexOf('chrome.runtime.onMessage.addListener')
    const firstExecute = source.indexOf('executeDomAction(')
    const guard = source.indexOf('isTrustedTopLevelExtensionSender', listenerStart)
    expect(listenerStart).toBeGreaterThan(-1)
    expect(firstExecute).toBeGreaterThan(-1)
    expect(guard).toBeGreaterThan(listenerStart)
    expect(guard).toBeLessThan(firstExecute)
  })

  it('监听器不再把 sender 丢掉(必须接住并参与判定)', () => {
    expect(source).toContain('sender: RuntimeSenderLike | undefined')
    expect(source).not.toContain('(msg, _sender, sendResponse)')
  })
})
