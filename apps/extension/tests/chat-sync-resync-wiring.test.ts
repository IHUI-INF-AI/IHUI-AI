/**
 * 票 B02 / 票71 phase 2:扩展端 resync 接线锁。
 *
 * 只锁"接线还在"与"端内不手抄端点";调度语义由 `@ihui/shared/chat` 的
 * `chat-sync-resync-pump` 用例钉住(同一份实现三端共用),这里不重复测。
 *
 * 反向牙的意义:扩展端最容易的退化方式是"页面里直接 fetch 拼一个
 * `/api/chat/conversations/.../sync-snapshot`"—— 那样共享层的失败分型(404/409
 * 摘坐标、其余退避)就被绕过去了,而且四份路径必然漂移。所以出现字面量即判红。
 */
import { readFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { describe, expect, it } from 'vitest'

const HERE = dirname(fileURLToPath(import.meta.url))

describe('phase 2 resync 接线(扩展端)', () => {
  it('ChatPage 挂载即启动泵、卸载即停', () => {
    const page = readFileSync(
      join(HERE, '../entrypoints/sidepanel/pages/ChatPage.tsx'),
      'utf8',
    )
    expect(page).toContain('startExtensionChatSyncResync()')
    expect(page).toContain('pump.stop()')
  })

  it('适配层走共享泵与共享端点,不手抄路径', () => {
    const adapter = readFileSync(join(HERE, '../src/lib/chat-sync-resync.ts'), 'utf8')
    expect(adapter).toContain('startChatSyncResyncPump')
    expect(adapter).toContain('createChatSyncSnapshotFetcher')
    expect(adapter).not.toMatch(/['"`]\/chat\/conversations/)
  })
})
