import { describe, expect, it } from 'vitest'
import { isMaxTokensTruncatedFinishReason } from '@ihui/shared/utils'

import en from '@ihui/i18n/messages/extension/en.json'
import ja from '@ihui/i18n/messages/extension/ja.json'
import ko from '@ihui/i18n/messages/extension/ko.json'
import zhCN from '@ihui/i18n/messages/extension/zh-CN.json'
import zhTW from '@ihui/i18n/messages/extension/zh-TW.json'

/**
 * G-425 extension 腿:done 帧 finishReason 截断提示。
 *
 * 两个判据分开钉:
 *  ① 判定走共享层唯一助手(端内不留第二份判据 —— 这是本票把 web 那份下沉的理由);
 *  ② 提示词在五语言包里齐备且非空,否则 ChatPage 的 notice 条会渲染出一个键名。
 *
 * 接线点本身(streamChat 回调表里的 onFinishReason)由守门 90 的「注册即算接」
 * 对账,不在这里重复断言 DOM —— 本端提示面是既有 notice 状态条,无独立渲染件。
 */
describe('G-425 extension 截断提示', () => {
  it('判定助手来自共享层且口径与 web 一致', () => {
    expect(isMaxTokensTruncatedFinishReason('length')).toBe(true)
    expect(isMaxTokensTruncatedFinishReason('MAX_TOKENS')).toBe(true)
    expect(isMaxTokensTruncatedFinishReason('stop')).toBe(false)
    expect(isMaxTokensTruncatedFinishReason(undefined)).toBe(false)
  })

  const locales: Array<[string, { chat: Record<string, unknown> }]> = [
    ['zh-CN', zhCN],
    ['zh-TW', zhTW],
    ['en', en],
    ['ja', ja],
    ['ko', ko],
  ]

  for (const [lang, bundle] of locales) {
    it(`${lang} chat.truncation.maxLengthNotice 有非空译文`, () => {
      const truncation = bundle.chat.truncation as Record<string, string> | undefined
      const text = truncation?.maxLengthNotice
      expect(typeof text).toBe('string')
      expect((text ?? '').trim().length).toBeGreaterThan(0)
    })
  }
})
