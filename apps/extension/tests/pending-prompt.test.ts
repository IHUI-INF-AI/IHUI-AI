import { readFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { describe, expect, it } from 'vitest'
import {
  PENDING_PROMPT_MESSAGE_TYPE,
  PENDING_PROMPT_STORAGE_KEY,
  pendingPromptTextFromMessage,
  pendingPromptTextFromStorage,
} from '../lib/pending-prompt'

describe('pending prompt 消费者 (DBG-63)', () => {
  it('广播消息取出非空文本', () => {
    expect(
      pendingPromptTextFromMessage({
        type: PENDING_PROMPT_MESSAGE_TYPE,
        payload: { text: '  hello world  ' },
      }),
    ).toBe('hello world')
  })

  it('别的消息、缺 payload、空白文本都不填输入框', () => {
    expect(pendingPromptTextFromMessage({ type: 'ws.pending_vocab', payload: { text: 'x' } })).toBe(
      null,
    )
    expect(pendingPromptTextFromMessage({ type: PENDING_PROMPT_MESSAGE_TYPE })).toBe(null)
    expect(
      pendingPromptTextFromMessage({
        type: PENDING_PROMPT_MESSAGE_TYPE,
        payload: { text: '   ' },
      }),
    ).toBe(null)
    expect(pendingPromptTextFromMessage(null)).toBe(null)
  })

  it('session 结果按同一键取出,空袋返回 null', () => {
    expect(pendingPromptTextFromStorage({ [PENDING_PROMPT_STORAGE_KEY]: '选区' })).toBe('选区')
    expect(pendingPromptTextFromStorage({})).toBe(null)
    expect(pendingPromptTextFromStorage(null)).toBe(null)
  })

  it('ChatPage 同时听广播并在挂载时读 session', () => {
    const chat = readFileSync(
      fileURLToPath(new URL('../entrypoints/sidepanel/pages/ChatPage.tsx', import.meta.url)),
      'utf8',
    )
    expect(chat).toContain('pendingPromptTextFromMessage')
    expect(chat).toContain('pendingPromptTextFromStorage')
    expect(chat).toContain('PENDING_PROMPT_STORAGE_KEY')
    const background = readFileSync(
      fileURLToPath(new URL('../entrypoints/background.ts', import.meta.url)),
      'utf8',
    )
    expect(background).toContain("type: 'ws.pending_prompt'")
  })
})
