/**
 * 回灌目标行选择锁(2026-11-01 立)。
 *
 * 根因:三条客户端会话回灌腿只查 `owner_user_id IS NULL` 的运营池行;本机客户端号若已
 * 由某个用户个人池持有(admin 个人池有同 uid 行),回灌看不到它 ⇒ 走"自动入池"再建
 * 一条运营池行 ⇒ 同一上游号两行并存,新票/心跳只落运营池行,个人池行与签到绑定那条
 * 静默失联(2026-11-01 实测 uid 2345730760515203)。
 *
 * 判据(纯函数,不连库):运营池行优先(全局归属);运营池无行时,个人池恰好一行才认;
 * 多行 = 归属未判定,拒绝写入并让调用方点名,绝不猜。
 */
import { describe, it, expect } from 'vitest'
import { chooseSyncTargetRow } from '../src/services/relay-session-sync-target.js'

const ops = { id: 'ops-1', ownerUserId: null }
const personal = (id: string, owner = 'user-1') => ({ id, ownerUserId: owner })

describe('chooseSyncTargetRow · 回灌目标行(运营池优先 / 个人池唯一)', () => {
  it('运营池有行 ⇒ 选运营池行(即使个人池同 uid 行也存在)', () => {
    expect(chooseSyncTargetRow([ops, personal('p-1')])).toEqual({ kind: 'row', row: ops })
  })

  it('运营池无行、个人池恰好一行 ⇒ 选该行(不再另建运营池行)', () => {
    expect(chooseSyncTargetRow([personal('p-1')])).toEqual({
      kind: 'row',
      row: personal('p-1'),
    })
  })

  it('运营池无行、个人池多行 ⇒ ambiguous(不猜、不写,调用方点名)', () => {
    const d = chooseSyncTargetRow([personal('p-1'), personal('p-2', 'user-2')])
    expect(d.kind).toBe('ambiguous')
    if (d.kind === 'ambiguous') expect(d.count).toBe(2)
  })

  it('无任何行 ⇒ none(调用方走自动入池)', () => {
    expect(chooseSyncTargetRow([]).kind).toBe('none')
  })

  it('运营池多行(结构上不该发生)⇒ ambiguous,不择一而写', () => {
    const d = chooseSyncTargetRow([
      { id: 'ops-1', ownerUserId: null },
      { id: 'ops-2', ownerUserId: null },
    ])
    expect(d.kind).toBe('ambiguous')
    if (d.kind === 'ambiguous') expect(d.count).toBe(2)
  })
})
