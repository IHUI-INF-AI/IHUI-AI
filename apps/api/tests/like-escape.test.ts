/**
 * LIKE 通配符转义单源的判据本体(2026-11-01 立,门 279 的配套)。
 *
 * 三条各配反证:
 *  ① 反斜杠必须**先**被转义 —— 后插会把 `%` 转义出来的 `\%` 再转一次成 `\\%`
 *    (字面反斜杠 + 通配),口径正好反过来,而且症状是"转义了却还漏";
 *  ② 只转义 / 转义+包裹 两个原语分工不能合并(前缀/后缀/JSON 片段形态需要不包裹的那一枚);
 *  ③ null/undefined 回空串而不是 "null"(否则搜空值会命中字面量 "null" 的行)。
 */
import { describe, expect, it } from 'vitest'

import { __test__ as likeEscape } from '../src/utils/like-escape.js'

const { escapeLikeChars, asContainsTerm, asPrefixTerm } = likeEscape

describe('escapeLikeChars', () => {
  it.each([
    ['100%', '100\\%'],
    ['a_b', 'a\\_b'],
    ['已有\\反斜杠', '已有\\\\反斜杠'],
    ['%_%', '\\%\\_\\%'],
  ])('元字符逐个被转义:%s ⇒ %s', (input, expected) => {
    expect(escapeLikeChars(input)).toBe(expected)
  })

  it('普通串逐字不变(不许顺手改大小写或裁剪)', () => {
    expect(escapeLikeChars('部署流程')).toBe('部署流程')
    expect(escapeLikeChars('Hello World')).toBe('Hello World')
  })

  it.each([
    [null, ''],
    [undefined, ''],
    ['', ''],
  ])('空值回空串,不回 "null"(%s)', (input, expected) => {
    expect(escapeLikeChars(input)).toBe(expected)
  })

  it('变异自证:反斜杠若最后才被转义,`%` 会转成 `\\\\%` —— 这条必须能区分两种顺序', () => {
    const right = escapeLikeChars('50%')
    const wrong = '50%'.replace(/[%_]/g, '\\$&').replace(/\\/g, '\\\\')
    expect(right).toBe('50\\%')
    expect(wrong).not.toBe(right)
  })
})

describe('两个包裹原语', () => {
  it('asContainsTerm 转义且两头加 %', () => {
    expect(asContainsTerm('a_b')).toBe('%a\\_b%')
  })

  it('asPrefixTerm 转义且只在尾部加 %(前缀匹配靠它)', () => {
    expect(asPrefixTerm('inv01')).toBe('inv01%')
    expect(asPrefixTerm('a%b')).toBe('a\\%b%')
  })

  it('反向断言:需要"整值即模式"的三面不得走这两个出口(它们传的就是通配符本身)', () => {
    // 台账 scripts/data/like-wildcard-intentional.json 登记的三处用的是裸值;
    // 这里钉的是"若有人把它们改成走 asContainsTerm,测试会先响"这一半。
    expect(asContainsTerm('192.168.%')).toBe('%192.168.\\%%')
  })
})
