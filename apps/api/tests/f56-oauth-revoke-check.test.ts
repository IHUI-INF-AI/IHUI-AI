/**
 * F-56:`/oauth/authorize` 与 `/oauth/userinfo` 只做 introspect(验签+过期),
 * 登出/踢下线后的 access token 仍能在 OAuth 根路径换到全新 code/令牌。
 */
import { readFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { describe, expect, it } from 'vitest'

const oauthSrc = readFileSync(
  fileURLToPath(new URL('../src/routes/oauth-authorization-server.ts', import.meta.url)),
  'utf-8',
)
const authSrc = readFileSync(
  fileURLToPath(new URL('../src/plugins/auth.ts', import.meta.url)),
  'utf-8',
)

describe('F-56 OAuth 授权面叠加吊销检查', () => {
  it('复用 authenticate 的同一份黑名单出口,不另造第二套实现', () => {
    expect(oauthSrc).toContain("import { isAccessTokenRevoked } from '../plugins/auth.js'")
    expect(authSrc).toMatch(/export async function isAccessTokenRevoked\(/)
    // 授权面不得再起一份自己的黑名单检查实现
    expect(oauthSrc).not.toContain('async function isBearerRevoked')
    expect(oauthSrc).not.toContain('getTokenBlacklist')
  })

  it('authorize 与 userinfo 两个入口都查吊销', () => {
    const calls = oauthSrc.match(/await isAccessTokenRevoked\(/g) ?? []
    expect(calls).toHaveLength(2)
    // 不允许再出现"直接用裸 token 做 introspect"的绕过路径
    expect(oauthSrc).not.toMatch(/introspectAccessToken\(header\.slice/)
    expect(oauthSrc).not.toMatch(/introspectAccessToken\(bearer\.slice/)
  })

  it('Redis 不可用时保持与 authenticate 一致的放行口径', () => {
    // 放行口径落在唯一出口 auth.ts 上,授权面不再自带一份
    expect(authSrc).toContain('if (!blacklist) return false')
  })
})
