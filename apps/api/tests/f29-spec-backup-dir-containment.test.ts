/**
 * F-29:`/spec/pipeline-rollback` 接受绝对 backupDir —— 可读工作区外任意目录的 *.bak,
 * 搬进 .ihui-agent/specs 后再经 /workspace-ai/fs/read 取出。
 */
import { describe, expect, it, vi } from 'vitest'

vi.hoisted(() => {
  process.env.DATABASE_URL ??= 'postgresql://test:test@localhost:5432/test'
  process.env.JWT_SECRET ??= 'test-jwt-secret-with-enough-length'
})

vi.mock('../src/utils/workspace-roots.js', () => ({
  // 测试里把"登记根"简化为直接返回入参(workspacePath 用绝对路径),聚焦越界判定本身。
  assertWithinRegisteredRoots: (p: string) => p,
}))

import { specService } from '../src/services/spec-service.js'

const ROOT = 'C:/tmp/f29-workspace'

describe('F-29 备份目录必须在工作区内', () => {
  it('绝对路径指向工作区外 ⇒ 拒绝,且不读取该目录', async () => {
    const result = await specService.rollbackPipeline({
      workspacePath: ROOT,
      backupDir: 'D:/outside-backups',
    })
    expect(result.rolled).toBe(0)
    expect(result.error).toBe('备份目录越出工作区')
    expect(result.errors).toEqual(['备份目录越出工作区,已拒绝'])
  })

  it('相对路径 `..` 逃逸 ⇒ 拒绝', async () => {
    const result = await specService.rollbackPipeline({
      workspacePath: ROOT,
      backupDir: '../outside-backups',
    })
    expect(result.error).toBe('备份目录越出工作区')
  })

  it('工作区内相对路径照常处理(此处目录不存在 ⇒ 备份目录不存在)', async () => {
    const result = await specService.rollbackPipeline({
      workspacePath: ROOT,
      backupDir: '.ihui-agent/specs/backups/p1',
    })
    expect(result.error).toBe('备份目录不存在')
    expect(result.rolled).toBe(0)
  })
})
