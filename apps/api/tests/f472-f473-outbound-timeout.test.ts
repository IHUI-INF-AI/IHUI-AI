/**
 * F-472:ai-service 直连代理的 fetch 全部要带超时。
 * F-473:OAuth 回调里 GitHub/Apple 的取 token、取用户信息必须带超时。
 *
 * 这些路由的端到端依赖鉴权/DB/外部网络,这里锁"每个出站 fetch 都声明 signal"这一结构。
 */
import { readFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { describe, it, expect } from 'vitest'

function readSrc(name: string): string {
  return readFileSync(fileURLToPath(new URL(`../src/routes/${name}`, import.meta.url)), 'utf-8')
}

/** 收集文件中没有在随后 400 字符内声明 signal 的出站 fetch 调用。 */
function fetchCallsWithoutSignal(src: string): string[] {
  const offenders: string[] = []
  const re = /await fetch\(/g
  let match: RegExpExecArray | null
  while ((match = re.exec(src)) !== null) {
    const window = src.slice(match.index, match.index + 400)
    if (!window.includes('signal:')) {
      offenders.push(src.slice(match.index, match.index + 100).replace(/\s+/g, ' '))
    }
  }
  return offenders
}

describe('F-472 ai-service 直连代理超时', () => {
  it('ai-tutor-routes 的出站 fetch 都带 signal', () => {
    expect(fetchCallsWithoutSignal(readSrc('ai-tutor-routes.ts'))).toEqual([])
  })

  it('ai-frontend-routes 的出站 fetch 都带 signal', () => {
    expect(fetchCallsWithoutSignal(readSrc('ai-frontend-routes.ts'))).toEqual([])
  })
})

describe('F-473 OAuth 回调超时', () => {
  const src = readSrc('auth-extended.ts')

  it.each([
    'github.com/login/oauth/access_token',
    'api.github.com/user',
    'appleid.apple.com/auth/token',
  ])('%s 的 fetch 带 signal', (anchor) => {
    const at = src.indexOf(anchor)
    expect(at).toBeGreaterThan(-1)
    expect(src.slice(at, at + 400)).toContain('signal:')
  })
})
