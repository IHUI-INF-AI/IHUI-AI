/**
 * F-729:同一模型存在多个 active billing_mode 时,必须按调用类型选行。
 * 旧实现按 effective_at 取最新一条,后插入的 token 行会把图片/视频/音频顶到
 * 0 token 分支(0 元);本锁按纯选择器钉住优先级。
 */
import { describe, it, expect } from 'vitest'
import { selectPricingRowForCallType } from '../src/services/relay-billing-service.js'

type Row = { billingMode: string | null; tag: string }

const rows: Row[] = [
  { billingMode: 'token', tag: 'newest-token' },
  { billingMode: 'per_image', tag: 'image' },
  { billingMode: 'per_video', tag: 'video' },
  { billingMode: 'per_call', tag: 'call' },
]

describe('F-729 按 callType 选定价行', () => {
  it('image 优先 per_image,不被更新的 token 行顶掉', () => {
    expect(selectPricingRowForCallType(rows, 'image')?.tag).toBe('image')
  })

  it('video 优先 per_video', () => {
    expect(selectPricingRowForCallType(rows, 'video')?.tag).toBe('video')
  })

  it('audio 优先 per_call,不落 token', () => {
    expect(selectPricingRowForCallType(rows, 'audio')?.tag).toBe('call')
  })

  it('chat 仍优先 token', () => {
    expect(selectPricingRowForCallType(rows, 'chat')?.tag).toBe('newest-token')
  })

  it('没有兼容模式时回退第一行(后续由定价闸/预检决定是否 503)', () => {
    expect(selectPricingRowForCallType([{ billingMode: 'token', tag: 'only' }], 'image')?.tag).toBe(
      'only',
    )
  })
})
