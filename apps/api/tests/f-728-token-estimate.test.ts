/**
 * F-728:上游 usage 缺失时,CJK 文本不能按「字符 ÷ 4」估算。
 * 旧口径把中文用量低估 2~3 倍;新口径 CJK 1 字 = 1 token,英文仍 4:1。
 */
import { describe, it, expect } from 'vitest'
import { estimateTextTokens } from '../src/utils/token-estimate.js'

describe('F-728 CJK 感知 token 兜底估算', () => {
  it('空串 = 0', () => {
    expect(estimateTextTokens('')).toBe(0)
    expect(estimateTextTokens(null)).toBe(0)
    expect(estimateTextTokens(undefined)).toBe(0)
  })

  it('英文仍按 4 字符/token', () => {
    expect(estimateTextTokens('abcd')).toBe(1)
    expect(estimateTextTokens('abcdefgh')).toBe(2)
  })

  it('中文 1 字 = 1 token,不再 ÷4', () => {
    expect(estimateTextTokens('你好世界')).toBe(4)
  })

  it('中英混合分别估算', () => {
    // "hello" 5 字符 -> ceil(5/4)=2,加 2 个汉字 = 4
    expect(estimateTextTokens('hello你好')).toBe(4)
  })

  it('日文/韩文同样按 CJK 计', () => {
    expect(estimateTextTokens('こんにちは')).toBe(5)
    expect(estimateTextTokens('안녕하세요')).toBe(5)
  })
})
