// 全平台最低版本闸门的纯判据单测(2026-10-27 立)。
//
// 背景:web 端 lib/app-version-gate.ts 早就会读 check-update 响应的 minimumVersion,
// 但端点从不返回该字段 ⇒ 客户端那条强更分支结构上不可达(写了不生效)。
// 本文件钉住"下发送"这一格:配置了才拦、配错一律不拦(服务端既有降级哲学)。
import { describe, expect, it } from 'vitest'

import { APP_MIN_VERSION_ENV, resolveAppMinVersion } from '../src/routes/app-version.js'

describe('resolveAppMinVersion:未配置 ⇒ null(不拦)', () => {
  it('undefined / 空串 / 纯空白都当没配', () => {
    expect(resolveAppMinVersion(undefined)).toBeNull()
    expect(resolveAppMinVersion('')).toBeNull()
    expect(resolveAppMinVersion('   ')).toBeNull()
  })
})

describe('resolveAppMinVersion:合法 X.Y.Z ⇒ 原样下发', () => {
  it('三段数字', () => {
    expect(resolveAppMinVersion('1.2.3')).toBe('1.2.3')
    expect(resolveAppMinVersion('0.0.6')).toBe('0.0.6')
  })

  it('前后空白被裁掉', () => {
    expect(resolveAppMinVersion('  1.2.3  ')).toBe('1.2.3')
  })
})

describe('resolveAppMinVersion:配错 ⇒ null(绝不因为配置事故挡住全部用户)', () => {
  it('缺段 / 多段 / 带前缀 / 非数字都判不拦', () => {
    for (const bad of ['1.2', '1.2.3.4', 'v1.2.3', 'latest', '1.2.x', '1.2.3-beta']) {
      expect(resolveAppMinVersion(bad), `"${bad}" 不该被当成有效最低版本`).toBeNull()
    }
  })
})

describe('APP_MIN_VERSION_ENV:取值面只有一个(单一真相源)', () => {
  it('环境变量名固定为 IHUI_MIN_VERSION', () => {
    expect(APP_MIN_VERSION_ENV).toBe('IHUI_MIN_VERSION')
  })
})
