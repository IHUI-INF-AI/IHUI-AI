/**
 * F-699 学习计划完成率 `count(case …)` 无 `::int` — 判据夹具。
 *
 * pg 的 count() 走 int8,驱动按字符串返回;旧实现 `sum + completedItems`
 * 会变成字符串拼接:两个计划 5/6、3/6 → totalCompleted="053" → 53/12 → 442%。
 * 这里直接 import 生产汇总函数,用「字符串形态的 completedItems」复现驱动返回值;
 * 把 `Number()` 去掉改回旧写法时本文件必翻红(expected 8, actual "053")。
 */
import { describe, it, expect, vi } from 'vitest'

vi.hoisted(() => {
  process.env.DATABASE_URL ??= 'postgresql://test:test@localhost:5432/test'
  process.env.JWT_SECRET ??= 'test-jwt-secret-for-vitest-at-least-32-chars'
})

import { __test__ } from '../src/routes/edu-ai-management.js'

const { sumPlanCompletion } = __test__

const pgString = (n: number): number => String(n) as unknown as number

describe('F-699 学习计划完成率汇总', () => {
  it('两个计划 5/6、3/6 → 完成 8/12，不是字符串拼接 "053"', () => {
    const result = sumPlanCompletion([
      { totalItems: 6, completedItems: pgString(5) },
      { totalItems: 6, completedItems: pgString(3) },
    ])
    expect(result.totalItems).toBe(12)
    expect(result.totalCompleted).toBe(8)
    expect(result.overallRate).toBe(67)
  })

  it('单计划 5/6 → 83%，与原口径一致', () => {
    const result = sumPlanCompletion([{ totalItems: 6, completedItems: pgString(5) }])
    expect(result).toEqual({ totalItems: 6, totalCompleted: 5, overallRate: 83 })
  })

  it('无计划 → 全 0，不产生 NaN', () => {
    expect(sumPlanCompletion([])).toEqual({ totalItems: 0, totalCompleted: 0, overallRate: 0 })
  })

  it('数值形态入参同样正确（SQL 已 ::int 的路径）', () => {
    const result = sumPlanCompletion([
      { totalItems: 6, completedItems: 5 },
      { totalItems: 6, completedItems: 3 },
    ])
    expect(result).toEqual({ totalItems: 12, totalCompleted: 8, overallRate: 67 })
  })
})
