import { describe, it, expect, beforeEach, afterEach, vi } from 'vitest'

import {
  getEventsAfter,
  isStreamActive,
  pushEvent,
  registerStream,
  releaseStream,
} from '../src/utils/sse-replay-buffer.js'

/** 流数量上限(与实现一致,本文件不依赖导出,按契约写死)。 */
const MAX_STREAMS = 200

function keys(n: number): string[] {
  return Array.from({ length: n }, (_, i) => `f291-${i}`)
}

function registerAll(list: readonly string[]): void {
  for (const key of list) registerStream(key)
}

function activeCount(list: readonly string[]): number {
  return list.filter((key) => isStreamActive(key)).length
}

function drainAll(list: readonly string[]): void {
  for (const key of list) releaseStream(key)
  vi.advanceTimersByTime(60_001)
}

describe('F-291 SSE 重放缓冲:容量满时的重注册不得误淘汰其他活跃流', () => {
  beforeEach(() => {
    vi.useFakeTimers()
  })

  afterEach(() => {
    vi.useRealTimers()
  })

  it('容量满时重注册已有 key,不淘汰任何其他活跃流', () => {
    const list = keys(MAX_STREAMS)
    registerAll(list)
    expect(activeCount(list)).toBe(MAX_STREAMS)

    const newest = list[MAX_STREAMS - 1]!
    pushEvent(newest, { id: 1, rawLine: 'data: first\n' })

    registerStream(newest)

    // 旧实现会在这里删掉最老的 f291-0,且自身覆盖后总数掉到 199
    expect(isStreamActive(list[0]!)).toBe(true)
    expect(activeCount(list)).toBe(MAX_STREAMS)
    // 换代语义不变:重注册清空旧缓冲
    expect(getEventsAfter(newest, 0)).toEqual([])
    // 最老那条也该活着
    expect(getEventsAfter(list[0]!, -1)).toEqual([])

    drainAll(list)
  })

  it('容量满时注册全新 key 仍按 FIFO 淘汰最老流', () => {
    const list = keys(MAX_STREAMS)
    registerAll(list)

    const fresh = 'f291-fresh'
    registerStream(fresh)

    expect(isStreamActive(list[0]!)).toBe(false)
    expect(isStreamActive(fresh)).toBe(true)
    expect(activeCount([...list.slice(1), fresh])).toBe(MAX_STREAMS)

    drainAll([...list, fresh])
  })
})
