/**
 * F-288:CSV 公式注入过滤只覆盖四种可见符号,漏 TAB/CR/LF/前导空白;
 * 攻击者可构造 `\t=cmd|' /C calc'!A0` 让管理员"打开导出文件即执行代码"。
 */
import { readFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { describe, expect, it } from 'vitest'
import { sanitizeCsvCell } from '../src/utils/csv-utils.js'

describe('F-288 前导控制字符/空白后的公式符号同样要中和', () => {
  it('TAB / CR / LF / NUL 开头均前缀单引号', () => {
    expect(sanitizeCsvCell('\t=cmd|\' /C calc\'!A0')).toBe("'\t=cmd|' /C calc'!A0")
    expect(sanitizeCsvCell('\r=1+1')).toBe("'\r=1+1")
    expect(sanitizeCsvCell('\n@SUM(1,2)')).toBe("'\n@SUM(1,2)")
    expect(sanitizeCsvCell('\u0000+1')).toBe("'\u0000+1")
  })

  it('普通空白前缀后再接公式符号也要中和', () => {
    expect(sanitizeCsvCell('   =SUM(A1)')).toBe("'   =SUM(A1)")
    expect(sanitizeCsvCell('\u00a0-2-3')).toBe("'\u00a0-2-3")
  })

  it('原有四符号行为不变且幂等', () => {
    expect(sanitizeCsvCell('=SUM(A1)')).toBe("'=SUM(A1)")
    expect(sanitizeCsvCell("'=SUM(A1)")).toBe("'=SUM(A1)")
    expect(sanitizeCsvCell('gpt-4o')).toBe('gpt-4o')
    expect(sanitizeCsvCell('')).toBe('')
  })

  it('admin 导出器把 TAB 也纳入引号包裹(避免错列)', () => {
    const src = readFileSync(
      fileURLToPath(new URL('../src/routes/admin/export-csv.ts', import.meta.url)),
      'utf-8',
    )
    expect(src).toContain('/[\\t",\\r\\n]/')
  })
})
