/**
 * F-418(document-parser):anydoc 首次加载失败不得被进程级永久缓存。
 *
 * 用可抛一次的 getter 模拟"模块在、首次取导出时失败(依赖未就绪/ABI)":
 * 旧实现第一次失败后置位 `anydocLoadAttempted`,此后本进程永远拿不到 anydoc;
 * 修复后下一次解析会重新取,第二次成功。
 */
import { describe, it, expect, vi } from 'vitest'

const state = vi.hoisted(() => ({ reads: 0 }))

vi.mock('@firecrawl/anydoc', () => {
  const ns: Record<string, unknown> = {}
  Object.defineProperty(ns, 'toMarkdownBytes', {
    enumerable: true,
    get() {
      state.reads += 1
      if (state.reads === 1) throw new Error('native binding unavailable')
      return async () => '# recovered'
    },
  })
  Object.defineProperty(ns, 'formatFromPath', {
    enumerable: true,
    value: () => 'pptx',
  })
  return ns
})

import { parseDocument } from '../src/services/document-parser.js'

const PPTX_MIME = 'application/vnd.openxmlformats-officedocument.presentationml.presentation'

describe('F-418 anydoc 加载失败不永久缓存', () => {
  it('首次加载失败后,下一次解析重新加载并成功', async () => {
    await expect(
      parseDocument({ buffer: Buffer.from('fake-pptx'), mimeType: PPTX_MIME, filename: 'a.pptx' }),
    ).rejects.toThrow()
    expect(state.reads).toBe(1)

    const text = await parseDocument({
      buffer: Buffer.from('fake-pptx'),
      mimeType: PPTX_MIME,
      filename: 'a.pptx',
    })
    expect(text).toBe('# recovered')
    expect(state.reads).toBeGreaterThan(1)
  })
})
