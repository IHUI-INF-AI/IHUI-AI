/**
 * `/v1/models` 的「此刻生效倍率」接线形状锁(2026-11-17)。
 *
 * 为什么要锁:这条字段的价值全在**与计费侧同一个答案**。若有人图省事改成
 * "在自己的窗口清单里挑第一个 active_now 的倍率",宣告(专属优先)与计费
 * (priority 降序)两套排序就会漂开 —— 客户端看到的价与实际扣费不一致,
 * 且这种漂移在类型与现有用例里都看不出来(两边各自都是"合法的数字")。
 *
 * 所以这里不测数值,只钉住取值来源:必须是计费侧的 `resolvePeakMultiplier`。
 */
import { readFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { describe, expect, it } from 'vitest'

const V1_PUBLIC_SRC = readFileSync(
  fileURLToPath(new URL('../src/routes/v1-public.ts', import.meta.url)),
  'utf8',
)

describe('/v1/models 生效倍率接线', () => {
  it('M1 取值来自计费侧 resolvePeakMultiplier,不是本地挑窗口', () => {
    expect(V1_PUBLIC_SRC).toContain('await resolvePeakMultiplier(m.id')
    expect(V1_PUBLIC_SRC).toContain('peak_multiplier_now: peakNow.multiplier')
  })

  it('M2 只在该模型有可宣告窗口时才解析(无规则模型不增开销)', () => {
    // 三元守护:peak 为 null 时不调用(否则每个模型都多一次规则表读取)
    expect(V1_PUBLIC_SRC).toMatch(/const peakNow = peak \? await resolvePeakMultiplier/)
  })

  it('M3 该字段随 peak_pricing 一起出场:无规则时整键省略,不写 0 也不写 null', () => {
    expect(V1_PUBLIC_SRC).toContain('...(peakNow')
  })
})
