/**
 * F-474:Coze SSE 代理必须有超时,并且客户端断开时 abort 上游。
 * 端到端需要 hijack + 假上游,这里锁住关键结构(与 F-428 同口径的结构断言)。
 */
import { readFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { describe, it, expect } from 'vitest'

const src = readFileSync(
  fileURLToPath(new URL('../src/routes/coze.ts', import.meta.url)),
  'utf-8',
)

describe('F-474 Coze SSE 超时与断连取消', () => {
  it('SSE 代理接收 request 并在客户端 close 时 abort', () => {
    const at = src.indexOf('async function streamCozeSse(')
    expect(at).toBeGreaterThan(-1)
    const body = src.slice(at, at + 2200)
    expect(body).toContain('request: FastifyRequest')
    expect(body).toContain("request.raw.on('close', onClientClose)")
    expect(body).toContain('signal: controller.signal')
    expect(body).toContain('controller.abort()')
    expect(body).toContain("request.raw.off('close', onClientClose)")
  })

  it('每次读取都有空闲超时,读完清定时器', () => {
    const at = src.indexOf('async function streamCozeSse(')
    const body = src.slice(at, at + 2200)
    expect(body).toContain('COZE_SSE_IDLE_TIMEOUT_MS')
    expect(body).toContain('setTimeout(() => controller.abort(), COZE_SSE_IDLE_TIMEOUT_MS)')
    expect(body).toContain('clearTimeout(idleTimer)')
  })

  it('所有调用点都把 request 传进去', () => {
    const calls = src.match(/streamCozeSse\(/g) ?? []
    expect(calls.length).toBe(5) // 1 处定义 + 4 处调用
    const withRequest = src.match(/streamCozeSse\(request,/g) ?? []
    expect(withRequest.length).toBe(4)
  })
})
