/**
 * F-85:Batch 列表按 `_apiKeyId` 过滤,但 5 个单对象端点只判"任务存在" ——
 * 持有 batches:read/write 的 A 租户拿到 B 租户 id 即可读原文/结果、恶意取消。
 */
import { readFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { describe, expect, it } from 'vitest'

const src = readFileSync(
  fileURLToPath(new URL('../src/routes/v1-batches.ts', import.meta.url)),
  'utf-8',
)

describe('F-85 单对象 Batch 端点校验归属', () => {
  it('归属判据与列表同源:比较 task._apiKeyId 与 request.apiKey.id', () => {
    expect(src).toContain('function ownsBatchTask(')
    expect(src).toContain('task._apiKeyId === apiKey.id')
  })

  it('5 个单对象端点都走同一判据(不存在与不属于他人同为 404)', () => {
    const guarded = src.match(/if \(!task \|\| !ownsBatchTask\(request, task\)\)/g) ?? []
    expect(guarded).toHaveLength(5)
    // 不允许再留下"只判存在性"的旧分支
    expect(src).not.toMatch(/if \(!task\) \{/)
  })

  it('OpenAI 与 Anthropic 各端点均使用对应文案', () => {
    expect(src).toContain("error(404, 'Batch not found')")
    expect(src).toContain("error(404, 'Message batch not found')")
  })
})
