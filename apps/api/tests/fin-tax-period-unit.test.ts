import { describe, expect, it } from 'vitest'

import {
  addMonths,
  dueDateOf,
  monthAfterPeriod,
  periodsBetween,
} from '../src/services/fin-accounting/tax-period.js'

describe('periodsBetween:申报期间展开', () => {
  it('月度逐月展开,含端点', () => {
    expect(periodsBetween('monthly', '2026-01', '2026-03')).toEqual([
      '2026-01',
      '2026-02',
      '2026-03',
    ])
  })

  it('月度跨年连续', () => {
    expect(periodsBetween('monthly', '2026-11', '2027-02')).toEqual([
      '2026-11',
      '2026-12',
      '2027-01',
      '2027-02',
    ])
  })

  it('季度同一年只取覆盖到的季度', () => {
    expect(periodsBetween('quarterly', '2026-02', '2026-08')).toEqual([
      '2026-Q1',
      '2026-Q2',
      '2026-Q3',
    ])
  })

  it('季度跨年不丢 Q1', () => {
    expect(periodsBetween('quarterly', '2026-10', '2027-03')).toEqual(['2026-Q4', '2027-Q1'])
  })

  it('年度按年展开', () => {
    expect(periodsBetween('annual', '2025-06', '2027-02')).toEqual(['2025', '2026', '2027'])
  })

  it('区间反了返回空(不静默生成)', () => {
    expect(periodsBetween('monthly', '2026-03', '2026-01')).toEqual([])
  })

  it('期间格式非法抛错', () => {
    expect(() => periodsBetween('monthly', '2026-13', '2026-14')).toThrow()
    expect(() => periodsBetween('monthly', '2026-1', '2026-02')).toThrow()
  })
})

describe('dueDateOf:申报截止日', () => {
  it('月度:次月 15 日', () => {
    expect(dueDateOf('2026-03', 15, 1)).toBe('2026-04-15')
  })

  it('月度:次月带默认 offset', () => {
    expect(dueDateOf('2026-03', 15)).toBe('2026-04-15')
  })

  it('季度:季后首月 15 日,Q4 跨年', () => {
    expect(dueDateOf('2026-Q2', 15, 1)).toBe('2026-07-15')
    expect(dueDateOf('2026-Q4', 15, 1)).toBe('2027-01-15')
  })

  it('年度默认次年 1 月', () => {
    expect(dueDateOf('2026', 15, 1)).toBe('2027-01-15')
  })

  it('年度汇算:次年 5 月 31 日', () => {
    expect(dueDateOf('2026', 31, 5)).toBe('2027-05-31')
  })

  it('31 号回退 2 月月末(平年/闰年)', () => {
    expect(dueDateOf('2026-01', 31, 1)).toBe('2026-02-28')
    expect(dueDateOf('2024-01', 31, 1)).toBe('2024-02-29')
  })

  it('31 号回退 30 天月月末', () => {
    expect(dueDateOf('2026-04', 31, 1)).toBe('2026-05-31')
    expect(dueDateOf('2026-09', 31, 1)).toBe('2026-10-31')
  })

  it('1 号不会被回退改写', () => {
    expect(dueDateOf('2026-01', 1, 1)).toBe('2026-02-01')
  })
})

describe('monthAfterPeriod / addMonths:跨月与跨年', () => {
  it('月度期间进入次月', () => {
    expect(monthAfterPeriod('2026-12')).toBe('2027-01')
    expect(monthAfterPeriod('2026-01')).toBe('2026-02')
  })

  it('季度期间进入季后首月', () => {
    expect(monthAfterPeriod('2026-Q1')).toBe('2026-04')
    expect(monthAfterPeriod('2026-Q3')).toBe('2026-10')
    expect(monthAfterPeriod('2026-Q4')).toBe('2027-01')
  })

  it('年度期间进入次年首月', () => {
    expect(monthAfterPeriod('2026')).toBe('2027-01')
  })

  it('addMonths 跨年正负都正确', () => {
    expect(addMonths('2026-01', 4)).toBe('2026-05')
    expect(addMonths('2026-11', 3)).toBe('2027-02')
    expect(addMonths('2026-01', -1)).toBe('2025-12')
    expect(addMonths('2026-01', 12)).toBe('2027-01')
  })
})
