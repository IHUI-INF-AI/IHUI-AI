/**
 * F-411:定时任务返回 `errors` 非空时不能仍记 success。
 * 判据函数 + 调用点一起锁(VIP 到期 / 佣金结算两条腿)。
 */
import { readFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { describe, it, expect, vi } from 'vitest'

vi.hoisted(() => {
  process.env.DATABASE_URL ??= 'postgresql://test:test@localhost:5432/test'
  process.env.JWT_SECRET ??= 'test-jwt-secret-for-vitest-at-least-32-chars'
})

import { jobErrorsStatus } from '../src/workers/scheduler-worker.js'

describe('F-411 errors 非空不得判 success', () => {
  it('errors 为空 ⇒ success', () => {
    expect(jobErrorsStatus({ errors: [] })).toBe('success')
  })

  it('errors 非空 ⇒ failed', () => {
    expect(jobErrorsStatus({ errors: ['user-1 降级失败'] })).toBe('failed')
  })

  it('VIP 到期与佣金结算的调用点都走判据函数', () => {
    const src = readFileSync(
      fileURLToPath(new URL('../src/workers/scheduler-worker.ts', import.meta.url)),
      'utf-8',
    )
    for (const marker of ["'VIP expire daily done'", "'commission settle daily done'"]) {
      const at = src.indexOf(marker)
      expect(at).toBeGreaterThan(-1)
      const tail = src.slice(at, at + 260)
      expect(tail).toContain('recordJobExecution(name, jobErrorsStatus(result))')
    }
  })
})
