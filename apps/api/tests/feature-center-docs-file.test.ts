import { existsSync } from 'node:fs'
import { join } from 'node:path'
import { afterAll, beforeAll, describe, expect, it } from 'vitest'
import Fastify, { type FastifyInstance } from 'fastify'
import { featureCenterRoutes } from '../src/routes/feature-center.js'

const DOCS_DIR = existsSync(join(process.cwd(), 'docs'))
  ? join(process.cwd(), 'docs')
  : join(process.cwd(), '../../docs')
const PUBLIC_PNG = 'developer/incentive-program/images/1.png'

let app: FastifyInstance

beforeAll(async () => {
  expect(existsSync(join(DOCS_DIR, PUBLIC_PNG))).toBe(true)
  app = Fastify({ logger: false })
  await app.register(featureCenterRoutes)
  await app.ready()
})

afterAll(async () => {
  await app.close()
})

describe('feature-center 文档中心非 Markdown 文件直出', () => {
  it('列表把公开非 md 文件按真实 format 收进文档中心', async () => {
    const res = await app.inject({ method: 'GET', url: '/documents' })
    expect(res.statusCode).toBe(200)
    const items = (res.json() as { data: Array<{ id: string; format: string; url: string }> }).data
    const item = items.find((i) => i.id === `file:${PUBLIC_PNG}`)
    expect(item).toBeTruthy()
    expect(item?.format).toBe('image')
    expect(item?.url).toBe(`/api/feature-center/documents/file/${PUBLIC_PNG}`)
  })

  it('公开图片按 canonical MIME 直出字节', async () => {
    const res = await app.inject({
      method: 'GET',
      url: `/documents/file/${PUBLIC_PNG}`,
    })
    expect(res.statusCode).toBe(200)
    expect(res.headers['content-type']).toBe('image/png')
    expect(res.headers['x-content-type-options']).toBe('nosniff')
    expect(res.rawPayload.byteLength).toBeGreaterThan(0)
  })

  it('拒绝路径穿越、白名单外扩展名与未公开的顶层文件', async () => {
    const traversal = await app.inject({
      method: 'GET',
      url: '/documents/file/..%2Fpackage.json',
    })
    expect(traversal.statusCode).toBe(404)

    const notWhitelisted = await app.inject({
      method: 'GET',
      url: '/documents/file/developer/incentive-program/images/1.mjs',
    })
    expect(notWhitelisted.statusCode).toBe(404)

    const privateTopLevel = await app.inject({
      method: 'GET',
      url: '/documents/file/agent-enhancement-report.html',
    })
    expect(privateTopLevel.statusCode).toBe(404)
  })
})
