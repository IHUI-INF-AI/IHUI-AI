/**
 * F-165:/relay/capacity/call-trend 查不存在的 cost_used_total_cents ——
 * 整个趋势接口恒 500,面板长期空白,而错误被 catch 成一句"查询失败"。
 */
import { readFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { describe, expect, it } from 'vitest'

const src = readFileSync(
  fileURLToPath(new URL('../src/routes/admin/relay-capacity.ts', import.meta.url)),
  'utf-8',
)

describe('F-165 调用趋势使用真实成本列', () => {
  it('不再引用不存在的 cost_used_total_cents', () => {
    expect(src).not.toContain('cost_used_total_cents')
  })

  it('成本列与 llm_call_logs schema 对齐为 cost_cents', () => {
    expect(src).toContain('COALESCE(sum(cost_cents), 0)')
  })

  it('趋势端点仍保留失败日志,不是静默空数组', () => {
    expect(src).toContain("error(500, '查询调用趋势失败')")
  })
})
