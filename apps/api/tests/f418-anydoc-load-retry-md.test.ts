/**
 * F-418(markdown-converter):anydoc 首次加载失败不得被进程级永久缓存。
 * 与 document-parser 同一根因,两处都改;本文件锁 markdown-converter 这条腿。
 */
import { mkdtempSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { describe, it, expect, vi } from 'vitest'

const state = vi.hoisted(() => ({ reads: 0 }))

vi.mock('@firecrawl/anydoc', () => {
  const ns: Record<string, unknown> = {}
  Object.defineProperty(ns, 'toMarkdown', {
    enumerable: true,
    get() {
      state.reads += 1
      if (state.reads === 1) throw new Error('native binding unavailable')
      return async () => '# recovered'
    },
  })
  Object.defineProperty(ns, 'toMarkdownBytes', {
    enumerable: true,
    value: async () => '# bytes',
  })
  Object.defineProperty(ns, 'formatFromPath', {
    enumerable: true,
    value: () => 'pptx',
  })
  return ns
})

import { convertToMarkdownDetailed } from '../src/services/markdown-converter-service.js'

describe('F-418 anydoc 加载失败不永久缓存(markdown-converter)', () => {
  it('首次加载失败后,下一次转换重新加载并成功', async () => {
    const dir = mkdtempSync(join(tmpdir(), 'f418-'))
    const file = join(dir, 'probe.pptx')
    writeFileSync(file, 'not-a-real-pptx')

    const first = await convertToMarkdownDetailed(file)
    expect(first.markdown).toBe('')
    expect(first.error).toContain('anydoc')
    expect(state.reads).toBe(1)

    const second = await convertToMarkdownDetailed(file)
    expect(second.markdown).toBe('# recovered')
    expect(state.reads).toBeGreaterThan(1)
  })
})
