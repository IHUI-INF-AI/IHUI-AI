import { mkdtempSync, readFileSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { describe, expect, it } from 'vitest'

import {
  classifyWorkspacePath,
  createAtomicCheckpoint,
  executeAtomicRollback,
  planAtomicRollback,
} from '../src/services/atomic-rollback.js'
import { classifySwitchPath } from '../src/services/relay-switch/core.js'

describe('读不到不覆盖', () => {
  it('工作区路径读不到时不算缺失', async () => {
    await expect(classifyWorkspacePath(join(tmpdir(), 'ihui-absent-path'))).resolves.toBe('absent')
    const denied = Object.assign(new Error('denied'), { code: 'EACCES' })
    await expect(
      classifyWorkspacePath('anywhere', async () => {
        throw denied
      }),
    ).resolves.toBe('unreadable')
  })

  it('快照时跳过的文件回滚不得删除', async () => {
    const root = mkdtempSync(join(tmpdir(), 'atomic-unread-'))
    writeFileSync(join(root, 'keep.txt'), 'keep')
    const checkpoint = await createAtomicCheckpoint(root, { description: 'unread' })
    writeFileSync(join(root, 'later.txt'), 'later')
    const metaPath = join(checkpoint.dir, 'meta.json')
    const meta = JSON.parse(readFileSync(metaPath, 'utf8')) as {
      skipped: Array<{ path: string; reason: string }>
    }
    meta.skipped.push({ path: 'later.txt', reason: '读不到' })
    writeFileSync(metaPath, JSON.stringify(meta))

    const plan = await planAtomicRollback(root, checkpoint.meta.id)
    expect(plan?.remove.map((item) => item.path)).not.toContain('later.txt')
    await executeAtomicRollback(root, checkpoint.meta.id, { confirm: true })
    expect(readFileSync(join(root, 'later.txt'), 'utf8')).toBe('later')
  })

  it('登录态路径读不到时不说成没有', () => {
    expect(classifySwitchPath(join(tmpdir(), 'ihui-switch-absent'))).toBe('absent')
    const denied = Object.assign(new Error('denied'), { code: 'EACCES' })
    expect(() =>
      classifySwitchPath('anywhere', () => {
        throw denied
      }),
    ).toThrow(/读不到/)
  })
})
