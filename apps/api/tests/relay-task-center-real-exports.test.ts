/**
 * 任务中心取用面的"真出口"锁(2026-10-29 立)。
 *
 * 立因:relay-task-center.ts 按名 import worker 的 runTraeSessionSync,而共用助手重构
 * 把这个出口摘了 ⇒ 运行时 TypeError(管理面「手动触发」恒 500)。同题的
 * relay-task-center.test.ts 用 vi.mock 供了同名键 ⇒ 账面 9/9 绿,缺陷只在 typecheck
 * 现读时才露头。**mock 掉被检模块的测试结构上打不到"出口还在不在"**。
 *
 * 判据:不经 mock,直接 importActual 真模块面,断言那两个名字仍是函数。
 */
import { test } from 'vitest'
import { vi } from 'vitest'
import assert from 'node:assert/strict'

const REQUIRED_EXPORTS = [
  'runTraeSessionSync',
  'runQoderSessionSync',
  'runWorkbuddySessionSync',
] as const

test('worker 真模块面必须交出三个手动触发出口(mock 面掩盖过一次)', async () => {
  const real = await vi.importActual<Record<string, unknown>>(
    '../src/workers/relay-account-pool-worker.js',
  )
  const present = Object.keys(real).filter((k) => typeof real[k] === 'function')
  for (const name of REQUIRED_EXPORTS) {
    assert.equal(
      typeof real[name],
      'function',
      `${name} 不在真出口面(函数出口:${present.join(', ') || '无'})⇒ 任务中心按名取用即抛`,
    )
  }
})
