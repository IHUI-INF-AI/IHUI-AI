/**
 * F-30:workspace-ai 的 git/status、git/review-diff、github/status 未走 workspace_permissions 闸,
 * 未配置权限的用户可绕过 setup 引导直接读取登记工作区的仓库状态/diff 原文。
 */
import { readFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { describe, expect, it } from 'vitest'

const src = readFileSync(
  fileURLToPath(new URL('../src/routes/workspace-ai.ts', import.meta.url)),
  'utf-8',
)

describe('F-30 git/github 端点接入 workspace 权限闸', () => {
  it('三个端点各自在跑 git 之前调用 isAllowedWorkspace', () => {
    expect(src).toContain("isAllowedWorkspace(request, reply, body.workspacePath, 'git_status')")
    expect(src).toContain(
      "isAllowedWorkspace(request, reply, body.workspacePath, 'git_review_diff')",
    )
    expect(src).toContain(
      "isAllowedWorkspace(request, reply, body.workspacePath, 'github_status')",
    )
  })

  it('权限检查发生在 fsBridge/githubClient 读取之前', () => {
    const statusIdx = src.indexOf("'git_status'")
    expect(statusIdx).toBeGreaterThan(-1)
    expect(src.indexOf('fsBridge.run', statusIdx)).toBeGreaterThan(statusIdx)

    const reviewIdx = src.indexOf("'git_review_diff'")
    expect(reviewIdx).toBeGreaterThan(-1)
    expect(src.indexOf('fsBridge.run', reviewIdx)).toBeGreaterThan(reviewIdx)

    const githubIdx = src.indexOf("'github_status'")
    expect(githubIdx).toBeGreaterThan(-1)
    expect(src.indexOf('githubClient.detectRemote', githubIdx)).toBeGreaterThan(githubIdx)
  })
})
