/**
 * SSRF 规范出口的 **数值字面量** 档(2026-10-31 收口)。
 *
 * 立因(三份实现里最弱的那份恰好是"规范出口"):embed-proxy.ts 与 url-preview.ts 各带一份
 * 逐字相同的 isPrivateIPv4,它们把纯整数/0x 十六进制还原成 32 位地址并拒绝混合进制;
 * 而 utils/ssrf-guard.ts 的点分分支只认 `a.b.c.d` ⇒ `http://2130706433/`(= 127.0.0.1)
 * 在本仓被所有调用方当作规范的那条出口上**读成公网地址放行**。
 * 本文件既钉"合并后行为不变差",也钉那一格原本会漏的形态;摘掉 isPrivateIPv4Literal
 * 的接入(退回旧的点分专用分支)即翻红。
 */
import { describe, expect, it } from 'vitest'

import {
  assertSafeFetchUrl,
  isPrivateIPv4Literal,
  isPrivateOrReservedIp,
} from '../src/utils/ssrf-guard.js'

describe('数值字面量还原与 fail-closed', () => {
  it.each([
    ['十进制整数 = 127.0.0.1', '2130706433'],
    ['十六进制 = 127.0.0.1', '0x7f000001'],
    ['十进制整数 = 192.168.0.1', '3232235521'],
    ['十进制整数 = 10.0.0.1', '167772161'],
    ['混合进制(0177.0.0.1)无法无歧义归一', '0177.0.0.1'],
    ['混合进制(0x7f.1)', '0x7f.1'],
    ['超 32 位范围', '99999999999'],
  ])('%s ⇒ 判为内网/拒绝', (_label, ip) => {
    expect(isPrivateIPv4Literal(ip)).toBe(true)
    expect(isPrivateOrReservedIp(ip)).toBe(true)
  })

  it('正向对照:公网地址不被"一律打回"(否则出口就是一条死路)', () => {
    expect(isPrivateIPv4Literal('8.8.8.8')).toBe(false)
    expect(isPrivateOrReservedIp('8.8.8.8')).toBe(false)
    expect(isPrivateOrReservedIp('1.1.1.1')).toBe(false)
  })

  it('v4-mapped IPv6 内嵌回环仍按同一份实现判(不得只修 IPv4 一侧)', () => {
    expect(isPrivateOrReservedIp('::ffff:127.0.0.1')).toBe(true)
    expect(isPrivateOrReservedIp('::ffff:2130706433')).toBe(true)
  })
})

describe('URL 级出口', () => {
  it('http://2130706433/ 不安全(首跳即回环地址的整数写法)', async () => {
    const r = await assertSafeFetchUrl('http://2130706433/')
    expect(r.safe).toBe(false)
  })

  it('https://8.8.8.8/ 仍放行(收窄不是把公网一起关掉)', async () => {
    const r = await assertSafeFetchUrl('https://8.8.8.8/')
    expect(r.safe).toBe(true)
  })
})
