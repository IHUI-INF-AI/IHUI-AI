/**
 * D125(2026-10-23 立)`collab:` 事件族进 /ws/broadcast 帧类别推导的回归。
 * 设计稿 docs/d125-session-collab-design.md §4:G-201 判定出口零改动,
 * 本测试钉的是**追加面**——前缀推导把两枚新事件归入 'collab' 类,
 * 且既有类别/未知前缀的行为不变(新类别对既有连接零行为差)。
 */
import { describe, it, expect } from 'vitest'

import { broadcastEventClassOf, parseBroadcastConnectionRole } from '../src/plugins/ws-broadcast'

describe('D125 collab 帧类别推导', () => {
  it('collab:invitation / collab:comment 归入 collab 类', () => {
    expect(broadcastEventClassOf('collab:invitation')).toBe('collab')
    expect(broadcastEventClassOf('collab:comment')).toBe('collab')
  })

  it('既有前缀行为不变(追加不挤掉旧档)', () => {
    expect(broadcastEventClassOf('conversation:updated')).toBe('conversation')
    expect(broadcastEventClassOf('mcp:status')).toBe('mcp')
    expect(broadcastEventClassOf('checkpoint:availability')).toBeNull()
    expect(broadcastEventClassOf('something:else')).toBeNull()
  })

  it('collab 是合法连接角色;非法值仍回落 all(门控是收窄,不是安全门)', () => {
    expect(parseBroadcastConnectionRole('collab')).toBe('collab')
    expect(parseBroadcastConnectionRole('collaboration')).toBe('all')
    expect(parseBroadcastConnectionRole(undefined)).toBe('all')
  })
})
