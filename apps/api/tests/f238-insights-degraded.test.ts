/**
 * F-238:洞察服务查了不存在的列 `cost_used_total_cents`,且单维度失败只 warn ——
 * 成本异常与免费敞口两个维度永久静默失效,面板看上去一切正常。
 */
import { readFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { describe, it, expect, vi } from 'vitest'

vi.hoisted(() => {
  process.env.DATABASE_URL ??= 'postgresql://test:test@localhost:5432/test'
})

const dbMock = vi.hoisted(() => ({
  execute: vi.fn(async () => {
    throw new Error('column "cost_used_total_cents" does not exist')
  }),
}))

vi.mock('../src/db/index.js', () => ({
  dbRead: { execute: dbMock.execute },
  db: { execute: dbMock.execute },
}))

import { generateInsights } from '../src/services/relay-insights-service.js'

describe('F-238 洞察服务:列名与降级可见性', () => {
  it('成本两维度查的是 llm_call_logs.cost_cents,不再出现 cost_used_total_cents', () => {
    const src = readFileSync(
      fileURLToPath(new URL('../src/services/relay-insights-service.ts', import.meta.url)),
      'utf-8',
    )
    expect(src).toContain('sum(cost_cents)')
    expect(src).toContain('COALESCE(sum(cost_cents), 0) = 0')
    // 本仓 llm_call_logs 只有 cost_cents(见 packages/database schema),不存在这个累计列。
    expect(src).not.toContain('cost_used_total_cents')
  })

  it('全维度查询失败时不得静默 —— 每个失败维度都产出可见的降级洞察', async () => {
    dbMock.execute.mockClear()
    const result = await generateInsights()

    const degraded = result.insights.filter((i) => i.type === 'analysis_degraded')
    expect(degraded).toHaveLength(5)
    expect(degraded.every((i) => i.severity === 'warning')).toBe(true)
    expect(result.summary.warning).toBe(5)
    expect(degraded[0]?.detail).toContain('does not exist')
    expect(degraded.map((i) => i.title).join('\n')).toContain('成本异常')
  })
})
