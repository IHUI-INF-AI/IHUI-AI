/**
 * F-26(2026-11-08):`parsePaging` / `pageQuerySchema` 缺页码上界。
 *
 * `page=1e308` 是有限整数,旧实现只 `Math.max(1, ...)` ⇒ page 原样保留,
 * `(page-1)*pageSize` 变成 Infinity,PG 报 `invalid input syntax for type bigint: "Infinity"`,
 * 任何列表端点都能被一个参数打成 500。本文件钉住:页码有上界、offset 全程安全整数。
 */
import { describe, it, expect } from 'vitest'
import { parsePaging, pageQuerySchema } from '../src/utils/paging'

const PAGE_MAX = 1_000_000

describe('F-26 parsePaging 页码上界', () => {
  it('page=1e308 → 夹到上界,offset 不再是 Infinity', () => {
    const { page, pageSize } = parsePaging({ page: '1e308' })
    expect(page).toBe(PAGE_MAX)
    expect((page - 1) * pageSize).toBeLessThan(Number.MAX_SAFE_INTEGER)
    expect(Number.isFinite((page - 1) * pageSize)).toBe(true)
  })

  it('page=Infinity / NaN / 负数 / 0 都回落到合法档', () => {
    expect(parsePaging({ page: 'Infinity' }).page).toBe(1)
    expect(parsePaging({ page: 'NaN' }).page).toBe(1)
    expect(parsePaging({ page: '-5' }).page).toBe(1)
    expect(parsePaging({ page: '0' }).page).toBe(1)
  })

  it('正常页码与页大小不受影响', () => {
    expect(parsePaging({ page: '3', pageSize: '50' })).toEqual({ page: 3, pageSize: 50 })
    expect(parsePaging({ pageSize: '999999' }).pageSize).toBe(100)
  })

  it('zod 形态与函数形态同一边界:pageQuerySchema 拒收 1e308', () => {
    const r = pageQuerySchema.safeParse('1e308')
    expect(r.success).toBe(false)
    expect(pageQuerySchema.safeParse(String(PAGE_MAX)).success).toBe(true)
  })
})
