/**
 * 回灌腿可转译锁(2026-10-29 立)。
 *
 * 立因:`apps/api/tsconfig.json` 的 include 只覆盖 src 目录下的 .ts,整个 scripts 目录
 * 不在 tsc 射程内 ⇒ 语法级破损能穿过 typecheck/守门全绿,直到真跑那一刻由 tsx 抛
 * `Transform failed`。2026-10-29 实测:一次 union 合并把 `relay-trae-session-sync.ts`
 * 同一 try 块里留下两个 `const deviceUpdate`,qoder 腿因 import 它而连带死掉
 * (池内号 10-29 起再没回灌过)。
 *
 * 判据:用 tsx 真转译这两枚脚本(不喂 stdin ⇒ 在 parseArgs 处返回 2,既不连库也不发
 * 上游请求),断言"用法错在、转译错不在"。摘掉 `--stdin` 卫兵或把脚本改坏都当场翻红。
 */
import { test } from 'vitest'
import assert from 'node:assert/strict'
import { spawnSync } from 'node:child_process'
import { fileURLToPath } from 'node:url'
import { dirname, resolve } from 'node:path'

const HERE = dirname(fileURLToPath(import.meta.url))
const API_DIR = resolve(HERE, '..')
const TSX = resolve(API_DIR, 'node_modules/tsx/dist/cli.mjs')

const SCRIPTS = ['scripts/relay-trae-session-sync.ts', 'scripts/relay-qoder-session-sync.ts']

for (const rel of SCRIPTS) {
  test(`${rel} 必须能被 tsx 转译(合并型重复声明是唯一打不到的形态)`, () => {
    const r = spawnSync(process.execPath, [TSX, rel, '--json'], {
      cwd: API_DIR,
      encoding: 'utf8',
      windowsHide: true,
      // 不喂 stdin(首通道 ignore)⇒ 走到 parseArgs 的用法错就返回
      stdio: ['ignore', 'pipe', 'pipe'],
      timeout: 120_000,
    })
    const stderr = String(r.stderr ?? '')
    assert.match(
      stderr,
      /必须 --stdin/,
      `没跑到用法卫兵 ⇒ 脚本起不来: exit=${r.status} ${stderr.slice(0, 400)}`,
    )
    assert.doesNotMatch(stderr, /Transform failed|already been declared/, '转译期报错 ⇒ 本腿死')
    assert.equal(r.status, 2)
  })
}
