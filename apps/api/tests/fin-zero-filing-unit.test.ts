import { describe, expect, it } from 'vitest'

import { judgeZeroFiling } from '../src/services/fin-accounting/filing-derive-service.js'

/**
 * 一键零申报的判据纯核(2026-11-24 三波)。钉的是最危险的失误方向:
 * "有票/有流水时绝不放行零申报"——零申报必须是量出来的零,不是推定的零。
 */
describe('judgeZeroFiling 一键零申报判据', () => {
  it('票 0 张且账面发生额 0 分 ⇒ 允许按零', () => {
    expect(judgeZeroFiling({ invoiceCount: 0, periodOccurrenceCents: 0 })).toEqual({ ok: true })
  })

  it('本期有票即拒绝,零不能盖过票', () => {
    const r = judgeZeroFiling({ invoiceCount: 3, periodOccurrenceCents: 0 })
    expect(r.ok).toBe(false)
    expect(r.reason).toContain('3 张票')
  })

  it('账面有发生额即拒绝(借或贷任一非零都算有数)', () => {
    expect(judgeZeroFiling({ invoiceCount: 0, periodOccurrenceCents: 1 }).ok).toBe(false)
    expect(judgeZeroFiling({ invoiceCount: 0, periodOccurrenceCents: -50_000 }).ok).toBe(false)
  })

  it('拒绝理由必须点名差异,供人复核定位', () => {
    const r = judgeZeroFiling({ invoiceCount: 0, periodOccurrenceCents: 12_345 })
    expect(r.ok).toBe(false)
    expect(r.reason).toContain('123.45')
  })
})
