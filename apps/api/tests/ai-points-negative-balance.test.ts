/**
 * 负余额欠费口径单测(纯函数,不连库)。
 *
 * 2026-11-27 立:上游已发生、冻结不足时,差额不再“扣到 0 就消失”,
 * 而是把 user_points.points 写成负数;可用余额仍夹到 0,欠费期间不能继续透支。
 */
import { describe, expect, it } from 'vitest'
import { availableOf } from '../src/services/daily-credits.js'

const TODAY = new Date('2026-11-27T12:00:00+08:00')

function row(input: {
  points: number
  dailyPoints?: number
  dailyPointsDate?: string
  reservedPoints?: number
}) {
  return {
    points: input.points,
    dailyPoints: input.dailyPoints ?? 0,
    dailyPointsDate: input.dailyPointsDate ?? '2026-11-27',
    reservedPoints: input.reservedPoints ?? 0,
  }
}

describe('availableOf 负余额口径', () => {
  it('永久余额为负时可用余额夹到 0,不把欠费当成可用余额', () => {
    expect(availableOf(row({ points: -50 }), TODAY)).toBe(0)
    expect(availableOf(row({ points: -50, reservedPoints: 20 }), TODAY)).toBe(0)
  })

  it('当日赠送先抵消欠费,剩余部分才可消费', () => {
    expect(availableOf(row({ points: -50, dailyPoints: 100 }), TODAY)).toBe(50)
    expect(availableOf(row({ points: -50, dailyPoints: 100, reservedPoints: 20 }), TODAY)).toBe(30)
  })

  it('昨日赠送不参与今日欠费抵消', () => {
    expect(
      availableOf(row({ points: -50, dailyPoints: 100, dailyPointsDate: '2026-11-26' }), TODAY),
    ).toBe(0)
  })

  it('正余额口径保持不变', () => {
    expect(availableOf(row({ points: 100, dailyPoints: 20 }), TODAY)).toBe(120)
    expect(availableOf(row({ points: 100, dailyPoints: 20, reservedPoints: 60 }), TODAY)).toBe(60)
  })
})
