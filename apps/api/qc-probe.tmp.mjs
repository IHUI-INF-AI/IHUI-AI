// 探针:验证 Fastify 5 下 querystring schema 用 type:integer 时,字符串 query 是否被正确 coerce
import Fastify from 'fastify'
import { z } from 'zod'

// 模拟我写的 query schema(含 coerce.number -> 转 integer)
const qSchema = z.object({
  departmentId: z.string().uuid().optional(),
  limit: z.coerce.number().int().min(1).max(200).optional(),
  offset: z.coerce.number().int().min(0).optional(),
})
const jsonSchema = z.toJSONSchema(qSchema, { target: 'openApi3' })
console.log('生成的 querystring schema:', JSON.stringify(jsonSchema))

const app = Fastify({ logger: false })
app.setErrorHandler((err, _req, reply) => {
  const sc = typeof err.statusCode === 'number' ? err.statusCode : 500
  reply.status(sc).send({ code: sc, message: err.message })
})

app.get('/probe', { schema: { querystring: jsonSchema } }, async (req, reply) => {
  return reply.send({ code: 0, data: { q: req.query, types: Object.fromEntries(Object.entries(req.query).map(([k,v]) => [k, typeof v])) } })
})

await app.ready()

// 测试1:正常字符串 query(HTTP query 永远是字符串)
const r1 = await app.inject({ method: 'GET', url: '/probe?departmentId=00000000-0000-4000-8000-000000000000&limit=5&offset=0' })
console.log('\n[字符串query limit=5] status=', r1.statusCode, 'body=', r1.body)

// 测试2:limit 超范围
const r2 = await app.inject({ method: 'GET', url: '/probe?limit=999' })
console.log('[limit=999 超max] status=', r2.statusCode, 'body=', r2.body)

// 测试3:额外未声明字段(测 additionalProperties:false)
const r3 = await app.inject({ method: 'GET', url: '/probe?limit=5&foo=bar' })
console.log('[额外字段 foo=bar] status=', r3.statusCode, 'body=', r3.body)

await app.close()
