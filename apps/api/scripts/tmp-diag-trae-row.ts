import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { config as dotenvConfig } from 'dotenv'
const API_DIR = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
dotenvConfig({ path: path.resolve(API_DIR, '.env') })
const { eq } = await import('drizzle-orm')
const { aiRelayAccountPool } = await import('@ihui/database')
const { db } = await import('../src/db/index.js')
const rows = await db.select().from(aiRelayAccountPool).where(eq(aiRelayAccountPool.providerCode, 'trae'))
const want = ['340221726063980', '3770697304515840']
for (const r of rows as any[]) {
  if (!want.includes(String(r.uid))) continue
  console.log('\n=== uid', r.uid, '|', r.name, '===')
  for (const [k, v] of Object.entries(r)) {
    if (v === null || v === undefined) { console.log(`  ${k} = ${v}`); continue }
    if (typeof v === 'string' && /token|secret|pem/i.test(k)) { console.log(`  ${k} = <str len=${(v as string).length}>`); continue }
    if (v instanceof Date) { console.log(`  ${k} = ${v.toISOString()}`); continue }
    const s = typeof v === 'object' ? JSON.stringify(v) : String(v)
    console.log(`  ${k} = ${s.length > 120 ? s.slice(0, 120) + '…' : s}`)
  }
}
process.exit(0)
