/**
 * 构建后资产复制:tsc 只编译 .ts,不会复制 src 下运行时 require 的 JSON 资产。
 * crew-role-loader.ts 通过 createRequire('./crew-roles.json') 加载内置角色表,
 * dist 缺该文件会导致运行时静默回退 fallback(2026-09-10 e2e CI 根修)。
 * 新增运行时 JSON 资产时在此追加。
 */
import { copyFileSync, mkdirSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, '..');

const assets = [['src/services/crew-roles.json', 'dist/services/crew-roles.json']];

for (const [src, dest] of assets) {
  const srcPath = join(root, src);
  const destPath = join(root, dest);
  if (!existsSync(srcPath)) {
    console.warn(`[copy-assets] 跳过(源不存在): ${src}`);
    continue;
  }
  mkdirSync(dirname(destPath), { recursive: true });
  copyFileSync(srcPath, destPath);
  console.log(`[copy-assets] ${src} -> ${dest}`);
}
