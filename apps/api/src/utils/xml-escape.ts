/**
 * XML/SSML 文本与属性值转义 —— **本仓唯一实现**(§0.6)。
 *
 * 立因:此前只有 services/captcha-service.ts 里有一份私有副本;新增的
 * Azure Speech TTS 路线把**用户原文**拼进 `<speak>/<voice>/<prosody>` 时没有转义出口可用,
 * 于是 `text` 里一个 `</voice>` 就能关掉外层节点、注入任意 SSML(含 `<mstts:express-as>`)。
 * 两处共用这一份,不再各写第二份。
 */
const XML_ESCAPES: Readonly<Record<string, string>> = {
  '<': '&lt;',
  '>': '&gt;',
  '&': '&amp;',
  "'": '&apos;',
  '"': '&quot;',
}

export function escapeXml(s: string): string {
  return s.replace(/[<>&'"]/g, (ch) => XML_ESCAPES[ch] ?? ch)
}
