/**
 * 大陆手机号的唯一归一/校验入口。
 *
 * 2026-10-26 代码审查:同一件事散在三处 —— auth-codes 只认 `^1[3-9]\d{9}$`,
 * admin 表单认 `^(\+?86)?1\d{10}$`,群发 SQL 的归一化又额外支持 `0086/86` 前缀。
 * 结果是「+86 号码能进后台表单、却被公开取码端点拒绝」。这里收口成一条判据:
 * 先归一(去空格/连字符/国际前缀),再按 11 位大陆号校验。
 */

export const PHONE_CN_RE = /^1[3-9]\d{9}$/

/**
 * 去国际前缀与空格/连字符,得到裸号。**不判合法性** —— 腾讯回执里的号码可能是境外号,
 * 归一必须对任何输入都有定义(返回 null 会把"能对上账"变成"对不上")。
 * 这一条是"归一"这一步的唯一实现:校验档与不校验档都必须走它,否则两份步骤必然漂移
 * (黑名单/送达对账靠的就是两边归一到同一个串)。
 */
export function stripCnSmsPrefix(raw: string): string {
  let t = raw.trim().replace(/[\s-]/g, '')
  if (t.startsWith('+86')) t = t.slice(3)
  else if (t.startsWith('0086')) t = t.slice(4)
  else if (t.startsWith('86') && t.length === 13) t = t.slice(2)
  return t
}

/** 归一为 11 位大陆手机号;不是合法号码返回 null。`0086`/`86` 前缀与空格、连字符都接受。 */
export function normalizeSmsPhone(raw: string): string | null {
  const t = stripCnSmsPrefix(raw)
  return PHONE_CN_RE.test(t) ? t : null
}

