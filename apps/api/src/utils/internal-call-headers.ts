/**
 * api → ai-service 内部调用的票据头构造(2026-11-06)。
 *
 * 与旧的 `X-Internal-Secret` 并存发送,是"最小必要兼容":滚动发布窗口内,
 * 先发布的一侧用 dual 档即可同时接受票与旧密钥;双侧全部发布后把
 * `INTERNAL_SECRET_AUTH_MODE` 切回 ticket,旧密钥即失效。
 *
 * fail-closed:签不出票就不发请求(返回 null),绝不退化成"只带常驻密钥"裸奔。
 */
import {
  mintInternalServiceTicket,
  type InternalTicketScope,
} from '../plugins/internal-service-ticket.js'

export const INTERNAL_TICKET_HEADER = 'X-Internal-Service-Ticket'
export const INTERNAL_SECRET_HEADER = 'X-Internal-Secret'

/** 服务主体(sub 以 `service:` 开头,端点不会把它当真人 uuid 去绑定归属字段)。 */
export const SERVICE_PRINCIPAL_API = 'service:apps-api'

export interface InternalCallHeaderOptions {
  scope: InternalTicketScope
  /** 用于兼容档同时携带的旧密钥;不传则只发票。 */
  legacySecret?: string | null
  /** 真人主体时传 userId;系统级调用默认服务主体。 */
  subject?: string
  extra?: Record<string, string>
}

/**
 * 构造一次内部调用的鉴权头。票据签发失败(如 JWT_SECRET 缺失)时返回 null,
 * 由调用方把这次调用按失败处理 —— 这是 fail-closed 的关键,不是可选项。
 */
export async function buildInternalCallHeaders(
  opts: InternalCallHeaderOptions,
): Promise<Record<string, string> | null> {
  try {
    const ticket = await mintInternalServiceTicket({
      userId: opts.subject ?? SERVICE_PRINCIPAL_API,
      scope: opts.scope,
    })
    if (!ticket) return null
    return {
      ...(opts.extra ?? {}),
      [INTERNAL_TICKET_HEADER]: ticket,
      ...(opts.legacySecret ? { [INTERNAL_SECRET_HEADER]: opts.legacySecret } : {}),
    }
  } catch {
    return null
  }
}
