/**
 * 进程角色判定的唯一出口(F-302)。
 *
 * API 与 worker 两个入口(`index.ts` / `worker-entry.ts`)都经 `buildServer()` 载入
 * 同一批 route/service 模块,任何"模块级定时器"都会被两边各起一份 —— 同一份
 * `~/.ihui/routines.json` 上的同一 cron 被两个进程各触发一次,persist 还整文件互相覆盖。
 *
 * 角色只由入口**显式声明**,模块自身不猜(`process.argv` / `cwd` 在测试与 PM2 下都不可靠):
 *   - `src/index.ts`(API 进程)         → 默认值 `'api'`,无需声明;
 *   - `src/worker-entry.ts`(队列 worker)→ 在 `buildServer()` 前声明 `'worker'`。
 *
 * 边界:本模块只回答"我是谁",**不承担 leader election**。多实例(蓝绿)之间
 * API 侧定时任务的独占判定仍由 `index.ts` 的 `waitForSchedulerOwnership` 负责(§22c 单一真相源)。
 */

export type ProcessRole = 'api' | 'worker'

let currentRole: ProcessRole = 'api'

/** 入口声明本进程角色(API 为默认值,worker 入口必须在 buildServer 前调用)。 */
export function declareProcessRole(role: ProcessRole): void {
  currentRole = role
}

/** 当前进程角色。 */
export function getProcessRole(): ProcessRole {
  return currentRole
}
