/**
 * 上游没回 usage 时的字符→token 兜底估算。
 *
 * 旧口径统一「字符数 ÷ 4」是按英文平均 4 字符/token 设计的;中文/日文/韩文
 * 实际约 1~1.5 字/token,÷4 会把用量低估 2~3 倍,计费少收。
 * 这里 CJK 按 1 字 = 1 token(宁可略高,不再少收),其余字符仍按 4:1。
 * 仅用于兜底;上游真实 usage 永远优先。
 */
const CJK_CHAR = /[\u3040-\u30ff\u3400-\u4dbf\u4e00-\u9fff\uf900-\ufaff\uac00-\ud7af]/u

export function estimateTextTokens(text: string | null | undefined): number {
  const raw = text ?? ''
  if (!raw) return 0
  let cjk = 0
  let other = 0
  for (const ch of raw) {
    if (CJK_CHAR.test(ch)) cjk++
    else other++
  }
  return cjk + Math.ceil(other / 4)
}
