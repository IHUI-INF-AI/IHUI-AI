/**
 * UUID 形状判据的唯一真相源(§0.6)。
 *
 * `users.id` 等主键是 Postgres `uuid` 列:非 uuid 形态的主体/参数进 SQL 会抛
 * `22P02 invalid input syntax for type uuid`,与"服务坏了"同形(500),无法追责。
 * 因此所有入口必须在查询之前用本模块拦成 400/401,而不是让数据库报错。
 */
export const UUID_STRING_RE = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i

/** 是否是可落进 Postgres `uuid` 列的规范形态(大小写不敏感)。 */
export function isUuidString(value: unknown): value is string {
  return typeof value === 'string' && UUID_STRING_RE.test(value)
}
