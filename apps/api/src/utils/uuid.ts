/**
 * uuid 形状判据的**唯一出口**(2026-09-28 立)。
 *
 * 立因有两层:
 *  ① 同一正则在 `plugins/ws-tasks.ts`、`routes/interactions.ts` 里各写了一份(字面量同形)。
 *     两处算同一件事必漂移,是本仓记过最多次的失败型 —— 这两处已并到本出口。
 *     **刻意没有并进来的第三处**:`routes/edu-supplementary-routes.ts` 用的是 `z.uuid()`,
 *     实测它比本判据**更严**(校验 RFC 版本位/变体位:`0000…-0000-…` 收,而把 variant 写成 `5…`
 *     的一串拒),两者回答的不是同一个问题 —— 本出口答"这串会不会让 `uuid` 列抛 22P02",
 *     zod 答"这串是不是一个语义合法的 uuid"。把严的换成宽的是**放宽别人的契约**,故不并。
 *  ② `GET /api/agents/<不是 uuid 的一段>` 在**游客可访问**的路由上回 **500** —— 因为
 *     `agents.agent_id` 是 `uuid` 列,`eq(agents.agentId, 'carousel')` 会让 Postgres 抛
 *     `22P02 invalid input syntax for type uuid`,而路由没有兜住它。症状是"不存在"与"服务坏了"
 *     在响应上完全同形,客户端无法分辨,监控上还是一枚 5xx。真机普查时实测到
 *     `/api/agents/carousel` 与 `/api/agents/definitely-not-a-real-slug-9x7` 双双 500。
 *
 * 用法边界:本判据只回答"这串**能不能**是一个 uuid",不回答"这条记录在不在"。
 * 因此它适合放在**进入 SQL 之前**当形状闸;放在 SQL 之后没有任何意义。
 */
export const UUID_STRING_RE = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i

export function isUuidString(value: unknown): value is string {
  return typeof value === 'string' && UUID_STRING_RE.test(value)
}
