/**
 * LIKE / ILIKE 通配符转义的唯一出口(2026-11-01 立,AGENTS §0.6 单一真相源)。
 *
 * 为什么必须有它:把用户输入直接拼进 LIKE 模式串,里面的 `%` 与 `_` 会被 Postgres 当**通配符**
 * 解释 —— 后果不是注错(参数化仍在,语法注入零命中),而是两件更安静的事:
 *  ① 匹配集被放大:`search=%` 命中全表、`search=a_b` 匹配任意单字符 ⇒ 跨行信息被读走,
 *     而 B-tree 索引在 `%…%` 前置通配下本来就用不上,一枚 `%` 就能把列表查询打成全表扫(DoS);
 *  ② 写面跟着放大:`exam-queries.ts` 那两枚用 `nickname ILIKE` 子查询圈 userId 再批量写,
 *     通配能把"某人"扩成"全体"。
 *
 * 本仓此前的形态是**六份各自实现**(voice-note / ai-world ×2 / order / tbox-points /
 * algorithm-record),口径还互不相同:五份转义 `% _ \`,第六份是**删掉** `%_` 且漏了反斜杠
 * —— 搜 `100%` 会被吃掉那个百分号。两份"包裹"、三份"不包裹",所以后来者无从复用,只能再抄一份。
 *
 * 两个原语,分工写死在这里(缺一都不能收口):
 *  - `escapeLikeChars` —— 只转义、不包裹。给**前缀/后缀/JSON 片段**形态用
 *    (`oss.ts` 定位删除目标、`user-extras.ts` 邀请码前缀、`live-queries.ts` 回调匹配);
 *  - `asContainsTerm`  —— 转义 + 包 `%…%`。给中缀搜索用(`%${kw}%` 那一族)。
 * 单源只出这两枚,不再出第三种形态:第三种就是第七份实现的种子。
 *
 * 刻意不处理的面(改这些会把功能弄坏,三条都有文档化契约):
 * `routes/admin/relay-logs.ts:40` zod 注释原文写着「客户端 IP 筛选,**支持 LIKE 通配符**(如 '192.168.%')」,
 * 同契约另有 `routes/developer-relay.ts:452` 与 `routes/admin/export-csv.ts:367` —— 那三处
 * **整值即模式**,调用方就是要传通配符。它们不得改走本文件,已在守门
 * `check-like-wildcard-escape.mjs` 的具名豁免台账里逐条登记(带理由与到期)。
 *
 * 反斜杠是 Postgres LIKE 的默认转义符,所以它必须**第一个**被转义 —— 后插会把
 * `%` 转义产生的 `\%` 再转一次,变成 `\\%`(字面反斜杠 + 通配),口径反了。
 */

/** LIKE 元字符集合:`%` 任意串、`_` 任意单字符、`\` 转义引导符。 */
const LIKE_METACHARS = /[\\%_]/g

/** 只转义,不加任何包裹。空串/非串一律回空串(不返回 null,调用方无需再判)。 */
export function escapeLikeChars(value: unknown): string {
  if (value === null || value === undefined) return ''
  return String(value).replace(LIKE_METACHARS, '\\$&')
}

/** 转义 + 包成"包含"模式。给 `%${kw}%` 那一族用。 */
export function asContainsTerm(value: unknown): string {
  return `%${escapeLikeChars(value)}%`
}

/** 转义 + 只加尾 `%`(前缀匹配)。给"按前缀定位"那一族用。 */
export function asPrefixTerm(value: unknown): string {
  return `${escapeLikeChars(value)}%`
}

export const __test__ = { LIKE_METACHARS, escapeLikeChars, asContainsTerm, asPrefixTerm }
