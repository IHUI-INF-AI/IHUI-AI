/**
 * 「活跃派单」状态判据的**唯一出口**(2026-11-01,S-ACTIVE 抽出)。
 *
 * 语义在这里定死,不许为了别的端点去改:活跃 = pending | running。这一条同时是
 * GET /subagents/active 的返回口径与并发上限(dispatch/_tryPreempt)的计数口径 ——
 * 两处本来各写一遍同一个谓词,现在合成一份。
 *
 * 抽成具名函数的目的是可引源(§22c):路由层测试 mock service.listActive 时,
 * 必须用这个生产谓词复刻,而不是在测试里另抄一份 —— 谓词一旦被放宽成"全状态",
 * 本票的语义判据即变红(见 apps/api/tests/subagents-active-tenant-isolation.test.ts ②)。
 */
export function isActiveDispatchStatus(status: string): boolean {
  return status === 'pending' || status === 'running'
}
