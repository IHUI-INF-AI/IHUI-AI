/**
 * 内部调用主体:用某个 userId 签一枚短期 JWT。
 *
 * 这个函数原先住在 `routes/v1-shared.ts`,只有 v1 系列路由能用。但"api 服务内部以某个
 * 用户身份调用 ai-service"不是 v1 面独有的需求 —— services 层的 context engine 同样需要,
 * 而 services 引 routes 是反向依赖(utils/ai-service-fetch.ts 的头注已把这条纪律写死:
 * "放参数而非本模块内签,避免 utils→routes 反向依赖")。
 *
 * 所以实现下沉到这里,`routes/v1-shared.ts` 只做 re-export 保持既有导入不变 ——
 * **签发规则全仓仍然只有一份**(AGENTS §0.6:第二份必然漂移,漂开那天没有任何东西会红)。
 */
import { signAccessToken } from '@ihui/auth'

/** 用 userId 签发短期内部 JWT,模拟内部调用满足 ai-service 的 JWT 鉴权。 */
export function mintInternalJwt(userId: string): Promise<string> {
  return signAccessToken({ userId, phone: '', familyId: `apikey-${userId}`, roleId: 0 })
}
