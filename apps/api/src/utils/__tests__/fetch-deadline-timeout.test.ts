import { describe, it, expect, vi, afterEach } from 'vitest'
import { fetchWithTimeout, fetchWithinDeadline, isDeadlineAbort } from '../fetch-deadline.js'

/** 永不返回 headers 的 fetch 形态(模拟上游挂死),仅在 abort 时 reject。 */
const hangingFetch = (_input: string | URL | Request, init: RequestInit): Promise<Response> =>
  new Promise((_resolve, reject) => {
    init.signal?.addEventListener('abort', () => reject((init.signal as AbortSignal).reason))
  })

/** headers 立即返回、响应体永不结束的 fetch 形态。 */
const stallingBodyFetch = (
  _input: string | URL | Request,
  init: RequestInit,
): Promise<Response> => {
  const stream = new ReadableStream({
    start(controller) {
      init.signal?.addEventListener('abort', () => {
        controller.error((init.signal as AbortSignal).reason)
      })
    },
  })
  return Promise.resolve(new Response(stream))
}

describe('T-3 fetchWithTimeout:出站请求必须有界', () => {
  afterEach(() => {
    vi.unstubAllGlobals()
  })

  it('headers 阶段挂死:按时拒绝,rejection 可程序化识别为 deadline abort', async () => {
    vi.stubGlobal('fetch', hangingFetch)
    const started = Date.now()
    const err: unknown = await fetchWithTimeout(
      'https://example.test/hang',
      {},
      50,
      'hang-test',
    ).catch((e: unknown) => e)
    expect(isDeadlineAbort(err)).toBe(true)
    expect((err as Error).message).toContain('50ms')
    expect(Date.now() - started).toBeLessThan(2000)
  })

  it('headers 已到但响应体停滞:deadline 不解除,body 读取仍会超时', async () => {
    const res = await fetchWithinDeadline(
      'https://example.test/stall',
      {},
      { timeoutMs: 50, label: 'stall-test', fetchImpl: stallingBodyFetch },
    )
    const err: unknown = await res.text().catch((e: unknown) => e)
    expect(isDeadlineAbort(err)).toBe(true)
    expect((err as Error).message).toContain('50ms')
  })
})
