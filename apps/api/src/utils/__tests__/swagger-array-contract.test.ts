/**
 * F-323 夹具：默认 200 契约不得把 `data` 钉成 object。
 *
 * 改前事实：`swaggerSchemas.success.properties.data = { type:'object', additionalProperties:true }`，
 * Fastify 的 fast-json-stringify 会把数组按 object 序列化成 `{"0":...,"1":...}`，
 * GET /api/proxy/extended/usage、/api/proxy/gemini/media 这类数组响应整包变形。
 */
import { describe, it, expect } from 'vitest'
import Fastify from 'fastify'
import { buildSchema } from '../swagger.js'

async function probe(payload: unknown): Promise<unknown> {
  const app = Fastify()
  app.get('/probe', { schema: buildSchema({ summary: 'f323 probe', auth: true }) }, async () => ({
    code: 0,
    message: 'ok',
    data: payload,
  }))
  const res = await app.inject({ method: 'GET', url: '/probe' })
  expect(res.statusCode).toBe(200)
  await app.close()
  return res.json().data
}

describe('F-323 响应 data 契约', () => {
  it('数组原样序列化为数组，不再是 {"0":...}', async () => {
    expect(await probe([1, 2, 3])).toEqual([1, 2, 3])
  })

  it('对象与标量仍按原值透传', async () => {
    expect(await probe({ total: 2, list: [1, 2] })).toEqual({ total: 2, list: [1, 2] })
    expect(await probe(null)).toBeNull()
    expect(await probe('ok')).toBe('ok')
  })
})
