/**
 * 登录地区键:把同一片公网出口折叠成一个"地区",用于"是否首次在该地区登录"的判定。
 *
 * 规则:
 *  - IPv4 取前两段(123.173.26.28 → 123.173),同城同运营商的动态拨号不反复触发;
 *  - IPv6 取前两组(240e:312:... → 240e:312);
 *  - 其余原样返回(空串/非法值由调用方决定是否忽略)。
 *
 * 只做地域聚合,不承担任何鉴权/限流判据。
 */
export function ipRegionKey(ip: string): string {
  const v4 = /^(\d{1,3}\.\d{1,3})\./.exec(ip)
  if (v4) return v4[1] ?? ip
  if (ip.includes(':')) {
    return ip.split(':').slice(0, 2).join(':').toLowerCase()
  }
  return ip
}
