/**
 * 申报到期提醒调度(2026-11-24 立)。
 *
 * 形态逐字照抄 jobs/hr-jobs-cron.ts:node-cron + start/stop 成对导出,
 * 启动侧挂 index.ts 的后台调度集合。每天 09:05(避开整点高峰)。
 * ENABLE_FIN_JOBS=false 禁用(默认开启)。幂等由 fin-filing-watch.ts 的
 * (任务,业务日) 通知键保证,当天重启不会重发。
 */
import cron, { type ScheduledTask } from 'node-cron'
import { logger } from '../utils/logger.js'
import { scanFilingDeadlines } from '../services/fin-filing-watch.js'

const scheduledTasks: ScheduledTask[] = []

export function startFinFilingCronScheduler(): void {
  if (scheduledTasks.length > 0) return
  if (process.env.ENABLE_FIN_JOBS === 'false') {
    logger.info('[fin-jobs] ENABLE_FIN_JOBS=false,跳过调度(startFinFilingCronScheduler 仍可手动调用)')
    return
  }
  const task = cron.schedule(
    '5 9 * * *',
    async () => {
      try {
        const r = await scanFilingDeadlines()
        logger.info('[fin-jobs] 申报到期提醒 tick', {
          date: r.date,
          reminded: r.reminded,
          deduped: r.deduped,
          skippedNoAssignee: r.skippedNoAssignee,
        })
      } catch (e) {
        logger.error('[fin-jobs] 申报到期提醒异常', {
          err: e instanceof Error ? e.message : String(e),
        })
      }
    },
    { timezone: 'Asia/Shanghai' },
  )
  scheduledTasks.push(task)
  logger.info('[fin-jobs] 申报到期提醒已调度(每日 09:05 Asia/Shanghai)')
}

export function stopFinFilingCronScheduler(): void {
  for (const t of scheduledTasks.splice(0)) t.stop()
}
