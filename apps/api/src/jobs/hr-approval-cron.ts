/**
 * 人事审批超时升级调度(HR-3 第 0 期,2026-11-11 立)。
 *
 * 形态逐字照抄 jobs/hr-jobs-cron.ts:node-cron + start/stop 成对导出,启动侧挂
 * startBackgroundSchedulers(index.ts)。单枚 cron 每 30 分钟一轮,调
 * escalateTimedOut() 把到点未决的审批节点升级给 escalation_approver_id。
 * ENABLE_HR_APPROVAL_ESCALATION=false 禁用(默认开启)。
 */
import cron, { type ScheduledTask } from 'node-cron'
import { logger } from '../utils/logger.js'
import { escalateTimedOut } from '../services/hr-approval.js'

const CRON_EXPRESSION = '0 */30 * * * *'
const scheduledTasks: ScheduledTask[] = []

export function startHrApprovalEscalationScheduler(): void {
  if (scheduledTasks.length > 0) return
  if (process.env.ENABLE_HR_APPROVAL_ESCALATION === 'false') {
    logger.info(
      '[hr-approval-cron] ENABLE_HR_APPROVAL_ESCALATION=false,跳过调度(startHrApprovalEscalationScheduler 仍可手动调用)',
    )
    return
  }
  const task = cron.schedule(
    CRON_EXPRESSION,
    async () => {
      try {
        const result = await escalateTimedOut({ now: new Date() })
        if (result.escalated > 0) {
          logger.info(`[hr-approval-cron] tick 升级 ${result.escalated} 个超时审批节点`)
        }
      } catch (e) {
        logger.error('[hr-approval-cron] 定时 tick 异常', {
          err: e instanceof Error ? e.message : String(e),
        })
      }
    },
    { timezone: 'Asia/Shanghai' },
  )
  scheduledTasks.push(task)
  logger.info(`[hr-approval-cron] cron started (cron: "${CRON_EXPRESSION}" Asia/Shanghai)`)
}

export function stopHrApprovalEscalationScheduler(): void {
  for (const t of scheduledTasks) t.stop()
  if (scheduledTasks.length > 0) logger.info('[hr-approval-cron] cron scheduler stopped')
  scheduledTasks.length = 0
}
