/**
 * 人事定时任务调度(HR-1 第 0 期,2026-11-11 立)。
 *
 * 形态逐字照抄 jobs/backup-jobs-cron.ts:node-cron + start/stop 成对导出,启动侧挂
 * startBackgroundSchedulers(index.ts)。三个任务各一枚 cron,由 hr-jobs.ts 的 HR_JOBS 单源
 * 提供表达式;每轮调 runHrJob(name, at, { manual:false }),留痕与幂等由出口统一包。
 * ENABLE_HR_JOBS=false 禁用(默认开启)。
 */
import cron, { type ScheduledTask } from 'node-cron'
import { logger } from '../utils/logger.js'
import { HR_JOBS, runHrJob } from '../services/hr-jobs.js'

const scheduledTasks: ScheduledTask[] = []

export function startHrJobsScheduler(): void {
  if (scheduledTasks.length > 0) return
  if (process.env.ENABLE_HR_JOBS === 'false') {
    logger.info('[hr-jobs] ENABLE_HR_JOBS=false,跳过调度(startHrJobsScheduler 仍可手动调用)')
    return
  }
  for (const meta of HR_JOBS) {
    const task = cron.schedule(
      meta.cron,
      async () => {
        try {
          await runHrJob(meta.name, new Date(), { manual: false })
        } catch (e) {
          logger.error('[hr-jobs] 定时 tick 异常', {
            job: meta.name,
            err: e instanceof Error ? e.message : String(e),
          })
        }
      },
      { timezone: 'Asia/Shanghai' },
    )
    scheduledTasks.push(task)
    logger.info(`[hr-jobs] cron started (job: ${meta.name}, cron: "${meta.cron}" Asia/Shanghai)`)
  }
}

export function stopHrJobsScheduler(): void {
  for (const t of scheduledTasks) t.stop()
  if (scheduledTasks.length > 0) logger.info('[hr-jobs] cron scheduler stopped')
  scheduledTasks.length = 0
}
