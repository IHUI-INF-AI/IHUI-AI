/**
 * 中转站告警规则评估调度(2026-09-16 立,深度对标补强 U)。
 *
 * node-cron 每 5 分钟评估全部启用规则(与 pii-retention-cleanup 同模式:
 * start/stop 成对,src/index.ts 启动时调用 start)。评估内部自带:
 * - 冷却防风暴(cooldownMinutes)
 * - 单规则异常隔离
 * - 推送走既有 pushAlert 通道
 */
import cron, { type ScheduledTask } from 'node-cron'
import { logger } from '../utils/logger.js'
import { evaluateAllAlertRules } from '../services/relay-alert-rules-service.js'

let scheduledTask: ScheduledTask | null = null

/** 手动触发一次评估(管理端"立即评估"按钮与调度共用)。 */
export async function runAlertRuleEvaluation(): Promise<{
  evaluated: number
  triggered: number
  skippedCooldown: number
}> {
  const result = await evaluateAllAlertRules()
  if (result.triggered > 0) {
    logger.warn('[relay-alert] 评估完成并触发告警', result)
  }
  return result
}

export function startRelayAlertEvaluationScheduler(): void {
  if (scheduledTask) return
  scheduledTask = cron.schedule(
    '*/5 * * * *',
    async () => {
      try {
        const r = await evaluateAllAlertRules()
        if (r.triggered > 0) {
          logger.warn('[relay-alert] 定时评估触发告警', r)
        }
      } catch (e) {
        logger.error('[relay-alert] 定时评估异常', {
          err: e instanceof Error ? e.message : String(e),
        })
      }
    },
    { timezone: 'Asia/Shanghai' },
  )
  logger.info('[relay-alert] evaluation scheduler started (cron: "*/5 * * * *" Asia/Shanghai)')
}

export function stopRelayAlertEvaluationScheduler(): void {
  if (scheduledTask) {
    scheduledTask.stop()
    scheduledTask = null
    logger.info('[relay-alert] evaluation scheduler stopped')
  }
}
