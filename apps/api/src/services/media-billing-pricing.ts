/**
 * 媒体生成定价(零 IO 纯判据,2026-11-21 立)。
 *
 * 与 ``media-billing.ts``(带 db/扣分 IO)分开的唯一理由是**可单测**:
 * 定价公式一旦被误改(比如把"张"改成"次"、把倍数写死),扣的就是真金白银,
 * 必须有一条不连库的测试钉住(测试隔离铁律:测试禁止连库)。
 *
 * 口径:
 *   · 单位定价 ``MEDIA_UNIT_POINTS`` —— 图像按**张**、视频按**次**;
 *   · 倍数沿用 ``inferPointsMultiplier``(与 LLM 计费同一张档位表,单一真相源);
 *   · 公式 ``ceil(units × 单位价 × 倍数)``;倍数 0(免费模型)⇒ 0 积分,完全豁免。
 *   单位价依据(对齐 LLM"1 积分 = 1000 tokens"基准):
 *     图像 3 积分 ≈ 3k tokens 算力等值 —— 2K 同步出图实测 40-50s,成本高于一次对话;
 *     视频 12 积分 ≈ 12k tokens 算力等值 —— 异步任务 + 160s 轮询 + 成片转码,明显重于图像。
 */
import { inferPointsMultiplier } from './points-multiplier.js'

/** 可计费的媒体类别。语音/OCR 目前无可用通道,不在此列。 */
export type MediaCategory = 'image' | 'video'

/** 单位定价(积分):图像按张、视频按次。改动此处即改动全站口径。 */
export const MEDIA_UNIT_POINTS: Readonly<Record<MediaCategory, number>> = Object.freeze({
  image: 3,
  video: 12,
})

/** 单次生成的积分预估(纯函数,零 IO)。units 非法(非正/非有限)一律按 1 计。 */
export function estimateMediaPoints(
  modelId: string,
  category: MediaCategory,
  units = 1,
): number {
  const multiplier = inferPointsMultiplier(modelId)
  if (multiplier <= 0) return 0
  const safeUnits = Number.isFinite(units) && units > 0 ? Math.floor(units) : 1
  return Math.ceil(safeUnits * MEDIA_UNIT_POINTS[category] * multiplier)
}
