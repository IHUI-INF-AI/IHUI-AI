import { describe, expect, it } from 'vitest'
import { isTokenZeroPriceIssue } from '../ai-model-governance-policy.js'

const base = {
  isRelayPublic: true,
  inputPricePer1k: 0,
  outputPricePer1k: 0,
  tags: ['chat'],
}

describe('isTokenZeroPriceIssue', () => {
  it('只抓公开且 token 输入/输出都明确为 0 的文本模型', () => {
    expect(isTokenZeroPriceIssue(base)).toBe(true)
  })

  it('非公开模型不算公开零价问题', () => {
    expect(isTokenZeroPriceIssue({ ...base, isRelayPublic: false })).toBe(false)
  })

  it('按次计价的图片/视频模型不算 token 零价问题', () => {
    expect(isTokenZeroPriceIssue({ ...base, tags: ['image', 'vision'] })).toBe(false)
    expect(isTokenZeroPriceIssue({ ...base, tags: ['video'] })).toBe(false)
  })

  it('null 价格是未知价,不当成 0 元', () => {
    expect(isTokenZeroPriceIssue({ ...base, inputPricePer1k: null })).toBe(false)
    expect(isTokenZeroPriceIssue({ ...base, outputPricePer1k: null })).toBe(false)
  })

  it('负数是动态成本哨兵,不当成 0 元', () => {
    expect(isTokenZeroPriceIssue({ ...base, inputPricePer1k: -100000 })).toBe(false)
    expect(isTokenZeroPriceIssue({ ...base, outputPricePer1k: -100000 })).toBe(false)
  })

  it('只有一侧为 0 时,单侧免费可能是官方计价口径,不算问题', () => {
    expect(isTokenZeroPriceIssue({ ...base, inputPricePer1k: 0.216 })).toBe(false)
    expect(isTokenZeroPriceIssue({ ...base, outputPricePer1k: 0.5 })).toBe(false)
  })
})
