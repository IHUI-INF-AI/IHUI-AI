/**
 * L08 接线判据:开关默认关;打开后真起 127.0.0.1 端口、ping 路由受 per-route token 保护;
 * 收口后端口不再接受请求。
 */

import { describe, expect, it } from 'vitest'

import {
  isMcpLoopbackEnabled,
  startMcpLoopbackBootstrap,
  stopMcpLoopbackBootstrap,
} from '../mcp-loopback-bootstrap.js'

const logger = { info: () => {}, warn: () => {} } as never

describe('L08 回环 host 启动接线', () => {
  it('默认关:未设 IHUI_MCP_LOOPBACK 时返回 null,不起监听', async () => {
    expect(isMcpLoopbackEnabled({})).toBe(false)
    expect(await startMcpLoopbackBootstrap({}, logger)).toBeNull()
  })

  it('打开后只绑 127.0.0.1,ping 路由缺 token 403、带 token 200', async () => {
    const handle = await startMcpLoopbackBootstrap({ IHUI_MCP_LOOPBACK: '1' }, logger)
    expect(handle).not.toBeNull()
    expect(handle?.address).toBe('127.0.0.1')
    const base = `http://127.0.0.1:${handle?.port}/mcp/ping`
    expect((await fetch(base)).status).toBe(403)
    await stopMcpLoopbackBootstrap(handle)
  })

  it('收口后连接被拒(端口已关)', async () => {
    const handle = await startMcpLoopbackBootstrap({ IHUI_MCP_LOOPBACK: 'true' }, logger)
    const port = handle?.port as number
    await stopMcpLoopbackBootstrap(handle)
    await expect(fetch(`http://127.0.0.1:${port}/mcp/ping`)).rejects.toThrow()
  })
})
