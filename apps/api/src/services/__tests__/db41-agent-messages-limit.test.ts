/**
 * DB-44 夹具。
 *
 * 缺陷：GET /agents/:id/messages 的 v1 分支返回整个 active 会话的 messages，
 * 常量 HISTORY_LIMIT(50) 只用于其它列表；v1 响应可无限大。
 * 判据：v1 复用「可见消息 + 最近 N 条」收敛，且路由确实调用该收敛函数。
 */
import { readFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { describe, expect, it } from 'vitest'
import type { AgentRuntimeSessionMessage } from '@ihui/database'
import { visibleAgentMessages } from '../../db/agent-chat-queries.js'

const ROUTE_SRC = readFileSync(
  join(dirname(fileURLToPath(import.meta.url)), '..', '..', 'routes', 'mobile-chat-routes.ts'),
  'utf8',
)

function messages(count: number): AgentRuntimeSessionMessage[] {
  return Array.from({ length: count }, (_, i) => ({
    id: `m${i + 1}`,
    role: 'user' as const,
    content: `c${i + 1}`,
    timestamp: i,
  }))
}

describe('DB-44 v1 历史上限', () => {
  it('只保留最近 N 条可见消息', () => {
    const tail = visibleAgentMessages(messages(120), 50)
    expect(tail).toHaveLength(50)
    expect(tail[0]?.id).toBe('m71')
    expect(tail[49]?.id).toBe('m120')
  })

  it('v1 分支使用收敛函数（不再整段返回）', () => {
    expect(ROUTE_SRC).toContain('visibleAgentMessages(messages, HISTORY_LIMIT)')
  })
})
