import { describe, expect, it } from 'vitest'
import type { WechatRuntimeAccount } from '../wechat-hub/types.js'
import { applySendPolicy } from '../wechat-hub/send-policy.js'

function account(
  metadata: Record<string, unknown>,
  allowlistEnabled = false,
): WechatRuntimeAccount {
  return {
    id: 'acc-1',
    userId: 'user-1',
    label: '测试账号',
    backend: 'mock',
    status: 'online',
    credentials: {},
    cursor: null,
    metadata,
    allowlistEnabled,
  }
}

describe('微信智联出站策略', () => {
  it('空文本与超长文本在本地拒绝', () => {
    const windows = new Map()
    expect(
      applySendPolicy(account({}), { accountId: 'acc-1', target: 'u1', text: '  ' }, windows)
        ?.status,
    ) //
      .toBe('local-rejected')
    expect(
      applySendPolicy(
        account({}),
        { accountId: 'acc-1', target: 'u1', text: 'x'.repeat(5001) },
        windows,
      )?.rejectedBy,
    ).toBe('text-too-long')
  })

  it('白名单开启但清单为空时 fail-closed', () => {
    const result = applySendPolicy(
      account({}, true),
      { accountId: 'acc-1', target: 'u1', text: 'hi' },
      new Map(),
    )
    expect(result?.ok).toBe(false)
    expect(result?.rejectedBy).toBe('allowlist')
  })

  it('白名单命中后按每分钟限额拦截', () => {
    const windows = new Map<string, { minute: number; count: number }>()
    const runtime = account({ allowedTargets: ['u1'], rateLimitPerMinute: 1 }, true)
    expect(
      applySendPolicy(runtime, { accountId: 'acc-1', target: 'u1', text: 'one' }, windows),
    ).toBeNull()
    const second = applySendPolicy(
      runtime,
      { accountId: 'acc-1', target: 'u1', text: 'two' },
      windows,
    )
    expect(second?.rejectedBy).toBe('rate-limit')
  })
})
