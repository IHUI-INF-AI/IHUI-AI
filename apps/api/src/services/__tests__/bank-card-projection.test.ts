import { describe, it, expect } from 'vitest'
import { projectBankCards } from '../bank-card-projection.js'

describe('projectBankCards', () => {
  it('只投影银行卡，且按卡号去重后取最新一条', () => {
    const cards = projectBankCards(
      [
        {
          method: 'wechat',
          accountInfo: { account: 'wx-openid' },
          createdAt: '2026-11-01T00:00:00.000Z',
        },
        {
          method: 'bank_card',
          accountInfo: { account: '6222 0212 3456 7890', holder: '张三', bank: '工商银行' },
          createdAt: '2026-11-03T00:00:00.000Z',
        },
        {
          method: 'bank',
          accountInfo: { account: '6222021234567890', bankName: '工商银行' },
          createdAt: '2026-11-02T00:00:00.000Z',
        },
      ],
      'user-1',
    )

    expect(cards).toHaveLength(1)
    expect(cards[0]).toMatchObject({
      number: '**** **** **** 7890',
      holder: '张三',
      bankName: '工商银行',
      isDefault: false,
    })
    expect(cards[0]?.id).toHaveLength(24)
  })

  it('忽略非银行卡、短卡号与空 accountInfo', () => {
    const cards = projectBankCards(
      [
        { method: 'alipay', accountInfo: { account: 'alipay-account' }, createdAt: null },
        { method: 'bank_card', accountInfo: { account: '1234567' }, createdAt: null },
        { method: 'bank_card', accountInfo: null, createdAt: null },
        { method: 'bank_card', accountInfo: [], createdAt: null },
      ],
      'user-2',
    )
    expect(cards).toEqual([])
  })

  it('缺 holder/bankName 时给中性兜底，不伪造银行/持卡人', () => {
    const cards = projectBankCards(
      [
        {
          method: 'bank_card',
          accountInfo: { bankAccount: '6228480000001234' },
          createdAt: '2026-11-01T00:00:00.000Z',
        },
      ],
      'user-3',
    )
    expect(cards[0]).toMatchObject({
      number: '**** **** **** 1234',
      holder: '—',
      bankName: '银行卡',
    })
  })
})
