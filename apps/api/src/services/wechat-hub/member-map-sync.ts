/**
 * 成员映射自动下发编排。
 *
 * 联系人/群成员在本地镜像更新后，把昵称 → 平台成员 id 的映射推给本地桥，
 * 供桥在 OCR 昵称歧义时回填真实身份。下发失败只记 warn，不回滚、不阻断原同步结果。
 */

import type { WechatActionResult } from '@ihui/types'
import { logger } from '../../utils/logger.js'
import { assertAccountForUser } from './guards.js'
import { listMemberMapEntries } from './contacts.js'
import { wechatHubManager } from './manager.js'
import type { WechatMemberMapEntry } from './types.js'

/** 一次下发的明细：条目全量 + 按来源计数 + 桥回执。 */
export interface WechatMemberMapPushSummary {
  accountId: string
  entries: WechatMemberMapEntry[]
  contactCount: number
  groupMemberCount: number
  pushed: boolean
  result: WechatActionResult
}

/** 汇总本账号映射条目并下发给桥；桥回执失败不抛错，原因写进 summary.result。 */
export async function pushMemberMapForAccount(
  userId: string,
  accountId: string,
): Promise<WechatMemberMapPushSummary> {
  await assertAccountForUser(userId, accountId)
  const entries = await listMemberMapEntries(accountId)
  const contactCount = entries.filter((entry) => entry.source === 'contact').length
  const groupMemberCount = entries.length - contactCount
  const result = await wechatHubManager.pushMemberMap(userId, accountId, entries)
  if (!result.ok) {
    logger.warn('[wechat-hub] 成员映射下发失败', {
      accountId,
      contactCount,
      groupMemberCount,
      reason: result.reason,
    })
  }
  return {
    accountId,
    entries,
    contactCount,
    groupMemberCount,
    pushed: result.ok,
    result,
  }
}
