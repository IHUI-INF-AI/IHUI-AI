/**
 * 语音占位文案的判定，单独成文件是为了让「分析/导出/转写」三层共用同一份口径，
 * 同时不把转写服务的重依赖（fs、ai-service fetch、媒体根）传染给纯计算模块。
 *
 * 桥接后端入站时会给语音消息写 `[语音]` 这类占位文案；它非空，所以：
 * - 转写层：必须认成「还没转」，否则历史语音永远转不了；
 * - 分析层：必须认成「没有文本」，否则关键词/摘要语料里会混进一堆 `[语音]`；
 * - 导出层：保留原文照出（那是归档事实），不做静默改写。
 * 三层口径都从这里来，不许各自抄一份列表。
 */

export const VOICE_PLACEHOLDERS: readonly string[] = ['[语音]', '[语音消息]', '[voice]', '[Voice]']

export function isVoicePlaceholder(content: string | null | undefined): boolean {
  const text = (content ?? '').trim()
  return text === '' || VOICE_PLACEHOLDERS.includes(text)
}
