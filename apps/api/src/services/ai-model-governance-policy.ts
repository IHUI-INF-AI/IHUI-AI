/** 按次计价的媒体模型没有 token 单价是正常状态,不能算 token 零价问题。 */
const MEDIA_PRICING_TAGS = new Set(['image', 'video', 'audio', 'music', '3d', 'generation'])

/**
 * 只抓「公开 + token 计价 + 输入/输出都明确为 0 + 非媒体」的模型。
 * null=价格未知,-100000=动态成本哨兵,都不能当成免费;媒体按次价由 perUnit 字段承载。
 */
export function isTokenZeroPriceIssue(model: {
  isRelayPublic: boolean
  inputPricePer1k: number | null
  outputPricePer1k: number | null
  tags?: string[] | null
}): boolean {
  if (!model.isRelayPublic) return false
  if (model.inputPricePer1k === null || model.outputPricePer1k === null) return false
  if (Number(model.inputPricePer1k) !== 0 || Number(model.outputPricePer1k) !== 0) return false
  const tags = (model.tags ?? []).map((tag) => String(tag).toLowerCase())
  return !tags.some((tag) => MEDIA_PRICING_TAGS.has(tag))
}
