/**
 * Agent SSE 事件总线(进程内广播)。
 *
 * 从 routes/agents-kanban.ts 抽出为独立模块(2-2 P0 修复):
 * workspace-lock-heartbeat / subagent-dispatch 等 service 需要广播 SSE 事件,
 * 若直接 import 路由层会造成 service → route 的反向依赖(且 route 已 import 这些
 * service,会形成循环导入)。事件总线本身无业务逻辑,下沉到 services 层。
 */
import { EventEmitter } from 'events'
import type { AgentSSEEvent } from '@ihui/types'

export const sseEventBus = new EventEmitter()
sseEventBus.setMaxListeners(0)

/** 广播 Agent SSE 事件(所有 /agents/kanban/tasks/stream 订阅者都会收到) */
export function broadcastSSEEvent(event: AgentSSEEvent): void {
  sseEventBus.emit('agent-sse', event)
}
