/**
 * 管理面 provider 元数据。
 *
 * `provider_code` 本身只是路由键,但管理页需要回答"它是直连、账号池还是本机桥"。
 * 这张表刻意放在服务层而不是数据库:先让展示语义单源,后续再迁到 provider registry。
 */
import { isRelayProviderCode } from './relay-account-format.js'

export type ProviderRuntimeMode = 'account_pool' | 'local_bridge' | 'http' | 'mock'

const LOCAL_BRIDGE_PROVIDERS = new Set(['qoder'])
const MOCK_PROVIDERS = new Set(['custom', 'mock'])

const DISPLAY_NAMES: Record<string, string> = {
  qoder: 'Qoder',
  trae: 'Trae',
  workbuddy: 'WorkBuddy',
  codearts: 'CodeArts',
  opencode: 'OpenCode',
  zcode: 'Zcode',
  loomy: 'Loomy',
  minimax: 'MiniMax',
  doubao: '豆包',
  lingma: '通义灵码',
  grokbot: 'GrokBot',
  raccoon: 'Raccoon',
  cursor: 'Cursor',
  openai: 'OpenAI',
  anthropic: 'Anthropic',
  cohere: 'Cohere',
  swiftapi: 'SwiftAPI',
  custom: '自定义',
}

export function providerRuntimeMode(providerCode: string | null | undefined): ProviderRuntimeMode {
  const code = String(providerCode ?? '').toLowerCase()
  if (LOCAL_BRIDGE_PROVIDERS.has(code)) return 'local_bridge'
  if (MOCK_PROVIDERS.has(code)) return 'mock'
  if (isRelayProviderCode(code)) return 'account_pool'
  return 'http'
}

export function providerDisplayName(providerCode: string | null | undefined): string {
  const code = String(providerCode ?? '').toLowerCase()
  return DISPLAY_NAMES[code] ?? providerCode ?? ''
}

export function runtimeModeLabel(mode: ProviderRuntimeMode): string {
  switch (mode) {
    case 'account_pool':
      return '账号池反代'
    case 'local_bridge':
      return '本机 SDK 桥'
    case 'mock':
      return 'Mock'
    default:
      return 'HTTP 直连'
  }
}
