/**
 * 资讯生成/发布统计的 ai-service 代理(2026-10-31 安全强化第 31 批)。
 *
 * 为什么单独成模块:这条代理是"web 绕过 apps/api 直连 8803"根因修复的一部分
 * (next.config 里 `/api/admin/news/:path*` 整段 rewrite 已删),它需要能被单测
 * 钉住(字段保真 / 非 2xx 透传 / 上游异常 502),而 news 路由文件的模块级依赖
 * 会拖入 DB 查询与缓存层。代理判据只此一份,路由层只做 reply 包装。
 */

import type { FastifyRequest } from 'fastify'
import { aiServiceFetch } from '../utils/ai-service-fetch.js'

export type NewsStatusProxyResult =
  { ok: true; status: number; payload: unknown } | { ok: false; status: number; message: string }

/**
 * 拉取 ai-service `/api/admin/news/status`(ai-service 侧要求登录;apps/api 侧
 * 由调用方挂 `requireAuth`,与改造前的可见性一致:登录可读、匿名不可读)。
 */
export async function fetchNewsStatus(request: FastifyRequest): Promise<NewsStatusProxyResult> {
  try {
    const upstream = await aiServiceFetch(request, '/api/admin/news/status', { method: 'GET' })
    const text = await upstream.text()
    let payload: unknown = text
    if ((upstream.headers.get('content-type') ?? '').includes('application/json')) {
      try {
        payload = JSON.parse(text) as unknown
      } catch {
        // 非 JSON 正文保留原始 text(由调用方原样放进信封)
      }
    }
    if (upstream.ok) return { ok: true, status: upstream.status, payload }
    return { ok: false, status: upstream.status, message: `资讯统计获取失败: ${upstream.status}` }
  } catch {
    // 不把异常正文透给客户端(上游地址/内部细节不外泄)
    return { ok: false, status: 502, message: 'ai-service unavailable' }
  }
}
