/**
 * 会计期间工具(纯函数,零 DB 依赖)。
 *
 * 期间一律用 "YYYY-MM" 字符串:比较即字典序,跨年推进不需要日期对象,
 * 也不会因为时区把 12 月 31 日算成次年 1 月。
 */

import { AppError } from '../../errors/AppError.js'

export const PERIOD_RE = /^\d{4}-(0[1-9]|1[0-2])$/

export function assertPeriod(period: string, where = 'period'): void {
  if (!PERIOD_RE.test(period)) {
    throw new AppError(`${where} 必须是 YYYY-MM(01~12 月)`, 400, 'FIN_BAD_PERIOD')
  }
}

export function nextPeriod(period: string): string {
  assertPeriod(period)
  const [y, m] = period.split('-').map(Number) as [number, number]
  return m === 12 ? `${y + 1}-01` : `${y}-${String(m + 1).padStart(2, '0')}`
}

export function prevPeriod(period: string): string {
  assertPeriod(period)
  const [y, m] = period.split('-').map(Number) as [number, number]
  return m === 1 ? `${y - 1}-12` : `${y}-${String(m - 1).padStart(2, '0')}`
}

export function nextPeriodOf(period: string): string {
  return nextPeriod(period)
}

/** 期间最后一天(YYYY-MM 的第 N 天),用于系统生成的结转凭证日期 */
export function lastDayOf(period: string): string {
  assertPeriod(period)
  const [y, m] = period.split('-').map(Number) as [number, number]
  const day = new Date(Date.UTC(y, m, 0)).getUTCDate()
  return String(day).padStart(2, '0')
}
