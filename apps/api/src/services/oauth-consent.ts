/**
 * 第三方 OAuth 登录的「用户协议同意」判据 —— **唯一真相源**。
 *
 * 通用回调 `POST /auth/:platform/callback` 在查/建用户与签发 token 之前必须知道
 * 发起这次授权的用户是否真的同意过条款。web 与 RN 端此前只在前端采集同意,
 * 服务端没有任何记录 ⇒ 绕过前端直接打回调即可在未同意的情况下拿到 token。
 *
 * 机制:客户端在跳转厂商前调用 `POST /auth/oauth/consent`,把同意结果按 state
 * 写入 Redis(`oauth:consent:<state>`,TTL 600s);回调侧一次性 get + del 消费,
 * 缺失 / 过期 / 平台不符 / 未同意一律拒绝。本文件只保留纯判据,Redis I/O 留在
 * 路由层(与既有 `/auth/oauth/*` 家族同一模式)。
 */

/** 未同意条款的机器可判错误码(HTTP 403 的 errorCode 字段)。 */
export const OAUTH_AGREEMENT_REQUIRED = 'OAUTH_AGREEMENT_REQUIRED'

/** 发起期同意记录的 Redis key 前缀(一次性消费)。 */
export const OAUTH_CONSENT_KEY_PREFIX = 'oauth:consent:'

/** 同意记录有效期:10 分钟,覆盖用户在 IdP 授权页的正常停留时长。 */
export const OAUTH_CONSENT_TTL_SECONDS = 600

/** 同意记录载荷;判据只依赖 platform 与 agreementAccepted 两格。 */
export interface OAuthConsentState {
  platform?: string
  agreementAccepted?: boolean
}

/**
 * 该 state 的发起期同意记录是否足以放行回调。
 *
 * 缺省 / 脏值 / 平台不符一律按未同意处理(fail-closed):记录丢失、过期、
 * 或把 A 平台的 state 拿去 B 平台回调,都不得换取 token。
 */
export function isOAuthConsentRecorded(
  state: OAuthConsentState | null | undefined,
  platform: string,
): boolean {
  if (!state) return false
  if (state.agreementAccepted !== true) return false
  return state.platform === platform
}
