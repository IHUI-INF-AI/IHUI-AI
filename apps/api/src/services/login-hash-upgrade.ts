import { updateUser } from '../db/queries.js'
import { upgradeHashIfNeeded } from '../utils/password-crypto.js'

/**
 * 登录成功后的**透明哈希升级**（唯一出口）。
 *
 * 为什么要抽这一层：升级判据本来只住在 /auth/login 一处内联代码里，
 * 而 `/auth/login/password`、`/auth/login/username` 两个登录入口只 verify 不升级
 * （2026-10-28 普查发现）。今天库里 0 条 bcrypt/SHA256 存量，所以这不是急症；
 * 但只要有一次从外部导入过 bcrypt 哈希并走了别名入口登录，那条账户就**永远升不上去**，
 * 而 /auth/login 那条会升 —— 三个入口三种结果，正是"同类判据多份必然漂移"那一型(§0.6)。
 *
 * 容错方向：升级失败**绝不阻断登录**。实测成因是 system admin 这类不可变用户
 * 带 immutability trigger，updateUser 会抛 PostgresError —— 把它冒泡到登录就是 500。
 */
export interface LoginHashUpgradeLog {
  info: (obj: unknown, msg?: string) => void
  warn: (obj: unknown, msg?: string) => void
}

export async function transparentlyUpgradePasswordHash(params: {
  userId: string
  password: string
  currentHash: string
  log: LoginHashUpgradeLog
}): Promise<boolean> {
  try {
    const upgraded = await upgradeHashIfNeeded(params.password, params.currentHash)
    if (!upgraded) return false
    await updateUser(params.userId, { passwordHash: upgraded })
    params.log.info({ userId: params.userId }, '密码哈希已透明升级 bcrypt→argon2id')
    return true
  } catch (e) {
    params.log.warn(
      { err: String(e), userId: params.userId },
      '密码哈希透明升级失败(可能是 system admin 不可变用户触发 trigger),跳过升级,登录流程继续',
    )
    return false
  }
}
