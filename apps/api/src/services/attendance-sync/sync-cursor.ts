/**
 * 考勤同步器 — 增量游标存储(2026-11-13 立)。
 *
 * 用 system_configs KV 表存游标(schema 零改动),键名:
 *   sync:cursor:{userId}:{source}:{kind}
 *
 * 游标语义由各 provider 定义(时间戳 / 平台 page token / 最近更新时间),
 * 本层只做「读上次 → provider 用 → 写本次」,不解释内容。
 */

import { eq } from 'drizzle-orm'
import { db } from '../../db/index.js'
import { systemConfigs } from '@ihui/database'
import type { SyncKind, SyncSource } from './types.js'

function cursorKey(userId: string, source: SyncSource, kind: SyncKind): string {
  return `sync:cursor:${userId}:${source}:${kind}`
}

/** 读上次同步游标;首次为 null(provider 走全量窗口) */
export async function readSyncCursor(
  userId: string,
  source: SyncSource,
  kind: SyncKind,
): Promise<string | null> {
  const key = cursorKey(userId, source, kind)
  const [row] = await db
    .select({ value: systemConfigs.value })
    .from(systemConfigs)
    .where(eq(systemConfigs.key, key))
    .limit(1)
  return row?.value ?? null
}

/** 写本次游标(upsert:key 唯一) */
export async function writeSyncCursor(
  userId: string,
  source: SyncSource,
  kind: SyncKind,
  cursor: string,
): Promise<void> {
  const key = cursorKey(userId, source, kind)
  const [existing] = await db
    .select({ id: systemConfigs.id })
    .from(systemConfigs)
    .where(eq(systemConfigs.key, key))
    .limit(1)

  if (existing) {
    await db
      .update(systemConfigs)
      .set({ value: cursor, updatedAt: new Date() })
      .where(eq(systemConfigs.id, existing.id))
  } else {
    await db.insert(systemConfigs).values({
      key,
      value: cursor,
      type: 'string',
      category: 'hr_sync',
      description: `考勤同步游标(${source}/${kind})`,
      isPublic: false,
    })
  }
}
