import type { FastifyReply, FastifyRequest } from 'fastify'
import { and, eq } from 'drizzle-orm'
import { db } from '../db/index.js'
import { tenantMembers } from '@ihui/database'
import { isSystemAdmin } from '../plugins/require-permission.js'
import { error } from '../utils/response.js'

export type TenantRole = 'owner' | 'admin' | 'member'

export const TENANT_ROLE_RANK: Record<TenantRole, number> = { owner: 3, admin: 2, member: 1 }

export function tenantRoleRank(role: string): number {
  return TENANT_ROLE_RANK[role as TenantRole] ?? 0
}

/**
 * 租户成员资格 + 角色校验（从 routes/tenant.ts 抽出的单一出口）。
 *
 * 非成员与"租户不存在"同形返回 404 —— 不给外部拿 403/404 差异枚举租户 ID 的信号。
 * 平台管理员旁路只对后台运维开放（includeInternalChannel=false，内部服务通道不算管理员）。
 */
export async function guardTenantAccess(
  request: FastifyRequest,
  reply: FastifyReply,
  tenantId: string,
  minRole: 'member' | 'admin' = 'member',
): Promise<boolean> {
  const userId = request.userId
  if (!userId) {
    reply.status(401).send(error(401, '未登录'))
    return false
  }
  if (isSystemAdmin(request, { includeInternalChannel: false })) return true
  const [row] = await db
    .select({ role: tenantMembers.role })
    .from(tenantMembers)
    .where(and(eq(tenantMembers.tenantId, tenantId), eq(tenantMembers.userId, userId)))
    .limit(1)
  if (!row) {
    reply.status(404).send(error(404, '租户不存在'))
    return false
  }
  if (tenantRoleRank(row.role) < tenantRoleRank(minRole)) {
    reply.status(403).send(error(403, '需要租户管理员权限'))
    return false
  }
  return true
}

/** 操作者在本租户的有效角色；平台管理员按最高档处理（与 guardTenantAccess 旁路同口径）。 */
export async function resolveOperatorRole(
  request: FastifyRequest,
  tenantId: string,
): Promise<TenantRole> {
  if (isSystemAdmin(request, { includeInternalChannel: false })) return 'owner'
  const userId = request.userId
  if (!userId) return 'member'
  const [row] = await db
    .select({ role: tenantMembers.role })
    .from(tenantMembers)
    .where(and(eq(tenantMembers.tenantId, tenantId), eq(tenantMembers.userId, userId)))
    .limit(1)
  return (row?.role as TenantRole | undefined) ?? 'member'
}
