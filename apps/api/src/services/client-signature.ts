/**
 * 客户端签名的服务端薄壳(2026-11-17 立)。
 *
 * 算法唯一实现在 `@ihui/shared` 的 `utils/client-sign.ts`(与三端同一份,纯 JS SHA-256);
 * 本文件只做两件本地化的事:**从环境读密钥**、**读严格模式开关**。判据不得在服务端另抄一份
 * (抄第二份的后果是端与服务端的拼接格式漂开,全端登录 403 且日志看不出原因)。
 *
 * 失效方向恒为"多一次人机验证":密钥没配 / 签名缺失 / 签名损坏 ⇒ 一律 `signed=false`,
 * 由调用方回落到既有 UA 判据 —— 绝不因为"验签没过"就放行。
 */

import { verifyClientSignature as verifyShared } from '@ihui/shared'

/** 结构化结论;`reason` 只为日志可读,不参与放行判断(判断只看 `signed`) */
export type ClientSignatureVerdict = ReturnType<typeof verifyShared>

/**
 * 校验请求头 `X-IHUI-Client`。
 * 密钥来源:`IHUI_CLIENT_SIGN_SECRET`(apps/api/.env,与三端打包注入的值必须一致)。
 */
export function verifyClientSignature(raw: unknown): ClientSignatureVerdict {
  return verifyShared(raw, process.env.IHUI_CLIENT_SIGN_SECRET ?? '')
}

/**
 * 严格模式开关(`IHUI_CLIENT_SIGN_STRICT=1`)。
 *
 * 打开后:非浏览器 UA 但**没有有效签名**的请求同样要求 Turnstile —— 这是"改 UA 绕过"
 * 被真正堵死的时刻。打开前提是三端(Android / iOS / 小程序 / 桌面)全部已发版并带上
 * `X-IHUI-Client`;**默认关闭**,未打开时行为与本改动之前逐字相同。
 */
export function isClientSignatureStrict(): boolean {
  return process.env.IHUI_CLIENT_SIGN_STRICT === '1'
}

/** 当前是否已配置密钥(用于启动日志/健康检查暴露"签名面是否就绪",不暴露密钥本身) */
export function isClientSignatureConfigured(): boolean {
  return Boolean(process.env.IHUI_CLIENT_SIGN_SECRET)
}
