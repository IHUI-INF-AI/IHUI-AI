/**
 * 推送型来源(webhook / IM 回调)的落账缓冲端口。
 *
 * 只做"先落账、泵下一拍取走"一件事件:**绝不去重**。重复投递照样进队、照样交给
 * SuperAgentHost.receive(),由引擎的 triggers 集判 duplicate —— 幂等唯一真源在引擎。
 */

import type { IncomingTrigger, TriggerSourcePort } from '@ihui/shared/super-agent'

export class BufferedTriggerSourcePort implements TriggerSourcePort {
  private queue: IncomingTrigger[] = []
  private taken = 0

  constructor(
    readonly sourceId: string,
    readonly ownerUserId: string,
  ) {}

  /** 入队即返回;不查重、不合并。 */
  enqueue(trigger: IncomingTrigger): void {
    this.queue.push(trigger)
  }

  async fetchTriggers(): Promise<IncomingTrigger[]> {
    if (this.queue.length === 0) return []
    const out = this.queue
    this.queue = []
    this.taken += out.length
    return out
  }

  /** 健康读数:仅用于观测,不参与幂等判断。 */
  health(): { pending: number; taken: number } {
    return { pending: this.queue.length, taken: this.taken }
  }

  clear(): void {
    this.queue = []
  }
}
