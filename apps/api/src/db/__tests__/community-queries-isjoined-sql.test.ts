/**
 * isJoined 子查询的 SQL 形状锁。
 *
 * 回归点(2026-11-27 线上实跑抓到):子查询里 `circle_members` 也有 `id` 列,
 * 若外层 `circles.id` 不限定表名,Postgres 会把未限定 `"id"` 解析成内层
 * `circle_members.id`,条件退化为 `circle_id = id` 恒 false ⇒ 所有已加入用户都读成未加入。
 * 本测试只构造 SQL(不连库),钉住外层 id 必须带 `"circles"` 限定。
 */
import { describe, expect, it, vi } from 'vitest'
import { eq } from 'drizzle-orm'
import { drizzle } from 'drizzle-orm/postgres-js'
import postgres from 'postgres'
import { circles } from '@ihui/database'

vi.mock('../index.js', () => ({ db: {}, dbRead: {} }))

import { circleSelectColumns } from '../community-queries.js'

const ME = '11111111-1111-4111-8111-111111111111'

describe('circleSelectColumns isJoined SQL', () => {
  it('外层 circles.id 带表名,避免被 circle_members.id 遮蔽', () => {
    const client = postgres('postgresql://test:test@localhost:5432/test', {
      max: 1,
      idle_timeout: 1,
      onnotice: () => {},
    })
    const db = drizzle(client)
    const sql = db
      .select(circleSelectColumns(ME))
      .from(circles)
      .where(eq(circles.slug, 'isjoined-sql-shape'))
      .toSQL()

    expect(sql.sql).toContain('"circles"."id"')
    expect(sql.sql).not.toContain('WHERE "circle_id" = "id"')
    expect(sql.params).toContain(ME)

    void client.end({ timeout: 0 })
  })

  it('匿名(viewerId 缺省)恒 false,不生成成员子查询', () => {
    const cols = circleSelectColumns(undefined)
    expect(cols.isJoined).toBeDefined()
  })
})
