import type { FastifyPluginAsync } from 'fastify'
import { z } from 'zod'
import { desc, eq, sql } from 'drizzle-orm'
import { agentReviews, agents, users } from '@ihui/database'
import { success, error } from '../utils/response.js'
import { checkAuth } from '../plugins/auth.js'
import { dbRead } from '../db/index.js'

const listQuerySchema = z
  .object({
    page: z.coerce.number().int().min(1).default(1),
    pageSize: z.coerce.number().int().min(1).max(50).default(20),
  })
  .strict()

/**
 * 用户评价:当前用户名下智能体收到的评价。
 * 只读、只展示昵称,不返回评价者 id/手机号等身份字段。
 */
export const agentReviewRoutes: FastifyPluginAsync = async (server) => {
  server.get('/agent-reviews', async (request, reply) => {
    if (!(await checkAuth(request, reply))) return
    const userId = request.userId
    if (!userId) return reply.status(401).send(error(401, '未登录'))
    const q = listQuerySchema.parse(request.query)
    const rows = await dbRead
      .select({
        id: agentReviews.id,
        agentName: agents.name,
        nickname: users.nickname,
        rating: agentReviews.rating,
        content: agentReviews.content,
        createdAt: agentReviews.createdAt,
      })
      .from(agentReviews)
      // agent_reviews.agent_id 是 varchar,agents.agent_id 是 uuid:右侧显式转 text,
      // 避免 uuid = varchar 在 Postgres 里没有比较算子(22P02/42883)而 500。
      .innerJoin(agents, sql`${agents.agentId}::text = ${agentReviews.agentId}`)
      .leftJoin(users, eq(users.id, agentReviews.userId))
      .where(eq(agents.userId, userId))
      .orderBy(desc(agentReviews.createdAt))
      .limit(q.pageSize)
      .offset((q.page - 1) * q.pageSize)

    return reply.send(
      success(
        rows.map((row) => ({
          id: row.id,
          agentName: row.agentName,
          author: row.nickname?.trim() || '匿名用户',
          rating: row.rating,
          content: row.content ?? '',
          createdAt: row.createdAt.toISOString(),
        })),
      ),
    )
  })
}
