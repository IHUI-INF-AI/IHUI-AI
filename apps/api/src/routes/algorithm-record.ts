/**
 * 国家网信办「算法/模型备案」公开查询路由。
 *
 * 公开(免登录):任何访客可查询全网已备案的算法/模型记录(数据来自网信办官方批量公告清单)。
 * 用户自身不开发模型，因此这里只提供"全网公开备案"查询，不再展示本平台的虚假备案号。
 *
 * GET /api/algorithm-record/search?q=&kind=&batch=&category=&page=&pageSize=
 *  - q: 关键字(算法名称/主体名称/备案编号/算法类别/应用产品)
 *  - kind: algorithm_recommend | deep_synthesis(可选)
 *  - batch: 批次(如 2026-07,可选)
 *  - category: 算法类别/角色(可选)
 *  - page / pageSize: 分页(默认 1 / 20,最大 100)
 */
import type { FastifyPluginAsync } from 'fastify'
import { z } from 'zod'
import {
  success,
  error,
  emptyToUndefined,
} from '../utils/response.js'
import {
  searchAlgorithmRecords,
  ALGORITHM_RECOMMEND_KIND,
  DEEP_SYNTHESIS_KIND,
} from '../services/algorithm-record-service.js'

const querySchema = z.object({
  q: z.transform(emptyToUndefined).pipe(z.string().trim().max(128).optional()),
  kind: z
    .transform(emptyToUndefined)
    .pipe(z.enum([ALGORITHM_RECOMMEND_KIND, DEEP_SYNTHESIS_KIND]).optional()),
  batch: z.transform(emptyToUndefined).pipe(z.string().trim().max(32).optional()),
  category: z.transform(emptyToUndefined).pipe(z.string().trim().max(128).optional()),
  page: z.coerce.number().int().min(1).default(1),
  pageSize: z.coerce.number().int().min(1).max(100).default(20),
})

const algorithmRecordRoutes: FastifyPluginAsync = async (server) => {
  // 公开查询(无需鉴权)
  server.get('/algorithm-record/search', async (request, reply) => {
    const parsed = querySchema.safeParse(request.query)
    if (!parsed.success) {
      return reply.status(400).send(error(400, parsed.error.issues[0]?.message ?? '参数错误'))
    }
    const result = await searchAlgorithmRecords({
      q: parsed.data.q,
      kind: parsed.data.kind,
      batch: parsed.data.batch,
      category: parsed.data.category,
      page: parsed.data.page,
      pageSize: parsed.data.pageSize,
    })
    return reply.send(success(result))
  })
}

export default algorithmRecordRoutes
