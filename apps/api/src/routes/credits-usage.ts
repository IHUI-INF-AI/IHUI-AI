// 按日积分消耗聚合只读路由(需登录)。前缀 /api/credits(注册方见 routes/index.ts)。
// 鉴权面纪律(AGENTS.md §5):整棵子树走 preHandler authenticate 强制登录,
// 不使用任何 `/api/<前缀>/[^/]+` 参数正则当公开面;新端点默认登录态。

import type { FastifyPluginAsync, FastifyRequest, FastifyReply } from 'fastify'
import { z } from 'zod'
import { authenticate } from '../plugins/auth.js'
import { getDailyCreditsUsage, MAX_CREDITS_USAGE_DAYS } from '../services/credits-usage-service.js'
import { success, error } from '../utils/response.js'
import { buildResponseSchema } from '../utils/api-schemas.js'

const dailyUsageQuerySchema = z.object({
  days: z.coerce.number().int().min(1).max(MAX_CREDITS_USAGE_DAYS).default(90),
})

export const creditsUsageRoutes: FastifyPluginAsync = async (server) => {
  // 统一鉴权:所有端点需登录
  server.addHook('preHandler', async (request: FastifyRequest, reply: FastifyReply) => {
    try {
      await authenticate(request)
    } catch (e) {
      const statusCode = (e as Error & { statusCode?: number }).statusCode ?? 401
      const message = (e as Error).message || '操作失败,请稍后重试'
      return reply.status(statusCode).send(error(statusCode, message))
    }
  })

  // GET /usage/daily?days=90 - 当前用户最近 N 天按日积分消耗聚合(UTC 分桶,缺日补零)
  server.get(
    '/usage/daily',
    {
      schema: {
        summary: '按日积分消耗聚合(只读)',
        tags: ['credits'],
        // 参数校验一律交给下方 Zod(min 1 / max 365 / 越界 400),
        // 不声明 Fastify querystring JSON schema:那会让校验先于鉴权执行,
        // 且默认错误体不经本路由的统一 { code, message } 序列化。
        response: buildResponseSchema(400, 401),
      },
    },
    async (request, reply) => {
      const userId = request.userId!
      const parsed = dailyUsageQuerySchema.safeParse(request.query)
      if (!parsed.success) {
        return reply.status(400).send(error(400, parsed.error.issues[0]?.message ?? '参数错误'))
      }
      const data = await getDailyCreditsUsage({ userId, days: parsed.data.days })
      return reply.send(success(data))
    },
  )
}
