/**
 * 主机诊断只读面(2026-11-17 立)。
 *
 * `GET /api/admin/relay/diagnostics/host` —— 把 `collectHostDiagnostics()` 的结果原样交出。
 *
 * 为什么独立成插件:诊断面不该往已有 40+ 端点的号池管理文件里再塞一条(那个文件是多人
 * 在飞面);独立插件也让端点行为能被轻量 Fastify 直接钉住。
 *
 * 权限:沿用 `requireAdmin`(与号池管理面同档),诊断结果含主机名与路径,不对外公开。
 */
import type { FastifyPluginAsync } from 'fastify'
import { requireAdmin } from '../../plugins/require-permission.js'
import { success } from '../../utils/response.js'
import { collectHostDiagnostics } from '../../services/host-diagnostics.js'

export const relayDiagnosticsRoutes: FastifyPluginAsync = async (server) => {
  server.addHook('preHandler', requireAdmin)

  server.get('/admin/relay/diagnostics/host', async (_request, reply) => {
    return reply.send(success(collectHostDiagnostics()))
  })
}

export default relayDiagnosticsRoutes
