/**
 * Cosy 能力自述端点(2026-11-18 立)。
 *
 * `GET /api/admin/relay/cosy-capability` —— 把「设备头族有哪些、请求签名可不可复现、
 * 不可复现时走哪条通路」变成可查询的数据,避免每次排障都去翻 adapter 源码。
 *
 * 只读、无副作用、不含任何凭据值(只吐键位与头名)。
 */
import type { FastifyPluginAsync } from 'fastify'
import { requireAdmin } from '../../plugins/require-permission.js'
import { success } from '../../utils/response.js'
import { describeCosyCapability } from '../../services/relay-cosy-capability.js'

export const relayCosyCapabilityRoutes: FastifyPluginAsync = async (server) => {
  server.get('/admin/relay/cosy-capability', { preHandler: requireAdmin }, async (_request, reply) => {
    return reply.send(success(describeCosyCapability()))
  })
}

export default relayCosyCapabilityRoutes
