/**
 * G-1058623③ 智能体分类字典公开端点(机主拍板:新建公开双键字典端点)。
 *
 * 背景:api-client getAgentCategories() 调 GET /api/cache/agent-category-dict/categories
 * (fetchApi 的 normalizeUrl 把 /cozeZhsApi 前缀归一为 /api),此前后端零命中,
 * 4 个 RN 调用方(HomeScreen/PlazaScreen/AgentScreen/AiAssistantScreen)全靠静态 fallback 降级。
 * 既有管理面路由 agent-categories-cache.ts(带 requireAdmin)不可直接开放(权限面),
 * 故新建本公开**只读**端点:数据构建复用其缓存存储的推导函数 buildAgentCategoryDict(),
 * admin 路由本身的行为零改动。
 *
 * 路径:绝对路径字面量注册,确保 scripts/check-api-routes.mjs 静态扫描可识别。
 * 鉴权:公开(无 auth preHandler,字典无用户隐私);限流:每 IP 每分钟 60 次(照 public-status.ts 公开路由惯例)。
 * 返回:{ code:0, message:'success', data:{ agentCategory:[{id,name}], agentMainCategory:[{id,name}] } },
 * 与 packages/api-client/src/endpoints/agent.ts 的 AgentCategories 契约逐字对齐。
 */
import type { FastifyPluginAsync } from 'fastify'
import { success } from '../utils/response.js'
import { buildResponseSchema } from '../utils/api-schemas.js'
import { buildAgentCategoryDict } from './agent-categories-cache.js'

const RATE_LIMIT_CONFIG = { max: 60, timeWindow: '1 minute' as const }

export const agentCategoryDictRoutes: FastifyPluginAsync = async (server) => {
  server.get(
    '/api/cache/agent-category-dict/categories',
    {
      config: { rateLimit: RATE_LIMIT_CONFIG },
      schema: { response: buildResponseSchema() },
    },
    async (_request, reply) => {
      return reply.send(success(buildAgentCategoryDict()))
    },
  )
}
