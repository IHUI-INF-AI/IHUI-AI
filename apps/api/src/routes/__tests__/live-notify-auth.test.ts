// 2026-11-07: live notify begin/end 原先完全公开,可被伪造刷直播状态与指标。
// 三组判据(用户要求):无签名 401、签名错 403、正确签名 200;且拒绝时指标不得被写。
import { describe, it, expect, beforeAll, afterAll, vi } from 'vitest'
import Fastify, { type FastifyInstance } from 'fastify'

const SECRET = 'test-live-notify-secret'

vi.hoisted(() => {
  process.env.DATABASE_URL ??= 'postgresql://test:test@localhost:5432/test'
  process.env.JWT_SECRET ??= 'test-jwt-secret-for-vitest-at-least-32-chars'
  process.env.LIVE_NOTIFY_SECRET = 'test-live-notify-secret'
})

import { liveRoutes } from '../live.js'

describe('Live notify 内部回调共享密钥', () => {
  let app: FastifyInstance
  const recordDisconnected = vi.fn()

  beforeAll(async () => {
    app = Fastify({ logger: false })
    app.decorate('recordLiveStreamDisconnected', recordDisconnected as never)
    await app.register(liveRoutes, { prefix: '/api' })
    await app.ready()
  })

  afterAll(async () => {
    await app.close()
  })

  const paths = ['/api/live/notify/stream-begin', '/api/live/notify/stream-end'] as const
  const payload = { streamId: 'test-stream', eventType: 'notify' }

  for (const url of paths) {
    it(`${url} 无签名头 → 401`, async () => {
      const res = await app.inject({ method: 'POST', url, payload })
      expect(res.statusCode).toBe(401)
    })

    it(`${url} 签名错 → 403,且指标不被写`, async () => {
      recordDisconnected.mockClear()
      const res = await app.inject({
        method: 'POST',
        url,
        headers: { 'x-live-notify-secret': 'wrong-secret' },
        payload,
      })
      expect(res.statusCode).toBe(403)
      expect(recordDisconnected).not.toHaveBeenCalled()
    })

    it(`${url} 正确签名 → 200`, async () => {
      const res = await app.inject({
        method: 'POST',
        url,
        headers: { 'x-live-notify-secret': SECRET },
        payload,
      })
      expect(res.statusCode).toBe(200)
      expect(res.json().code).toBe(0)
    })
  }
})
