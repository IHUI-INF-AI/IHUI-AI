import { describe, expect, it } from 'vitest'

import { __test__, mergeRequestMetadata } from '../v1-public'

const { requestMetadataSchema } = __test__

const valid = {
  workspace: { file_count: 3, languages: ['ts'], data_policy: 'local' },
  business: { id: 'biz-1', product: 'ihui', version: '1.0.0', stage: 'dev' },
  context: { request_id: 'req-1', session_id: 'sess-1' },
  user: { user_id: 'user-1' },
}

describe('B3-07 v1 四层请求元数据 schema', () => {
  it('接受完整四层 + 顶层 userId 别名', () => {
    const parsed = requestMetadataSchema.parse({ ...valid, userId: 'legacy' })
    expect(parsed.context.request_id).toBe('req-1')
    expect(parsed.userId).toBe('legacy')
  })

  it('缺层直接拒绝', () => {
    expect(() =>
      requestMetadataSchema.parse({ ...valid, context: undefined }),
    ).toThrow()
  })

  it('层内未知字段拒绝(不把脏结构送进追踪表)', () => {
    expect(() =>
      requestMetadataSchema.parse({
        ...valid,
        context: { ...valid.context, unknown: 'x' },
      }),
    ).toThrow()
  })

  it('request_id 与 user_id 必填', () => {
    expect(() =>
      requestMetadataSchema.parse({
        ...valid,
        context: { session_id: 'only-session' },
      }),
    ).toThrow()
    expect(() =>
      requestMetadataSchema.parse({ ...valid, user: {} }),
    ).toThrow()
  })

  it('合并出口保留四层身份，只补顶层兼容别名', () => {
    const merged = mergeRequestMetadata(valid, 'legacy-user', true)
    expect(merged).toMatchObject({
      user: { user_id: 'user-1' },
      userId: 'legacy-user',
      byokMode: true,
      context: { request_id: 'req-1' },
    })
  })

  it('无四层且无 userId 时不写 metadata（旧客户端零行为变化）', () => {
    expect(mergeRequestMetadata(undefined, undefined)).toBeNull()
  })
})
