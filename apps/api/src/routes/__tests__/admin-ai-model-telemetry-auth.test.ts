import { describe, expect, it, beforeAll, afterAll, vi } from 'vitest'
import Fastify, { type FastifyInstance } from 'fastify'

vi.hoisted(() => {
  process.env.DATABASE_URL ??= 'postgresql://test:test@127.0.0.1:5399/test'
  process.env.JWT_SECRET ??= 'test-jwt-secret-for-vitest-at-least-32-chars'
  process.env.CREDENTIALS_ENCRYPTION_KEY ??= 'test-credentials-key-at-least-32-chars'
  process.env.REDIS_URL ??= 'redis://127.0.0.1:6399'
})

vi.mock('../../db/index.js', () => ({ db: {}, dbRead: {} }))
vi.mock('../../services/ai-model-telemetry-v2.js', () => ({
  resolveTelemetryWindow: (value: unknown) => value,
  collectAiModelTelemetryV2: vi.fn(),
  collectAiModelModelsTelemetryV2: vi.fn(),
  collectRecentAiModelCalls: vi.fn(),
}))
vi.mock('../../services/ai-model-governance.js', () => ({
  collectAiModelGovernance: vi.fn(),
}))

import { adminMonitoringRoutes } from '../admin-monitoring-routes'

describe('admin ai-model telemetry auth guard', () => {
  let app: FastifyInstance
  beforeAll(async () => {
    app = Fastify({ logger: false })
    await app.register(adminMonitoringRoutes, { prefix: '/api/admin' })
    await app.ready()
  })
  afterAll(async () => {
    await app.close()
  })

  it('无凭证请求 /telemetry/health 均被 requireAdmin 拒绝', async () => {
    for (const url of [
      '/api/admin/ai-model-config/telemetry',
      '/api/admin/ai-model-config/telemetry/models?configId=3',
      '/api/admin/ai-model-config/telemetry/calls?configId=3',
      '/api/admin/ai-model-config/health',
    ]) {
      const res = await app.inject({ method: 'GET', url })
      expect(res.statusCode).toBe(401)
      expect(res.json()).toMatchObject({ code: 401 })
    }
  })
})
