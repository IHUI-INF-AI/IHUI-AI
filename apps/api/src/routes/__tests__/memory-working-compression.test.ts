import { describe, it, expect, vi } from 'vitest'

vi.hoisted(() => {
  process.env.DATABASE_URL ??= 'postgresql://test:test@127.0.0.1:5399/test'
  process.env.JWT_SECRET ??= 'test-jwt-secret-for-vitest-at-least-32-chars'
})

import { toFiniteCount, formatWorkingCompression } from '../memory.js'

describe('压缩计数运行时容错(迁移跳过类型重建后的旧类型读取)', () => {
  it('字符串数字按数值处理,加法不拼字符串', () => {
    expect(toFiniteCount('5') + 3).toBe(8)
    expect(toFiniteCount(5) + 3).toBe(8)
  })

  it('展示文案对字符串/数字给出一致读数', () => {
    expect(formatWorkingCompression('5', '3', 'summary')).toBe('压缩 5 条 → 3(summary)')
    expect(formatWorkingCompression(5, 3, null)).toBe('压缩 5 条 → 3(summary)')
  })

  it('非法或缺失计数降级为 0,不产生 NaN', () => {
    expect(toFiniteCount('abc')).toBe(0)
    expect(toFiniteCount(null)).toBe(0)
    expect(formatWorkingCompression(null, undefined, null)).toBe('压缩 0 条 → 0(summary)')
  })
})
