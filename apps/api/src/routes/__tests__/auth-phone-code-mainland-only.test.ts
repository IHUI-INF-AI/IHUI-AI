import { afterAll, beforeAll, describe, expect, it, vi } from 'vitest'
import Fastify, { type FastifyInstance } from 'fastify'
import cookie from '@fastify/cookie'

// 校验码一律判错:本用例只锁"手机号格式门",不进入建号/发 token 分支。
vi.mock('../../utils/code-store.js', () => ({
  verifyCode: vi.fn(async () => false),
  getCodeEntry: vi.fn(async () => undefined),
  putCodeEntry: vi.fn(async () => undefined),
  generateCode: vi.fn(() => '123456'),
  CODE_TTL_MS: 5 * 60 * 1000,
  CODE_RESEND_INTERVAL_MS: 60 * 1000,
}))

import { authExtendedRoutes } from '../auth-extended.js'

const URL = '/api/auth/login/phone-code'

describe('POST /api/auth/login/phone-code — 仅限中国大陆手机号', () => {
  let app: FastifyInstance

  beforeAll(async () => {
    app = Fastify({ logger: false })
    await app.register(cookie)
    await app.register(authExtendedRoutes, { prefix: '/api' })
    await app.ready()
  })

  afterAll(async () => {
    await app.close()
  })

  const post = (body: unknown) => app.inject({ method: 'POST', url: URL, payload: body as object })

  it('美国号码(+1)⇒ 400,文案引导海外用户使用 Google 登录', async () => {
    const res = await post({ phone: '+14155552671', code: '123456' })
    expect(res.statusCode).toBe(400)
    expect(res.json().message).toContain('仅支持中国大陆手机号')
    expect(res.json().message).toContain('Google')
  })

  it('香港号码(852)⇒ 400,不得因缺少 + 号而放行', async () => {
    const res = await post({ phone: '85212345678', code: '123456' })
    expect(res.statusCode).toBe(400)
    expect(res.json().message).toContain('仅支持中国大陆手机号')
  })

  it('大陆号码格式通过,继续走验证码校验(未误伤)', async () => {
    const res = await post({ phone: '13812345678', code: '123456' })
    expect(res.statusCode).toBe(400)
    expect(res.json().message).toBe('验证码错误或已过期')
  })
})
