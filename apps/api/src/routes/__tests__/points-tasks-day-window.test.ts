import { describe, it, expect } from 'vitest'
import { dayBounds } from '../points-tasks.js'

// 每日任务进度窗口回归(2026-11-07):
// periodKey 用上海业务日(bizDayKey),而 dayBounds 此前把上海日键当 UTC 日键用,
// 于是窗口 = 上海 08:00 → 次日 08:00。北京时间 00:00–07:59 的关注/考试永远落不进
// 当天窗口,任务进度与领取判据整体错位。断言窗口必须覆盖上海本地整天。
describe('points-tasks dayBounds — 上海业务日窗口', () => {
  it('普通日:窗口 = 上海 00:00 → 次日 00:00(UTC 前一日 16:00 起)', () => {
    const { from, to } = dayBounds('2026-11-07')
    expect(from.toISOString()).toBe('2026-11-06T16:00:00.000Z')
    expect(to.toISOString()).toBe('2026-11-07T16:00:00.000Z')
  })

  it('跨月/跨年边界:12-31 的窗口不得漂到 01-01 08:00', () => {
    const { from, to } = dayBounds('2026-12-31')
    expect(from.toISOString()).toBe('2026-12-30T16:00:00.000Z')
    expect(to.toISOString()).toBe('2026-12-31T16:00:00.000Z')
  })

  it('窗口长度恒为 24h(上海无夏令时)', () => {
    const { from, to } = dayBounds('2026-11-07')
    expect(to.getTime() - from.getTime()).toBe(24 * 3600 * 1000)
  })
})
