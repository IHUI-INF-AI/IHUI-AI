/** D12(2026-09-19 立):automation 执行会话解析——绑定会话优先,否则 auto_<id> 旧行为。 */
import { describe, expect, it } from 'vitest'
import { resolveAutomationSessionId } from '../../services/agent-automation-scheduler.js'

describe('resolveAutomationSessionId', () => {
  it('未绑定会话时保持旧行为 auto_<id>', () => {
    expect(resolveAutomationSessionId({ id: 'a-1' })).toBe('auto_a-1')
    expect(resolveAutomationSessionId({ id: 'a-1', conversationId: null })).toBe('auto_a-1')
  })

  it('绑定会话时复用该会话线程', () => {
    expect(resolveAutomationSessionId({ id: 'a-1', conversationId: 'conv-9' })).toBe('conv-9')
  })
})
