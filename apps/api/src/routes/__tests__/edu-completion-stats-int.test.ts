/**
 * F-699 夹具：`count(case when ...)` 在 PG 返回 int8（驱动按字符串带回），
 * 汇总时 `0 + "5"` 变字符串拼接 → 完成率算出 442%。
 *
 * 修法：SQL 加 `::int`，汇总再 `Number()` 强转；本夹具同时钉住源码与算式。
 */
import { readFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { describe, it, expect } from 'vitest'

const HERE = dirname(fileURLToPath(import.meta.url))
const SRC = readFileSync(resolve(HERE, '../edu-ai-management.ts'), 'utf-8')

describe('F-699 完成率汇总', () => {
  it('completed 计数带 ::int，不再把 int8 当字符串带回', () => {
    expect(SRC).toContain('end)::int`')
  })

  it('汇总 reduce 用 Number() 强转，挡住字符串拼接', () => {
    expect(SRC).toContain('Number(s.totalItems)')
    expect(SRC).toContain('Number(s.completedItems)')
  })

  it('算式对照：旧口径 442%，新口径 67%', () => {
    const stats = [
      { totalItems: 6, completedItems: '5' },
      { totalItems: 6, completedItems: '3' },
    ]
    // 旧：0 + "5" = "05"，"05" + "3" = "053"，"053" / 12 = 4.4166…
    // 旧实现的起点是数字 0(不是空串),这里用类型断言复刻其运行期行为。
    const legacySeed = 0 as unknown as string
    const legacy = stats.reduce((sum: string, s) => sum + s.completedItems, legacySeed)
    const legacyRate = Math.round((Number(legacy) / 12) * 100)
    expect(legacy).toBe('053')
    expect(legacyRate).toBe(442)
    // 新：先归一再求和
    const totalItems = stats.reduce((sum, s) => sum + Number(s.totalItems), 0)
    const totalCompleted = stats.reduce((sum, s) => sum + Number(s.completedItems), 0)
    expect(Math.round((totalCompleted / totalItems) * 100)).toBe(67)
  })
})
