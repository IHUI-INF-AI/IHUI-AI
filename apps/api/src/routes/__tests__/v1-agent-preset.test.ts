/** /v1/agents/execute 的 agentPreset 边界与冲突判据。 */
import { describe, expect, it } from 'vitest'
import { agentExecuteSchema, buildAgentExecuteBody } from '../v1-ai-core.js'
import type { V1AgentExecuteRequest } from '@ihui/types'

const base: V1AgentExecuteRequest = { agentId: 'a1', input: 'do it' }

describe('v1 agentPreset', () => {
  it('只给 agentPreset 时透传 agent_preset,不带旧的显式字段', () => {
    const built = buildAgentExecuteBody({ ...base, agentPreset: 'coder' })
    expect(built).toEqual({
      ok: true,
      body: { agent_id: 'a1', input: 'do it', goal: 'do it', agent_preset: 'coder' },
    })
  })

  it('与 permissionMode / permissionPreset / maxIterations 同给一律拒绝', () => {
    for (const extra of [
      { permissionMode: 'accept-edits' },
      { permissionPreset: 'auto' },
      { maxIterations: 8 },
    ]) {
      const built = buildAgentExecuteBody({ ...base, agentPreset: 'coder', ...extra })
      expect(built.ok).toBe(false)
      if (!built.ok) expect(built.message).toContain('agentPreset')
    }
  })

  it('未给 agentPreset 时既有字段语义不变', () => {
    const built = buildAgentExecuteBody({
      ...base,
      maxIterations: 12,
      permissionPreset: 'auto',
    })
    expect(built).toEqual({
      ok: true,
      body: {
        agent_id: 'a1',
        input: 'do it',
        goal: 'do it',
        max_iterations: 12,
        permission_preset: 'auto',
      },
    })
  })

  it('schema 接受 agentPreset 且保留字符串约束', () => {
    expect(agentExecuteSchema.safeParse({ ...base, agentPreset: 'researcher' }).success).toBe(true)
    expect(agentExecuteSchema.safeParse({ ...base, agentPreset: '' }).success).toBe(false)
  })
})
