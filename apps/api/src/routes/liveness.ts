/**
 * 探活别名族(2026-11-17 立,对标 qoder2api-hub 的 `/ping /healthz /livez /readyz`)。
 *
 * 语义边界(单一真相源):
 * - 本组端点只回答「进程在不在」:**纯文本**、免鉴权、不查依赖、不查账号池。
 * - `/readyz` 是**轻量就绪**(进程可服务),不冒充「DB/Redis/AI 三项都通」;
 *   后者唯一真相源仍是 `/api/health/ready`。响应头 X-Ready-Scope 把这一区别写死:
 *   liveness / liveness-only —— 客户端与探针可按头区分,不必靠读文档猜。
 *
 * 为什么抽成独立插件:端点行为要能被 app.inject 直接钉住(不需要拉起整机与真实依赖),
 * 且注册面与清单(AUTH_PUBLIC_EXACT_PATHS / HEALTH_PATHS)同住一处判据。
 */
import type { FastifyPluginAsync } from 'fastify'

export interface LivenessAlias {
  path: string
  text: string
  scope: 'liveness' | 'liveness-only'
}

export const LIVENESS_ALIASES: readonly LivenessAlias[] = [
  { path: '/ping', text: 'pong', scope: 'liveness' },
  { path: '/healthz', text: 'ok', scope: 'liveness' },
  { path: '/livez', text: 'ok', scope: 'liveness' },
  { path: '/readyz', text: 'ok', scope: 'liveness-only' },
]

export const livenessRoutes: FastifyPluginAsync = async (server) => {
  for (const alias of LIVENESS_ALIASES) {
    server.get(alias.path, async (_request, reply) => {
      reply.header('X-Ready-Scope', alias.scope)
      reply.header('Cache-Control', 'no-store')
      return reply.type('text/plain; charset=utf-8').send(alias.text)
    })
  }
}
