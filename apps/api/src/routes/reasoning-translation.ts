/**
 * 思维链翻译端点(2026-11-13 立)
 *
 * 前缀 `/api/ai/reasoning`(注册方见 routes/index.ts)。
 * 鉴权面:整棵子树 preHandler 强制登录 —— 翻译消耗模型配额,不能匿名调用。
 * 不做流式:译文是一次性替换视图,逐字流式只会让用户看到半句译文再整段跳变。
 */

import type { FastifyPluginAsync, FastifyRequest, FastifyReply } from 'fastify'
import { z } from 'zod'
import { REASONING_TRANSLATION_LANGS, REASONING_TRANSLATION_MAX_CHARS } from '@ihui/types'
import { authenticate } from '../plugins/auth.js'
import { success, error } from '../utils/response.js'
import {
  ReasoningTranslationError,
  translateReasoning,
} from '../services/reasoning-translation-service.js'

const translateBodySchema = z.object({
  text: z.string().min(1).max(REASONING_TRANSLATION_MAX_CHARS),
  targetLang: z.enum(REASONING_TRANSLATION_LANGS),
})

export const reasoningTranslationRoutes: FastifyPluginAsync = async (server) => {
  server.addHook('preHandler', async (request: FastifyRequest, reply: FastifyReply) => {
    try {
      await authenticate(request)
    } catch (e) {
      const statusCode = (e as Error & { statusCode?: number }).statusCode ?? 401
      const message = (e as Error).message || '操作失败,请稍后重试'
      return reply.status(statusCode).send(error(statusCode, message))
    }
  })

  // POST /translate — 把一段思考内容译成目标语言(原文不回传)
  server.post('/translate', async (request, reply) => {
    const parsed = translateBodySchema.safeParse(request.body)
    if (!parsed.success) {
      return reply
        .status(400)
        .send(error(400, parsed.error.issues[0]?.message ?? '参数错误', 'INVALID_TRANSLATE_BODY'))
    }
    try {
      const data = await translateReasoning(request, parsed.data)
      return reply.send(success(data))
    } catch (err) {
      if (err instanceof ReasoningTranslationError) {
        // too_long / empty_input = 请求问题(400);upstream / empty_output = 依赖不可用(502)
        const status = err.code === 'too_long' || err.code === 'empty_input' ? 400 : 502
        request.log.warn({ code: err.code, status }, 'reasoning translation failed')
        return reply.status(status).send(error(status, err.message, err.code.toUpperCase()))
      }
      throw err
    }
  })
}
