/**
 * 请求体上限单一真相源(2026-10-28 DDoS P2 收口)。
 *
 * 背景:全局 bodyLimit 从 10MiB 收到 2MiB,目的是把普通 JSON 接口的单请求内存放大压小。
 * 但「请求体天然携带二进制媒体」的路由(multipart 上传、base64 图片/音频、协议透传)
 * 本来就超过 2MiB —— 不给它们显式上限,它们就会被全局值静默 413。
 * 那不是安全,是功能坏死(且症状是"导入失败/上传失败",极难归因)。
 *
 * 因此约定(判据由 apps/api/tests/body-limit-regression.test.ts 静态守卫,新增路由漏设即红):
 *   1. 普通 JSON / urlencoded 路由 —— 一律吃全局 GLOBAL_JSON_BODY_LIMIT,不单独声明;
 *   2. 媒体路由 —— **必须**显式声明 bodyLimit,值取自本模块,禁止就地写魔法数字;
 *   3. 本模块是这些数字的唯一出处:要调上限只改这里,不要在路由里另起一份。
 *
 * 取值依据(不是拍的,逐条可查):
 *   - GLOBAL 2MiB:普通业务 JSON(文本对话/表单/配置)实际峰值远低于此 —— 2MiB 已能装下
 *     约 40 万汉字;同时把"单请求内存放大"从 10MiB 压到 1/5,且与 headersTimeout 一起
 *     构成 slowloris 的第一道闸。
 *   - MEDIA 34MiB:对齐"上游 25MiB 单文件经 base64 膨胀(×4/3 ≈ 33.3MiB)"这一入参形态,
 *     与 ai-audio 既有 34MiB 先例同值(不新造第二个数)。
 *   - MEDIA_FILE_UPLOAD 26MiB:上游单文件上限 25MiB(Whisper 音频 / DALL·E 图像) + multipart 边界余量。
 *   - FILE_UPLOAD 100MiB+1MiB:与 @fastify/multipart 的 limits.fileSize 对齐(单一真相源
 *     MAX_MULTIPART_UPLOAD_SIZE),+1MiB 留给表单边界与其他文本字段。
 *   - SMALL_IMAGE 3MiB:头像等小图内部校验 2MiB,整包需含 multipart 边界余量。
 */

import { MAX_MULTIPART_UPLOAD_SIZE } from '../utils/file-type-validator.js'

/** 全局请求体上限(server.ts bodyLimit):只管普通 JSON / urlencoded。 */
export const GLOBAL_JSON_BODY_LIMIT = 2 * 1024 * 1024

/** base64 内联媒体(图片/音频)入参上限:34MiB。 */
export const MEDIA_BASE64_BODY_LIMIT = 34 * 1024 * 1024

/**
 * 媒体单文件 multipart 上传上限:26MiB。
 * 依据:上游单文件 25MiB 上限(OpenAI Whisper 音频 / DALL·E 图像等)+ multipart 边界余量。
 * 适用:音频转写(STT)、图片变体/混合等"一次传一个媒体文件"的路由。
 */
export const MEDIA_FILE_UPLOAD_BODY_LIMIT = 26 * 1024 * 1024

/** 通用文件上传上限:100MiB + 1MiB(对齐 multipart 单文件限制)。 */
export const FILE_UPLOAD_BODY_LIMIT = MAX_MULTIPART_UPLOAD_SIZE + 1024 * 1024

/** 小图上传(头像等)上限:3MiB(内部校验 2MiB + 余量)。 */
export const SMALL_IMAGE_UPLOAD_BODY_LIMIT = 3 * 1024 * 1024
