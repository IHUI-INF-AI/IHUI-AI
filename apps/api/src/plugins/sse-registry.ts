import type { FastifyPluginAsync } from 'fastify'
import fp from 'fastify-plugin'
import type { SseStateStore } from '../utils/sse-state-store.js'
import { getSseStateStore, SSE_REPLICA_ID } from '../utils/sse-state-store.js'
import { abortLocalStreams } from '../utils/sse-stream-registry.js'

declare module 'fastify' {
  interface FastifyInstance {
    /** SSE 流注册表状态层(memory|redis,config.SSE_REGISTRY_BACKEND 选择) */
    sseRegistry: SseStateStore
  }
}

/**
 * SSE 流注册表插件(2026-09-19 立,#22 的多副本就绪演进)。
 *
 * 职责(轻量,只做装配不做业务):
 * 1. decorate sseRegistry:暴露状态层单例,供路由/未来跨副本重连接线
 *    (fetchReplayEvents / fetchSessionMeta 异步跨副本读)。
 * 2. 注入远端 abort 广播的落地回调:其它副本 publishAbort 后,本进程对
 *    其持有的连接执行 abortLocalStreams(redis backend 才有真实订阅;
 *    memory 下为 no-op,等价单副本)。
 * 3. onClose 优雅断开状态层连接(Redis 命令/订阅双连接)。
 *
 * 注意:连接绑定层(sse-stream-registry.ts)不依赖本插件即可工作(工厂自建
 * 单例);本插件仅保证服务进程生命周期内订阅回调就绪与退出清理。
 */
const sseRegistryPlugin: FastifyPluginAsync = async (server) => {
  const store = getSseStateStore()
  store.onRemoteAbort((broadcast) => {
    abortLocalStreams(broadcast.conversationId, broadcast.messageId)
  })
  server.decorate('sseRegistry', store)
  server.addHook('onClose', async () => {
    store.dispose()
  })
  server.log.info(
    { backend: store.backend, replicaId: SSE_REPLICA_ID },
    'sse registry state store initialized',
  )
}

export const sseRegistry = fp(sseRegistryPlugin, {
  name: 'sse-registry',
  fastify: '5.x',
})
