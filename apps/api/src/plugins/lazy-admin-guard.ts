/**
 * `requireAdmin` 的**懒加载**闸门唯一出口。
 *
 * 为什么要有这一档:require-permission 的静态链拖 auth/rbac/db,在 webhook / 装配类
 * 单测里被模块顶层 import 会污染加载面(两侧注释都记过这件事)。此前 automations.ts
 * 与 github-app.ts 各写了一份逐字相同的 4 行 shim(§0.6:第二份必然漂移),现收到这里。
 * 本模块自身**不 import** require-permission —— 动态 import 留在函数体内,懒性质不变。
 */
import type { FastifyReply, FastifyRequest } from 'fastify'

export async function requireAdminGuardLazy(
  request: FastifyRequest,
  reply: FastifyReply,
): Promise<void> {
  const { requireAdmin } = await import('./require-permission.js')
  return requireAdmin(request, reply)
}
