fn main() {
    println!("cargo:rerun-if-env-changed=IHUI_LAUNCHER_EMBED_RESOURCE");
    // 关键：Launcher 既是独立 exe，也是 Tauri app 的 path 依赖。
    // 作为依赖被编译时若也把 VERSION 资源塞进 rlib，最终 app link 会出现
    // “CVT1100 duplicate resource: VERSION” 而链接失败。
    // 只认构建脚本显式传入的 env（scripts/desktop-launcher-build.mjs 设置）；
    // Tauri 构建把 launcher 当依赖时没有这个 env ⇒ 不嵌资源。
    if std::env::var_os("IHUI_LAUNCHER_EMBED_RESOURCE").is_none() {
        return;
    }
    #[cfg(windows)]
    {
        let mut res = winres::WindowsResource::new();
        res.set_icon("../src-tauri/icons/icon.ico");
        res.set("FileDescription", "智汇AI 启动器");
        res.set("ProductName", "智汇AI");
        res.set("FileVersion", "0.1.0");
        res.set("ProductVersion", "0.1.0");
        res.set("CompanyName", "吉林省爱智汇人工智能科技有限公司");
        res.set("LegalCopyright", "© 2026 IHUI AI · 李春川");
        res.set("OriginalFilename", "智汇AI.exe");
        if let Err(err) = res.compile() {
            panic!("launcher resource compile failed: {err}");
        }
    }
}
