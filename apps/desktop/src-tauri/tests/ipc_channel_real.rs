//! B2-02 真实受限命名管道创建验证。
//!
//! rustc --edition 2021 --test tests/ipc_channel_real.rs -o ipc_channel_real.exe
//! IHUI_TEST_USER_SID=S-1-5-... ipc_channel_real.exe --nocapture

#[path = "../src/ipc_channel_acl.rs"]
mod ipc_channel_acl;

#[test]
fn creates_restricted_pipe_with_current_user_dacl() {
    let Ok(sid) = std::env::var("IHUI_TEST_USER_SID") else {
        eprintln!("skip: IHUI_TEST_USER_SID 未设置");
        return;
    };
    let leaf = format!("ihui-ipc-real-{}", std::process::id());
    let report = ipc_channel_acl::selftest(&sid, &leaf);
    assert!(report.ok, "restricted pipe failed: {}", report.detail);
    assert_eq!(report.detail, "pipe created and closed");
    assert!(report.sddl.contains(&format!(";;;{sid}")));
    assert!(report.sddl.contains(";;;SY"));
}
