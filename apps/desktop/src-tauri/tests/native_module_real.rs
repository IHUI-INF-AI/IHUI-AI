//! B2-07 真实 BP_* DLL 加载验证。
//!
//! 该文件同时可作为独立 harness 编译（不依赖 Tauri）：
//!   rustc --edition 2021 --test tests/native_module_real.rs -o native_module_real.exe
//!   IHUI_BP_FIXTURE_DLL=...\bp_fixture.dll native_module_real.exe
//!
//! 夹具 DLL 由 `tests/fixtures/bp_fixture.c` 用 MSVC `cl /LD` 编译。

#[path = "../src/native_module_abi.rs"]
mod native_module_abi;

#[test]
fn loads_real_bp_fixture_dll() {
    let Ok(path) = std::env::var("IHUI_BP_FIXTURE_DLL") else {
        eprintln!("skip: IHUI_BP_FIXTURE_DLL 未设置");
        return;
    };
    let report = native_module_abi::probe_native_module(&path);
    assert!(report.ok, "fixture load failed: {}", report.reason);
    assert_eq!(report.reason, "loaded-initialized-shutdown");
    assert_eq!(report.abi_version, 1);
}
