//! `ihui-tool-host` 可执行入口：`--pipe <name> --token <token>`。
//!
//! 独立进程，不初始化 Tauri/GUI；由 `ToolHostClient` 拉起并握手。
//! 失败一律非 0 退出并把原因写到 stderr，调用方不会拿到"假装启动成功"的句柄。

fn main() {
    #[cfg(windows)]
    {
        if let Err(e) = ihui_desktop_lib::tool_host::run_from_args() {
            eprintln!("[tool-host] {e}");
            std::process::exit(1);
        }
    }
    #[cfg(not(windows))]
    {
        eprintln!("[tool-host] 仅支持 Windows");
        std::process::exit(2);
    }
}
