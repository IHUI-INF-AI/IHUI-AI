// 桌面端图标圆角化:共享源图 apps/mobile-rn/assets/icon.png 是直角全出血黑底方块
// (iOS 系统自动切圆角、Android 走独立 adaptive-icon,均不可预切圆角),
// 桌面端 Windows 不做任何自动圆角,需自行烘焙圆角 + 四角透明再交给 `tauri icon`。
// 用法:node scripts/make-rounded-icon.mjs(icons:regen 第一步自动调用)
import sharp from 'sharp'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const scriptDir = dirname(fileURLToPath(import.meta.url))
const desktopRoot = resolve(scriptDir, '..')
const srcPath = join(desktopRoot, '../mobile-rn/assets/icon.png')
const outPath = join(desktopRoot, 'src-tauri/icons/source-rounded.png')

// 圆角半径 ≈ 22% 边长,对齐现代应用图标(Apple squircle 近似)观感
const RADIUS = Math.round(1024 * 0.22)

const mask = Buffer.from(
  `<svg width="1024" height="1024"><rect width="1024" height="1024" rx="${RADIUS}" ry="${RADIUS}" fill="#fff"/></svg>`,
)

await sharp(srcPath)
  .resize(1024, 1024, { fit: 'cover' })
  .ensureAlpha()
  .composite([{ input: mask, blend: 'dest-in' }])
  .png()
  .toFile(outPath)

const out = sharp(outPath)
const meta = await out.metadata()
console.log(`[ok] rounded icon -> ${outPath} (${meta.width}x${meta.height}, radius ${RADIUS})`)

// tauri icon v2 不再输出 256x256.png,但它仍被 tauri.conf.json bundle.icon 引用,必须在此补生成
const icon256Path = join(desktopRoot, 'src-tauri/icons/256x256.png')
await sharp(outPath).resize(256, 256).png().toFile(icon256Path)
console.log(`[ok] bundle icon 256x256 -> ${icon256Path}`)
