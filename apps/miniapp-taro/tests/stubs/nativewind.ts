/**
 * node 环境下的 nativewind 最小桩。
 *
 * 背景:RN 共享屏的 color-scheme-sync 引 `{ colorScheme } from 'nativewind'`;真包内部
 * require('react-native'),在 Node 解析下绕过本仓 vitest 的裸包 alias ⇒ 收集期 SyntaxError。
 * 这里只保留色板写入/读取的空实现,判据不变。
 */
const current = { value: 'light' as 'light' | 'dark' }

export const colorScheme = {
  set: (next: 'light' | 'dark') => {
    current.value = next
  },
  get: () => current.value,
}

