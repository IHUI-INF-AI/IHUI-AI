/**
 * 自定义导航 RN 壳页安全区锁(2026-11-27)。
 *
 * 判据:`navigationStyle: 'custom'` 去掉原生导航栏后,页面必须用 `RnShellPage` 垫
 * 状态栏高度;若退回裸 `ThemeRoot`,RN 的 NavBar/页内返回头会落到状态栏下面。
 * 本测试覆盖当前全部 8 枚 custom-nav 壳页。
 */
import { describe, it, expect } from 'vitest'
import { readFileSync } from 'node:fs'
import { resolve } from 'node:path'

const read = (path: string) => readFileSync(resolve(path), 'utf8')

const CUSTOM_NAV_SHELL_PAGES = [
  'src/pkg-about/about/model-record/index.tsx',
  'src/pkg-mirror2/home/index.tsx',
  'src/pkg-content/search/index.tsx',
  'src/pkg-content/activity-detail-shared/index.tsx',
  'src/pkg-content/circle-post/index.tsx',
  'src/pkg-user/circle-detail/index.tsx',
  'src/pkg-user/circle-index/index.tsx',
  'src/pkg-user/fans/index.tsx',
] as const

describe('custom-nav RN 壳页状态栏安全区', () => {
  it('8 枚壳页全部走 RnShellPage,不再直接包 ThemeRoot', () => {
    for (const path of CUSTOM_NAV_SHELL_PAGES) {
      const source = read(path)
      expect(source, path).toContain("from '@/components/RnShellPage'")
      expect(source, path).not.toContain("from '@/components/ThemeRoot'")
    }
  })

  it('RnShellPage 以系统状态栏高度作 paddingTop', () => {
    const source = read('src/components/RnShellPage.tsx')
    expect(source).toContain('getTopBarMetrics()')
    expect(source).toContain('paddingTop: statusBarHeight')
  })
})
