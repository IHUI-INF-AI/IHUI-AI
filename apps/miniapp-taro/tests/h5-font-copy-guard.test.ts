import { describe, it, expect } from 'vitest'
import fs from 'fs'
import path from 'path'

const CONFIG = fs.readFileSync(path.resolve(__dirname, '..', 'config', 'index.ts'), 'utf8')

describe('H5 构建:字体复制目录必须存在才声明', () => {
  it('h5 字体 copy 条件含 existsSync 守卫,不再无条件指向缺失目录', () => {
    const cond = CONFIG.match(/taroEnv === 'h5'[^\n]*/)?.[0] || ''
    expect(cond).toContain('fs.existsSync')
    expect(cond).toContain('h5-fonts')
    expect(CONFIG).toContain("import fs from 'fs'")
  })
  it('反向变异:去掉守卫后判据必须判红(证明测试不是空转)', () => {
    const guard = CONFIG.match(/taroEnv === 'h5'[^\n]*/)?.[0] || ''
    const mutated = guard.split(' && ')[0]
    expect(mutated).not.toContain('fs.existsSync')
    expect(mutated).toBe("taroEnv === 'h5'")
  })
})
