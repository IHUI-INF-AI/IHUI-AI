import { describe, expect, it } from 'vitest'

import { TARO_UI_ROUTES } from '../src/constants/ui-routes.generated'
import { DRAWER_MENU_ROUTES, DRAWER_ROUTE_TARGETS } from '../src/utils/drawer-routes'

/**
 * 抽屉跳转目标的锚点(2026-11-26 立)。
 *
 * 为什么值得一条测试:抽屉 key→路由表此前在三页各写一份,漂移出 5 个死目标
 * (`/pages/demand|inspiration|dynamic|company|freebie`),点击后 navigateTo 直接失败、
 * 页面零反馈 —— 这类缺陷编译器看不见(字符串),只能靠注册表回查。
 * 判据面 = ui-routes.generated(由 app.config.ts 生成),所以页面搬迁后忘改这里会当场红。
 */
const registered = new Set(TARO_UI_ROUTES.map((route) => route.path))
const tabRoutes = new Set(TARO_UI_ROUTES.filter((route) => route.tab).map((route) => route.path))

describe('左抽屉跳转目标', () => {
  it('每个目标都命中 app.config 注册页', () => {
    const missing = DRAWER_ROUTE_TARGETS.filter((url) => !registered.has(url))
    expect(missing).toEqual([])
  })

  it('tab 档只能标在 tabBar 页上(否则 switchTab 必失败)', () => {
    for (const [key, route] of Object.entries(DRAWER_MENU_ROUTES)) {
      if (!route.tab) continue
      expect(tabRoutes.has(route.url), `${key} 标了 tab,但 ${route.url} 不在 tabBar`).toBe(true)
    }
  })

  it('非 tab 目标不得标 tab', () => {
    for (const [key, route] of Object.entries(DRAWER_MENU_ROUTES)) {
      if (route.tab) continue
      expect(tabRoutes.has(route.url), `${key} 未标 tab,但 ${route.url} 是 tabBar 页`).toBe(false)
    }
  })
})
