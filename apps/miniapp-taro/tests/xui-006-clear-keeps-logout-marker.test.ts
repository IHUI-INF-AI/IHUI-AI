// XUI-006 夹具:"清除全部"必须保留退出登录标记,否则清缓存后冷启会静默重登。
// 改前必红:KEEP_KEYS_ON_CLEAR 不含 ihui-session-logged-out,该键会被列入可清除集合。
import { describe, expect, it } from 'vitest'
import { readFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { SESSION_LOGGED_OUT_STORAGE_KEY } from '@ihui/shared/auth/auto-login-policy'
import { KEEP_KEYS_ON_CLEAR } from '../src/constants/storage'

function clearableKeys(all: string[]): string[] {
  return all.filter((k) => !KEEP_KEYS_ON_CLEAR.includes(k))
}

describe('XUI-006 清缓存保留退出标记', () => {
  it('KEEP_KEYS_ON_CLEAR 含 ihui-session-logged-out', () => {
    expect(KEEP_KEYS_ON_CLEAR).toContain(SESSION_LOGGED_OUT_STORAGE_KEY)
  })

  it('清除全部时退出标记与登录态一起保留,只清业务缓存', () => {
    const removed = clearableKeys([
      SESSION_LOGGED_OUT_STORAGE_KEY,
      'ihui_token',
      'ihui_refresh_token',
      'ihui_image_history',
      'ai_chat_history',
    ])
    expect(removed).toEqual(['ihui_image_history', 'ai_chat_history'])
  })

  it('cache 页面复用统一常量,不再维护第二份 KEEP_KEYS', () => {
    const src = readFileSync(resolve(__dirname, '../src/pages/setting/cache.tsx'), 'utf8')
    expect(src).toMatch(/KEEP_KEYS_ON_CLEAR/)
    expect(src).not.toMatch(/const KEEP_KEYS = /)
  })
})
