/**
 * DBG-33: miniapp `relativeTime` 必须把应用当前语言交给共享 `formatRelativeTime`。
 * 生产实现已改读 `getCurrentLocale()`;本册钉住「切语言后相对时间跟着变」,
 * 并锁可执行源码里不再出现字面量 zh-CN。
 */
import { readFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { describe, expect, it, vi } from 'vitest'
import { formatRelativeTime } from '@ihui/shared/utils/date-utils'

const LOCALES = ['zh-CN', 'zh-TW', 'en', 'ja', 'ko'] as const
type AppLocale = (typeof LOCALES)[number]

const localeBox = vi.hoisted(() => ({ value: 'zh-CN' as AppLocale }))

vi.mock('../src/i18n', () => ({
  getCurrentLocale: () => localeBox.value,
}))

import { relativeTime } from '../src/utils/time'

/** 落在「小时」档中段,用例跑几秒也不会跨档。 */
const PAST = Date.now() - 2 * 60 * 60 * 1000

function executable(src: string): string {
  return src.replace(/\/\*[\s\S]*?\*\//g, '').replace(/^\s*\/\/.*$/gm, '')
}

describe('DBG-33 relativeTime 跟随当前 locale', () => {
  it('可执行源码把当前语言传进去,不再写死 zh-CN', () => {
    const src = executable(
      readFileSync(join(dirname(fileURLToPath(import.meta.url)), '../src/utils/time.ts'), 'utf8'),
    )
    const start = src.indexOf('export function relativeTime')
    const end = src.indexOf('export function nowDate')
    const fn = src.slice(start, end)
    expect(start).toBeGreaterThanOrEqual(0)
    expect(end).toBeGreaterThan(start)
    expect(fn).toContain('formatRelativeTime(date, getCurrentLocale())')
    expect(fn).not.toMatch(/['"]zh-CN['"]/)
  })

  it.each(LOCALES)('%s 与 formatRelativeTime(date, 该语言) 逐字相同', (locale) => {
    localeBox.value = locale
    expect(relativeTime(PAST)).toBe(formatRelativeTime(PAST, locale))
  })

  it('en 与 zh-CN 文案不同,逐字相等才有牙', () => {
    expect(formatRelativeTime(PAST, 'en')).not.toBe(formatRelativeTime(PAST, 'zh-CN'))
  })
})
