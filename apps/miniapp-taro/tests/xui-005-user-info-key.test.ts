// XUI-005 夹具:个人中心/社群入口的登录态判断必须走 utils/auth.getUserInfo()
// (真实键 ihui_user_info,含历史键迁移),不得再读不存在的 'data' 键。
// 改前必红:UserCard / MyAgents / RecentAgents / community 均在读 getStorageSync('data'),
// 未登录态判断恒为 false,入口被误判为"请先登录"或用户信息恒空。
import { describe, expect, it } from 'vitest'
import { readFileSync } from 'node:fs'
import { resolve } from 'node:path'

const ROOT = resolve(__dirname, '..')

const FILES = [
  'src/pages/user/components/UserCard.tsx',
  'src/pages/community/components/MyAgents.tsx',
  'src/pages/community/components/RecentAgents.tsx',
  'src/pages/community/index.tsx',
]

describe('XUI-005 登录态读取键', () => {
  it.each(FILES)('%s 使用 getUserInfo 且不再读 data 键', (file) => {
    const src = readFileSync(resolve(ROOT, file), 'utf8')
    expect(src).not.toMatch(/getStorageSync\(\s*'data'\s*\)/)
    expect(src).toMatch(/getUserInfo\(\)/)
  })
})
