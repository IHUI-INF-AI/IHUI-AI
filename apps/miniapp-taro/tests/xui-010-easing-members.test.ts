// XUI-010 夹具:小程序 rn-compat 的 Easing 垫片缺 sin —— 共享层 HomeScreen 直接
// 调 `Easing.sin(...)`,模块里没有该成员 ⇒ undefined 调用,首页渲染崩溃。
// 改前必红:Easing.sin 不是函数(TypeError)。
import { describe, expect, it, vi } from 'vitest'

// primitives 会拉 @tarojs/components(依赖构建期注入的常量);本夹具只测纯数学成员,
// 用空组件桩切断这条依赖,不动 Easing 之外的任何实现。
vi.mock('../src/rn-compat/primitives', () => ({
  Image: () => null,
  ScrollView: () => null,
  Text: () => null,
  View: () => null,
}))

vi.mock('@tarojs/taro', () => ({
  default: {
    getSystemInfoSync: () => ({
      windowWidth: 375,
      windowHeight: 667,
      pixelRatio: 2,
      platform: 'devtools',
    }),
  },
}))

import { Easing } from '../src/rn-compat/apis'

describe('XUI-010 Easing 垫片成员', () => {
  it('sin/exp/circle 都是可调用函数(共享层可直接调用)', () => {
    expect(typeof Easing.sin).toBe('function')
    expect(typeof Easing.exp).toBe('function')
    expect(typeof Easing.circle).toBe('function')
  })

  it('sin 值域与 RN 语义一致:sin(0)=0, sin(1)=1', () => {
    expect(Easing.sin(0)).toBe(0)
    expect(Easing.sin(1)).toBeCloseTo(1, 6)
    expect(Easing.sin(0.5)).toBeCloseTo(1 - Math.cos(Math.PI / 4), 10)
  })

  it('exp/circle 端点正确', () => {
    expect(Easing.exp(0)).toBe(0)
    expect(Easing.exp(1)).toBe(1)
    expect(Easing.circle(0)).toBe(0)
    expect(Easing.circle(1)).toBe(1)
  })
})
