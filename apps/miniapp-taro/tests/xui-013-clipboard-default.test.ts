//
// XUI-013 夹具:rn-compat/platform 的默认导出必须是 Clipboard 本体。
// 共享层(Home/ModelRecord/Income/RankingDetail/News 等)写的是
//   import Clipboard from '@react-native-clipboard/clipboard'
//   Clipboard.setString(...)  /  Clipboard.getString()
// 旧默认导出是成员袋 ⇒ default.setString === undefined,点击复制即 TypeError。
// 改前必红:defaultExport 不是 Clipboard 本体、也没有 setString 方法。
import { describe, expect, it, vi } from 'vitest'

// primitives/style 在模块 load 期拉 @tarojs/components(@tarojs/runtime 需要构建期常量);
// 本夹具只验证导出形状,不渲染组件,用空组件桩切断依赖。
vi.mock('@tarojs/components', () => ({
  Image: () => null,
  ScrollView: () => null,
  Text: () => null,
  View: () => null,
}))

vi.mock('@tarojs/taro', () => ({
  default: {
    getSystemInfoSync: () => ({ pixelRatio: 2, windowWidth: 375, windowHeight: 800 }),
    getClipboardData: async () => ({ data: 'clip' }),
    setClipboardData: async () => undefined,
    chooseImage: async () => ({ tempFilePaths: [] }),
    chooseMedia: async () => ({ tempFiles: [] }),
    saveImageToPhotosAlbum: async () => undefined,
    saveVideoToPhotosAlbum: async () => undefined,
  },
}))

import defaultExport, { Clipboard, getString, setString } from '../src/rn-compat/platform'

describe('XUI-013 Clipboard 默认导出形状', () => {
  it('默认导出就是 Clipboard 本体', () => {
    expect(defaultExport).toBe(Clipboard)
    expect(typeof defaultExport.setString).toBe('function')
    expect(typeof defaultExport.getString).toBe('function')
    expect(typeof (defaultExport as unknown as { ImagePicker?: unknown }).ImagePicker).toBe(
      'undefined',
    )
  })

  it('默认导出可直接调用并透传 Taro 剪贴板', async () => {
    await defaultExport.setString('hello')
    await expect(defaultExport.getString()).resolves.toBe('clip')
    expect(setString).toBe(Clipboard.setString)
    expect(getString).toBe(Clipboard.getString)
  })
})
