/**
 * strip-scrollview-padding.mjs — 移除 Taro 生成 base.wxml 中 scroll-view 的 padding 属性。
 *
 * 背景:微信 IDE 模拟器 webview 渲染模式对 scroll-view 的 padding 属性报警告
 * `<scroll-view>: the padding property is not yet supported in webview rendering mode`。
 * 该 padding 属性是 Taro 4 运行时模板自动生成的(`padding="{{i.p12||[0,0,0,0]}}"`),
 * 并非项目源码书写;本项目未使用 Taro scroll-view 的 padding 功能(源码无直接 padding),
 * 移除后功能不受影响,且让 IDE 控制台干净。真机本就支持 scroll-view padding,不受影响。
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import { resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const __filename = fileURLToPath(import.meta.url)
const __dirname = dirname(__filename)
const ROOT = resolve(__dirname, '..')
const BASE_WXML = resolve(ROOT, 'dist/base.wxml')

if (!existsSync(BASE_WXML)) {
  console.warn('[strip-scrollview-padding] dist/base.wxml 不存在,跳过(可能未构建)')
  process.exit(0)
}

const content = readFileSync(BASE_WXML, 'utf8')
// 精确匹配 Taro 模板自动生成的 scroll-view padding 绑定
const PADDING_RE = /\s+padding="\{\{i\.p12\|\|\[0,0,0,0\]\}\}"/g
const count = (content.match(PADDING_RE) || []).length

if (count === 0) {
  console.info('[strip-scrollview-padding] 未发现 scroll-view padding 属性,无需处理')
  process.exit(0)
}

const next = content.replace(PADDING_RE, '')
writeFileSync(BASE_WXML, next, 'utf8')
console.info(`[strip-scrollview-padding] ✅ 已从 base.wxml 移除 ${count} 处 scroll-view padding 属性`)
