/**
 * 小程序侧 HostToastLayer(M4 端口等价层)。
 *
 * 与 RN 侧共用 `apps/mobile-rn/src/host/host-toast.ts` 这一条通道:共享屏调
 * `onToast → showHostToast` 写入事件,本层是端内唯一订阅者,负责落成 `Taro.showToast`。
 * 此前小程序没有订阅者 ⇒ 事件在 prod 被静默丢弃(dev 才 warn),端口看起来"接了"。
 *
 * 样式口径:error 走端内既有错误样式(无图标,`icon:'none'`,与业务代码一致);
 * success 走标准成功图标;info 走无图标轻提示。
 */
import Taro from '@tarojs/taro'
import { useEffect } from 'react'
import type { ToastKind } from '@ihui/types'
import { subscribeHostToast } from '../../../mobile-rn/src/host/host-toast'

const DEFAULT_DURATION = 2000

export function showMiniHostToast(
  message: string,
  kind: ToastKind = 'info',
  duration?: number,
): void {
  const title = typeof message === 'string' ? message.trim() : ''
  if (!title) return
  void Taro.showToast({
    title,
    icon: kind === 'success' ? 'success' : 'none',
    duration: duration ?? DEFAULT_DURATION,
  })
}

/** 把共享通道接到 Taro toast;返回取消订阅(组件卸载/单测清理用)。 */
export function bindHostToastToTaro(): () => void {
  return subscribeHostToast((message, kind, duration) => {
    showMiniHostToast(message, kind, duration)
  })
}

export function HostToastLayer() {
  useEffect(() => bindHostToastToTaro(), [])
  return null
}
