/**
 * 小程序 OnToast 端口实现:必须经共享 host-toast 通道落到 Taro.showToast,
 * 且默认时长与端内直呼一致(1500ms),不能包一层同名假转换。
 */
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'

const taro = vi.hoisted(() => ({ showToast: vi.fn() }))
vi.mock('@tarojs/taro', () => ({ default: taro }))

import { bindHostToastToTaro } from '../HostToastLayer'
import { onToast } from '../on-toast'

describe('小程序 onToast 端口', () => {
  let unsubscribe: () => void

  beforeEach(() => {
    taro.showToast.mockClear()
    vi.stubGlobal('__DEV__', true)
    unsubscribe = bindHostToastToTaro()
  })

  afterEach(() => {
    unsubscribe()
    vi.unstubAllGlobals()
  })

  it('success 经共享通道落成标准成功图标,默认 1500ms', () => {
    onToast('已复制', { kind: 'success' })
    expect(taro.showToast).toHaveBeenCalledWith({
      title: '已复制',
      icon: 'success',
      duration: 1500,
    })
  })

  it('error 走无图标样式,显式 duration 原样透传', () => {
    onToast('操作失败', { kind: 'error', duration: 2000 })
    expect(taro.showToast).toHaveBeenCalledWith({
      title: '操作失败',
      icon: 'none',
      duration: 2000,
    })
  })

  it('未挂载渲染层时不直呼 Taro.showToast(事件只在通道里)', () => {
    unsubscribe()
    onToast('不应出现')
    expect(taro.showToast).not.toHaveBeenCalled()
  })
})
