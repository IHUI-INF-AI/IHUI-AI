/**
 * 问答创建页的宿主端口实现(2026-11-07)。
 *
 * 共享层(packages/app/features/ask-create)只声明端口形状,平台 API 全部落在本文件:
 * - `media` ← `Taro.chooseImage`(多选 N 张、原端内 sizeType=compressed 不变)
 * - `draft` ← `Taro.getStorageSync` / `setStorageSync` / `removeStorageSync`(包成异步形)
 *
 * 与 RN 侧 apps/mobile-rn/src/screens/AskCreateScreen.tsx 的适配器一一对应:
 * 两端把同一 `MediaPort` / `AsyncKvPort` 真传给共享段,而不是各写一套端内逻辑。
 */

import Taro from '@tarojs/taro'
import type { AsyncKvPort, MediaAsset, MediaPort } from '@ihui/types'

async function chooseImages(count: number): Promise<readonly MediaAsset[]> {
  const res = await Taro.chooseImage({ count, sizeType: ['compressed'] })
  return (res.tempFilePaths ?? []).map((uri) => ({ uri }))
}

export function createAskMediaPort(): MediaPort {
  return {
    pickImage: async () => {
      const assets = await chooseImages(1)
      return assets[0] ?? null
    },
    pickImages: async (options) => chooseImages(Math.max(1, options?.count ?? 1)),
    previewImage: async (urls, index = 0) => {
      if (urls.length === 0) return
      await Taro.previewImage({ urls: [...urls], current: urls[index] })
    },
  }
}

export function createAskDraftPort(): AsyncKvPort {
  return {
    get: async <T>(key: string): Promise<T | null> => {
      const raw: unknown = Taro.getStorageSync(key)
      if (!raw) return null
      try {
        return typeof raw === 'string' ? (JSON.parse(raw) as T) : (raw as T)
      } catch {
        return null
      }
    },
    set: async (key: string, value: unknown): Promise<void> => {
      Taro.setStorageSync(key, JSON.stringify(value))
    },
    remove: async (key: string): Promise<void> => {
      Taro.removeStorageSync(key)
    },
  }
}
