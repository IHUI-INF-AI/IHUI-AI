import type { Order } from './index'

/** 后端 GET /orders/:orderNo 返回的 edu_orders 原始行（金额列名为 payAmount）。 */
export interface OrderDetailRow {
  id?: string | number
  orderNo?: string
  amount?: string | number | null
  payAmount?: string | number | null
  title?: string | null
  targetTitle?: string | null
  createTime?: string | null
  createdAt?: string | Date | null
  [key: string]: unknown
}

/**
 * 订单详情字段归一：后端详情行用的是 payAmount/targetTitle/createdAt，
 * 端内 Order 契约读 amount/title/createTime。不归一会让退款页金额恒 0.00、商品与时间空白。
 */
export function normalizeOrderDetail(row: OrderDetailRow): Order {
  const amount = Number(row.amount ?? row.payAmount ?? 0)
  return {
    ...row,
    amount: Number.isFinite(amount) ? amount : 0,
    title: row.title ?? row.targetTitle ?? '',
    createTime: row.createTime ?? (row.createdAt ? String(row.createdAt) : ''),
  } as unknown as Order
}
