/** 后端 user_vips 原始行(字段名与端内 VipInfo 不同)。 */
export interface VipMineRow {
  levelValue?: number
  levelName?: string
  endTime?: string | null
}

export interface VipInfoShape {
  level: number
  name: string
  expireTime: string
}

/**
 * /vip/my 的 `{ vip }` 包络拆包 + 字段归一。
 * 无会员记录返回 null,调用方必须落空态而不是继续读包络对象。
 */
export function normalizeVipMine(row: VipMineRow | null | undefined): VipInfoShape | null {
  if (!row) return null
  return {
    level: row.levelValue ?? 0,
    name: row.levelName ?? '',
    expireTime: row.endTime ?? '',
  }
}
