// XUI-003 小程序侧夹具:/vip/my 拆包后的行字段(levelValue/endTime)必须归一成端内
// VipInfo(level/expireTime),否则会员页/店铺页恒读空。
import { describe, expect, it } from 'vitest'
import { normalizeVipMine } from '../vip-mine'

describe('XUI-003 小程序会员行归一', () => {
  it('user_vips 行归一为端内 VipInfo', () => {
    expect(
      normalizeVipMine({
        levelValue: 3,
        levelName: '铂金会员',
        endTime: '2099-01-01T00:00:00.000Z',
      }),
    ).toEqual({ level: 3, name: '铂金会员', expireTime: '2099-01-01T00:00:00.000Z' })
  })

  it('无会员记录返回 null', () => {
    expect(normalizeVipMine(null)).toBeNull()
    expect(normalizeVipMine(undefined)).toBeNull()
  })

  it('字段缺失时给安全默认值,不产出 undefined', () => {
    const info = normalizeVipMine({})
    expect(info).not.toBeNull()
    expect(info?.level).toBe(0)
    expect(info?.name).toBe('')
    expect(info?.expireTime).toBe('')
  })
})
