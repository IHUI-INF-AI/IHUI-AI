// XUI-016 小程序侧夹具:订单详情行是 edu_orders 原字段(payAmount/targetTitle/createdAt),
// 必须归一成端内 Order 的 amount/title/createTime,否则退款页金额恒 0.00、商品与时间空白。
import { describe, expect, it } from 'vitest'
import { normalizeOrderDetail } from '../order-normalize'

describe('XUI-016 订单详情字段归一', () => {
  it('payAmount/targetTitle/createdAt 归一为 amount/title/createTime', () => {
    expect(
      normalizeOrderDetail({
        id: 'o-1',
        orderNo: 'NO-1',
        payAmount: '99.00',
        targetTitle: '课程 A',
        createdAt: '2026-01-02T03:04:05.000Z',
      }),
    ).toMatchObject({
      amount: 99,
      title: '课程 A',
      createTime: '2026-01-02T03:04:05.000Z',
    })
  })

  it('已有 amount 时以 amount 为准,不被 payAmount 覆盖', () => {
    expect(normalizeOrderDetail({ amount: '12.34', payAmount: '99.00' }).amount).toBe(12.34)
  })

  it('金额全缺时回落 0 而不是 undefined/NaN', () => {
    const order = normalizeOrderDetail({ id: 'o-2' })
    expect(order.amount).toBe(0)
    expect(Number.isNaN(order.amount)).toBe(false)
  })
})
