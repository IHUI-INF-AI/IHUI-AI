// XUI-021 小程序侧夹具:分销概览必须一一映射 —— 可提现取 availableCommission,
// 团队人数取 invitedCount,等级取 level;不得把待结算 pendingCommission 当可提。
import { describe, expect, it } from 'vitest'
import { normalizeDistributionOverview } from '../distribution-normalize'

describe('XUI-021 分销概览字段映射', () => {
  it('available 取 availableCommission、teamCount 取 invitedCount、level 取 level', () => {
    expect(
      normalizeDistributionOverview({
        totalCommission: 100,
        availableCommission: 30,
        pendingCommission: 70,
        withdrawnCommission: 5,
        level: 3,
        invitedCount: 8,
        activeCount: 6,
        orderCount: 12,
        inviteCode: 'ABC123',
      }),
    ).toEqual({
      level: 3,
      totalCommission: 100,
      available: 30,
      pendingCommission: 70,
      withdrawn: 5,
      teamCount: 8,
      inviteCode: 'ABC123',
    })
  })

  it('阴性对照:只有 pendingCommission 时 available 不得等于待结算', () => {
    const info = normalizeDistributionOverview({ pendingCommission: 70 })
    expect(info.available).toBe(0)
    expect(info.pendingCommission).toBe(70)
  })

  it('空响应给出数值默认值,不产出 undefined', () => {
    expect(normalizeDistributionOverview({})).toEqual({
      level: 0,
      totalCommission: 0,
      available: 0,
      pendingCommission: 0,
      withdrawn: 0,
      teamCount: 0,
      inviteCode: null,
    })
  })
})
