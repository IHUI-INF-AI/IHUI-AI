/**
 * XUI-072:课程详情「签到」原先无条件连发成功 + 失败两条 toast,
 * 用户看到「签到成功」后紧跟「失败」。本夹具钉住:成功提示必须在 try 内、
 * 失败提示只能在 catch 分支,二者互斥。
 */
import { readFileSync } from 'node:fs'
import { join } from 'node:path'
import { describe, expect, it } from 'vitest'

const SRC = readFileSync(join(__dirname, '..', 'detail.tsx'), 'utf8')

/** 判据:正反两面对同一实现 */
export function detectSignToast(src: string): string[] {
  const missing: string[] = []
  const fn =
    /const handleSign = useCallback\(async \(\) => \{[\s\S]*?\}, \[t\]\)/.exec(src)?.[0] ?? ''
  if (!fn) return ['handleSign']
  if (!/try \{[\s\S]*?await post\('/.test(fn)) missing.push('sign request inside try')
  if (!/try \{[\s\S]*?onToast\(t\('course\.signSuccess'\)/.test(fn)) {
    missing.push('success toast inside try')
  }
  if (!/catch \{[\s\S]*?onToast\(t\('common\.failed'\)/.test(fn)) {
    missing.push('failure toast inside catch')
  }
  // 旧病灶:成功与失败两条 toast 无条件相邻
  if (
    /onToast\(t\('course\.signSuccess'\)(?:(?!catch)[\s\S]){0,80}onToast\(t\('common\.failed'\)/.test(
      fn,
    )
  ) {
    missing.push('success and failure toasts both fire')
  }
  return missing
}

describe('XUI-072 签到 toast 单一出口', () => {
  it('正向:成功只在 try、失败只在 catch', () => {
    expect(detectSignToast(SRC)).toEqual([])
  })

  it('反向对照:旧实现(两条 toast 连发)必须判红', () => {
    const oldImpl = `
const handleSign = useCallback(async () => {
  await post('/sign-in', {})
  onToast(t('course.signSuccess'), { kind: 'success' })
  onToast(t('common.failed'), { kind: 'error' })
}, [t])
`
    expect(detectSignToast(oldImpl)).toEqual([
      'sign request inside try',
      'success toast inside try',
      'failure toast inside catch',
      'success and failure toasts both fire',
    ])
  })
})
