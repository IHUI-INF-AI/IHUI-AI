/**
 * XUI-055:调用方声明 `allowsMultipleSelection: true` 但没给 `selectionLimit`
 * (CirclePostScreen 选图),旧垫片只取 `selectionLimit ?? 1` ⇒ 多选退化成单选。
 */
import { beforeEach, describe, expect, it, vi } from 'vitest'

const taro = vi.hoisted(() => ({
  chooseImage: vi.fn(),
  getSetting: vi.fn(),
  getSystemInfoSync: vi.fn(() => ({ windowWidth: 375, windowHeight: 667 })),
}))

vi.mock('@tarojs/taro', () => ({ default: taro }))
vi.mock('@tarojs/components', () => ({
  View: () => null,
  Text: () => null,
  ScrollView: () => null,
  Image: () => null,
  Input: () => null,
  Switch: () => null,
  Textarea: () => null,
}))

import { ImagePicker } from './platform'

beforeEach(() => {
  taro.chooseImage.mockReset()
  taro.chooseImage.mockResolvedValue({ tempFilePaths: [], tempFiles: [] })
})

describe('XUI-055 多选不再退化为单选', () => {
  it('allowsMultipleSelection 无上限 ⇒ 取小程序上限 9', async () => {
    await ImagePicker.launchImageLibraryAsync({
      allowsMultipleSelection: true,
      quality: 0.8,
    })
    expect(taro.chooseImage).toHaveBeenCalledWith({ count: 9 })
  })

  it('显式 selectionLimit 优先', async () => {
    await ImagePicker.launchImageLibraryAsync({
      allowsMultipleSelection: true,
      selectionLimit: 3,
    })
    expect(taro.chooseImage).toHaveBeenCalledWith({ count: 3 })
  })

  it('未声明多选仍是单选', async () => {
    await ImagePicker.launchImageLibraryAsync({ quality: 0.8 })
    expect(taro.chooseImage).toHaveBeenCalledWith({ count: 1 })
  })
})
