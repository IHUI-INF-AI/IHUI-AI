/**
 * `apps/mobile-rn/src/context/AuthContext` 在小程序端的等价实现。
 *
 * RN 壳（`@rn-shells/*`）与共享屏（`@ihui/rn-app/*`）只通过 `useAuth()` 读
 * `user/token/ready`，并通过 `login/logout/returnUrl` 驱动登录出口。这里不复制
 * 登录流程，全部委托给端内唯一真相源 `stores/user`；因此 RN 壳不需要知道
 * 小程序登录细节，小程序也不需要抄一份 RN 的登录状态机。
 */
import type { ReactNode } from 'react'
import { useUserStore } from '@/stores/user'
import type { AuthUser } from '@ihui/api-client'

export type { AuthUser }

export interface LoginResult {
  success: boolean
  error?: string
}

export interface AuthContextValue {
  user: AuthUser | null
  token: string | null
  ready: boolean
  login: (account: string, password: string) => Promise<LoginResult>
  loginBySso: () => Promise<LoginResult>
  logout: () => Promise<void>
  returnUrl: string | null
  setReturnUrl: (url: string | null) => void
}

/**
 * 端内登录态已经由 `stores/user` 单点持有；壳层不需要再包一层 Provider。
 * 保留同名 `AuthProvider` 导出，供仍按 RN RootNavigator 形制使用的镜像页直接复用。
 */
export function AuthProvider({ children }: { children: ReactNode }) {
  return <>{children}</>
}

export function useAuth(): AuthContextValue {
  const user = useUserStore((s) => s.user)
  const token = useUserStore((s) => s.token)

  return {
    // 端内 UserInfo 与 api-client AuthUser 的公共字段同名；壳层只消费昵称/头像/id。
    user: (user as unknown as AuthUser | null) ?? null,
    token: token || null,
    ready: true,
    login: async () => ({ success: false, error: '请在「我的」完成登录' }),
    loginBySso: async () => ({ success: false, error: '请在「我的」完成登录' }),
    logout: async () => {
      useUserStore.getState().logout()
    },
    returnUrl: null,
    setReturnUrl: () => {},
  }
}
