/**
 * `apps/mobile-rn/src/components/Drawer` 在小程序端的等价实现。
 *
 * RN Drawer 依赖 Animated / PanResponder / Modal / 手势链，小程序端没有等价物；
 * 但首页壳只在用户点左上角菜单时才需要它。这里先提供**不影响首页渲染**的占位：
 * 关闭态返回 null，打开态用一个最小遮罩提示（后续可换成 Taro 侧滑页）。
 *
 * 目的不是永久降级，而是让「同一个 RN 首页壳」能先在端内挂载；侧滑菜单是下一步
 * 单独补的交互件，不阻塞首屏一致性。
 */
import type { ReactNode } from 'react'

export type DrawerTab = 'home' | 'ai' | 'square' | 'share' | 'mine'
export type DrawerExtraMenu = 'tools' | 'aigc' | 'learn' | 'modelPlaza' | 'company' | 'assistant'
export type DrawerUserLevel = 'vip' | 'normal'

export interface DrawerModelConfig {
  id: string
  name: string
  icon?: string
}

export interface DrawerProps {
  visible?: boolean
  onClose?: () => void
  children?: ReactNode
  [key: string]: unknown
}

/** 占位实现：关闭态不挂任何树；打开态交给端内后续侧滑菜单页，这里不抢交互。 */
export function Drawer({ visible }: DrawerProps) {
  if (!visible) return null
  return null
}
