/**
 * rn-compat/expo-modules-core —— 阻止 Taro/webpack 解析 node_modules 内带 `export type *` 的 TS 入口。
 * 真包只应在 RN 端运行;小程序侧 expo-* 别名已全部指到 rn-compat,本件兜底 transitively 解析。
 */
export class UnavailabilityError extends Error {
  constructor(moduleName: string, methodName: string) {
    super(`${moduleName}.${methodName} is not available in miniapp`)
    this.name = 'UnavailabilityError'
  }
}

export function requireNativeModule<T = unknown>(_name: string): T {
  return {} as T
}

export function requireOptionalNativeModule<T = unknown>(_name: string): T | null {
  return null
}

export type EventSubscription = { remove: () => void }

export class EventEmitter {
  addListener(_event: string, _listener: (...args: unknown[]) => void): EventSubscription {
    return { remove: () => {} }
  }

  removeAllListeners(_event?: string): void {}

  emit(_event: string, ..._args: unknown[]): void {}
}
