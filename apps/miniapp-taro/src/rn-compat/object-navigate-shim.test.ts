/**
 * XUI-056:RN 侧存在对象形 `navigation.navigate({ name, params })`;
 * 旧垫片把它当字符串路由名 ⇒ 解析失败、跳转静默不执行。
 */
import { describe, expect, it, vi } from 'vitest'

const taro = vi.hoisted(() => ({
  showToast: vi.fn(),
  switchTab: vi.fn(),
  navigateTo: vi.fn(),
  redirectTo: vi.fn(),
  navigateBack: vi.fn(),
  getCurrentPages: vi.fn(() => [{}]),
  getCurrentInstance: vi.fn(() => ({ page: null, router: { path: '', params: {} } })),
}))

vi.mock('@tarojs/taro', () => ({
  default: taro,
  useDidShow: vi.fn(),
  useDidHide: vi.fn(),
  useUnload: vi.fn(),
}))

import { RN_ROUTE_MAP } from './route-map.generated'
import { MINI_TAB_PATHS } from './navigation'
import { createCompatNavigation } from './navigation'

const entry =
  Object.entries(RN_ROUTE_MAP).find(([, path]) => !MINI_TAB_PATHS.includes(path)) ??
  Object.entries(RN_ROUTE_MAP)[0]
const [ROUTE_NAME, ROUTE_PATH] = entry

const makeNav = () =>
  createCompatNavigation({
    fail: vi.fn(),
    focusListeners: new Set(),
    blurListeners: new Set(),
  })

describe('XUI-056:对象形 navigate 必须真跳', () => {
  it('navigate({ name, params }) 走 navigateTo', () => {
    taro.navigateTo.mockClear()
    const nav = makeNav()
    nav.navigate({ name: ROUTE_NAME, params: { id: 3 } })
    expect(taro.navigateTo).toHaveBeenCalledWith({ url: `${ROUTE_PATH}?id=3` })
  })

  it('字符串形保持原行为', () => {
    taro.navigateTo.mockClear()
    const nav = makeNav()
    nav.navigate(ROUTE_NAME)
    expect(taro.navigateTo).toHaveBeenCalledWith({ url: ROUTE_PATH })
  })
})
