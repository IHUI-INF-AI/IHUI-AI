/**
 * rn-compat/icons-runtime.tsx —— lucide 图标在小程序端的渲染出口(生成物 icons-generated.tsx 的唯一依赖)。
 *
 * 手法与端内 `src/components/LineIcon` 同一条:SVG 当 CSS mask(只取 alpha),
 * 实际颜色由 background-color 决定 ⇒ 图标随主题 token 换色,而不是定死成黑色描边。
 * (RN 端 lucide 是矢量描边、颜色走 props,这里取的是同一张观感,不是又造一套机制。)
 */
import type { CSSProperties } from 'react'
import { View } from '@tarojs/components'

export interface CompatIconProps {
  /** 边长(RN 的 size 是 dp ⇒ 数字按 px 落,与 RN 同尺寸) */
  size?: number | string
  color?: string
  /** lucide 的 strokeWidth 在 mask 形态下改不了几何,只作占位接收 */
  strokeWidth?: number
  opacity?: number
  style?: CSSProperties
  fill?: string
  name?: string
}

/** SVG → data URI(# 必须转义,否则 weapp 把 # 当 fragment 截断) */
function toDataUri(svg: string): string {
  const normalized = svg.replace(/\s+/g, ' ').trim()
  return `url("data:image/svg+xml,${encodeURIComponent(normalized).replace(/%23/g, '%2523')}")`
}

export function makeIcon(defaultName: string, svg: string) {
  return function CompatIcon(props: CompatIconProps) {
    const raw = props.size ?? 24
    const box = typeof raw === 'number' ? `${raw}px` : raw
    const style: CSSProperties = {
      display: 'inline-block',
      width: box,
      height: box,
      backgroundColor: props.color ?? 'currentColor',
      WebkitMaskImage: toDataUri(svg),
      maskImage: toDataUri(svg),
      WebkitMaskSize: '100% 100%',
      maskSize: '100% 100%',
      WebkitMaskRepeat: 'no-repeat',
      maskRepeat: 'no-repeat',
      WebkitMaskPosition: 'center',
      maskPosition: 'center',
      flexShrink: 0,
      opacity: props.opacity,
      ...props.style,
    }
    void defaultName
    return <View style={style} />
  }
}
