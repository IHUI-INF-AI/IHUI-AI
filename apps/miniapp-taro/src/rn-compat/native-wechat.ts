/**
 * rn-compat/native-wechat.ts —— `react-native-wechat-lib` 的小程序端承载。
 *
 * 为什么必须补:该包入口是未编译的 RN 原生源码,进入 weapp 图即 `ModuleParseError`(与
 * react-native-svg / webview / expo-modules-core 同一型),而它由 `apps/mobile-rn/src/lib/wechat.ts`
 * 的 `import * as wechatLib` 带入 —— 那一条链在壳承载页闭包里。
 *
 * 这一档**不实现分享/授权**:小程序的微信分享与登录是端内原生能力(Taro 的 shareMenu / wx.login),
 * 与 RN SDK 的 registerApp/sendAuthRequest 不同形,不是"翻译一下"的关系。
 * 这里把成员显式留空(`undefined`)而不是删除 —— 调用方 `apps/mobile-rn/src/lib/wechat.ts`
 * 本来就有 `typeof wechatLib.X !== 'function'` 的守卫,读到 undefined 即走它的"SDK 未初始化"降级路径;
 * 而导出这些名字能让 webpack 不再报"export not found"(缺一名字就多一类静默 undefined)。
 *
 * 要真补齐小程序端分享/登录,正确工作是端内另开一条 Taro 原生链(不是把这里改成假实现)。
 */
const unsupported = (name: string): undefined => {
  console.warn(
    `[rn-compat] react-native-wechat-lib 的 ${name} 在小程序端由 undefined 承载 ⇒ 调用方的"SDK 未初始化"降级路径生效`,
  )
  return undefined
}

export const registerApp = unsupported('registerApp')
export const isWXAppInstalled = unsupported('isWXAppInstalled')
export const sendAuthRequest = unsupported('sendAuthRequest')
export const shareWebpage = unsupported('shareWebpage')

export type AuthResponse = Record<string, unknown>

export default { registerApp, isWXAppInstalled, sendAuthRequest, shareWebpage }
