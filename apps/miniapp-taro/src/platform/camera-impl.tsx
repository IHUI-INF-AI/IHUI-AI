/**
 * 相机占位组件的**唯一定义**。
 *
 * 立因(2026-11-12,构建实证):RN 壳屏 `import { CameraView } from '@/platform/camera'`,
 * 本端此前没有这个文件 ⇒ `build:weapp` 在 resolve 阶段硬失败。
 *
 * 行为如实:**小程序没有可复用的 CameraView 组件**(硬件相机走 Taro 的 `chooseImage` /
 * `scanCode` 命令式能力,不是可挂载的视图)。这里给一个显式的"不可用"占位,而不是
 * 返回 `null` 让调用方以为相机渲染成功 —— 后者只会在运行时留一块空白(XUI-054)。
 * `useCameraPermissions` 的交集面按"未授权且不可申请"如实回答。
 */
import { Text, View } from 'react-native'
import type { ReactElement } from 'react'

export interface CameraViewProps {
  children?: ReactElement | null
  style?: unknown
  facing?: 'front' | 'back'
  [key: string]: unknown
}

/** 不可用占位:可见的说明文字,而不是静默空白。 */
export function CameraView(_props: CameraViewProps): ReactElement {
  return (
    <View style={{ padding: 12 }}>
      <Text>camera is not available on miniapp</Text>
    </View>
  )
}

export function useCameraPermissions(): [
  { granted: false; status: 'denied' },
  () => Promise<{ granted: false; status: 'denied' }>,
] {
  return [{ granted: false, status: 'denied' }, async () => ({ granted: false, status: 'denied' })]
}
