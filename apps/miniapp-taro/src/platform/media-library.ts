/**
 * `@/platform/media-library` 的小程序腿 —— **只做转出口**,不实现任何行为。
 *
 * 立因(2026-11-12,构建实证):RN 壳 `apps/mobile-rn/src/{components,screens,hooks}/**`
 * 写 `import … from '@/platform/media-library'`。这些壳在小程序编译面里(mini 段 `@` → 本端 src),
 * 而本端此前没有这个文件 ⇒ `build:weapp` 在 resolve 阶段硬失败。
 *
 * 为什么命名空间与扁平**两者都给**:RN 侧两种写法都在用(`MediaLibrary.saveToLibraryAsync`
 * 与解构式的 `requestPermissionsAsync`),只给命名空间会让后者在构建期变成
 * "export 'saveToLibraryAsync' was not found" 的警告 + 运行时 undefined 的静默失败。
 * 实现仍是 `rn-compat/platform` 那一份(§0.6 不建第二套)。
 */
import { MediaLibrary as Impl } from '../rn-compat/platform'

export const MediaLibrary = Impl
export const requestPermissionsAsync = Impl.requestPermissionsAsync
export const getAsync = Impl.getAsync
export const createAssetAsync = Impl.createAssetAsync
export const saveToLibraryAsync = Impl.saveToLibraryAsync
export const saveToPhotosAsync = Impl.saveToPhotosAsync
export const deleteAssetsAsync = Impl.deleteAssetsAsync
