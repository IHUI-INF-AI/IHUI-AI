/**
 * `@/platform/updates` 的小程序腿 —— **只做转出口**,不实现任何行为。
 *
 * 立因(2026-11-12,构建实证):RN 壳 `apps/mobile-rn/src/{components,screens,hooks}/**`
 * 写 `import … from '@/platform/updates'`。这些壳在小程序编译面里(mini 段 `@` → 本端 src),
 * 而本端此前只有 auth/pay 两个同名文件 ⇒ `build:weapp` 在 resolve 阶段硬失败
 * (实测 `resolve '@/platform/audio' in .../src/components` 直接 ✖ Errors)。
 *
 * 为什么是"转出口"而不是"再写一份":§0.6 单一真相源。每个真正的能力承接体早已存在
 * (`src/rn-compat/*` + expo-* 别名表),这里再写一份就是第二套实现,必然漂移。
 */

/**
 * 小程序没有 OTA 热更新通道(Taro 构建产物由平台审核下发)⇒ 这里只交出显式的"无更新"态。
 * 不返回假成功:调用方按 `isAvailable === false` 走"重启 App 才生效"的既有降级分支。
 */
export const Updates = {
  isAvailable: false,
  async checkForUpdateAsync(): Promise<{ isAvailable: false }> {
    return { isAvailable: false }
  },
  async fetchUpdateAsync(): Promise<{ isNew: false }> {
    return { isNew: false }
  },
  async reloadAsync(): Promise<never> {
    throw new Error('updates.reloadAsync is not supported on miniapp')
  },
}
