import { View, Text, Image } from '@tarojs/components'
import { cn } from '@ihui/design-tokens'
import type { AvatarSize } from '@ihui/shared/ui/avatar-spec'

export interface AvatarProps {
  src?: string
  name?: string
  size?: AvatarSize
  shape?: 'circle' | 'square'
  onClick?: () => void
}

/**
 * 类名表留在本端文件里是**必须的**,不是没做完:小程序 tailwind 的 content 只扫 `./src/**`
 * (见 `apps/miniapp-taro/tailwind.config.ts:22`),类名写进 `packages/shared` 就进不了产物,
 * 头像会静默失去尺寸。跨端唯一真相是数值表 `@ihui/shared/ui/avatar-spec` 的 `AVATAR_PX`,
 * 这张表与它的对应关系由 `packages/shared/src/ui/__tests__/avatar-spec-wiring.test.ts` 钉住
 * (任一端改数值而没改这张 ⇒ 测试红)。
 * 2026-10-22 机主定档:取 web/RN 已同值的五档,小程序整体升一档(sm 24→32…xl 56→64)。
 */
const SIZES: Record<AvatarSize, string> = {
  xs: 'h-6 w-6 text-xs',
  sm: 'h-8 w-8 text-xs',
  md: 'h-10 w-10 text-sm',
  lg: 'h-12 w-12 text-base',
  xl: 'h-16 w-16 text-xl',
}

export default function Avatar({
  src,
  name = '',
  size = 'md',
  shape = 'circle',
  onClick,
}: AvatarProps) {
  const sizeClass = SIZES[size]
  const shapeClass = shape === 'circle' ? 'rounded-md' : 'rounded-lg'

  if (src) {
    return (
      <Image
        className={cn(sizeClass, shapeClass, 'bg-muted')}
        src={src}
        mode="aspectFill"
        onClick={onClick}
      />
    )
  }

  return (
    <View
      className={cn('flex items-center justify-center', sizeClass, shapeClass, 'bg-primary/10')}
      onClick={onClick}
      hoverClass="opacity-60"
    >
      <Text className="text-primary font-medium">{name.charAt(0) || '?'}</Text>
    </View>
  )
}
