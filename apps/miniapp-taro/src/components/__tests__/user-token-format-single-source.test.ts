/**
 * XUI-065:小程序 UserInfoCard 曾自留一套 w/k 智汇值格式(1 位小数、1000 起跳),
 * 与 RN 走的共享函数(万/亿 + 2 位小数)分歧。本夹具钉住「只有一个来源」。
 */
import { readFileSync } from 'node:fs'
import { join } from 'node:path'
import { describe, expect, it } from 'vitest'
import { formatTokenValue } from '@ihui/shared/utils/format'

const APP_ROOT = join(__dirname, '..', '..', '..')
const read = (p: string) => readFileSync(join(APP_ROOT, p), 'utf8')

describe('XUI-065:智汇值格式化收敛到共享函数', () => {
  it('UserInfoCard 不再自留 formatTokenValue 实现', () => {
    const src = read('src/components/UserInfoCard.tsx')
    expect(src).not.toMatch(/function formatTokenValue/)
    expect(src).not.toContain("+ 'w'")
    expect(src).not.toContain("+ 'k'")
    expect(src).toContain("import { formatTokenValue } from '@ihui/shared/utils/format'")
  })

  it('共享函数与 RN 同表:万/亿 + 2 位小数', () => {
    expect(formatTokenValue(999)).toBe('999')
    expect(formatTokenValue(12345)).toBe('1.23万')
    expect(formatTokenValue(100000000)).toBe('1.00亿')
  })
})
