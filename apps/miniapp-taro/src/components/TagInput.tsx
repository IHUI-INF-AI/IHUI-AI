import { useTt, t } from '@/i18n'
import { View, Text } from '@tarojs/components'
import { FocusInput } from '@/components/FocusField'
import { useState } from 'react'

export interface TagInputProps {
  value?: string[]
  placeholder?: string
  max?: number
  onChange?: (tags: string[]) => void
}

export default function TagInput({
  value = [],
  placeholder = t('TagInput.p1'),
  max = 10,
  onChange,
}: TagInputProps) {
  const tt = useTt()
  const [input, setInput] = useState('')

  const addTag = () => {
    const v = input.trim()
    if (v && !value.includes(v) && value.length < max) {
      onChange?.([...value, v])
      setInput('')
    }
  }

  // 按 tag 值删除(与渲染 key 同一标识):列表支持删除,按下标渲染会随位置复用错位,
  // 用去重后唯一的 tag 值本身作 key 与删除入参,彻底解耦"节点身份"与"数组下标"。
  const removeTag = (tag: string) => {
    onChange?.(value.filter((v) => v !== tag))
  }

  return (
    <View className="flex flex-wrap items-center px-md py-sm bg-muted rounded-sm">
      {value.map((tag) => (
        <View
          key={tag}
          className="flex items-center mr-sm mb-[12rpx] px-[20rpx] py-xs rounded-md bg-primary/10"
        >
          <Text className="text-label text-primary mr-xs">{tag}</Text>
          <View
            className="text-label text-primary"
            hoverClass="opacity-60"
            onClick={() => removeTag(tag)}
          >
            <Text>×</Text>
          </View>
        </View>
      ))}
      <FocusInput
        className="flex-1 min-w-20 text-body"
        placeholder={value.length >= max ? tt('TagInput.p2', '已达上限') : placeholder}
        value={input}
        onInput={(e) => setInput(e.detail.value)}
        onConfirm={addTag}
      />
    </View>
  )
}
