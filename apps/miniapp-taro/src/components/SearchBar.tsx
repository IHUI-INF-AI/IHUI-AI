import { useState } from 'react'
import { t } from '@/i18n'
import { View, Text, Input, type InputProps } from '@tarojs/components'
import LineIcon from '@/components/LineIcon'

type ConfirmType = NonNullable<InputProps['confirmType']>

export interface SearchBarProps {
  value?: string
  placeholder?: string
  onInput?: (value: string) => void
  onSearch?: () => void
  onClear?: () => void
  /** 键盘确认键类型,默认 'search' */
  confirmType?: ConfirmType
  /**
   * 外层容器附加类。圆角输入井本体(bg-muted rounded-md border + 聚焦变色)始终保留;
   * 提供本属性时不再追加默认外边距 mx-3 my-2,用于嵌入 flex 行(如 flex-1 / mx-0)。
   */
  className?: string
}

/** 圆角输入井本体样式(不含外边距与边框色,边框色由聚焦态决定) */
const searchBarWellClassName =
  'flex items-center gap-2 px-3 py-2 bg-muted rounded-md border transition-colors'

export default function SearchBar({
  value = '',
  placeholder = t('course.list.search'),
  onInput,
  onSearch,
  onClear,
  confirmType = 'search',
  className,
}: SearchBarProps) {
  const [focused, setFocused] = useState(false)
  return (
    <View
      className={`${searchBarWellClassName} ${focused ? 'border-ring' : 'border-border'} ${className ?? 'mx-3 my-2'}`}
    >
      <LineIcon name="search" size={24} color="var(--color-muted-foreground)" />
      <Input
        className="flex-1 text-sm"
        placeholder={placeholder}
        value={value}
        confirmType={confirmType}
        onFocus={() => setFocused(true)}
        onBlur={() => setFocused(false)}
        onInput={(e) => onInput?.(e.detail.value)}
        onConfirm={() => onSearch?.()}
      />
      {value && (
        <Text className="text-sm text-muted-foreground" onClick={onClear}>
          ×
        </Text>
      )}
    </View>
  )
}
