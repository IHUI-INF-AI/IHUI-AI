import { Video } from '@tarojs/components'

/**
 * AIGC 列表内联视频渲染器 —— 共享屏只按 video Renderer 端口挂载,
 * 本组件是端内平台能力层(Taro Video 组件),页面文件不出现渲染 JSX。
 */
export default function AigcVideoInline({ uri, onError }: { uri: string; onError?: () => void }) {
  return (
    <Video
      src={uri}
      style={{ width: '100%', height: '100%' }}
      controls
      autoplay
      showFullscreenBtn
      objectFit="contain"
      onError={onError}
    />
  )
}
