import type { ComponentProps } from 'react'
import { View, Text } from '@tarojs/components'
import { cn, type BadgeBaseProps } from '@ihui/design-tokens'

/**
 * 徽章组件 —— 与 `packages/ui-native/src/badge.tsx` 逐类对齐(「一模一样」契约)。
 *
 * 两端共用同一组语义 token:`bg-primary` / `bg-secondary` / `bg-destructive` / `border-border`
 * 配 `text-*-foreground`,均由统一 design-tokens 提供,视觉由 token 保证一致。
 * RN 端用 cva `badgeVariants` 生成类;小程序端未声明 cva,故以本地常量镜像同一组 variant 类
 * (与 Button 的 `md` 档处理同策略:共享类型复用、类常量本地化)。
 * `variant` 类型直接复用 `@ihui/design-tokens` 的 `BadgeBaseProps`(内含 `BadgeVariant` 枚举,两端一致),
 * 不在此另起枚举,保证 API 1:1。小程序端此前只有领域徽章(LevelBadge/UnreadBadge),无通用 Badge。
 */
const BADGE_BASE = 'flex flex-row items-center px-2.5 py-0.5 rounded-md'
const BADGE_VARIANT_CLASSES: Record<NonNullable<BadgeBaseProps['variant']>, string> = {
  default: 'bg-primary',
  secondary: 'bg-secondary',
  destructive: 'bg-destructive',
  outline: 'border border-border bg-transparent',
}
const BADGE_TEXT_VARIANT_CLASSES: Record<NonNullable<BadgeBaseProps['variant']>, string> = {
  default: 'text-primary-foreground',
  secondary: 'text-secondary-foreground',
  destructive: 'text-destructive-foreground',
  outline: 'text-foreground',
}

export type BadgeProps = ComponentProps<typeof View> & BadgeBaseProps & { label?: string }

export function Badge({ variant, label, className, children, ...props }: BadgeProps) {
  const v = variant ?? 'default'
  return (
    <View className={cn(BADGE_BASE, BADGE_VARIANT_CLASSES[v], className)} {...props}>
      <Text className={cn('text-xs font-semibold', BADGE_TEXT_VARIANT_CLASSES[v])}>
        {label ?? children}
      </Text>
    </View>
  )
}

export default Badge
