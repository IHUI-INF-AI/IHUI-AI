// 平台特有:依赖端内 store 的冷启动鉴权就绪位(`@/hooks/use-auth-ready-gate`)与 Taro 存储面

import type { ReactNode } from 'react'
import { useEffect, useState } from 'react'

import PageLoading from '@/components/PageLoading'
import { useAuthReadyGate } from '@/hooks/use-auth-ready-gate'

/**
 * 鉴权就绪门 —— 壳承载页的通用外罩(2026-10-27 立)。
 *
 * 共享屏 / RN 壳在自己挂载时立刻取数,而小程序的鉴权判定要等冷启动落定;未落定就挂载会打出一屏
 * 401 错误态。端内手写页此前用 `useDidShow + gate.waitUntilReady(load)` 处理同一件事 ——
 * 本组件把"等就绪再放行"固化成一处(现读 35 枚手写页带着同一个钩子),壳承载页只需包一层,
 * 行为与原页一致:未就绪显示加载中,落定后渲染真相源。
 */
export default function AuthReadyGate({ children }: { children: ReactNode }) {
  const gate = useAuthReadyGate()
  const [ready, setReady] = useState(gate.allow)
  useEffect(() => {
    if (gate.allow) {
      setReady(true)
      return
    }
    return gate.waitUntilReady(() => setReady(true))
  }, [gate.allow])
  if (!ready) return <PageLoading />
  return <>{children}</>
}
