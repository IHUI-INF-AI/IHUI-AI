import { View, Text } from '@tarojs/components'
import { type ReactNode, type ReactElement } from 'react'

/**
 * 认证按钮共享组件 — 对齐 zhs_app-ZZ login.vue / register.vue 的 btn
 * 2026-09-03:移除 zcbutton.png 渐变背景覆盖层,底色统一走 design-tokens
 * (login/register 变体均为 var(--color-foreground) 黑底 + var(--color-card) 白字,对齐 web bg-primary)。
 * 圆角:login=radius-xl,register=radius-lg(由各页面 CSS .btn-login/.btn-register 定义)
 */

export interface AuthButtonProps {
  /** 按钮文字 */
  children: ReactNode
  /** 点击回调 */
  onClick: () => void
  /** 禁用态(loading 时传 true) */
  disabled?: boolean
  /** 视觉变体:login=登录/找回密码,register=注册 */
  variant?: 'login' | 'register'
}

export default function AuthButton({
  children,
  onClick,
  disabled = false,
  variant = 'login',
}: AuthButtonProps): ReactElement {
  const variantClass = variant === 'register' ? 'btn-register' : 'btn-login'
  return (
    <View className="login-btn">
      <View
        className={`btn ${variantClass} ${disabled ? 'btn-disabled' : ''}`}
        onClick={disabled ? undefined : onClick}
      >
        <Text className="btn-text">{children}</Text>
      </View>
    </View>
  )
}
