/**
 * RnShellPage —— 小程序端承载 RN 壳时的页面安全区根容器。
 *
 * 立因:页面 config 设 `navigationStyle: 'custom'` 后,原生导航栏(含状态栏占位)被去掉;
 * 而 RN 壳的 NavBar 只负责行内 44px,不负责状态栏顶距(移动端由 App.tsx 的
 * SafeAreaView 单点注入)。若直接 `<ThemeRoot><XxxScreenShell /></ThemeRoot>`,NavBar
 * 会被状态栏/右上角胶囊压住不可见。本容器在读一次系统状态栏高度后垫在页面顶部,
 * 让自定义导航栏从状态栏下方开始。仅 custom nav 的 RN 壳页使用,原生导航页不要套,
 * 否则会多垫一层。
 */
import type { PropsWithChildren } from 'react'
import ThemeRoot from '@/components/ThemeRoot'
import { getTopBarMetrics } from '@/utils/system-info'

export default function RnShellPage({ children }: PropsWithChildren) {
  const { statusBarHeight } = getTopBarMetrics()
  // RN 屏 root 普遍是 `flex:1` 的 shell。ThemeRoot 默认高度 auto 时,flex:1 子项在
  // 小程序里会折叠成 0 高(Agent/Share 这类整屏脚手架会白屏);给一个确定高度
  // 再把状态栏 padding 计入盒内,子屏才能像 RN 一样填满视口。
  return (
    <ThemeRoot style={{ height: '100vh', boxSizing: 'border-box', paddingTop: statusBarHeight }}>
      {children}
    </ThemeRoot>
  )
}
