import { Text, View } from '@tarojs/components'
import { type VipBadgeBaseProps } from '@ihui/design-tokens'

/**
 * VIP 徽章 —— 与 `packages/ui-native/src/vip-badge.tsx` 逐类对齐(「一模一样」契约)。
 *
 * API 1:1 复用 `@ihui/design-tokens` 的 `VipBadgeBaseProps`(size 'sm'|'md' + label,两端一致)。
 * 布局/间距/字号走共享 token 类(flex-row items-center rounded-md px-* py-* text-xs gap-*),
 * 这些类在两端 Tailwind preset 均存在,视觉由 token 保证。
 *
 * 颜色例外:RN 端用 `bg-amber-500/10` + `text-amber-600`,但共享 preset 仅含语义色、
 * 未含 Tailwind 默认 amber 调色板(改 preset 会动正在飞的 design-tokens 包,本轮不碰)。
 * 为达成两端「一模一样」视觉,此处用与 amber-500(#f59e0b)/amber-600(#d97706) 等价的
 * rgba 内联(amber-500/10 = rgba(245,158,11,0.1)),变更收口在单文件,不引入共享层改动。
 * 后续若把 amber 收进共享 preset,可改回 `bg-amber-500/10 text-amber-600`。
 */
const AMBER_BG = 'rgba(245, 158, 11, 0.1)' // amber-500 @ 10%
const AMBER_FG = '#d97706' // amber-600

export function VipBadge({ size = 'sm', label = 'VIP' }: VipBadgeBaseProps) {
  const sizing = size === 'md' ? 'px-2.5 py-1 text-xs gap-1' : 'px-2 py-0.5 text-xs gap-0.5'
  return (
    <View
      className={`flex flex-row items-center rounded-md ${sizing}`}
      style={{ backgroundColor: AMBER_BG }}
    >
      <Text className="text-xs font-medium" style={{ color: AMBER_FG }}>
        {label}
      </Text>
    </View>
  )
}

export default VipBadge
