// 平台特有:依赖 Taro 运行时 API(getAccountInfoSync),不可下沉到跨端共享层。

import Taro from '@tarojs/taro'

/**
 * 小程序版本号的唯一出口(2026-11-04 立,同族"看起来像版本号、却不被任何东西驱动"的收口)。
 * `miniProgram.version` 只有线上版非空,开发/体验版为空串 ⇒ 空串表示"取不到",
 * 调用方一律按「不显示」处理,禁止拿它再编一个号(§0.3 没取到不记绿也不冒红)。
 */
export function getMiniappVersion(): string {
  return Taro.getAccountInfoSync?.()?.miniProgram?.version ?? ''
}
