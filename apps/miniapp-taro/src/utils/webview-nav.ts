import { navigateTo } from '@tarojs/taro'

/**
 * 主包可用的 WebView 导航出口。
 *
 * `pages/webview/index` 整个在分包里，主包页面不能反向依赖分包（微信分包规则下
 * 该导出会解析为 undefined，运行期表现为「链接缺失 无法打开网页」）。主包页面统一
 * 从本文件导入；跳转参数与分包页 `navigateToWebView` 保持逐字一致：
 * `/pages/webview/index?url=<encoded>&title=<encoded>`(title 可选)。
 */
export function navigateToWebView(url: string, title?: string): void {
  const titleParam = title ? `&title=${encodeURIComponent(title)}` : ''
  void navigateTo({ url: `/pages/webview/index?url=${encodeURIComponent(url)}${titleParam}` })
}
