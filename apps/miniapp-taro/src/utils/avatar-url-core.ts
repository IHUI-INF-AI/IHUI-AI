/**
 * 智能体头像 URL 三态判定(纯逻辑、零端侧依赖)。
 *
 * 端侧 `web-asset-url.ts` 的 `resolveAvatarUrl` 在其上注入站点底座补全;
 * node --test 单测直接复用本文件,不复制规则(§22c 单一真相源)。
 *
 * 规则:
 * - 空值/非字符串 → fallback(本地占位图)
 * - http(s):// 开头 → 原样透传
 * - 本端静态前缀(/pkg-ai/ /static/ /images/ /assets/) → 原样透传,不拼站点底座
 * - 其余相对路径(如 /agents/coze/<bot>.webp) → 交 `resolveAsset` 补全;补全落空 → fallback
 *
 * 站点底座拼装不在本文件:端侧 `resolveWebAssetUrl` 复用 shared `joinUrl`,避免第二套 base。
 */

/** 已是本端静态资源的相对前缀(不拼站点底座,原样透传) */
const LOCAL_AVATAR_PREFIXES: readonly string[] = ['/pkg-ai/', '/static/', '/images/', '/assets/']

export interface AvatarResolveOptions {
  /** 空 avatar / 补全落空时的本地占位图 */
  fallback: string
  /** 相对路径补全回调(端侧注入 resolveWebAssetUrl);返回 undefined 视为补全落空 */
  resolveAsset?: (path: string) => string | undefined
}

/**
 * 头像 URL 三态判定。
 *
 * @example
 * resolveAvatarUrlCore('/agents/coze/x.webp', { fallback: '/pkg-ai/assets/default-agent.png', resolveAsset: (p) => `https://aizhs.top${p}` })
 */
export function resolveAvatarUrlCore(avatar: unknown, opts: AvatarResolveOptions): string {
  const { fallback, resolveAsset } = opts
  if (typeof avatar !== 'string' || avatar.trim() === '') return fallback
  const value = avatar.trim()
  if (/^https?:\/\//i.test(value)) return value
  if (LOCAL_AVATAR_PREFIXES.some((p) => value.startsWith(p))) return value
  const resolved = typeof resolveAsset === 'function' ? resolveAsset(value) : value
  return resolved ?? fallback
}
