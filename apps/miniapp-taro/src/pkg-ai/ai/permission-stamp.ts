// D111/G-165①:小程序端消息级权限档盖章值读取(对齐 mobile-rn / extension)。
// 来源:ai-callback 按会话 workspacePath 反查 workspace_permissions 后盖进
// assistant 消息 metadata.permissionMode(不采信客户端自报);只认 string,
// 缺 key = 老消息/未绑定工作区,安静降级 null,绝不编造 default。

export function readStampedPermissionMode(
  messages: ReadonlyArray<{ role: string; metadata?: Record<string, unknown> | null }>,
): string | null {
  for (let i = messages.length - 1; i >= 0; i--) {
    const m = messages[i]
    if (m === undefined || m.role !== 'assistant') continue
    const mode = m.metadata?.permissionMode
    if (typeof mode === 'string') return mode
  }
  return null
}
