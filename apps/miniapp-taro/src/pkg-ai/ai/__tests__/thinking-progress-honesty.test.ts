/**
 * 同型根因 C(假指标):AI 对话「思考进度 %」由随机数递增伪造,
 * 服务端并不提供进度。本夹具钉住:不再有随机进度驱动、不再渲染百分比。
 */
import { readFileSync } from 'node:fs'
import { join } from 'node:path'
import { describe, expect, it } from 'vitest'

const APP_ROOT = join(__dirname, '..', '..', '..', '..')
const read = (p: string) => readFileSync(join(APP_ROOT, p), 'utf8')

const CHAT = read('src/pkg-ai/ai/chat.tsx')
const LIST = read('src/pkg-ai/ai/chat-list-extras.tsx')

/** 判据:正反两面对同一实现 */
export function detectFakeThinkingProgress(chat: string, list: string): string[] {
  const missing: string[] = []
  if (chat.includes('Math.random()')) missing.push('random progress driver')
  if (/thinkingprogress/i.test(chat)) missing.push('thinkingProgress state')
  if (list.includes('thinking-progress-bar')) missing.push('progress bar rendered')
  if (/Math\.floor\(progress\)(?:%|\}%)/.test(list)) missing.push('percentage text rendered')
  if (/progress:\s*number/.test(list)) missing.push('progress prop still required')
  return missing
}

describe('AI 思考进度不得伪造百分比', () => {
  it('正向:无随机驱动、无百分比渲染', () => {
    expect(detectFakeThinkingProgress(CHAT, LIST)).toEqual([])
  })

  it('反向对照:旧实现(随机递增 + 百分比)必须判红', () => {
    const oldChat = 'setThinkingProgress((p) => (p < 99 ? p + Math.random() * 1 : p))'
    const oldList = `
style={{ width: \`\${Math.floor(progress)}%\` }}
<View className="thinking-progress-bar" />
progress: number
`
    expect(detectFakeThinkingProgress(oldChat, oldList)).toEqual([
      'random progress driver',
      'thinkingProgress state',
      'progress bar rendered',
      'percentage text rendered',
      'progress prop still required',
    ])
  })
})
