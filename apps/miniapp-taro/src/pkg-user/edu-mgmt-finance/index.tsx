import { useI18n } from '@/i18n'
import ThemeRoot from '@/components/ThemeRoot'
import { get } from '@/api'
import { ChildRecordsView, type ChildRecordRow } from '../edu-child/records-page'

interface Row {
  id: string
  studentName: string
  className: string
  feeName: string
  amount: number
  paymentDate: string
  status: string
}
export default function Page() {
  const { t } = useI18n()
  const st = (s: string) => {
    const k = `eduFinance.status.${s}`
    const v = t(k)
    return v === k ? s : v
  }
  return (
    <ThemeRoot>
      <ChildRecordsView
        titleKey="eduMgmt.financeTitle"
        columns={[
          { key: 'student', title: t('eduFinance.student') },
          { key: 'className', title: t('eduFinance.className') },
          { key: 'fee', title: t('eduFinance.fee') },
          { key: 'amount', title: t('eduFinance.amount'), tone: 'warn' },
          { key: 'date', title: t('eduFinance.date') },
          { key: 'status', title: t('eduParent.statusTitle'), tone: 'ok' },
        ]}
        load={async (): Promise<ChildRecordRow[]> => {
          const res = await get<{ list: Row[] }>('/edu-ai-management/payment-record')
          return ((res as { list?: Row[] } | null)?.list ?? []).map((r) => ({
            id: r.id,
            cells: {
              student: r.studentName,
              className: r.className,
              fee: r.feeName,
              amount: (r.amount / 100).toFixed(2),
              date: (r.paymentDate ?? '').slice(0, 10),
              status: st(r.status),
            },
          }))
        }}
      />
    </ThemeRoot>
  )
}
