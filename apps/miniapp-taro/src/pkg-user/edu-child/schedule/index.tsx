import { useI18n } from '@/i18n'
import ThemeRoot from '@/components/ThemeRoot'
import { ChildRecordsView, childIdOf, type ChildRecordRow } from '../records-page'

import { get } from '@/api'
const WKD = ['mon', 'tue', 'wed', 'thu', 'fri', 'sat', 'sun'] as const
interface Row {
  id: string
  courseName: string
  teacher: string | null
  weekday: number
  startTime: string
  endTime: string
  classroom: string | null
}
export default function Page() {
  const { t } = useI18n()
  const wk = (n: number) => {
    const k = `eduSchedule.weekday.${WKD[n - 1] ?? ''}`
    const v = t(k)
    return v === k ? String(n) : v
  }
  return (
    <ThemeRoot>
      <ChildRecordsView
        titleKey="eduSchedule.title"
        columns={[
          { key: 'course', title: t('eduSchedule.course') },
          { key: 'weekday', title: t('eduSchedule.weekdayTitle'), tone: 'ok' },
          { key: 'teacher', title: t('eduSchedule.teacher') },
          { key: 'time', title: t('eduSchedule.time') },
          { key: 'classroom', title: t('eduSchedule.classroom') },
        ]}
        load={async (): Promise<ChildRecordRow[]> => {
          const id = childIdOf()
          if (!id) return []
          const res = await get<{ list: Row[] }>(`/edu-ai-management/parent/child/${id}/schedule`)
          return (res?.list ?? []).map((c) => ({
            id: c.id,
            cells: {
              course: c.courseName,
              weekday: wk(c.weekday),
              teacher: c.teacher ?? '—',
              time: `${c.startTime.slice(0, 5)}-${c.endTime.slice(0, 5)}`,
              classroom: c.classroom ?? '—',
            },
          }))
        }}
      />
    </ThemeRoot>
  )
}
