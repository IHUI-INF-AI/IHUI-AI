import { useI18n } from '@/i18n'
import ThemeRoot from '@/components/ThemeRoot'
import { get } from '@/api'
import { ChildRecordsView, childIdOf, type ChildRecordRow } from '../records-page'

interface Row {
  id: string
  title: string
  planType: string
  startDate: string
  endDate: string
  status: string
}
export default function Page() {
  const { t } = useI18n()
  return (
    <ThemeRoot>
      <ChildRecordsView
        titleKey="eduChildStudyPlans.title"
        columns={[
          { key: 'title', title: t('eduChildStudyPlans.title2') },
          { key: 'planType', title: t('eduChildStudyPlans.planType'), tone: 'ok' },
          { key: 'range', title: t('eduChildStudyPlans.range') },
          { key: 'status', title: t('eduParent.statusTitle') },
        ]}
        load={async (): Promise<ChildRecordRow[]> => {
          const id = childIdOf()
          if (!id) return []
          const res = await get<{ list: Row[] }>(
            `/edu-ai-management/parent/children/${id}/study-plans`,
          )
          return ((res as { list?: Row[] } | null)?.list ?? []).map((s) => ({
            id: s.id,
            cells: {
              title: s.title,
              planType: s.planType,
              range: `${(s.startDate ?? '').slice(0, 10)} ~ ${(s.endDate ?? '').slice(0, 10)}`,
              status: s.status,
            },
          }))
        }}
      />
    </ThemeRoot>
  )
}
