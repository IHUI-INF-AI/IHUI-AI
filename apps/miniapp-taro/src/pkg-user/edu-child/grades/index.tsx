import { useI18n } from '@/i18n'
import ThemeRoot from '@/components/ThemeRoot'
import { get } from '@/api'
import { ChildRecordsView, childIdOf, type ChildRecordRow } from '../records-page'

interface Row {
  id: string
  subject: string
  examName: string
  score: number
  totalScore: number
  examDate: string
}
export default function Page() {
  const { t } = useI18n()
  return (
    <ThemeRoot>
      <ChildRecordsView
        titleKey="eduChildGrades.title"
        columns={[
          { key: 'subject', title: t('eduGrades.subject'), tone: 'ok' },
          { key: 'exam', title: t('eduGrades.exam') },
          { key: 'score', title: t('eduGrades.score') },
          { key: 'date', title: t('eduGrades.date') },
        ]}
        load={async (): Promise<ChildRecordRow[]> => {
          const id = childIdOf()
          if (!id) return []
          const res = await get<{ list: Row[] }>(`/edu-ai-management/parent/child/${id}/grades`)
          return ((res as { list?: Row[] } | null)?.list ?? []).map((g) => ({
            id: g.id,
            cells: {
              subject: g.subject,
              exam: g.examName,
              score: `${g.score}/${g.totalScore}`,
              date: (g.examDate ?? '').slice(0, 10),
            },
          }))
        }}
      />
    </ThemeRoot>
  )
}
