import { useI18n } from '@/i18n'
import ThemeRoot from '@/components/ThemeRoot'
import { get } from '@/api'
import { ChildRecordsView, childIdOf, type ChildRecordRow } from '../records-page'

interface Row {
  id: string
  date: string
  mealType: string
  dishName: string
  ingredients: string | null
  nutrition: string | null
}
export default function Page() {
  const { t } = useI18n()
  return (
    <ThemeRoot>
      <ChildRecordsView
        titleKey="eduChildMeals.title"
        columns={[
          { key: 'dish', title: t('eduChildMeals.dish') },
          { key: 'date', title: t('eduChildMeals.date') },
          { key: 'mealType', title: t('eduChildMeals.mealType'), tone: 'ok' },
          { key: 'ingredients', title: t('eduChildMeals.ingredients') },
          { key: 'nutrition', title: t('eduChildMeals.nutrition') },
        ]}
        load={async (): Promise<ChildRecordRow[]> => {
          const id = childIdOf()
          if (!id) return []
          const res = await get<{ list: Row[] }>(`/edu-ai-management/parent/children/${id}/meals`)
          return ((res as { list?: Row[] } | null)?.list ?? []).map((m) => ({
            id: m.id,
            cells: {
              dish: m.dishName,
              date: (m.date ?? '').slice(0, 10),
              mealType: m.mealType,
              ingredients: m.ingredients ?? '—',
              nutrition: m.nutrition ?? '—',
            },
          }))
        }}
      />
    </ThemeRoot>
  )
}
