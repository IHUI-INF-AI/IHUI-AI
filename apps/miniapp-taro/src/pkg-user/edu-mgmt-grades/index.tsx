import { useI18n } from '@/i18n'
import ThemeRoot from '@/components/ThemeRoot'
import { get } from '@/api'
import { ChildRecordsView, type ChildRecordRow } from '../edu-child/records-page'

interface Term {
  id: string
  name: string
  isCurrent: boolean
}
interface Row {
  id: string
  studentId: string
  subject: string
  examName: string
  score: number
  totalScore: number
  examDate: string
}
export default function Page() {
  const { t } = useI18n()
  return (
    <ThemeRoot>
      <ChildRecordsView
        titleKey="eduMgmt.gradesTitle"
        columns={[
          { key: 'student', title: t('eduGrades.student') },
          { key: 'subject', title: t('eduGrades.subject'), tone: 'ok' },
          { key: 'exam', title: t('eduGrades.exam') },
          { key: 'score', title: t('eduGrades.score') },
          { key: 'date', title: t('eduGrades.date') },
        ]}
        load={async (): Promise<ChildRecordRow[]> => {
          const terms = await get<{ list: Term[] }>('/edu-ai-management/term')
          const list0 = terms?.list ?? []
          const current = list0.find((x) => x.isCurrent) ?? list0[0]
          if (!current) return []
          const res = await get<{ list: Row[] }>(
            `/edu-ai-management/exam-score?termId=${current.id}`,
          )
          return ((res as { list?: Row[] } | null)?.list ?? []).map((s) => ({
            id: s.id,
            cells: {
              student: s.studentId,
              subject: s.subject,
              exam: s.examName,
              score: `${s.score}/${s.totalScore}`,
              date: (s.examDate ?? '').slice(0, 10),
            },
          }))
        }}
      />
    </ThemeRoot>
  )
}
