import { useCallback } from 'react'
import Taro from '@tarojs/taro'
import { IcpRecordScreen as SharedIcpRecordScreen } from '@ihui/rn-app/features/icp-record/IcpRecordScreen'
import { useI18n } from '@/i18n'
import { useTheme } from '@/rn-compat/theme'
import ThemeRoot from '@/components/ThemeRoot'

const MIIT_QUERY_URL = 'https://beian.miit.gov.cn/'

export default function IcpRecord() {
  const { t } = useI18n()
  const { resolvedTheme } = useTheme()

  const onCopy = useCallback((text: string) => {
    void Taro.setClipboardData({ data: text })
  }, [])

  const onQuery = useCallback(() => {
    void Taro.navigateTo({ url: `/pages/webview/index?url=${encodeURIComponent(MIIT_QUERY_URL)}` })
  }, [])

  return (
    <ThemeRoot>
      <SharedIcpRecordScreen
        t={t}
        colorScheme={resolvedTheme}
        onBack={() => Taro.navigateBack()}
        onCopy={onCopy}
        onQuery={onQuery}
      />
    </ThemeRoot>
  )
}
