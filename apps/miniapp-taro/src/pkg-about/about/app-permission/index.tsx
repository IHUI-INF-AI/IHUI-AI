import { useCallback, useState } from 'react'
import Taro, { useDidShow } from '@tarojs/taro'
import type { AppPermissionStatus } from '@ihui/types'
import { AppPermissionScreen as SharedAppPermissionScreen } from '@ihui/rn-app/features/app-permission/AppPermissionScreen'
import { useI18n } from '@/i18n'
import { useTheme } from '@/rn-compat/theme'
import ThemeRoot from '@/components/ThemeRoot'

/** 共享清单前五项在小程序侧有对应的授权 scope(其余三项无 scope,保持未知) */
const SCOPES = [
  'scope.writePhotosAlbum',
  'scope.camera',
  'scope.record',
  'scope.userLocation',
  'scope.notification',
]

export default function AppPermission() {
  const { t } = useI18n()
  const { resolvedTheme } = useTheme()
  const [statusByIndex, setStatusByIndex] = useState<Record<number, AppPermissionStatus>>({})

  const load = useCallback(async () => {
    try {
      const res = await Taro.getSetting()
      const auth = (res.authSetting || {}) as Record<string, boolean>
      const next: Record<number, AppPermissionStatus> = {}
      SCOPES.forEach((scope, index) => {
        next[index] =
          auth[scope] === true ? 'granted' : auth[scope] === false ? 'denied' : 'unknown'
      })
      setStatusByIndex(next)
    } catch {
      // 取不到授权状态时不猜:徽标保持缺省(不渲染),不冒绿也不冒红
    }
  }, [])

  useDidShow(() => {
    void load()
  })

  const onOpenSettings = useCallback(() => {
    void Taro.openSetting({ success: () => void load() })
  }, [load])

  return (
    <ThemeRoot>
      <SharedAppPermissionScreen
        t={t}
        colorScheme={resolvedTheme}
        onBack={() => Taro.navigateBack()}
        statusByIndex={statusByIndex}
        onOpenSettings={onOpenSettings}
      />
    </ThemeRoot>
  )
}
