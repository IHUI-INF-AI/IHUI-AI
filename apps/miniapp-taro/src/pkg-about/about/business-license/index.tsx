import { useCallback } from 'react'
import Taro from '@tarojs/taro'
import { BusinessLicenseScreen as SharedBusinessLicenseScreen } from '@ihui/rn-app/features/business-license/BusinessLicenseScreen'
import { useI18n } from '@/i18n'
import { useTheme } from '@/rn-compat/theme'
import ThemeRoot from '@/components/ThemeRoot'
import { aizhsUrl } from '@/constants/icon-urls'

const LICENSE_IMAGE = aizhsUrl('remote-images/yyzz.jpg')

export default function BusinessLicense() {
  const { t } = useI18n()
  const { resolvedTheme } = useTheme()

  const onPreview = useCallback((visible: boolean) => {
    if (!visible) return
    void Taro.previewImage({ urls: [LICENSE_IMAGE], current: LICENSE_IMAGE })
  }, [])

  return (
    <ThemeRoot>
      <SharedBusinessLicenseScreen
        t={t}
        title={t('businessLicense.title')}
        colorScheme={resolvedTheme}
        onBack={() => Taro.navigateBack()}
        imageSource={{ uri: LICENSE_IMAGE }}
        previewVisible={false}
        onPreviewVisibleChange={onPreview}
      />
    </ThemeRoot>
  )
}
