/**
 * G-20261114:chat 同步消息面 → 页面消息行的投影判据(本端薄适配)。
 *
 * 合并算法(同 id 覆盖 / 终态粘性 / 回声不追加 / 零变化 null)的唯一实现在
 * `@ihui/shared/chat` 的 `chat-sync-surface`;本文件只保留本端行类型(role 收窄为
 * ChatSyncRole)与同名导出,给 hook 和既有用例使用,不再维护第二套判据。
 */

import {
  applyChatSyncSurfaceMerge as applySharedChatSyncSurfaceMerge,
  planChatSyncSurfaceMerge as planSharedChatSyncSurfaceMerge,
  type ChatSyncSurfaceMergePlan,
  type ChatSyncSurfaceRow as SharedChatSyncSurfaceRow,
} from '@ihui/shared/chat'
import type { ChatSyncMessageSurface, ChatSyncRole } from '@ihui/types'

export type { ChatSyncSurfaceMergePlan, ChatSyncSurfaceUpdate } from '@ihui/shared/chat'

/** 页面行参与判据的最小面(其它展示字段由调用方保留) */
export interface ChatSyncSurfaceRow extends SharedChatSyncSurfaceRow {
  role: ChatSyncRole
}

/** 计算内核面与页面行的差异。返回 null = 零变化(调用方必须跳过 setState)。 */
export function planChatSyncSurfaceMerge(
  local: readonly ChatSyncSurfaceRow[],
  surface: readonly ChatSyncMessageSurface[],
): ChatSyncSurfaceMergePlan | null {
  return planSharedChatSyncSurfaceMerge(local, surface)
}

/** 把 plan 落到页面行上(不改入参;未变更行保持原引用)。 */
export function applyChatSyncSurfaceMerge(
  local: readonly ChatSyncSurfaceRow[],
  plan: ChatSyncSurfaceMergePlan,
): ChatSyncSurfaceRow[] {
  return applySharedChatSyncSurfaceMerge<ChatSyncSurfaceRow>(local, plan)
}
