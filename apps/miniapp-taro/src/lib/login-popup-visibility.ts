import { useEffect, useState } from 'react'

type Listener = (visible: boolean) => void

let loginPopupVisible = false
const listeners = new Set<Listener>()

/** 登录抽屉开合的端内广播:自定义 tabBar 在页面树之外,只能靠模块级订阅同步。 */
export function setLoginPopupVisible(next: boolean) {
  loginPopupVisible = next
  for (const listener of listeners) listener(next)
}

export function useLoginPopupVisible() {
  const [visible, setVisible] = useState(loginPopupVisible)
  useEffect(() => {
    listeners.add(setVisible)
    setVisible(loginPopupVisible)
    return () => {
      listeners.delete(setVisible)
    }
  }, [])
  return visible
}
