import { View, Text } from '@tarojs/components'
import { useI18n } from '@/i18n'
import LineIcon from '@/components/LineIcon'

/**
 * 注册页协议同意行 — 对齐共享屏 packages/app/src/features/register/RegisterScreen.tsx 的 agreementRow:
 * 勾选框 + 「我已阅读并同意 服务条款 和 隐私政策」+ 未勾选时的行内红字。
 * 拆到同目录子模块只是为了 index.tsx 保持在 250 行以内(门会读同目录 ./ 模块)。
 */
export interface AgreementRowProps {
  agreed: boolean
  showError: boolean
  onToggle: () => void
  onOpenTerms: () => void
  onOpenPrivacy: () => void
}

export default function AgreementRow({
  agreed,
  showError,
  onToggle,
  onOpenTerms,
  onOpenPrivacy,
}: AgreementRowProps) {
  const { t } = useI18n()
  return (
    <View className="reg-agreement">
      <View className="reg-agreement-main">
        <View
          className={`reg-checkbox ${agreed ? 'reg-checkbox-checked' : ''}`}
          hoverClass="opacity-60"
          onClick={onToggle}
        >
          {/* 勾选符原为字符「✓」,按图标纪律改用 LineIcon;居中由父级 .reg-checkbox 的 flex 负责 */}
          {agreed ? <LineIcon name="check" size={22} color="var(--color-card)" /> : null}
        </View>
        <Text className="reg-agreement-text">
          {t('auth.agreePrefix')}
          <Text className="reg-agreement-link" onClick={onOpenTerms}>
            {t('auth.termsOfService')}
          </Text>
          {t('auth.and')}
          <Text className="reg-agreement-link" onClick={onOpenPrivacy}>
            {t('auth.privacyPolicy')}
          </Text>
        </Text>
      </View>
      {showError ? (
        <Text className="block mt-[12rpx] text-[length:26rpx] text-[color:var(--color-danger)]">
          {t('auth.agreeRequired')}
        </Text>
      ) : null}
    </View>
  )
}
