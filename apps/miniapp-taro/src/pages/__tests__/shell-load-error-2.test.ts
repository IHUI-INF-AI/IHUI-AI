/**
 * XUI-066(第 2 组):作品发布/讲师详情 把失败写死成空串传给共享屏 → 屏内无失败出口。
 * 另核 ai-chat-detail:它的加载失败已有独立 ErrorState 出口,不属于静默失败,仅留痕。
 */
import { readFileSync } from 'node:fs'
import { join } from 'node:path'
import { describe, expect, it } from 'vitest'

const APP_ROOT = join(__dirname, '..', '..', '..')
const read = (p: string) => readFileSync(join(APP_ROOT, p), 'utf8')

const PUBLISH = read('src/pkg-ai/aigc/publish.tsx')
const TEACHER = read('src/pkg-learn/teacher/detail.tsx')
const CHAT_DETAIL = read('src/pkg-ai/ai-chat-detail/index.tsx')

describe('XUI-066 组2:壳必须把失败上抛', () => {
  it('作品发布:submitError 状态 + 透传,不再写死空串', () => {
    expect(PUBLISH).not.toContain('error=""')
    expect(PUBLISH).toContain('const [submitError, setSubmitError] = useState(')
    expect(PUBLISH).toContain('setSubmitError(t(\'aigc.publish.publishFail\'))')
    expect(PUBLISH).toContain('error={submitError}')
    expect(PUBLISH.match(/setSubmitError\(/g)?.length).toBe(2)
  })

  it('讲师详情:loadError 状态 + 透传,不再写死空串', () => {
    expect(TEACHER).not.toContain('error=""')
    expect(TEACHER).toContain('const [loadError, setLoadError] = useState(')
    expect(TEACHER).toContain("setLoadError(tt('common.loadFailed'))")
    expect(TEACHER).toContain('error={loadError}')
    expect(TEACHER.match(/setLoadError\(/g)?.length).toBe(2)
  })

  it('ai-chat-detail 不属于静默失败:加载失败有独立 ErrorState 出口', () => {
    expect(CHAT_DETAIL).toContain('<ErrorState')
    expect(CHAT_DETAIL).toContain('setError(true)')
    expect(CHAT_DETAIL).toContain('onRetry={loadData}')
  })
})
