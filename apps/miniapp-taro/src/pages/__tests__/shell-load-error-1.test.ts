/**
 * XUI-066(第 1 组):帮助/分类详情/提现/VIP 权益/学习榜 五个壳把加载失败写死成 error="",
 * 共享屏只能显示空列表,用户看不到失败原因也无法重试。本夹具钉住每屏都有真实 loadError。
 */
import { readFileSync } from 'node:fs'
import { join } from 'node:path'
import { describe, expect, it } from 'vitest'

const APP_ROOT = join(__dirname, '..', '..', '..')
const REPO_ROOT = join(APP_ROOT, '..', '..')
const read = (p: string) => readFileSync(join(APP_ROOT, p), 'utf8')

const SHELLS: Array<[string, string]> = [
  ['help', 'src/pkg-about/about/help.tsx'],
  ['category-detail', 'src/pkg-content/category-detail/index.tsx'],
  ['withdrawal', 'src/pkg-shop/wallet/withdrawal/index.tsx'],
  ['vip-privilege', 'src/pkg-shop/vip/privilege.tsx'],
  ['study-rank', 'src/pages/study/rank.tsx'],
]

const LOCALES = ['zh-CN', 'zh-TW', 'en', 'ja', 'ko'].map((l) => ({
  l,
  json: JSON.parse(
    readFileSync(join(REPO_ROOT, 'packages/i18n/messages/miniapp-taro', `${l}.json`), 'utf8'),
  ) as { common?: Record<string, string> },
}))

describe('XUI-066 组1:壳必须把加载失败上抛', () => {
  for (const [name, path] of SHELLS) {
    it(`${name} 不再写死 error=""`, () => {
      const src = read(path)
      expect(src).not.toContain('error=""')
      expect(src).toContain('error={loadError}')
      expect(src).toContain('const [loadError, setLoadError] = useState(')
      expect(src.match(/setLoadError\(/g)?.length).toBe(2)
    })
  }

  it('复用已有键:common.loadFailed 在 5 个语言包中均存在', () => {
    for (const { l, json } of LOCALES) {
      expect(json.common?.loadFailed, l).toBeTruthy()
    }
  })
})
