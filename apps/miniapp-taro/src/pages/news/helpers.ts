import Taro from '@tarojs/taro'
import { getToken } from '@/utils/auth'

export const PAGE_SIZE = 20

export function authHeader(): Record<string, string> {
  const token = getToken()
  return token ? { Authorization: `Bearer ${token}` } : {}
}

export function goBack() {
  Taro.navigateBack({ fail: () => Taro.reLaunch({ url: '/pages/index/index' }) })
}

/**
 * ISO → `YYYY/MM/DD`。
 * 2026-11-25:原实现只输出 `MM/DD`(`11/25`),与 RN 端(动态/资讯卡片)的 `2026/11/25`
 * 及 web 的 formatDateOnly 都不一样 —— 同一列表三端三种日期形态。统一为带年份形态;
 * 跨年文章不再出现"看不清是哪一年"。
 */
export function fmtDate(iso?: string): string {
  if (!iso) return ''
  const d = new Date(iso)
  if (Number.isNaN(d.getTime())) return ''
  const p = (n: number) => String(n).padStart(2, '0')
  return `${d.getFullYear()}/${p(d.getMonth() + 1)}/${p(d.getDate())}`
}

export function goDetail(id: string) {
  if (!id) return
  void Taro.navigateTo({ url: `/pkg-content/news/detail?id=${encodeURIComponent(id)}` })
}
