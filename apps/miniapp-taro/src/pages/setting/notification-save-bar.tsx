import { useI18n } from '@/i18n'
import { View, Text } from '@tarojs/components'

interface NotificationSaveBarProps {
  saving: boolean
  onSave: () => void
}

/** 保存条:对齐 RN saveBtn(高 50dp→100rpx、圆角 control→sm、品牌实底;保存中禁用) */
export default function NotificationSaveBar({ saving, onSave }: NotificationSaveBarProps) {
  const { t } = useI18n()
  return (
    <View className="mx-[20rpx] mt-[32rpx]">
      <View
        className={`flex h-[100rpx] items-center justify-center rounded-sm ${
          saving ? 'bg-[var(--color-muted)]' : 'bg-cta'
        }`}
        onClick={() => {
          if (!saving) onSave()
        }}
        hoverClass="opacity-60"
      >
        <Text
          className={`text-title font-semibold ${
            saving ? 'text-muted-foreground' : 'text-cta-foreground'
          }`}
        >
          {saving ? t('notificationSettings.saving') : t('notificationSettings.save')}
        </Text>
      </View>
    </View>
  )
}
