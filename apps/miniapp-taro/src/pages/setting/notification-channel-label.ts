import { useI18n } from '@/i18n'

/**
 * 后端 title 承载的是存储键(服务端不拼中文,§19),端侧按渠道映射到共享屏同一套词条。
 * 未知键回落调用方给的原值 —— 既不吞配置项,也不新造文案键。
 */
const CHANNEL_KEYS: Record<string, string> = {
  pushEnabled: 'push',
  messageEnabled: 'message',
  emailEnabled: 'email',
  smsEnabled: 'sms',
  marketingEnabled: 'marketing',
  /* 同一组偏好还有**短名**这一族写入方:设置首页的 `NotificationSection` 按共享屏
     SettingsScreen.tsx:96-98 的 notifRows 键名(push/message/email)PUT
     `/settings/notification`,⇒ GET 回来的行键就是这三个短名。少了下面三行,屏上会
     直接印出存储键原文「push」「message」「email」。 */
  push: 'push',
  message: 'message',
  email: 'email',
}

export function useChannelLabel() {
  const { t } = useI18n()
  /* 逐渠道写字面量而不是拼 key:动态拼键既躲过静态抽取,也让「哪条渠道有词条」在阅读时不可见 */
  const labels: Record<string, () => string> = {
    push: () => t('notificationSettings.push'),
    message: () => t('notificationSettings.message'),
    email: () => t('notificationSettings.email'),
    sms: () => t('notificationSettings.sms'),
    marketing: () => t('notificationSettings.marketing'),
  }
  return (key: string, fallback: string): string => {
    const suffix = CHANNEL_KEYS[key]
    const render = suffix ? labels[suffix] : undefined
    return render ? render() : fallback
  }
}
