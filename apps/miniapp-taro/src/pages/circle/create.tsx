/**
 * 圈子发帖入口(兼容旧路由 /pages/circle/create)。
 *
 * 旧实现把 group 建圈接口 POST /circles 当发帖用(字段 title/content/visibility/topics
 * 与后端 name/description 契约不符,按契约会 400)。现重定向到共享壳
 * pkg-content/circle-post/index,由 RN CirclePostScreen + 共享 CirclePostScreen 承载
 * 选圈 + 标题/正文/图片 + POST /circles/:id/posts,与 web /circles/post 同链路。
 */
import { View } from '@tarojs/components'
import Taro, { useDidShow } from '@tarojs/taro'

export default function CircleCreateLegacyPage() {
  useDidShow(() => {
    const params = Taro.getCurrentInstance().router?.params ?? {}
    const circleId = typeof params.circleId === 'string' ? params.circleId : ''
    const query = circleId ? `?circleId=${encodeURIComponent(circleId)}` : ''
    void Taro.redirectTo({ url: `/pkg-content/circle-post/index${query}` })
  })
  return <View />
}
