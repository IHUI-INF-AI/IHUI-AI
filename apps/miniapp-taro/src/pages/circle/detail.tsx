/**
 * 圈子详情入口(兼容旧路由 /pages/circle/detail?id=)。
 *
 * 旧实现是端内独立帖子详情:取 GET /circles/:id 的 group 数据,却按 title/content/
 * author/createTime 渲染,并带评论/点赞/收藏/关注。现重定向到共享壳
 * pkg-user/circle-detail/index,由 RN CircleDetailScreen + 共享 CircleDetailScreen 承载
 * 圈子头 + GET /circles/:id/posts 帖子列表,与 web /circles/[id] 同业务对象。
 */
import { View } from '@tarojs/components'
import Taro, { useDidShow } from '@tarojs/taro'

export default function CircleDetailLegacyPage() {
  useDidShow(() => {
    const params = Taro.getCurrentInstance().router?.params ?? {}
    const id = typeof params.id === 'string' ? params.id : ''
    if (!id) {
      void Taro.redirectTo({ url: '/pages/circle/index' })
      return
    }
    void Taro.redirectTo({
      url: `/pkg-user/circle-detail/index?id=${encodeURIComponent(id)}`,
    })
  })
  return <View />
}
