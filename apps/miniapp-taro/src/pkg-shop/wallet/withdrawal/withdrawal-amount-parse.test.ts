/**
 * U-7(复核坐实):「全部提现」写入 `1,234.56` 这类千分位展示串,
 * 旧提交逻辑 `Number(amount)` 得 NaN ⇒ 永远提示「请输入有效金额」。
 * 另外提交失败曾被 catch 静默吞掉。
 */
import { readFileSync } from 'node:fs'
import { join } from 'node:path'
import { describe, expect, it } from 'vitest'
import { formatWithdrawAmount, parseWithdrawAmount } from './withdrawal-props'

const APP_ROOT = join(__dirname, '..', '..', '..', '..')
const read = (p: string) => readFileSync(join(APP_ROOT, p), 'utf8')

describe('U-7 提现金额解析', () => {
  it('千分位展示串能被解析回数字', () => {
    expect(parseWithdrawAmount(formatWithdrawAmount(1234.56))).toBe(1234.56)
    expect(parseWithdrawAmount('1,234.56')).toBe(1234.56)
    expect(parseWithdrawAmount(' 1 234.56 ')).toBe(1234.56)
  })

  it('非法输入仍得 NaN,由守卫拦下', () => {
    expect(Number.isNaN(parseWithdrawAmount('abc'))).toBe(true)
    expect(parseWithdrawAmount('')).toBe(0)
    expect(parseWithdrawAmount('0.00')).toBe(0)
  })

  it('壳页用解析函数提交,且失败不再静默', () => {
    const src = read('src/pkg-shop/wallet/withdrawal/index.tsx')
    expect(src).toContain('const amt = parseWithdrawAmount(amount)')
    expect(src).not.toContain('const amt = Number(amount)')
    expect(src).toMatch(/catch\s*\{\s*\/\/ U-7[\s\S]{0,120}onToast\(/)
  })
})
