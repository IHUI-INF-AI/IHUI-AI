/**
 * XUI-073:充值下单失败时 outer catch 跳到「orderNo=」空单号结果页(错误数据)。
 * 同型根因B:/pagesA/top-up/index 已随分包迁移删除(死路由)。
 * 另钉住:新提示文案在 5 个语言包里都有键,不留中文硬编码。
 */
import { readFileSync } from 'node:fs'
import { join } from 'node:path'
import { describe, expect, it } from 'vitest'

const APP_ROOT = join(__dirname, '..', '..', '..', '..')
const REPO_ROOT = join(APP_ROOT, '..', '..')
const read = (abs: string) => readFileSync(abs, 'utf8')

const RECHARGE = read(join(APP_ROOT, 'src/pkg-shop/wallet/recharge/index.tsx'))
const USER_PAGE = read(join(APP_ROOT, 'src/pages/user/index.tsx'))
const LOCALES = ['zh-CN', 'zh-TW', 'en', 'ja', 'ko'].map((l) =>
  read(join(REPO_ROOT, 'packages/i18n/messages/miniapp-taro', `${l}.json`)),
)

export function detectRechargeFailure(src: string): string[] {
  const missing: string[] = []
  if (src.includes('?orderNo=&status=failed')) missing.push('empty orderNo redirect')
  if (!src.includes("tt('wallet.recharge.submitFailed'")) missing.push('inline failure toast')
  return missing
}

describe('XUI-073 充值失败不得跳空单号结果页', () => {
  it('正向:外侧失败就地提示,不再拼 orderNo=', () => {
    expect(detectRechargeFailure(RECHARGE)).toEqual([])
  })

  it('反向对照:旧实现必须判红', () => {
    const oldImpl = `Taro.redirectTo({ url: '/pkg-shop/pay/result/index?orderNo=&status=failed' })`
    expect(detectRechargeFailure(oldImpl)).toEqual(['empty orderNo redirect', 'inline failure toast'])
  })

  it('新提示键在 5 个语言包中均存在', () => {
    for (const src of LOCALES) expect(src).toContain('"submitFailed":')
  })
})

describe('同型B:小程序内不得再出现已删除的 /pagesA/* 路由', () => {
  it('会员卡钱包入口备用跳转指向在册充值页', () => {
    expect(USER_PAGE).not.toContain("'/pagesA/")
    expect(USER_PAGE).toContain("'/pkg-shop/wallet/top-up/index'")
  })
})
