// 批次 5:VIP 详情页对比表的纯映射层(取数/三态留在 compare-table.tsx,渲染在共享 VipMatrix)。

import type { VipCompareRow } from '@ihui/types'

export interface CompareMatrixRow {
  label: string
  values: string[]
}

/** /vip-compare 行 → VipMatrix 的行;feature 机器键经 label 翻译,未登记则原样透出 */
export function mapCompareRows(
  rows: VipCompareRow[],
  label: (feature: string) => string,
): CompareMatrixRow[] {
  return rows.map((row) => ({
    label: label(row.feature),
    values: [row.basic, row.premium, row.enterprise],
  }))
}
