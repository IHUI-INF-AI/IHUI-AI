import {
  resolveVipBenefitEntries,
  resolveVipBenefitHeader,
  resolveVipBenefitPopup,
  type VipBenefitTt,
} from '@ihui/rn-app/features/vip-benefit/view-model'
import type { VipBenefitEntry, VipBenefitHeaderInfo, VipBenefitPopup } from '@ihui/types'

/** 头部等级信息(未开通/已开通/到期提示一次给全) */
export function buildVipBenefitHeader(
  info: { level?: number; name?: string; expireTime?: string } | null,
  tt: VipBenefitTt,
): VipBenefitHeaderInfo {
  return resolveVipBenefitHeader(info, tt)
}

/** 3 个入口卡;弹层状态由壳页注入 */
export function buildVipBenefitEntries(
  tt: VipBenefitTt,
  onPress: (id: VipBenefitEntry['id']) => void,
): VipBenefitEntry[] {
  return resolveVipBenefitEntries(tt).map((entry) => ({
    ...entry,
    onPress: () => onPress(entry.id),
  }))
}

/** 弹层内容(未含回调;回调由壳页注入) */
export type VipBenefitPopupContent =
  | Omit<Extract<VipBenefitPopup, { kind: 'matrix' }>, 'onPrimary' | 'onClose'>
  | Omit<Extract<VipBenefitPopup, { kind: 'benefits' }>, 'onPrimary' | 'onClose'>

/** 入口弹层内容(矩阵/权益清单);回调由壳页注入 */
export function buildVipBenefitPopup(
  kind: VipBenefitEntry['id'],
  tt: VipBenefitTt,
): VipBenefitPopupContent {
  return resolveVipBenefitPopup(kind, tt)
}
