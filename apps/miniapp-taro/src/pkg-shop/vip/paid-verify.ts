/**
 * XUI-039:VIP 支付成功页落本地账本前,必须以服务端订单状态为准。
 *
 * 旧实现挂载即写 `VIP_PAID_STATUS_KEY=true`,任何入口只要带 orderNo/amount 参数
 * 就能伪造"已支付"并重复领权益。这里把"是否已支付"收敛成一次可测的轮询:
 * 仅当服务端返回 `status === 'paid'` 才允许落盘;`pending` 允许短暂重试(支付回调有延迟),
 * 其它终态(失败/关闭/退款)立即返回 false。
 */
export const PAID_STATUS_POLL_ATTEMPTS = 3
export const PAID_STATUS_POLL_DELAY_MS = 500

export type PaidStatusFetcher = (orderNo: string) => Promise<{ status?: string } | undefined>

export interface ConfirmPaidOptions {
  attempts?: number
  delayMs?: number
  sleep?: (ms: number) => Promise<void>
}

const defaultSleep = (ms: number) => new Promise<void>((resolve) => setTimeout(resolve, ms))

export async function confirmVipPaid(
  orderNo: string,
  fetchStatus: PaidStatusFetcher,
  options: ConfirmPaidOptions = {},
): Promise<boolean> {
  if (!orderNo) return false
  const attempts = Math.max(1, options.attempts ?? PAID_STATUS_POLL_ATTEMPTS)
  const delayMs = options.delayMs ?? PAID_STATUS_POLL_DELAY_MS
  const sleep = options.sleep ?? defaultSleep
  for (let i = 0; i < attempts; i += 1) {
    try {
      const res = await fetchStatus(orderNo)
      const status = res?.status
      if (status === 'paid') return true
      // 非 pending 的终态( failed/closed/refunded )不再重试,直接判未支付。
      if (status && status !== 'pending') return false
    } catch {
      // 网络/接口异常按"尚未确认"处理,继续下一次轮询。
    }
    if (i < attempts - 1) await sleep(delayMs)
  }
  return false
}
