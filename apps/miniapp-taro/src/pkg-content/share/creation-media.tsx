import { Audio, Video } from '@tarojs/components'
import type {
  ShareLandingAudio,
  ShareLandingVideo,
} from '@ihui/rn-app/features/share-landing/ShareLandingScreen'

/** 小程序侧视频槽:共享屏只负责布局，播放器原语用 Taro Video */
export function renderShareVideo(video: ShareLandingVideo) {
  return (
    <Video
      className="w-full"
      style={{ height: '420rpx' }}
      src={video.url}
      poster={video.cover}
      controls
      objectFit="contain"
    />
  )
}

/** 小程序侧音频槽:共享屏只负责布局，播放器原语用 Taro Audio */
export function renderShareAudio(audio: ShareLandingAudio) {
  return <Audio src={audio.url} controls name={audio.url} />
}
