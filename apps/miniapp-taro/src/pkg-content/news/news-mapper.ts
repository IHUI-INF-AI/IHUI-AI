// 资讯原始行 → 页面渲染形状的唯一归一处(端内小面,零文案键)。
// 后端 GET /news/articles(/:id)返回 news_articles 原始行(viewCount/publishedAt/
// createdAt/coverImage),详情载荷还多包一层 { article };而 @/api 的 News 声明是
// views/createTime/coverUrl 且当平铺用。原先页面直取 news.views/createTime ⇒ 恒
// undefined,整屏正文块(含 articleDetail.views 卡)永不渲染(假绿)。本模块把两个
// 口径差异(嵌套载荷 + 字段名)一次性归一,阅读数因此真来自端点 viewCount。
import type { News } from '@/api'

/** 后端原始文章行(列表项与 {article} 详情载荷的并集形状;逐键可选,归一前不假定在场) */
interface ArticleRaw {
  id?: string | number
  title?: string
  summary?: string
  content?: string
  views?: number
  viewCount?: number
  createTime?: string
  publishedAt?: string
  createdAt?: string
  coverUrl?: string
  coverImage?: string
}

/** 时间只展示日期档;解析失败原样回吐,不造 Invalid Date 上屏 */
function formatDay(value: string): string {
  const d = new Date(value)
  if (Number.isNaN(d.getTime())) return value
  try {
    return new Intl.DateTimeFormat().format(d)
  } catch {
    return value
  }
}

/** 接受 {article: 原始行} 或平铺原始行,产出页面可直接渲染的 News */
export function normalizeArticle(raw: unknown): News {
  const wrapped: ArticleRaw =
    raw && typeof raw === 'object' && 'article' in raw
      ? (raw as { article?: ArticleRaw }).article || {}
      : (raw as ArticleRaw) || {}
  const timeSrc = wrapped.createTime || wrapped.publishedAt || wrapped.createdAt || ''
  return {
    ...(wrapped as News),
    views: wrapped.views ?? wrapped.viewCount ?? 0,
    createTime: timeSrc ? formatDay(timeSrc) : '',
    coverUrl: wrapped.coverUrl || wrapped.coverImage || '',
  }
}
