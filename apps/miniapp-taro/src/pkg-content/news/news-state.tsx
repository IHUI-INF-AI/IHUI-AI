import { EmptyState, ErrorState } from '@/components/ScreenStates.taro'
import { useTt } from '@/i18n'

/**
 * 资讯详情的加载失败 / 空态 — 对齐共享屏 ArticleDetailScreen:
 * 失败走 ErrorState(带重试,onRetry 回灌页面 load),无数据走 EmptyState。
 * 拆到同目录子模块只是为了 detail.tsx 保持在 250 行以内(门会读同目录 ./ 模块)。
 */
export default function NewsState({ failed, onRetry }: { failed: boolean; onRetry: () => void }) {
  const tt = useTt()
  if (failed) {
    return (
      <ErrorState
        message={tt('articleDetail.loadFailed', '加载文章失败')}
        onRetry={onRetry}
        retryLabel={tt('common.retry', '重试')}
      />
    )
  }
  return <EmptyState title={tt('common.empty', '暂无数据')} />
}
