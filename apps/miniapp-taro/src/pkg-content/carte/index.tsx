import Taro, { useDidShow } from '@tarojs/taro'
import { useI18n, useTt } from '@/i18n'
import ThemeRoot from '@/components/ThemeRoot'
import { useTheme } from '@/rn-compat/theme'
import { showShareMenu } from '@/utils/share'
import { CARTE_I18N_KEYS } from '@ihui/shared/constants'
import { CarteScreen } from '@ihui/rn-app/features/carte/CarteScreen'

/** 图片槽位 → 本端分包静态路径(单一源在 src/pkg-content/assets/,由 config copy.patterns 派生产物) */
const AVATAR_SOURCE = { uri: '/pkg-content/assets/xuancai@2x.png' }
const QRCODE_SOURCE = { uri: '/pkg-content/assets/ewm@2x.png' }

export default function CartePage() {
  const { t } = useI18n()
  const tt = useTt()
  const { resolvedTheme } = useTheme()

  useDidShow(() => {
    Taro.setNavigationBarTitle({ title: tt(CARTE_I18N_KEYS.title, '智汇社社群') })
    showShareMenu()
  })

  return (
    <ThemeRoot>
      <CarteScreen
        t={t}
        avatarSource={AVATAR_SOURCE}
        qrcodeSource={QRCODE_SOURCE}
        onBack={() => {
          void Taro.navigateBack()
        }}
        colorScheme={resolvedTheme}
      />
    </ThemeRoot>
  )
}
