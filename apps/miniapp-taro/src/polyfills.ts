/**
 * 浏览器端最小 process 替身。
 *
 * RN 壳（`@rn-shells/*`，与 RN 原生端同一份源码）里有 `process.env.*` 与
 * `process.nextTick` 的裸读；Taro H5 默认不带 Node polyfill，会让壳页在
 * 模块初始化阶段抛 `ReferenceError: process is not defined` 而白屏。
 *
 * 只补这两个最小面，不引入完整 Node polyfill；小程序/RN 原生端已有运行时，
 * 不会被本文件覆盖（判空后直接返回）。
 */
type ProcessShim = {
  env: Record<string, string | undefined>
  browser: boolean
  platform: string
  argv: string[]
  nextTick: (cb: (...args: unknown[]) => void, ...args: unknown[]) => void
}

const g = globalThis as typeof globalThis & { process?: ProcessShim }

if (typeof g.process === 'undefined') {
  g.process = {
    env: { NODE_ENV: 'production', TARO_ENV: 'h5' },
    browser: true,
    platform: 'browser',
    argv: [],
    nextTick: (cb, ...args) => {
      Promise.resolve().then(() => cb(...args))
    },
  }
}

export {}
