/**
 * `/downloads.json` — 8 端下载元数据的运行期真值出口(2026-11-02 立)。
 *
 * 为什么挂在根路径而不是 `/api/downloads`:nginx 把整段 `location /api/` 转给后端 Fastify,
 * Next 的 App Route 经公网域名到不了(这条实测边界写在 `app/api/desktop-feed/route.ts` 头注),
 * 所以浏览器要读的 Next 数据出口沿用 `desktop-feed.json` / `feed.json` 那一格的先例 —— 根级 `.json`。
 *
 * 消费方:侧边栏「下载」栏(client component)。它此前只能读构建期常量,
 * 于是"发版即更新"对侧栏完全不成立;这条出口把服务端已经能取到的真值交给它。
 *
 * 如实分档:`source` 与 `resolvedAt` 一起给,调用方(和任何读这条出口的尺子)能区分
 * "取到了"「拿不到输入」「该端确实没货」三态,不会把降级读成成功(AGENTS §0.3)。
 */
import { resolveLiveDownloads } from '@/config/downloads-live'

export const revalidate = 600

export async function GET() {
  const downloads = await resolveLiveDownloads()
  return Response.json(
    { generatedAt: new Date().toISOString(), downloads },
    {
      headers: {
        // 浏览器侧 2 分钟:比页面窗口更短,避免"刷新页面还是旧号"这种两端不一致的观感
        'Cache-Control': 'public, max-age=120, s-maxage=600, stale-while-revalidate=1800',
      },
    },
  )
}
