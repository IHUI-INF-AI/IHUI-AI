/**
 * `/health` — Next.js 自身的存活探针出口（2026-11-07 立）。
 *
 * 为什么必须有一条独立出口：`scripts/dev-stack.mjs` 原先拿 `path: '/'` 探 web 腿，
 * 探的是营销首页整页 SSR。实测（2026-11-07 11:0x，并发门禁把 CPU 打满时）首页响应
 * 2.0–24.8s，而 `httpProbe` 的超时是 2500ms ⇒ `isUp` 判假死 ⇒ watcher 每 60–90s
 * 杀一次重拉，实例永远热不起来（活锁）。探活要判的是「服务还活着、路由还能命中」，
 * 不是「首页渲染得多快」——所以给它一条零依赖、不读库、不取快照的静态出口。
 *
 * 为什么挂在根级而不是 `/api/health`：dev 链的 `beforeFiles` 把 `/api/:path*` 整段
 * rewrite 给 8802（`next.config.ts`），公网 nginx 同样把 `/api/` 交给后端 Fastify
 * ⇒ 挂在 `/api/` 下的探针必然打到别人腿上，成为假阳性。
 *
 * 身份标记：应答体带 `service: '@ihui/web'`，`dev-stack` 侧用 `healthExpect` 校验，
 * 免得「占着 8801 的任意 200 桩」被当成 web 本体（同 api 腿 2026-10-31 的教训）。
 *
 * `force-static`：`output: 'export'` 的桌面静态导出档要求 Route Handler 显式声明，
 * 否则构建报错（与 `feed.json` / `downloads.json` 等既有出口同一写法）。
 */
export const dynamic = 'force-static'

export async function GET() {
  return Response.json(
    { status: 'ok', service: '@ihui/web' },
    { headers: { 'Cache-Control': 'no-store' } },
  )
}
