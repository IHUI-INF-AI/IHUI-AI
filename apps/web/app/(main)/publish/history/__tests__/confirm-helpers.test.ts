import { describe, expect, it } from 'vitest'

import { buildConfirmBody, toLocalDateTimeInputValue } from '../confirm-helpers'

describe('buildConfirmBody', () => {
  const now = new Date(2026, 10, 28, 1, 0, 0)

  it('立即确认不传 scheduled_at', () => {
    expect(buildConfirmBody({ mode: 'now', now })).toEqual({ ok: true, body: {} })
  })

  it('未来时间转成 UTC ISO', () => {
    const result = buildConfirmBody({
      mode: 'later',
      localDateTime: '2026-11-29T09:30',
      now,
    })
    expect(result.ok).toBe(true)
    if (!result.ok) return
    const iso = result.body.scheduled_at
    expect(iso).toBeTruthy()
    if (typeof iso !== 'string') return
    expect(new Date(iso).getTime()).toBe(new Date(2026, 10, 29, 9, 30, 0).getTime())
  })

  it('空时间返回 MISSING_TIME', () => {
    expect(buildConfirmBody({ mode: 'later', now, localDateTime: '' })).toEqual({
      ok: false,
      errorCode: 'MISSING_TIME',
    })
  })

  it('非法时间返回 INVALID_TIME', () => {
    expect(
      buildConfirmBody({ mode: 'later', now, localDateTime: '2026-13-45T99:99' }),
    ).toEqual({ ok: false, errorCode: 'INVALID_TIME' })
  })

  it('过去或太近的时间返回 PAST_TIME', () => {
    expect(
      buildConfirmBody({ mode: 'later', now, localDateTime: '2026-11-28T00:59' }),
    ).toEqual({ ok: false, errorCode: 'PAST_TIME' })
  })

  it('datetime-local 值按本地时区格式化', () => {
    expect(toLocalDateTimeInputValue(new Date(2026, 10, 28, 1, 5, 0))).toBe('2026-11-28T01:05')
  })
})
