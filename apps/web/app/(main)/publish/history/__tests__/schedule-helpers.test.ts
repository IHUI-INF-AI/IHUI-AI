import { describe, expect, it } from 'vitest'

import { formatScheduledDistance } from '../schedule-helpers'

const NOW = Date.parse('2026-11-28T00:00:00Z')

function at(ms: number): string {
  return new Date(NOW + ms).toISOString()
}

describe('formatScheduledDistance', () => {
  it('空值和非法时间返回 null,不渲染噪声', () => {
    expect(formatScheduledDistance(null, NOW)).toBeNull()
    expect(formatScheduledDistance(undefined, NOW)).toBeNull()
    expect(formatScheduledDistance('not-a-time', NOW)).toBeNull()
  })

  it('未来超过 1 天显示天/小时', () => {
    expect(formatScheduledDistance(at(26 * 60 * 60_000), NOW)).toBe('还有 1 天 2 小时')
    expect(formatScheduledDistance(at(48 * 60 * 60_000), NOW)).toBe('还有 2 天')
  })

  it('未来 1 小时到 1 天显示小时/分钟', () => {
    expect(formatScheduledDistance(at(2 * 60 * 60_000 + 5 * 60_000), NOW)).toBe('还有 2 小时 5 分')
    expect(formatScheduledDistance(at(3 * 60 * 60_000), NOW)).toBe('还有 3 小时')
  })

  it('未来 1 分钟到 1 小时按分钟向上取整', () => {
    expect(formatScheduledDistance(at(5 * 60_000 + 1), NOW)).toBe('还有 6 分钟')
    expect(formatScheduledDistance(at(30_000), NOW)).toBe('不到 1 分钟')
  })

  it('到点后 5 分钟内是等待调度,不是失败', () => {
    expect(formatScheduledDistance(at(0), NOW)).toBe('刚到点，等待调度')
    expect(formatScheduledDistance(at(-4 * 60_000), NOW)).toBe('刚到点，等待调度')
  })

  it('超过 5 分钟按分钟/小时显示超时', () => {
    expect(formatScheduledDistance(at(-6 * 60_000), NOW)).toBe('已超时 6 分钟')
    expect(formatScheduledDistance(at(-90 * 60_000), NOW)).toBe('已超时 1 小时')
  })
})
