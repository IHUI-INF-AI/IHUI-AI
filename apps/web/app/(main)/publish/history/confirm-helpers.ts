/**
 * 草稿确认时的排期参数：只把“用户选的本地时间”换成后端要的 UTC。
 *
 * 为什么单独抽出来：
 * - `datetime-local` 的值没有时区，直接传给后端会被按服务器时区误读；
 * - “确认后立即进调度”和“确认后定时”是同一个确认端点的两种 body，
 *   用纯函数锁住，避免后续有人把定时分支写成第二个接口。
 */

export type ConfirmMode = 'now' | 'later'

export type ConfirmBodyResult =
  | { ok: true; body: Record<string, string> }
  | { ok: false; errorCode: 'MISSING_TIME' | 'INVALID_TIME' | 'PAST_TIME' }

/** 把 Date 格式化成 `<input type="datetime-local">` 能吃的本地值。 */
export function toLocalDateTimeInputValue(date: Date): string {
  const pad = (n: number) => String(n).padStart(2, '0')
  return `${date.getFullYear()}-${pad(date.getMonth() + 1)}-${pad(date.getDate())}T${pad(date.getHours())}:${pad(date.getMinutes())}`
}

/**
 * 组装 `POST /api/publish/tasks/:id/confirm` 的 body。
 * 立即：空对象；定时：`scheduled_at` 用 ISO UTC，后端只认这个。
 * 至少留 60 秒余量，避免“刚点完就已经过期”被调度器跳过。
 */
export function buildConfirmBody(input: {
  mode: ConfirmMode
  localDateTime?: string
  now?: Date
}): ConfirmBodyResult {
  if (input.mode === 'now') return { ok: true, body: {} }

  const raw = (input.localDateTime ?? '').trim()
  if (!raw) return { ok: false, errorCode: 'MISSING_TIME' }

  const parsed = new Date(raw)
  if (Number.isNaN(parsed.getTime())) return { ok: false, errorCode: 'INVALID_TIME' }

  const now = input.now ?? new Date()
  if (parsed.getTime() <= now.getTime() + 60_000) return { ok: false, errorCode: 'PAST_TIME' }

  return { ok: true, body: { scheduled_at: parsed.toISOString() } }
}
