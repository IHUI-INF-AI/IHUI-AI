/**
 * 排期时间展示纯函数(从 TaskCard 抽出,便于单测)。
 * 只负责「现在离计划时间还有多久」,不做时区转换:
 * scheduledAt 是 ISO8601 UTC,new Date() 会按浏览器本地时区正确比较。
 */

const MINUTE = 60_000
const HOUR = 60 * MINUTE
const DAY = 24 * HOUR

/** 超过这个迟到阈值才叫「超时」,避免轮询 60s 内的正常抖动被误报。 */
const LATE_GRACE_MS = 5 * MINUTE

export function formatScheduledDistance(
  scheduledAt: string | null | undefined,
  nowMs: number = Date.now(),
): string | null {
  if (!scheduledAt) return null
  const target = Date.parse(scheduledAt)
  if (Number.isNaN(target)) return null

  const diff = target - nowMs
  if (diff > DAY) {
    const days = Math.floor(diff / DAY)
    const hours = Math.floor((diff % DAY) / HOUR)
    return hours > 0 ? `还有 ${days} 天 ${hours} 小时` : `还有 ${days} 天`
  }
  if (diff > HOUR) {
    const hours = Math.floor(diff / HOUR)
    const minutes = Math.floor((diff % HOUR) / MINUTE)
    return minutes > 0 ? `还有 ${hours} 小时 ${minutes} 分` : `还有 ${hours} 小时`
  }
  if (diff > MINUTE) {
    return `还有 ${Math.ceil(diff / MINUTE)} 分钟`
  }
  if (diff > 0) {
    return '不到 1 分钟'
  }
  if (diff > -LATE_GRACE_MS) {
    return '刚到点，等待调度'
  }
  const lateMinutes = Math.floor(-diff / MINUTE)
  if (lateMinutes < 60) {
    return `已超时 ${lateMinutes} 分钟`
  }
  const lateHours = Math.floor(lateMinutes / 60)
  return `已超时 ${lateHours} 小时`
}
