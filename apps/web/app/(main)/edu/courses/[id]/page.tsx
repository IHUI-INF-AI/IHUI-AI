import { redirect } from 'next/navigation'

// A 套壳:静态导出要求动态路由提供 generateStaticParams,返回 [] 不预生成,运行时服务端渲染。
// /edu/courses/[id] 已并入 canonical /learn/[id](同 lessons 表同 id 空间,跳转带原 id),保留文件与路由,只做跳转。
// /edu/courses/[id]/learn 播放页不动(共享播放器,已被 /learn/[id] 引用)。
export function generateStaticParams() {
  return [{ id: '1' }]
}

export default async function Page({ params }: { params: Promise<{ id: string }> }) {
  const { id } = await params
  redirect(`/learn/${id}`)
}
