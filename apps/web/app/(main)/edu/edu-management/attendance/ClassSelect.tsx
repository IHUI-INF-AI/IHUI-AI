'use client'

import * as React from 'react'
import { useQuery } from '@tanstack/react-query'
import { useTranslations } from 'next-intl'

import { apiOrThrow } from '@/lib/api'
import { Select, SelectContent, SelectItem, SelectTrigger, SelectValue } from '@ihui/ui-react'

/** 班级选项(GET /api/edu-ai-management/class 的投影,取法与 grades/scheduling 页同源) */
export interface ClassOption {
  id: string
  name: string
}

/** 教师侧班级清单唯一取数出口:所有 classId 选择器共用,禁止手输 UUID */
export function useClasses(): { classes: ClassOption[]; isLoading: boolean } {
  const query = useQuery({
    queryKey: ['edu-ai-management', 'class', 'options'],
    queryFn: () =>
      apiOrThrow<{ list: ClassOption[] }>('/api/edu-ai-management/class?page=1&pageSize=200'),
  })
  const classes = React.useMemo(() => query.data?.list ?? [], [query.data])
  return { classes, isLoading: query.isLoading }
}

/** 班级下拉:清单到货后自动选中首个,免用户空提交(与 grades 页同一口径) */
export function ClassSelect({
  value,
  onChange,
  triggerClassName = 'w-40',
}: {
  value: string
  onChange: (v: string) => void
  triggerClassName?: string
}) {
  const t = useTranslations('eduAttendance')
  const { classes, isLoading } = useClasses()

  React.useEffect(() => {
    if (!value && classes.length > 0) onChange(classes[0]!.id)
  }, [value, classes, onChange])

  return (
    <Select value={value} onValueChange={onChange} disabled={classes.length === 0}>
      <SelectTrigger className={triggerClassName}>
        <SelectValue placeholder={isLoading ? t('loading') : t('selectClass')} />
      </SelectTrigger>
      <SelectContent>
        {classes.map((c) => (
          <SelectItem key={c.id} value={c.id}>
            {c.name}
          </SelectItem>
        ))}
      </SelectContent>
    </Select>
  )
}
