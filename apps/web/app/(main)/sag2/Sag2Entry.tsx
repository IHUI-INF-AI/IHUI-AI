'use client'

import { useSearchParams } from 'next/navigation'

import PageClient from './PageClient'

/**
 * 把 URL 查询参数注入工作台（全局检索 Ctrl/Cmd+K 跳转带来的 q/path）。
 *
 * 为什么参数读取放在客户端组件里：`output: 'export'`（build:static / GitHub Pages）
 * 没有请求期，服务端组件读 `searchParams` 会让 `/sag2` 被判成动态路由、构建直接失败
 * （Next 报 `Route /sag2 with dynamic = "error" couldn't be rendered statically`）。
 * 因此 page.tsx 保持同步静态渲染，参数在这里读，并由 page.tsx 的 <Suspense> 包裹
 * `useSearchParams`（硬要求，同 app/(main)/agreement/page.tsx、app/sso/register/page.tsx）。
 */
export default function Sag2Entry() {
  const searchParams = useSearchParams()
  return (
    <PageClient
      initialQuery={searchParams.get('q') ?? ''}
      initialPath={searchParams.get('path') ?? ''}
    />
  )
}
