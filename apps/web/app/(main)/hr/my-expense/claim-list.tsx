'use client'

/**
 * 我的报销单列表(十一波)。
 * 状态词/类别词走 labels.ts;空态给一句人话,不渲染空表格。
 */
import { useTranslations } from 'next-intl'

import { categoryWord, statusWord, type T } from './labels'

export type Step = {
  approver: string
  action: 'approve' | 'reject'
  at: string
  comment?: string
}

export type Claim = {
  id: string
  title: string
  category: string
  amount: string
  status: string
  currentStep: number
  approverChain: string[]
  currentApproverName?: string | null
  steps?: Step[]
  note?: string | null
}

export function ClaimList({ rows }: { rows: Claim[] }) {
  const t = useTranslations('hrGap') as unknown as T

  if (rows.length === 0) {
    return <p className="mt-2 text-sm text-muted-foreground">{t('expMyEmpty')}</p>
  }

  return (
    <div className="mt-2 space-y-2">
      {rows.map((r) => {
        const reject = (r.steps ?? []).filter((s) => s.action === 'reject').pop()
        const approver = r.currentApproverName ?? (r.approverChain[r.currentStep] ?? '').slice(0, 8)
        return (
          <div key={r.id} className="rounded-lg border border-stroke-subtle p-3">
            <div className="flex flex-wrap items-center gap-2 text-xs">
              <b>{r.title}</b>
              <span className="text-muted-foreground">{categoryWord(t, r.category)}</span>
              <span className="tabular-nums">¥{r.amount}</span>
              <span className="rounded-full border border-stroke-subtle px-2 py-0.5">
                {statusWord(t, r.status)}
              </span>
              {r.status === 'submitted' ? (
                <span className="text-muted-foreground">
                  {t('expCurrentApprover')}:{approver}
                </span>
              ) : null}
            </div>
            {reject?.comment ? (
              <p className="mt-1 text-xs text-destructive">
                {t('expRejectReason')}:{reject.comment}
              </p>
            ) : null}
            {r.note ? <p className="mt-1 text-[11px] text-muted-foreground">{r.note}</p> : null}
          </div>
        )
      })}
    </div>
  )
}
