/**
 * 报销自助页的取词表(十一波)。
 * 只做"协议码 → 界面词"的映射;未命中的码原样回显,不吞数据(§19)。
 */
export type T = (key: string) => string

export const EXPENSE_CATEGORIES = [
  'travel',
  'entertainment',
  'education',
  'welfare',
  'office',
  'other',
] as const

export function categoryWord(t: T, category: string): string {
  switch (category) {
    case 'travel':
      return t('expCatTravel')
    case 'entertainment':
      return t('expCatEntertainment')
    case 'education':
      return t('expCatEducation')
    case 'welfare':
      return t('expCatWelfare')
    case 'office':
      return t('expCatOffice')
    case 'other':
      return t('expCatOther')
    default:
      return category
  }
}

export function statusWord(t: T, status: string): string {
  switch (status) {
    case 'submitted':
      return t('expStatusSubmitted')
    case 'approved':
      return t('expStatusApproved')
    case 'rejected':
      return t('expStatusRejected')
    case 'paid':
      return t('expStatusPaid')
    case 'voided':
      return t('expStatusVoided')
    default:
      return status
  }
}
