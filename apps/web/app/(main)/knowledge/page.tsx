'use client'

import * as React from 'react'
import { Brain } from 'lucide-react'

import { KnowledgeList } from '@/components/knowledge/KnowledgeList'
import { fetchAiServiceJson } from '@/lib/api'

interface MemorySearchResult {
  id: string
  content: string
  score?: number
  metadata?: Record<string, unknown>
}

export default function KnowledgePage() {
  const [items, setItems] = React.useState<MemorySearchResult[]>([])
  const [loading, setLoading] = React.useState(false)
  const [searched, setSearched] = React.useState(false)

  const handleSearch = async (query: string) => {
    setLoading(true)
    setSearched(true)
    try {
      // 2026-09-09 0-5 迁移:该端点注册在 ai-service 8803(next dev rewrites 转发),
      // 响应为非标准格式 {query, results, count}(无 {code,data} 包装),故走
      // fetchAiServiceJson——统一鉴权(cookie/Bearer)/CSRF/设备指纹/30s 超时。
      const res = await fetchAiServiceJson<{ results?: MemorySearchResult[] }>(
        '/api/agents/memory/search',
        {
          method: 'POST',
          body: JSON.stringify({ query, top_k: 10 }),
        },
      )
      setItems(res.success ? (res.data?.results ?? []) : [])
    } catch {
      setItems([])
    } finally {
      setLoading(false)
    }
  }

  return (
    <div className="space-y-4 px-4 py-4">
      <div className="flex items-center gap-2">
        <Brain className="h-5 w-5 text-primary" />
        <h1 className="text-lg font-semibold">知识库</h1>
      </div>
      <p className="text-sm text-muted-foreground">通过语义搜索检索记忆库中的知识内容</p>

      {!searched ? (
        <div className="flex flex-col items-center gap-3 py-16 text-center">
          <Brain className="h-12 w-12 text-muted-foreground/30" />
          <p className="text-sm text-muted-foreground">输入关键词搜索知识库内容</p>
        </div>
      ) : (
        <KnowledgeList items={items} onSearch={handleSearch} loading={loading} />
      )}
    </div>
  )
}
