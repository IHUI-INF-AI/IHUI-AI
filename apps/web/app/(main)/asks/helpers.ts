import { apiFailureToError } from '@ihui/shared/utils'

import { fetchApi } from '@/lib/api'

export const PAGE_SIZE = 20

/**
 * 需求广场(/asks)首屏失败分支必须走 `apiFailureToError`(守门 135 的唯一出口)。
 *
 * 旧写法 `throw new Error(r.error)` 只取 message,把 ApiResult 失败分支自带的
 * `status` / `errorCode` 丢掉 —— 真接口取证(2026-10-08,本机 8802 实测游客/坏令牌
 * GET /api/asks):HTTP 401,响应体 `{"code":401,"message":"Invalid or expired
 * token"}` **不带 errorCode**,能分辨鉴权失败的档只剩 HTTP status。身份一丢,
 * `toUserFriendlyMessage` 判序(errorCode → HTTP status → 文案正则)只能落到参数类
 * 正则 `/invalid|missing|required|must be|expected/i`,用户看到「提交的信息有误,
 * 请检查后重试」—— 把"去登录"引导成"改表单"(PROJECT_PLAN 台账「广场(AI需求广场)
 * 首屏直接进错误态」P1;同型先例 /plaza 已由枚 a5f5227531 收口,RN 侧 PlazaScreen 同)。
 */
export async function api<T>(url: string, options?: RequestInit): Promise<T> {
  const r = await fetchApi<T>(url, options)
  if (!r.success) throw apiFailureToError(r)
  return r.data
}
