import { DOWNLOADS, type DownloadEntry } from '@/lib/downloads'
import type { DownloadPlatform } from '@/config/downloads.config'

/**
 * platform → 下载条目(icon + labelKey)的查表(2026-11-03 收口)。
 *
 * 此前 `DownloadDetailContent.tsx` 里另手抄了 `PLATFORM_ICON` / `PLATFORM_LABEL_KEY` 两张表,
 * 而 `lib/downloads.tsx` 的 `DOWNLOADS` 每条本就带 `icon` + `labelKey` —— 同一件事三份真相,
 * 新增一端要三处同改,漏一处就是静默错配。现在两处的取用都走这张表(源 = `DOWNLOADS`)。
 *
 * 键集由 `DOWNLOAD_PLATFORMS` 钉住、运行时由测试逐端断言有条目
 * (见 `apps/web/src/tests/download-platform-not-launched.test.tsx`),
 * 因此 `lib/downloads.tsx`(端外共享文件)无需为这一格再开出口。
 */
export const DOWNLOAD_ENTRY_BY_PLATFORM: Record<DownloadPlatform, DownloadEntry> =
  Object.fromEntries(DOWNLOADS.map((entry) => [entry.platform, entry])) as Record<
    DownloadPlatform,
    DownloadEntry
  >

/** 清单里确有登记条目的端(顺序沿用入参;取不到条目的端不会进列表) */
export function platformEntriesOf(platforms: readonly DownloadPlatform[]): DownloadEntry[] {
  return platforms
    .map((platform) => DOWNLOAD_ENTRY_BY_PLATFORM[platform])
    .filter((entry) => Boolean(entry))
}
