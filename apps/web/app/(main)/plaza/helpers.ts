import { apiFailureToError } from '@ihui/shared/utils'

import { fetchApi } from '@/lib/api'

export const PREVIEW_SIZE = 6

/**
 * 广场首屏失败分支必须走 `apiFailureToError`(守门 135 的唯一出口)。
 *
 * 旧写法 `throw new Error(r.error)` 只取 message,把 ApiResult 失败分支自带的
 * `status` / `errorCode` 丢掉 —— 而 `toUserFriendlyMessage` 的判序是
 * errorCode → HTTP status → 文案正则,前两档一丢,401 的 "Invalid or expired token"
 * 只能落到参数类正则 `/invalid|missing|required/`,用户看到「提交的信息有误,请检查后重试」
 * (即 PROJECT_PLAN 实拍「广场 tab 一进即弹错误框」那一型)。RN 侧同一处已按该出口收口
 * (`apps/mobile-rn/src/screens/PlazaScreen.tsx`),web 侧此前仍是被丢身份的形态。
 */
export async function api<T>(url: string): Promise<T> {
  const r = await fetchApi<T>(url)
  if (!r.success) throw apiFailureToError(r)
  return r.data
}
