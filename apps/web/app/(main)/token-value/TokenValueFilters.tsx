'use client'

import { useMemo } from 'react'
import { CategoryBar, Input, type CategoryBarItem } from '@ihui/ui-react'
import { RANGES, type Range } from './helpers'

interface Props {
  range: Range
  customFrom: string
  customTo: string
  t: (k: string) => string
  onRange: (r: Range) => void
  onCustomFrom: (v: string) => void
  onCustomTo: (v: string) => void
}

export function TokenValueFilters({
  range,
  customFrom,
  customTo,
  t,
  onRange,
  onCustomFrom,
  onCustomTo,
}: Props) {
  const items = useMemo<CategoryBarItem[]>(
    () => RANGES.map((opt) => ({ id: opt.key, label: t(opt.labelKey) })),
    [t],
  )
  return (
    <div className="flex flex-wrap items-center gap-2">
      <CategoryBar
        items={items}
        value={range}
        onChange={(id) => {
          const matched = RANGES.find((opt) => opt.key === id)
          if (matched) onRange(matched.key)
        }}
      />
      {range === 'custom' && (
        <div className="flex items-center gap-2">
          <Input
            type="date"
            value={customFrom}
            onChange={(e) => onCustomFrom(e.target.value)}
            className="h-8 w-[140px]"
          />
          <span className="text-xs text-muted-foreground">~</span>
          <Input
            type="date"
            value={customTo}
            onChange={(e) => onCustomTo(e.target.value)}
            className="h-8 w-[140px]"
          />
        </div>
      )}
    </div>
  )
}
