'use client'

/**
 * 统一购买中枢(2026-09-16 立)。
 *
 * 解决的问题:此前"买 API"的入口分散在四处 ——
 * /wallet/recharge(充值)、/developer/relay/subscriptions(订阅)、
 * /models/redeem(兑换码)、/developer/relay/keys(给 Key 充值),
 * 用户找不到单一购买入口。本页把"订阅"与"充值"两条主链路收拢到一页双 Tab,
 * 底层支付与记账链路完全复用既有实现(零改动,零风险)。
 */
import * as React from 'react'
import { useTranslations } from 'next-intl'

import { Tabs, TabsContent, TabsList, TabsTrigger } from '@ihui/ui-react'
import { BackButton } from '@/components/common'
import { SubscribeTab } from './SubscribeTab'
import { TopupTab } from './TopupTab'

type PurchaseTab = 'subscribe' | 'topup'

export default function PurchasePageClient() {
  const t = useTranslations('purchase')
  const [tab, setTab] = React.useState<PurchaseTab>('subscribe')

  return (
    <div className="mx-auto w-full max-w-3xl space-y-4 px-4 py-4">
      <BackButton />
      <div>
        <h1 className="text-2xl font-bold tracking-tight">{t('title')}</h1>
        <p className="mt-1 text-sm text-muted-foreground">{t('subtitle')}</p>
      </div>

      <Tabs value={tab} onValueChange={(v) => setTab(v === 'topup' ? 'topup' : 'subscribe')}>
        <TabsList>
          <TabsTrigger value="subscribe">{t('tabSubscribe')}</TabsTrigger>
          <TabsTrigger value="topup">{t('tabTopup')}</TabsTrigger>
        </TabsList>
        <TabsContent value="subscribe">
          <SubscribeTab />
        </TabsContent>
        <TabsContent value="topup">
          <TopupTab />
        </TabsContent>
      </Tabs>
    </div>
  )
}
