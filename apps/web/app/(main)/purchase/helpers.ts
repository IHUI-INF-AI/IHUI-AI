/**
 * 统一购买页(充值 + 订阅)共享格式化工具(2026-09-16 立)。
 *
 * 金额单位统一为"分"(与 plans.price / orders.amount 一致),
 * token 一律用紧凑格式(1.2M / 500K),避免长数字撑破卡片。
 */

/** 分 → 人民币显示(整数元;不足 1 元保留 2 位小数)。 */
export function formatCents(cents: number): string {
  const yuan = Number(cents ?? 0) / 100
  const digits = Number.isInteger(yuan) ? 0 : 2
  return `¥${yuan.toFixed(digits)}`
}

/** token 紧凑显示;-1 = 不限,0 = 未配置(显示为 "-")。 */
export function formatTokens(n: number): string {
  const v = Number(n ?? 0)
  if (v === -1) return '∞'
  if (v <= 0) return '-'
  if (v >= 1_000_000) return `${(v / 1_000_000).toFixed(v % 1_000_000 === 0 ? 0 : 1)}M`
  if (v >= 1_000) return `${(v / 1_000).toFixed(v % 1_000 === 0 ? 0 : 1)}K`
  return String(v)
}

/** 秒 → 倒计时显示(如 3小时20分 / 12分30秒)。 */
export function formatCountdown(seconds: number): string {
  const s = Math.max(0, Math.floor(seconds))
  const h = Math.floor(s / 3600)
  const m = Math.floor((s % 3600) / 60)
  const sec = s % 60
  if (h > 0) return `${h}小时${m}分`
  if (m > 0) return `${m}分${sec}秒`
  return `${sec}秒`
}

/** ISO 时间 → 本地日期显示(YYYY-MM-DD)。 */
export function formatDate(iso: string | null | undefined): string {
  if (!iso) return '-'
  const d = new Date(iso)
  if (Number.isNaN(d.getTime())) return '-'
  return new Intl.DateTimeFormat('zh-CN', {
    year: 'numeric',
    month: '2-digit',
    day: '2-digit',
  }).format(d)
}

/** 窗口已用比例(0-100);不限或未配置返回 0。 */
export function windowPercent(used: number, limit: number): number {
  if (!Number.isFinite(limit) || limit <= 0) return 0
  return Math.min(100, Math.max(0, Math.round((used / limit) * 100)))
}
