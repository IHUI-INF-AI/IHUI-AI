'use client'

import * as React from 'react'
import Link from 'next/link'
import { useQuery } from '@tanstack/react-query'
import { useTranslations, useLocale } from 'next-intl'
import { ArrowRight } from 'lucide-react'

import { fetchApi } from '@/lib/api'
import { buildQs, type PageData } from '@/lib/edu'
import { BackButton } from '@/components/common'

import { InvoicesTab } from '../settings/billing/InvoicesTab'
import { PAGE_SIZE } from '../settings/billing/helpers'
import type { InvoiceApplication } from '../settings/billing/types'

export default function InvoicesPage() {
  const t = useTranslations('settings')
  const ti = useTranslations('admin.edu.finance.invoices')
  const locale = useLocale()
  const [page, setPage] = React.useState(1)

  const currencyFmt = React.useMemo(
    () => new Intl.NumberFormat(locale, { style: 'currency', currency: 'CNY' }),
    [locale],
  )
  const dateFmt = React.useMemo(
    () =>
      new Intl.DateTimeFormat(locale, {
        year: 'numeric',
        month: '2-digit',
        day: '2-digit',
        hour: '2-digit',
        minute: '2-digit',
      }),
    [locale],
  )

  const query = useQuery({
    queryKey: ['invoices', 'applications', page],
    queryFn: async () => {
      const res = await fetchApi<PageData<InvoiceApplication>>(
        `/invoices/applications${buildQs({ page, pageSize: PAGE_SIZE })}`,
      )
      if (!res.success) throw new Error(res.error)
      return res.data
    },
  })

  return (
    <div className="mx-auto w-full max-w-3xl space-y-4 px-4 py-4">
      <BackButton fallbackHref="/settings/billing" />
      <header className="space-y-1">
        <h1 className="text-xl font-semibold">{ti('title')}</h1>
        <p className="text-sm text-muted-foreground">{ti('subtitle')}</p>
      </header>
      <InvoicesTab
        t={t}
        list={query.data?.list ?? []}
        isLoading={query.isLoading}
        error={query.error as Error | null}
        page={page}
        total={query.data?.total ?? 0}
        pageSize={PAGE_SIZE}
        currencyFmt={currencyFmt}
        dateFmt={dateFmt}
        onPageChange={setPage}
      />
      <div className="flex items-center gap-1 text-sm text-muted-foreground">
        <Link
          href="/settings/billing"
          className="inline-flex items-center gap-1 text-primary hover:underline"
        >
          {t('billingTitle')}
          <ArrowRight className="h-4 w-4" aria-hidden="true" />
        </Link>
      </div>
    </div>
  )
}
