'use client'

import type { RefObject } from 'react'

interface PreviewCanvasProps {
  iframeRef: RefObject<HTMLIFrameElement | null>
  srcDoc: string
  currentWidth: number
  currentHeight?: number
  showFrame: boolean
  deviceRadius: number
}

export function PreviewCanvas({
  iframeRef,
  srcDoc,
  currentWidth,
  currentHeight,
  showFrame,
  deviceRadius,
}: PreviewCanvasProps) {
  // 非桌面设备(手机/平板)使用固定高度匹配设备视口;桌面/自定义保留 flex 撑满。
  const hasFixedHeight = currentHeight !== null
  return (
    <section
      style={{
        flex: 1,
        display: 'flex',
        flexDirection: 'column',
        overflow: 'auto',
        padding: 8,
      }}
    >
      <div
        style={{
          width: '100%',
          maxWidth: currentWidth,
          height: hasFixedHeight ? currentHeight : undefined,
          margin: '0 auto',
          flex: hasFixedHeight ? '0 0 auto' : '1 1 auto',
          minHeight: 0,
          border: '1px solid var(--border)',
          borderRadius: showFrame ? deviceRadius : 8,
          overflow: 'hidden',
          background: 'var(--card)',
          display: 'flex',
          flexDirection: 'column',
          boxShadow: showFrame ? '0 2px 8px rgba(0,0,0,0.06)' : 'none',
          transition: 'max-width 0.2s ease, height 0.2s ease, border-radius 0.2s ease',
        }}
      >
        <iframe
          ref={iframeRef}
          srcDoc={srcDoc}
          title="design-preview"
          // srcDoc 内容由用户/AI 生成。不给 sandbox 时它继承父窗口同源 ⇒ 内嵌脚本可读
          // window.parent.document、localStorage、会话 cookie,一次 XSS 即换登录态。
          // allow-scripts 足够:画布内的注入脚本只用 postMessage 与自身 document,
          // 父侧也只调 contentWindow.postMessage(不读 contentDocument)。
          sandbox="allow-scripts"
          style={{
            flex: 1,
            border: 'none',
            background: 'var(--card)',
            width: '100%',
            height: '100%',
          }}
        />
      </div>
    </section>
  )
}
