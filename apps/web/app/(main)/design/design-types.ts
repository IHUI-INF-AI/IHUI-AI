type CssGroupId = 'layout' | 'boxModel' | 'typography' | 'background' | 'effects' | 'responsive'
type CssPropType = 'text' | 'number' | 'select' | 'color'

interface CssProperty {
  key: string
  label: string
  type: CssPropType
  unit?: string
  options?: string[]
  group: CssGroupId
}

interface CssGroup {
  id: CssGroupId
  label: string
  props: CssProperty[]
}

interface SelectedElement {
  elementId: string
  tagName: string
  text: string
  style: Record<string, string>
}

/** 组件树节点:由 DOMParser 解析 HTML 字符串生成。 */
interface TreeNode {
  tagName: string
  id: string
  className: string
  /** 同 tagName 在父级 children 中的索引,用于点击时定位 iframe 元素。 */
  index: number
  children: TreeNode[]
}

type RightPanelTab = 'css' | 'comments'

type TranslationFn = (key: string, params?: Record<string, string | number>) => string

export type {
  CssGroupId,
  CssPropType,
  CssProperty,
  CssGroup,
  SelectedElement,
  TreeNode,
  RightPanelTab,
  TranslationFn,
}
