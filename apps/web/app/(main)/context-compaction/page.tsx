'use client'

import * as React from 'react'
import { useSearchParams } from 'next/navigation'
import { useTranslations } from 'next-intl'

import ContextCompactionPanel from '@/components/context-compaction/ContextCompactionPanel'

/**
 * 上下文压缩感知页面(P0-6,2026-09-03 立)。
 *
 * 独立路由 /context-compaction:让用户感知并回看 AGENT 会话被 LLM 语义压缩的历史。
 * 通过查询参数 ?session_id=... 指定目标会话,渲染 ContextCompactionPanel。
 * 侧边栏不新增导航(避免与既有 /context 归属冲突),本页面可由 /context/compression
 * 等既有入口深链或直接带 session_id 访问。
 */
export default function ContextCompactionPage() {
  const t = useTranslations('contextCompaction')
  const searchParams = useSearchParams()
  const sessionId = searchParams.get('session_id') ?? ''

  return (
    <div style={{ margin: '0 auto', maxWidth: 720, padding: 16 }}>
      <h1 style={{ fontSize: 18, fontWeight: 700 }}>{t('title')}</h1>
      <p
        style={{
          marginTop: 4,
          marginBottom: 12,
          fontSize: 13,
          color: '#666',
        }}
      >
        {t('desc')}
      </p>
      {!sessionId && (
        <p style={{ marginBottom: 12, fontSize: 13, color: '#999' }}>{t('noSession')}</p>
      )}
      <ContextCompactionPanel sessionId={sessionId} />
    </div>
  )
}
