/**
 * 模型运行遥测的展示口径(2026-11-26 立):
 * 监测条与表格行共用同一套数字/时间格式,避免两处对 0、极小速率、P95 舍入各写一遍。
 * 速率不做"固定两位"——低流量下 1 次/5 分钟 = 0.003,固定两位会被误读成 0;
 * 也保留高流量的可读性(≥100 只留 1 位小数)。
 */

export function formatRate(value: number, locale: string): string {
  if (!Number.isFinite(value) || value <= 0) return '0'
  const digits = value >= 100 ? 1 : value >= 1 ? 2 : 3
  return new Intl.NumberFormat(locale, { maximumFractionDigits: digits }).format(value)
}

export function formatPercent(rate: number | null, locale: string): string {
  if (rate === null) return '—'
  return `${new Intl.NumberFormat(locale, { maximumFractionDigits: 1 }).format(rate * 100)}%`
}

export function formatLatency(ms: number | null, locale: string): string | null {
  if (ms === null) return null
  if (ms < 1000) return `${Math.round(ms)}ms`
  return `${new Intl.NumberFormat(locale, { maximumFractionDigits: 2 }).format(ms / 1000)}s`
}

export function formatClock(value: number | string, locale: string): string {
  return new Intl.DateTimeFormat(locale, {
    hour: '2-digit',
    minute: '2-digit',
    hour12: false,
  }).format(new Date(value))
}

export function formatTime(value: number | string, locale: string): string {
  return new Intl.DateTimeFormat(locale, {
    hour: '2-digit',
    minute: '2-digit',
    second: '2-digit',
    hour12: false,
  }).format(new Date(value))
}

/** 7d 窗口的调用明细跨天,只给时分秒会看不出是哪一天。 */
export function formatDateTime(value: number | string, locale: string): string {
  return new Intl.DateTimeFormat(locale, {
    month: '2-digit',
    day: '2-digit',
    hour: '2-digit',
    minute: '2-digit',
    second: '2-digit',
    hour12: false,
  }).format(new Date(value))
}

export function formatSeriesTick(
  value: number,
  window: '1h' | '24h' | '7d',
  locale: string,
): string {
  if (window === '7d') {
    return new Intl.DateTimeFormat(locale, {
      month: '2-digit',
      day: '2-digit',
      hour: '2-digit',
      hour12: false,
    }).format(new Date(value))
  }
  return formatClock(value, locale)
}

export function formatCost(cents: number | null | undefined, locale: string): string {
  if (cents === null || cents === undefined || !Number.isFinite(cents)) return '—'
  // cost_cents 是"分"且可为小数(上游按厘/更细粒度计价);固定两位会把
  // 1 次调用的 ¥0.002 永久显示成 ¥0.00,管理员误以为免费。小额保留 3-4 位。
  const value = cents / 100
  return new Intl.NumberFormat(locale, {
    style: 'currency',
    currency: 'CNY',
    minimumFractionDigits: 2,
    maximumFractionDigits: Math.abs(value) > 0 && Math.abs(value) < 0.01 ? 4 : 2,
  }).format(value)
}
