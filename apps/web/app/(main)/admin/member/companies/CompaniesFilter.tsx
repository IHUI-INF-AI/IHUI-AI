'use client'

import { Plus } from 'lucide-react'
import { useTranslations } from 'next-intl'
import {
  Button,
  SearchInput,
  Select,
  SelectContent,
  SelectItem,
  SelectTrigger,
  SelectValue,
} from '@ihui/ui-react'

interface CompaniesFilterProps {
  search: string
  status: string
  onSearchChange: (v: string) => void
  onStatusChange: (v: string) => void
  onCreate: () => void
}

export function CompaniesFilter({
  search,
  status,
  onSearchChange,
  onStatusChange,
  onCreate,
}: CompaniesFilterProps) {
  const t = useTranslations('admin.member')
  return (
    <div className="flex flex-wrap items-center gap-2">
      <SearchInput
        value={search}
        onChange={(e) => onSearchChange(e.target.value)}
        placeholder={t('namePlaceholder')}
        aria-label={t('colName')}
        size="lg"
        wrapperClassName="w-full max-w-xs"
      />
      <Select value={status} onValueChange={onStatusChange}>
        <SelectTrigger className="h-9 w-[140px]" id="company-status-filter">
          <SelectValue />
        </SelectTrigger>
        <SelectContent>
          <SelectItem value="all">{t('colStatus')}</SelectItem>
          <SelectItem value="1">{t('enabled')}</SelectItem>
          <SelectItem value="0">{t('disabled')}</SelectItem>
        </SelectContent>
      </Select>
      <Button onClick={onCreate} size="sm" className="ml-auto">
        <Plus className="h-4 w-4" />
        {t('create')}
      </Button>
    </div>
  )
}
