export function Empty({ text }: { text: string }) {
  return <p className="py-3 text-center text-xs text-muted-foreground">{text}</p>
}

/** 状态徽章:ok 绿 / warn 黄 / danger 红 / 其余灰(词表与页内 hrTone 同一真相源) */
export function Badge({ status }: { status: string }) {
  const tone =
    hrTone(status) === 'ok'
      ? 'bg-success/10 text-success'
      : hrTone(status) === 'danger'
        ? 'bg-destructive/10 text-destructive'
        : hrTone(status) === 'warn'
          ? 'bg-warning/10 text-warning'
          : 'bg-muted text-muted-foreground'
  return (
    <span className={`inline-flex rounded-md px-1.5 py-0.5 text-[11px] font-medium ${tone}`}>
      {status}
    </span>
  )
}

