'use client'

import * as React from 'react'
import { useMutation } from '@tanstack/react-query'
import { Loader2, Sparkles } from 'lucide-react'
import { Button, Card, CardContent, CardDescription, CardHeader, CardTitle } from '@ihui/ui-react'
import { Alert } from '@/components/feedback'
import type { WechatAutoReplyRuleView } from '@ihui/types'
import { wechatHubApi } from './wechat-hub-api'

export default function AutoReplyPreview({
  accountId,
  rule,
}: {
  accountId: string
  rule: WechatAutoReplyRuleView
}) {
  const [text, setText] = React.useState('你好，想咨询一下。')
  const previewMutation = useMutation({
    mutationFn: () => wechatHubApi.previewAutoReplyRule(accountId, rule.id, { text: text.trim() }),
  })

  return (
    <Card>
      <CardHeader className="pb-2">
        <CardTitle className="text-body">AI 回复预览</CardTitle>
        <CardDescription>
          只生成不发送，不占规则冷却；默认取该账号最近活跃会话作为上下文。
        </CardDescription>
      </CardHeader>
      <CardContent className="space-y-3">
        <textarea
          value={text}
          onChange={(event) => {
            setText(event.target.value)
            previewMutation.reset()
          }}
          rows={3}
          maxLength={2_000}
          className="w-full rounded-sm border border-stroke-field bg-transparent px-3 py-2 text-sm outline-none focus:border-stroke-focus"
          placeholder="输入一条客户消息，看看 AI 会怎么回"
        />
        <div className="flex items-center gap-2">
          <Button
            size="sm"
            onClick={() => previewMutation.mutate()}
            disabled={previewMutation.isPending || !text.trim()}
          >
            {previewMutation.isPending ? (
              <Loader2 className="mr-1 h-3.5 w-3.5 animate-spin" />
            ) : (
              <Sparkles className="mr-1 h-3.5 w-3.5" />
            )}
            生成预览
          </Button>
          <span className="text-xs text-muted-foreground">规则：{rule.name}</span>
        </div>
        {previewMutation.isError ? (
          <Alert
            variant="danger"
            title="生成失败"
            description={
              previewMutation.error instanceof Error ? previewMutation.error.message : '未知错误'
            }
          />
        ) : null}
        {previewMutation.data ? (
          <div className="whitespace-pre-wrap break-words rounded-md border border-stroke-field bg-muted/40 p-3 text-sm">
            {previewMutation.data.replyText || '(模型返回空文本)'}
          </div>
        ) : null}
      </CardContent>
    </Card>
  )
}
