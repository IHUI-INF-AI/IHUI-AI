'use client'

import * as React from 'react'
import { useMutation } from '@tanstack/react-query'
import { Download, Loader2 } from 'lucide-react'
import { Button } from '@ihui/ui-react'
import { wechatHubApi } from './wechat-hub-api'

function downloadText(filename: string, content: string, mimeType: string): void {
  const blob = new Blob([content], { type: mimeType })
  const url = URL.createObjectURL(blob)
  const anchor = document.createElement('a')
  anchor.href = url
  anchor.download = filename
  document.body.appendChild(anchor)
  anchor.click()
  anchor.remove()
  setTimeout(() => URL.revokeObjectURL(url), 0)
}

export default function ConversationExportButton({
  accountId,
  conversationId,
}: {
  accountId: string
  conversationId: string | null
}) {
  const [notice, setNotice] = React.useState<string | null>(null)
  const [format, setFormat] = React.useState<'jsonl' | 'csv'>('jsonl')
  const exportMutation = useMutation({
    mutationFn: (selectedFormat: 'jsonl' | 'csv') =>
      wechatHubApi.exportMessages(accountId, {
        format: selectedFormat,
        conversationId: conversationId ?? undefined,
        limit: 5_000,
      }),
    onSuccess: (result) => {
      downloadText(result.filename, result.content, result.mimeType)
      setNotice(`已导出 ${result.count} 条`)
      setTimeout(() => setNotice(null), 4_000)
    },
    onError: (error) => {
      setNotice(error instanceof Error ? error.message : '导出失败')
      setTimeout(() => setNotice(null), 4_000)
    },
  })

  return (
    <div className="flex items-center gap-2">
      <select
        value={format}
        onChange={(event) => setFormat(event.target.value === 'csv' ? 'csv' : 'jsonl')}
        aria-label="导出格式"
        className="h-8 rounded-sm border border-stroke-field bg-transparent px-2 text-xs outline-none focus:border-stroke-focus"
      >
        <option value="jsonl">JSONL</option>
        <option value="csv">CSV</option>
      </select>
      <Button
        size="sm"
        variant="outline"
        onClick={() => exportMutation.mutate(format)}
        disabled={exportMutation.isPending}
      >
        {exportMutation.isPending ? (
          <Loader2 className="mr-1 h-3.5 w-3.5 animate-spin" />
        ) : (
          <Download className="mr-1 h-3.5 w-3.5" />
        )}
        导出
      </Button>
      {notice ? <span className="text-xs text-muted-foreground">{notice}</span> : null}
    </div>
  )
}
