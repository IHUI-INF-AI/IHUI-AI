/**
 * 群与朋友圈 Tab 组合：群动作卡 + 朋友圈卡。
 */

'use client'

import type { WechatBackend } from '@ihui/types'
import { Alert } from '@/components/feedback'
import GroupActionCard from './GroupActionCard'
import MomentCard from './MomentCard'

export default function GroupOpsPanel({
  accountId,
  backend,
  readOnly = false,
}: {
  accountId: string
  backend: WechatBackend
  readOnly?: boolean
}) {
  if (backend === 'ilink') {
    return (
      <Alert
        variant="info"
        title="iLink 官方通道仅支持私聊"
        description="群创建/邀请/踢人/改名/公告与朋友圈需要桥接账号（WeChatFerry 或 mock 桥）。请切换到桥接账号后再使用本页。"
      />
    )
  }
  if (readOnly) {
    return (
      <div className="space-y-3">
        <Alert
          variant="info"
          title="群管理动作不可用"
          description="截图 OCR 只读接入不能建群/邀请/踢人/改名/公告，也不能发布朋友圈；下方只展示已归档的朋友圈和真实本地媒体。"
        />
        <MomentCard accountId={accountId} readOnly />
      </div>
    )
  }
  return (
    <div className="space-y-3">
      <GroupActionCard accountId={accountId} />
      <MomentCard accountId={accountId} />
    </div>
  )
}
