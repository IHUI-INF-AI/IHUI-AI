/**
 * 分析结果的条形图数据（纯函数，不碰 DOM）。
 *
 * 为什么单独抽出来：分析面板此前只有文字与色块 chip，同一份「谁说得最多 / 哪些词出现最多」
 * 读起来要靠眼睛数。这里把排序与取比例做成可测的纯计算，视图层只负责画。
 *
 * 口径：
 * - 只画有量的（value <= 0 或非有限数直接丢），0 长度条只占位不提供信息；
 * - 排序按 value 降序，值相同按 label 升序，保证同一份结果多次渲染顺序不变；
 * - ratio 以本组最大值为基准（不是总和），一眼看出相对差距，而不是被长尾摊平；
 * - limit 只截断展示条数，不改变基准：基准取截断前的最大值，否则截断后图形会骗人。
 */

export interface BarInput {
  key: string
  label: string
  value: number
}

export interface BarRow extends BarInput {
  ratio: number
}

export function buildBarRows(items: readonly BarInput[], limit = 8): BarRow[] {
  const usable = items.filter((item) => Number.isFinite(item.value) && item.value > 0)
  if (usable.length === 0) return []

  const base = usable.reduce((max, item) => (item.value > max ? item.value : max), 0)
  if (base <= 0) return []

  const sorted = [...usable].sort((a, b) => {
    if (b.value !== a.value) return b.value - a.value
    if (a.label < b.label) return -1
    if (a.label > b.label) return 1
    return 0
  })

  const cap = Number.isFinite(limit) && limit > 0 ? Math.floor(limit) : sorted.length
  return sorted.slice(0, cap).map((item) => ({ ...item, ratio: item.value / base }))
}
