'use client'

import { useQuery } from '@tanstack/react-query'
import { Loader2, RefreshCw, ShieldCheck } from 'lucide-react'
import {
  Button,
  Card,
  CardContent,
  CardHeader,
  CardTitle,
  Table,
  TableBody,
  TableCell,
  TableHead,
  TableHeader,
  TableRow,
} from '@ihui/ui-react'
import { Alert } from '@/components/feedback'
import { cn } from '@/lib/utils'
import { wechatHubApi } from './wechat-hub-api'

function formatTime(value: string): string {
  return new Intl.DateTimeFormat('zh-CN', {
    month: '2-digit',
    day: '2-digit',
    hour: '2-digit',
    minute: '2-digit',
    second: '2-digit',
  }).format(new Date(value))
}

export default function AuditPanel({ accountId }: { accountId: string }) {
  const actionsQuery = useQuery({
    queryKey: ['wechat-hub', 'actions', accountId],
    queryFn: () => wechatHubApi.actions(accountId, 200),
    refetchInterval: 20_000,
  })

  return (
    <Card>
      <CardHeader className="flex flex-row items-center justify-between pb-2">
        <CardTitle className="flex items-center gap-2 text-body">
          <ShieldCheck className="h-4 w-4 text-primary" />
          动作审计
        </CardTitle>
        <Button
          size="sm"
          variant="ghost"
          onClick={() => void actionsQuery.refetch()}
          disabled={actionsQuery.isFetching}
        >
          <RefreshCw className={cn('h-3.5 w-3.5', actionsQuery.isFetching && 'animate-spin')} />
        </Button>
      </CardHeader>
      <CardContent className="space-y-2">
        {actionsQuery.isError ? (
          <Alert
            variant="danger"
            title="读取审计失败"
            description={
              actionsQuery.error instanceof Error ? actionsQuery.error.message : '未知错误'
            }
          />
        ) : actionsQuery.isLoading ? (
          <div className="flex items-center gap-2 py-6 text-sm text-muted-foreground">
            <Loader2 className="h-4 w-4 animate-spin" />
            加载审计…
          </div>
        ) : (actionsQuery.data ?? []).length === 0 ? (
          <p className="py-6 text-center text-sm text-muted-foreground">
            暂无动作。连接、发送、分析都会在这里留痕。
          </p>
        ) : (
          <div className="max-h-[560px] overflow-y-auto">
            <Table>
              <TableHeader>
                <TableRow>
                  <TableHead>时间</TableHead>
                  <TableHead>动作</TableHead>
                  <TableHead>目标</TableHead>
                  <TableHead>状态</TableHead>
                  <TableHead>错误</TableHead>
                </TableRow>
              </TableHeader>
              <TableBody>
                {(actionsQuery.data ?? []).map((item) => (
                  <TableRow key={item.id}>
                    <TableCell className="whitespace-nowrap text-xs text-muted-foreground">
                      {formatTime(item.createdAt)}
                    </TableCell>
                    <TableCell className="font-mono text-xs">{item.action}</TableCell>
                    <TableCell className="max-w-[220px] break-all text-xs">
                      {item.target ?? '—'}
                    </TableCell>
                    <TableCell className="text-xs">
                      <span
                        className={cn(
                          'rounded-md px-1.5 py-0.5',
                          item.status === 'success'
                            ? 'bg-emerald-500/10 text-emerald-700 dark:text-emerald-300'
                            : 'bg-red-500/10 text-red-700 dark:text-red-300',
                        )}
                      >
                        {item.status}
                      </span>
                    </TableCell>
                    <TableCell className="max-w-[260px] break-words text-xs text-muted-foreground">
                      {item.error ?? '—'}
                    </TableCell>
                  </TableRow>
                ))}
              </TableBody>
            </Table>
          </div>
        )}
      </CardContent>
    </Card>
  )
}
