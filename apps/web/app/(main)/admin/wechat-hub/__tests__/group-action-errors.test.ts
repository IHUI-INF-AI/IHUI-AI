/** 群写动作的失败提示：错误码认得的，给出「下一步该干什么」，别只甩一句英文。 */

import { describe, expect, it } from 'vitest'
import { ApiError } from '@ihui/api-client'
import { describeGroupActionError } from '../group-action-errors'

describe('describeGroupActionError', () => {
  it('已知错误码给中文结论，原始文案作副说明', () => {
    const view = describeGroupActionError(
      new ApiError('群写动作未开启，请先在群管理面板打开', 409, 'WECHAT_GROUP_WRITES_DISABLED'),
    )
    expect(view.title).toContain('群写动作未开启')
    expect(view.detail).toBe('')
  })

  it('过期/限流都给可执行的下一步', () => {
    expect(
      describeGroupActionError(new ApiError('token expired', 409, 'WECHAT_GROUP_CONFIRM_EXPIRED'))
        .title,
    ).toContain('重新预览')
    expect(
      describeGroupActionError(new ApiError('too many', 429, 'WECHAT_GROUP_RATE_LIMITED')).title,
    ).toContain('每小时')
  })

  it('未知错误码不编造结论，回退原始文案', () => {
    const view = describeGroupActionError(new Error('桥不在线'))
    expect(view.title).toBe('桥不在线')
    expect(view.detail).toBe('')
  })
})
