import { describe, expect, it } from 'vitest'
import { buildBarRows } from '../analysis-chart'

describe('buildBarRows', () => {
  it('按计数降序，比例以最大值为基准', () => {
    const rows = buildBarRows([
      { key: 'a', label: '甲', value: 10 },
      { key: 'b', label: '乙', value: 30 },
      { key: 'c', label: '丙', value: 20 },
    ])
    expect(rows.map((r) => r.label)).toEqual(['乙', '丙', '甲'])
    expect(rows[0]?.ratio).toBe(1)
    expect(rows[1]?.ratio).toBeCloseTo(2 / 3, 6)
    expect(rows[2]?.ratio).toBeCloseTo(1 / 3, 6)
  })

  it('同值时按 label 升序，顺序稳定', () => {
    const rows = buildBarRows([
      { key: 'z', label: 'b', value: 5 },
      { key: 'y', label: 'a', value: 5 },
    ])
    expect(rows.map((r) => r.label)).toEqual(['a', 'b'])
  })

  it('非有限值与非正值被丢弃，不占条位', () => {
    const rows = buildBarRows([
      { key: 'a', label: '零', value: 0 },
      { key: 'b', label: '负', value: -3 },
      { key: 'c', label: 'NaN', value: Number.NaN },
      { key: 'd', label: '真', value: 4 },
    ])
    expect(rows).toHaveLength(1)
    expect(rows[0]).toMatchObject({ label: '真', ratio: 1 })
  })

  it('limit 只截断展示，基准仍取截断前的最大值', () => {
    const rows = buildBarRows(
      [
        { key: 'a', label: '大', value: 100 },
        { key: 'b', label: '中', value: 50 },
        { key: 'c', label: '小', value: 10 },
      ],
      2,
    )
    expect(rows.map((r) => r.label)).toEqual(['大', '中'])
    expect(rows[1]?.ratio).toBeCloseTo(0.5, 6)
  })

  it('空输入与非法 limit 都不炸', () => {
    expect(buildBarRows([])).toEqual([])
    const rows = buildBarRows([{ key: 'a', label: 'a', value: 1 }], 0)
    expect(rows).toHaveLength(1)
  })
})
