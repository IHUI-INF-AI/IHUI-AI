'use client'

import * as React from 'react'
import { useMutation } from '@tanstack/react-query'
import {
  Button,
  Dialog,
  DialogContent,
  DialogDescription,
  DialogFooter,
  DialogHeader,
  DialogTitle,
} from '@ihui/ui-react'
import { Alert } from '@/components/feedback'
import type { WechatAccountView } from '@ihui/types'
import { wechatHubApi } from './wechat-hub-api'

export default function DeleteAccountDialog({
  account,
  onClose,
  onDeleted,
}: {
  account: WechatAccountView | null
  onClose: () => void
  onDeleted: () => void
}) {
  const [error, setError] = React.useState<string | null>(null)
  const mutation = useMutation({
    mutationFn: (id: string) => wechatHubApi.deleteAccount(id),
    onSuccess: () => {
      onDeleted()
      onClose()
    },
    onError: (e) => setError(e instanceof Error ? e.message : '删除失败'),
  })
  return (
    <Dialog open={Boolean(account)} onOpenChange={(open) => !open && onClose()}>
      <DialogContent>
        <DialogHeader>
          <DialogTitle>删除微信账号</DialogTitle>
          <DialogDescription>
            将同时删除该账号的会话、消息、分析记录与动作审计，且不可恢复。
          </DialogDescription>
        </DialogHeader>
        {error ? <Alert variant="danger" title="删除失败" description={error} /> : null}
        <p className="text-sm">确认删除「{account?.label}」？</p>
        <DialogFooter>
          <Button variant="outline" onClick={onClose}>
            取消
          </Button>
          <Button
            variant="destructive"
            disabled={mutation.isPending}
            onClick={() => account && mutation.mutate(account.id)}
          >
            删除
          </Button>
        </DialogFooter>
      </DialogContent>
    </Dialog>
  )
}
