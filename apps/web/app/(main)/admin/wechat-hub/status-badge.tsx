'use client'

import { cn } from '@/lib/utils'
import type { WechatAccountStatus } from '@ihui/types'

const STATUS_META: Record<WechatAccountStatus, { label: string; className: string }> = {
  disconnected: { label: '未连接', className: 'bg-muted text-muted-foreground' },
  connecting: { label: '连接中', className: 'bg-sky-500/10 text-sky-700 dark:text-sky-300' },
  awaiting_scan: {
    label: '等待扫码',
    className: 'bg-amber-500/10 text-amber-700 dark:text-amber-300',
  },
  online: {
    label: '在线',
    className: 'bg-emerald-500/10 text-emerald-700 dark:text-emerald-300',
  },
  expired: { label: '已过期', className: 'bg-red-500/10 text-red-700 dark:text-red-300' },
  error: { label: '异常', className: 'bg-red-500/10 text-red-700 dark:text-red-300' },
}

export function WechatStatusBadge({
  status,
  className,
}: {
  status: WechatAccountStatus
  className?: string
}) {
  const meta = STATUS_META[status]
  return (
    <span
      className={cn(
        'inline-flex items-center rounded-md px-2 py-0.5 text-xs font-medium',
        meta.className,
        className,
      )}
    >
      {meta.label}
    </span>
  )
}

