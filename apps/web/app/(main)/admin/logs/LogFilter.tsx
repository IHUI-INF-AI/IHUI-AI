'use client'

import { useTranslations } from 'next-intl'
import {} from 'lucide-react'
import { Input, SearchInput } from '@ihui/ui-react'
import { METHODS, inputClass } from './helpers'

interface Props {
  method: string
  onMethodChange: (v: string) => void
  statusCode: string
  onStatusCodeChange: (v: string) => void
  path: string
  onPathChange: (v: string) => void
}

export function LogFilter({
  method,
  onMethodChange,
  statusCode,
  onStatusCodeChange,
  path,
  onPathChange,
}: Props) {
  const t = useTranslations('admin.logs')
  return (
    <div className="flex flex-wrap items-center gap-2">
      <select
        value={method}
        onChange={(e) => onMethodChange(e.target.value)}
        className={inputClass}
        aria-label={t('method')}
      >
        <option value="all">{t('allMethods')}</option>
        {METHODS.map((m) => (
          <option key={m} value={m}>
            {m}
          </option>
        ))}
      </select>
      <Input
        value={statusCode}
        onChange={(e) => onStatusCodeChange(e.target.value)}
        placeholder={t('statusPlaceholder')}
        className="h-9 w-28"
        inputMode="numeric"
        aria-label={t('statusCode')}
      />
      <SearchInput
        value={path}
        onChange={(e) => onPathChange(e.target.value)}
        placeholder={t('pathPlaceholder')}
        aria-label={t('path')}
        size="lg"
        wrapperClassName="min-w-[140px] min-[640px]:min-w-[200px] flex-1"
      />
    </div>
  )
}
