import { useTranslations } from 'next-intl'
import { AdminCategoryTable } from '@/components/admin/category-admin'
import type { Category } from './types'

interface Props {
  categories: Category[]
  isLoading: boolean
  error: Error | null
  deletePending: boolean
  onEdit: (c: Category) => void
  onDelete: (id: string) => void
}

export function CategoriesTable({
  categories,
  isLoading,
  error,
  deletePending,
  onEdit,
  onDelete,
}: Props) {
  const t = useTranslations('admin.edu.exam.categories')
  return (
    <AdminCategoryTable
      list={categories}
      isLoading={isLoading}
      error={error}
      deletePending={deletePending}
      onEdit={onEdit}
      onDelete={(item) => onDelete(item.id)}
      labels={{
        colName: t('colName'),
        colSort: t('colSort'),
        colStatus: t('colStatus'),
        colActions: t('colAction'),
        loading: t('loading'),
        noData: t('noCategories'),
        enabled: t('statusEnabled'),
        disabled: t('statusDisabled'),
        edit: t('edit'),
        delete: t('delete'),
        confirmTitle: t('confirmDelete'),
        confirmAction: t('delete'),
        confirmCancel: t('cancel'),
      }}
    />
  )
}
