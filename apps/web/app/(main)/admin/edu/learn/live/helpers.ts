import type { LForm, Live, LiveStage } from './types'

export const PAGE_SIZE = 10

export const EMPTY: LForm = {
  title: '',
  lecturerName: '',
  startTime: '',
  status: 'upcoming',
}

export const STATUS_MAP: Record<string, { labelKey: string; cls: string }> = {
  upcoming: {
    labelKey: 'statusUpcoming',
    cls: 'bg-amber-500/10 text-amber-600 dark:text-amber-400',
  },
  ongoing: { labelKey: 'statusOngoing', cls: 'bg-rose-500/10 text-rose-600 dark:text-rose-400' },
  ended: { labelKey: 'statusEnded', cls: 'bg-muted text-muted-foreground' },
}

/** 后端行只有启用位 status(0/1);阶段由 isLive/isPublished 派生。 */
export function liveStage(l: Pick<Live, 'isLive' | 'isPublished'>): LiveStage {
  if (l.isLive) return 'ongoing'
  if (l.isPublished) return 'ended'
  return 'upcoming'
}

export function liveToForm(l: Live): LForm {
  return {
    title: l.title,
    lecturerName: l.lecturerName ?? '',
    startTime: l.startTime,
    status: liveStage(l),
  }
}

/**
 * 提交体按语义键(isLive/isPublished),不回传 status:
 * `status` 是启用位(0/1),把 upcoming/ongoing/ended 原样提交会撞
 * `createChannelSchema.status: z.number().int()` ⇒ 400。
 */
export function toChannelPayload(form: LForm) {
  const live = form.status === 'ongoing'
  return {
    title: form.title,
    lecturerName: form.lecturerName || null,
    startTime: form.startTime || null,
    isLive: live,
    isPublished: live || form.status === 'ended',
  }
}
