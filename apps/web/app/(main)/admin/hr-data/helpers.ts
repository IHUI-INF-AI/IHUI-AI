/** 批次状态 → 语义色。verified 绿(已完成)、rejected 红(作废)、其余灰(待处理)。 */
export function batchStatusTone(status: string): 'ok' | 'warn' | 'muted' | 'danger' {
  if (status === 'verified') return 'ok'
  if (status === 'pending_review') return 'warn'
  if (status === 'rejected') return 'danger'
  return 'muted'
}

/** 行匹配状态 → 语义色。conflict 必须人工裁决,用 danger 强制视觉提示。 */
export function rowStatusTone(status: string): 'ok' | 'warn' | 'muted' | 'danger' {
  if (status === 'matched') return 'ok'
  if (status === 'conflict') return 'danger'
  if (status === 'duplicate') return 'warn'
  if (status === 'not_found') return 'warn'
  return 'muted'
}

/** 金额格式化:统一两位小数 + 千分位,避免各页面各写一套。 */
export function fmtMoney(value: string | number | null | undefined): string {
  const n = Number(value ?? 0)
  if (!Number.isFinite(n)) return '0.00'
  return n.toLocaleString('zh-CN', { minimumFractionDigits: 2, maximumFractionDigits: 2 })
}

/** 当月 YYYY-MM */
export function currentMonth(): string {
  const d = new Date()
  return `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}`
}

