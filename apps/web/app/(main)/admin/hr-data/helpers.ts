/** 待办严重度 → 语义色。blocker 用 danger 强制提示(不能继续),warn 用 warning。 */
export type TodoSeverity = 'blocker' | 'warn' | 'info'

export function severityTone(severity: string): 'danger' | 'warn' | 'muted' {
  if (severity === 'blocker') return 'danger'
  if (severity === 'warn') return 'warn'
  return 'muted'
}
