'use client'

/**
 * 请假多级审批(2026-11-23 立)。
 *
 * 之前只有"单级审批"接进了考勤页(请假单点通过/驳回),多级审批链
 * (假别 + 天数 → 有序审批人 → 超时升级)的六个别端点在后端躺着,
 * 没有一个入口能配链、能看待办、能跑升级扫描。本页把这条链收口。
 */

import * as React from 'react'
import { useTranslations } from 'next-intl'
import { Workflow, ListChecks } from 'lucide-react'

import { FeaturePageShell } from '@/components/layout'
import { FlowsPanel } from './flows-panel'
import { InstancesPanel } from './instances-panel'

type TabKey = 'instances' | 'flows'

export default function HrApprovalPage() {
  const t = useTranslations('hrApproval')
  const [tab, setTab] = React.useState<TabKey>('instances')

  const tabs: Array<{
    key: TabKey
    label: string
    icon: React.ComponentType<{ className?: string }>
  }> = [
    { key: 'instances', label: t('tabInstances'), icon: ListChecks },
    { key: 'flows', label: t('tabFlows'), icon: Workflow },
  ]

  return (
    <FeaturePageShell title={t('title')} description={t('desc')} icon={Workflow} domain="hr">
      <div className="mb-3 flex flex-wrap gap-1">
        {tabs.map(({ key, label, icon: Icon }) => (
          <button
            key={key}
            className={`inline-flex items-center gap-1.5 rounded-md px-2.5 py-1.5 text-xs ${
              tab === key ? 'bg-muted font-medium' : 'text-muted-foreground hover:bg-muted/60'
            }`}
            onClick={() => setTab(key)}
          >
            <Icon className="h-3.5 w-3.5" />
            {label}
          </button>
        ))}
      </div>
      {tab === 'instances' ? <InstancesPanel /> : <FlowsPanel />}
    </FeaturePageShell>
  )
}
