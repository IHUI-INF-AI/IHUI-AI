export async function api<T>(url: string, options?: RequestInit): Promise<T> {
  const r = await fetchApi<T>(url, options)
  if (!r.success) throw new ApiError(r.error, r.status, r.errorCode)
  return r.data
}

export async function fetchAsks(params: {
  page: number
  pageSize?: number
  search?: string
  resolved?: boolean
}): Promise<AsksListData> {
  const qs = new URLSearchParams({
    page: String(params.page),
    pageSize: String(params.pageSize ?? PAGE_SIZE),
  })
  if (params.search) qs.set('search', params.search)
  if (params.resolved !== undefined) qs.set('resolved', String(params.resolved))
  return api<AsksListData>(`/api/admin/asks?${qs.toString()}`)
}

export function askToForm(item: AskItem): AskForm {
  return {
    title: item.title,
    content: item.content,
    tags: (item.tags ?? []).join(', '),
    status: item.status,
    isResolved: item.isResolved,
  }
}

export function parseTags(tags: string): string[] {
  return tags
    .split(/[,，\s]+/)
    .map((s) => s.trim())
    .filter(Boolean)
}
