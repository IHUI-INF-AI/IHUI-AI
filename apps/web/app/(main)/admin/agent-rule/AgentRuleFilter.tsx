'use client'
import type React from 'react'
import {} from 'lucide-react'
import { useTranslations } from 'next-intl'
import { SearchInput } from '@ihui/ui-react'

interface Props {
  searchAgentId: string
  setSearchAgentId: (v: string) => void
  searchName: string
  setSearchName: (v: string) => void
}

export function AgentRuleFilter({
  searchAgentId,
  setSearchAgentId,
  searchName,
  setSearchName,
}: Props) {
  const t = useTranslations('admin.agentRule')
  return (
    <div className="flex flex-wrap items-center gap-2">
      <SearchInput
        value={searchAgentId}
        onChange={(e: React.ChangeEvent<HTMLInputElement>) => setSearchAgentId(e.target.value)}
        placeholder={t('searchAgentId')}
        size="lg"
        wrapperClassName="w-full max-w-xs"
      />
      <SearchInput
        value={searchName}
        onChange={(e: React.ChangeEvent<HTMLInputElement>) => setSearchName(e.target.value)}
        placeholder={t('searchRuleName')}
        size="lg"
        wrapperClassName="w-full max-w-xs"
      />
    </div>
  )
}
