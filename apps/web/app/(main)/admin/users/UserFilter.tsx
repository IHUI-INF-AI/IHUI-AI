'use client'

import { useTranslations } from 'next-intl'
import {} from 'lucide-react'
import {
  SearchInput,
  Select,
  SelectContent,
  SelectItem,
  SelectTrigger,
  SelectValue,
} from '@ihui/ui-react'
import { selectClass } from './helpers'

interface Props {
  search: string
  onSearchChange: (v: string) => void
  role: string
  onRoleChange: (v: string) => void
  status: string
  onStatusChange: (v: string) => void
}

export function UserFilter({
  search,
  onSearchChange,
  role,
  onRoleChange,
  status,
  onStatusChange,
}: Props) {
  const t = useTranslations('admin.users')
  return (
    <div className="flex flex-wrap items-center gap-2">
      <SearchInput
        value={search}
        onChange={(e) => onSearchChange(e.target.value)}
        placeholder={t('searchPlaceholder')}
        aria-label={t('search')}
        size="lg"
        wrapperClassName="w-full max-w-xs"
      />
      <Select value={role} onValueChange={onRoleChange}>
        <SelectTrigger className={selectClass} aria-label={t('role')}>
          <SelectValue />
        </SelectTrigger>
        <SelectContent>
          <SelectItem value="all">{t('allRoles')}</SelectItem>
          <SelectItem value="1">{t('roleAdmin')}</SelectItem>
          <SelectItem value="0">{t('roleUser')}</SelectItem>
        </SelectContent>
      </Select>
      <Select value={status} onValueChange={onStatusChange}>
        <SelectTrigger className={selectClass} aria-label={t('status')}>
          <SelectValue />
        </SelectTrigger>
        <SelectContent>
          <SelectItem value="all">{t('allStatus')}</SelectItem>
          <SelectItem value="1">{t('statusActive')}</SelectItem>
          <SelectItem value="0">{t('statusDisabled')}</SelectItem>
          <SelectItem value="3">{t('statusCancelled')}</SelectItem>
        </SelectContent>
      </Select>
    </div>
  )
}
