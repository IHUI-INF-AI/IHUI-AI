'use client'

import { Search } from 'lucide-react'
import { useTranslations } from 'next-intl'
import {
  SearchInput,
  Select,
  SelectContent,
  SelectItem,
  SelectTrigger,
  SelectValue,
} from '@ihui/ui-react'
import { cn } from '@/lib/utils'
import { inputClass } from './helpers'

interface Props {
  keyword: string
  setKeyword: (v: string) => void
  resourceFilter: string
  setResourceFilter: (v: string) => void
  actionFilter: string
  setActionFilter: (v: string) => void
  resources: string[]
  actions: string[]
  filteredCount: number
}

export function PermissionsFilter({
  keyword,
  setKeyword,
  resourceFilter,
  setResourceFilter,
  actionFilter,
  setActionFilter,
  resources,
  actions,
  filteredCount,
}: Props) {
  const t = useTranslations('admin.permissions')
  return (
    <div className="flex flex-wrap items-center gap-2">
      <SearchInput
        value={keyword}
        onChange={(e) => setKeyword(e.target.value)}
        placeholder={t('searchPlaceholder')}
        size="lg"
        wrapperClassName="min-w-[140px] min-[640px]:min-w-[200px] flex-1"
      />
      <Select value={resourceFilter} onValueChange={(v) => setResourceFilter(v)}>
        <SelectTrigger className={inputClass} aria-label={t('resource')}>
          <SelectValue />
        </SelectTrigger>
        <SelectContent>
          <SelectItem value="all">{t('allResources')}</SelectItem>
          {resources.map((r) => (
            <SelectItem key={r} value={r}>
              {r}
            </SelectItem>
          ))}
        </SelectContent>
      </Select>
      <Select value={actionFilter} onValueChange={(v) => setActionFilter(v)}>
        <SelectTrigger className={cn(inputClass, 'w-32')} aria-label={t('action')}>
          <SelectValue />
        </SelectTrigger>
        <SelectContent>
          <SelectItem value="all">{t('allActions')}</SelectItem>
          {actions.map((a) => (
            <SelectItem key={a} value={a}>
              {a}
            </SelectItem>
          ))}
        </SelectContent>
      </Select>
      <span className="text-sm text-muted-foreground">
        {t('filteredCount', { count: filteredCount })}
      </span>
    </div>
  )
}
