/**
 * 大屏时间口径的回归锁(住在每次提交都跑的那一层)。
 * 立因:小时柱的分桶、跨天判定、「刷新于」全部来自服务端按 Asia/Shanghai 的聚合,
 * 而前端曾经用浏览器时区去截「今天第几小时」—— 换一台非 +08 的值班机就会把已经发生的
 * 小时整段截掉,剩下的空槽照样画成 0 柱,画面看着完全正常。
 * 所以断言必须**与宿主机时区无关**:一律喂 UTC 瞬间,只认数据侧读数。
 */
import { readFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { describe, expect, it } from 'vitest'

import { DATA_TZ, tzParts } from '../data-time'

describe('大屏时间口径(按数据侧时区,不按浏览器)', () => {
  it('同一 UTC 日内跨了数据侧午夜 ⇒ 日期判定必须跟着跨天', () => {
    const before = tzParts(new Date('2026-10-24T15:59:59Z')) // 上海 23:59:59
    const after = tzParts(new Date('2026-10-24T16:00:00Z')) // 上海次日 00:00:00
    expect(before.dateKey).toBe('2026-10-24')
    expect(after.dateKey).toBe('2026-10-25')
  })

  it('数据侧午夜归一到 0 点(不得冒出 24 点这一档)', () => {
    const midnight = tzParts(new Date('2026-10-24T16:00:00Z'))
    expect(midnight.hour).toBe(0)
    expect(midnight.hms).toBe('00:00:00')
  })

  it('小时柱的截断口径 = 数据侧小时:UTC 00:00 是上海 8 点', () => {
    const morning = tzParts(new Date('2026-10-24T00:00:00Z'))
    expect(morning.hour).toBe(8)
    expect(morning.hms).toBe('08:00:00')
    // 反向锁:换算必须真的动了 —— 与 UTC 小时同值就等于这层皮是假的
    expect(morning.hour).not.toBe(new Date('2026-10-24T00:00:00Z').getUTCHours())
  })

  it('读数形态固定为 YYYY-MM-DD / HH:mm:ss(页头时钟与事件流共用)', () => {
    const p = tzParts(new Date('2026-10-24T01:02:03Z'))
    expect(p.dateKey).toMatch(/^\d{4}-\d{2}-\d{2}$/)
    expect(p.hms).toMatch(/^\d{2}:\d{2}:\d{2}$/)
    expect(p.hms).toBe('09:02:03')
  })

  it('page.tsx 不得再按浏览器时区取小时(回退即红)', () => {
    const src = readFileSync(resolve(__dirname, '..', 'page.tsx'), 'utf8')
    expect(src).toContain('tzParts(now).hour')
    expect(src).not.toMatch(/now\.getHours\(\)/)
    expect(src).not.toMatch(/d\.toDateString\(\)/)
    expect(DATA_TZ).toBe('Asia/Shanghai')
  })
})
