/**
 * 大屏的时间口径:所有读数按**数据侧时区**(生产机 Asia/Shanghai)显示与判定。
 *
 * 为什么单独成模块而不是住在 page.tsx:Next 的 page.tsx 只允许 default 导出与路由段配置,
 * 想被测试 import 就得另起模块(与同目录 unknown-state.ts 同一条理由)。
 * 小时柱的分桶、跨天判定、「刷新于」读的都是服务端按 Asia/Shanghai 聚合的数
 * (`to_char(createdAt AT TIME ZONE 'Asia/Shanghai','HH24')`),前端若按浏览器时区算,
 * 换到非 +08 的值班机上会把「今天」切成错的小时 —— 而画面看着完全正常。
 */
export const DATA_TZ = 'Asia/Shanghai'

const TZ_PARTS = new Intl.DateTimeFormat('en-GB', {
  timeZone: DATA_TZ,
  hour12: false,
  year: 'numeric',
  month: '2-digit',
  day: '2-digit',
  hour: '2-digit',
  minute: '2-digit',
  second: '2-digit',
})

export interface DataTimeParts {
  /** 'YYYY-MM-DD'(数据侧日期,用于跨天判定) */
  dateKey: string
  /** 'HH:mm:ss'(数据侧时刻) */
  hms: string
  /** 数据侧 0–23 小时;服务端小时柱的分桶键就按它截断 */
  hour: number
}

/** en-GB + hour12:false 在午夜可能给出 "24",统一归一到 0。 */
export function tzParts(d: Date): DataTimeParts {
  const p: Record<string, string> = {}
  for (const s of TZ_PARTS.formatToParts(d)) if (s.type !== 'literal') p[s.type] = s.value
  const hour = (Number(p.hour) || 0) % 24
  const pad = (n: number) => String(n).padStart(2, '0')
  return {
    dateKey: `${p.year}-${p.month}-${p.day}`,
    hms: `${pad(hour)}:${p.minute ?? '00'}:${p.second ?? '00'}`,
    hour,
  }
}
