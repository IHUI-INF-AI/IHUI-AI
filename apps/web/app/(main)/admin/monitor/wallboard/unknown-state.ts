/**
 * 展示层判定态(§0.3「没判」绝不渲染成「判过」)—— 生产监控大屏唯一一份"测到了没有"的尺子。
 *
 * 为什么住在这个文件而不是 page.tsx:Next 的 page.tsx 只允许 default 导出与路由段配置,
 * 想被测试 import 就得另起模块;判据住两处必然漂移(本仓记过最多次的失败型)。
 * 后端每路数据源独立降级留 null(apps/api/src/routes/admin-ops-wallboard.ts),
 * 前端任何 null→数字兜底、null→'ok' 阈值染色,都是把"通道不可达"谎报成"机器健康/零告警"。
 */
export type StatusTone = 'ok' | 'warn' | 'bad' | 'unknown'

/** 数值可用性:NaN/Infinity 不算"测到了"(面板会把它们画成空白或 0,两种都误导)。 */
export function isNum(v: number | null | undefined): v is number {
  return typeof v === 'number' && Number.isFinite(v)
}

/** 未置值:boolean 档位取不到时是 null(后端降级)或 undefined(整块不可达),两者都得走"未知"。 */
export function isUnset(v: boolean | null | undefined): v is null | undefined {
  return v === null || v === undefined
}

/** 阈值着色:非有限值一律 'unknown',不得伪造默认值通过阈值。 */
export function thresholdTone(
  v: number | null | undefined,
  classify: (n: number) => 'ok' | 'warn' | 'bad',
): StatusTone {
  return isNum(v) ? classify(v) : 'unknown'
}
