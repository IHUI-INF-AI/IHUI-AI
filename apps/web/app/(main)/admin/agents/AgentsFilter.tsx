'use client'
import type React from 'react'
import { useTranslations } from 'next-intl'
import {
  SearchInput,
  Select,
  SelectContent,
  SelectItem,
  SelectTrigger,
  SelectValue,
} from '@ihui/ui-react'
import { STATUS_OPTIONS, STATUS_KEY, selectClass } from './helpers'

interface AgentsFilterProps {
  search: string
  status: string
  onSearchChange: (v: string) => void
  onStatusChange: (v: string) => void
}

export function AgentsFilter({
  search,
  status,
  onSearchChange,
  onStatusChange,
}: AgentsFilterProps) {
  const t = useTranslations('admin.agents')
  const tc = useTranslations('common')

  return (
    <div className="flex flex-wrap items-center gap-2">
      <SearchInput
        value={search}
        onChange={(e: React.ChangeEvent<HTMLInputElement>) => onSearchChange(e.target.value)}
        placeholder={t('searchPlaceholder')}
        aria-label={tc('search')}
        size="lg"
        wrapperClassName="w-full max-w-xs"
      />
      <Select value={status} onValueChange={onStatusChange}>
        <SelectTrigger className={selectClass} aria-label={t('fieldStatus')}>
          <SelectValue />
        </SelectTrigger>
        <SelectContent>
          <SelectItem value="all">{t('allStatus')}</SelectItem>
          {STATUS_OPTIONS.map((s) => (
            <SelectItem key={s} value={s}>
              {t(STATUS_KEY[s] ?? 'statusUnknown')}
            </SelectItem>
          ))}
        </SelectContent>
      </Select>
    </div>
  )
}
