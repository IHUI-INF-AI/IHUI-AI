'use client'

import { useTranslations } from 'next-intl'
import { CategoryShell, type CategoryNavGroup } from '@/components/layout'
import { NAV_GROUPS, SETTINGS_NAV_LABEL_KEY } from './helpers'

export default function SettingsLayout({ children }: { children: React.ReactNode }) {
  const t = useTranslations('settings')
  // 2026-10-19:经 SETTINGS_NAV_LABEL_KEY 表取值,而不是裸 t(labelKey)。
  // 守门 121 C6 档只认静态发射点(`t('字面量')` 或 字面量表 + `t(表[表达式])`),
  // 裸 `t(变量)` 两型都判不出 ⇒ 导航键会被记成"未接线"并顶破棘轮。
  // 取不到全键时回落到 key 本身(表与 NAV_GROUPS 须同批维护,漏登记时
  // 退化成原始 key 而不是 next-intl 的 missing-message 抛错)。
  const label = (key: string) => {
    const full = SETTINGS_NAV_LABEL_KEY[key]
    return full ? t(full) : key
  }
  const navGroups: CategoryNavGroup[] = NAV_GROUPS.map((group) => ({
    label: group.labelKey ? label(group.labelKey) : undefined,
    items: group.items.map((item) => ({
      href: item.href,
      label: label(item.labelKey),
      icon: item.icon,
    })),
  }))

  return (
    <CategoryShell title={t('title')} description={t('subtitle')} navGroups={navGroups}>
      {children}
    </CategoryShell>
  )
}
