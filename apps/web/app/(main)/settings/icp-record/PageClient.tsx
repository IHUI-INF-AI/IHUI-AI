'use client'

import * as React from 'react'
import { useTranslations } from 'next-intl'
import { useRouter } from 'next/navigation'
import { useTheme } from 'next-themes'

import { IcpRecordScreen } from '@ihui/rn-app/pilot'
import { createIcpRecordT } from '@/lib/rn-pilot/icp-record-view-model'

/** 备案查询/公示地址(与改造前 web 页一致)。 */
const MIIT_QUERY_URL = 'https://beian.miit.gov.cn'

/**
 * ICP 备案页 · web 消费共享屏(2026-11-07)。
 *
 * 改造前 web 页自持 6 行静态数据;收编后 6 行以共享屏为单一事实源,web 只补
 * 「备案范围」与「备案链接」两行(共享屏新增的**可选** prop,两端都能传)。
 * 无鉴权门、无取数,保留原返回语义。
 */
export default function IcpRecordPageClient() {
  const t = useTranslations('settings')
  const router = useRouter()
  const { resolvedTheme } = useTheme()

  const tShared = React.useMemo(() => createIcpRecordT(t), [t])
  const colorScheme = resolvedTheme === 'dark' ? 'dark' : 'light'

  const openRecordUrl = React.useCallback((url: string) => {
    window.open(url, '_blank', 'noopener,noreferrer')
  }, [])

  return (
    <div className="mx-auto flex h-[calc(100dvh-8rem)] min-h-[480px] w-full max-w-2xl flex-col overflow-hidden py-4">
      <IcpRecordScreen
        t={tShared}
        onBack={() => router.back()}
        scope={t('icpRecordScopeValue')}
        recordUrl={MIIT_QUERY_URL}
        onOpenRecordUrl={openRecordUrl}
        colorScheme={colorScheme}
      />
    </div>
  )
}
