export const mmss = (s: number) =>
  `${String(Math.floor(s / 60)).padStart(2, '0')}:${String(s % 60).padStart(2, '0')}`

/**
 * 考试剩余秒数 = 截止时间戳 − 现在(2026-11-08 W-01)。
 *
 * 立因:旧实现每秒 `setLeftSec((s) => s - 1)`,把"经过的时间"当成 tick 次数。浏览器在后台
 * 会节流/暂停定时器,锁屏或系统休眠更是直接不走 —— 自减型倒计时于是跟着"冻住",
 * 切后台 10 分钟回来还剩原来的时间,考试被无声延长(且没有任何门能看见)。
 * 改成纯函数后,每次重算都以 deadline 为准:`visibilitychange` / `focus` / `pageshow`
 * 回前台立刻按真实剩余时间刷新,少走一段也补得回来。
 *
 * 口径:向上取整(与"开始时显示满额 duration:00"一致);越过截止点一律夹到 0,不出现负数。
 */
export const remainingSeconds = (deadline: number, now: number = Date.now()): number =>
  Math.max(0, Math.ceil((deadline - now) / 1000))
