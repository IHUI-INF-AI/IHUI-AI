'use client'

import { useParams } from 'next/navigation'
import MarketPageClient from '../PageClient'

/**
 * `/skills-market/[id]` 的薄壳:把 URL 里的 skill name 交给列表页那一份
 * `SkillsMarketPageClient`,由它按 `deepLinkName` 反查条目并自动打开详情弹层。
 *
 * 刻意不复制第二套详情 UI —— 深链与卡片点击共用同一个组件,
 * 才是"详情页可以被链接直达"而不是"多了一个详情页"。
 */
export default function SkillMarketDetailRoute() {
  const params = useParams<{ id: string | string[] }>()
  const raw = Array.isArray(params.id) ? params.id[0] : params.id
  const slug = typeof raw === 'string' && raw.length > 0 ? raw : undefined
  // Next 一般已解码动态段,但畸形百分号编码(如手改地址栏的 `%zz`)会让
  // decodeURIComponent 抛错 ⇒ 兜底回原值,不让一个坏 URL 崩掉整页。
  let name: string | undefined
  if (slug) {
    try {
      name = decodeURIComponent(slug)
    } catch {
      name = slug
    }
  }
  return <MarketPageClient deepLinkName={name} />
}
