import type { Metadata } from 'next'

import { apiOrThrow } from '@/lib/api'
import { excerptFromContent, type DocDetail } from '@/lib/content'

import PageClient from './PageClient'

interface PageProps {
  params: Promise<{ slug: string }>
}

/**
 * 正文取数放在客户端(与 help/[slug]、announcements/[id] 同形):服务端 RSC 只有在
 * NEXT_PUBLIC_API_BASE_URL 已配置时才拿得到绝对基址,未配置时 resolveApiBaseUrl() 返回 ''
 * ⇒ 相对 fetch 在 Node 里必然失败。客户端走同源 /api/* 反代,两种环境都成立。
 */
const loadDoc = async (slug: string): Promise<DocDetail | null> => {
  try {
    return await apiOrThrow<DocDetail>(`/api/docs/${encodeURIComponent(slug)}`, {
      timeoutMs: 10_000,
    })
  } catch {
    return null
  }
}

export function generateStaticParams(): { slug: string }[] {
  return []
}

export async function generateMetadata({ params }: PageProps): Promise<Metadata> {
  const { slug } = await params
  const detail = await loadDoc(slug)
  return {
    title: detail?.doc.title ?? slug,
    description: detail ? excerptFromContent(detail.doc.content) : undefined,
    alternates: { canonical: `/docs/${slug}` },
  }
}

export default function DocsDetailPage() {
  return <PageClient />
}
