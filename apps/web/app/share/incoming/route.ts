/**
 * 系统分享接收入口。只回判定，不写会话，不读文件内容。
 * 静态导出期与 websub 同一档：GET 可预渲染，POST 在 standalone 上收表单。
 */
import {
  admitShareIntake,
  fieldsFromShareParts,
  shareIntakeStatus,
  type ShareIntakePlan,
} from '@/lib/turn-deeplink'

export const dynamic = 'force-static'

function json(plan: ShareIntakePlan): Response {
  return Response.json(plan, {
    status: shareIntakeStatus(plan),
    headers: { 'Cache-Control': 'no-store' },
  })
}

export function GET(): Response {
  return json(admitShareIntake({ method: 'GET', fields: {} }))
}

export async function POST(request: Request): Promise<Response> {
  let parts: unknown = null
  try {
    const form = await request.formData()
    const collected: { name: string; kind: 'text' | 'file'; value?: string; size?: number }[] = []
    // @ts-expect-error -- G 面:@types/node 26 全局 FormData 缺 entries();纯增量不改在飞行,对象空间补丁用 Array.from(formData.entries()) 断言写法
    for (const [name, value] of form.entries()) {
      if (typeof value === 'string') collected.push({ name, kind: 'text', value })
      else
        collected.push({
          name,
          kind: 'file',
          size: typeof value.size === 'number' ? value.size : Number.NaN,
        })
    }
    parts = collected
  } catch {
    parts = null
  }
  return json(admitShareIntake({ method: 'POST', fields: fieldsFromShareParts(parts) }))
}
