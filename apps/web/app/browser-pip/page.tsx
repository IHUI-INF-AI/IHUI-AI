import { AiPipMonitor } from '@/components/browser-pip/ai-pip-monitor'

export const dynamic = 'force-dynamic'

/**
 * 桌面端 AI 画中画监看页(独立 Tauri 窗加载)。
 *
 * 只给桌面壳用:普通浏览器没有窗口级置顶 API,也不该把这个裸页当产品入口;
 * 主站页面的「画中画监看」按钮在 Tauri 下走 `open_browser_pip_window`,
 * 非 Tauri 仍走 Document PiP。
 */
export default async function BrowserPipPage({
  searchParams,
}: {
  searchParams: Promise<{ session?: string | string[] }>
}) {
  const params = await searchParams
  const raw = params.session
  const sessionId = Array.isArray(raw) ? (raw[0] ?? '') : (raw ?? '')
  return <AiPipMonitor sessionId={sessionId} />
}
