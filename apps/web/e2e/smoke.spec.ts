import { test, expect } from '@playwright/test'

test.describe('冒烟测试', () => {
  test('首页可访问', async ({ page }) => {
    await page.goto('/')
    await expect(page).toHaveTitle(/IHUI|AI/i)
  })

  test('导航栏可见', async ({ page }) => {
    await page.goto('/')
    // 检查侧边栏或导航存在
    const nav = page.locator('nav, [role="navigation"], aside').first()
    await expect(nav).toBeVisible({ timeout: 10000 })
  })

  test('登录页可访问', async ({ page }) => {
    // 直连独立登录页 /sso/login(/login 的 308 已于 2026-10-22 摘除,它现在是弹窗软路由,
    // 判据锁 tests/auth-login-route-redirect.test.ts)
    await page.goto('/sso/login')
    await page.waitForLoadState('domcontentloaded')
    await expect(page).toHaveURL(/\/sso\/login/)
    // 任意可见 input 即可(SSO 页用 type=text, 密码登录用 type=tel/password)
    await expect(page.locator('input:not([type="file"]):visible').first()).toBeVisible({
      timeout: 10000,
    })
  })

  test('登录入口 /login 走弹窗形态,不整页落到 SSO 授权页也不白屏', async ({ page }) => {
    // 2026-10-22 摘掉 /login→/sso/login 的 308 后,/login 是软路由:开全局登录弹窗 + 回前一页
    // (新标签直链无来路时降级首页)。这条只在 CI 的 build+start 面有意义(本机常驻 dev 仍持旧配置):
    // ① 没有整页落到授权页 ② 不是白屏(有可见输入框) ③ 弹窗里的表单确实可达。
    await page.goto('/login')
    await page.waitForLoadState('domcontentloaded')
    expect(page.url()).not.toContain('/sso/login')
    await expect(page.locator('input:not([type="file"]):visible').first()).toBeVisible({
      timeout: 15000,
    })
  })

  test('注册页可访问', async ({ page }) => {
    await page.goto('/register')
    await expect(page.locator('input:not([type="file"]):visible').first()).toBeVisible({
      timeout: 10000,
    })
  })
})
