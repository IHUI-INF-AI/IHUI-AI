// 本地实跑用 override:本沙箱无法从 playwright CDN 下载 chromium(网络被墙),
// 但系统自带 Microsoft Edge(Chromium 内核)。用 channel:'msedge' 复用系统 Edge 跑 e2e,
// 并去掉依赖的 setup 项目(admin.json 登录态已存在,无需再打真实后端登录)。
import { defineConfig, devices } from '@playwright/test'
import base from './playwright.config'

const projects = (base.projects ?? [])
  .filter((p) => p.name !== 'setup')
  .map((p) =>
    p.name === 'chromium'
      ? {
          ...p,
          dependencies: [],
          use: {
            ...p.use,
            ...devices['Desktop Chrome'],
            // 复用系统 Edge(Chromium 内核)代替被墙的 playwright chromium
            channel: 'msedge' as const,
            launchOptions: {
              args: [
                '--disable-dev-shm-usage',
                '--no-sandbox',
                // 反节流:headless 下 rAF/定时器易被压成 1fps,导致流式采样失真
                '--disable-background-timer-throttling',
                '--disable-backgrounding-occluded-windows',
                '--disable-renderer-backgrounding',
              ],
            },
          },
        }
      : p,
  )

export default defineConfig({
  ...base,
  projects,
})
