// @vitest-environment jsdom
/**
 * useGlobalShortcuts 面板数据源回归(2026-09-22)
 *
 * DEFAULT_SHORTCUTS 是在 effect 里写进 ref 的,而 `shortcuts` 曾只依赖 [scope] ——
 * 首帧 memo 固化成空数组,此后永不重算,Ctrl+/ 帮助面板因此永远 0 行(真机取证)。
 * 本文件钉住"effect 注册完成后 shortcuts 必须含全部注册表条目"这一契约。
 */
import { describe, it, expect } from 'vitest'
import { readFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { renderHook, waitFor } from '@testing-library/react'
import { useGlobalShortcuts } from '../src/hooks/use-global-shortcuts'

describe('useGlobalShortcuts — Ctrl+/ 面板数据源', () => {
  it('注册表条目在挂载后全部可见(面板不再空白)', async () => {
    const { result } = renderHook(() => useGlobalShortcuts())
    await waitFor(() => expect(result.current.shortcuts.length).toBeGreaterThan(0))
    const keys = result.current.shortcuts.map((s) => s.key)
    expect(keys).toEqual(
      expect.arrayContaining([
        'Ctrl+K',
        'Ctrl+/',
        'Ctrl+Shift+P',
        // 2026-09-22 改绑/新增后必须仍在面板内可见
        'Ctrl+Shift+,',
        'Ctrl+Shift+U',
        'Ctrl+Shift+M',
        'Ctrl+Shift+/',
      ]),
    )
    expect(result.current.shortcuts.every((s) => s.active)).toBe(true)
  })

  it('注册表每条 chord 都有 shortcutHelp.desc 描述键(否则面板回显硬编码中文)', () => {
    const read = (rel: string) => readFileSync(fileURLToPath(new URL(rel, import.meta.url)), 'utf8')
    const registry = [
      ...read('../src/hooks/use-global-shortcuts.ts').matchAll(
        /\{\s*key:\s*'([^']+)'\s*,\s*description:/g,
      ),
    ].map((m) => m[1])
    const mapped = [
      ...read('../src/providers/global-hooks-provider.tsx').matchAll(/'(Ctrl\+[^']+)':\s*'desc\./g),
    ].map((m) => m[1])
    const missing = registry.filter((k) => !mapped.includes(k))
    expect(missing, `缺少 desc 键的 chord:${missing.join(', ')}`).toEqual([])
    expect(registry.length).toBeGreaterThan(10)
  })
})
