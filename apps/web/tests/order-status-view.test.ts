// XUI-001 夹具:订单状态图标/文案取值必须对所有已知状态及未知状态都返回完整视图。
// 改前必红:旧实现 `STATUS_CONFIG[order.status]` 在 refunding/completed/failed 上得到
// undefined,随后 `sc.icon` 抛 TypeError;本用例把该取值路径钉死。
import { describe, expect, it } from 'vitest'
import { resolveOrderStatusView } from '../app/(main)/orders/[id]/PageClient'

const KNOWN = ['pending', 'paid', 'cancelled', 'refunding', 'refunded', 'completed', 'failed']

describe('XUI-001 订单状态视图取值', () => {
  it.each(KNOWN)('已知状态 %s 返回完整视图', (status) => {
    const view = resolveOrderStatusView(status)
    expect(view.icon).toBeTruthy()
    expect(typeof view.cls).toBe('string')
    expect(view.cls.length).toBeGreaterThan(0)
    expect(view.key).not.toBe('status.unknown')
  })

  it('未知/历史状态不得崩溃,落到 status.unknown', () => {
    const view = resolveOrderStatusView('expired')
    expect(view.icon).toBeTruthy()
    expect(typeof view.cls).toBe('string')
    expect(view.key).toBe('status.unknown')
  })
})
