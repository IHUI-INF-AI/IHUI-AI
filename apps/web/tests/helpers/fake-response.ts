/**
 * 假 Response 的**单一出口**(web 测试)。
 *
 * 为什么必须收敛:共享 `@ihui/api-client` 读响应体走 `response.text()` 再 JSON.parse
 * (BUG-13 之后成功路径不再先调 `json()`)。只给 `json()` 的裸对象会直接
 * `TypeError: response.text is not a function`,而各测试各写一份假响应时这种漂移
 * 只能靠全量跑才能发现。这里让 `text()` 与 `json()` 同源于同一个 body 字符串。
 */
export interface FakeResponseInit {
  /** 显式 ok;缺省按 status < 400 推导(与真实 Response 同语义) */
  ok?: boolean
  /** HTTP 状态码,缺省 200 */
  status?: number
  headers?: Record<string, string>
  /** 模拟读体失败(网络中断/流被掐),对应 `response.text()` 抛错分支 */
  textThrows?: boolean
}

export function fakeResponse(body: unknown, init: FakeResponseInit = {}): Response {
  const status = init.status ?? 200
  const ok = init.ok ?? status < 400
  const text = body === undefined ? '' : typeof body === 'string' ? body : JSON.stringify(body)
  return {
    ok,
    status,
    headers: new Headers(init.headers),
    text: async () => {
      if (init.textThrows) throw new TypeError('network error')
      return text
    },
    json: async () => JSON.parse(text),
  } as unknown as Response
}
