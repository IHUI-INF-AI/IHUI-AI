import { describe, expect, it } from 'vitest'

import { vueToNextRedirects } from '../src/config/redirects.config'

/**
 * /login 必须留在「本仓软路由」语义里(打开全局登录弹窗 + 回前一页,并承担
 * ?method=qr&embed=true 的 RN WebView 嵌二维码),不得被 308 永久重定向顶掉。
 * 判据源 = redirects.config.ts 的真实条目,不在此复制一份重定向清单。
 */
describe('/login 不再被重定向到 SSO 授权页', () => {
  const bySource = new Map(vueToNextRedirects.map((r) => [r.source, r.destination]))

  it('redirects 表里不存在 /login 条目', () => {
    expect(bySource.has('/login')).toBe(false)
  })

  it('/sso/login 也不自循环(它是真实页面,不该出现在重定向表)', () => {
    expect(bySource.has('/sso/login')).toBe(false)
  })

  it('/register→/sso/register 保留(本仓无 app/register 路由,摘了会 404)', () => {
    expect(bySource.get('/register')).toBe('/sso/register')
  })
})
