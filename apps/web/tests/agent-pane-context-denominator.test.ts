// 上下文占用百分比的分母:只许取"模型真实容量出口",不许写死数字(D129 同族的量化显示项)。
//
// 为什么用源码级锁而不是渲染断言:这个百分比本身是一行算术,渲染断言只会证明
// "我把同一个数算了两遍";真正会出事的是**分母的来源**被换回一个字面量 ——
// 换回去之后界面照样显示一个看着合理的百分比,没有任何运行时报错,只有拿 32K 模型的人
// 看到"100% 才用了 39%"。这类"账面绿而数值错"的判据只能钉在取材面上。
// 两条断言各有反向对照:把 `128000` 写回去 ⇒ 第一条红;把出口换成别的名字/删掉 ⇒ 第二条红。
import { readFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

import { describe, expect, it } from 'vitest'

// 本文件在 apps/web/tests/ ⇒ 仓库根就是上一级(不是两级;第一版按 monorepo 惯例多跳了一层,
// 三条断言全因 ENOENT 红 —— 路径算错表现成"判据没命中"是最容易误读的一种红)。
const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const PANE = join(ROOT, 'src', 'components', 'ai', 'agent-task-progress-pane.tsx')
const RESUME = join(ROOT, 'src', 'hooks', 'use-chat', 'resume-stream.ts')

describe('上下文占用分母不得写死', () => {
  it('任务进度面板:不得出现硬编码上下文容量(128000 / 128_000)', () => {
    const src = readFileSync(PANE, 'utf8')
    expect(src).not.toMatch(/\/\s*128[_,]?000/)
    expect(src).not.toMatch(/contextUsage\s*=[^;\n]*128\s*_?\s*000/)
  })

  it('任务进度面板:分母必须来自唯一容量出口 getModelContextCapacity', () => {
    const src = readFileSync(PANE, 'utf8')
    expect(src).toMatch(/getModelContextCapacity\s*\(/)
    expect(src).toMatch(/import\s*\{[^}]*getModelContextCapacity[^}]*\}\s*from\s*'@ihui\/api-client'/)
  })

  it('发送侧续传链用同一个出口(两处算同一分母 ⇒ 只许有一份实现)', () => {
    const src = readFileSync(RESUME, 'utf8')
    expect(src).toMatch(/getModelContextCapacity\s*\(/)
    expect(src).not.toMatch(/contextLimit\s*[:=]\s*128[_,]?000/)
  })
})
