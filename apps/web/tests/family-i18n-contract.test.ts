const packCache = new Map<string, Record<string, unknown>>()
function pack(loc: Locale): Record<string, unknown> {
  const hit = packCache.get(loc)
  if (hit) return hit
  const j = JSON.parse(readFileSync(path.join(MESSAGES, `${loc}.json`), 'utf8')) as Record<
    string,
    unknown
  >
  packCache.set(loc, j)
  return j
}

function at(obj: unknown, p: string[]): Record<string, string> | undefined {
  let cur = obj
  for (const seg of p) {
    if (!cur || typeof cur !== 'object') return undefined
    cur = (cur as Record<string, unknown>)[seg]
  }
  return cur as Record<string, string> | undefined
}

/**
 * 精确抽键:先把 `const <变量> = useTranslations('<ns>')` / `getTranslations('<ns>')` 绑成
 * 变量 → 命名空间,再只收"命名空间等于本族 ns"的调用实参。
 * 早期版本用"任意 t('x') + 联合类型成员"的粗正则,会把 `tCommon('close')`(common 命名空间)
 * 和 `| 'c1000'`(错误码字面值,不是键)算进来 ⇒ 一片假红。
 */
function referencedKeys(src: string, famNs: string): Set<string> {
  const varToNs = new Map<string, string>()
  for (const m of src.matchAll(
    /const\s+(\w+)\s*=\s*(?:await\s+)?(?:use|get)Translations\(\s*'([^']+)'\s*\)/g,
  )) {
    varToNs.set(m[1] as string, m[2] as string)
  }
  const keys = new Set<string>()
  const dynRoots = new Set<string>()
  for (const [v, ns] of varToNs) {
    if (ns !== famNs) continue
    for (const m of src.matchAll(new RegExp(`\\b${v}\\(\\s*'([A-Za-z0-9_.]+)'`, 'g')))
      keys.add(m[1] as string)
    // 动态取词 t(`${root}.${x}.leaf`) / t(`${root}Foo`) —— 记根段,孤儿判定对其子树放行
    for (const m of src.matchAll(new RegExp(`\\b${v}\\(\\s*\\\`([A-Za-z0-9_]+)[.$\\\`]`, 'g')))
      dynRoots.add(m[1] as string)
  }
  // 非组件常量表:任何 *Key 字段的值(labelKey / titleKey / descKey… 渲染处 t(x.key) 取词)
  // 允许带点:`scheduling` 族把嵌套路径整体存进表里('weekdays.weekdayMon'),那样扫描器才看得见字面键
  for (const m of src.matchAll(/\b\w*[Kk]ey:\s*'([A-Za-z0-9_.]+)'/g)) keys.add(m[1] as string)
  /**
   * 常量表两种形态:对象表与数组表,且**允许带类型标注**
   * (`const MEAL_TYPE_KEYS: Record<string, string> = { … }` —— 不带这条就会把 16 个在用键误判成孤儿键)。
   */
  for (const block of src.matchAll(/const\s+([A-Z0-9_]*KEYS[A-Z0-9_]*)\s*(?::[^=\n]+)?=\s*\{([\s\S]*?)\n\}/g)) {
    /** 加了"名字"捕获组之后,内容组下标从 1 变成 2 —— 写错会让采集静默变空并把在用键打成孤儿键 */
    for (const m of (block[2] ?? '').matchAll(/:\s*'([A-Za-z0-9_.]+)'/g)) keys.add(m[1] as string)
  }
  for (const block of src.matchAll(/const\s+[A-Z0-9_]*KEYS[A-Z0-9_]*\s*(?::[^=\n]+)?=\s*\[([\s\S]*?)\n\]/g)) {
    for (const m of (block[1] ?? '').matchAll(/'([A-Za-z0-9_.]+)'/g)) keys.add(m[1] as string)
  }
  return new Set([...keys, ...dynRoots])
}

/** 把命名空间子树摊平成 "a.b" → 字符串值(动态根 errorCodes.c1000.meaning 这类走这里) */
function flatLeaves(obj: unknown, prefix = ''): Record<string, string> {
  if (obj === null || typeof obj !== 'object') return prefix ? { [prefix]: String(obj) } : {}
  const acc: Record<string, string> = {}
  for (const [k, v] of Object.entries(obj as Record<string, unknown>)) {
    Object.assign(acc, flatLeaves(v, prefix ? `${prefix}.${k}` : k))
  }
  return acc
}

const HAN = /[一-鿿]/
const ph = (s: string): string => (s.match(/\{[A-Za-z0-9_]+\}/g) ?? []).sort().join(',')

/** 权威调用守门 70(不复刻判据),返回 file → 命中数 */
function gate70Counts(): Map<string, number> {
  const out = path.join(REPO_ROOT, '.ihui-agent/tmp/vitest-zh-scan.json')
  execFileSync(process.execPath, ['scripts/scan-hardcoded-zh.mjs', '--json', out], {
    cwd: REPO_ROOT,
    encoding: 'utf8',
    windowsHide: true,
    stdio: ['ignore', 'ignore', 'ignore'],
    maxBuffer: 64 * 1024 * 1024,
  })
  const parsed = JSON.parse(readFileSync(out, 'utf8')) as {
    files?: Array<{ file: string; count: number }>
  }
  const map = new Map<string, number>()
  for (const row of parsed.files ?? []) map.set(row.file, row.count)
  return map
}

describe.each(FAMILIES)('家族 $name 取词契约', (fam: Family) => {
  const perFile = fam.sources.map((f) => ({
    f,
    keys: referencedKeys(readFileSync(path.join(WEB_ROOT, f), 'utf8'), fam.nsLiteral),
  }))
  const raw = new Set(perFile.flatMap((p) => [...p.keys]))
  const zhLeaves = flatLeaves(at(pack('zh-CN'), fam.nsPath) ?? {})

  /**
   * 动态取词(如 t(`errorCodes.${code}.meaning`))只能按"根段"识别,这里把根段展开成它
   * 在 zh-CN 下的全部叶子 —— 否则会把整棵子树误判成孤儿,也会漏掉逐语言非空校验。
   */
  const referenced = new Set<string>()
  for (const k of raw) {
    if (k in zhLeaves) referenced.add(k)
    else
      for (const leaf of Object.keys(zhLeaves)) if (leaf.startsWith(`${k}.`)) referenced.add(leaf)
  }

  it('哨兵:引用键数量达到下限(整体改动丢失时这里先红)', () => {
    expect(
      referenced.size,
      `${fam.name} 只解析到 ${referenced.size} 个取词键`,
    ).toBeGreaterThanOrEqual(fam.minReferenced)
  })

  it('引用的每个键在五语言包该命名空间下都有非空值', () => {
    for (const loc of LOCALES) {
      const leaves = flatLeaves(at(pack(loc), fam.nsPath) ?? {})
      const missing = [...referenced].filter(
        (k) => typeof leaves[k] !== 'string' || leaves[k] === '',
      )
      expect(
        missing,
        `${loc}.${fam.nsPath.join('.')} 缺键 ${missing.slice(0, 8).join(', ')}`,
      ).toEqual([])
    }
  })

  it('命名空间键集合五语言完全一致(族内 parity)', () => {
    const base = Object.keys(zhLeaves).sort()
    expect(base.length).toBeGreaterThanOrEqual(fam.minReferenced)
    for (const loc of LOCALES) {
      expect(
        Object.keys(flatLeaves(at(pack(loc), fam.nsPath) ?? {})).sort(),
        `${loc} 键集合漂移`,
      ).toEqual(base)
    }
  })

  it('键名不含点号(next-intl 字面含点键永不渲染)', () => {
    const bad: string[] = []
    const walk = (o: unknown, p: string[]) => {
      if (!o || typeof o !== 'object') return
      for (const [k, v] of Object.entries(o as Record<string, unknown>)) {
        if (k.includes('.')) bad.push([...p, k].join('.'))
        walk(v, [...p, k])
      }
    }
    walk(at(pack('zh-CN'), fam.nsPath), fam.nsPath)
    expect(bad, `${fam.name} 出现含点键`).toEqual([])
  })

  it('ko/en 值无汉字,且 ICU 占位符各语言逐一保留', () => {
    for (const loc of ['ko', 'en'] as Locale[]) {
      const leaves = flatLeaves(at(pack(loc), fam.nsPath) ?? {})
      for (const k of Object.keys(zhLeaves)) {
        expect(HAN.test(leaves[k] ?? ''), `${loc}.${k} 含汉字: ${leaves[k]}`).toBe(false)
      }
    }
    for (const loc of LOCALES) {
      const leaves = flatLeaves(at(pack(loc), fam.nsPath) ?? {})
      for (const k of Object.keys(zhLeaves)) {
        expect(ph(leaves[k] ?? ''), `${loc}.${k} 占位符漂移`).toBe(ph(zhLeaves[k] ?? ''))
      }
    }
  })

  it('族内不存在"语言包有、源码不引用"的孤儿键', () => {
    const unused = Object.keys(zhLeaves)
      .filter((k) => !referenced.has(k))
      .sort()
    expect(unused, `${fam.name} 孤儿键 ${unused.join(', ')} —— 要么补引用要么删键`).toEqual([])
  })

  it('守门 70 实测:族内源码文件命中全部归零(直接调权威脚本,不复刻判据)', () => {
    const counts = gate70Counts()
    const bad = fam.sources
      .map((f) => ({ f, n: counts.get(`apps/web/${f}`) ?? 0 }))
      .filter((r) => r.n > 0)
    expect(bad, `仍有硬编码中文:${bad.map((b) => `${b.f}=${b.n}`).join(' ')}`).toEqual([])
  })
})

