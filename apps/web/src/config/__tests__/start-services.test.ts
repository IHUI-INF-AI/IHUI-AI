import { describe, expect, it } from 'vitest'

import { getCapability } from '@ihui/shared/capabilities'

import { START_SERVICES, START_SERVICE_COUNT } from '../start-services'
import { vueToNextRedirects } from '../redirects.config'

describe('总管工作台八卡配置', () => {
  it('恰好八张服务卡，导出的计数一致', () => {
    expect(START_SERVICES).toHaveLength(8)
    expect(START_SERVICE_COUNT).toBe(START_SERVICES.length)
  })

  it('id 与 capabilityIds 都不重复', () => {
    const ids = START_SERVICES.map((s) => s.id)
    const capabilityIds = START_SERVICES.flatMap((s) => s.capabilityIds)
    expect(new Set(ids).size).toBe(ids.length)
    expect(new Set(capabilityIds).size).toBe(capabilityIds.length)
  })

  it('落点唯一且都是站内绝对路径', () => {
    const hrefs = START_SERVICES.map((s) => s.href)
    expect(new Set(hrefs).size).toBe(hrefs.length)
    for (const href of hrefs) expect(href.startsWith('/')).toBe(true)
  })

  it('每张卡先上 UI 面，agentTool 与主能力一致', () => {
    for (const service of START_SERVICES) {
      expect(service.surfaces).toContain('web')
      const primary = getCapability(service.capabilityIds[0] ?? '')
      expect(service.agentTool).toBe(primary?.agentTool ?? null)
    }
  })

  it('/start 的跳转由页面自身负责，不写进 redirects 配置', () => {
    expect(vueToNextRedirects.some((r) => r.source === '/start')).toBe(false)
  })

  it('八张卡挂的 capabilityIds 都在能力目录里，且不是 planned', () => {
    for (const service of START_SERVICES) {
      expect(service.capabilityIds.length).toBeGreaterThan(0)
      for (const capabilityId of service.capabilityIds) {
        const capability = getCapability(capabilityId)
        expect(capability?.id).toBe(capabilityId)
        expect(capability?.status).not.toBe('planned')
      }
    }
  })
})
