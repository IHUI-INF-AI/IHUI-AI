import { fetchApi } from '@/lib/api'

/**
 * Best-of-N 前端 API 客户端(W23,2026-09-14 立,对标 Cursor 多副本自动评审择优)。
 *
 * 服务端契约(apps/ai-service 的 routers/best_of_n.py,已挂载到 /api):
 *  - POST /api/best-of-n/run  body { messages, n } → BestOfNResult(candidates + winner + rationale)
 *
 * 响应统一用 ApiResult 包装,成功时 data 为对应结构体。
 */

/** 单个候选的执行与评审结果(与后端 CandidateResult.to_dict() 对齐) */
export interface BestOfCandidate {
  candidate_id: number
  content: string
  model: string
  ok: boolean
  error: string
  /** 评审分(0-100);n=1 或评审兜底时为 null */
  score: number | null
  score_reason?: string
  latency_ms: number
  tokens_in?: number
  tokens_out?: number
  cost_usd?: number
}

/** POST /api/best-of-n/run 响应(与后端 BestOfNResult.to_dict() 对齐) */
export interface BestOfNResultData {
  winner: BestOfCandidate
  candidates: BestOfCandidate[]
  nRequested: number
  evaluatorModel: string
  evaluatorFallback: boolean
  rationale: string
  totalCostUsd: number
  runId: string
}

/** 运行 Best-of-N:同任务 N 副本并行执行 + LLM 评审自动择优 */
export async function runBestOfN(task: string, n = 3, model?: string): Promise<BestOfNResultData> {
  const r = await fetchApi<BestOfNResultData>('/api/best-of-n/run', {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({
      messages: [{ role: 'user', content: task }],
      n,
      ...(model ? { model } : {}),
    }),
    // N 副本同步执行 + 评审,耗时可达分钟级,放大超时
    timeoutMs: 180_000,
  })
  if (!r.success) throw new Error(r.error || 'Best-of-N 执行失败')
  return r.data
}
