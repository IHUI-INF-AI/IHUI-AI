import { fetchApi } from '@/lib/api'

/**
 * 上下文压缩感知(P0-6)前端 API 客户端(2026-09-03 立)。
 *
 * 服务端契约(apps/ai-service 的 routers/context_compaction.py,已挂载到 /api):
 *  - GET /api/context-compaction?session_id=...     → 该会话被 LLM 语义压缩的历史(时间倒序 + 总次数)
 *
 * 响应统一用 ApiResult 包装,成功时 data 为对应结构体。
 */

/** 单条压缩历史记录(字段与后端 record_compaction 对齐) */
export interface CompactionRecord {
  compaction_id: string
  session_id: string
  original_tokens: number
  compressed_tokens: number
  saved_tokens: number
  saved_ratio: number
  summary: string
  trigger: string
  user_id?: string
  compacted_at: number
  metadata?: Record<string, unknown>
}

/** GET /api/context-compaction 响应 */
export interface CompactionHistoryResult {
  session_id: string
  total: number
  compactions: CompactionRecord[]
}

/** 列出指定会话的上下文压缩历史 */
export async function listCompactionHistory(
  sessionId: string,
  limit = 50,
): Promise<CompactionHistoryResult> {
  const qs = new URLSearchParams()
  qs.set('session_id', sessionId)
  if (limit > 0) qs.set('limit', String(limit))
  const r = await fetchApi<CompactionHistoryResult>(
    `/api/context-compaction?${qs.toString()}`,
  )
  if (!r.success) throw new Error(r.error || '加载压缩历史失败')
  return r.data
}
