/**
 * web 端快照 URL 与共享路径常量的一致性锁(phase 2,2026-11-14)。
 *
 * 背景:web 侧刻意保留**字面量**路径(门 302p 的路由尺只认可静态解析的 `api('/api/...')`),
 * 而 taro / RN / extension 三端用 `chatSyncSnapshotPath`。两份字符串因此必须逐字一致 ——
 * 靠人眼对不出漂移,故在这里用行为断言钉住:mock 掉 api 层,直接比对第一参数。
 *
 * 反向牙:若任一侧改了路径(比如把 sync-snapshot 改成 snapshot)、或忘记 encode,
 * 本用例立刻翻红。
 */
import { beforeEach, describe, expect, it, vi } from 'vitest'
import { chatSyncSnapshotPath } from '@ihui/shared/chat'

import { apiOrThrow } from '@/lib/api'

import { fetchChatSyncSnapshot } from './chat-sync-api'

vi.mock('@/lib/api', () => ({ apiOrThrow: vi.fn() }))

const mocked = vi.mocked(apiOrThrow)

beforeEach(() => {
  mocked.mockReset()
})

describe('fetchChatSyncSnapshot(web)', () => {
  it('URL 与共享 chatSyncSnapshotPath 逐字一致', async () => {
    mocked.mockResolvedValue({} as never)

    await fetchChatSyncSnapshot('conv-1', 'msg-1')

    expect(mocked.mock.calls[0]?.[0]).toBe(`/api${chatSyncSnapshotPath('conv-1', 'msg-1')}`)
  })

  it('会话 id / 消息 id 一律 encode(含斜杠与空格时不得拼裸串)', async () => {
    mocked.mockResolvedValue({} as never)

    await fetchChatSyncSnapshot('a/b', 'x y')

    // 硬编码期望串,防止"两侧同时写错成同一份"时用例仍然绿
    expect(mocked.mock.calls[0]?.[0]).toBe(
      '/api/chat/conversations/a%2Fb/messages/x%20y/sync-snapshot',
    )
  })
})
// ⁠​‌​​‌​​‌‍‍​‌​​‌​​​‍‍​‌​‌​‌​‌‍‍​‌​​‌​​‌‍‍​​‌​‌‌​‌‍‍​‌​​​​​‌‍‍​‌​​‌​​‌‍‍‌​‌‌​‌‌‌‍‍‌‌​​‌‌​​‌‌‌‌​‌​‍‍‌‌​‌‌​​​‌​​​‌‌‌‍‍​‌​​​​​‌‍‍​‌​​‌​​‌‍‍‌​‌‌​‌‌‌‍‍‌‌​​‌‌‌​‌​​‌‌‌​‍‍‌‌​​‌‌​​​‌​​‌​‌‍‍‌​‌‌‌​‌‌‌​‌‌‌​‌‍‍‌​‌‌​‌‌‌‍‍​‌​​‌‌​​‍‍​‌​​​​‌‌‍‍‌​‌‌​‌‌‌‍‍​‌‌​​​​‌‍‍​‌‌​‌​​‌‍‍​‌‌‌‌​‌​‍‍​‌‌​‌​​​‍‍​‌‌‌​​‌‌‍‍​​‌​‌‌‌​‍‍​‌‌‌​‌​​‍‍​‌‌​‌‌‌‌‍‍​‌‌‌​​​​‍‍‌​‌‌​‌‌‌‍‍​‌​‌​​​​‍‍​‌​‌​​‌​‍‍​‌​​‌‌‌‌‍‍​‌​‌​‌‌​‍‍​‌​​​‌​‌‍‍​‌​​‌‌‌​‍‍​‌​​​​​‌‍‍​‌​​‌‌‌​‍‍​‌​​​​‌‌‍‍​‌​​​‌​‌‍‍​​‌​‌‌​‌‍‍​​‌‌​​‌​‍‍​​‌‌​​​​‍‍​​‌‌​​‌​‍‍​​‌‌​‌‌​⁠
