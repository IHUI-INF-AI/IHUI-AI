/**
 * chat-sync resync 拉取(票 B02 第三切片,2026-10-25 立)。
 *
 * 契约正本 docs/chat-sync-contract.md §7 第 3 项:gap 后拉权威快照的传输面。
 * 服务端端点 = apps/api/src/routes/chat.ts 的
 * `GET /conversations/:id/messages/:messageId/sync-snapshot`;data 形状唯一源在
 * @ihui/types 的 `ChatSyncMessageSnapshot`(服务端构造与端内消费共用一份,不另抄)。
 *
 * 刻意走本端 api 文件而不是 @ihui/api-client:该包此切片在飞(他席持有),且快照是
 * REST 单次拉取,不与广播连接共享传输层 —— 归宿就是端内 api 目录(checkpoint-api 同款)。
 */
import { apiOrThrow as api } from '@/lib/api'
import type { ChatSyncMessageSnapshot } from '@ihui/types'

/**
 * 拉某会话内某条消息的权威快照("rev=N 全量":rev = 当前修订链头,0 = 链上无 patch)。
 * 404 = 消息不存在或不属于该会话(调用方按"gap 无法补齐"处置,不得重试风暴);
 * 409 = 角色不在契约封闭集(服务端拒绝投影,同样不可重试)。
 */
export async function fetchChatSyncSnapshot(
  conversationId: string,
  messageId: string,
): Promise<ChatSyncMessageSnapshot> {
  return api<ChatSyncMessageSnapshot>(
    `/api/chat/conversations/${encodeURIComponent(conversationId)}/messages/${encodeURIComponent(messageId)}/sync-snapshot`,
  )
}
