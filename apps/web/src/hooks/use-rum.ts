'use client'

/**
 * 根级 RUM 副作用 hook（在 GlobalHooksProvider 挂载一次）。
 *
 * 职责：
 * - 启动 30s 定时 flush（未同意时 collector.start() 不建定时器）；
 * - 采集首屏/启动指标（性能取数口径见 lib/rum/startup.ts）；
 * - 安装未捕获异常监听（不 preventDefault，不吞业务异常）；
 * - 同意开关变化时立即启停；
 * - 页面隐藏时主动 flush 一次，降低丢掉最后一批的概率。
 */

import * as React from 'react'

import { getRumCollector, installStartupRum } from '@/lib/rum'
import { onRumConsentChange } from '@/lib/rum/consent'

export function useRum(): void {
  React.useEffect(() => {
    const collector = getRumCollector()
    collector.start()
    const cleanupStartup = installStartupRum(collector)
    const cleanupErrorHandlers = collector.installGlobalErrorHandlers()
    const unsubscribeConsent = onRumConsentChange((granted) => {
      if (granted) {
        collector.start()
      } else {
        collector.stop()
      }
    })
    const onVisibilityChange = () => {
      if (document.visibilityState === 'hidden') void collector.flush()
    }
    document.addEventListener('visibilitychange', onVisibilityChange)
    return () => {
      cleanupStartup()
      cleanupErrorHandlers()
      unsubscribeConsent()
      document.removeEventListener('visibilitychange', onVisibilityChange)
    }
  }, [])
}
