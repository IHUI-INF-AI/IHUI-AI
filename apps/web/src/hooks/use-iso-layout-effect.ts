'use client'

import * as React from 'react'

/**
 * isomorphic layout effect:客户端用 useLayoutEffect(hydration 后、浏览器 paint 前执行,
 * setState 触发的重渲染对用户不可见),SSR 用 useEffect(规避 React useLayoutEffect SSR 警告)。
 *
 * 单一真相源(AGENTS.md §0.6):本定义此前是 `hooks/use-media-query.ts` 的私有常量,
 * 第二个消费方(TagsView 的 addTag)需要同一语义时**导出复用**,不得再抄一份三元表达式。
 *
 * 什么时候该用它:凡是「首帧渲染出来、但正确答案要等挂载后才算得出」的客户端状态,
 * 且该状态会改变几何(位置/尺寸)而不是只改颜色或文案 —— 用 useEffect 会先按错误几何
 * paint 一帧,那一帧就是一条 layout-shift(CLS);用本 hook 则纠正发生在 paint 之前,CLS 为 0。
 * 反例:只改 className 颜色/文案、不改几何的,用 useEffect 即可,不必升级。
 */
export const useIsoLayoutEffect =
  typeof window !== 'undefined' ? React.useLayoutEffect : React.useEffect
