// D113 onToolDelta 工厂行为测试:覆盖式写入 partialDiff(重放幂等)+ 空 toolCallId 丢弃
import { describe, expect, it, vi, beforeEach } from 'vitest'

const updateToolCall = vi.fn()
vi.mock('@/stores/chat', () => ({
  useChatStore: { getState: () => ({ updateToolCall }) },
}))

import { createToolDeltaHandler } from '../stream-handlers'

const evt = (over: Partial<{ toolCallId: string; seq: number; partialText: string }> = {}) => ({
  toolCallId: 'tc-1',
  seq: 1,
  partialText: 'line1\nline2',
  ...over,
})

describe('createToolDeltaHandler — D113 流中 diff 预览', () => {
  beforeEach(() => updateToolCall.mockClear())

  it('写入 (messageId, toolCallId, { partialDiff })', () => {
    createToolDeltaHandler('m1')(evt())
    expect(updateToolCall).toHaveBeenCalledWith('m1', 'tc-1', { partialDiff: 'line1\nline2' })
  })

  it('同 toolCallId 二次到达 → 覆盖式更新(重放/乱序安全,seq 不参与判断)', () => {
    const h = createToolDeltaHandler('m1')
    h(evt({ seq: 1, partialText: 'v1' }))
    h(evt({ seq: 2, partialText: 'v1\nv2' }))
    expect(updateToolCall).toHaveBeenLastCalledWith('m1', 'tc-1', { partialDiff: 'v1\nv2' })
    expect(updateToolCall).toHaveBeenCalledTimes(2)
  })

  it('空 toolCallId → 丢弃,零写入', () => {
    createToolDeltaHandler('m1')(evt({ toolCallId: '' }))
    expect(updateToolCall).not.toHaveBeenCalled()
  })
})
