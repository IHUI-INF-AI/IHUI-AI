// @vitest-environment jsdom
// 票60 步序四(2026-10-20):发送链路按 store 实例化。
// 咬一件事:createSendMessage 收到哪个 store,就把运行时注册落到哪个实例 ——
// 传窗格实例时不污染单例;不传时仍默认单例(既有行为不变)。

import { describe, expect, it } from 'vitest'

import { createChatStore, useChatStore } from '@/stores/chat'
import { getStreamRuntime } from '../stream-runtime'
import { createSendMessage } from '../send-message'
import { createSendAnswer } from '../send-answer'
import type { ChatActionContext } from '../types'

function makeCtx(): ChatActionContext {
  return {
    t: (key) => key,
    router: {} as ChatActionContext['router'],
    queryClient: {} as ChatActionContext['queryClient'],
    setFallbackNotice: () => {},
    abortRef: { current: null },
    lastSentContentRef: { current: '' },
    lastSentAnswerRef: { current: null },
    sendInFlightRef: { current: false },
    streamGenerationRef: { current: 0 },
    streamConversationRef: { current: null },
  }
}

describe('发送链路按窗格 store 实例化', () => {
  it('传入窗格实例时运行时注册落到该实例,不污染单例', () => {
    const paneStore = createChatStore('ihui-chat-pane-send-chain-test')
    const ctx = makeCtx()

    const send = createSendMessage(ctx, paneStore)
    const paneRuntime = getStreamRuntime(paneStore)

    expect(paneRuntime.sendInstance).toBe(send)
    expect(paneRuntime.actionCtx).toBe(ctx)
    expect(getStreamRuntime(useChatStore).sendInstance).not.toBe(send)
  })

  it('不传 store 时默认单例', () => {
    const ctx = makeCtx()

    const send = createSendMessage(ctx)

    expect(getStreamRuntime(useChatStore).sendInstance).toBe(send)
  })

  it('createSendAnswer 同样接受窗格实例,默认仍单例', () => {
    const paneStore = createChatStore('ihui-chat-pane-send-answer-test')
    const ctx = makeCtx()

    expect(typeof createSendAnswer(ctx, paneStore)).toBe('function')
    expect(typeof createSendAnswer(ctx)).toBe('function')
  })
})
