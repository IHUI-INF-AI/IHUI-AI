/**
 * pool-model-routing 测试(2026-11-22 立):登记集与快照读出。
 * isPoolModelId 的判定行为此前由 send-message 分流契约间接覆盖;本文件补
 * rememberPoolModelIds → listPoolModelIds → isPoolModelId 的闭环,并钉住
 * "auto 决策腿候选来自登记集"这一数据源(listPoolModelIds 是它唯一出口)。
 */

import { beforeEach, describe, expect, it } from 'vitest'

import { isPoolModelId, listPoolModelIds, rememberPoolModelIds } from '../pool-model-routing'

beforeEach(() => {
  window.sessionStorage.clear()
  // 模块级单例:重复登记幂等,清不掉已存项 —— 用一次空登记无法重置,
  // 故各用例只依赖"追加"语义,不依赖空态。
})

describe('pool-model-routing 登记集', () => {
  it('登记后 isPoolModelId 命中,listPoolModelIds 返回同一集合', () => {
    rememberPoolModelIds(['cursor/composer-2.5', 'doubao/doubao-seed-2.1'])
    expect(isPoolModelId('cursor/composer-2.5')).toBe(true)
    expect(listPoolModelIds()).toEqual(
      expect.arrayContaining(['cursor/composer-2.5', 'doubao/doubao-seed-2.1']),
    )
  })

  it('重复登记幂等,快照不出现重复 id', () => {
    rememberPoolModelIds(['cursor/composer-2.5'])
    rememberPoolModelIds(['cursor/composer-2.5'])
    const ids = listPoolModelIds()
    expect(ids.filter((id) => id === 'cursor/composer-2.5')).toHaveLength(1)
  })

  it('空数组登记是 no-op,不写 sessionStorage', () => {
    const before = window.sessionStorage.getItem('ihui.poolModelIds.v1')
    rememberPoolModelIds([])
    expect(window.sessionStorage.getItem('ihui.poolModelIds.v1')).toBe(before)
  })

  it('auto 字面量永远不在号池登记集(决策腿 channel 字段才是分流判据)', () => {
    rememberPoolModelIds(['cursor/composer-2.5'])
    expect(isPoolModelId('auto')).toBe(false)
  })
})
