/**
 * pool-model-routing.ts — 号池模型 id 的登记与判定(2026-11-14 立)。
 *
 * 为什么需要:模型选择器把「我的号池」模型(如 `cursor/composer-2.5`)与
 * ai-service 的平台模型混在同一份列表里;发送时必须区分 —— 号池模型要走
 * `/ws/relay/chat`,不能交给 ai-service 的 litellm(litellm 未映射这些平台厂商,
 * 会报 `Unmapped LLM provider ... custom_llm_provider=cursor`)。
 *
 * 判定只认「选择器实际从 /api/account-pool/models 拿到过的 id」,不做前缀猜测:
 * `doubao/…`、`codex/…` 这类前缀同时存在于 ai-service 目录,猜测会把平台模型误路由。
 *
 * 存储用 sessionStorage:同标签页刷新后仍能判定(模型选择器尚未重新拉取时也能发),
 * 关标签页即失效 —— 号池模型随账号变化,跨会话持久化反而会留下已失效的 id。
 */

const STORAGE_KEY = 'ihui.poolModelIds.v1'

const poolModelIds: Set<string> = load()

function load(): Set<string> {
  try {
    if (typeof window === 'undefined') return new Set()
    const raw = window.sessionStorage.getItem(STORAGE_KEY)
    if (!raw) return new Set()
    const parsed: unknown = JSON.parse(raw)
    if (!Array.isArray(parsed)) return new Set()
    return new Set(parsed.filter((v): v is string => typeof v === 'string' && v.length > 0))
  } catch {
    return new Set()
  }
}

/** 由模型选择器在拿到号池列表后调用(重复调用幂等)。 */
export function rememberPoolModelIds(ids: readonly string[]): void {
  if (ids.length === 0) return
  let changed = false
  for (const id of ids) {
    if (typeof id === 'string' && id && !poolModelIds.has(id)) {
      poolModelIds.add(id)
      changed = true
    }
  }
  if (!changed) return
  try {
    if (typeof window !== 'undefined') {
      window.sessionStorage.setItem(STORAGE_KEY, JSON.stringify([...poolModelIds]))
    }
  } catch {
    /* 隐私模式/配额满:内存态仍可用,不阻断发送 */
  }
}

/** 该模型 id 是否来自「我的号池」(决定本轮走 WS 号池长连接)。 */
export function isPoolModelId(model: string): boolean {
  return poolModelIds.has(model)
}
