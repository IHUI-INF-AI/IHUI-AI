'use client'

import * as React from 'react'
import { useTranslations } from 'next-intl'

import type { AgentStatus, BackgroundAgent } from '@/components/ai/types'

const NAME_MAX = 40

/**
 * 弹一条后台任务终态桌面通知。
 * 仅在「已授权 + 页面不可见」时弹,点击通知聚焦窗口;未授权时静默,不主动骚扰权限。
 */
function notify(title: string, body: string): void {
  if (typeof window === 'undefined' || !('Notification' in window)) return
  if (Notification.permission !== 'granted' || document.visibilityState === 'visible') return
  try {
    const notification = new Notification(title, { body, icon: '/favicon.ico' })
    notification.onclick = () => {
      window.focus()
      notification.close()
    }
  } catch {
    // 部分浏览器在 iframe 中禁用通知 API,静默降级
  }
}

/**
 * 后台任务 running → completed/failed 时发桌面通知。
 * 对比上一帧状态,只在终态跳变时触发一次。
 */
export function useBackgroundAgentNotify(agents: BackgroundAgent[]): void {
  const t = useTranslations('ai.backgroundAgents')
  const prevRef = React.useRef<Map<string, AgentStatus>>(new Map())

  React.useEffect(() => {
    const current = new Map<string, AgentStatus>()
    for (const agent of agents) {
      const prev = prevRef.current.get(agent.agent_id)
      current.set(agent.agent_id, agent.status)
      if (prev !== 'running' || (agent.status !== 'completed' && agent.status !== 'failed'))
        continue
      notify(
        t(agent.status === 'completed' ? 'notifyCompletedTitle' : 'notifyFailedTitle', {
          name: agent.prompt.slice(0, NAME_MAX),
        }),
        agent.result?.output ?? agent.error ?? '',
      )
    }
    prevRef.current = current
  }, [agents, t])
}
