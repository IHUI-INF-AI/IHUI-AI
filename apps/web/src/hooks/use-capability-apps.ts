'use client'

import * as React from 'react'

import { deleteCapabilityApp, listCapabilityApps, saveCapabilityApp } from '@ihui/api-client'
import type { CapabilityAppRecord } from '@ihui/types'

/**
 * 能力应用前端状态(2026-11-13 立)
 *
 * 与 use-plugins 同一套路:本地状态 + 共享 client,写操作成功后才回填服务端记录
 * (应用定义是内容,不做乐观更新 —— 渲染一份尚未落库的定义会让用户以为"已保存")。
 */
export interface UseCapabilityAppsReturn {
  apps: CapabilityAppRecord[]
  authenticated: boolean
  loading: boolean
  error: string | null
  refresh: () => Promise<void>
  save: (app: CapabilityAppRecord) => Promise<CapabilityAppRecord>
  remove: (id: string) => Promise<boolean>
}

export function useCapabilityApps(): UseCapabilityAppsReturn {
  const [apps, setApps] = React.useState<CapabilityAppRecord[]>([])
  const [authenticated, setAuthenticated] = React.useState(false)
  const [loading, setLoading] = React.useState(true)
  const [error, setError] = React.useState<string | null>(null)

  const refresh = React.useCallback(async () => {
    setLoading(true)
    setError(null)
    try {
      const data = await listCapabilityApps()
      setApps(data.apps)
      setAuthenticated(data.authenticated)
    } catch (err) {
      setApps([])
      setAuthenticated(false)
      setError(err instanceof Error ? err.message : '加载失败')
    } finally {
      setLoading(false)
    }
  }, [])

  React.useEffect(() => {
    void refresh()
  }, [refresh])

  const save = React.useCallback(async (app: CapabilityAppRecord) => {
    const saved = await saveCapabilityApp(app)
    setApps((prev) => {
      const next = prev.filter((item) => item.id !== saved.id)
      return [saved, ...next].sort((a, b) => b.updatedAt.localeCompare(a.updatedAt))
    })
    return saved
  }, [])

  const remove = React.useCallback(async (id: string) => {
    try {
      await deleteCapabilityApp(id)
      setApps((prev) => prev.filter((item) => item.id !== id))
      return true
    } catch {
      return false
    }
  }, [])

  return { apps, authenticated, loading, error, refresh, save, remove }
}
