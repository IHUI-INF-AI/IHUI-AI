import type { AgentHookRunEvent } from '@ihui/shared'

/**
 * 会话级钩子运行累计(2026-11-21 第 38 项)。
 *
 * 为什么要有它:`hookRuns` 是 50 条 FIFO,面板只呈现"最近一帧";一次会话里跑了
 * 200 次钩子、其中 3 次超时,滚动窗口会把早期失败挤掉,看起来"全部正常"。
 * 本累计只做加法、不落事件、不改写既有帧 —— 与 `hookRuns` 是同一份输入的两个视图,
 * 不是第二份真相源。
 */
export interface HookRunStats {
  /** 逐钩子条目数(不是帧数:一帧可含多枚钩子) */
  total: number
  ok: number
  timeout: number
  error: number
  /** 全部条目耗时总和(ms),用于算均值 */
  totalDurationMs: number
  /** 单条最长耗时(ms),用于发现"某枚钩子从 3ms 变 900ms" */
  slowestMs: number
}

export const EMPTY_HOOK_RUN_STATS: HookRunStats = {
  total: 0,
  ok: 0,
  timeout: 0,
  error: 0,
  totalDurationMs: 0,
  slowestMs: 0,
}

export function accumulateHookRunStats(
  prev: HookRunStats,
  event: AgentHookRunEvent,
): HookRunStats {
  let { total, ok, timeout, error, totalDurationMs, slowestMs } = prev
  for (const hook of event.hooks) {
    total += 1
    totalDurationMs += Math.max(0, hook.durationMs)
    slowestMs = Math.max(slowestMs, hook.durationMs)
    if (hook.status === 'ok') ok += 1
    else if (hook.status === 'timeout') timeout += 1
    else error += 1
  }
  return { total, ok, timeout, error, totalDurationMs, slowestMs }
}

/** 均值:total=0 时返回 0(不返回 NaN,面板不该出现 NaNms)。 */
export function hookRunStatsAverageMs(stats: HookRunStats): number {
  return stats.total > 0 ? Math.round(stats.totalDurationMs / stats.total) : 0
}
