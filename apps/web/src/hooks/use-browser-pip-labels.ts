'use client'

import { useTranslations } from 'next-intl'

import type { BrowserPipLabels } from '@/lib/browser-pip'

/**
 * 画中画浮窗的文案包 —— 2026-11-24 立。
 *
 * 浮窗是独立 document,next-intl 的 React 上下文进不去,只能把译文当数据传进去;
 * 这里做唯一的"译文 → 浮窗 label"装配点,主面板与 AI 菜单共用,避免两处各拼一份。
 */
export function useBrowserPipLabels(): BrowserPipLabels {
  const t = useTranslations('aiChat.pictureInPicture')
  return {
    title: t('title'),
    emptyState: t('emptyState'),
    readOnly: t('readOnly'),
    handover: t('handover'),
    connecting: t('statusConnecting'),
    running: t('statusRunning'),
    waiting: t('statusWaiting'),
    gate: t('statusGate'),
    error: t('statusError'),
    stalled: (seconds: number) => t('statusStalled', { seconds }),
    tooSmall: t('tooSmall'),
    checkpointProgress: (done: number, total: number) =>
      t('checkpointProgress', { done, total }),
    checkpointWaiting: (label: string) => t('checkpointWaiting', { label }),
    continueLabel: t('continueLabel'),
    taskFailed: t('taskFailed'),
  }
}
