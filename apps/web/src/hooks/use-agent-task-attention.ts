'use client'

/**
 * use-agent-task-attention — 把后台任务运行态投影到左侧会话行。
 *
 * 数据源仍是既有 `/api/workspace/agent/tasks`，不新建任务表；
 * 只有带 conversationId 的运行中任务会出现在会话列表的注意力徽标里。
 * 5 秒轮询是轻量的：该接口只返回当前用户内存态任务，不读全量历史。
 */

import * as React from 'react'

import { fetchApi } from '@/lib/api'
import type { AgentTaskView } from '@/lib/agent-task-view'
import {
  buildConversationTaskAttention,
  normalizeTaskList,
  type ConversationTaskAttentionById,
} from '@/lib/task-view-model'
import { useAuthStore } from '@/stores/auth'

const POLL_MS = 5_000

function sameAttention(
  a: ConversationTaskAttentionById,
  b: ConversationTaskAttentionById,
): boolean {
  const aKeys = Object.keys(a)
  const bKeys = Object.keys(b)
  if (aKeys.length !== bKeys.length) return false
  return aKeys.every((key) => {
    const left = a[key]
    const right = b[key]
    return (
      Boolean(left?.running) === Boolean(right?.running) &&
      Boolean(left?.waiting) === Boolean(right?.waiting) &&
      (left?.unread ?? 0) === (right?.unread ?? 0)
    )
  })
}

export function useAgentTaskAttention(): ConversationTaskAttentionById {
  const isAuthenticated = useAuthStore((state) => state.isAuthenticated)
  const [attention, setAttention] = React.useState<ConversationTaskAttentionById>({})

  React.useEffect(() => {
    if (!isAuthenticated || typeof window === 'undefined') {
      setAttention((current) => (Object.keys(current).length === 0 ? current : {}))
      return
    }

    let cancelled = false
    let inFlight = false

    const tick = async () => {
      if (inFlight) return
      inFlight = true
      try {
        const res = await fetchApi<{ tasks: Record<string, AgentTaskView> }>(
          '/api/workspace/agent/tasks',
        )
        if (cancelled || !res.success) return
        const tasks = normalizeTaskList(Object.values(res.data?.tasks ?? {}), {
          mergeByConversation: true,
        })
        const next = buildConversationTaskAttention(tasks)
        setAttention((current) => (sameAttention(current, next) ? current : next))
      } catch {
        // 轮询失败不清空既有状态，避免网络抖动导致徽标闪烁。
      } finally {
        inFlight = false
      }
    }

    void tick()
    const timer = window.setInterval(() => void tick(), POLL_MS)
    return () => {
      cancelled = true
      window.clearInterval(timer)
    }
  }, [isAuthenticated])

  return attention
}
