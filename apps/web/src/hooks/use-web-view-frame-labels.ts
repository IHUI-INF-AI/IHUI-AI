import { useMemo } from 'react'
import { useTranslations } from 'next-intl'
import type { WebViewFrameLabels } from '@ihui/ui-react'

/**
 * WebViewFrame 界面文案注入(简体中文以外的界面由此本地化)。
 *
 * `@ihui/ui-react` 不引 next-intl(被多端共用),组件内只留
 * DEFAULT_WEB_VIEW_FRAME_LABELS 中文兜底;消费端必须传 labels,
 * 否则非中文界面整块回显中文。
 */
export function useWebViewFrameLabels(): WebViewFrameLabels {
  const t = useTranslations('webviewFrame')
  return useMemo<WebViewFrameLabels>(
    () => ({
      loadingText: t('loadingText'),
      screenshotNotice: t('screenshotNotice'),
      blockedTitle: t('blockedTitle'),
      failedTitle: t('failedTitle'),
      externalTitle: t('externalTitle'),
      retry: t('retry'),
      openExternal: t('openExternal'),
      idlePlaceholder: t('idlePlaceholder'),
    }),
    [t],
  )
}
