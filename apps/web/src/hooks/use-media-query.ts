'use client'

import * as React from 'react'

/**
 * isomorphic layout effect:客户端用 useLayoutEffect(hydration 后、浏览器 paint 前执行,
 * setState 触发的重渲染对用户不可见),SSR 用 useEffect(规避 React useLayoutEffect SSR 警告)。
 */
const useIsoLayoutEffect = typeof window !== 'undefined' ? React.useLayoutEffect : React.useEffect

/** 响应式媒体查询,SSR 安全(默认返回 false)。
 *  2026-09-09:useEffect → isomorphic layout effect。
 *  原实现 hydration 后在 useEffect 里 setState,重渲染发生在 paint 之后 —— 依赖本 hook 的
 *  组件(如 Sidebar footerCollapsed)会先以错误布局 paint 一帧再纠正,产生可见闪烁;
 *  layout effect 在 paint 前完成纠正,首帧即正确(初始值仍为 false,与 SSR 一致,无 hydration mismatch)。 */
export function useMediaQuery(query: string): boolean {
  const [matches, setMatches] = React.useState(false)

  useIsoLayoutEffect(() => {
    if (typeof window === 'undefined') return
    const mql = window.matchMedia(query)
    const handler = (e: MediaQueryListEvent) => setMatches(e.matches)
    setMatches(mql.matches)
    mql.addEventListener('change', handler)
    return () => mql.removeEventListener('change', handler)
  }, [query])

  return matches
}

export function useIsMobile(): boolean {
  // 2026-08-01 阈值从 768px 改为 1023px:与 CSS --breakpoint-tablet-lg:1024px 对齐,
  // 让 <1024px(手机+平板竖屏)统一走移动模式(FAB/全屏/抽屉),≥1024px 走桌面三列布局。
  // 与 sidebar/ai-side-panel/web-work-panel 的 tablet-lg: 断点类一致。
  return useMediaQuery('(max-width: 1023px)')
}

export function useIsTablet(): boolean {
  return useMediaQuery('(min-width: 769px) and (max-width: 1024px)')
}

export function useIsDesktop(): boolean {
  return useMediaQuery('(min-width: 1025px)')
}
