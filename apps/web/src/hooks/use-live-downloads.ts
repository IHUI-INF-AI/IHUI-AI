'use client'

/**
 * `useLiveDownloads` — 侧边栏「下载」栏的运行期真值(2026-11-02 立)。
 *
 * 失效方向刻意是"什么都不改":取不到(离线/超时/路由 404)就一直用构建期底稿,
 * 于是这条腿挂掉的可见表现是"版本号旧一格",而不是"整栏点不动"或抛错打断侧栏渲染。
 * 因此本 hook 不暴露 loading/error —— 调用方没有能据此分支的合法动作,给了只会诱导出
 * 一闪而过的骨架屏(AGENTS §0.3:说不出结论的中间态不要伪装成状态机)。
 *
 * 类型只走 `import type`:判据住在 downloads-live-meta(纯、两面可用),
 * 而 downloads-live.ts 含 `node:fs`,进了浏览器包就是构建错误。
 */
import { useEffect, useState } from 'react'

import type { LiveDownloads } from '@/config/downloads-live-meta'

interface DownloadsFeedDocument {
  downloads?: LiveDownloads
}

export function useLiveDownloads(): LiveDownloads | null {
  const [live, setLive] = useState<LiveDownloads | null>(null)

  useEffect(() => {
    let cancelled = false
    const controller = new AbortController()
    fetch('/downloads.json', { signal: controller.signal })
      .then((res) => (res.ok ? (res.json() as Promise<DownloadsFeedDocument>) : null))
      .then((doc) => {
        if (cancelled || !doc?.downloads) return
        setLive(doc.downloads)
      })
      .catch(() => {
        // 取不到 = 保持底稿,不喊人也不留错误态
      })
    return () => {
      cancelled = true
      controller.abort()
    }
  }, [])

  return live
}
