import { useMemo } from 'react'
import { useTranslations } from 'next-intl'
import type { UploadLabels } from '@ihui/ui-react'

/**
 * Upload 界面文案注入(简体中文以外的界面由此本地化)。
 *
 * `@ihui/ui-react` 不引 next-intl(被多端共用),组件内只留 DEFAULT_UPLOAD_LABELS 中文兜底;
 * 消费端必须传 labels,否则非中文界面整块回显中文。
 */
export function useUploadLabels(): UploadLabels {
  const t = useTranslations('upload')
  return useMemo<UploadLabels>(
    () => ({
      placeholder: t('placeholder'),
      done: t('done'),
      cancelUpload: t('cancelUpload'),
      removeUploadedAriaLabel: t('removeUploadedAriaLabel'),
      removeItemAriaLabel: t('removeItemAriaLabel'),
      sizeLimitHint: t('sizeLimitHint'),
      maxCountReached: t('maxCountReached'),
      oversizeFiles: t('oversizeFiles'),
      uploadFailed: t('uploadFailed'),
      uploadFailedWithStatus: t('uploadFailedWithStatus'),
      invalidJsonResponse: t('invalidJsonResponse'),
      noUrlField: t('noUrlField'),
      networkError: t('networkError'),
      uploadCancelled: t('uploadCancelled'),
    }),
    [t],
  )
}
