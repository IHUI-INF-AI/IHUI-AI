'use client'

import * as React from 'react'
import { useQuery } from '@tanstack/react-query'

import { fetchApi } from '@/lib/api'
import { useAuthGate } from '@/hooks/use-auth-gate'

/**
 * 当前用户所属租户及在其中的角色(2026-11-24 立)。
 *
 * 数据源:GET /api/tenants/(后端返回当前用户加入的租户列表,每条带 role:
 * owner / admin / member)。前端鉴权入口(如「企业应用凭据」)需要据此判断
 * 用户是否具备租户管理能力 —— 与后端 `guardTenantAccess(tenantId, 'admin')` 对齐。
 *
 * - 未登录 / 会话未就绪:不发请求,`roles` 为空、`loaded` 为 false(调用方保守隐藏入口);
 * - 拉取失败或无所属租户:`roles` 为空数组、`loaded` 为 true;
 * - 本 hook 只负责取角色列表,可见性裁定统一走 `canSeeTenantAdminEntry` 谓词,不在此私写过滤。
 */

interface MyTenantRole {
  id: string
  slug: string
  role: string
}

const MY_TENANTS_QUERY_KEY = ['my', 'tenants'] as const

export function useMyTenantRoles(): {
  /** 当前用户所属租户的角色列表(可能含 member;是否管理员由谓词裁定)。 */
  roles: string[]
  /** 租户角色是否已加载完成(含失败/空列表终态)。false 期间调用方应保守隐藏鉴权入口。 */
  loaded: boolean
} {
  const { allow } = useAuthGate()

  const query = useQuery<MyTenantRole[], Error>({
    queryKey: MY_TENANTS_QUERY_KEY,
    enabled: allow,
    staleTime: 60_000,
    queryFn: async () => {
      const res = await fetchApi<MyTenantRole[]>('/api/tenants/')
      if (!res.success) throw new Error(res.error || '读取租户列表失败')
      return res.data ?? []
    },
  })

  const roles = React.useMemo(() => (query.data ?? []).map((tenant) => tenant.role), [query.data])

  return { roles, loaded: allow ? !query.isLoading : false }
}
