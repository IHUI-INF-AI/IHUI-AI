import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { describe, expect, it } from 'vitest'

const here = path.dirname(fileURLToPath(import.meta.url))
const appDir = path.resolve(here, '../../app')

function walk(dir: string): string[] {
  const out: string[] = []
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (entry.name === '__tests__' || entry.name === 'node_modules') continue
    const full = path.join(dir, entry.name)
    if (entry.isDirectory()) out.push(...walk(full))
    else if (/\.(ts|tsx)$/.test(entry.name)) out.push(full)
  }
  return out
}

const forbidden = /searchParams\.get\('(amount|price|total|paid|status|payStatus|codeUrl|payUrl|credential|success|role|vip)'\)/
const methodRead = /searchParams\.get\('method'\)/

const rel = (f: string) => path.relative(appDir, f).split(path.sep).join('/')

describe('同型根因 S-03:URL 参数不得直接充当金额/状态/凭据', () => {
  const files = walk(appDir)

  it('没有任何页面把金额/支付状态/二维码凭据从 URL 读出来当事实', () => {
    const offenders = files.filter((f) => forbidden.test(fs.readFileSync(f, 'utf8')))
    expect(offenders.map(rel)).toEqual([])
  })

  it("method 只允许登录页做展示分流(W-07 的充值 method 已改服务端白名单)", () => {
    const offenders = files.filter((f) => methodRead.test(fs.readFileSync(f, 'utf8')))
    expect(offenders.map(rel)).toEqual(['login/PageClient.tsx'])
  })
})
