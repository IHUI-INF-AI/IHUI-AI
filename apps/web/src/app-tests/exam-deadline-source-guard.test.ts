import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { describe, expect, it } from 'vitest'

const here = path.dirname(fileURLToPath(import.meta.url))

function read(rel: string): string {
  return fs.readFileSync(path.resolve(here, rel), 'utf8')
}

describe('考试/答题倒计时必须是截止时间戳模型(W-01/W-02)', () => {
  const exam = read('../../app/(main)/exam/[id]/PageClient.tsx')
  const admin = read('../../app/(main)/admin/edu/answer/online/page.tsx')

  it('考试端不再用每秒自减,改为截止时间戳 + 共用 hook', () => {
    expect(exam).not.toMatch(/setLeftSec\(\(s\) => s - 1\)/)
    expect(exam).toContain('useDeadlineCountdown')
    expect(exam).toContain('Date.now() + duration * 60_000')
    expect(exam).toContain('autoSubmitRef')
  })

  it('管理端在线答题同样不再自减,并复用同一 hook', () => {
    expect(admin).not.toMatch(/setRemaining\(\(s\) =>/)
    expect(admin).toContain('useDeadlineCountdown')
    expect(admin).toContain('Date.now() + duration * 60_000')
    expect(admin).toContain('autoSubmitRef')
  })
})
