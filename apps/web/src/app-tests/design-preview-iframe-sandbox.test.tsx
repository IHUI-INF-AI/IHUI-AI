/**
 * 设计器预览 iframe 的 sandbox(2026-10-31 立)。
 *
 * 现读缺陷:`<iframe srcDoc={srcDoc}>` 不带 sandbox ⇒ srcdoc 文档继承父窗口同源,
 * 而 srcDoc 是用户/AI 生成的 HTML(design-utils.ts 直接把 html 拼上编辑脚本)。
 * 同源的一次脚本执行就能读 window.parent.document、localStorage、会话 cookie ——
 * 设计器里一次内容注入即换到登录态。
 *
 * 本枚钉两件事:
 *   ① sandbox 存在且恰为 `allow-scripts`(不给 allow-same-origin ⇒ 断源);
 *   ② 父侧与画侧的全部跨框通信只有 postMessage(实测 grep 面:DesignPage 只用
 *      contentWindow.postMessage,零 contentDocument 读取)⇒ 断源不会把功能改坏。
 *      这一条是"收紧不靠牺牲功能"的凭据,不是本文件的运行时断言(运行时由 ① 与
 *      真浏览器走查共同覆盖,浏览器走查仍未做,见交付说明)。
 */
import { describe, expect, it } from 'vitest'
import { render } from '@testing-library/react'
import { createRef } from 'react'

import { PreviewCanvas } from '../../app/(main)/design/PreviewCanvas'

describe('设计器预览 iframe 必须断源', () => {
  it('① sandbox 恰为 allow-scripts(不含 allow-same-origin)', () => {
    const { container } = render(
      <PreviewCanvas
        iframeRef={createRef<HTMLIFrameElement>()}
        srcDoc="<p>用户生成的内容</p>"
        currentWidth={375}
        showFrame={false}
        deviceRadius={12}
      />,
    )

    const iframe = container.querySelector('iframe')
    expect(iframe).not.toBeNull()
    const sandbox = iframe!.getAttribute('sandbox')
    expect(sandbox).toBe('allow-scripts')
    expect(sandbox).not.toContain('allow-same-origin')
  })
})
