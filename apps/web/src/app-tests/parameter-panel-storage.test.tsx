import { render, waitFor } from '@testing-library/react'
import { beforeEach, describe, expect, it, vi } from 'vitest'

vi.mock('next-intl', () => ({ useTranslations: () => (k: string) => k }))
vi.mock('@/lib/playground-api', () => ({
  fetchPlaygroundModels: vi.fn(async () => ({ success: true, models: [] })),
}))

import { ParameterPanel } from '@/components/playground/ParameterPanel'
import type { PlaygroundParams } from '@/components/playground/PlaygroundTypes'

const STORAGE_KEY = 'ihui-playground-api-key'
const params: PlaygroundParams = {
  model: 'm',
  temperature: 0.7,
  maxTokens: 100,
  topP: 1,
  stream: false,
}

/** happy-dom 在 render 期间可能切换存储分区,用稳定的内存实现钉住行为。 */
function makeStorage(): Storage {
  const map = new Map<string, string>()
  return {
    getItem: (k: string) => map.get(k) ?? null,
    setItem: (k: string, v: string) => void map.set(k, String(v)),
    removeItem: (k: string) => void map.delete(k),
    clear: () => map.clear(),
    key: (i: number) => Array.from(map.keys())[i] ?? null,
    get length() {
      return map.size
    },
  } as Storage
}

describe('ParameterPanel API Key 存储', () => {
  beforeEach(() => {
    Object.defineProperty(window, 'localStorage', { configurable: true, value: makeStorage() })
    Object.defineProperty(window, 'sessionStorage', { configurable: true, value: makeStorage() })
  })

  it('清掉旧 localStorage 残值,并从 sessionStorage 恢复', async () => {
    window.localStorage.setItem(STORAGE_KEY, 'legacy-secret')
    window.sessionStorage.setItem(STORAGE_KEY, 'session-secret')
    const onApiKeyChange = vi.fn()

    render(
      <ParameterPanel
        params={params}
        onParamsChange={vi.fn()}
        apiKey=""
        onApiKeyChange={onApiKeyChange}
      />,
    )

    expect(window.localStorage.getItem(STORAGE_KEY)).toBeNull()
    await waitFor(() => {
      expect(onApiKeyChange).toHaveBeenCalledWith('session-secret')
    })
  })
})
