'use client'

import { create } from 'zustand'

/**
 * 对话 → 文档修订的交接队列(2026-11-28 立)。
 *
 * 为什么是 store 而不是 props:
 * 修订入口在输入区的附件 chip 上(ContextChipsRow → ContextReferencePanel),
 * 承载 diff 的对话框挂在 MessageInput 根部 —— 中间隔着引用卡容器,逐层透传
 * 一个新 prop 只会让"聊天输入区"多出一条只在修订时才用的通道;而请求本身
 * 是**一次性、可排队**的(用户可能连点两份文档),用单槽状态最省。
 *
 * 只保留最新一条:同时开两个修订对话框没有意义,后一条覆盖前一条(旧 File 由
 * 浏览器 GC,不持 objectURL,不存在泄漏)。
 */
export interface ChatDocRevisionRequest {
  id: string
  file: File
  /** 输入区当次正文;空串表示交给面板用默认修订指令。 */
  instruction: string
  createdAt: number
}

interface ChatDocRevisionState {
  request: ChatDocRevisionRequest | null
  open: (file: File, instruction: string) => ChatDocRevisionRequest
  close: () => void
}

let seq = 0

export const useChatDocRevisionStore = create<ChatDocRevisionState>((set) => ({
  request: null,
  open: (file, instruction) => {
    seq += 1
    const request: ChatDocRevisionRequest = {
      id: `chat-revise-${seq}`,
      file,
      instruction: instruction.trim(),
      createdAt: Date.now(),
    }
    set({ request })
    return request
  },
  close: () => set({ request: null }),
}))
