import { beforeEach, describe, expect, it } from 'vitest'
import { useFileHandoffStore } from '../file-handoff'

function makeFile(name: string, content = 'x'): File {
  return new File([content], name, { type: 'text/plain', lastModified: 1_700_000_000_000 })
}

describe('file-handoff store', () => {
  beforeEach(() => {
    useFileHandoffStore.getState().clear()
  })

  it('根窗格消费自己的条目,非根窗格不能抢走', () => {
    const file = makeFile('报告.txt')
    useFileHandoffStore.getState().enqueue({ file })
    expect(useFileHandoffStore.getState().consumeForPane('pane-1')).toEqual([])
    const consumed = useFileHandoffStore.getState().consumeForPane(null)
    expect(consumed).toHaveLength(1)
    expect(consumed[0]?.file).toBe(file)
    expect(useFileHandoffStore.getState().pending).toEqual([])
  })

  it('同一文件连续入队只保留一条', () => {
    const file = makeFile('报告.txt')
    useFileHandoffStore.getState().enqueue({ file, prompt: '先读' })
    useFileHandoffStore.getState().enqueue({ file, prompt: '重复' })
    expect(useFileHandoffStore.getState().pending).toHaveLength(1)
    expect(useFileHandoffStore.getState().pending[0]?.prompt).toBe('先读')
  })

  it('按目标窗格隔离队列', () => {
    useFileHandoffStore.getState().enqueue({ file: makeFile('a.txt'), targetPaneId: 'pane-1' })
    useFileHandoffStore.getState().enqueue({ file: makeFile('b.txt'), targetPaneId: null })
    expect(useFileHandoffStore.getState().consumeForPane('pane-1')).toHaveLength(1)
    expect(useFileHandoffStore.getState().consumeForPane(null)).toHaveLength(1)
  })
})
