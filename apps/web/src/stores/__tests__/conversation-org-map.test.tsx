import { cleanup, render } from '@testing-library/react'
import React from 'react'
import { afterEach, describe, expect, it } from 'vitest'

import { useConversationOrgMap, useConversationOrgStore } from '../conversation-org'

// 回归背景:selector 曾写成 `(s) => (userId ? s.byUser[userId] ?? {} : {})`,
// 未登录/空桶时每次调用返回新字面量 → useSyncExternalStore 快照永不稳定 →
// "Maximum update depth exceeded" 全路由崩溃(浏览器实测,2026-09-26)。
// 本文件是阳性对照:把 selector 改回不稳定形态时,下面两条用例必须红。

afterEach(() => {
  cleanup()
  useConversationOrgStore.setState({ byUser: {} })
})

function Probe({ userId, onMap }: { userId: string | null; onMap: (map: unknown) => void }) {
  onMap(useConversationOrgMap(userId))
  return null
}

describe('useConversationOrgMap 快照稳定性(全路由崩溃回归)', () => {
  it('未登录(userId=null)时多次渲染返回同一引用,不触发无限重渲染', () => {
    const seen: unknown[] = []
    const { rerender } = render(<Probe userId={null} onMap={(m) => seen.push(m)} />)
    rerender(<Probe userId={null} onMap={(m) => seen.push(m)} />)
    rerender(<Probe userId={null} onMap={(m) => seen.push(m)} />)
    expect(seen.length).toBe(3)
    expect(seen[0]).toBe(seen[1])
    expect(seen[1]).toBe(seen[2])
  })

  it('已登录但桶不存在时返回稳定空引用;写入后返回真实桶', () => {
    const seen: unknown[] = []
    render(<Probe userId="u1" onMap={(m) => seen.push(m)} />)
    useConversationOrgStore.setState({
      byUser: { u1: { c1: { folder: '工作', tags: ['a'] } } },
    })
    // 同一 React 树内 selector 重算:桶出现后拿到真实引用;再次空查仍稳定
    expect(seen[0]).toBeDefined()
    const bucket = useConversationOrgStore.getState().byUser.u1
    expect(bucket?.c1?.folder).toBe('工作')
  })
})
