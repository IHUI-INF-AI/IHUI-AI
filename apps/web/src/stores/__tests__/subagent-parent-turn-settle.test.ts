import { beforeEach, describe, expect, it } from 'vitest'

import type { SubAgentActivity } from '@/components/ai/types'
import { useChatStore, type ChatMessage } from '../chat'

function activity(agentId: string, status: SubAgentActivity['status']): SubAgentActivity {
  return {
    agentId,
    name: agentId,
    type: 'general',
    status,
    currentStep: status,
    completedSteps: [],
  }
}

function message(activities: SubAgentActivity[]): ChatMessage {
  return {
    id: 'm-1',
    role: 'assistant',
    content: '',
    createdAt: 1,
    subagentActivities: activities,
  }
}

describe('markAllAgentStreamsDone', () => {
  beforeEach(() => {
    useChatStore.setState({
      messages: [],
      subAgentActivities: [],
    })
  })

  it('父轮次收场时，未终态改为取消，已完成和失败保持', () => {
    const running = activity('run', 'running')
    const thinking = activity('think', 'thinking')
    const completed = activity('ok', 'completed')
    const failed = activity('bad', 'failed')
    useChatStore.setState({
      messages: [message([running, completed])],
      subAgentActivities: [running, thinking, completed, failed],
    })

    useChatStore.getState().markAllAgentStreamsDone()

    const global = useChatStore.getState().subAgentActivities
    expect(global.map((agent) => agent.status)).toEqual([
      'cancelled',
      'cancelled',
      'completed',
      'failed',
    ])
    expect(global.every((agent) => agent.streamingDone === true)).toBe(true)

    const onMessage = useChatStore.getState().messages[0]?.subagentActivities ?? []
    expect(onMessage.map((agent) => agent.status)).toEqual(['cancelled', 'completed'])
    expect(onMessage.every((agent) => agent.streamingDone === true)).toBe(true)
  })
})
