import { create } from 'zustand'
import type { SessionFileChange } from '@ihui/shared/chat/session-file-changes'

interface SessionDiffState {
  open: boolean
  changes: SessionFileChange[]
  openWith: (changes: SessionFileChange[]) => void
  close: () => void
}

export const useSessionDiffStore = create<SessionDiffState>((set) => ({
  open: false,
  changes: [],
  openWith: (changes) => set({ open: true, changes }),
  close: () => set({ open: false, changes: [] }),
}))
