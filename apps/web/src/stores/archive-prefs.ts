// D186 会话归档「不再提示」用户偏好 store(2026-09-30 立)。
// - 单布尔偏好:归档确认弹层勾选「不再提示」后直读直写,不派生第二状态;
// - 持久化走既有 persist 工厂 createPersistConfig(localStorage,SSR 侧自动降级 noop),
//   与 code-block-prefs / conversation-org 等同层惯例,不造第二套存储机制。
// - 默认 false:二次确认是保护性默认,只有用户显式勾选才跳过。

import { create } from 'zustand'
import { persist } from 'zustand/middleware'

import { createPersistConfig } from './persist-helpers'

interface ArchivePrefsState {
  /** 归档时跳过二次确认(勾选「不再提示」后置 true) */
  skipArchiveConfirm: boolean
  setSkipArchiveConfirm: (skip: boolean) => void
}

export const useArchivePrefsStore = create<ArchivePrefsState>()(
  persist(
    (set) => ({
      skipArchiveConfirm: false,
      setSkipArchiveConfirm: (skipArchiveConfirm) => set({ skipArchiveConfirm }),
    }),
    createPersistConfig<ArchivePrefsState>('ihui-archive-prefs', (s) => ({
      skipArchiveConfirm: s.skipArchiveConfirm,
    })),
  ),
)
