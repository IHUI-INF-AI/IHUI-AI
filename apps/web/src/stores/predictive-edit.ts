// 预测式编辑(V3 #82)「开关」用户偏好 store —— 票面"两把钥匙"的第一把。
//
// 与「门槛」(`lib/predictive-edit-api.ts` 的 `passesEditIntentThreshold`)严格分工:
// - 本位 = 用户意志(要不要这个功能),持久化偏好,默认开启
//   (2026-10-25 接线以来功能常开,默认值保持既有行为逐字不变);
// - 门槛位 = 机器条件(这次内容够不够格问),每次请求现算、不落存储。
// 两意合并成单一布尔 ⇒ "关"只能借"不发请求"表达,与后端判出的
// `no_action` 在面上不可分辨,服务端三态即被折回两态(票面点名禁令)。
//
// 持久化走既有 persist 工厂(createPersistConfig,localStorage,SSR 侧自动降级
// noop),与 code-block-prefs / conversation-org 同层惯例,不造第二套存储机制。

import { create } from 'zustand'
import { persist } from 'zustand/middleware'

import { createPersistConfig } from './persist-helpers'

interface PredictiveEditPrefsState {
  /** 预测式编辑总开关:关 ⇒ 聊天输入区与编辑器两条链路都不发起预测请求。 */
  enabled: boolean
  setEnabled: (enabled: boolean) => void
  toggle: () => void
}

export const usePredictiveEditPrefsStore = create<PredictiveEditPrefsState>()(
  persist(
    (set) => ({
      enabled: true,
      setEnabled: (enabled) => set({ enabled }),
      toggle: () => set((s) => ({ enabled: !s.enabled })),
    }),
    createPersistConfig<PredictiveEditPrefsState>('ihui-predictive-edit-prefs', (s) => ({
      enabled: s.enabled,
    })),
  ),
)

/** 开关位读取(会话侧钩子与组件共用;SSR 首帧按默认开,与常开现状同形)。 */
export function usePredictiveEditEnabled(): boolean {
  return usePredictiveEditPrefsStore((s) => s.enabled)
}
