// D181 电脑使用画中画偏好 store(2026-10-23 立项落地,对标竞品 chatSession.pictureInPicture.*)。
// - 两档隐藏语义:hideInAllSessions(全局)/ hiddenConversationIds(按会话),默认均不隐藏(画中画可见);
// - 持久化走既有 persist 工厂 createPersistConfig(localStorage,SSR 侧自动降级 noop),
//   与 code-block-prefs / conversation-org / ai-panel 同层惯例,不造第二套存储机制;
// - computer-use 会话可视化本体未立项 ⇒ 消费端按拍板只做"开关+持久化+空态占位"。

import { create } from 'zustand'
import { persist } from 'zustand/middleware'

import { createPersistConfig } from './persist-helpers'

interface PictureInPicturePrefsState {
  /** 在所有会话中隐藏画中画(全局档) */
  hideInAllSessions: boolean
  /** 在此会话中隐藏画中画(按会话档,存被隐藏的会话 id) */
  hiddenConversationIds: string[]
  setHideInAllSessions: (hide: boolean) => void
  setSessionHidden: (conversationId: string, hidden: boolean) => void
}

export const usePictureInPicturePrefsStore = create<PictureInPicturePrefsState>()(
  persist(
    (set) => ({
      hideInAllSessions: false,
      hiddenConversationIds: [],
      setHideInAllSessions: (hideInAllSessions) => set({ hideInAllSessions }),
      setSessionHidden: (conversationId, hidden) =>
        set((s) => ({
          hiddenConversationIds: hidden
            ? s.hiddenConversationIds.includes(conversationId)
              ? s.hiddenConversationIds
              : [...s.hiddenConversationIds, conversationId]
            : s.hiddenConversationIds.filter((id) => id !== conversationId),
        })),
    }),
    createPersistConfig<PictureInPicturePrefsState>('ihui-picture-in-picture-prefs', (s) => ({
      hideInAllSessions: s.hideInAllSessions,
      hiddenConversationIds: s.hiddenConversationIds,
    })),
  ),
)
