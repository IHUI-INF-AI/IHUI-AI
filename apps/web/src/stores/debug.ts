/**
 * IDE 调试面板 zustand store。
 *
 * 设计:
 * - 面板状态从组件 useState 迁移到全局 store,编辑器(CodeEditor 断点 gutter)可共享读写
 * - 变量树采用扁平 variablesByRef 映射(DAP variablesReference → 子变量列表),
 *   避免深层嵌套树的不可变更新;expandedRefs 控制展开状态,懒加载子树
 * - breakpoints/watches 沿用 localStorage 键(ide:breakpoints / ide:watches),平滑迁移
 */
import { create } from 'zustand'
import {
  getScopes as getScopesApi,
  getVariablesByReference,
  type DebugScope,
  type StackFrame,
} from '@/lib/api/debug'

export type DebugState = 'stopped' | 'running' | 'paused'

export interface VariableNode {
  name: string
  value: string
  type: string
  /** DAP variablesReference(>0 表示有可展开子树) */
  variablesReference?: number
}

export interface Breakpoint {
  id: string
  file: string
  line: number
  enabled: boolean
}

export interface ConsoleLog {
  level: 'info' | 'log' | 'warn' | 'error'
  text: string
}

const BREAKPOINTS_KEY = 'ide:breakpoints'
const WATCHES_KEY = 'ide:watches'
const MAX_LOGS = 200

function loadJson<T>(key: string, fallback: T): T {
  if (typeof window === 'undefined') return fallback
  try {
    const raw = window.localStorage.getItem(key)
    return raw ? (JSON.parse(raw) as T) : fallback
  } catch {
    return fallback
  }
}

function saveJson(key: string, value: unknown): void {
  if (typeof window === 'undefined') return
  try {
    window.localStorage.setItem(key, JSON.stringify(value))
  } catch {
    /* ignore */
  }
}

export interface DebugStore {
  debugState: DebugState
  sessionId: string | null
  loading: boolean
  /** 调用栈 + 当前选中帧 */
  stackFrames: StackFrame[]
  currentFrameId: number | null
  /** scope 分组(Locals/Globals 等,来自 DAP scopes 响应) */
  scopes: DebugScope[]
  /** scope 分组展开状态(name → expanded) */
  scopeExpanded: Record<string, boolean>
  /** DAP variablesReference → 子变量列表(懒加载缓存) */
  variablesByRef: Record<number, VariableNode[]>
  /** 变量子树展开状态(variablesReference → expanded) */
  expandedRefs: Record<number, boolean>
  /** 正在加载的 variablesReference(防重复请求) */
  loadingRefs: Record<number, boolean>
  /** 监视表达式 + 求值结果 */
  watches: string[]
  watchValues: Record<number, string>
  consoleLogs: ConsoleLog[]
  breakpoints: Breakpoint[]

  // ---- 纯状态操作 ----
  setLoading(v: boolean): void
  setSessionId(sid: string | null): void
  setDebugState(s: DebugState): void
  setStackFrames(frames: StackFrame[]): void
  setCurrentFrameId(frameId: number | null): void
  /** 清空运行时数据(回到 stopped 或 running) */
  clearRuntime(): void
  appendLog(log: ConsoleLog): void
  toggleBreakpoint(id: string): void
  removeBreakpoint(id: string): void
  /** gutter 点击入口:同 file+line 已有断点则移除,否则新增(编辑器与面板共用) */
  toggleBreakpointAt(file: string, line: number): void
  addWatch(expr: string): boolean
  removeWatch(idx: number): void
  setWatchValues(map: Record<number, string>): void

  // ---- 数据加载(DAP 懒加载) ----
  /** 加载当前帧的 scope 分组 + 每组顶层变量 */
  loadScopes(sessionId: string, frameId: number): Promise<void>
  /** 切换变量子树展开;首次展开时按 variablesReference 拉取子变量 */
  toggleVariable(sessionId: string, variablesReference: number): Promise<void>
  /** 切换 scope 分组展开;首次展开时拉取该组变量 */
  toggleScope(sessionId: string, scope: DebugScope): Promise<void>
}

export const useDebugStore = create<DebugStore>((set, get) => ({
  debugState: 'stopped',
  sessionId: null,
  loading: false,
  stackFrames: [],
  currentFrameId: null,
  scopes: [],
  scopeExpanded: {},
  variablesByRef: {},
  expandedRefs: {},
  loadingRefs: {},
  watches: loadJson<string[]>(WATCHES_KEY, []),
  watchValues: {},
  consoleLogs: [],
  breakpoints: loadJson<Breakpoint[]>(BREAKPOINTS_KEY, []),

  setLoading: (v) => set({ loading: v }),
  setSessionId: (sid) => set({ sessionId: sid }),
  setDebugState: (s) => set({ debugState: s }),
  setStackFrames: (frames) => set({ stackFrames: frames, currentFrameId: frames[0]?.id ?? null }),
  setCurrentFrameId: (frameId) => set({ currentFrameId: frameId }),
  clearRuntime: () =>
    set({
      stackFrames: [],
      currentFrameId: null,
      scopes: [],
      scopeExpanded: {},
      variablesByRef: {},
      expandedRefs: {},
      loadingRefs: {},
      watchValues: {},
    }),

  appendLog: (log) => set((s) => ({ consoleLogs: [...s.consoleLogs, log].slice(-MAX_LOGS) })),

  toggleBreakpoint: (id) => {
    const next = get().breakpoints.map((b) => (b.id === id ? { ...b, enabled: !b.enabled } : b))
    set({ breakpoints: next })
    saveJson(BREAKPOINTS_KEY, next)
  },

  removeBreakpoint: (id) => {
    const next = get().breakpoints.filter((b) => b.id !== id)
    set({ breakpoints: next })
    saveJson(BREAKPOINTS_KEY, next)
  },

  toggleBreakpointAt: (file, line) => {
    const { breakpoints } = get()
    const existing = breakpoints.find((b) => b.file === file && b.line === line)
    const next = existing
      ? breakpoints.filter((b) => b !== existing)
      : [...breakpoints, { id: `${file}:${line}`, file, line, enabled: true }]
    set({ breakpoints: next })
    saveJson(BREAKPOINTS_KEY, next)
  },

  addWatch: (expr) => {
    const trimmed = expr.trim()
    if (!trimmed) return false
    const { watches } = get()
    if (watches.includes(trimmed)) return false // 去重
    const next = [...watches, trimmed]
    set({ watches: next })
    saveJson(WATCHES_KEY, next)
    return true
  },

  removeWatch: (idx) => {
    const next = get().watches.filter((_, i) => i !== idx)
    set({ watches: next })
    saveJson(WATCHES_KEY, next)
    const values = { ...get().watchValues }
    delete values[idx]
    set({ watchValues: values })
  },

  setWatchValues: (map) => set({ watchValues: map }),

  loadScopes: async (sessionId, frameId) => {
    const res = await getScopesApi(sessionId, frameId)
    const scopes = res.scopes ?? []
    set({ scopes, scopeExpanded: {}, variablesByRef: {}, expandedRefs: {}, loadingRefs: {} })
    // 逐组拉取顶层变量(非 expensive 组;expensive 组等用户手动展开)
    await Promise.all(
      scopes
        .filter((sc) => sc.variablesReference > 0 && !sc.expensive)
        .map(async (sc) => {
          const varRes = await getVariablesByReference(sessionId, sc.variablesReference)
          set((s) => ({
            variablesByRef: {
              ...s.variablesByRef,
              [sc.variablesReference]: (varRes.variables ?? []).map((v) => ({
                name: v.name,
                value: v.value,
                type: v.type ?? 'string',
                variablesReference: v.variablesReference,
              })),
            },
            scopeExpanded: { ...s.scopeExpanded, [sc.name]: true },
          }))
        }),
    )
  },

  toggleVariable: async (sessionId, variablesReference) => {
    const { expandedRefs, variablesByRef, loadingRefs } = get()
    if (variablesReference <= 0) return
    const expanded = !expandedRefs[variablesReference]
    set({ expandedRefs: { ...expandedRefs, [variablesReference]: expanded } })
    if (!expanded) return
    // 已缓存或正在加载则不重复请求
    if (variablesByRef[variablesReference] || loadingRefs[variablesReference]) return
    set({ loadingRefs: { ...loadingRefs, [variablesReference]: true } })
    try {
      const varRes = await getVariablesByReference(sessionId, variablesReference)
      set((s) => ({
        variablesByRef: {
          ...s.variablesByRef,
          [variablesReference]: (varRes.variables ?? []).map((v) => ({
            name: v.name,
            value: v.value,
            type: v.type ?? 'string',
            variablesReference: v.variablesReference,
          })),
        },
        loadingRefs: { ...s.loadingRefs, [variablesReference]: false },
      }))
    } catch (e) {
      set((s) => ({
        loadingRefs: { ...s.loadingRefs, [variablesReference]: false },
        expandedRefs: { ...s.expandedRefs, [variablesReference]: false },
      }))
      get().appendLog({
        level: 'error',
        text: `[variables] ${e instanceof Error ? e.message : String(e)}`,
      })
    }
  },

  toggleScope: async (sessionId, scope) => {
    const { scopeExpanded, variablesByRef } = get()
    const expanded = !scopeExpanded[scope.name]
    set({ scopeExpanded: { ...scopeExpanded, [scope.name]: expanded } })
    if (!expanded || scope.variablesReference <= 0) return
    if (variablesByRef[scope.variablesReference]) return // 已缓存
    try {
      const varRes = await getVariablesByReference(sessionId, scope.variablesReference)
      set((s) => ({
        variablesByRef: {
          ...s.variablesByRef,
          [scope.variablesReference]: (varRes.variables ?? []).map((v) => ({
            name: v.name,
            value: v.value,
            type: v.type ?? 'string',
            variablesReference: v.variablesReference,
          })),
        },
      }))
    } catch (e) {
      set((s) => ({ scopeExpanded: { ...s.scopeExpanded, [scope.name]: false } }))
      get().appendLog({
        level: 'error',
        text: `[scopes] ${e instanceof Error ? e.message : String(e)}`,
      })
    }
  },
}))
