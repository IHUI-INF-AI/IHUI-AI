/**
 * 列表响应解包(2026-11-23 立)。
 *
 * 后端列表端点历史上返回过三种形状:`{list}`(人事/部门)、`{rows}`(报表)、裸数组。
 * 页面若各自写 `data.list` 就会在换一个端点时静默变空列表 —— 空表格最像"没数据",
 * 排查代价极高。统一在这里解包,页面只关心 `rowsOf<T>(data)`。
 */
export function rowsOf<T>(data: unknown): T[] {
  if (Array.isArray(data)) return data as T[]
  if (data && typeof data === 'object') {
    const bag = data as { list?: unknown; rows?: unknown; items?: unknown }
    if (Array.isArray(bag.list)) return bag.list as T[]
    if (Array.isArray(bag.rows)) return bag.rows as T[]
    if (Array.isArray(bag.items)) return bag.items as T[]
  }
  return []
}
