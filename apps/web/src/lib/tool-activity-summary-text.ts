import {
  ACTIVITY_CATEGORIES,
  type ActivityCategory,
  type ToolActivitySummary,
} from '@ihui/shared/chat'

/**
 * 类目 → taskStatus 摘要词键(字面量,禁止动态拼接 —— 键扫描器只认字面量)。
 * 与 tool-category.ts 的 TOOL_CATEGORY_ACTIVITY_KEYS 同域不同用途:那张表给**单条**
 * 活动出双时态动词,本表给**一轮聚合**出计数短语。
 */
const SUMMARY_KEYS: Readonly<Record<ActivityCategory, string>> = {
  file: 'summaryFiles',
  image: 'summaryImages',
  search: 'summarySearches',
  thinking: 'summaryThinking',
  custom: 'summaryCustom',
}

export type SummaryTranslate = (key: string, values?: Record<string, number | string>) => string

/**
 * 一轮工具活动的单行摘要(类目顺序固定,零计数类目不出现,失败数追加在末尾)。
 * 取词失败(端侧缺键)时跳过该段而不是喷键名 —— 摘要行是装饰性交代,坏字比缺字更糟。
 */
export function toolActivitySummaryText(
  summary: ToolActivitySummary,
  translate: SummaryTranslate,
): string {
  if (summary.total === 0) return ''
  const parts: string[] = []
  for (const category of ACTIVITY_CATEGORIES) {
    const count = summary.byCategory[category]
    if (count <= 0) continue
    const key = SUMMARY_KEYS[category]
    const rendered = translate(key, { n: count })
    if (rendered !== key && rendered.trim() !== '') parts.push(rendered)
  }
  if (summary.failed > 0) {
    const failed = translate('summaryFailed', { n: summary.failed })
    if (failed !== 'summaryFailed' && failed.trim() !== '') parts.push(failed)
  }
  return parts.join(' · ')
}
