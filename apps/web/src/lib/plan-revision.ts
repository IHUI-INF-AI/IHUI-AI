/**
 * 计划评审「修改」→ 发回同会话的修订指令。
 *
 * 为什么走聊天草稿而不是 `POST /agent-plan/{plan_id}/decision`:
 * 聊天里的 `planSteps` 没有关联 plan_id(decision 端点服务的是 plan 模式持久化的计划),
 * 评审面板消费的只是"最近一条带 planSteps 的消息"。把修改意见作为下一条用户消息
 * 发回同一会话,才是这条数据面唯一可用的闭环。
 */

/** 反馈为空时的兜底指令:让 Agent 自己先说清要调整什么 */
const EMPTY_FEEDBACK_PROMPT =
  '请重新规划当前任务:先说明需要调整的地方,在更新计划前不要开始执行。'

/**
 * 把评审意见拼成下一条用户消息。
 *
 * 两条分支都必须**显式要求先不要开始执行** —— 否则 Agent 容易把
 * "更新计划"读成"开始执行",打回就变成了放行。
 */
export function buildPlanRevisionPrompt(feedback: string): string {
  const trimmed = feedback.trim()
  if (trimmed === '') return EMPTY_FEEDBACK_PROMPT
  return `请根据以下修改意见更新当前计划,先不要开始执行:\n\n${trimmed}`
}
