/**
 * 认证引导进行中的全局标志（web）。
 *
 * 冷启动时后台 hook 会先于 bootstrap 发出请求，这些请求的 401 在 api-client
 * 「续期一次仍失败」出口会触发 `setUnauthorizedHandler`。若此刻引导链正在用
 * refresh cookie 建立会话，直接 `expireSession()` 会把刚写入的 token/user 清掉，
 * 表现为接口 200、界面永远“请先登录”。
 *
 * 这里只存一个进程内计数，不承载任何凭据；api.ts 与 use-auth-bootstrap 共用。
 */
let inFlightCount = 0

export function beginAuthBootstrap(): void {
  inFlightCount += 1
}

export function endAuthBootstrap(): void {
  inFlightCount = Math.max(0, inFlightCount - 1)
}

export function isAuthBootstrapInFlight(): boolean {
  return inFlightCount > 0
}
