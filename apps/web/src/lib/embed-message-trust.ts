/**
 * 内嵌代理 iframe 的消息来源闸（2026-11-08）。
 *
 * 代理页运行在 `sandbox` 无 `allow-same-origin` 的 iframe 中，是 opaque origin，
 * `MessageEvent.origin` 恒为字符串 `'null'`，**不能**用于同源校验。
 * 可精确校验的是 `MessageEvent.source`：它必须等于本面板 iframe 的 `contentWindow`。
 *
 * 通过来源闸后，仍只接受 `ihui-embed-` 前缀的白名单消息；所有跳转类 url 仅接受 http(s)，
 * 防止 `javascript:` / `data:` 进入地址栏、历史栈或应用内新标签。
 * 来源不匹配时一律返回 null —— 调用方据此保证「零副作用」。
 */

export type EmbedBridgeAction =
  | { kind: 'nav'; url: string; title?: string }
  | { kind: 'loaded'; url: string; title?: string }
  | { kind: 'newtab'; url: string; title?: string }
  | { kind: 'proxy-error'; message: string }

const EMBED_TYPE_MAP = {
  'ihui-embed-nav': 'nav',
  'ihui-embed-loaded': 'loaded',
  'ihui-embed-newtab': 'newtab',
  'ihui-embed-proxy-error': 'proxy-error',
} as const

function isHttpUrl(url: unknown): url is string {
  if (typeof url !== 'string' || !url.trim()) return false
  try {
    const parsed = new URL(url)
    return parsed.protocol === 'http:' || parsed.protocol === 'https:'
  } catch {
    return false
  }
}

export function parseEmbedMessage(
  data: unknown,
  source: MessageEventSource | null,
  expectedWindow: Window | null,
): EmbedBridgeAction | null {
  // 来源闸：expectedWindow 为空（iframe 未挂载/已销毁）或来源不匹配 → 零副作用
  if (!expectedWindow || source !== expectedWindow) return null
  if (!data || typeof data !== 'object') return null

  const payload = data as Record<string, unknown>
  const kind =
    typeof payload.type === 'string'
      ? EMBED_TYPE_MAP[payload.type as keyof typeof EMBED_TYPE_MAP]
      : undefined
  if (!kind) return null

  if (kind === 'proxy-error') {
    return { kind, message: typeof payload.message === 'string' ? payload.message : '' }
  }

  if (!isHttpUrl(payload.url)) return null
  const title = typeof payload.title === 'string' && payload.title ? payload.title : undefined
  return { kind, url: payload.url, title }
}
