import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'

import {
  RUM_CONSENT_STORAGE_KEY,
  isRumConsentGranted,
  onRumConsentChange,
  resetRumConsentForTests,
  setRumConsent,
} from '../consent'

function setDoNotTrack(value: string): void {
  Object.defineProperty(navigator, 'doNotTrack', {
    configurable: true,
    value,
  })
}

describe('RUM 同意闸', () => {
  beforeEach(() => {
    resetRumConsentForTests()
    setDoNotTrack('0')
  })

  afterEach(() => {
    vi.unstubAllGlobals()
    vi.restoreAllMocks()
    resetRumConsentForTests()
  })

  it('默认关闭（本地无记录）', () => {
    expect(isRumConsentGranted()).toBe(false)
  })

  it('显式同意后为 true，撤回后回到 false', () => {
    setRumConsent(true)
    expect(isRumConsentGranted()).toBe(true)
    setRumConsent(false)
    expect(isRumConsentGranted()).toBe(false)
  })

  it('DNT 优先于本地同意：已存 1 仍判未同意', () => {
    setRumConsent(true)
    setDoNotTrack('1')
    expect(isRumConsentGranted()).toBe(false)
  })

  it('localStorage 读失败时 fail closed', () => {
    vi.stubGlobal('localStorage', {
      getItem: () => {
        throw new Error('storage disabled')
      },
      setItem: () => {},
      removeItem: () => {},
    })
    expect(isRumConsentGranted()).toBe(false)
  })

  it('同意变化会广播给订阅者，取消订阅后不再收到', () => {
    const received: boolean[] = []
    const unsubscribe = onRumConsentChange((granted) => received.push(granted))
    setRumConsent(true)
    setRumConsent(false)
    expect(received).toEqual([true, false])
    unsubscribe()
    setRumConsent(true)
    expect(received).toEqual([true, false])
  })

  it('写入的键是 ihui_rum_consent_v1', () => {
    setRumConsent(true)
    expect(localStorage.getItem(RUM_CONSENT_STORAGE_KEY)).toBe('1')
  })
})
