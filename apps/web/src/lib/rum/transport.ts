/**
 * RUM 上报通道：复用既有 `POST /api/v1/telemetry/ingest`（apps/api/src/routes/telemetry.ts）。
 *
 * 该端点只把 name/props/timestamp 写日志，不落 IP / UA 字段；客户端已在采集层完成脱敏与白名单。
 * 不新增端点 ⇒ 不改 OpenAPI 产物，也不扩大服务端攻击面。
 *
 * 走 `fetchApi`（守门 73 要求端内不得裸 fetch）；网络失败由 fetchApi 自己有界重试一次，
 * 采集层再以"连续失败 2 次熔断"兜住，绝不会因失败产生无界重试风暴。
 */

import { fetchApi } from '@/lib/api'
import type { RumEvent, RumTransport } from './collector'

export const RUM_INGEST_PATH = '/api/v1/telemetry/ingest'
/** 上报请求超时：比普通业务请求短，避免页面卸载/后台时挂住。 */
export const RUM_INGEST_TIMEOUT_MS = 5_000

export const rumTelemetryTransport: RumTransport = async (events: RumEvent[]) => {
  const result = await fetchApi<{ accepted?: number }>(RUM_INGEST_PATH, {
    method: 'POST',
    body: JSON.stringify({ events }),
    timeoutMs: RUM_INGEST_TIMEOUT_MS,
  })
  if (!result.success) {
    throw new Error('rum ingest rejected')
  }
}
