/** 文本获取器(组件注入 i18n 解析,registry 保持纯数据) */
export interface CommandTextGetter {
  getLabel: (id: string) => string
  getDescription: (id: string) => string
  getKeywords: (id: string) => string[]
}

/** 按查询词过滤命令(label/description/keywords 子串匹配,大小写不敏感) */
export function filterCommands(
  defs: CommandDef[],
  query: string,
  text: CommandTextGetter,
): CommandDef[] {
  const q = query.trim().toLowerCase()
  if (!q) return defs
  return defs.filter((c) => {
    const keywords = text.getKeywords(c.id)
    const haystack =
      `${text.getLabel(c.id)} ${text.getDescription(c.id)} ${keywords.join(' ')}`.toLowerCase()
    return haystack.includes(q)
  })
}

/** 按 MRU 降序稳定排序(MRU 命中者优先,未命中保持原顺序) */
export function sortByMru(defs: CommandDef[], mruIds: string[]): CommandDef[] {
  const rank = new Map(mruIds.map((id, idx) => [id, idx]))
  return [...defs].sort((a, b) => {
    const ra = rank.get(a.id) ?? Number.MAX_SAFE_INTEGER
    const rb = rank.get(b.id) ?? Number.MAX_SAFE_INTEGER
    return ra - rb
  })
}

/** 按分组顺序分组(保持组内原顺序) */
export function groupCommands(
  defs: CommandDef[],
): Array<{ group: CommandGroup; items: CommandDef[] }> {
  return COMMAND_GROUP_ORDER.map((group) => ({
    group,
    items: defs.filter((c) => c.group === group),
  })).filter((g) => g.items.length > 0)
}
