// ============================================================================
// MRU(Most Recently Used)持久化
// ============================================================================

const MRU_STORAGE_KEY = 'ihui-command-mru'
const MRU_LIMIT = 8

interface MruEntry {
  id: string
  lastUsedAt: number
}

function readMruMap(): Map<string, number> {
  if (typeof window === 'undefined') return new Map()
  try {
    const raw = window.localStorage.getItem(MRU_STORAGE_KEY)
    if (!raw) return new Map()
    const parsed: unknown = JSON.parse(raw)
    if (!Array.isArray(parsed)) return new Map()
    const map = new Map<string, number>()
    for (const item of parsed) {
      if (
        typeof item === 'object' &&
        item !== null &&
        typeof (item as MruEntry).id === 'string' &&
        typeof (item as MruEntry).lastUsedAt === 'number'
      ) {
        map.set((item as MruEntry).id, (item as MruEntry).lastUsedAt)
      }
    }
    return map
  } catch {
    // localStorage 禁用/损坏时静默降级为无 MRU
    return new Map()
  }
}

function writeMruMap(map: Map<string, number>) {
  if (typeof window === 'undefined') return
  try {
    const entries: MruEntry[] = Array.from(map.entries())
      .sort((a, b) => b[1] - a[1])
      .slice(0, MRU_LIMIT)
      .map(([id, lastUsedAt]) => ({ id, lastUsedAt }))
    window.localStorage.setItem(MRU_STORAGE_KEY, JSON.stringify(entries))
  } catch {
    // 写入失败静默(隐私模式等)
  }
}

/** 读取 MRU 命令 id 列表(按最近使用降序,只含注册表中存在的 id) */
export function getMruCommandIds(): string[] {
  const known = new Set(ALL_IDS)
  const map = readMruMap()
  return Array.from(map.entries())
    .filter(([id]) => known.has(id))
    .sort((a, b) => b[1] - a[1])
    .map(([id]) => id)
}

/** 记录一次命令使用(更新 lastUsedAt,超过上限淘汰最旧) */
export function recordCommandUse(id: string): void {
  if (!ALL_IDS.includes(id)) return
  const map = readMruMap()
  // 时间戳严格递增:同一毫秒内多次记录时避免并列导致降序排序不稳定(淘汰错条目)
  const maxTs = Array.from(map.values()).reduce((m, v) => Math.max(m, v), 0)
  map.set(id, Math.max(Date.now(), maxTs + 1))
  writeMruMap(map)
}

/** 清空 MRU(测试/重置用) */
export function clearMru(): void {
  if (typeof window === 'undefined') return
  try {
    window.localStorage.removeItem(MRU_STORAGE_KEY)
  } catch {
    // 静默
  }
}

