// ============================================================================
// 类型定义
// ============================================================================

export type CommandGroup = 'navigate' | 'view' | 'tools' | 'settings' | 'mode'

export type CommandAction =
  | { type: 'navigate'; href: string }
  | { type: 'ideTab'; tab: IDETabType; href: string }
  | { type: 'workPanel' }
  | { type: 'mode'; mode: 'build' | 'plan' | 'review' | 'spec' }

export interface CommandDef {
  /** 唯一 id,i18n 用 `commandPalette.commands.<id>.*` 解析 */
  id: string
  group: CommandGroup
  icon: LucideIcon
  action: CommandAction
  /** 快捷键提示(展示用,如 "Ctrl+,"),实际监听在 use-global-shortcuts */
  shortcut?: string
}

