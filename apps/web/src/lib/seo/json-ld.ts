/**
 * JSON-LD 内联脚本载荷的唯一出口。
 *
 * `<script type="application/ld+json" dangerouslySetInnerHTML>` 里直接 `JSON.stringify(...)`
 * 会把数据中的 `<` 原样写进脚本体:载荷一旦含 `</script>`,标签当场提前闭合,其后的字符
 * 被当成 HTML 解析(注入面)。把 `<` 转成 JSON 等价转义 `\u003c` 后解析结果逐字不变,
 * 浏览器却再也看不到闭合序列 —— 与 blog/[slug]、ai-news 等已转义页面同形,这里收成
 * 一处实现,新页面直接用,不再各抄一份正则。
 */
export function jsonLdHtml(value: unknown): string {
  const json = JSON.stringify(value)
  return json === undefined ? '' : json.replace(/</g, '\\u003c')
}
