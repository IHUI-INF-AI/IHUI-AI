/**
 * D01(2026-10-25 立)对话内 Agent 选择器的数据源。
 *
 * 唯一数据面在 ai-service 的 `services/persona_registry.py`(`PERSONAS_CONTRACTS`),
 * 这里只做 GET /api/llm/personas 的拉取投影 —— 前端不写死 persona 名单,
 * 也不定义第二份 persona/工具白名单(票面硬要求)。
 *
 * 行为与 lib/models-api.ts 同款:
 *   - 失败/超时/404 → 返回空数组 + logger.warn(调用方按"只有默认项"渲染)
 *   - 永远不抛出,调用方不需要 try-catch
 *   - 走 /api/llm/* 既有反代(next rewrites → ai-service),不新增网关规则
 */

import { fetchAiServiceJson } from '@ihui/api-client'

import { logger } from './logger'

/** 单个 persona 的目录项(与 ai-service persona_catalog() 的投影一一对应) */
export interface PersonaCatalogItem {
  /** persona id(researcher / coder / reviewer / architect / debugger),即请求里的 agentId */
  name: string
  /** 契约描述(输入契约的 description 字段),用作下拉项副标题 */
  description: string
  /** 工具白名单摘要(只读展示;真正并入由 ai-service 在请求时完成) */
  tools: string[]
}

/**
 * 拉取 persona 目录(对话内 Agent 选择器)。
 * 失败/空 → 返回空数组,调用方降级为仅"默认专家"一项。
 */
export async function fetchPersonaCatalog(): Promise<PersonaCatalogItem[]> {
  try {
    const res = await fetchAiServiceJson<{ personas?: PersonaCatalogItem[] }>('/llm/personas', {
      method: 'GET',
    })
    if (!res.success) {
      if (typeof window !== 'undefined') {
        logger.warn('[personas-api] fetchPersonaCatalog 失败', res.error)
      }
      return []
    }
    return res.data?.personas ?? []
  } catch (err) {
    if (typeof window !== 'undefined') {
      logger.warn('[personas-api] fetchPersonaCatalog 异常,返回空数组', err)
    }
    return []
  }
}
