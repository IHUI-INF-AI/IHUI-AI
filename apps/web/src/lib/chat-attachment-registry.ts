/**
 * 对话附件登记簿(2026-11-28 立,主 AI 主动发起修订的执行面)。
 *
 * 为什么需要:AI 通过 `web_ui_invoke(name='document.revise')` 触发修订时,端侧只拿到
 * 文件名 —— 真正的 File 字节住在 `useMessageReferences` 的局部 ref 里,UI 桥够不到。
 * 这里在附件提交时登记一份按文件名索引的弱引用表(仅本会话内存,不落盘、不进 store,
 * 会话结束即随页面销毁),修订入口按名字取回同一个 File 对象,不重新上传、不伪造内容。
 *
 * 边界:
 * - 只登记已通过三档校验的附件(commitFileReference),被拒文件不进来;
 * - 同名文件后提交者覆盖先提交者,并成为"最近一份"兜底;
 * - 上限 20 条,超出按登记顺序淘汰,避免长会话把 File 字节一直挂在内存里。
 */

const MAX_ENTRIES = 20

const byName = new Map<string, File>()
let latest: File | null = null

/** 登记一份对话附件(commit 成功后调用) */
export function rememberChatAttachment(file: File): void {
  // 覆盖同名项时先删旧键,保证 Map 的插入顺序 = 最近登记顺序
  if (byName.has(file.name)) byName.delete(file.name)
  byName.set(file.name, file)
  latest = file
  while (byName.size > MAX_ENTRIES) {
    const oldest = byName.keys().next().value
    if (oldest === undefined) break
    byName.delete(oldest)
  }
}

/**
 * 按文件名取附件。
 * - 给了 name:精确命中才返回(模型常把文件名写错,错名不回退到别的文件);
 * - 未给 name:返回最近登记的一份(单附件对话的常见形态)。
 */
export function findChatAttachment(name?: string): File | null {
  const key = (name ?? '').trim()
  if (!key) return latest
  return byName.get(key) ?? null
}

/** 测试面:清空登记簿 */
export function __resetChatAttachments(): void {
  byName.clear()
  latest = null
}
