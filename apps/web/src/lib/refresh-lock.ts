/**
 * 跨上下文刷新单飞(2026-10-20 立)。
 *
 * 立因:`refreshAccessTokenOnce`(@ihui/api-client)的 in-flight 去重只在**单个 JS 上下文**
 * 内生效。两个页签(或桌面端两个窗口)在第 15 分钟同批过期后几乎同时 POST /auth/refresh,
 * 都带着同一枚 refresh token:先到者轮转 v1→v2,后到者重放 v1。服务端虽有 30s 宽限期,
 * 但宽限期外的迟到重放仍会走到"陈旧副本"分支被拒 —— 后到者这条会话就得重新登录。
 *
 * 修法:把刷新动作放进 Web Locks 的具名锁里串行化。后到者拿到锁时,浏览器 cookie /
 * 桌面 vault 里已经是先到者刚写回的新凭据,于是它这次刷新是正常轮转,不需要重放。
 *
 * 降级:环境没有 `navigator.locks`(旧 Safari / 非浏览器宿主)时直接执行,行为与改动前
 * 逐字节一致 —— 锁是优化,不是正确性前置。
 */
const REFRESH_LOCK_NAME = 'ihui-auth-refresh'

/**
 * 在跨上下文互斥锁内执行一次刷新。
 *
 * 锁的持有范围 = 一次完整的刷新(含凭据写回),不只是一次网络请求:只有把"读旧凭据 →
 * 换新凭据 → 写回"整体串起来,后到者才看得到先到者的成果。
 */
export async function withRefreshLock<T>(fn: () => Promise<T>): Promise<T> {
  const locks = typeof navigator === 'undefined' ? undefined : navigator.locks
  if (!locks || typeof locks.request !== 'function') return fn()
  return locks.request(REFRESH_LOCK_NAME, () => fn())
}

/** 锁名(测试与诊断用)。 */
export const __REFRESH_LOCK_NAME = REFRESH_LOCK_NAME
