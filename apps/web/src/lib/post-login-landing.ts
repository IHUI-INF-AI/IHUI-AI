import { isAdmin } from '@ihui/shared/auth/auth-utils'

/**
 * 管理员登录且**没有**被登录守卫带回具体目标时的默认落地页:生产在线监控大屏。
 * 单一真相源 —— 主站登录弹窗(LoginDialog)等登录落点一律经 resolvePostLoginLanding 取用,
 * 勿在别处另写一份落地路径。
 */
export const ADMIN_POST_LOGIN_LANDING = '/admin/monitor/wallboard'

/** resolvePostLoginLanding 只需要的身份字段(结构上兼容 AuthUser / AuthTokenUser)。 */
export interface PostLoginUser {
  roleId?: number
  role?: string
}

/**
 * 计算登录成功后的默认落点。
 *
 * - 有显式 redirect 目标(如登录守卫带回的 `/chat/history`)⇒ 原样返回,由调用方走安全判据跳转;
 * - 无显式目标且是管理员(roleId >= 1,与后端 requireAdmin 同口径)⇒ 监控大屏;
 * - 其余(普通用户 / 身份缺失)⇒ null,维持原语义(留在当前页)。
 */
export function resolvePostLoginLanding(
  user: PostLoginUser | null | undefined,
  explicitRedirect?: string | null,
): string | null {
  if (explicitRedirect) return explicitRedirect
  return isAdmin(user ?? null) ? ADMIN_POST_LOGIN_LANDING : null
}
