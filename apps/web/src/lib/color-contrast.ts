/**
 * 颜色对比度工具(2026-11-15 v3 立)。
 *
 * 自定义主题需要两件事:
 *   1. 由主色自动推导黑/白前景,保证按钮文字始终可读;
 *   2. 在设置页给出 WCAG 对比度提示,避免用户选出不可读组合。
 * Provider 与自定义主题卡片共用这一份实现(§0.6 单一真相源)。
 */

export function hexToRgb(hex: string): [number, number, number] {
  const value = hex.replace('#', '')
  return [
    Number.parseInt(value.slice(0, 2), 16),
    Number.parseInt(value.slice(2, 4), 16),
    Number.parseInt(value.slice(4, 6), 16),
  ]
}

export function relativeLuminance(hex: string): number {
  const [r, g, b] = hexToRgb(hex).map((channel) => {
    const c = channel / 255
    return c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4
  }) as [number, number, number]
  return 0.2126 * r + 0.7152 * g + 0.0722 * b
}

/** 主色上的前景色:按相对亮度自动选黑/白 */
export function contrastForeground(hex: string): '#000000' | '#ffffff' {
  return relativeLuminance(hex) > 0.45 ? '#000000' : '#ffffff'
}

/** WCAG 对比度(1–21) */
export function contrastRatio(foreground: string, background: string): number {
  const a = relativeLuminance(foreground)
  const b = relativeLuminance(background)
  const lighter = Math.max(a, b)
  const darker = Math.min(a, b)
  return (lighter + 0.05) / (darker + 0.05)
}
