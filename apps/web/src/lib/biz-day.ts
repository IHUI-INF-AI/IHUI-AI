/**
 * 业务日键 —— 全站"今天/近 N 天"的唯一取法。
 *
 * 口径:Asia/Shanghai。依据是实测,不是约定:
 * - 本机 Postgres 会话时区 = Asia/Shanghai(`show timezone`,now() 带 +08),仓内各聚合 SQL
 *   (mobile-stats / relay-capacity / 学习周报 / 佣金日汇总)都按 +08 截日;
 * - 浏览器/设备时区与 Node 进程时区都不保证是 +08。
 *
 * 用 `toISOString().slice(0,10)` 直接取 UTC 日,会让北京时间 00:00–07:59 的"今天"落到前一天:
 * 管理端的日期筛选、趋势图与埋点 visitDate 都会与后端统计错开一整天,而画面看着完全正常。
 * 中国无夏令时,UTC+8 固定偏移即等价于业务时区。
 */
export function bizDayKey(d: Date): string {
  return new Date(d.getTime() + 8 * 3600_000).toISOString().slice(0, 10)
}

/** 今天(业务时区)的日期键 */
export const bizTodayKey = (): string => bizDayKey(new Date())

/** 业务时区下 n 天前的日期键(n=0 即今天) */
export function bizDaysAgoKey(n: number): string {
  return bizDayKey(new Date(Date.now() - n * 86400_000))
}

/** 由日期键取「月/日」展示串(业务时区,与键本身同源) */
export function bizMonthDayLabel(dayKey: string): string {
  const [, m, d] = dayKey.split('-')
  return `${Number(m)}/${Number(d)}`
}
