import { describe, expect, it } from 'vitest'

import { contrastForeground, contrastRatio, relativeLuminance } from '../color-contrast'

describe('color-contrast', () => {
  it('黑白亮度边界', () => {
    expect(relativeLuminance('#ffffff')).toBeCloseTo(1, 5)
    expect(relativeLuminance('#000000')).toBeCloseTo(0, 5)
  })

  it('主色自动前景', () => {
    expect(contrastForeground('#ffffff')).toBe('#000000')
    expect(contrastForeground('#000000')).toBe('#ffffff')
    expect(contrastForeground('#18181b')).toBe('#ffffff')
  })

  it('对比度符合 WCAG 极值', () => {
    expect(contrastRatio('#000000', '#ffffff')).toBeCloseTo(21, 1)
    expect(contrastRatio('#ffffff', '#ffffff')).toBeCloseTo(1, 5)
  })
})
