import { describe, expect, it } from 'vitest'

import { summarizeToolActivity } from '@ihui/shared/chat'
import { toolActivitySummaryText } from '../tool-activity-summary-text'

const t = (key: string, values?: Record<string, number | string>) =>
  values && typeof values.n === 'number' ? `${key}:${values.n}` : key

function textOf(
  items: Array<{ toolName: string; status: 'running' | 'success' | 'error' | 'cancelled' }>,
) {
  return toolActivitySummaryText(summarizeToolActivity(items), t)
}

describe('toolActivitySummaryText', () => {
  it('空集返回空串（调用侧据此不渲染摘要行）', () => {
    expect(textOf([])).toBe('')
  })

  it('类目顺序固定:文件 → 图像 → 检索 → 分析 → 其他（与 ACTIVITY_CATEGORIES 同序）', () => {
    expect(
      textOf([
        { toolName: 'unknown_plugin_tool', status: 'success' },
        { toolName: 'analyze_code', status: 'success' },
        { toolName: 'web_search', status: 'success' },
        { toolName: 'image_generation', status: 'success' },
        { toolName: 'read_file', status: 'success' },
      ]),
    ).toBe(
      'summaryFiles:1 · summaryImages:1 · summarySearches:1 · summaryThinking:1 · summaryCustom:1',
    )
  })

  it('零计数类目不出现', () => {
    expect(textOf([{ toolName: 'read_file', status: 'success' }])).toBe('summaryFiles:1')
  })

  it('失败数追加在末尾', () => {
    expect(
      textOf([
        { toolName: 'read_file', status: 'success' },
        { toolName: 'web_search', status: 'error' },
      ]),
    ).toBe('summaryFiles:1 · summarySearches:1 · summaryFailed:1')
  })

  it('端侧缺键时跳过该段（不把键名喷到界面）', () => {
    const missing = (key: string) => key
    const summary = summarizeToolActivity([{ toolName: 'read_file', status: 'success' }])
    expect(toolActivitySummaryText(summary, missing)).toBe('')
  })
})
