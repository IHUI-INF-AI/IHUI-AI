/**
 * protected-paths 回归(2026-10-31 立,票「E2E 自动补测」第二枚真补测)。
 *
 * 这一格同时被 `proxy.ts`(命中即验 cookie)与 `/sso/login`(只有落在这集合内才自动回跳)消费,
 * 漂移的表现是安静的一侧:要么受保护页被直接放行,要么 `//evil.com/admin` 这类协议相对地址
 * 被当成同源回跳目标送出去。所以正向(该挡)/反向(不该挡、不该回跳)必须成对钉住。
 */
import { describe, expect, it } from 'vitest'

import { isProtectedPath, protectedPathOf } from '../protected-paths'

describe('受保护路径唯一真相源', () => {
  it('isProtectedPath 逐字口径:/admin 与子路径命中,/administrator 不命中', () => {
    expect(isProtectedPath('/admin')).toBe(true)
    expect(isProtectedPath('/admin/users')).toBe(true)
    expect(isProtectedPath('/administrator')).toBe(false)
    expect(isProtectedPath('/edu/edu-management')).toBe(true)
    expect(isProtectedPath('/edu/edu-management/courses/1')).toBe(true)
    expect(isProtectedPath('/edu/edu-managementx')).toBe(false)
    expect(isProtectedPath('/public')).toBe(false)
  })

  it('protectedPathOf 只回路径:query 与 hash 不进回跳', () => {
    expect(protectedPathOf('/admin/users?tab=1&page=2#top')).toBe('/admin/users')
    expect(protectedPathOf('/admin')).toBe('/admin')
  })

  it('protectedPathOf 拒绝三类越权入口:协议相对 / 反斜杠 / 非 http 协议', () => {
    expect(protectedPathOf('//evil.com/admin')).toBe('')
    expect(protectedPathOf('/\\evil.com/admin')).toBe('')
    expect(protectedPathOf('javascript:alert(1)//admin')).toBe('')
    expect(protectedPathOf('https://aizhs.top/admin')).toBe('')
  })

  it('protectedPathOf 不误挡同源非受保护路径', () => {
    expect(protectedPathOf('/public')).toBe('')
    expect(protectedPathOf('/')).toBe('')
  })
})
