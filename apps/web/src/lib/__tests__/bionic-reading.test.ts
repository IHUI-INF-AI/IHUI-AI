import { describe, expect, it } from 'vitest'

import { bionicizeText, splitBionicWord } from '../bionic-reading'

describe('splitBionicWord(仿生阅读单个 token)', () => {
  it('拉丁词加粗前 40%,最多 5 个字符', () => {
    expect(splitBionicWord('Reading')).toEqual({ lead: 'Rea', rest: 'ding' })
    expect(splitBionicWord('internationalization')).toEqual({
      lead: 'inter',
      rest: 'nationalization',
    })
    expect(splitBionicWord('world')).toEqual({ lead: 'wo', rest: 'rld' })
  })

  it('中文、短词、纯数字、带标点 token 一律跳过', () => {
    expect(splitBionicWord('中文')).toBeNull()
    expect(splitBionicWord('ab')).toBeNull()
    expect(splitBionicWord('2026')).toBeNull()
    expect(splitBionicWord('hello,')).toBeNull()
  })
})

describe('bionicizeText(段落切分)', () => {
  it('保留空白,只把拉丁词的加粗段标出来', () => {
    expect(bionicizeText('Reading 中文 world')).toEqual([
      { text: 'Rea', bold: true },
      { text: 'ding', bold: false },
      { text: ' ', bold: false },
      { text: '中文', bold: false },
      { text: ' ', bold: false },
      { text: 'wo', bold: true },
      { text: 'rld', bold: false },
    ])
  })

  it('没有可加粗 token 时返回 null(调用方复用原节点)', () => {
    expect(bionicizeText('中文标点,。')).toBeNull()
    expect(bionicizeText('a b c')).toBeNull()
    expect(bionicizeText('')).toBeNull()
  })
})
