/**
 * biz-day 业务日键回归(2026-10-31 立,票「E2E 自动补测」首枚真补测)。
 *
 * 判据为什么值这个测试:全站"今天/近 N 天"都靠 `bizDayKey` 按 UTC+8 截日,而北京时间
 * 00:00–07:59 的"今天"如果用 `toISOString().slice(0,10)` 取 UTC 日,会整体落到前一天 ——
 * 管理端筛选、趋势图与埋点 visitDate 会和后端统计错开一整天,画面却看不出异常。
 * 所以边界只钉一处:UTC 15:59 与 16:00 这一对必须分属两天。
 */
import { afterEach, describe, expect, it, vi } from 'vitest'

import { bizDayKey, bizDaysAgoKey, bizMonthDayLabel, bizTodayKey } from '../biz-day'

const DAY = 86_400_000

afterEach(() => {
  vi.useRealTimers()
})

describe('biz-day 业务日键(Asia/Shanghai 截日)', () => {
  it('北京 00:00 边界:UTC 15:59 仍属前一日,UTC 16:00 归次日', () => {
    expect(bizDayKey(new Date('2026-10-31T15:59:59.999Z'))).toBe('2026-10-31')
    expect(bizDayKey(new Date('2026-10-31T16:00:00.000Z'))).toBe('2026-11-01')
  })

  it('跨年:UTC 12-31 16:00 = 北京 01-01', () => {
    expect(bizDayKey(new Date('2026-12-31T15:59:00.000Z'))).toBe('2026-12-31')
    expect(bizDayKey(new Date('2026-12-31T16:00:00.000Z'))).toBe('2027-01-01')
  })

  it('无夏令时:7 月仍按固定 +08 截日', () => {
    expect(bizDayKey(new Date('2026-07-01T15:59:59.000Z'))).toBe('2026-07-01')
    expect(bizDayKey(new Date('2026-07-01T16:00:00.000Z'))).toBe('2026-07-02')
  })

  it('bizTodayKey / bizDaysAgoKey 与"今天减 n 天"同源(固定系统时钟)', () => {
    vi.useFakeTimers()
    // 北京 2026-11-01 00:30(UTC 仍是 10-31)⇒ 今天必须读到 11-01
    vi.setSystemTime(new Date('2026-10-31T16:30:00.000Z'))
    expect(bizTodayKey()).toBe('2026-11-01')
    expect(bizDaysAgoKey(0)).toBe('2026-11-01')
    expect(bizDaysAgoKey(1)).toBe('2026-10-31')
    expect(bizDaysAgoKey(7)).toBe('2026-10-25')
    expect(bizDayKey(new Date(Date.now() - 30 * DAY))).toBe(bizDaysAgoKey(30))
  })

  it('bizMonthDayLabel 去前导零(展示串与键同源)', () => {
    expect(bizMonthDayLabel('2026-03-05')).toBe('3/5')
    expect(bizMonthDayLabel('2026-11-23')).toBe('11/23')
  })
})
