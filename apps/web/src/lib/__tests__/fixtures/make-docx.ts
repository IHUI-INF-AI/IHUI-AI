import JSZip from 'jszip'

/** 测试夹具:生成最小可解析 docx(zip + word/document.xml),用于段落写回断言。 */
export async function makeDocx(
  paragraphs: string[],
  options: { textbox?: boolean; stylePerParagraph?: boolean } = {},
): Promise<Uint8Array> {
  const escape = (value: string) =>
    value.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')

  const body = paragraphs
    .map((text, index) => {
      const pPr = options.stylePerParagraph
        ? `<w:pPr><w:pStyle w:val="Heading${index + 1}"/></w:pPr>`
        : ''
      const textbox = options.textbox
        ? `<w:r><w:txbxContent><w:p><w:r><w:t>文本框内容</w:t></w:r></w:p></w:txbxContent></w:r>`
        : ''
      return `<w:p>${pPr}${textbox}<w:r><w:rPr><w:b/></w:rPr><w:t xml:space="preserve">${escape(
        text,
      )}</w:t></w:r></w:p>`
    })
    .join('')

  const xml = [
    '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>',
    '<w:document xmlns:w="http://schemas.openxmlformats.org/wordprocessingml/2006/main"><w:body>',
    body,
    '<w:sectPr><w:pgSz w:w="11906" w:h="16838"/></w:sectPr>',
    '</w:body></w:document>',
  ].join('')

  const zip = new JSZip()
  zip.file(
    '[Content_Types].xml',
    '<?xml version="1.0"?><Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types"><Default Extension="xml" ContentType="application/xml"/></Types>',
  )
  zip.file(
    '_rels/.rels',
    '<?xml version="1.0"?><Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships"><Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/officeDocument" Target="word/document.xml"/></Relationships>',
  )
  zip.file('word/document.xml', xml)
  return zip.generateAsync({ type: 'uint8array' })
}

export async function readDocumentXml(bytes: Uint8Array): Promise<string> {
  const zip = await JSZip.loadAsync(bytes)
  const entry = zip.file('word/document.xml')
  if (!entry) throw new Error('fixture missing word/document.xml')
  return entry.async('string')
}

export function countParagraphs(xml: string): number {
  return (xml.match(/<w:p(?:\s|>)/g) ?? []).length
}
