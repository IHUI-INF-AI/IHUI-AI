import { describe, expect, it } from 'vitest'
import { diffStatsFromContents } from '../diff-stats'

describe('diffStatsFromContents', () => {
  it('新建文件按全文行数计新增,删除方向为 0', () => {
    expect(diffStatsFromContents('', 'a\nb\n')).toEqual({ additions: 2, deletions: 0 })
  })

  it('纯删除只计删除,不把空新内容算成新增', () => {
    expect(diffStatsFromContents('a\nb\n', '')).toEqual({ additions: 0, deletions: 2 })
  })

  it('同位置替换按 Myers 行级差异计增删', () => {
    expect(diffStatsFromContents('a\nb\nc\n', 'a\nx\nc\n')).toEqual({
      additions: 1,
      deletions: 1,
    })
  })

  it('空旧空新与完全相同的两份全文都不产生假变更', () => {
    expect(diffStatsFromContents('', '')).toEqual({ additions: 0, deletions: 0 })
    expect(diffStatsFromContents('same\n', 'same\n')).toEqual({ additions: 0, deletions: 0 })
  })
})
