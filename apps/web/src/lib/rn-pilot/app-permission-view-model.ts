const NAME_KEY = /^appPermission\.name(\d)$/
const DESC_KEY = /^appPermission\.desc(\d)$/

/**
 * 共享 TFunction 的文案注入。
 * 标题/说明沿用 web `appPermission` 词表;必需/可选与页脚沿用共享屏中文口径。
 */
export function createAppPermissionT(t: (key: string) => string): TFunction {
  return (key) => {
    if (key === 'appPermission.title') return t('title')
    if (key === 'appPermission.intro') return t('subtitle')
    if (key === 'common.back') return '返回'
    if (key === 'appPermission.required') return '必须'
    if (key === 'appPermission.optional') return '可选'
    if (key === 'appPermission.footer') return '您可随时在浏览器或系统设置中管理相关权限'
    const nameMatch = NAME_KEY.exec(key)
    if (nameMatch) return PERMISSION_COPY[Number(nameMatch[1])]?.name ?? key
    const descMatch = DESC_KEY.exec(key)
    if (descMatch) return PERMISSION_COPY[Number(descMatch[1])]?.desc ?? key
    return key
  }
}
