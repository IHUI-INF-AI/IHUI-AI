'use client'

import { useMemo } from 'react'
import { useMessages } from 'next-intl'
import type { TFunction } from '@ihui/types'

/** 按全键路径(如 `agreement.subtitle`)从 next-intl messages 取字符串。 */
function readMessage(source: unknown, key: string): string | null {
  let cursor: unknown = source
  for (const part of key.split('.')) {
    if (!cursor || typeof cursor !== 'object') return null
    cursor = (cursor as Record<string, unknown>)[part]
  }
  return typeof cursor === 'string' ? cursor : null
}

/** 共享屏 TFunction 的 `{name}` 插值,与 RN 端 i18n 口径一致。 */
function interpolate(template: string, values?: Record<string, string | number>): string {
  if (!values) return template
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    name in values ? String(values[name]) : match,
  )
}

/**
 * next-intl messages → 共享屏通用 TFunction。
 *
 * 共享屏(packages/app)只认 `(key, options) => string` 的全键路径签名,web 侧用本适配器
 * 把 next-intl 的词表接上,避免每个试点页各写一遍取词逻辑。
 */
export function useSharedScreenT(): TFunction {
  const messages = useMessages()
  return useMemo<TFunction>(
    () => (key, options) => {
      const template = readMessage(messages, key)
      return template === null ? key : interpolate(template, options)
    },
    [messages],
  )
}
