/**
 * web ICP 备案页 → 共享 IcpRecordScreen 视图模型的适配层。
 *
 * 改造前 web 页自持 6 行静态数据(备案号/主体/主体类型/时间/链接/范围),其中
 * 「备案链接」「备案范围」两行共享屏改造前没有展示位。共享屏新增 `scope` /
 * `recordUrl` / `onOpenRecordUrl` 三个**可选** prop 后,web 只做词条注入与两行数据
 * 透传;其余 6 行仍以共享屏为单一事实源(与 RN/小程序同源),本层不复制实现。
 */

import type { TFunction } from '@ihui/types'

/** 共享词条全键 → web `settings` 命名空间相对键。 */
const SHARED_KEY_TO_PAGE: Record<string, string> = {
  'icpRecord.title': 'icpRecordCardTitle',
  'icpRecord.label0': 'icpRecordNumber',
  'icpRecord.label2': 'icpRecordEntity',
  'icpRecord.label3': 'icpRecordEntityType',
  'icpRecord.label5': 'icpRecordTime',
  'icpRecord.scope': 'icpRecordScope',
  'icpRecord.url': 'icpRecordUrl',
  'icpRecord.footer': 'icpRecordNotice',
}

/** web 词表没有、但共享屏会渲染的键(仅在这两行传值时可达)。 */
const WEB_MISSING_KEYS: Record<string, string> = {
  'icpRecord.label1': '公安网安备号',
  'icpRecord.label4': '域名',
}

/**
 * 共享 TFunction 的文案注入:业务词条走 web 既有 `settings` 词表;
 * `common.back` 为共享屏通用返回文案(web 词表无该键,沿用中文口径)。
 */
export function createIcpRecordT(t: (key: string) => string): TFunction {
  return (key) => {
    if (key === 'common.back') return '返回'
    const missing = WEB_MISSING_KEYS[key]
    if (missing) return missing
    const mapped = SHARED_KEY_TO_PAGE[key]
    return mapped ? t(mapped) : key
  }
}
