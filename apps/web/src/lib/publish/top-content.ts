/**
 * 内容复盘排序:把“哪篇值得继续写”从事后感觉变成可核对的一行。
 * 只排有阅读/播放快照的内容;并列时先看点赞,再看标题稳定排序。
 */

export interface ContentPlatformPerformance {
  readonly platform: string
  readonly taskId: string
  readonly views: number
  readonly likes: number
  readonly comments: number
  readonly shares: number
  readonly posts: number
  readonly publishedAt: string | null
  readonly publishedUrl: string | null
}

export interface ContentPerformance {
  readonly taskId: string
  readonly title: string
  readonly platform: string
  readonly views: number
  readonly likes: number
  readonly comments: number
  readonly shares: number
  readonly publishedAt: string | null
  readonly publishedUrl: string | null
  readonly platformKeys?: ReadonlyArray<string>
  readonly platformCount?: number
  readonly posts?: number
  readonly platforms?: ReadonlyArray<ContentPlatformPerformance>
}

export function dedupeContent(
  items: ReadonlyArray<ContentPerformance>,
): ContentPerformance[] {
  const byKey = new Map<string, ContentPerformance>()
  for (const item of items) {
    const key = `${item.taskId}:${item.platform}`
    const previous = byKey.get(key)
    if (!previous) {
      byKey.set(key, item)
      continue
    }
    const prevAt = previous.publishedAt ?? ''
    const nextAt = item.publishedAt ?? ''
    if (nextAt > prevAt) byKey.set(key, item)
  }
  return Array.from(byKey.values())
}

export function rankTopContent(
  items: ReadonlyArray<ContentPerformance>,
  limit = 5,
): ContentPerformance[] {
  const safeLimit =
    Number.isFinite(limit) && limit >= 1 ? Math.min(20, Math.floor(limit)) : 5
  return items
    .filter(
      (item) =>
        item.title.trim().length > 0 &&
        Number.isFinite(item.views) &&
        item.views > 0 &&
        Number.isFinite(item.likes) &&
        item.likes >= 0,
    )
    .slice()
    .sort(
      (a, b) =>
        b.views - a.views ||
        b.likes - a.likes ||
        a.title.localeCompare(b.title, 'zh-CN'),
    )
    .slice(0, safeLimit)
}
