/**
 * 工具活动列表窗口化(2026-10-29 立)。
 *
 * 为什么需要:一轮对话里几十上百个工具卡会把 DOM 撑爆(每张卡都带 StreamRow /
 * 展开明细 / 可能的内联 diff),长会话滚动与首帧渲染都被拖慢。消息级窗口化
 * (`windowing.ts`)管的是"挂哪些消息",管不到"单条消息里挂多少张工具卡";
 * 本文件补的就是这一格:**默认只挂首段,用户点一下再全量挂载**。
 *
 * 与 `windowing.ts` 的分工(不重复实现):
 * - `windowing.ts` 判消息行级别(阈值 60 / 缓冲 6 / 上限 120),是几何驱动;
 * - 本文件判单条消息内的工具卡计数,是交互驱动(展开即全量),不读 DOM、不碰 state。
 *
 * 纯函数、无副作用:未越限时原样返回入参引用(不复制数组),越限且未展开时
 * 才切出前 `limit` 条 —— 调用方拿到的 `visible` 直接进 `.map`,不需要再包一层。
 */

/** 默认窗口大小:单条消息内最多挂载的工具卡数(超出走「展开其余 N 项」)。 */
export const ACTIVITY_WINDOW_LIMIT = 40

export interface ActivityWindow<T> {
  /** 本次应挂载的条目(展开或未越限时即原数组)。 */
  readonly visible: readonly T[]
  /** 被折叠掉的条目数;0 表示不需要「展开更多」入口。 */
  readonly hiddenCount: number
}

/**
 * 按窗口大小切分工具活动列表。
 *
 * 语义(测试逐条锁):
 * ① 未展开且总数 > limit ⇒ 只返回前 limit 条,hiddenCount = 总数 - limit;
 * ② 已展开或总数 ≤ limit ⇒ 全量返回,hiddenCount = 0(同一引用,不做无谓拷贝);
 * ③ 不修改入参、不依赖外部状态,同一入参恒得同一结果。
 *
 * 注意 `expanded` 是**消息级**状态且不持久化:流式追加导致总数变化时,
 * 已展开的消息保持展开(布尔不变),未展开的消息按新长度重算 hiddenCount。
 */
export function windowActivities<T>(
  items: readonly T[],
  limit: number = ACTIVITY_WINDOW_LIMIT,
  expanded: boolean = false,
): ActivityWindow<T> {
  // 上限归一:脏值(NaN/Infinity)回落默认档,负数按 0 处理 —— 保证 hiddenCount
  // 永远是"被折叠的条数",不会出现负数或 NaN 把界面文案带歪。
  const effectiveLimit = Number.isFinite(limit)
    ? Math.max(0, Math.floor(limit))
    : ACTIVITY_WINDOW_LIMIT
  if (expanded || items.length <= effectiveLimit) {
    return { visible: items, hiddenCount: 0 }
  }
  return {
    visible: items.slice(0, effectiveLimit),
    hiddenCount: items.length - effectiveLimit,
  }
}
