/**
 * 从「旧全文 / 新全文」得到逐文件增删行数。
 *
 * 不另写一套 diff：直接复用 `@ihui/shared/attribution` 的 Myers 行级差异
 * (`computeDiffHunks`),与 AI 行归因、人工编辑解析共用同一个真相源。
 * 超大文件由共享层按预算退化为「公共前缀/后缀单 hunk」,此时行数仍是真实内容
 * 的可证明下界而非伪造精确值。
 */
import { computeDiffHunks } from '@ihui/shared/attribution'

export interface DiffLineStats {
  additions: number
  deletions: number
}

export function diffStatsFromContents(
  oldContent: string | null | undefined,
  newContent: string | null | undefined,
): DiffLineStats {
  const before = oldContent ?? ''
  const after = newContent ?? ''
  if (!before && !after) return { additions: 0, deletions: 0 }
  let additions = 0
  let deletions = 0
  for (const hunk of computeDiffHunks(before, after)) {
    for (const line of hunk.lines) {
      if (line.kind === 'add') additions += 1
      else if (line.kind === 'del') deletions += 1
    }
  }
  return { additions, deletions }
}
