// 图片"点开看"的唯一出口(D129 的可点击那一半)。
//
// 为什么要有这个文件:此前只有助手侧渲染器 (`markdown-stream.tsx` 的 `MarkdownImage`) 会点开图片,
// 判据是"外链走 window.open,其余交给工作面板"。用户自己上传的图(D129 刚把它从源码渲染成真实图片)
// 需要的正是同一套行为 —— 在组件里再抄一份 `if (isExternal) window.open(...)` 就是"两处算同一件事",
// 而漂开的表现是"助手发的图能点开、用户传的图点不开"这种没人会去归因的差异。
//
// 一条纪律:来源档位一律用 `WorkPanelOpenSource`(定义在 work-panel store,只有一处),
// 新调用方**必须**带自己的 source,不得复用 'markdown-image' 冒充 —— 埋点与"最近访问"都按它分流。
import { useWorkPanelStore, type WorkPanelOpenSource } from '@/stores/work-panel'

/** 外链开新窗口(不放进面板:跨站内容嵌进同域面板会带来鉴权与 CSP 两类问题);其余交给工作面板。 */
export function openImageSource(src: string, source: WorkPanelOpenSource): void {
  const url = src.trim()
  if (url.length === 0) return
  if (/^https?:\/\//i.test(url)) {
    window.open(url, '_blank', 'noopener,noreferrer')
    return
  }
  useWorkPanelStore.getState().openPanel({ url, source })
}
