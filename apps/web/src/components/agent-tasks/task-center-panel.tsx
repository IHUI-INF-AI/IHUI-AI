'use client'

/**
 * TaskCenterPanel — AI 面板里的“任务中心”主视图。
 *
 * 普通用户默认看到 AgentTaskCenter（人话列表/详情/空态/错误态）；
 * “技术视图”仍复用既有 UnifiedTaskDashboard，保留四源聚合、搜索、筛选与启停能力，
 * 但不再作为普通用户的第一视线。
 */

import * as React from 'react'
import { useTranslations } from 'next-intl'
import { ArrowLeft } from 'lucide-react'

import { Button } from '@ihui/ui-react'

import { UnifiedTaskDashboard } from '@/components/agents/UnifiedTaskDashboard'
import { AgentTaskCenter } from './agent-task-center'

export function TaskCenterPanel() {
  const t = useTranslations('agentTaskCenter')
  const [technical, setTechnical] = React.useState(false)

  if (technical) {
    return (
      <div
        className="relative z-10 space-y-2 rounded-xl bg-background p-2"
        data-testid="task-center-technical"
      >
        <Button variant="ghost" size="xs" onClick={() => setTechnical(false)}>
          <ArrowLeft className="h-3.5 w-3.5" />
          {t('backToTasks')}
        </Button>
        <UnifiedTaskDashboard />
      </div>
    )
  }

  return (
    <div data-testid="task-center-panel">
      <AgentTaskCenter variant="panel" onToggleTechnical={() => setTechnical(true)} />
    </div>
  )
}
