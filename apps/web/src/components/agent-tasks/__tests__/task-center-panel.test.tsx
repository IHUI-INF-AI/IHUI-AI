// @vitest-environment jsdom
import * as React from 'react'
import { afterEach, describe, expect, it, vi } from 'vitest'
import { cleanup, fireEvent, render, screen } from '@testing-library/react'

vi.mock('next-intl', () => ({
  useTranslations: () => (key: string) =>
    ({
      technicalView: '技术视图',
      backToTasks: '返回任务列表',
    })[key] ?? key,
}))
vi.mock('../agent-task-center', () => ({
  AgentTaskCenter: ({ onToggleTechnical }: { onToggleTechnical?: () => void }) => (
    <button type="button" data-testid="agent-task-center-mock" onClick={onToggleTechnical}>
      普通列表
    </button>
  ),
}))
vi.mock('@/components/agents/UnifiedTaskDashboard', () => ({
  UnifiedTaskDashboard: () => <div data-testid="unified-task-dashboard-mock" />,
}))

import { TaskCenterPanel } from '../task-center-panel'

afterEach(() => cleanup())

describe('TaskCenterPanel', () => {
  it('默认是普通任务列表，技术视图按需切换并可返回', () => {
    render(<TaskCenterPanel />)

    expect(screen.getByTestId('agent-task-center-mock')).toBeTruthy()
    expect(screen.queryByTestId('unified-task-dashboard-mock')).toBeNull()

    fireEvent.click(screen.getByTestId('agent-task-center-mock'))
    expect(screen.getByTestId('unified-task-dashboard-mock')).toBeTruthy()

    fireEvent.click(screen.getByText('返回任务列表'))
    expect(screen.getByTestId('agent-task-center-mock')).toBeTruthy()
  })
})
