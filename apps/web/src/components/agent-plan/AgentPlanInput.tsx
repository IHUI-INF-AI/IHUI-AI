'use client'

import { useState } from 'react'
import { useTranslations } from 'next-intl'
import { Sparkles, Loader2 } from 'lucide-react'
import { Button, Input } from '@ihui/ui-react'
import { Textarea } from '@/components/form'
import type { CreateAgentPlanInput } from '@ihui/api-client'

interface Props {
  busy: boolean
  onGenerate: (input: CreateAgentPlanInput) => void
}

export function AgentPlanInput({ busy, onGenerate }: Props) {
  const t = useTranslations('agentPlan')
  const [goal, setGoal] = useState('')
  const [sessionId, setSessionId] = useState('')
  const [model, setModel] = useState('')

  const canSubmit = goal.trim().length > 0 && !busy

  const submit = () => {
    if (!canSubmit) return
    onGenerate({
      goal: goal.trim(),
      session_id: sessionId.trim() || undefined,
      model: model.trim() || undefined,
    })
  }

  return (
    <div className="flex flex-col gap-4">
      <div className="flex flex-col gap-2">
        <label htmlFor="agent-plan-goal" className="text-sm font-medium">
          {t('goalLabel')}
        </label>
        <Textarea
          id="agent-plan-goal"
          autoResize
          value={goal}
          onChange={(e) => setGoal(e.target.value)}
          placeholder={t('goalPlaceholder')}
          className="min-h-[120px]"
        />
      </div>

      <div className="grid grid-cols-1 gap-4 sm:grid-cols-2">
        <div className="flex flex-col gap-2">
          <label htmlFor="agent-plan-session" className="text-sm font-medium">
            {t('sessionLabel')}
          </label>
          <Input
            id="agent-plan-session"
            value={sessionId}
            onChange={(e) => setSessionId(e.target.value)}
            placeholder={t('sessionPlaceholder')}
            disabled={busy}
          />
        </div>
        <div className="flex flex-col gap-2">
          <label htmlFor="agent-plan-model" className="text-sm font-medium">
            {t('modelLabel')}
          </label>
          <Input
            id="agent-plan-model"
            value={model}
            onChange={(e) => setModel(e.target.value)}
            placeholder={t('modelPlaceholder')}
            disabled={busy}
          />
        </div>
      </div>

      <div className="flex items-center justify-end">
        <Button onClick={submit} disabled={!canSubmit}>
          {busy ? (
            <>
              <Loader2 className="animate-spin" />
              {t('generating')}
            </>
          ) : (
            <>
              <Sparkles />
              {t('generate')}
            </>
          )}
        </Button>
      </div>
    </div>
  )
}
