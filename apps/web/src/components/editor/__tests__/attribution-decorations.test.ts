import { describe, expect, it } from 'vitest'
import { buildAttributionDecorations } from '../attribution-decorations'
import type { AttributionSource } from '@ihui/shared/attribution'

describe('buildAttributionDecorations — UI 最小面', () => {
  it('连续 ai 行合并为一个整行区间', () => {
    const sources: AttributionSource[] = ['human', 'ai', 'ai', 'human']
    const decos = buildAttributionDecorations(sources)
    expect(decos).toHaveLength(1)
    expect(decos[0]?.range).toMatchObject({ startLineNumber: 2, endLineNumber: 3 })
    expect(decos[0]?.options.className).toBe('ihui-attr-ai-line')
  })

  it('ai-then-human 用琥珀类,不与 ai 合并', () => {
    const sources: AttributionSource[] = ['ai', 'ai-then-human', 'ai']
    const decos = buildAttributionDecorations(sources)
    expect(decos.map((d) => d.options.className)).toEqual([
      'ihui-attr-ai-line',
      'ihui-attr-ai-then-human-line',
      'ihui-attr-ai-line',
    ])
  })

  it('纯 human 行不着色(零 decoration)', () => {
    expect(buildAttributionDecorations(['human', 'human'])).toEqual([])
  })

  it('空数组 / undefined 不产生 decoration(关闭开关即走此路径)', () => {
    expect(buildAttributionDecorations([])).toEqual([])
    expect(buildAttributionDecorations(undefined)).toEqual([])
  })

  it('行号从 1 起、末行闭区间对齐', () => {
    const sources: AttributionSource[] = ['human', 'human', 'ai']
    const decos = buildAttributionDecorations(sources)
    expect(decos[0]?.range).toMatchObject({ startLineNumber: 3, endLineNumber: 3, startColumn: 1 })
  })
})
