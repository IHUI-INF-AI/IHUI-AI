/**
 * 逐行来源 → Monaco 整行装饰(纯函数,便于单测)。
 * 连续同源行合并成一个区间;只对 'ai' 与 'ai-then-human' 着色,'human' 不着色。
 */
import type { AttributionSource } from '@ihui/shared/attribution'

export interface AttributionDecoration {
  range: { startLineNumber: number; startColumn: number; endLineNumber: number; endColumn: number }
  options: { isWholeLine: boolean; className: string; hoverMessage: { value: string } }
}

const CLASS_BY_SOURCE: Record<string, string> = {
  ai: 'ihui-attr-ai-line',
  'ai-then-human': 'ihui-attr-ai-then-human-line',
}

export function buildAttributionDecorations(
  sources: readonly AttributionSource[] | undefined,
): AttributionDecoration[] {
  if (!sources || sources.length === 0) return []
  const decorations: AttributionDecoration[] = []
  let runStart = 0
  for (let i = 1; i <= sources.length; i += 1) {
    const ended = i === sources.length || sources[i] !== sources[runStart]
    if (!ended) continue
    const source = sources[runStart] ?? 'human'
    const className = CLASS_BY_SOURCE[source]
    if (className && runStart < i) {
      decorations.push({
        range: { startLineNumber: runStart + 1, startColumn: 1, endLineNumber: i, endColumn: 1 },
        options: {
          isWholeLine: true,
          className,
          hoverMessage: {
            value: source === 'ai' ? 'AI 写入,尚未被人工改动' : 'AI 写入后已被人工改动',
          },
        },
      })
    }
    runStart = i
  }
  return decorations
}
