'use client'

import * as React from 'react'
import { useTopBarBack } from '@/stores/topbar-back'

interface BackButtonProps {
  /** 无浏览器历史(直接打开/新标签页)时的降级路由,默认 '/' */
  fallbackHref?: string
}

/**
 * BackButton — 统一页面返回键声明器(2026-09-08 重构)
 *
 * 2026-09-08 用户需求:工作展示区所有页面的返回键彻底统一收敛到顶栏
 * 「搜索按钮右侧、加号左侧」单一位置,带拉出动画;无返回需求的页面不显示。
 *
 * 本组件不再渲染任何 DOM(页面内联返回按钮全部废除),改为向
 * topbar-back store 注册返回意图;唯一渲染点 = GlobalTopBar 的 TopBarBackButton:
 * - 优先 router.back()(保留滚动位置 + 浏览器历史)
 * - 无 history(直接打开/新标签页)时降级到 fallbackHref
 *
 * 用法:子页面挂载 `<BackButton fallbackHref="..." />`(渲染 null,仅注册)。
 */
export function BackButton({ fallbackHref = '/' }: BackButtonProps) {
  const config = React.useMemo(() => ({ fallbackHref }), [fallbackHref])
  useTopBarBack(config)
  return null
}
