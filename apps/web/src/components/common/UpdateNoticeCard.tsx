'use client'

import * as React from 'react'
import { RefreshCw } from 'lucide-react'
import { CloseButton } from '@ihui/ui-react'
import { cn } from '@/lib/utils'

export interface UpdateNoticeCardProps {
  /** 主标题(如「有新版本可用」)。 */
  title: string
  /** 副标题(如「刷新页面以获取最新版本」)。 */
  body: string
  /** 主按钮文案(如「更新」)。 */
  actionLabel: string
  /** 关闭按钮的无障碍名称。 */
  closeLabel: string
  onAction: () => void
  /** 不传 = 不可关闭(强更场景由调用方决定是否给关闭口)。 */
  onClose?: () => void
  /** 动作进行中:按钮置灰防重复点击。 */
  busy?: boolean
  className?: string
}

/**
 * 更新提示卡片(2026-10-27 立):web 端所有"有新版本"提示的唯一视觉实现。
 *
 * 为什么抽这一层:同一个卡片此前在 PWAUpdatePrompt 里手写、版本闸门若再手写一份就是第二份
 * (本仓铁律:同类 UI 实现全仓只许一份,第二份必然漂移)。RN 端 components/UpdatePrompt.tsx
 * 按同一版式同构实现(图标 primary + 标题 + 副标题 + cta 主按钮 + 关闭 X),两端文案走
 * packages/i18n 的同一份 appUpdate 命名空间 ⇒ 视觉与措辞都由单一真相源决定。
 */
export function UpdateNoticeCard({
  title,
  body,
  actionLabel,
  closeLabel,
  onAction,
  onClose,
  busy = false,
  className,
}: UpdateNoticeCardProps) {
  return (
    <div className={cn('flex items-center gap-3 rounded-lg border bg-card p-3 shadow', className)}>
      <RefreshCw className="h-5 w-5 shrink-0 text-primary" />
      <div className="flex-1 min-w-0 text-sm">
        <p className="font-medium">{title}</p>
        <p className="text-xs text-muted-foreground">{body}</p>
      </div>
      <button
        type="button"
        onClick={onAction}
        disabled={busy}
        className="rounded-sm bg-cta px-3 py-1.5 text-xs font-medium text-cta-foreground hover:bg-cta/90 disabled:opacity-60"
      >
        {actionLabel}
      </button>
      {onClose ? <CloseButton aria-label={closeLabel} onClick={onClose} /> : null}
    </div>
  )
}
