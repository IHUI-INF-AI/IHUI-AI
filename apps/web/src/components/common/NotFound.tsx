import * as React from 'react'
import { Xiaofang } from '@/components/brand/Xiaofang'
import { cn } from '@/lib/utils'

interface NotFoundProps {
  title?: string
  description?: string
  action?: React.ReactNode
  code?: number | string
  className?: string
}

export function NotFound({
  title = '页面未找到',
  description = '您访问的页面不存在或已被移动',
  action,
  code = 404,
  className,
}: NotFoundProps) {
  return (
    <div
      className={cn(
        'flex flex-col items-center justify-center gap-4 px-4 py-12 text-center',
        className,
      )}
    >
      {/* 404 专属品牌位(2026-11-15):「小方也迷路了」比裸数字更有记忆点;
          403 保留纯文字(code 非 404 不渲染),避免"没权限"被误读成"页面不存在"。
          静态 404 由 BuildBrand404 走同一组件,原生 img 不依赖 Next Image 运行时。 */}
      {String(code) === '404' && (
        <Xiaofang variant="lost" size={148} alt="" priority className="mx-auto" />
      )}
      <div className="text-6xl font-bold text-muted-foreground/30 min-[640px]:text-7xl">{code}</div>
      <h1 className="text-heading font-semibold min-[640px]:text-display">{title}</h1>
      <p className="max-w-md text-body text-muted-foreground">{description}</p>
      {action && <div className="mt-2">{action}</div>}
    </div>
  )
}
