import type { ReactElement } from 'react'
import { Pin, PinOff } from 'lucide-react'
import { cn } from '@/lib/utils'

/**
 * PinToggleIcon — 「置顶类」常驻开关的图标唯一实现（2026-11-21 立）。
 *
 * 语义：图标描述**当前状态**，不是"点下去会发生什么"。
 *   pressed=true  → 实心图钉（已钉住）
 *   pressed=false → 划掉的图钉（未钉住）
 *
 * 立因（用户实报"窗口置顶按钮逻辑正好相反"）：常驻开关带 `aria-pressed` + 高亮底，
 * 且常与 Min/Max/Close 这类纯状态按钮同簇；此时若按动作画图标（pressed 时画 PinOff），
 * 视觉读法就变成"当前没开启"，与高亮态正好相反。功能链路本身没错，错在图标语义。
 *
 * 不归本组件管的两种（各自语义正确，勿改成状态式）：
 * - 一次性菜单项：动作图标 + 文字（"置顶 / 取消置顶"），点完即执行；
 * - 展开/收起控件（aria-expanded，如侧栏搜索的 X）：面板本身可见，X 表示"点我收起"。
 *
 * 守门：scripts/check-toggle-icon-semantics.mjs（拦 aria-pressed 真值支画 PinOff 等解除型图标）。
 */
export function PinToggleIcon({
  pressed,
  className,
}: {
  /** 当前是否已置顶（真值 = 已钉住） */
  pressed: boolean
  className?: string
}): ReactElement {
  if (pressed) {
    return <Pin aria-hidden className={cn('fill-current', className)} />
  }
  return <PinOff aria-hidden className={className} />
}
