import * as React from 'react'
import { cn } from '@/lib/utils'

/**
 * PageContainer — (main) 路由组页面级统一容器(2026-09-04 立)
 *
 * 背景:MainShell 的 <main> 自 2026-08-01 起完全去掉 padding(用户要求内容占满工作区),
 * 约定为"需要留白的页面自行在页面组件内加"。但大量页面遗漏了水平留白,导致内容贴边。
 * 本组件收口该约定:默认 `px-4 py-4`,页面外层直接用它包裹,不再手写留白类。
 *
 * 用法:
 *   <PageContainer>                     → px-4 py-4(标准内容页)
 *   <PageContainer className="space-y-4"> → 追加布局类(最常见)
 *   <PageContainer padded={false}>      → 全出血页(home/编辑器等有意贴边的页面)
 */
interface PageContainerProps extends React.HTMLAttributes<HTMLDivElement> {
  /** 关闭水平/垂直留白(用于全屏/编辑器等有意出血的页面),默认 true */
  padded?: boolean
}

export function PageContainer({ padded = true, className, children, ...props }: PageContainerProps) {
  return (
    <div className={cn(padded && 'px-4 py-4', className)} {...props}>
      {children}
    </div>
  )
}

export default PageContainer
