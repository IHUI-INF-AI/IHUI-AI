import { readFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

import { describe, expect, it } from 'vitest'

const here = dirname(fileURLToPath(import.meta.url))
const src = (file: string): string => readFileSync(resolve(here, '..', file), 'utf8')

describe('遥测上报面的 URL 凭据段剥离接线(G-855)', () => {
  it("① 两个上报站点都必须走共享层唯一出口,不得各写 split('?')[0]", () => {
    for (const file of ['VisitTracker.tsx', 'AnalyticsCapture.tsx']) {
      const text = src(file)
      expect(text).toContain('stripUrlCredentialSegments')
      expect(text).toContain('@ihui/shared/utils/sanitize-url')
    }
  })

  it('② VisitTracker 落库字段取的是剥过的那一份,而不是原文 location.search', () => {
    const text = src('VisitTracker.tsx')
    expect(text).toMatch(/const path = stripUrlCredentialSegments\(/)
    expect(text).not.toMatch(/url: window\.location\.pathname \+ window\.location\.search/)
    expect(text).toMatch(/referer: stripUrlCredentialSegments\(/)
  })

  it('③ AnalyticsCapture 的 label 与 props.url 都取剥过的 href(签名下载链接的 label 也会带 ?sig=)', () => {
    const text = src('AnalyticsCapture.tsx')
    expect(text).toMatch(/safeHref\.split\('\/'\)\.pop\(\)/)
    expect(text).toMatch(/url: safeHref\.slice\(/)
    expect(text).not.toMatch(/url: href\.slice\(/)
  })
})
