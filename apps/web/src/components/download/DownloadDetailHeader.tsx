'use client'

import { Calendar, CheckCircle2, Package } from 'lucide-react'

import { Card } from '@ihui/ui-react'
import type { PlatformMeta } from '@/config/downloads.config'
import type { DownloadEntry } from '@/lib/downloads'

/**
 * 详情页头部卡:平台图标 + 名称 + 版本 + 发布日期 + 状态徽章。
 *
 * `isAvailable` 由调用方按 `isPlatformLaunched(meta)` 传入 —— 徽章与「尚未上线」态的
 * 可选平台清单必须是同一个判据,不能在这里再算一遍。
 */
export function DownloadDetailHeader({
  icon: Icon,
  label,
  meta,
  isAvailable,
  t,
}: {
  icon: DownloadEntry['icon']
  label: string
  meta: PlatformMeta
  isAvailable: boolean
  t: (key: string) => string
}) {
  return (
    <Card className="mb-6 p-3">
      <div className="flex flex-col gap-4 sm:flex-row sm:items-center sm:justify-between">
        <div className="flex items-center gap-4">
          <div className="flex h-14 w-14 shrink-0 items-center justify-center rounded-md bg-cta/10 text-primary">
            <Icon className="h-7 w-7" />
          </div>
          <div className="min-w-0">
            <h1 className="flex items-center gap-2 text-heading font-semibold text-foreground">
              <span>{label}</span>
              {meta.version && (
                <span className="rounded-sm bg-muted px-1.5 py-0.5 text-label font-medium text-muted-foreground">
                  v{meta.version}
                </span>
              )}
            </h1>
            <div className="mt-1 flex flex-wrap items-center gap-x-3 gap-y-1 text-label text-muted-foreground">
              {meta.releaseDate && (
                <span className="inline-flex items-center gap-1">
                  <Calendar className="h-3 w-3" />
                  {meta.releaseDate}
                </span>
              )}
              {isAvailable ? (
                <span className="inline-flex items-center gap-1 text-emerald-600 dark:text-emerald-400">
                  <CheckCircle2 className="h-3 w-3" />
                  {t('downloadAvailable')}
                </span>
              ) : (
                <span className="inline-flex items-center gap-1 text-amber-600 dark:text-amber-400">
                  <Package className="h-3 w-3" />
                  {t('downloadComingSoon')}
                </span>
              )}
            </div>
          </div>
        </div>
      </div>
    </Card>
  )
}
