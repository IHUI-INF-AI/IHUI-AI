// 回归:统一查看器把带鉴权文件取成 blob: 后,地址本身没有后缀。
// FilePreview 的 office 分支过去从 url 猜 ext,导致 OfficePreview 永远收到空 ext,
// docx/xlsx/pptx 全部显示“该文件类型不支持预览”。这里锁死显式 ext 的传递。
import { afterEach, describe, expect, it, vi } from 'vitest'
import React from 'react'
import { cleanup, render, screen } from '@testing-library/react'
import { FilePreview } from '../FilePreview'

vi.mock('next-intl', () => ({
  useTranslations: () => (key: string) => key,
}))

vi.mock('../office-preview', () => ({
  SUPPORTED_EXTS: new Set(['docx', 'xlsx', 'xls', 'pptx']),
  OfficePreview: ({ ext }: { ext: string }) =>
    React.createElement('div', {
      'data-testid': 'office-preview-stub',
      'data-ext': ext,
    }),
}))

vi.mock('../PDFViewer', () => ({
  PDFViewer: () => React.createElement('div', { 'data-testid': 'pdf-viewer-stub' }),
}))

afterEach(cleanup)

describe('FilePreview 显式扩展名', () => {
  it('blob url + type=office + ext=docx:OfficePreview 收到 docx,不再判 unsupported', () => {
    render(<FilePreview url="blob:http://localhost/abc" type="office" ext="docx" />)
    expect(screen.getByTestId('office-preview-stub').getAttribute('data-ext')).toBe('docx')
  })

  it('显式 ext 大小写与前导点归一后再交给 OfficePreview', () => {
    render(<FilePreview url="blob:http://localhost/abc" type="office" ext=".XLSX" />)
    expect(screen.getByTestId('office-preview-stub').getAttribute('data-ext')).toBe('xlsx')
  })
})
