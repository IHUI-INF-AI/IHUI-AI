/**
 * 自定义主题卡片(2026-11-15 v4)
 *
 * 「自动修正对比度」必须按亮/暗各自的背景亮度把正文设为黑或白。
 */

import { cleanup, fireEvent, render, screen } from '@testing-library/react'
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'

vi.mock('next-intl', () => ({
  useTranslations: () => (key: string) => key,
}))

vi.mock('sonner', () => ({ toast: { success: vi.fn(), error: vi.fn() } }))

import { contrastForeground } from '@/lib/color-contrast'
import { useAppearanceStore } from '@/stores/appearance-settings'
import { CustomThemeCard } from '../custom-theme-card'

beforeEach(() => {
  useAppearanceStore.getState().resetAll()
})

afterEach(() => {
  cleanup()
})

describe('CustomThemeCard 自动对比度', () => {
  it('亮/暗两套色板的正文都按各自背景修正为黑或白', () => {
    useAppearanceStore.getState().update({
      customTheme: {
        enabled: true,
        light: {
          primary: '#18181b',
          background: '#f5f5f4',
          foreground: '#444444',
          card: '#ffffff',
          muted: '#f4f4f5',
          border: '#e4e4e7',
        },
        dark: {
          primary: '#fafafa',
          background: '#111827',
          foreground: '#777777',
          card: '#111113',
          muted: '#1f1f23',
          border: '#2a2a2f',
        },
      },
    })

    render(<CustomThemeCard />)
    fireEvent.click(screen.getByTestId('appearance-custom-theme-auto-contrast'))

    const theme = useAppearanceStore.getState().customTheme
    expect(theme.light.foreground).toBe(contrastForeground('#f5f5f4'))
    expect(theme.dark.foreground).toBe(contrastForeground('#111827'))
    expect(theme.light.foreground).toBe('#000000')
    expect(theme.dark.foreground).toBe('#ffffff')
    // 背景不被改动
    expect(theme.light.background).toBe('#f5f5f4')
    expect(theme.dark.background).toBe('#111827')
  })
})
