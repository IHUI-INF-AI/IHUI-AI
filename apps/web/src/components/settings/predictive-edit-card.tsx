'use client'

/**
 * PredictiveEditCard — 设置页「预测式编辑」开关卡片(V3 #82 两把钥匙之"开关"位的 UI 入口)。
 *
 * 这一位只管用户意志(要不要这个功能);"这次内容够不够格问"是另一把钥匙
 * (`lib/predictive-edit-api` 的门槛位),两者互不替代 —— 合并成一个布尔
 * 就会把"关了所以没建议"和"模型判了没有编辑意图"折成同一张脸。
 * 状态绑定 predictive-edit store(`ihui-predictive-edit-prefs`,persist 工厂惯例),
 * 与 WebSearchCard 同层同形,不自建第二套开关机制。
 */

import * as React from 'react'
import { useTranslations } from 'next-intl'
import { Sparkles } from 'lucide-react'

import { Card, CardContent, CardHeader, CardTitle, Switch } from '@ihui/ui-react'

import { usePredictiveEditPrefsStore } from '@/stores/predictive-edit'

/** 设置页「预测式编辑」开关卡片 */
export function PredictiveEditCard() {
  const t = useTranslations('chat')
  const enabled = usePredictiveEditPrefsStore((s) => s.enabled)
  const setEnabled = usePredictiveEditPrefsStore((s) => s.setEnabled)

  return (
    <Card data-testid="predictive-edit-card">
      <CardHeader>
        <CardTitle className="flex items-center gap-2 text-base">
          <Sparkles className="h-4 w-4" />
          {t('predictiveEditSetting')}
        </CardTitle>
      </CardHeader>
      <CardContent>
        <div className="flex items-center justify-between gap-3">
          <span className="font-[weight:inherit] min-w-0 flex-1 text-body text-muted-foreground">
            {t('predictiveEditSettingDesc')}
          </span>
          <Switch
            id="settings-predictive-edit"
            data-testid="settings-predictive-edit"
            checked={enabled}
            onCheckedChange={setEnabled}
            className="shrink-0"
          />
        </div>
      </CardContent>
    </Card>
  )
}
