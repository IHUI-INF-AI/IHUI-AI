'use client'

import * as React from 'react'
import { AlertTriangle, RefreshCw } from 'lucide-react'

interface OverviewErrorProps {
  onRetry: () => void
  message?: string
}

/**
 * 只读概览卡的统一错误态(2026-10-30 补)。
 * 之前这些卡的 fetch 失败被 `.catch(() => {})` 静默吞掉,用户看到的是"空数据"而非"加载失败",
 * 无法区分"确实没数据"和"网络/鉴权出错"。本组件给出明确失败提示 + 重试入口。
 */
export function OverviewError({ onRetry, message }: OverviewErrorProps) {
  return (
    <div className="flex flex-col items-center gap-2 py-4 text-center">
      <AlertTriangle className="h-5 w-5 text-destructive" />
      <p className="text-sm text-muted-foreground">{message ?? '数据加载失败'}</p>
      <button
        type="button"
        onClick={onRetry}
        className="flex items-center gap-1 rounded-md text-sm font-medium text-primary transition-colors hover:text-primary/80"
      >
        <RefreshCw className="h-3.5 w-3.5" />
        重试
      </button>
    </div>
  )
}
