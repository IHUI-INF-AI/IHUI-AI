'use client'

/**
 * L07 首屏明示条:桥版本不匹配时显示原因,并已通过 state 模块禁用桌面入口。
 *
 * 只在 Tauri 运行时执行;浏览器里 `isTauriRuntime()` 为假,组件返回 null,
 * 不会给线上 web 增加任何可见元素。
 */

import { useEffect, useState } from 'react'
import { isLocalWebDevOrigin, isTauriRuntime } from '../lib/api-base-url'
import {
  NATIVE_BRIDGE_PROTOCOL_VERSION,
  runNativeBridgeHandshake,
  type BridgeHandshakeResult,
} from '../lib/native-bridge-handshake'
import { setNativeBridgeFeaturesEnabled } from '../lib/native-bridge-state'

export function NativeBridgeBanner() {
  const [result, setResult] = useState<BridgeHandshakeResult | null>(null)

  useEffect(() => {
    if (!isTauriRuntime()) return
    // dev 壳(窗口由本机 8801 承载)按设计不在桌面端 remote ACL 里,握手必失败;
    // 这不是"壳过期",跳过握手并保持桌面入口禁用,避免首屏误报「请更新桌面端」。
    if (isLocalWebDevOrigin()) {
      setNativeBridgeFeaturesEnabled(false)
      return
    }
    let alive = true
    void (async () => {
      const { invoke } = await import('@tauri-apps/api/core')
      const handshake = await runNativeBridgeHandshake((command) => invoke(command))
      if (!alive) return
      setNativeBridgeFeaturesEnabled(handshake.ok)
      setResult(handshake)
    })()
    return () => {
      alive = false
    }
  }, [])

  if (!result || result.ok) return null

  return (
    <div
      role="alert"
      style={{
        position: 'fixed',
        top: 0,
        left: 0,
        right: 0,
        zIndex: 9999,
        padding: '8px 12px',
        background: '#7f1d1d',
        color: '#fff',
        fontSize: 13,
        lineHeight: 1.5,
      }}
    >
      桌面桥版本不匹配（native {result.nativeVersion ?? '?'} / web 协议{' '}
      {NATIVE_BRIDGE_PROTOCOL_VERSION}）：{result.detail ?? result.reason}
      。桌面入口已禁用，请更新桌面端。
      {result.missing.length > 0 ? ` 缺失命令：${result.missing.join('、')}` : ''}
    </div>
  )
}
