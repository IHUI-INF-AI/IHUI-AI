'use client'

import { useEffect, useMemo, useState } from 'react'

export interface DocsTocItem {
  id: string
  label: string
  level?: number
}

export interface DocsTocProps {
  items: DocsTocItem[]
  heading?: string
  className?: string
}

const LEVEL_INDENT: Record<number, string> = {
  2: 'ps-4',
  3: 'ps-8',
}

export function DocsToc({ items, heading, className }: DocsTocProps) {
  const [activeId, setActiveId] = useState<string | null>(null)
  const idsKey = useMemo(() => items.map((item) => item.id).join('\n'), [items])

  useEffect(() => {
    if (typeof IntersectionObserver === 'undefined') return
    const targets = idsKey
      .split('\n')
      .filter(Boolean)
      .map((id) => document.getElementById(id))
      .filter((el): el is HTMLElement => el !== null)
    if (targets.length === 0) return
    const observer = new IntersectionObserver(
      (entries) => {
        const visible = entries.find((entry) => entry.isIntersecting)
        if (visible) setActiveId(visible.target.id)
      },
      { rootMargin: '0px 0px -60% 0px' },
    )
    for (const target of targets) observer.observe(target)
    return () => {
      observer.disconnect()
    }
  }, [idsKey])

  if (items.length === 0) return null

  return (
    <nav
      aria-label={heading ?? 'table of contents'}
      className={`rounded-lg border border-border bg-card p-3 ${className ?? ''}`.trim()}
    >
      {heading ? <p className="text-label font-medium text-foreground">{heading}</p> : null}
      <ul className="space-y-1">
        {items.map((item) => (
          <li key={item.id} className={LEVEL_INDENT[item.level ?? 1] ?? ''}>
            <a
              href={`#${item.id}`}
              aria-current={activeId === item.id ? 'true' : undefined}
              className={`block break-words text-body transition-colors ${
                activeId === item.id
                  ? 'font-medium text-foreground'
                  : 'text-muted-foreground hover:text-foreground'
              }`}
            >
              {item.label}
            </a>
          </li>
        ))}
      </ul>
    </nav>
  )
}
