import * as React from 'react'
import ReactMarkdown, { type Components } from 'react-markdown'
import remarkGfm from 'remark-gfm'

import { markdownComponents } from '@/lib/content'
import { cn } from '@/lib/utils'
import { CodeBlock } from './code-block'

/** react-markdown 的 code className 形如 `language-ts` / 语言名取不出来即视为行内代码 */
function languageOf(className: string | undefined): string | undefined {
  const matched = /language-(\w+)/.exec(className ?? '')
  return matched?.[1]
}

// 标题锚点沿用 @/lib/content 的 markdownComponents(全站唯一一份判据,§0.6),这里只补代码块
const components: Components = {
  ...markdownComponents,
  pre: ({ children }) => <>{children}</>,
  code: ({ className, children }) => {
    const text = String(children ?? '').replace(/\n$/, '')
    const language = languageOf(typeof className === 'string' ? className : undefined)
    if (language || text.includes('\n')) {
      return <CodeBlock code={text} language={language} />
    }
    return <code className={className}>{children}</code>
  },
}

export interface MarkdownBodyProps {
  content: string
  className?: string
}

/**
 * 文档正文的 Markdown 渲染层(GFM:表格 / 任务列表 / 围栏代码 / 删除线 / 自动链接)。
 * 刻意不挂 rehype-raw:正文里的裸 HTML 一律转义成文本,不开 XSS 敞口(D04 禁令)。
 */
export function MarkdownBody({ content, className }: MarkdownBodyProps): React.ReactElement {
  return (
    <div className={cn('prose prose-sm max-w-none dark:prose-invert', className)}>
      <ReactMarkdown remarkPlugins={[[remarkGfm, { singleTilde: false }]]} components={components}>
        {content}
      </ReactMarkdown>
    </div>
  )
}

export default MarkdownBody
