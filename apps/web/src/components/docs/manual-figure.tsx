import Image from 'next/image'

/**
 * 使用说明手册的「真实界面截图」图版(票 D54)。
 *
 * 唯一用途:把无头浏览器对本机在线站点实拍的工作区界面,以固定版式嵌进手册正文。
 * 禁止用于生成式假 UI / 示意图 —— 资产一律来自实拍,落 `public/images/docs/manual/`。
 *
 * 版式取自 §4 单一源头档位:圆角 `rounded-xl`(panel 角色档)、图注 `text-xs text-muted-foreground`,
 * 外边距交给所在 `<section className="space-y-3">`,组件本身不带外边距以免双重留白。
 */
export interface ManualFigureProps {
  /** 实拍截图在 public 下的路径,如 `/images/docs/manual/agent-market.png` */
  src: string
  /** 面向读屏器的界面描述(不写"示意图"字样:图就是实拍) */
  alt: string
  /** 图注:说明这是哪一屏、读者应在其中找什么 */
  caption: string
  /** 实拍视口宽(px),与截图真实像素一致 */
  width?: number
  /** 实拍视口高(px),与截图真实像素一致 */
  height?: number
}

/** 无头浏览器实拍视口默认尺寸(1440×900,Desktop Chrome 档位) */
const SHOT_VIEWPORT = { width: 1440, height: 900 } as const

export function ManualFigure({
  src,
  alt,
  caption,
  width = SHOT_VIEWPORT.width,
  height = SHOT_VIEWPORT.height,
}: ManualFigureProps) {
  return (
    <figure className="space-y-2">
      <div className="overflow-hidden rounded-xl border bg-muted/40">
        <Image
          src={src}
          alt={alt}
          width={width}
          height={height}
          className="block h-auto w-full"
        />
      </div>
      <figcaption className="font-[weight:inherit] text-label text-muted-foreground">{caption}</figcaption>
    </figure>
  )
}
