import { describe, expect, it } from 'vitest'
import { render } from '@testing-library/react'

import { DocsToc } from './docs-toc'
import type { DocsTocItem } from './docs-toc'

const ITEMS: DocsTocItem[] = [
  { id: 'auth', label: 'Auth' },
  { id: 'chat', label: 'Chat Completions', level: 1 },
  { id: 'agent-api', label: 'Agent API', level: 2 },
  { id: 'errors', label: 'Errors' },
  { id: 'sdk', label: 'SDKs', level: 3 },
]

describe('DocsToc', () => {
  it('① items 为空不渲染空壳', () => {
    const { container } = render(<DocsToc items={[]} />)
    expect(container.innerHTML).toBe('')
  })

  it('② N 条 items 渲染 N 个 href="#id" 锚点', () => {
    const { container } = render(<DocsToc items={ITEMS} />)
    const links = container.querySelectorAll('nav a')
    expect(links.length).toBe(ITEMS.length)
    for (const item of ITEMS) {
      expect(container.querySelector(`a[href="#${item.id}"]`)).not.toBeNull()
    }
  })

  it('③ label 逐条正确', () => {
    const { container } = render(<DocsToc items={ITEMS} />)
    const texts = Array.from(container.querySelectorAll('nav a')).map((a) => a.textContent)
    expect(texts).toEqual(ITEMS.map((item) => item.label))
  })

  it('④ DOM 无 hr / divide- 类 / emoji 字符', () => {
    const { container } = render(<DocsToc items={ITEMS} heading="Contents" />)
    expect(container.querySelector('hr')).toBeNull()
    const emojiPattern = /\p{Extended_Pictographic}/u
    const tokens = Array.from(container.querySelectorAll('*')).flatMap((el) =>
      (el.getAttribute('class') ?? '').split(/\s+/),
    )
    expect(tokens.some((cls) => cls.startsWith('divide-'))).toBe(false)
    expect(tokens.some((cls) => /^border-[tblr](?![a-z])/.test(cls))).toBe(false)
    expect(container.textContent).not.toMatch(emojiPattern)
    expect(container.innerHTML).not.toMatch(emojiPattern)
    expect(container.querySelector('[title]')).toBeNull()
  })
})
