import { describe, expect, it } from 'vitest'
import { render } from '@testing-library/react'
import { NextIntlClientProvider } from 'next-intl'

import { MarkdownBody } from './markdown-body'

// code-block 的复制按钮取 a11y.copyCode 作 aria-label,测试侧只喂这一条消息(不另立第二份文案源)
function renderBody(content: string) {
  return render(
    <NextIntlClientProvider locale="zh-CN" messages={{ a11y: { copyCode: '复制代码' } }}>
      <MarkdownBody content={content} />
    </NextIntlClientProvider>,
  )
}

const TABLE_MD = `| 命令 | 用途 |
| --- | --- |
| pnpm dev | 启动全栈 |
`

const CODE_MD = '```bash\npnpm dev\n```'

describe('MarkdownBody 格式渲染层', () => {
  it('① GFM 管道表格渲染成真 <table>', () => {
    const { container } = renderBody(TABLE_MD)
    expect(container.querySelector('table')).not.toBeNull()
    expect(container.querySelectorAll('tbody tr').length).toBe(1)
    expect(container.querySelector('thead th')?.textContent).toBe('命令')
  })

  it('② 围栏代码块出 <pre> + 语言标识 + 复制按钮', () => {
    const { container } = renderBody(CODE_MD)
    const pre = container.querySelector('pre')
    expect(pre).not.toBeNull()
    expect(pre?.querySelector('code')?.getAttribute('class')).toBe('language-bash')
    const label = container.querySelector('[data-testid="code-block-language"]')
    expect(label?.textContent).toBe('bash')
    const button = container.querySelector('button')
    expect(button).not.toBeNull()
    expect(button?.getAttribute('aria-label')).toBe('复制代码')
  })

  it('③ 裸 <script> 不产生可执行 HTML(rehype-raw 未开)', () => {
    const { container } = renderBody('危险输入:<script>window.x=1</script>')
    expect(container.querySelector('script')).toBeNull()
    expect(container.textContent).toContain('<script>')
  })

  it('④ 正文容器挂 prose 档(与站内既有用法一致)', () => {
    const { container } = renderBody('# 标题\n\n段落')
    const wrapper = container.firstElementChild
    expect(wrapper?.className).toContain('prose')
    expect(wrapper?.querySelector('h1')).not.toBeNull()
  })
})
