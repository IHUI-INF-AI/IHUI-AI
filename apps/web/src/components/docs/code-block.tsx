'use client'

import * as React from 'react'
import { Check, Copy } from 'lucide-react'
import { useTranslations } from 'next-intl'

import { Button } from '@ihui/ui-react'

export interface CodeBlockProps {
  code: string
  language?: string
}

/** 围栏代码块:语言角标 + 复制按钮(无语法高亮——本仓无高亮依赖档给静态文档用)。 */
export function CodeBlock({ code, language }: CodeBlockProps): React.ReactElement {
  const tA11y = useTranslations('a11y')
  const [copied, setCopied] = React.useState(false)
  const timerRef = React.useRef<number | null>(null)

  React.useEffect(() => {
    return () => {
      if (timerRef.current !== null) window.clearTimeout(timerRef.current)
    }
  }, [])

  // 复制结果在 promise 回调里落地,不读任何事件对象(§42 React 事件闭包陷阱)
  const handleCopy = React.useCallback(() => {
    navigator.clipboard
      ?.writeText(code)
      .then(() => {
        setCopied(true)
        if (timerRef.current !== null) window.clearTimeout(timerRef.current)
        timerRef.current = window.setTimeout(() => setCopied(false), 1500)
      })
      .catch(() => {})
  }, [code])

  return (
    <div className="my-4 overflow-hidden rounded-lg border border-border">
      <div className="flex items-center justify-between gap-2 bg-muted/50 px-3 py-1.5">
        <span data-testid="code-block-language" className="font-mono text-label text-muted-foreground">
          {language ?? 'text'}
        </span>
        <Button size="xs" variant="ghost" onClick={handleCopy} aria-label={tA11y('copyCode')}>
          {copied ? <Check className="h-3.5 w-3.5" /> : <Copy className="h-3.5 w-3.5" />}
        </Button>
      </div>
      <pre className="m-0 overflow-x-auto p-3">
        <code className={language ? `language-${language}` : undefined}>{code}</code>
      </pre>
    </div>
  )
}

export default CodeBlock
