'use client'

/**
 * Cookie 自动保活状态角标(2026-09-29)。
 *
 * 账号页头部一行小字,让"自动保活"可见:守护由 ai-service cookie_refresh_daemon
 * 承担(每 COOKIE_REFRESH_INTERVAL_HOURS 小时 headless 访问平台首页保活并回写
 * 轮换 cookie),本组件只读 /publish/cookie-refresh/stats 展示状态,不发任何写操作
 * ——用户不需要再逐卡片点"刷新 Cookie"。auto_enabled=false 时整行不渲染
 * (守护未开启时不假装开启)。
 */
import { useEffect, useState } from 'react'
import { useTranslations } from 'next-intl'
import { RefreshCw } from 'lucide-react'

import { getCookieRefreshStats, type CookieRefreshStats } from '@ihui/api-client'

function formatLastRun(iso: string): string {
  const d = new Date(iso)
  if (Number.isNaN(d.getTime())) return ''
  const pad = (n: number) => String(n).padStart(2, '0')
  return `${pad(d.getMonth() + 1)}-${pad(d.getDate())} ${pad(d.getHours())}:${pad(d.getMinutes())}`
}

export function CookieAutoRefreshChip() {
  const t = useTranslations('publish.cookieAutoRefresh')
  const [stats, setStats] = useState<CookieRefreshStats | null>(null)

  useEffect(() => {
    let alive = true
    getCookieRefreshStats()
      .then((r) => {
        if (alive && r.success && r.data) setStats(r.data)
      })
      .catch(() => {})
    return () => {
      alive = false
    }
  }, [])

  if (!stats || !stats.auto_enabled) return null

  return (
    <p
      className="flex items-center gap-1 text-xs text-muted-foreground"
      data-testid="cookie-auto-refresh-chip"
    >
      <RefreshCw className="h-3 w-3" aria-hidden />
      <span>{t('on', { hours: stats.interval_hours })}</span>
      <span aria-hidden>·</span>
      <span>{stats.last_run_at ? t('lastRun', { time: formatLastRun(stats.last_run_at) }) : t('pending')}</span>
    </p>
  )
}
