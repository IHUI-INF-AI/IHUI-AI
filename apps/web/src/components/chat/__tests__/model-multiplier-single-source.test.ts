/**
 * 模型积分倍率「单一来源」回归锁(2026-11-23 立)。
 *
 * 背景: 前端曾维护两份展示倍率(KNOWN_MODEL_META 手写小数 + TIER_TO_DISPLAY
 * 0.05/0.12/0.40/0.77 映射),与后端真实扣分 `points_multiplier` 各算各的。
 * 本测直接读 model-selector.tsx 源码面,钉住三条:
 *  ① 展示刻度表必须消失;
 *  ② 已知模型表不再保存任何价格;
 *  ③ 平台目录 / 号池 / 兜底三条路径都把后端值直接作为展示值。
 */
import * as fs from 'node:fs'
import * as path from 'node:path'
import { fileURLToPath } from 'node:url'

import { describe, expect, it } from 'vitest'

const HERE = path.dirname(fileURLToPath(import.meta.url))
const SELECTOR_SRC = fs.readFileSync(path.resolve(HERE, '..', 'model-selector.tsx'), 'utf8')

describe('模型积分倍率·单一来源', () => {
  it('展示刻度映射表不得复活', () => {
    expect(SELECTOR_SRC).not.toContain('TIER_TO_DISPLAY')
    expect(SELECTOR_SRC).not.toContain('tierToDisplayMultiplier')
  })

  it('已知模型表只留徽章,不再写积分倍率', () => {
    const start = SELECTOR_SRC.indexOf('const KNOWN_MODEL_META')
    const end = SELECTOR_SRC.indexOf('/** 已知模型查询')
    expect(start).toBeGreaterThan(-1)
    expect(end).toBeGreaterThan(start)
    const block = SELECTOR_SRC.slice(start, end)
    expect(block).not.toContain('pointsMultiplier')
  })

  it('号池/目录/兜底三条路径都直接使用后端倍率', () => {
    expect(SELECTOR_SRC).toContain("typeof m.pointsMultiplier === 'number'")
    expect(SELECTOR_SRC).toContain("typeof m.points_multiplier === 'number'")
    expect(SELECTOR_SRC).toContain('pointsMultiplier: tier')
    expect(SELECTOR_SRC).not.toContain('known.pointsMultiplier')
  })
})
