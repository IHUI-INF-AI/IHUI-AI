/**
 * 号池模型 ⇄ 健康台账 的 id 对齐规则(2026-11-18 立,真机踩坑回归锁)。
 *
 * 真机现场:CF 免费额度用尽后,后台已把 `@cf/zai-org/glm-4.7-flash` 记账为
 * `status=down/reason=quota`,但选择器里那一行仍是"未验证、可点" —— 因为号池
 * 下发的 id 是 `cf/@cf/zai-org/glm-4.7-flash`(多一层平台前缀),与台账键逐字节不同,
 * 简单 `Map.get(id)` 命中不了。本测试钉住"三种写法都认得出是同一模型"。
 */

import { describe, expect, it } from 'vitest'

import { idProbeKeys, sameModelId } from '../model-tier-utils'

describe('idProbeKeys / sameModelId', () => {
  it('平台前缀 + 上游自带 @ 的号池 id,与台账键判为同一模型', () => {
    expect(sameModelId('cf/@cf/zai-org/glm-4.7-flash', '@cf/zai-org/glm-4.7-flash')).toBe(true)
  })

  it('裸名也能认出来(部分平台登记行不带 <平台>/ 前缀)', () => {
    expect(sameModelId('oai/gpt-4o-mini', 'gpt-4o-mini')).toBe(true)
  })

  it('大小写差异不算两个模型', () => {
    expect(sameModelId('agnes/Agnes-3.0-Flash', 'agnes-3.0-flash')).toBe(true)
  })

  it('不同模型不会被误判成同一模型', () => {
    expect(sameModelId('cf/@cf/zai-org/glm-4.7-flash', 'cf/@cf/zai-org/glm-4.7-pro')).toBe(false)
    expect(sameModelId('agnes/agnes-2.5-flash', 'agnes/agnes-3.0-flash')).toBe(false)
    expect(sameModelId('gpt-4o', 'gpt-4')).toBe(false)
  })

  it('空 id 不产生候选键(避免空串把整张清单都命中)', () => {
    expect(idProbeKeys('')).toEqual([])
    expect(idProbeKeys('   ')).toEqual([])
    expect(sameModelId('', 'agnes-3.0-flash')).toBe(false)
  })
})
