import { cleanup, render, screen } from '@testing-library/react'
import { afterEach, describe, expect, it, vi } from 'vitest'

vi.mock('next-intl', () => ({
  useTranslations: () => (key: string) => key,
}))

vi.mock('@/components/media/ai-revision-panel', () => ({
  AiRevisionPanel: ({
    name,
    initialInstruction,
    autoRun,
  }: {
    name: string
    initialInstruction?: string
    autoRun?: boolean
  }) => (
    <div
      data-testid="revision-panel"
      data-name={name}
      data-instruction={initialInstruction ?? ''}
      data-autorun={String(Boolean(autoRun))}
    />
  ),
}))

import { ChatRevisionDialog } from '../chat-revision-dialog'
import type { ChatDocRevisionRequest } from '@/stores/chat-doc-revision'

function requestOf(id: string): ChatDocRevisionRequest {
  return {
    id,
    file: new File(['合同正文'], '合同.docx', {
      type: 'application/vnd.openxmlformats-officedocument.wordprocessingml.document',
    }),
    instruction: '把付款条款改成 30 天',
    createdAt: 1,
  }
}

afterEach(cleanup)

describe('ChatRevisionDialog', () => {
  it('无请求时不渲染面板', () => {
    render(<ChatRevisionDialog request={null} onClose={() => {}} />)
    expect(screen.queryByTestId('revision-panel')).toBeNull()
  })

  it('请求到位时把文件名与对话指令、autoRun 一起交给修订面板', () => {
    render(<ChatRevisionDialog request={requestOf('r1')} onClose={() => {}} />)
    const panel = screen.getByTestId('revision-panel')
    expect(panel.getAttribute('data-name')).toBe('合同.docx')
    expect(panel.getAttribute('data-instruction')).toBe('把付款条款改成 30 天')
    expect(panel.getAttribute('data-autorun')).toBe('true')
    expect(screen.getByText('合同.docx')).toBeTruthy()
  })
})
