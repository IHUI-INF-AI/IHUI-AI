import { describe, it, expect } from 'vitest'
import {
  PERSONALITY_PRESET_IDS,
  PERSONALITY_PRESETS,
  type PersonalityPresetId,
} from '../personality-presets'

describe('personality-presets 数据契约', () => {
  it('预设 id 列表与元数据数组一一对应', () => {
    expect(PERSONALITY_PRESETS.map((p) => p.id)).toEqual([...PERSONALITY_PRESET_IDS])
  })

  it('每个预设都带 label/description/prompt 三类 i18n key', () => {
    for (const p of PERSONALITY_PRESETS) {
      expect(p.labelKey).toBe(`chat.personalityPresets.${p.id}.label`)
      expect(p.descriptionKey).toBe(`chat.personalityPresets.${p.id}.description`)
      expect(p.promptKey).toBe(`chat.personalityPresets.${p.id}.prompt`)
    }
  })

  it('default 预设存在且排在首位', () => {
    expect(PERSONALITY_PRESETS[0]?.id).toBe('default')
  })

  it('id 无重复', () => {
    const ids = PERSONALITY_PRESETS.map((p) => p.id) as PersonalityPresetId[]
    expect(new Set(ids).size).toBe(ids.length)
  })
})
