// @vitest-environment happy-dom
import { cleanup, fireEvent, render, screen } from '@testing-library/react'
import { afterEach, describe, expect, it, vi } from 'vitest'

vi.mock('next-intl', () => ({
  useTranslations: () => (key: string) => key,
}))

afterEach(cleanup)

import { ContextChipsRow } from '../context-chips-row'

function renderQueue(
  items: readonly { text: string }[],
  onQueueReorder?: (from: number, to: number) => void,
) {
  const onQueueRemove = vi.fn()
  render(
    <ContextChipsRow
      references={[]}
      onRemoveReference={vi.fn()}
      tools={[]}
      onRemoveTool={vi.fn()}
      quoted={null}
      onClearQuoted={vi.fn()}
      hasMentions={false}
      onRemoveMention={vi.fn()}
      pastePreviews={[]}
      onDismissPastePreviews={vi.fn()}
      queueItems={items}
      onQueueRemove={onQueueRemove}
      onQueueReorder={onQueueReorder}
    />,
  )
  return { onQueueRemove }
}

describe('运行中待发队列重排入口', () => {
  it('两条以上才出现上移/下移;点下移把下标交给回调', () => {
    const onQueueReorder = vi.fn()
    renderQueue([{ text: '甲' }, { text: '乙' }], onQueueReorder)
    expect((screen.getByTestId('input-queue-moveup-0') as HTMLButtonElement).disabled).toBe(true)
    fireEvent.click(screen.getByTestId('input-queue-movedown-0'))
    expect(onQueueReorder).toHaveBeenCalledWith(0, 1)
    expect((screen.getByTestId('input-queue-movedown-1') as HTMLButtonElement).disabled).toBe(true)
  })

  it('只有一条时不渲染重排按钮,取消仍在', () => {
    const { onQueueRemove } = renderQueue([{ text: '只有一条' }])
    expect(screen.queryByTestId('input-queue-moveup-0')).toBeNull()
    fireEvent.click(screen.getByTestId('input-queue-remove-0'))
    expect(onQueueRemove).toHaveBeenCalledWith(0)
  })

  it('没接重排回调时不渲染上移/下移', () => {
    renderQueue([{ text: '甲' }, { text: '乙' }])
    expect(screen.queryByTestId('input-queue-moveup-0')).toBeNull()
    expect(screen.queryByTestId('input-queue-movedown-1')).toBeNull()
  })
})
