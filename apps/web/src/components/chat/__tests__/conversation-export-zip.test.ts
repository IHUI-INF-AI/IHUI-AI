import { describe, it, expect, vi, beforeEach, afterEach } from 'vitest'

vi.mock('@ihui/api-client', async (importOriginal) => {
  const actual = (await importOriginal()) as Record<string, unknown>
  return {
    ...actual,
    getMessages: vi.fn(),
    exportConversationZip: vi.fn(),
  }
})

import { getMessages, exportConversationZip } from '@ihui/api-client'
import {
  copyConversationMarkdown,
  downloadConversationZip,
} from '../conversation-export'

const mockedGetMessages = vi.mocked(getMessages)
const mockedZip = vi.mocked(exportConversationZip)

function pageOf(messages: Array<{ id: string; role: string; content: string }>) {
  return {
    success: true as const,
    data: { messages, total: messages.length },
  }
}

describe('会话导出:复制 Markdown / ZIP', () => {
  const writeText = vi.fn<(text: string) => Promise<void>>(async () => undefined)
  let clickSpy: ReturnType<typeof vi.spyOn>

  beforeEach(() => {
    vi.clearAllMocks()
    Object.defineProperty(navigator, 'clipboard', {
      configurable: true,
      value: { writeText },
    })
    vi.stubGlobal('URL', {
      ...URL,
      createObjectURL: vi.fn(() => 'blob:mock'),
      revokeObjectURL: vi.fn(),
    })
    clickSpy = vi.spyOn(HTMLAnchorElement.prototype, 'click').mockImplementation(() => {})
  })

  afterEach(() => {
    clickSpy.mockRestore()
    vi.unstubAllGlobals()
  })

  it('复制整段会话为 Markdown', async () => {
    mockedGetMessages.mockResolvedValue(
      pageOf([
        { id: 'u1', role: 'user', content: '问题' },
        { id: 'a1', role: 'assistant', content: '答案' },
      ]) as never,
    )
    const done = await copyConversationMarkdown('c1', '会话标题', {
      user: '用户',
      assistant: '助手',
    })
    expect(done).toBe(true)
    const copied = writeText.mock.calls[0]?.[0] ?? ''
    expect(copied).toContain('# 会话标题')
    expect(copied).toContain('## 用户')
    expect(copied).toContain('## 助手')
    expect(copied).toContain('答案')
  })

  it('无消息时不写剪贴板', async () => {
    mockedGetMessages.mockResolvedValue(pageOf([]) as never)
    const done = await copyConversationMarkdown('c1', '空会话', {
      user: '用户',
      assistant: '助手',
    })
    expect(done).toBe(false)
    expect(writeText).not.toHaveBeenCalled()
  })

  it('ZIP 走服务端二进制并触发下载', async () => {
    mockedZip.mockResolvedValue(new Blob(['zip-bytes'], { type: 'application/zip' }))
    const done = await downloadConversationZip('c1', '会话标题')
    expect(done).toBe(true)
    expect(mockedZip).toHaveBeenCalledWith('c1')
    expect(clickSpy).toHaveBeenCalledTimes(1)
  })
})
