/**
 * ChatNoticeLog(web 对话内提示留痕)渲染单测。
 *
 * 只钉两条最容易回退的判据:
 * ① 空列表**不出图**(否则每条消息尾部都挂一条空边框);
 * ② 有记录时文案上屏,且带上类型标记(便于断言语义色走对了分支)。
 */
import { beforeEach, describe, expect, it } from 'vitest'
import { act, cleanup, render } from '@testing-library/react'
import { ChatNoticeLog } from '../notice-log'
import { recordNotice, setNoticeScope } from '@/lib/notice-log-store'

async function settle(): Promise<void> {
  for (let i = 0; i < 5; i++) await Promise.resolve()
}

// 刻意**不** resetModules:store 是模块级单例,重置会让组件与用例各拿一份,
// 测出来的是两份内存而不是真实链路。每个用例用独立 conversationId 隔离即可。
beforeEach(() => {
  window.localStorage.clear()
  cleanup()
})

describe('ChatNoticeLog', () => {
  it('空列表不出图', async () => {
    const { container } = render(<ChatNoticeLog conversationId="conv-empty" />)
    await act(settle)
    expect(container.querySelector('[data-testid="chat-notice-log"]')).toBeNull()
    expect(container.textContent).toBe('')
  })

  it('有记录时文案与类型标记都上屏', async () => {
    setNoticeScope('conv-x')
    await act(settle)
    act(() => {
      recordNotice('error', '网络异常,请稍后重试')
      recordNotice('success', '已保存')
    })
    await act(settle)

    const { getByText, container } = render(<ChatNoticeLog conversationId="conv-x" />)
    await act(settle)
    expect(getByText('网络异常,请稍后重试')).toBeTruthy()
    expect(getByText('已保存')).toBeTruthy()
    const rows = container.querySelectorAll('[data-notice-kind]')
    expect(rows).toHaveLength(2)
    expect(rows[0]?.getAttribute('data-notice-kind')).toBe('error')
    expect(rows[1]?.getAttribute('data-notice-kind')).toBe('success')
  })
})
