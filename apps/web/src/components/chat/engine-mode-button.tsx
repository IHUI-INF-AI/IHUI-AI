'use client'

/**
 * EngineModeControl — 聊天输入区底栏的引擎切换控件(2026-11-15)
 *
 * 目的:让用户在**主界面直接可见**当前 agent 执行引擎(本地/云端/自动)并 1 击切换,
 * 不用进「设置→偏好」深列表。设置页仍有完整卡片(EngineModeCard)做说明。
 *
 * 形态:复用 EngineModeToggle 的紧凑三态分段控件,始终可见(不藏进弹层)。
 * 项目禁用圆形发送钮/不引 radix Popover,故这里直接内联分段控件,最省事且 1 击可达。
 *
 * 说明:浏览器端选「本地」时接线代码会自动回退云端(见 engine-mode-card.tsx 注),
 * 这里如实显示三态、不隐藏本地项 —— 偏好可记录,桌面壳上真正生效。
 */

import { EngineModeToggle } from '@ihui/ui-react'
import { useTranslations } from 'next-intl'

import { useEngineModeStore } from '@/stores/engine-mode'
import type { EngineMode } from '@ihui/shared'

/** 聊天底栏引擎切换控件 */
export function EngineModeControl({ disabled = false }: { disabled?: boolean }) {
  const mode = useEngineModeStore((s) => s.mode)
  const setMode = useEngineModeStore((s) => s.setMode)
  const t = useTranslations('engineMode')

  // 三态标签 + aria 走语言包(2026-11-15):共享组件不引 next-intl,标签由此注入。
  const labelMap: Record<EngineMode, string> = {
    local: t('local'),
    cloud: t('cloud'),
    auto: t('auto'),
  }

  return (
    <div data-testid="engine-mode-control">
      <EngineModeToggle
        value={mode}
        onChange={setMode}
        disabled={disabled}
        labelMap={labelMap}
        ariaLabel={t('title')}
        className="shrink-0"
      />
    </div>
  )
}

export default EngineModeControl
