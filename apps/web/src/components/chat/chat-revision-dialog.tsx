'use client'

import * as React from 'react'
import { Dialog, DialogContent, DialogHeader, DialogTitle } from '@ihui/ui-react'
import { AiRevisionPanel } from '@/components/media/ai-revision-panel'
import type { ChatDocRevisionRequest } from '@/stores/chat-doc-revision'

interface Props {
  request: ChatDocRevisionRequest | null
  onClose: () => void
}

/**
 * 对话侧发起的文档修订对话框(2026-11-28 立)。
 *
 * 立因:用户原话要的是"主 AI 对话反向驱动文档修订" —— 在聊天输入区写一句
 * "把付款条款改成 30 天"、挂上合同.docx、点附件卡上的「AI 修订」,就应该直接
 * 出修订稿并做双栏对比,而不是再让用户跑去文档中心重新打开一遍。
 *
 * 复用 `AiRevisionPanel`(生成 / 双栏 diff / 逐处接受驳回 / 导出都是同一份实现);
 * 本组件只负责对话侧的容器与语义:标题用文件名、不写死描述(Radix 显式
 * `aria-describedby={undefined}`)、尺寸沿用查看器 revision 面板那套
 * `grid-rows-[auto_minmax(0,1fr)]`(避免 `max-h-[60vh]` 在生产布局被算成 0 的塌陷)。
 */
export function ChatRevisionDialog({ request, onClose }: Props) {
  return (
    <Dialog
      open={request !== null}
      onOpenChange={(open) => {
        if (!open) onClose()
      }}
    >
      <DialogContent
        className="h-[92vh] max-w-[min(96vw,112rem)] grid-rows-[auto_minmax(0,1fr)]"
        aria-describedby={undefined}
      >
        <DialogHeader className="pr-8">
          <DialogTitle className="break-words">{request?.file.name ?? ''}</DialogTitle>
        </DialogHeader>
        {request ? (
          <AiRevisionPanel
            key={request.id}
            file={request.file}
            name={request.file.name}
            initialInstruction={request.instruction}
            autoRun
            onClose={onClose}
            className="min-h-0"
          />
        ) : null}
      </DialogContent>
    </Dialog>
  )
}
