'use client'

/**
 * 工作台会话栏数据出口(2026-10-28 立)。
 *
 * 与 chat/history 页同一 queryKey(['chat','conversations'])与同一 pageSize=100 档:
 * conversation-list 的收藏/归档/删除失效面 invalidateQueries({queryKey:['chat','conversations']})
 * 会自然命中本出口,工作台栏与历史页因此共享缓存与失效语义,不另立第二套 key。
 * 登录态门与 history 页同口径(未就绪不发请求,防 401 噪声)。
 */
import { useQuery } from '@tanstack/react-query'

import { fetchApi } from '@/lib/api'
import { useAuthBootstrap } from '@/hooks/use-auth-bootstrap'
import { useAuthStore } from '@/stores/auth'
import type { Conversation } from '@/components/chat/conversation-list'

export interface WorkbenchConversationsResponse {
  conversations: Conversation[]
}

export function useWorkbenchConversations() {
  const isAuthenticated = useAuthStore((s) => s.isAuthenticated)
  const { ready } = useAuthBootstrap()
  return useQuery({
    queryKey: ['chat', 'conversations'],
    queryFn: async () => {
      const res = await fetchApi<WorkbenchConversationsResponse>(
        '/api/chat/conversations?pageSize=100',
      )
      if (!res.success) throw new Error(res.error || 'loadFailed')
      return res.data
    },
    enabled: ready && isAuthenticated,
    staleTime: 30_000,
  })
}
