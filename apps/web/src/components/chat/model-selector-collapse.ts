/**
 * 模型选择器 —— 厂商(反代平台)分组的折叠态(2026-11-21 立)
 *
 * 为什么单独成文件:直接 import model-selector.tsx 会连带拉起 emoji-mart,
 * 其 native.json 缺 `type: json` import 属性会让 vitest 崩掉(同
 * model-tier-utils.ts:9-11 的既有口径)。折叠态的存取/归一化是纯逻辑,
 * 放这里可以脱离组件依赖树做单测。
 *
 * 存储键在 `@ihui/shared` 的 storage-keys 单源登记(各端禁止硬编码 key 字面量);
 * 只存「哪些组被收起」,不存模型与账号数据;取不到或内容损坏一律按「全部展开」,
 * 失效方向必须是"多展开一次",绝不能把整组模型藏起来。
 */

import { MODEL_SELECTOR_COLLAPSED_VENDORS_STORAGE_KEY } from '@ihui/shared'

export { MODEL_SELECTOR_COLLAPSED_VENDORS_STORAGE_KEY }

/** 切换某组的折叠态:返回新 Set,不原地改传入集合(React 状态更新要求新引用) */
export function toggleCollapsedVendor(prev: ReadonlySet<string>, label: string): Set<string> {
  const next = new Set(prev)
  if (next.has(label)) next.delete(label)
  else next.add(label)
  return next
}

/** 解析本机存储里的折叠组清单:非数组 / 坏 JSON / 空串与脏条目全部丢弃 */
export function parseCollapsedVendors(raw: string | null | undefined): Set<string> {
  if (!raw) return new Set()
  try {
    const parsed: unknown = JSON.parse(raw)
    if (!Array.isArray(parsed)) return new Set()
    return new Set(parsed.filter((item): item is string => typeof item === 'string' && item !== ''))
  } catch {
    return new Set()
  }
}

/** 序列化折叠组清单(只存组键,顺序无关) */
export function serializeCollapsedVendors(collapsed: ReadonlySet<string>): string {
  return JSON.stringify([...collapsed])
}
