import { describe, it, expect } from 'vitest'
import { computeJumpVisibility, JUMP_FAR_THRESHOLD } from './scroll-jump-buttons'

describe('computeJumpVisibility', () => {
  it('距顶 > 800 → 跳顶显示;距底不足 → 跳底不显示', () => {
    // scrollTop=900, scrollHeight=2000, clientHeight=800 → 距底 = 300
    const v = computeJumpVisibility(900, 2000, 800)
    expect(v.isFarFromTop).toBe(true)
    expect(v.isFarFromBottom).toBe(false)
  })

  it('距底 > 800 → 跳底显示;距顶不足 → 跳顶不显示', () => {
    // scrollTop=100, scrollHeight=2000, clientHeight=800 → 距底 = 1100
    const v = computeJumpVisibility(100, 2000, 800)
    expect(v.isFarFromTop).toBe(false)
    expect(v.isFarFromBottom).toBe(true)
  })

  it('既不太靠顶也不太靠底 → 两按钮均隐藏', () => {
    // scrollTop=100, scrollHeight=1000, clientHeight=800 → 距底 = 100
    const v = computeJumpVisibility(100, 1000, 800)
    expect(v.isFarFromTop).toBe(false)
    expect(v.isFarFromBottom).toBe(false)
  })

  it('恰好等于阈值(800)不算"超过" → 不显示', () => {
    const v = computeJumpVisibility(800, 2000, 800)
    expect(v.isFarFromTop).toBe(false)
    expect(v.isFarFromBottom).toBe(false)
  })

  it('支持自定义阈值参数', () => {
    // 阈值 500:scrollTop=600 > 500 → 跳顶显示
    const v = computeJumpVisibility(600, 2000, 800, 500)
    expect(v.isFarFromTop).toBe(true)
    expect(JUMP_FAR_THRESHOLD).toBe(800)
  })

  it('底部贴边(距底=0)→ 跳底不显示', () => {
    const v = computeJumpVisibility(1200, 2000, 800)
    expect(v.isFarFromTop).toBe(true)
    expect(v.isFarFromBottom).toBe(false)
  })
})
