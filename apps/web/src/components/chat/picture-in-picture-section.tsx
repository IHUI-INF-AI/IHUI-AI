/** Document Picture-in-Picture 能力面(仓内唯一既有画中画 API 通道;TS lib 未收录,本地声明) */
interface DocumentPictureInPictureLike {
  requestWindow(options?: { width?: number; height?: number }): Promise<Window>
}

/** 本组件开出的浮窗(模块级单例:同页多会话窗格共用一个画中画面板) */
let pipWindow: Window | null = null

function getPipCapability(): DocumentPictureInPictureLike | undefined {
  if (typeof window === 'undefined') return undefined
  return (window as Window & { documentPictureInPicture?: DocumentPictureInPictureLike })
    .documentPictureInPicture
}

/** 当前浏览器是否支持 Document Picture-in-Picture(菜单项按此决定是否出现) */
export function isDocumentPictureInPictureSupported(): boolean {
  return getPipCapability() !== undefined
}

/** 打开画中画浮窗;能力缺失时静默返回,开窗失败不阻断主流程 */
export function openPictureInPictureWindow(labels: { title: string; emptyState: string }): void {
  const dpp = getPipCapability()
  if (!dpp) return
  dpp
    .requestWindow({ width: 480, height: 360 })
    .then((w) => {
      pipWindow = w
      w.document.title = labels.title
      w.document.body.textContent = labels.emptyState
      w.addEventListener('pagehide', () => {
        if (pipWindow === w) pipWindow = null
      })
    })
    .catch(() => {
      // 开窗失败(权限/浏览器策略)静默:菜单动作不弹错、不阻断会话
    })
}
