'use client'
// 2026-09-10 0-6 组件拆分:断点列表从 debug-panel.tsx 抽出(自订阅 debug store)
import * as React from 'react'
import { useTranslations } from 'next-intl'
import { useDebugStore } from '@/stores/debug'
import { Circle, CircleDot, Trash2 } from 'lucide-react'
import { cn } from '@/lib/utils'

/** 断点区:toggle 启用/禁用 + 删除,顶部显示启用数统计 */
export function BreakpointSection() {
  const t = useTranslations('ide')
  const breakpoints = useDebugStore((s) => s.breakpoints)
  const toggleBreakpoint = useDebugStore((s) => s.toggleBreakpoint)
  const removeBreakpoint = useDebugStore((s) => s.removeBreakpoint)
  const enabledBreaks = breakpoints.filter((b) => b.enabled).length

  return (
    <div className="mb-2">
      <div className="flex items-center gap-1 px-2 py-1 text-xs font-medium text-muted-foreground">
        <span>{t('debug.breakpoints')}</span>
        <span className="ml-auto text-muted-foreground">
          {enabledBreaks}/{breakpoints.length}
        </span>
      </div>
      {breakpoints.map((b) => (
        <div
          key={b.id}
          className="group flex items-center gap-1.5 px-2 py-0.5 text-xs hover:bg-muted/30"
        >
          <button
            onClick={() => toggleBreakpoint(b.id)}
            className="text-muted-foreground"
            aria-label={t('debug.toggle')}
          >
            {b.enabled ? (
              <CircleDot className="h-3 w-3 text-red-500" />
            ) : (
              <Circle className="h-3 w-3" />
            )}
          </button>
          <span className={cn('truncate', !b.enabled && 'text-muted-foreground line-through')}>
            {b.file}:{b.line}
          </span>
          <button
            onClick={() => removeBreakpoint(b.id)}
            className="ml-auto text-muted-foreground opacity-0 hover:text-foreground group-hover:opacity-100"
            aria-label={t('debug.delete')}
          >
            <Trash2 className="h-3 w-3" />
          </button>
        </div>
      ))}
    </div>
  )
}
