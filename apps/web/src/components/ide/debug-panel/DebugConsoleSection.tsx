'use client'
// 2026-09-10 0-6 组件拆分:Debug Console 从 debug-panel.tsx 抽出(自订阅 consoleLogs,自持折叠态)
import * as React from 'react'
import { useTranslations } from 'next-intl'
import { useDebugStore, type ConsoleLog } from '@/stores/debug'
import { cn } from '@/lib/utils'
import { ChevronRight, ChevronDown, Terminal } from 'lucide-react'

/** Debug Console:可折叠,按 level 着色渲染日志行 */
export function DebugConsoleSection() {
  const t = useTranslations('ide')
  const consoleLogs = useDebugStore((s) => s.consoleLogs)
  const [showConsole, setShowConsole] = React.useState(true)

  return (
    <>
      <button
        onClick={() => setShowConsole(!showConsole)}
        className="flex items-center gap-1 px-2 py-1 text-xs font-medium text-muted-foreground hover:bg-muted/30"
      >
        {showConsole ? <ChevronDown className="h-3 w-3" /> : <ChevronRight className="h-3 w-3" />}
        <Terminal className="h-3 w-3" />
        <span>{t('debug.debugConsole')}</span>
      </button>
      {showConsole && (
        <div className="max-h-32 overflow-auto bg-background/50 p-1.5 font-mono text-[11px]">
          {consoleLogs.length === 0 ? (
            <div className="px-1 py-0.5 text-muted-foreground">—</div>
          ) : (
            consoleLogs.map((log: ConsoleLog, i: number) => (
              <div
                key={i}
                className={cn(
                  'px-1 py-0.5',
                  log.level === 'error' && 'text-red-600 dark:text-red-400',
                  log.level === 'warn' && 'text-amber-600 dark:text-amber-400',
                  log.level === 'info' && 'text-blue-600 dark:text-blue-400',
                  log.level === 'log' && 'text-foreground',
                )}
              >
                {log.text}
              </div>
            ))
          )}
        </div>
      )}
    </>
  )
}
// ⁠​‌​​‌​​‌‍‍​‌​​‌​​​‍‍​‌​‌​‌​‌‍‍​‌​​‌​​‌‍‍​​‌​‌‌​‌‍‍​‌​​​​​‌‍‍​‌​​‌​​‌‍‍‌​‌‌​‌‌‌‍‍‌‌​​‌‌​​‌‌‌‌​‌​‍‍‌‌​‌‌​​​‌​​​‌‌‌‍‍​‌​​​​​‌‍‍​‌​​‌​​‌‍‍‌​‌‌​‌‌‌‍‍‌‌​​‌‌‌​‌​​‌‌‌​‍‍‌‌​​‌‌​​​‌​​‌​‌‍‍‌​‌‌‌​‌‌‌​‌‌‌​‌‍‍‌​‌‌​‌‌‌‍‍​‌​​‌‌​​‍‍​‌​​​​‌‌‍‍‌​‌‌​‌‌‌‍‍​‌‌​​​​‌‍‍​‌‌​‌​​‌‍‍​‌‌‌‌​‌​‍‍​‌‌​‌​​​‍‍​‌‌‌​​‌‌‍‍​​‌​‌‌‌​‍‍​‌‌‌​‌​​‍‍​‌‌​‌‌‌‌‍‍​‌‌‌​​​​‍‍‌​‌‌​‌‌‌‍‍​‌​‌​​​​‍‍​‌​‌​​‌​‍‍​‌​​‌‌‌‌‍‍​‌​‌​‌‌​‍‍​‌​​​‌​‌‍‍​‌​​‌‌‌​‍‍​‌​​​​​‌‍‍​‌​​‌‌‌​‍‍​‌​​​​‌‌‍‍​‌​​​‌​‌‍‍​​‌​‌‌​‌‍‍​​‌‌​​‌​‍‍​​‌‌​​​​‍‍​​‌‌​​‌​‍‍​​‌‌​‌‌​⁠
