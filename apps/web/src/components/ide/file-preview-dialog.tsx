'use client'

import * as React from 'react'
import { readFileRaw } from '@ihui/api-client'
import { FileViewerDialog, type FileViewerTarget } from '@/components/media/file-viewer-dialog'
import { useIDEWorkspace } from '@/stores/ide-workspace'

/**
 * IDE 工作区二进制文件预览(2026-11-26 立)。
 *
 * 文件树里图片/PDF/Office/表格/音视频/3D/zip 不再开代码编辑器(二进制进编辑器只会是乱码),
 * 由 store.openFile 改投这里;字节从 /api/workspace/fs/raw 取(与 fs/read 同一权限闸),
 * 弹窗与工具栏交 `FileViewerDialog`(文档中心、项目文件同一实现)。
 */
export function IDEFilePreviewDialog() {
  const previewFile = useIDEWorkspace((s) => s.previewFile)
  const workspacePath = useIDEWorkspace((s) => s.workspacePath)
  const closePreview = useIDEWorkspace((s) => s.closePreview)

  const target = React.useMemo<FileViewerTarget | null>(() => {
    if (!previewFile || !workspacePath) return null
    return {
      name: previewFile.name,
      subtitle: previewFile.path,
      load: () => readFileRaw({ path: previewFile.path, workspacePath }),
    }
  }, [previewFile, workspacePath])

  return <FileViewerDialog target={target} onClose={closePreview} />
}
