import * as React from 'react'
import { useTranslations } from 'next-intl'
import { cn } from '@/lib/utils'

interface TerminalStatusIndicatorsProps {
  connected: boolean
  wsError: string | null
  fontSize: number
}

/**
 * 左下角连接状态指示器 + 右下角字号状态栏 + 错误横幅。
 * 连接状态点不使用 rounded-full(AGENTS.md §4),用 inline borderRadius:50% 的紧凑小点。
 */
export function TerminalStatusIndicators({
  connected,
  wsError,
  fontSize,
}: TerminalStatusIndicatorsProps) {
  const t = useTranslations('ide')
  return (
    <>
      {/* 连接状态指示器(左下角) */}
      <div className="pointer-events-none absolute bottom-1 left-2 flex items-center gap-1.5 rounded bg-background/80 px-2 py-0.5 text-xs text-muted-foreground backdrop-blur-sm">
        <span
          className={cn(
            'inline-block h-1.5 w-1.5',
            connected ? 'bg-green-500' : wsError ? 'bg-red-500' : 'bg-muted-foreground',
          )}
          style={{ borderRadius: '50%' }}
        />
        <span>
          {connected
            ? t('terminalPanel.connected')
            : wsError
              ? t('terminalPanel.connectionError')
              : t('terminalPanel.connecting')}
        </span>
      </div>

      {/* 字号状态栏(右下角) */}
      <div className="pointer-events-none absolute bottom-1 right-2 flex items-center gap-2 rounded bg-background/80 px-2 py-0.5 text-[10px] text-muted-foreground backdrop-blur-sm">
        <span>{fontSize}px</span>
        <span className="opacity-60">Ctrl+/−/0</span>
      </div>

      {wsError && (
        <div className="absolute left-2 right-2 bottom-2 bg-destructive/10 px-3 py-1 text-xs text-destructive">
          {wsError}
        </div>
      )}
    </>
  )
}
