'use client'

import type { ConnectorCapability, ConnectorOperation } from '@ihui/api-client/endpoints/connectors'

/** 操作路径/查询/请求体里未填的占位符(前端提示用,真正的缺参判定在后端) */
export function requiredParamNames(operation: ConnectorOperation | undefined): string[] {
  if (!operation) return []
  const names = new Set<string>()
  const collect = (value: unknown) => {
    if (typeof value === 'string') {
      for (const match of value.matchAll(/\{([A-Za-z0-9_]+)\}/g)) {
        if (match[1]) names.add(match[1])
      }
    } else if (Array.isArray(value)) {
      value.forEach(collect)
    } else if (value && typeof value === 'object') {
      Object.values(value as Record<string, unknown>).forEach(collect)
    }
  }
  for (const match of operation.path.matchAll(/\{([A-Za-z0-9_]+)\}/g)) {
    if (match[1]) names.add(match[1])
  }
  collect(operation.query)
  collect(operation.body)
  return [...names]
}

/** 能力位 -> i18n key(文案单一来源在 messages/web/*.json 的 connectors 段) */
export const CAPABILITY_LABEL_KEY: Record<ConnectorCapability, string> = {
  list: 'capList',
  search: 'capSearch',
  fetch: 'capFetch',
  action: 'capAction',
}

/** 名称转 URL-safe slug(中文等非字母数字压缩成 -,空则空串) */
export function toSlug(input: string): string {
  return input
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
}

/** 按能力位统计操作数 */
export function countCapabilities(
  operations: ConnectorOperation[],
): Record<ConnectorCapability, number> {
  const counts: Record<ConnectorCapability, number> = { list: 0, search: 0, fetch: 0, action: 0 }
  for (const op of operations) counts[op.capability] += 1
  return counts
}
