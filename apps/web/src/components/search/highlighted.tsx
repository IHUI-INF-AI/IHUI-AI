'use client'

/**
 * 命中片段高亮渲染。
 *
 * 区间由**后端**下发（`casefold` 口径一致），前端只负责切片渲染 ——
 * 前端自己再算一遍必然与后端漂移（全角/半角、连字、大小写）。
 *
 * 防御：区间可能越界或逆序（后端换实现时），一律夹到合法范围后丢弃空段，
 * 绝不因为一个坏区间让整块文本空白。
 */

import { useMemo } from 'react'

export type HighlightSpan = [number, number]

export function Highlighted({
  text,
  spans,
}: {
  text: string
  spans?: HighlightSpan[]
}) {
  const parts = useMemo(() => {
    if (!spans || spans.length === 0) return null
    const nodes: Array<string | { key: string; piece: string }> = []
    let cursor = 0
    for (const [start, end] of spans) {
      const from = Math.max(cursor, Math.min(start, text.length))
      const to = Math.max(from, Math.min(end, text.length))
      if (to <= from) continue
      if (from > cursor) nodes.push(text.slice(cursor, from))
      nodes.push({ key: `${from}-${to}`, piece: text.slice(from, to) })
      cursor = to
    }
    if (cursor < text.length) nodes.push(text.slice(cursor))
    return nodes
  }, [text, spans])

  if (!parts) return <>{text}</>
  return (
    <>
      {parts.map((part, index) =>
        typeof part === 'string' ? (
          <span key={`t${index}`}>{part}</span>
        ) : (
          <mark key={part.key} className="rounded bg-foreground px-0.5 text-background">
            {part.piece}
          </mark>
        ),
      )}
    </>
  )
}
