import * as React from 'react'
import { useTranslations } from 'next-intl'
import { CloudOff, WifiOff } from 'lucide-react'

import { isTauri } from '@/lib/tauri-bridge'
import { useConnectivity } from '@/hooks/use-connectivity'

export function ConnectivityBanner() {
  const t = useTranslations('connectivity')
  const { state } = useConnectivity()

  if (state === 'online' || state === 'probing') return null

  const isDevice = state === 'device-offline'
  const Icon = isDevice ? WifiOff : CloudOff

  return (
    <div
      role="status"
      data-testid="connectivity-banner"
      data-state={state}
      className="flex items-center gap-1.5 border-b border-border bg-amber-50 px-3 py-1 text-xs text-amber-700 dark:bg-amber-950/40 dark:text-amber-400"
    >
      <Icon className="h-3.5 w-3.5 shrink-0" aria-hidden />
      <span className="flex-1">
        {isDevice ? t('deviceOffline') : t('apiUnreachable')}
        {!isDevice && isTauri() && (
          <span className="ml-1 text-amber-600/80 dark:text-amber-400/80">
            {t('hostLocalAvailable')}
          </span>
        )}
      </span>
    </div>
  )
}

export default ConnectivityBanner
