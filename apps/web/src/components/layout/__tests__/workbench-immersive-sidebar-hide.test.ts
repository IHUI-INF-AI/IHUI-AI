// 大屏指挥台 · 沉浸模式隐藏全局主导航接线锁(2026-10-29 立):
// 三处必须同批:侧栏锚点 / Suspense 占位锚点 / CSS 规则 / 工作台写根属性。
// 少任何一处都会退化成"藏了侧栏但留 160px 空洞"或"属性写了没人认"。
import { readFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

import { describe, expect, it } from 'vitest'

const here = dirname(fileURLToPath(import.meta.url))
const webRoot = join(here, '../../../..')

function read(rel: string): string {
  return readFileSync(join(webRoot, rel), 'utf8')
}

describe('工作台沉浸模式 ⇄ 全局主导航', () => {
  it('桌面侧栏带稳定锚点 data-main-sidebar', () => {
    const sidebar = read('src/components/sidebar/Sidebar.tsx')
    expect(sidebar).toContain('data-main-sidebar')
  })

  it('GlobalShell 的 Suspense 占位同锚点（否则隐藏后留空洞）', () => {
    const shell = read('src/components/layout/GlobalShell.tsx')
    expect(shell).toContain('data-main-sidebar')
  })

  it('globals.css 有 html[data-workbench-immersive] 选中锚点的隐藏规则', () => {
    const css = read('app/globals.css')
    expect(css).toMatch(/html\[data-workbench-immersive='true'\]\s+aside\[data-main-sidebar\]/)
    expect(css).toMatch(/display:\s*none/)
  })

  it('工作台写/摘根属性（卸载必须摘，否则污染其它路由）', () => {
    const shell = read('src/components/chat/workbench/workbench-shell.tsx')
    expect(shell).toContain('root.dataset.workbenchImmersive')
    expect(shell).toContain('delete root.dataset.workbenchImmersive')
    expect(shell).toContain('return () => {')
  })
})
