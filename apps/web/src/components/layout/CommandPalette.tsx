'use client'

import * as React from 'react'
import { useTranslations } from 'next-intl'
import { Search, History } from 'lucide-react'
import { Dialog, DialogContent } from '@ihui/ui-react'
import { useNavigateWithProgress } from '@/stores/navigation'
import { useIDEWorkspace } from '@/stores/ide-workspace'
import { useWorkPanelStore } from '@/stores/work-panel'
import { useModeStore } from '@/stores/mode'
import { toast } from '@/components/common'
import {
  BUILTIN_COMMANDS,
  COMMAND_GROUP_LABEL_KEY,
  COMMAND_LABEL_KEY,
  COMMAND_DESC_KEY,
  COMMAND_KEYWORDS_KEY,
  UNKNOWN_LABEL_KEY,
  UNKNOWN_DESC_KEY,
  filterCommands,
  getMruCommandIds,
  groupCommands,
  recordCommandUse,
  sortByMru,
  type CommandDef,
} from '@/lib/command-registry'

/**
 * 统一命令面板(1-6 键盘优先交互)
 *
 * 2026-09-09 重写:原 6 项路由命令面板 + GlobalTopBar Plus 九宫格双面板割裂,
 * 现统一收编到 command-registry 单一事实源(21 项命令:6 路由 + 2 视图 + 5 IDE 工具
 * + 4 生态入口 + 4 ChatMode 切换)。
 *
 * 入口:
 * - Ctrl+K(编辑器聚焦时为 inline-edit,否则本面板,见 use-global-shortcuts)
 * - Ctrl+Shift+P(global-shortcut:open-plus,由 GlobalHooksProvider 转发到本面板)
 *
 * 键盘:↑↓ 导航 / Enter 执行 / Esc 关闭;空查询时展示「最近使用」MRU 组(持久化)。
 */
export function CommandPalette({
  open,
  onOpenChange,
}: {
  open: boolean
  onOpenChange: (v: boolean) => void
}) {
  const navigate = useNavigateWithProgress()
  const setActiveTopTab = useIDEWorkspace((s) => s.setActiveTopTab)
  const toggleWorkPanel = useWorkPanelStore((s) => s.toggle)
  const t = useTranslations('commandPalette')
  const tChat = useTranslations('chat')
  const [query, setQuery] = React.useState('')
  const [activeIndex, setActiveIndex] = React.useState(0)
  const [mruIds, setMruIds] = React.useState<string[]>([])
  const inputRef = React.useRef<HTMLInputElement>(null)
  const listRef = React.useRef<HTMLDivElement>(null)

  const text = React.useMemo(
    () => ({
      getLabel: (id: string) => t(COMMAND_LABEL_KEY[id] ?? UNKNOWN_LABEL_KEY),
      getDescription: (id: string) => t(COMMAND_DESC_KEY[id] ?? UNKNOWN_DESC_KEY),
      getKeywords: (id: string) =>
        (t.raw(COMMAND_KEYWORDS_KEY[id] ?? 'commands.unknown.keywords') as string[]) ?? [],
    }),
    [t],
  )

  // 打开时:重置查询 + 读取 MRU + 聚焦
  React.useEffect(() => {
    if (open) {
      setQuery('')
      setActiveIndex(0)
      setMruIds(getMruCommandIds())
      const timer = setTimeout(() => inputRef.current?.focus(), 50)
      return () => clearTimeout(timer)
    }
  }, [open])

  // 分组结果:空查询 → MRU 组 + 分组;有查询 → 过滤 + MRU 优先排序
  const sections = React.useMemo(() => {
    const filtered = filterCommands(BUILTIN_COMMANDS, query, text)
    if (query.trim()) {
      const sorted = sortByMru(filtered, mruIds)
      return [{ group: null as string | null, items: sorted }]
    }
    const groups = groupCommands(filtered)
    const recentIds = mruIds
      .map((id) => filtered.find((c) => c.id === id))
      .filter((c): c is CommandDef => !!c)
    const recent = recentIds.length > 0 ? [{ group: null as string | null, items: recentIds }] : []
    return [...recent, ...groups.map((g) => ({ group: g.group as string | null, items: g.items }))]
  }, [query, text, mruIds])

  // 一维化(键盘导航索引与渲染对齐)
  const flatItems = React.useMemo(() => sections.flatMap((s) => s.items), [sections])

  React.useEffect(() => {
    setActiveIndex(0)
  }, [query])

  React.useEffect(() => {
    if (activeIndex >= flatItems.length) setActiveIndex(0)
  }, [flatItems.length, activeIndex])

  /** 执行命令:解析声明式 action + 记录 MRU + 关闭面板 */
  const execute = React.useCallback(
    (cmd: CommandDef) => {
      recordCommandUse(cmd.id)
      onOpenChange(false)
      switch (cmd.action.type) {
        case 'navigate':
          navigate(cmd.action.href)
          break
        case 'ideTab':
          setActiveTopTab(cmd.action.tab)
          navigate(cmd.action.href)
          break
        case 'workPanel':
          toggleWorkPanel()
          break
        case 'mode': {
          // 与 GlobalHooksProvider Ctrl+1-4 逻辑一致:重复切换提示 + 成功提示
          const mode = cmd.action.mode
          const MODE_LABEL_KEYS: Record<string, string> = {
            build: 'modeBuild',
            plan: 'modePlan',
            review: 'modeReview',
            spec: 'modeSpec',
          }
          const label = tChat(MODE_LABEL_KEYS[mode] ?? 'modeBuild')
          const modeStore = useModeStore.getState()
          if (modeStore.currentMode === mode) {
            toast.info(tChat('modeAlreadyActive', { mode: label }))
            return
          }
          modeStore.setMode(mode)
          toast.success(tChat('modeSwitched', { mode: label }))
          break
        }
      }
    },
    [navigate, onOpenChange, setActiveTopTab, tChat, toggleWorkPanel],
  )

  function onKeyDown(e: React.KeyboardEvent) {
    if (e.key === 'ArrowDown') {
      e.preventDefault()
      setActiveIndex((i) => (flatItems.length ? (i + 1) % flatItems.length : 0))
    } else if (e.key === 'ArrowUp') {
      e.preventDefault()
      setActiveIndex((i) => (flatItems.length ? (i - 1 + flatItems.length) % flatItems.length : 0))
    } else if (e.key === 'Enter') {
      e.preventDefault()
      const item = flatItems[activeIndex]
      if (item) execute(item)
    }
  }

  // 激活项滚动到可视区
  React.useEffect(() => {
    const activeEl = listRef.current?.querySelector(`[data-idx="${activeIndex}"]`)
    activeEl?.scrollIntoView({ block: 'nearest' })
  }, [activeIndex])

  return (
    <Dialog open={open} onOpenChange={onOpenChange}>
      <DialogContent className="max-w-xl gap-0 p-0">
        <div className="flex items-center gap-2 bg-muted/30 px-4 py-3">
          <Search className="h-4 w-4 text-muted-foreground" />
          <input
            ref={inputRef}
            className="flex-1 bg-transparent text-sm outline-none placeholder:text-muted-foreground"
            placeholder={t('searchPlaceholder')}
            value={query}
            onChange={(e) => setQuery(e.target.value)}
            onKeyDown={onKeyDown}
          />
          <kbd className="rounded border bg-muted px-1.5 py-0.5 text-xs text-muted-foreground">
            ESC
          </kbd>
        </div>
        <div ref={listRef} className="max-h-[50vh] overflow-y-auto p-1">
          {flatItems.length === 0 ? (
            <div className="py-8 text-center text-sm text-muted-foreground">{t('noResults')}</div>
          ) : (
            sections.map((section, sIdx) => {
              // 计算该 section 在 flatItems 中的起始偏移
              const offset = sections.slice(0, sIdx).reduce((acc, s) => acc + s.items.length, 0)
              return (
                <div key={section.group ?? 'recent'}>
                  <div className="flex items-center gap-1.5 px-3 pt-2 pb-1 text-[11px] font-medium uppercase tracking-wide text-muted-foreground/70">
                    {section.group === null ? (
                      <>
                        <History className="h-3 w-3" />
                        {t('recentGroup')}
                      </>
                    ) : (
                      t(
                        COMMAND_GROUP_LABEL_KEY[
                          section.group as keyof typeof COMMAND_GROUP_LABEL_KEY
                        ] ?? 'groups.navigate',
                      )
                    )}
                  </div>
                  {section.items.map((item, idx) => {
                    const Icon = item.icon
                    const flatIdx = offset + idx
                    return (
                      <button
                        key={item.id}
                        type="button"
                        data-idx={flatIdx}
                        className={`flex w-full items-center gap-3 rounded-lg px-3 py-2.5 text-left transition-colors ${
                          flatIdx === activeIndex ? 'bg-accent' : 'hover:bg-accent/50'
                        }`}
                        onMouseEnter={() => setActiveIndex(flatIdx)}
                        onClick={() => execute(item)}
                      >
                        <Icon className="h-4 w-4 shrink-0 text-muted-foreground" />
                        <div className="min-w-0 flex-1">
                          <div className="truncate text-sm font-medium">
                            {text.getLabel(item.id)}
                          </div>
                          <div className="truncate text-xs text-muted-foreground">
                            {text.getDescription(item.id)}
                          </div>
                        </div>
                        {item.shortcut && (
                          <kbd className="shrink-0 rounded border bg-muted px-1.5 py-0.5 text-[10px] text-muted-foreground">
                            {item.shortcut}
                          </kbd>
                        )}
                      </button>
                    )
                  })}
                </div>
              )
            })
          )}
        </div>
        <div className="flex items-center justify-between bg-muted/30 px-4 py-2 text-xs text-muted-foreground">
          <span>{t('keyboardHint')}</span>
          <span>{t('resultCount', { count: flatItems.length })}</span>
        </div>
      </DialogContent>
    </Dialog>
  )
}
