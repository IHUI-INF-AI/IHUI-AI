'use client'

import * as React from 'react'
import {
  AlertTriangle,
  BarChart3,
  FlaskConical,
  LayoutTemplate,
  Loader2,
  Plus,
  ScrollText,
  Sparkles,
  TrendingUp,
} from 'lucide-react'

import { useRules } from '@/hooks/use-rules'
import { useRulesStore } from '@/stores/rules'
import type { Rule } from '@ihui/types'
import { Button } from '@ihui/ui-react'

import { RuleItem } from './RuleItem'
import { RuleEditDialog } from './RuleEditDialog'
import { RuleTestDialog } from './RuleTestDialog'
import { RuleConflictDialog } from './RuleConflictDialog'
import { RuleTemplateDialog } from './RuleTemplateDialog'
import { RuleDetailDialog } from './RuleDetailDialog'
import { RuleAbTestDialog } from './RuleAbTestDialog'
import { RuleGlobalStatsDialog } from './RuleGlobalStatsDialog'
import { RuleAutoGenerateDialog } from './RuleAutoGenerateDialog'
import { RuleKnowledgeGraphDialog } from './RuleKnowledgeGraphDialog'

/**
 * Rules 管理器 — 规则列表 + 编辑器 + 启用/禁用 + 优先级 + 测试 + 冲突检测 + 模板库。
 *
 * 对标 Trae IDE Rules:用户可编辑的规则集,约束 agent 运行时行为。
 * 数据流:react-query(useRules)↔ /api/rules ↔ ai-service rules_engine。
 *
 * 该文件为容器/汇总层:具体逻辑已拆分到同目录下的子组件。
 */

export function RulesManager() {
  const { rules, loading, error, refresh, deleteRule, toggleEnabled } = useRules()
  const { startCreate, startEdit } = useRulesStore()
  const [showConflicts, setShowConflicts] = React.useState(false)
  const [showTemplates, setShowTemplates] = React.useState(false)
  const [showAbTest, setShowAbTest] = React.useState(false)
  const [showGlobalStats, setShowGlobalStats] = React.useState(false)
  const [showAutoGenerate, setShowAutoGenerate] = React.useState(false)
  const [showKnowledgeGraph, setShowKnowledgeGraph] = React.useState(false)
  const [detailRule, setDetailRule] = React.useState<Rule | null>(null)

  return (
    <div className="space-y-4">
      <div className="flex items-center justify-between">
        <p className="text-sm text-muted-foreground">共 {rules.length} 条规则,按优先级降序排列</p>
        <div className="flex flex-wrap items-center gap-2">
          <Button variant="outline" size="sm" onClick={() => setShowAutoGenerate(true)}>
            <Sparkles className="mr-1 h-3.5 w-3.5" />
            <span>自动生成</span>
          </Button>
          <Button variant="outline" size="sm" onClick={() => setShowConflicts(true)}>
            <AlertTriangle className="mr-1 h-3.5 w-3.5" />
            <span>检测冲突</span>
          </Button>
          <Button variant="outline" size="sm" onClick={() => setShowKnowledgeGraph(true)}>
            <TrendingUp className="mr-1 h-3.5 w-3.5" />
            <span>知识图谱</span>
          </Button>
          <Button variant="outline" size="sm" onClick={() => setShowAbTest(true)}>
            <FlaskConical className="mr-1 h-3.5 w-3.5" />
            <span>A/B 测试</span>
          </Button>
          <Button variant="outline" size="sm" onClick={() => setShowGlobalStats(true)}>
            <BarChart3 className="mr-1 h-3.5 w-3.5" />
            <span>全局统计</span>
          </Button>
          <Button variant="outline" size="sm" onClick={() => setShowTemplates(true)}>
            <LayoutTemplate className="mr-1 h-3.5 w-3.5" />
            <span>模板库</span>
          </Button>
          <Button variant="outline" size="sm" onClick={() => refresh()}>
            刷新
          </Button>
          <Button size="sm" onClick={startCreate}>
            <Plus className="mr-1 h-3.5 w-3.5" />
            <span>新建规则</span>
          </Button>
        </div>
      </div>

      {loading ? (
        <div className="flex items-center justify-center py-16 text-muted-foreground">
          <Loader2 className="mr-2 h-5 w-5 animate-spin" />
          加载中...
        </div>
      ) : error ? (
        <div className="rounded-lg border border-destructive/50 bg-destructive/10 p-4 text-sm text-destructive">
          {(error as Error).message}
        </div>
      ) : rules.length === 0 ? (
        <div className="flex flex-col items-center justify-center gap-2 rounded-lg border border-dashed py-16 text-center">
          <ScrollText className="h-8 w-8 text-muted-foreground" />
          <p className="text-sm text-muted-foreground">暂无规则,点击「新建规则」创建</p>
        </div>
      ) : (
        <div className="space-y-2">
          {rules.map((rule, idx) => (
            <RuleItem
              key={rule.id}
              rule={rule}
              index={idx + 1}
              onEdit={() => startEdit(rule)}
              onDelete={() => deleteRule(rule.id)}
              onToggle={(enabled) => toggleEnabled({ id: rule.id, enabled })}
              onShowDetail={() => setDetailRule(rule)}
            />
          ))}
        </div>
      )}

      <RuleEditDialog />
      <RuleTestDialog />
      {showConflicts && (
        <RuleConflictDialog rules={rules} onClose={() => setShowConflicts(false)} />
      )}
      {showTemplates && <RuleTemplateDialog onClose={() => setShowTemplates(false)} />}
      {showAbTest && <RuleAbTestDialog rules={rules} onClose={() => setShowAbTest(false)} />}
      {showGlobalStats && <RuleGlobalStatsDialog onClose={() => setShowGlobalStats(false)} />}
      {showAutoGenerate && (
        <RuleAutoGenerateDialog
          onClose={() => setShowAutoGenerate(false)}
          onCreated={() => {
            refresh()
            setShowAutoGenerate(false)
          }}
        />
      )}
      {showKnowledgeGraph && (
        <RuleKnowledgeGraphDialog rules={rules} onClose={() => setShowKnowledgeGraph(false)} />
      )}
      {detailRule && <RuleDetailDialog rule={detailRule} onClose={() => setDetailRule(null)} />}
    </div>
  )
}

export default RulesManager
