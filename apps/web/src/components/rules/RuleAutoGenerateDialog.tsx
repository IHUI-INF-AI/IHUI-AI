'use client'

import * as React from 'react'
import { Loader2, Sparkles, X } from 'lucide-react'

import { cn } from '@/lib/utils'
import { rulesApi } from './rules-api'
import type { RuleAutoGenerateResult } from './types'
import { matchTypeLabel, scopeLabel } from '@/stores/rules'
import { useRules } from '@/hooks/use-rules'
import { Button } from '@ihui/ui-react'

interface RuleAutoGenerateDialogProps {
  onClose: () => void
  onCreated: () => void
}

function RuleAutoGenerateDialog({ onClose, onCreated }: RuleAutoGenerateDialogProps) {
  const [result, setResult] = React.useState<RuleAutoGenerateResult | null>(null)
  const [loading, setLoading] = React.useState(false)
  const [error, setError] = React.useState<string | null>(null)
  const [selected, setSelected] = React.useState<Set<number>>(new Set())
  const [creating, setCreating] = React.useState(false)
  const { createRule } = useRules()

  const handleGenerate = async () => {
    setLoading(true)
    setError(null)
    setResult(null)
    setSelected(new Set())
    try {
      const res = await rulesApi<RuleAutoGenerateResult>('/api/rules/auto-generate', {
        method: 'POST',
        body: JSON.stringify({}),
      })
      setResult(res)
      // 默认全选 confidence >= 0.6 的候选
      setSelected(
        new Set(
          res.candidates
            .map((_, idx) => idx)
            .filter((idx) => res.candidates[idx]!.confidence >= 0.6),
        ),
      )
    } catch (e) {
      setError((e as Error).message)
    } finally {
      setLoading(false)
    }
  }

  const handleBatchCreate = async () => {
    if (!result || selected.size === 0) return
    setCreating(true)
    try {
      for (const idx of selected) {
        const candidate = result.candidates[idx]
        if (!candidate) continue
        await createRule({
          name: candidate.name,
          description: candidate.description,
          content: candidate.content,
          scope: candidate.scope,
          matchType: candidate.matchType,
          priority: Math.round(candidate.confidence * 100),
        })
      }
      onCreated()
    } catch (e) {
      setError((e as Error).message)
    } finally {
      setCreating(false)
    }
  }

  const toggleSelect = (idx: number) => {
    setSelected((prev) => {
      const next = new Set(prev)
      if (next.has(idx)) next.delete(idx)
      else next.add(idx)
      return next
    })
  }

  return (
    // eslint-disable-next-line jsx-a11y/click-events-have-key-events, jsx-a11y/no-static-element-interactions -- 模态遮罩点击外部关闭;键盘用户通过关闭按钮(X)提供等价交互
    <div
      className="fixed inset-0 z-modal flex items-center justify-center bg-white/40 p-4 dark:bg-black/40"
      onClick={(e) => e.target === e.currentTarget && onClose?.()}
    >
      <div className="flex max-h-[85vh] w-full max-w-lg flex-col space-y-3 rounded-lg border border-border bg-card p-4 shadow-lg">
        <div className="flex items-center justify-between">
          <span className="text-sm font-semibold">
            <Sparkles className="mr-1 inline h-3.5 w-3.5" />
            自动生成规则
          </span>
          <button
            type="button"
            onClick={onClose}
            aria-label="关闭"
            className="flex h-9 w-9 items-center justify-center rounded-md text-muted-foreground hover:bg-accent hover:text-foreground"
          >
            <X className="h-4 w-4" />
          </button>
        </div>

        <p className="text-[10px] text-muted-foreground">
          从最近 7 天用户行为模式 LLM 提炼候选规则,勾选后批量创建
        </p>

        {!result && !loading && !error && (
          <div className="flex flex-col items-center justify-center gap-3 py-8 text-center">
            <Sparkles className="h-8 w-8 text-muted-foreground" />
            <Button size="sm" onClick={handleGenerate}>
              开始分析行为模式
            </Button>
          </div>
        )}

        {loading && (
          <div className="flex items-center justify-center py-8 text-muted-foreground">
            <Loader2 className="mr-2 h-4 w-4 animate-spin" />
            LLM 分析行为模式中...
          </div>
        )}

        {error && (
          <div className="rounded-md border border-destructive/50 bg-destructive/10 px-3 py-2 text-xs text-destructive">
            {error}
          </div>
        )}

        {result && (
          <div className="thin-scroll space-y-2 overflow-y-auto">
            {result.degraded && (
              <div className="rounded-sm bg-yellow-500/10 px-2 py-1 text-[10px] text-yellow-600">
                {result.message ?? '降级模式:LLM 不可用,返回空候选列表'}
              </div>
            )}
            <p className="text-[10px] text-muted-foreground">
              分析了 {result.behaviorCount} 条行为记录,生成 {result.candidates.length} 条候选规则
            </p>
            {result.candidates.length === 0 ? (
              <p className="py-4 text-center text-xs text-muted-foreground">
                无候选规则(行为数据不足或 LLM 不可用)
              </p>
            ) : (
              result.candidates.map((candidate, idx) => (
                <div
                  key={idx}
                  className={cn(
                    'space-y-1.5 rounded-md border bg-background px-3 py-2',
                    selected.has(idx) ? 'border-foreground/20' : 'border-border',
                  )}
                >
                  <div className="flex items-center gap-2">
                    <input
                      type="checkbox"
                      checked={selected.has(idx)}
                      onChange={() => toggleSelect(idx)}
                      className="h-3 w-3 shrink-0"
                    />
                    <span className="flex-1 truncate text-sm font-medium">{candidate.name}</span>
                    <span
                      className={cn(
                        'shrink-0 rounded-sm px-2 py-1 text-[10px]',
                        candidate.confidence >= 0.8
                          ? 'bg-green-500/10 text-green-600'
                          : candidate.confidence >= 0.6
                            ? 'bg-yellow-500/10 text-yellow-600'
                            : 'bg-muted text-muted-foreground',
                      )}
                    >
                      置信度 {(candidate.confidence * 100).toFixed(0)}%
                    </span>
                  </div>
                  {candidate.description && (
                    <p className="text-[10px] text-muted-foreground">{candidate.description}</p>
                  )}
                  <div className="flex items-center gap-1">
                    <span className="rounded-sm bg-muted px-1 py-0 text-[10px] text-muted-foreground">
                      {matchTypeLabel(candidate.matchType)}
                    </span>
                    <span className="rounded-sm bg-muted px-1 py-0 text-[10px] text-muted-foreground">
                      {scopeLabel(candidate.scope)}
                    </span>
                  </div>
                  <pre className="thin-scroll max-h-20 overflow-auto rounded-sm bg-muted/50 p-1.5 text-[10px] leading-relaxed text-muted-foreground">
                    {candidate.content}
                  </pre>
                </div>
              ))
            )}
          </div>
        )}

        {result && result.candidates.length > 0 && (
          <div className="flex items-center justify-between">
            <span className="text-[10px] text-muted-foreground">
              已选 {selected.size} / {result.candidates.length} 条
            </span>
            <div className="flex items-center gap-2">
              <Button variant="outline" size="sm" onClick={onClose}>
                取消
              </Button>
              <Button
                size="sm"
                onClick={handleBatchCreate}
                disabled={creating || selected.size === 0}
              >
                {creating ? '创建中...' : `批量创建(${selected.size})`}
              </Button>
            </div>
          </div>
        )}
      </div>
    </div>
  )
}

export { RuleAutoGenerateDialog }
export type { RuleAutoGenerateDialogProps }
