'use client'

// 平台特有:跳到 web 会话改动 Dialog(useSessionDiffStore)。不改 ai-service 循环。

import { FileDiff } from 'lucide-react'
import { Button } from '@ihui/ui-react'

import type { SessionFileChange } from '@ihui/shared/chat/session-file-changes'
import { useSessionDiffStore } from '@/stores/session-diff'

export interface ToolDiffJumpSource {
  filePath: string
  toolName: string
  oldContent?: string
  newContent?: string
  isNewFile?: boolean
  applyStatus?: SessionFileChange['applyStatus']
}

/** 单次工具 diff → 会话改动总览的一条。次数固定为 1,不在这里做跨消息聚合。 */
export function sessionChangeFromToolDiff(source: ToolDiffJumpSource): SessionFileChange {
  return {
    filePath: source.filePath,
    isNewFile: source.isNewFile ?? false,
    toolName: source.toolName,
    changedCount: 1,
    applyStatus: source.applyStatus,
    oldContent: source.oldContent ?? '',
    newContent: source.newContent ?? '',
  }
}

/** 打开已有会话改动 Dialog,只带这一份 diff。 */
export function openToolDiff(source: ToolDiffJumpSource): void {
  useSessionDiffStore.getState().openWith([sessionChangeFromToolDiff(source)])
}

export function ToolDiffJumpButton({
  source,
  label,
}: {
  source: ToolDiffJumpSource
  label: string
}) {
  return (
    <Button
      type="button"
      size="xs"
      variant="secondary"
      data-testid="tool-call-jump-diff"
      onClick={() => openToolDiff(source)}
    >
      <FileDiff className="h-3.5 w-3.5" aria-hidden />
      {label}
    </Button>
  )
}
