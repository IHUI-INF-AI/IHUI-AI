/**
 * D35 投影 hook 装车锁(2026-10-31)。
 *
 * 此前 `use-chat-history-projection` 的实现、41 例共享层测试、CLI 消费方都在,
 * 但 web 侧**没有任何页面会走到它**(hook 里那句"尚未挂进聊天主列表"如实登记即此)。
 * 本锁判的是调用点(去注释后的代码面):光 import、注释里提名字都不算装车。
 * 变异对照:把 chat-pane-body 里三处调用删掉/注释掉,本文件必须红。
 */
import { readFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { describe, expect, it } from 'vitest'

const here = dirname(fileURLToPath(import.meta.url))
const source = readFileSync(join(here, '..', 'chat-pane-body.tsx'), 'utf8')
const codeFace = source
  .split('\n')
  .filter((line) => !line.trimStart().startsWith('//') && !line.trimStart().startsWith('*'))
  .join('\n')

describe('D35 投影 hook 在聊天窗格的装车锁', () => {
  it('窗格真调用 hook(不是 import 了不用)', () => {
    expect(codeFace).toMatch(/useChatHistoryProjection\(/)
  })

  it('首屏投影与增量续读都真发起(loadLatest / refreshNewer 的调用点)', () => {
    expect(codeFace).toMatch(/projection\.loadLatest\(/)
    expect(codeFace).toMatch(/projection\.refreshNewer\(/)
  })

  it('投影结果真进消费面(turns 被读取并按 id 补进 store)', () => {
    expect(codeFace).toMatch(/projection\.turns/)
    expect(codeFace).toMatch(/chatStore\.setState\(\{\s*messages:/)
  })
})
