import { fireEvent, render, screen } from '@testing-library/react'
import { beforeEach, describe, expect, it } from 'vitest'

import { useSessionDiffStore } from '@/stores/session-diff'

import { openToolDiff, sessionChangeFromToolDiff, ToolDiffJumpButton } from '../open-tool-diff'

describe('sessionChangeFromToolDiff', () => {
  it('把单次工具 diff 收成会话改动的一条', () => {
    expect(
      sessionChangeFromToolDiff({
        filePath: 'src/a.ts',
        toolName: 'edit_file',
        oldContent: 'a',
        newContent: 'b',
        isNewFile: false,
        applyStatus: 'pending',
      }),
    ).toEqual({
      filePath: 'src/a.ts',
      isNewFile: false,
      toolName: 'edit_file',
      changedCount: 1,
      applyStatus: 'pending',
      oldContent: 'a',
      newContent: 'b',
    })
  })
})

describe('ToolDiffJumpButton', () => {
  beforeEach(() => {
    useSessionDiffStore.setState({ open: false, changes: [] })
  })

  it('点击后只打开这一份 diff,不另起一套对照视图', () => {
    render(
      <ToolDiffJumpButton
        label="会话改动总览"
        source={{
          filePath: 'src/a.ts',
          toolName: 'write_file',
          oldContent: '',
          newContent: 'hi',
          isNewFile: true,
        }}
      />,
    )
    fireEvent.click(screen.getByTestId('tool-call-jump-diff'))
    const state = useSessionDiffStore.getState()
    expect(state.open).toBe(true)
    expect(state.changes.map((change) => change.filePath)).toEqual(['src/a.ts'])
    expect(state.changes[0]?.isNewFile).toBe(true)
  })

  it('openToolDiff 与按钮走同一出口', () => {
    openToolDiff({ filePath: 'src/b.ts', toolName: 'edit_file', newContent: 'x' })
    expect(useSessionDiffStore.getState().changes[0]?.filePath).toBe('src/b.ts')
    expect(useSessionDiffStore.getState().changes[0]?.oldContent).toBe('')
  })
})
