import { cleanup, fireEvent, render, screen } from '@testing-library/react'
import type { ReactNode } from 'react'
import { afterEach, describe, expect, it, vi } from 'vitest'

vi.mock('next-intl', () => ({
  useTranslations: () => (key: string) => key,
}))

vi.mock('@/lib/media-proxy', () => ({
  toMediaImageUrl: (url: string) => url,
  toMediaStreamUrl: (url: string) => url,
}))

vi.mock('@/components/feedback', () => ({
  Tooltip: ({ children }: { children: ReactNode }) => <>{children}</>,
}))

import { ContextReferencePanel } from '../context-reference-panel'

const docx = {
  id: 'f-doc',
  type: 'file' as const,
  label: '合作协议.docx',
  uploadState: 'ready' as const,
}

const png = {
  id: 'f-img',
  type: 'image' as const,
  label: '现场照片.png',
  uploadState: 'ready' as const,
}

afterEach(cleanup)

describe('ContextReferencePanel · 对话侧 AI 修订入口', () => {
  it('文档附件出现魔棒,点击回传引用 id', () => {
    const onRevise = vi.fn()
    render(<ContextReferencePanel references={[docx, png]} onRevise={onRevise} />)
    fireEvent.click(screen.getByTestId('revise-reference-f-doc'))
    expect(onRevise).toHaveBeenCalledWith('f-doc')
  })

  it('图片附件没有修订入口,宿主未接线时也不渲染', () => {
    render(<ContextReferencePanel references={[png]} onRevise={() => {}} />)
    expect(screen.queryByTestId('revise-reference-f-img')).toBeNull()

    render(<ContextReferencePanel references={[docx]} />)
    expect(screen.queryByTestId('revise-reference-f-doc')).toBeNull()
  })
})
