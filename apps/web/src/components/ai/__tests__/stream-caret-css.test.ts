// jsdom 不计算样式、也不供 file 协议 URL(仓内先例:happy-dom 件用 fileURLToPath 走
// dirname(resolve()) 取 pack,jsdom 件不可),而本档判据全在 CSS 文本层 —— 独立成件、
// node 环境直读源文件,与 markdown-stream.test.tsx 的 DOM 档各钉一面。

import { readFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { describe, expect, it } from 'vitest'

// __tests__ → ai → components → src,再进 styles(与组件源码同一仓形路径)
const cssPath = resolve(dirname(fileURLToPath(import.meta.url)), '../../../styles/animations.css')
const css = readFileSync(cssPath, 'utf8')

describe('stream-caret-host 内联光标 CSS 契约', () => {
  it('规则在位且贴最后一个块元素(::after 行内子盒,告别悬在下一行)', () => {
    expect(css).toMatch(/\.stream-caret-host > :last-child::after\s*\{[^}]*content:\s*''/)
    expect(css).toMatch(/display:\s*inline-block/)
  })

  it('色走 design-token var(--color-primary),禁裸色值;节拍与思考区光标同谱 cursor-blink 1s step-end', () => {
    expect(css).toMatch(/background:\s*var\(--color-primary\)/)
    expect(css).toMatch(/animation:\s*cursor-blink 1s step-end infinite/)
  })

  it('motion-reduce 档降级常亮(无障碍"减少动态"偏好下不闪)', () => {
    expect(css).toMatch(
      /@media \(prefers-reduced-motion: reduce\)\s*\{\s*\.stream-caret-host[^}]*\{[^}]*animation:\s*none/,
    )
  })
})
