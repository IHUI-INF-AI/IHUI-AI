// 深化W/Y(2026-11-17):失败分布徽章点击定位的**目标决策**纯函数。
// 从组件里抽出可测:agent-task-progress-pane 只负责"展开批次 + RAF 滚动到 targetId + 高亮",
// 而"在子代理列表里选哪个当 targetId"这一决策收在本模块,轻量钉住防回归。

import type { Subagent } from '@/hooks/use-agent-progress'

/** 终态失败子代理(failed/dead);运行中/完成的不算 */
function isFailedTerminal(s: Subagent): boolean {
  return s.status === 'failed' || s.status === 'dead'
}

/**
 * 在已排序子代理里找首个匹配谓词的失败子代理 id。
 * 输入已是展示排序(sortSubagentsForDisplay)结果,故"首个"= 展示列表最靠前者。
 * 找不到返回 null(组件层静默忽略,理论不发生:徽章计数>0 ⇒ 至少一个该类失败)。
 */
export function resolveJumpTargetId(
  subagents: readonly Subagent[],
  matches: (s: Subagent) => boolean,
): string | null {
  const target = subagents.find((s) => isFailedTerminal(s) && matches(s))
  return target?.id ?? null
}

/** 按失败模式(failureKind)定位 —— 深化W:点"失败模式"徽章(限流/凭据被拒…) */
export function resolveJumpTargetIdByKind(
  subagents: readonly Subagent[],
  kind: string,
): string | null {
  return resolveJumpTargetId(subagents, (s) => s.failureKind === kind)
}

/** 按失败来源(failureSource)定位 —— 深化Y:点"失败来源"徽章(上游/本地/网络/工具) */
export function resolveJumpTargetIdBySource(
  subagents: readonly Subagent[],
  source: string,
): string | null {
  return resolveJumpTargetId(subagents, (s) => s.failureSource === source)
}
