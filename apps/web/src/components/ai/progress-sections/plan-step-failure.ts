// 中心字段:steps[].id 是跳转目标唯一锚点(PlanStep.id: string 必填)。
// steps[].error 与 status='failed' 是等价表达(旧事件 error=true 与显式 failed),
// 判定口径与 PlanStepsCard 折叠态 errorCount 一致。

import type { PlanStep } from '@/hooks/use-agent-progress'

/** 步骤是否算失败(与 PlanStepsCard 折叠态 errorCount 同口径:error=true 或 status=failed)。 */
export function isPlanStepFailed(step: PlanStep): boolean {
  return step.error === true || step.status === 'failed'
}

/**
 * 取首个失败步骤的 id,供失败计数徽章点击定位。
 * 返回 null 表示无失败步骤(调用方不造残标)。
 */
export function firstFailedStepId(steps: PlanStep[]): string | null {
  for (const s of steps) {
    if (isPlanStepFailed(s)) return s.id
  }
  return null
}
