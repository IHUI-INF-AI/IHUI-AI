// Spec 模式面板:智能分析标签页
import { Loader2, Brain } from 'lucide-react'
import { cn } from '@/lib/utils'
import { MarkdownViewer } from '@/components/media/MarkdownViewer'
import type { SpecPanelApi } from './useSpecPanel'

export function SpecEnhanceTab({ p }: { p: SpecPanelApi }) {
  return (
    <div className="space-y-2">
      <div className="flex items-center gap-2">
        <button
          type="button"
          onClick={p.handleEnhance}
          disabled={p.enhanceLoading}
          className={cn(
            'flex shrink-0 whitespace-nowrap h-7 items-center gap-1 rounded-md px-3 text-xs font-medium transition-colors',
            'bg-primary text-primary-foreground hover:bg-primary/90',
            p.enhanceLoading && 'cursor-not-allowed opacity-60',
          )}
        >
          {p.enhanceLoading ? (
            <Loader2 className="h-3 w-3 animate-spin" />
          ) : (
            <Brain className="h-3 w-3" />
          )}
          <span>{p.enhanceLoading ? '分析中' : '生成智能分析'}</span>
        </button>
      </div>
      {p.enhanceResult?.enhancement ? (
        <div className="max-h-[50vh] overflow-auto rounded-md border border-border bg-background p-3">
          <MarkdownViewer content={p.enhanceResult.enhancement} />
        </div>
      ) : (
        <p className="text-xs text-muted-foreground p-2">
          点击「生成智能分析」由 LLM 分析 spec,生成功能意图说明 + 潜在风险点 + 改进建议
        </p>
      )}
    </div>
  )
}
