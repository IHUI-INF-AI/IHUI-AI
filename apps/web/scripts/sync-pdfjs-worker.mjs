// 让 PDF.js 主线程 bundle 与 public 下的 worker 永远同版本。
// 背景(2026-11-27 真实浏览器验收):package.json 写的是 ^6.2.108,开发机解析到 6.5.438、
// 生产机仍锁在 6.2.108;public/pdfjs/pdf.worker.min.mjs 却是 6.5.438 的副本。
// 结果主线程(6.2)向 worker(6.5)发 "test",worker 报 `Unknown action from worker: test`,
// PDF 查看器一直转圈。版本不能靠人记得同步,必须在每次构建前从当前安装的包复制。
import { copyFileSync, existsSync, mkdirSync, readFileSync } from 'node:fs'
import { createHash } from 'node:crypto'
import { dirname, join, resolve } from 'node:path'
import { createRequire } from 'node:module'

const require = createRequire(import.meta.url)
const pkgPath = require.resolve('pdfjs-dist/package.json')
const pkgRoot = dirname(pkgPath)
const src = join(pkgRoot, 'build', 'pdf.worker.min.mjs')
const dest = resolve(process.cwd(), 'public', 'pdfjs', 'pdf.worker.min.mjs')

if (!existsSync(src)) {
  throw new Error(`[pdfjs-worker] 找不到 ${src};请先安装 pdfjs-dist`)
}
mkdirSync(dirname(dest), { recursive: true })
copyFileSync(src, dest)

const version = JSON.parse(readFileSync(pkgPath, 'utf8')).version
const sha = createHash('sha256').update(readFileSync(dest)).digest('hex').slice(0, 12)
console.log(`[pdfjs-worker] synced ${version} -> ${dest} sha256=${sha}`)
