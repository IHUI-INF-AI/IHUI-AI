// #11 引用溯源到终端(第 53 轮):cli 此前对 citations 帧 0 命中。
// 界面措辞必须出自词表(不是写死中文),来源内容(source/label)原样列出。
import { describe, expect, it } from 'vitest';

import { citationNoteText } from '../src/commands/task-status-line.js';

describe('citationNoteText(#11 承接)', () => {
  it('多条来源用 · 连接并带 source 标注', () => {
    const line = citationNoteText([
      { source: 'codebase', label: 'AGENTS.md §3' },
      { source: 'rag', label: '历史会话片段' },
    ]);
    expect(line).toContain('AGENTS.md §3(codebase)');
    expect(line).toContain('历史会话片段(rag)');
    expect(line.startsWith('参考来源：')).toBe(true);
    expect(line).not.toContain('cli.citationSources');
  });

  it('空列表不得产出"参考来源:"空行(调用方本就不该打,双保险)', () => {
    expect(citationNoteText([])).toBe('参考来源：');
  });
});
