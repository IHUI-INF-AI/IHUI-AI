/**
 * CLI 工具活动行(功能名 · 对象 · 度量)单测 —— 单一真相源 describeToolCall 的端内薄渲染。
 * 核心断言:CLI 输出禁止出现英文工具码名(AGENTS.md §5),仅无映射的动态名才回落原码名。
 */
import { describe, it, expect } from 'vitest'
import { describeToolActivityLine, toolActivityLabel } from '../src/commands/task-status-line.js'

describe('describeToolActivityLine', () => {
  it('read_file 解析出本地化功能名 + 路径对象,不含码名 read_file', () => {
    const { title, subject } = describeToolActivityLine({
      toolName: 'read_file',
      args: { path: 'apps/cli/src/i18n/index.ts' },
      status: 'success',
    })
    expect(title).toBe('读取文件内容')
    expect(subject).toBe('apps/cli/src/i18n/index.ts')
    expect(title).not.toContain('read_file')
  })

  it('write_file 成功后度量给出 +x -y 行增删', () => {
    const { title, metric } = describeToolActivityLine({
      toolName: 'write_file',
      args: { path: 'a/b.ts', content: 'l1\nl2\nl3' },
      status: 'success',
    })
    expect(title).toBe('写入文件')
    expect(metric).toBe('+3 -0')
  })

  it('检索类工具功能名 + 对象,不含码名 search_codebase', () => {
    const line = toolActivityLabel('search_codebase', { query: 'login' })
    expect(line).toContain('搜索代码库')
    expect(line).toContain('login')
    expect(line).not.toContain('search_codebase')
  })

  it('无映射的动态工具名回落 "调用 {code}"', () => {
    const { title } = describeToolActivityLine({
      toolName: 'custom_mcp_thing',
      args: { target: 'x' },
      status: 'running',
    })
    expect(title).toBe('调用 custom_mcp_thing')
  })

  it('只有码名(无 args)时只显示功能名,不硬凑对象', () => {
    expect(toolActivityLabel('run_command')).toBe('执行命令')
  })
})
