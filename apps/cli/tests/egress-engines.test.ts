import { describe, expect, it } from 'vitest'

import { judgeEgress } from '../src/tools/egress-engines.js'

describe('judgeEgress', () => {
  it('域名只看域名表，不因为地址表没量到而改判', () => {
    expect(
      judgeEgress({ host: 'a.evil.com', denyDomains: ['evil.com'], denyIps: null }),
    ).toEqual({ verdict: 'deny', engine: 'dns', reason: 'listed' })
    expect(
      judgeEgress({ host: 'notevil.com', denyDomains: ['evil.com'], denyIps: null }),
    ).toEqual({ verdict: 'allow', engine: 'dns', reason: 'not-listed' })
  })

  it('IP 只看地址表，域名表里的同名字符串不算', () => {
    expect(
      judgeEgress({ host: '10.0.0.8', denyDomains: ['10.0.0.8'], denyIps: [] }),
    ).toEqual({ verdict: 'allow', engine: 'tcp', reason: 'not-listed' })
    expect(
      judgeEgress({ host: '10.0.0.8', denyDomains: [], denyIps: ['10.0.0.8'] }),
    ).toEqual({ verdict: 'deny', engine: 'tcp', reason: 'listed' })
  })

  it('该走的那张表没量到就拒绝放行', () => {
    expect(judgeEgress({ host: '10.0.0.8', denyDomains: [], denyIps: null })).toEqual({
      verdict: 'unjudged',
      reason: 'list-unmeasured',
    })
    expect(judgeEgress({ host: null, denyDomains: [], denyIps: [] })).toEqual({
      verdict: 'unjudged',
      reason: 'host-unmeasured',
    })
  })
})
