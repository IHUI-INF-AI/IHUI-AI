import { describe, expect, it } from 'vitest'
import * as fs from 'node:fs'
import * as os from 'node:os'
import * as path from 'node:path'
import { loadInstalls, recordInstall } from '../src/lib/registry-client.js'

describe('安装清单读不到不是没有已装项', () => {
  it('不覆盖读不到的清单,缺失仍可以新记一条', () => {
    const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'ihui-registry-installs-'))
    const blocked = path.join(dir, 'registry-installs.json')
    const fresh = path.join(dir, 'fresh.json')
    fs.mkdirSync(blocked)
    try {
      expect(() => loadInstalls(blocked)).toThrow(/不能把它说成没有已装项/)
      expect(() =>
        recordInstall(
          { sourceType: 'skill', sourceId: 'demo', version: '1.0.0', installedAt: '2026-11-06T00:00:00.000Z' },
          blocked,
        ),
      ).toThrow(/不能把它说成没有已装项/)
      expect(fs.statSync(blocked).isDirectory()).toBe(true)
      expect(loadInstalls(fresh)).toEqual([])
      recordInstall(
        { sourceType: 'skill', sourceId: 'demo', version: '1.0.0', installedAt: '2026-11-06T00:00:00.000Z' },
        fresh,
      )
      expect(loadInstalls(fresh).map((row) => row.sourceId)).toEqual(['demo'])
      const corrupt = path.join(dir, 'corrupt.json')
      const body = '{not json'
      fs.writeFileSync(corrupt, body, 'utf-8')
      expect(() =>
        recordInstall(
          { sourceType: 'skill', sourceId: 'demo', version: '1.0.0', installedAt: '2026-11-06T00:00:00.000Z' },
          corrupt,
        ),
      ).toThrow(/不能把它说成没有已装项 \(corrupt\)/)
      expect(fs.readFileSync(corrupt, 'utf-8')).toBe(body)
    } finally {
      fs.rmSync(dir, { recursive: true, force: true })
    }
  })
})
