// @vitest-environment node
/**
 * CLI 语言包加载器回归守门。
 *
 * 背景:CLI 为拿到跨端 `taskStatus.*` 而把 messages/shared 深合并到自身语言包之下,
 * 首版 deepMerge 只遍历 base 的键 → **仅存在于 override 的顶层命名空间被整块吞掉**,
 * `t('cli.errorFileNotFound')` 回显成键名(界面/终端直接显示 `cli.errorFileNotFound`)。
 * 这里把两侧命名空间同时锁住,防止再犯。
 */
import { describe, it, expect } from 'vitest'
import { t, setLocale, type Locale } from '../src/i18n/index.js'

const LOCALES: Locale[] = ['zh-CN', 'en', 'ja', 'ko', 'zh-TW']

describe('CLI i18n 加载器:端命名空间与共享命名空间同时可达', () => {
  for (const locale of LOCALES) {
    it(`${locale}: cli.* 端自有键取到译文且不回显键名`, () => {
      setLocale(locale)
      const text = t('cli.errorFileNotFound', { path: 'x/y.ts' })
      expect(text).not.toBe('cli.errorFileNotFound')
      expect(text).toContain('x/y.ts')
    })

    it(`${locale}: taskStatus.* 共享键取到译文(工具活动行的功能名与度量单位)`, () => {
      setLocale(locale)
      expect(t('taskStatus.toolReadFile')).not.toBe('taskStatus.toolReadFile')
      expect(t('taskStatus.toolBrowserNavigate')).not.toBe('taskStatus.toolBrowserNavigate')
      expect(t('taskStatus.unitLines', { n: 12 })).toContain('12')
    })
  }
})
