/**
 * Y-95 命令/传输安全回归(2026-11-18)。
 *
 * RegistryClient 所有 fetch 把 Bearer token 发往 this.apiUrl;apiUrl 若被配成非回环 http,
 * token 就明文过网。本用例钉住构造函数的 transport 闸:
 *  - https 放行;
 *  - 回环 http(localhost / 127.x / ::1)放行 —— 本地开发默认 http://localhost:8802 不能被打破;
 *  - 非回环 http / 其他协议 / 空白 / 非法 URL 一律拒绝(fail-closed)。
 */
import { describe, expect, it } from 'vitest';
import { RegistryClient } from '../src/lib/registry-client.js';

describe('Y-95 RegistryClient apiUrl transport 闸', () => {
  it('https 放行', () => {
    expect(() => new RegistryClient('https://api.aizhs.top')).not.toThrow();
  });

  it('回环 http 放行(本地开发默认)', () => {
    for (const url of [
      'http://localhost:8802',
      'http://127.0.0.1:8802',
      'http://127.0.0.9:8802',
      'http://[::1]:8802',
    ]) {
      expect(() => new RegistryClient(url), url).not.toThrow();
    }
  });

  it('非回环 http 拒绝(明文传 Bearer 面)', () => {
    for (const url of ['http://api.aizhs.top', 'http://192.168.1.10:8802', 'http://example.com']) {
      expect(() => new RegistryClient(url), url).toThrow(/https/);
    }
  });

  it('无 bearer 也不放行非回环 http(闸与 token 无关)', () => {
    expect(() => new RegistryClient('http://api.aizhs.top', undefined)).toThrow(/https/);
  });

  it('空白 / 非法 URL / 其他协议一律拒绝', () => {
    expect(() => new RegistryClient('https://api.aizhs.top/x y')).toThrow(/空白/);
    expect(() => new RegistryClient('not-a-url')).toThrow(/合法 URL/);
    expect(() => new RegistryClient('ftp://api.aizhs.top')).toThrow(/协议/);
    expect(() => new RegistryClient('')).toThrow();
  });
});
