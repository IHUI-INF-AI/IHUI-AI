import { afterEach, describe, expect, it } from 'vitest'
import * as fs from 'node:fs'
import * as os from 'node:os'
import * as path from 'node:path'
import { addTask, getTasksPath, listTasks } from '../src/commands/tasks.js'

describe('任务清单读不到', () => {
  const prevHome = process.env.HOME
  const prevProfile = process.env.USERPROFILE
  let dir = ''

  afterEach(() => {
    if (prevHome === undefined) delete process.env.HOME
    else process.env.HOME = prevHome
    if (prevProfile === undefined) delete process.env.USERPROFILE
    else process.env.USERPROFILE = prevProfile
    if (dir) fs.rmSync(dir, { recursive: true, force: true })
  })

  it('不把它覆盖成空清单', () => {
    dir = fs.mkdtempSync(path.join(os.tmpdir(), 'ihui-tasks-unread-'))
    process.env.HOME = dir
    process.env.USERPROFILE = dir
    const blocked = getTasksPath()
    fs.mkdirSync(path.dirname(blocked), { recursive: true })
    fs.mkdirSync(blocked)
    expect(() => addTask(dir, 'keep')).toThrow(/不能把它覆盖成空清单/)
    expect(() => listTasks(dir)).toThrow(/不能把它覆盖成空清单/)
    expect(fs.statSync(blocked).isDirectory()).toBe(true)
  })
})
