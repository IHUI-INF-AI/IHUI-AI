import { describe, expect, it } from 'vitest'
import { resolveMaxSubagentDepth } from '../src/tools/subagent.js'

describe('subagent depth policy', () => {
  it('缺省 5 层，不再回到旧的 3 层硬顶', () => {
    expect(resolveMaxSubagentDepth(undefined)).toBe(5)
  })

  it('env 只能在 1..5 内收紧，越界值被夹住', () => {
    expect(resolveMaxSubagentDepth('1')).toBe(1)
    expect(resolveMaxSubagentDepth('3')).toBe(3)
    expect(resolveMaxSubagentDepth('9')).toBe(5)
    expect(resolveMaxSubagentDepth('0')).toBe(1)
    expect(resolveMaxSubagentDepth('abc')).toBe(5)
  })
})
