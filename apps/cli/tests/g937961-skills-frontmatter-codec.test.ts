// 票 G-937961 —— skills frontmatter codec:固定键序幂等写 + bodyLineOffset + unterminated 容错。
// 上游出处 `saved-workflows/frontmatter.ts`(块注释包 YAML);我方载体是 `.md` 的 `---` 围栏,
// codec 落在 `src/skills/frontmatter.ts`,写路径(skills/sync.ts)与加载路径(skills/index.ts)
// 都从这一个出口进出。
import { describe, expect, it } from 'vitest';
import {
  parseSkillsFrontmatter,
  serializeSkillsFrontmatter,
} from '../src/skills/frontmatter.js';
import { parseSkillDefinition, type SkillFrontmatter } from '../src/skills/index.js';

const fullFm: SkillFrontmatter = {
  name: 'demo-skill',
  description: 'demo description',
  allowedTools: ['read_file', 'run_command'],
  tools: ['web_search'],
  model: 'glm-5.3-flash',
  tags: ['coding', 'review'],
  version: '1.2.0',
  license: 'Apache-2.0',
  source: 'hub',
  relatedSkills: ['other-skill'],
  progressiveDisclosure: true,
  autoGeneratedAt: '2026-09-29T00:00:00.000Z',
  autoGeneratedFromTask: 'task-42',
  prerequisites: { commands: ['pnpm'], env: ['GITHUB_TOKEN'] },
};

describe('serializeSkillsFrontmatter:固定键序 ⇒ 幂等写', () => {
  it('与对象插入序无关,两次序列化逐字节相同', () => {
    const a: SkillFrontmatter = { name: 'x', description: 'd', tags: ['t'] };
    const b: SkillFrontmatter = { tags: ['t'], description: 'd', name: 'x' };
    expect(serializeSkillsFrontmatter(a)).toBe(serializeSkillsFrontmatter(b));
    expect(serializeSkillsFrontmatter(a)).toBe('name: x\ndescription: d\ntags: [t]');
  });

  it('键序固定:name → description → … → prerequisites(嵌套 commands/env 除外)', () => {
    const keys = serializeSkillsFrontmatter(fullFm)
      .split('\n')
      .map((l) => l.split(':')[0]!.trim())
      .filter((k) => k !== '' && k !== 'commands' && k !== 'env');
    expect(keys).toEqual([
      'name',
      'description',
      'allowed-tools',
      'tools',
      'model',
      'tags',
      'version',
      'license',
      'source',
      'related-skills',
      'progressive-disclosure',
      'auto-generated-at',
      'auto-generated-from-task',
      'prerequisites',
    ]);
  });
});

describe('save→parse 往返:经真实加载解析器逐字节恒等', () => {
  it('serialize → parseSkillDefinition → re-serialize 逐字节相同', () => {
    const body = '\n第一行正文\nsecond line\n';
    const fileText = `---\n${serializeSkillsFrontmatter(fullFm)}\n---\n${body}`;
    const def = parseSkillDefinition(fileText, '/tmp/demo-skill.md');
    expect(def.hasFrontmatter).toBe(true);
    expect(def.frontmatter).toEqual(fullFm);
    const resaved = `---\n${serializeSkillsFrontmatter(def.frontmatter)}\n---\n${body}`;
    expect(resaved).toBe(fileText);
  });
});

describe('parseSkillsFrontmatter:bodyLineOffset', () => {
  it('fileLine = bodyLine + bodyLineOffset(1 起数)', () => {
    const r = parseSkillsFrontmatter('---\nname: x\n---\nline1\nline2');
    expect(r.ok).toBe(true);
    if (!r.ok) return;
    expect(r.front).toBe('name: x');
    expect(r.body).toBe('line1\nline2');
    expect(r.bodyLineOffset).toBe(3);
    // 正文第 2 行(bodyLine=2)对应文件第 5 行 —— 诊断行号换算的唯一公式。
    expect(2 + r.bodyLineOffset).toBe(5);
  });

  it('两行式空块(--- 空块 body)offset=2', () => {
    const r = parseSkillsFrontmatter('---\n---\nbody');
    expect(r.ok).toBe(true);
    if (!r.ok) return;
    expect(r.front).toBe('');
    expect(r.bodyLineOffset).toBe(2);
  });

  it('CRLF 行尾也认,front/body 不带 CR 残留', () => {
    const r = parseSkillsFrontmatter('---\r\nname: x\r\n---\r\nbody');
    expect(r.ok).toBe(true);
    if (!r.ok) return;
    expect(r.front).toBe('name: x');
    expect(r.body).toBe('body');
  });
});

describe('unterminated_frontmatter:手删闭合行的容错', () => {
  it('codec 给具名 reason,不静默当 missing', () => {
    const r = parseSkillsFrontmatter('---\nname: x\ndescription: no closing fence');
    expect(r).toMatchObject({ ok: false, reason: 'unterminated_frontmatter' });
  });

  it('加载路径容错降级:不抛、整份原文当正文、frontmatter 置空', () => {
    const broken = '---\nname: ghost-skill\ndescription: no closing fence\nbody text';
    const def = parseSkillDefinition(broken, '/tmp/ghost.md');
    expect(def.hasFrontmatter).toBe(false);
    expect(def.frontmatter).toEqual({});
    expect(def.content).toBe(broken.trim());
  });

  it('missing_frontmatter:没有围栏的文件照旧', () => {
    expect(parseSkillsFrontmatter('just body')).toMatchObject({
      ok: false,
      reason: 'missing_frontmatter',
    });
  });
});
