import { once } from 'node:events';
import { createServer } from 'node:net';
import { describe, expect, it } from 'vitest';

import { connectToolHostMcp } from '../src/sandbox/tool-host-mcp.js';

describe('tool-host MCP raw relay adapter', () => {
  it('bridges stdin/stdout as a ChildProcess-shaped channel without exposing the host PID', async () => {
    let closed = 0;
    const server = createServer((socket) => {
      let tokenDone = false;
      let pending = '';
      socket.on('data', (chunk: Buffer) => {
        if (tokenDone) {
          socket.write(chunk);
          return;
        }
        pending += chunk.toString('utf8');
        const newline = pending.indexOf('\n');
        if (newline < 0) return;
        tokenDone = true;
        const rest = pending.slice(newline + 1);
        pending = '';
        if (rest.length > 0) socket.write(rest);
      });
    });
    server.listen(0, '127.0.0.1');
    await once(server, 'listening');
    const address = server.address();
    if (typeof address === 'string' || address === null) throw new Error('测试 server 没有端口');

    const proc = await connectToolHostMcp(
      { host: '127.0.0.1', port: address.port, token: 'relay-token', pid: 4321 },
      { close: async () => { closed += 1; } },
    );
    expect(proc.pid).toBe(0);
    expect(proc.mcpPid).toBe(4321);

    const response = once(proc.stdout, 'data');
    proc.stdin.write('{"jsonrpc":"2.0","id":1,"method":"ping"}\n');
    const [chunk] = await response;
    expect(chunk.toString('utf8')).toBe('{"jsonrpc":"2.0","id":1,"method":"ping"}\n');

    proc.kill();
    expect(proc.killed).toBe(true);
    expect(closed).toBe(1);
    server.closeAllConnections?.();
    server.close();
  });
});
