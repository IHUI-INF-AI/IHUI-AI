import { describe, expect, it } from 'vitest'
import * as fs from 'node:fs'
import * as os from 'node:os'
import * as path from 'node:path'
import { addInstalledSkill } from '../src/commands/ai-skills.js'

describe('已安装技能名单读不到', () => {
  it('不覆盖成只剩新的一项,缺失仍可以新记', () => {
    const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'ihui-ai-skills-'))
    const blocked = path.join(dir, 'ai-skills.json')
    const fresh = path.join(dir, 'fresh.json')
    fs.mkdirSync(blocked)
    try {
      expect(() => addInstalledSkill('demo', blocked)).toThrow(/不能把它覆盖成只剩新的一项/)
      expect(fs.statSync(blocked).isDirectory()).toBe(true)
      expect(addInstalledSkill('demo', fresh)).toBe(false)
      expect(addInstalledSkill('demo', fresh)).toBe(true)
      const saved = JSON.parse(fs.readFileSync(fresh, 'utf-8')) as { installed: string[] }
      expect(saved.installed).toEqual(['demo'])
    } finally {
      fs.rmSync(dir, { recursive: true, force: true })
    }
  })
})
