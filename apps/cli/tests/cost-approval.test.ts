import { describe, expect, it } from 'vitest'

import { decideCostApproval } from '../src/tools/cost-approval.js'

const base = {
  mandatory: true,
  failureMode: 'requireApproval',
  category: 'high-credit',
  balance: 10,
  cost: 4,
  decision: null as 'approved' | 'rejected' | null,
}

describe('decideCostApproval', () => {
  it('不是强制项就放行', () => {
    expect(decideCostApproval({ ...base, mandatory: false })).toEqual({
      disposition: 'proceed',
      reason: 'not-mandatory',
      effect: 'run',
    })
  })

  it('没量到是否强制、审批方式、余额时都不放行', () => {
    expect(decideCostApproval({ ...base, mandatory: null }).effect).toBe('none')
    expect(decideCostApproval({ ...base, failureMode: 'allow' }).reason).toBe('mode-unmeasured')
    expect(decideCostApproval({ ...base, balance: null }).reason).toBe('amount-unmeasured')
  })

  it('余额不够或被拒绝都没有副作用，通过才执行', () => {
    expect(decideCostApproval({ ...base, cost: 11 })).toEqual({
      disposition: 'refused',
      reason: 'insufficient-balance',
      effect: 'none',
    })
    expect(decideCostApproval({ ...base, decision: 'rejected' }).effect).toBe('none')
    expect(decideCostApproval(base).reason).toBe('awaiting-approval')
    expect(decideCostApproval({ ...base, decision: 'approved' })).toEqual({
      disposition: 'proceed',
      reason: 'approved',
      effect: 'run',
    })
  })
})
