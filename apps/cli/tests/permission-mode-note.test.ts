// G-153:权限档要说清后果。锁两条最容易坏的性质:五个已知档都能取到真文案、
// 未知档返回空串(宁可不说,也不回显键名或编一句假的)。
import { describe, expect, it } from 'vitest';

import { permissionModeNote } from '../src/commands/task-status-line.js';

describe('permissionModeNote(G-153)', () => {
  it('五个已知档各出真文案,且不回显键名', () => {
    for (const mode of ['default', 'plan', 'acceptEdits', 'bypassPermissions', 'manual']) {
      const note = permissionModeNote(mode);
      expect(note.length).toBeGreaterThan(4);
      expect(note).not.toContain('cli.permNote');
    }
  });

  it('高风险档文案确实提到风险', () => {
    expect(permissionModeNote('bypassPermissions')).toContain('高风险');
  });

  it('未知档返回空串(调用方据此不打印)', () => {
    expect(permissionModeNote('yolo-mode')).toBe('');
    expect(permissionModeNote('')).toBe('');
  });
});
