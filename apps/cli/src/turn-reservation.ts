/**
 * G-633(2026-09-29)回合起点预留号(turn reservation)。
 *
 * 要解决的真实问题:回合序号此前直接用 `runToolLoop` 内部的会话内迭代计数
 * (`iterations`,每条循环从 1 数起)。同进程里的并发回合 —— 多个 ACP 会话、
 * agent 与 subagent 并跑 —— 各自从 1 起数,落盘到账本快照/审计事实的 `turn`
 * 就会复用同一序号,恢复端无法按号归轮("两次并发回合都叫 t1")。
 *
 * 口径(先 reserve 再落盘):
 * - 回合**起点**先向本分配器原子预留一个号,再开流、再登记、再交快照;
 * - 号是进程级单调递增的,并发回合绝不复用同一 turnId(反证用例:
 *   两次并发 reserve 必得不同号,见 tests/turn-reservation.test.ts);
 * - 同一回合内换流(supersede / 上下文超限重读)沿用同一个预留号 ——
 *   预留的粒度是"回合",不是"流"。
 *
 * 原子性说明:Node 单线程事件循环内,**同步段**不会被其他任务插入,
 * "读-加-写"三步在同一次同步执行里完成即原子;本分配器没有任何 await,
 * 因此两次 reserve(哪怕隔着微任务并发调度)必得不同号。
 */

/** 进程级计数器:0 = 尚无任何回合预留(0 号永不发出) */
let lastReservedTurnNumber = 0;

/**
 * 为一个新回合原子预留序号。必须在回合起点、任何按回合落盘的动作
 * (登记账本 / 交快照 / 审计上报)之前调用 —— 先 reserve 再落盘。
 * 返回值单调递增且全进程唯一,永不复用。
 */
export function reserveTurnNumber(): number {
  lastReservedTurnNumber += 1;
  return lastReservedTurnNumber;
}

/** 最近一次预留出的号(诊断/观测用;0 = 尚无预留) */
export function peekLastReservedTurnNumber(): number {
  return lastReservedTurnNumber;
}

/**
 * 仅供测试复位计数器(生产代码禁止调用 —— 复位会制造号复用,
 * 恰是本模块要消灭的那件事)。
 */
export function __resetTurnReservationForTests(): void {
  lastReservedTurnNumber = 0;
}
