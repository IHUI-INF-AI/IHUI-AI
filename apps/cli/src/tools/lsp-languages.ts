/** 这门语言是否**真的可用**(任一候选在位且版本判据放行)。 */
export async function isLspServerAvailable(config: LspServerConfig): Promise<boolean> {
  return resolveLspCandidate(config).ok;
}

/** 列出当前机器上真的可用的语言(逐个候选探测,与 `lsp_server_status` 同源)。 */
export async function listAvailableLspServers(): Promise<LspServerConfig[]> {
  return LSP_SERVERS.filter((config) => resolveLspCandidate(config).ok);
}
