/**
 * 工具执行器接缝(W4-14)。
 *
 * `native` 是现有 `executeToolCall` 的薄封装;`ptc` 由 `ptc-tool.ts` 的只读绑定
 * 执行器实现,CLI 通过 `--tool-executor ptc` 显式选择。不选时仍走 native,
 * 不会静默替换。
 * 权限、超时、hook、审计仍全部由 `executeToolCall` 单点负责;换执行器只换
 * “调用怎么发起”,不换这些安全边界。
 */

import {
  executeToolCall,
  type ParsedToolCall,
  type ToolContext,
  type ToolResult,
} from './index.js';

export type ToolExecutorKind = 'native' | 'ptc';

export interface ToolExecutor {
  readonly kind: ToolExecutorKind;
  execute(call: ParsedToolCall, ctx: ToolContext): Promise<ToolResult>;
  /** 可选生命周期清理;保留式 runtime 用它终止 stateOwner 进程。 */
  dispose?(): Promise<void>;
}

export type NativeToolCallRunner = (
  call: ParsedToolCall,
  ctx: ToolContext,
) => Promise<ToolResult>;

/**
 * native 执行器。runner 可注入(测试/嵌入方替换底层),缺省就是 `executeToolCall`,
 * 从而保持既有权限闸、hook、审计、预算路径逐字不变。
 */
export function createNativeToolExecutor(runner: NativeToolCallRunner = executeToolCall): ToolExecutor {
  return {
    kind: 'native',
    execute: (call, ctx) => runner(call, ctx),
  };
}
