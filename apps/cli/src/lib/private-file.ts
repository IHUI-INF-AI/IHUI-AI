// 凭据类文件的唯一写入口。
//
// 为什么必须有这一格:`fs.writeFileSync(path, data, { mode: 0o600 })` 的 mode **只在
// 新建文件时生效**,对已存在的文件一个权限位都不改。本仓 CLI 的 settings.json 里住
// accessToken / refreshToken / apiKey,而绝大多数机器上这文件早就以默认 0644 落过盘
// —— 于是"给 writeFileSync 加 mode"这种修法对存量文件事实上无效(实测语义,不是推测)。
//
// 因此写凭据必须两步:写 + 显式 chmod 纠偏。凡是往 settings.json(或任何含凭据的文件)
// 落盘的地方一律走本函数,不得再抄第三份。
import * as fs from 'node:fs';

export function writePrivateFile(filePath: string, text: string): void {
  fs.writeFileSync(filePath, text, { encoding: 'utf-8', mode: 0o600 });
  try {
    // 已存在文件的权限位只有这一步能改
    fs.chmodSync(filePath, 0o600);
  } catch {
    // Windows 无 POSIX 权限语义:写入已完成,不因纠偏失败而让整个命令报错
  }
}
