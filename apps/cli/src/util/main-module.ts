/**
 * 主模块判定单一真相源(AGENTS §22d 判据形态)。
 *
 * 判定"本模块是否正被直接执行"(`node dist/tools/xxx.js` 形态):
 * argv[1] 解析成 URL 后与本模块 URL 全等。被测试 import 时必须为 false,
 * 保证 import 副作用不发网络请求、不抢 process.exit。
 *
 * 单文件打包(esbuild bundle / Node SEA)形态下,全模块 `import.meta.url`
 * 收敛到同一 exe 路径,次级入口脚本的自判定会**误触发**并在模块加载期
 * 抢跑 main()/process.exit(实测 tool-arg-report 由此截胡 ihui.exe --version)。
 * 故打包形态(构建注入 `IHUI_BUNDLED=1`)下恒为 false,入口判定权收敛到
 * 唯一入口 index.ts。
 */

import { pathToFileURL } from 'node:url'

export function isDirectRunMain(selfUrl: string): boolean {
  if (process.env.IHUI_BUNDLED === '1') return false
  if (typeof process.argv[1] !== 'string') return false
  return pathToFileURL(process.argv[1]).href === selfUrl
}
