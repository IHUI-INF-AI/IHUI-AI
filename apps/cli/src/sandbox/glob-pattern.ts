/**
 * 工作区相对路径的 glob 匹配原语(单一真相源)。
 *
 * 为什么要单拆一件:`checkFolderTrust`(sandbox/index.ts)此前把 glob→正则的四步替换
 * 内联在循环体里。新增"按操作分维的文件访问裁决"(file-access-policy.ts)需要同样的
 * 匹配语义 —— 两处各写一份必然漂移(AGENTS.md §0.6 本仓记过最多次的失败型),故把编译
 * 与匹配收在这一件,两侧一律 import,不再自抄。
 *
 * 语义(与 checkFolderTrust 历史行为逐字保持):
 * - `*` 匹配单层内的任意字符(不跨 `/`)
 * - `**` 匹配任意深度(含空)
 * - 其余正则元字符按字面量转义
 * 输入路径先归一为 POSIX 风格并去掉 `./` 前缀 —— 归一化也只此一处。
 */

/** 把 Windows 反斜杠与 `./` 前缀归一成 POSIX 相对路径(匹配两侧共用同一尺)。 */
export function normalizeWorkspacePath(filePath: string): string {
  return filePath.replace(/\\/g, '/').replace(/^\.\//, '');
}

/** 把一条 glob 模式编译成锚定正则源码(不含分隔符)。 */
export function compileGlobSource(pattern: string): string {
  return pattern
    .replace(/[.+^${}()|[\]\\]/g, '\\$&')
    .replace(/\*\*/g, '<<<GLOBSTAR>>>')
    .replace(/\*/g, '[^/]*')
    .replace(/<<<GLOBSTAR>>>/g, '.*');
}

/** 整路径逐字匹配一条 glob 模式(路径与模式都按现状,不做额外归一)。 */
export function globMatches(pattern: string, normalizedPath: string): boolean {
  return new RegExp(`^${compileGlobSource(pattern)}$`).test(normalizedPath);
}

/**
 * 模式的"含通配程度"计数(非通配字符越多 ⇒ 越大)。
 * `checkFolderTrust` 用它做 best-match 选择;访问裁决不看它(按声明序取首个命中),
 * 因此这里只提供计数,不提供优先级语义 —— 优先级属于各自的判据,不混进原语。
 */
export function globWildcardCount(pattern: string): number {
  return (pattern.match(/[*/]/g) ?? []).length;
}
