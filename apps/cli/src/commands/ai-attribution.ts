/**
 * `ihui ai-attribution` — AI 代码归属账读数(2026-11-05,goal-b49)。
 *
 * 用法:
 *   ihui ai-attribution stats [--path <p>] [--session <id>] [--json]
 *   ihui ai-attribution records [--path <p>] [--session <id>] [--limit <n>] [--json]
 *
 * 判据在哪:**不在这里**。归属判定(工具登记表 / ai·human·unknown 三态 / 回溯裁决)
 * 唯一一份住在服务端 `apps/ai-service/app/core/ai_code_attribution.py`;本命令只读
 * 服务端算好的结果,不在端内抄一份常量表、也不自己判归属(§0.6 单一真相源)。
 * 端内若再写一份归属工具登记表,就是第二份判据 ⇒ 必然漂移,故测试里有反向锁
 * (`apps/cli/tests/ai-attribution-cli.test.ts`:命令文件不得出现判据字面量)。
 *
 * 对标能力:Trae 的 `git-ai.git-ai-vscode` 扩展(v0.1.20,「Keep track of code
 * generated by AI」)——命令面 `showRepoHealth` / `showStatsOverview` / `toggleAICode`
 * 与 `showDaemonLog`。我方对位是「同一份归属账、两个读数口」:服务端按需落账,
 * 本命令读数;**不引入任何常驻进程**(对侧是 VSCode 扩展 + 常驻 daemon)。
 */

import type { Command } from 'commander';
import chalk from 'chalk';
import { loadSettings } from './settings.js';
import {
  createApiRequest,
  extractData,
  handleError,
  printJson,
  resolveApiKeyAsync,
  resolveBaseUrl,
} from './http-utils.js';

const API_PREFIX = '/api/ai-code-attribution';
const DEFAULT_TIMEOUT_MS = 30_000;

const apiRequest = createApiRequest(API_PREFIX, DEFAULT_TIMEOUT_MS);

type AttributionRequest = (
  baseUrl: string,
  path: string,
  options?: { method?: 'GET' | 'POST' | 'DELETE'; body?: unknown; timeoutMs?: number; apiKey?: string },
) => Promise<unknown>;

/** 提交成功后通知归属账。没登录或服务没起来都不影响提交本身。 */
export async function rememberCommittedFiles(sha: string, files: string[]): Promise<void> {
  if (process.env.VITEST) return;
  try {
    await postAttributionBackfill(sha, files);
  } catch {
    // 提交已经完成。回填失败留在下一轮,不改这次提交的结果。
  }
}

export async function postAttributionBackfill(
  sha: string,
  files: string[],
  request: AttributionRequest = apiRequest,
): Promise<{ updated: number; refused: string }> {
  const apiKey = loadSettings().apiKey;
  if (typeof apiKey !== 'string' || apiKey.length === 0) return { updated: 0, refused: '未登录' };
  const payload = await request(resolveBaseUrl(undefined), '/backfill', {
    method: 'POST',
    body: { commit_sha: sha, files },
    apiKey,
    timeoutMs: 2000,
  });
  const data = extractData(payload);
  if (!data || typeof data !== 'object') return { updated: 0, refused: '回填响应不是对象' };
  const row = data as { updated?: unknown; refused?: unknown };
  return {
    updated: typeof row.updated === 'number' ? row.updated : 0,
    refused: typeof row.refused === 'string' ? row.refused : '',
  };
}

/** 服务端 `/stats` 回送体(两个占比口径都给:含 unknown 的 ai_ratio + 只算已判出的 known_ratio)。 */
export interface AttributionStatsPayload {
  total: number;
  ai: number;
  human: number;
  unknown: number;
  ai_ratio: number;
  known_ratio: number;
}

/** 服务端 `/records` 回送的一条账行。 */
export interface AttributionRecordPayload {
  record_id: string;
  tool: string;
  file: string;
  attribution: string;
  reason: string;
  session_id: string;
  at: string;
  hunk_summary: string;
  anchor: {
    path: string;
    line_start: number;
    line_end: number;
    hunk_id: string;
    commit_sha: string;
  };
}

interface StatsOptions {
  path?: string;
  session?: string;
  json?: boolean;
}

interface RecordsOptions extends StatsOptions {
  limit?: string;
}

/**
 * 把统计折成人读的几行(纯函数:可单测,不触网)。
 *
 * 两个口径都给是有意的:`ai_ratio` 把 unknown 也算进分母(全账视角),
 * `known_ratio` 只在**归属已判出**的那部分里算(已判出视角)。
 * 只给一个就会让人把「没判出来」读成「不是 AI 写的」。
 */
export function formatStatsLines(stats: AttributionStatsPayload): string[] {
  return [
    `总记录 ${stats.total} 条:ai ${stats.ai} / human ${stats.human} / unknown ${stats.unknown}`,
    `AI 占比(含 unknown):${(stats.ai_ratio * 100).toFixed(1)}%`,
    `AI 占比(只算已判出):${(stats.known_ratio * 100).toFixed(1)}%`,
  ];
}

/** 把一条账行折成人读的一行(纯函数)。 */
export function formatRecordLine(record: AttributionRecordPayload): string {
  const anchor = record.anchor;
  const range =
    anchor.line_start > 0 ? `${anchor.path}:${anchor.line_start}-${anchor.line_end}` : anchor.path;
  const sha = anchor.commit_sha ? anchor.commit_sha.slice(0, 8) : '未提交(回溯不出)';
  return `[${record.attribution}] ${record.tool} ${range} · ${sha} · ${record.reason}`;
}

/** 把账行列表折成人读的多行(纯函数)。 */
export function formatRecordLines(records: AttributionRecordPayload[]): string[] {
  if (records.length === 0) return ['(归属账里没有匹配的记录)'];
  return records.map(formatRecordLine);
}

function buildQuery(opts: { path?: string; session?: string; limit?: string }): string {
  const params = new URLSearchParams();
  if (opts.path) params.set('path', opts.path);
  if (opts.session) params.set('session_id', opts.session);
  if (opts.limit) params.set('limit', opts.limit);
  const qs = params.toString();
  return qs ? `?${qs}` : '';
}

async function readStats(baseUrl: string, opts: StatsOptions, apiKey: string): Promise<void> {
  const resp = await apiRequest(baseUrl, `/stats${buildQuery(opts)}`, { apiKey });
  if (opts.json) {
    printJson(resp);
    return;
  }
  const stats = extractData(resp) as AttributionStatsPayload;
  console.info(chalk.bold('AI 代码归属统计'));
  for (const line of formatStatsLines(stats)) console.info(`  ${line}`);
}

async function readRecords(baseUrl: string, opts: RecordsOptions, apiKey: string): Promise<void> {
  const resp = await apiRequest(baseUrl, `/records${buildQuery(opts)}`, { apiKey });
  if (opts.json) {
    printJson(resp);
    return;
  }
  const data = extractData(resp) as { total?: number; records?: AttributionRecordPayload[] };
  const records = data?.records ?? [];
  console.info(chalk.bold(`AI 代码归属明细(${records.length} 条)`));
  for (const line of formatRecordLines(records)) console.info(`  ${line}`);
}

/** 在根 program 上注册 `ai-attribution` 命令组。 */
export function registerAiAttributionCommand(program: Command): void {
  const cmd = program
    .command('ai-attribution')
    .description('AI 代码归属账读数(AI 占比 / 明细;判据在服务端,此处只读)');

  cmd
    .command('stats')
    .description('AI 占比统计(可按路径或会话过滤)')
    .option('--path <path>', '按文件路径过滤')
    .option('--session <id>', '按会话 id 过滤')
    .option('--json', '以 JSON 格式输出')
    .action(async (opts: StatsOptions) => {
      try {
        const { apiUrl: cliApiUrl, apiKey: cliApiKey } = program.opts() as {
          apiUrl?: string;
          apiKey?: string;
        };
        const baseUrl = resolveBaseUrl(cliApiUrl);
        const apiKey = await resolveApiKeyAsync(cliApiKey, baseUrl);
        if (!apiKey) {
          console.error(chalk.red(`未登录:请先 ihui login(${baseUrl})`));
          process.exitCode = 1;
          return;
        }
        await readStats(baseUrl, opts, apiKey);
      } catch (err) {
        handleError('ai-attribution stats', err);
      }
    });

  cmd
    .command('records')
    .description('归属账明细(可按路径或会话过滤)')
    .option('--path <path>', '按文件路径过滤')
    .option('--session <id>', '按会话 id 过滤')
    .option('--limit <n>', '最多返回多少条')
    .option('--json', '以 JSON 格式输出')
    .action(async (opts: RecordsOptions) => {
      try {
        const { apiUrl: cliApiUrl, apiKey: cliApiKey } = program.opts() as {
          apiUrl?: string;
          apiKey?: string;
        };
        const baseUrl = resolveBaseUrl(cliApiUrl);
        const apiKey = await resolveApiKeyAsync(cliApiKey, baseUrl);
        if (!apiKey) {
          console.error(chalk.red(`未登录:请先 ihui login(${baseUrl})`));
          process.exitCode = 1;
          return;
        }
        await readRecords(baseUrl, opts, apiKey);
      } catch (err) {
        handleError('ai-attribution records', err);
      }
    });
}
