// D79 等待态文案池 — cli 端接线层(取词 + 象限/阶段推导)。
// 平台特有:纯文案派生,不依赖终端 API,但单独成模块是为了让渲染位可被用例钉住
// (repl.ts 2400+ 行、顶层有副作用,无法在测试里直接 import 验证 spinner 文案)。
import { resolveWaitingText, type WaitingPhase } from '@ihui/shared/chat';

import { getLocale } from '../i18n/index.js';

/** 渲染位传入的推导原料(全部为 repl 既有状态,不新增采集成本) */
export interface WaitingSpinnerTextInput {
  /** 当前模型 id,保留在文案前缀(既有视觉约定) */
  modelId: string;
  /** 本轮用户输入 — 作为确定性 seed(同输入必同文案,禁用 Math.random) */
  prompt: string;
  /** 会话历史条数,0=首轮,>0=追问 */
  historyLength: number;
  /**
   * 上一轮的用户输入(repl 既有 history 派生,非新增状态源)。
   * 传了就走共享池 avoidSeed 分支:本轮若与上一轮撞同一条则顺移一位;
   * 不传(undefined)时共享池走"未引入 avoidSeed"路径,输出与接线前逐字节一致。
   */
  previousPrompt?: string;
}

/**
 * 构造"首 token 等待 spinner"文案:`<modelId> · <等待池文案>`。
 * 象限定为 agent(等待的是模型回复本身);阶段按历史长度分首轮/追问。
 */
export function buildWaitingSpinnerText(input: WaitingSpinnerTextInput): string {
  const phase: WaitingPhase = input.historyLength === 0 ? 'first' : 'followup';
  const text = resolveWaitingText({
    quadrant: 'agent',
    phase,
    locale: getLocale(),
    seed: input.prompt,
    avoidSeed: input.previousPrompt,
  });
  return `${input.modelId} · ${text}`;
}
