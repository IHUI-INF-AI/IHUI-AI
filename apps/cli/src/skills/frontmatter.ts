/**
 * Skills frontmatter codec — 固定键序序列化(幂等写) + 围栏解析(bodyLineOffset + 容错)。
 *
 * 上游出处:`apps/zcode-cli/packages/core/src/tool/handlers/saved-workflows/frontmatter.ts`
 * (票 G-937961)。载体同构不同形:上游 saved workflow 用「zcode-workflow」块注释包 YAML
 * (使 .dwf.ts 仍是合法 TS);我方 skills 是 `.md` 的 `---` YAML 围栏。三条机制逐条对应:
 *   1) **固定键序 ⇒ 幂等写**:serialize 按固定键序展开,与对象字面量的插入序无关 ——
 *      同一份元数据两次写出逐字节相同;否则每次 pull 落盘都在 git 里造一个无意义 diff。
 *   2) **bodyLineOffset**:parse 返回正文之前有多少行,诊断按**文件行**报出来时加它:
 *      `fileLine = bodyLine + bodyLineOffset`(1 起数)。让每个调用点自己数一遍,
 *      是「诊断行号对不上文件」这种 bug 的标准产地(上游原注)。
 *   3) **unterminated 容错**:首行有 `---` 却没有闭合行(典型是手删了一行)给具名 reason
 *      `unterminated_frontmatter`,不再静默冒充"没有 frontmatter"。
 *
 * 本层只管**围栏结构**,失败面只有两个名字(missing / unterminated):字段级容错
 * (缩进错、键不认识、值解析不出)由 `parseFrontmatter`(index.ts)逐行跳过兜住 ——
 * 两层失败面分开,各自的名字才帮得上忙(上游原注:一个笼统的 "parse error" 谁都帮不上)。
 */

import type { SkillFrontmatter } from '@ihui/types';

/** 围栏标记。开启必须落在文件首行;闭合是一行只有 `---`(容忍首尾空白)。 */
export const SKILL_FRONTMATTER_DELIMITER = '---';

export type SkillsFrontmatterParseReason = 'missing_frontmatter' | 'unterminated_frontmatter';

export type SkillsFrontmatterParseResult =
  | {
      ok: true;
      /** 围栏内的原始文本(不含两侧 `---` 行;两行式空块为空串) */
      front: string;
      /** 闭合行之后的原始正文(未 trim;trim 由调用方按语义决定) */
      body: string;
      /**
       * 正文之前有多少行(开启行 + 围栏内文本 + 闭合行)。
       * 诊断按文件行报时:`fileLine = bodyLine + bodyLineOffset`(bodyLine 1 起数)。
       */
      bodyLineOffset: number;
    }
  | { ok: false; reason: SkillsFrontmatterParseReason; detail: string };

/**
 * 元数据 → frontmatter 文本(不含 `---` 围栏)。键序固定:
 * name → description → allowed-tools → tools → model → tags → version → license →
 * source → related-skills → progressive-disclosure → auto-generated-at →
 * auto-generated-from-task → prerequisites,与对象插入序无关 ⇒ 同一份元数据两次
 * 序列化逐字节相同(幂等写,tests/g937961 有钉)。
 * 不引入 yaml 库:数组用 inline [a, b, c],对象用嵌套块,布尔用 true/false,字符串用原值。
 */
export function serializeSkillsFrontmatter(fm: SkillFrontmatter): string {
  const lines: string[] = [];
  const push = (key: string, value: string): void => {
    lines.push(`${key}: ${value}`);
  };

  if (fm.name) push('name', fm.name);
  if (fm.description) push('description', fm.description);
  if (fm.allowedTools && fm.allowedTools.length > 0) {
    push('allowed-tools', `[${fm.allowedTools.join(', ')}]`);
  }
  if (fm.tools && fm.tools.length > 0) {
    push('tools', `[${fm.tools.join(', ')}]`);
  }
  if (fm.model) push('model', fm.model);
  if (fm.tags && fm.tags.length > 0) {
    push('tags', `[${fm.tags.join(', ')}]`);
  }
  if (fm.version) push('version', fm.version);
  if (fm.license) push('license', fm.license);
  if (fm.source) push('source', fm.source);
  if (fm.relatedSkills && fm.relatedSkills.length > 0) {
    push('related-skills', `[${fm.relatedSkills.join(', ')}]`);
  }
  if (fm.progressiveDisclosure !== undefined) {
    push('progressive-disclosure', fm.progressiveDisclosure ? 'true' : 'false');
  }
  if (fm.autoGeneratedAt) push('auto-generated-at', fm.autoGeneratedAt);
  if (fm.autoGeneratedFromTask) push('auto-generated-from-task', fm.autoGeneratedFromTask);
  if (fm.prerequisites) {
    const { commands, env } = fm.prerequisites;
    const hasCommands = commands && commands.length > 0;
    const hasEnv = env && env.length > 0;
    if (hasCommands || hasEnv) {
      lines.push('prerequisites:');
      if (hasCommands) lines.push(`  commands: [${commands!.join(', ')}]`);
      if (hasEnv) lines.push(`  env: [${env!.join(', ')}]`);
    }
  }
  return lines.join('\n');
}

/**
 * skill 文件内容 → 围栏结构。逐行扫描,CR-LF 与 CR 行尾都认;闭合行容忍首尾空白。
 * 三种结局各有名字:missing 是"这不是一份带 frontmatter 的 skill",unterminated 是
 * "你删掉了闭合行"。
 */
export function parseSkillsFrontmatter(content: string): SkillsFrontmatterParseResult {
  const lines = content.split(/\r?\n/);
  if ((lines[0] ?? '').trim() !== SKILL_FRONTMATTER_DELIMITER) {
    return {
      ok: false,
      reason: 'missing_frontmatter',
      detail: 'file does not start with a `---` frontmatter fence',
    };
  }
  for (let i = 1; i < lines.length; i += 1) {
    if (lines[i]!.trim() === SKILL_FRONTMATTER_DELIMITER) {
      return {
        ok: true,
        front: lines.slice(1, i).join('\n'),
        body: lines.slice(i + 1).join('\n'),
        bodyLineOffset: i + 1,
      };
    }
  }
  return {
    ok: false,
    reason: 'unterminated_frontmatter',
    detail: 'frontmatter fence is never closed with a `---` line',
  };
}
