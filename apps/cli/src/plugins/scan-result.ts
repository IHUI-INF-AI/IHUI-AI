/**
 * 装载结果的形状 —— `ScanResult`(2026-11-13 自 `loader.ts` 拆出)。
 *
 * 为什么单独一档而不是留在 `loader.ts`:扫描引擎(`plugin-scan.ts`)与公开出口(`loader.ts`)
 * 两边都要这个类型,任一边持有都会让另一边 import 出循环。类型的**唯一定义**住这里,
 * 两边只做 `import type` —— 不是第二份契约(§0.6)。
 */

import type { PluginLoadResult } from './types.js';
import type { PluginContributionAudit } from './contribution-audit.js';
import type { PluginActivationAudit } from './activation-events.js';
import type { CompiledInterfaceTool, InterfaceCompileOutcome } from './interface-tools.js';

/**
 * 内部扫描结果 = 装载结果 + 贡献裁决 + 激活事件裁决 + 接口型工具。
 * (`PluginLoadResult` 是 types.ts 的既有契约,**不扩字段** —— 老调用方的解构零改动。)
 */
export interface ScanResult extends PluginLoadResult {
  contributions: PluginContributionAudit;
  /** goal-b49/W6:激活事件的三态裁决(装载/延迟/拒绝),判据单源见 `activation-events.ts` */
  activations: PluginActivationAudit;
  /**
   * 插件贡献的**接口型工具**(2026-11-13 立):已编译成可直接 `registerTools()` 的 `Tool`。
   *
   * 为什么由装载器回而不是让调用方再解析一次清单:`interfaces[]` 的校验/拒收判据单源在
   * `interface-tools.ts`,重解析 = 第二份判据(§0.6)。调用方只管"接不接受这批工具",
   * 不需要知道声明长什么样。
   */
  interfaceTools: CompiledInterfaceTool[];
  /** 接口声明的逐条裁决(accept/拒收 + 判别码),供调用方按码汇总或自测读取 */
  interfaceOutcomes: InterfaceCompileOutcome[];
}
