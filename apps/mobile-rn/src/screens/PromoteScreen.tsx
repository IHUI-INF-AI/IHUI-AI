import { useCallback, useEffect, useRef, useState } from 'react'
import { useTheme } from '../context/ThemeContext'
import { appAlert } from '../components/BottomPops'
import { useNavigation } from '@react-navigation/native'
import type { NativeStackNavigationProp } from '@react-navigation/native-stack'
import { fetchApi } from '@ihui/api-client'
import {
  PromoteScreen as SharedPromoteScreen,
  type PromoteInfo,
  type PromoteInviteRecord,
} from '@ihui/rn-app'
import { useI18n } from '../i18n'
import type { RootStackParamList } from '../navigation/RootNavigator'

type NavigationProp = NativeStackNavigationProp<RootStackParamList>

interface OverviewData {
  inviteCode: string | null
  invitedCount: number
  activeCount: number
  totalCommission: number
  pendingCommission: number
}

interface TeamMembersData {
  list: Array<{
    id: string
    nickname: string | null
    joinDate: string
    commission: number
    status: 'active'
  }>
}

// 后端佣金金额出口为分(commission_flows.amount),共享屏按 ¥+原值渲染,折算只在此处做一次
const centsToYuan = (cents: number) => cents / 100

export function PromoteScreen() {
  const { resolvedTheme } = useTheme()
  const { t } = useI18n()
  const navigation = useNavigation<NavigationProp>()
  const [info, setInfo] = useState<PromoteInfo | null>(null)
  const [records, setRecords] = useState<PromoteInviteRecord[]>([])
  const [loading, setLoading] = useState(true)
  const [refreshing, setRefreshing] = useState(false)
  const [error, setError] = useState('')
  const [copied, setCopied] = useState(false)
  const copiedTimerRef = useRef<ReturnType<typeof setTimeout> | null>(null)

  const load = useCallback(
    async (refresh = false) => {
      if (refresh) setRefreshing(true)
      else setLoading(true)
      setError('')
      const [overviewRes, membersRes] = await Promise.all([
        fetchApi<OverviewData>('/api/distribution/overview'),
        fetchApi<TeamMembersData>('/api/distribution/team/members', {
          params: { page: 1, pageSize: 10 },
        }),
      ])
      if (!overviewRes.success || !membersRes.success) {
        setError(t('promote.loadFailed'))
        setLoading(false)
        setRefreshing(false)
        return
      }
      const ov = overviewRes.data
      if (ov) {
        setInfo({
          referralCode: ov.inviteCode ?? '',
          referralLink: '',
          inviteCount: ov.invitedCount,
          activeCount: ov.activeCount,
          totalEarnings: centsToYuan(ov.totalCommission),
          pendingEarnings: centsToYuan(ov.pendingCommission),
          rules: [],
        })
      }
      setRecords(
        (membersRes.data?.list ?? []).map((m) => ({
          id: m.id,
          nickname: m.nickname ?? '',
          joinDate: m.joinDate,
          contribution: centsToYuan(m.commission),
          status: m.status,
        })),
      )
      setLoading(false)
      setRefreshing(false)
    },
    [t],
  )

  useEffect(() => {
    void load()
  }, [load])

  useEffect(() => {
    return () => {
      if (copiedTimerRef.current) {
        clearTimeout(copiedTimerRef.current)
      }
    }
  }, [])

  const handleCopy = async () => {
    if (!info) return
    appAlert(t('promote.copyLink'), info.referralLink)
    setCopied(true)
    if (copiedTimerRef.current) {
      clearTimeout(copiedTimerRef.current)
    }
    copiedTimerRef.current = setTimeout(() => {
      setCopied(false)
      copiedTimerRef.current = null
    }, 1500)
  }

  const handleShare = () => {
    appAlert(t('promote.shareBtn'), info?.referralLink ?? '')
  }

  return (
    <SharedPromoteScreen
      t={t}
      info={info}
      records={records}
      loading={loading}
      refreshing={refreshing}
      error={error}
      copied={copied}
      onRefresh={() => void load(true)}
      onCopy={handleCopy}
      onShare={handleShare}
      onBack={() => navigation.goBack()}
      colorScheme={resolvedTheme}
    />
  )
}
