import { useState } from 'react'
import { useTheme } from '../context/ThemeContext'
import { useNavigation } from '@react-navigation/native'
import type { NativeStackNavigationProp } from '@react-navigation/native-stack'
import { fetchApi } from '@ihui/api-client'
import { CourseQAAskScreen as SharedCourseQAAskScreen } from '@ihui/rn-app'
import { useI18n } from '../i18n'
import type { RootStackParamList } from '../navigation/RootNavigator'

type Nav = NativeStackNavigationProp<RootStackParamList>

export function CourseQAAskScreen() {
  const { resolvedTheme } = useTheme()
  const { t } = useI18n()
  const navigation = useNavigation<Nav>()
  const [question, setQuestion] = useState('')
  const [submitting, setSubmitting] = useState(false)
  const [error, setError] = useState('')
  const [success, setSuccess] = useState(false)

  const submit = async () => {
    const text = question.trim()
    if (!text) {
      setError(t('courseQAAsk.placeholder'))
      return
    }
    setSubmitting(true)
    setError('')
    setSuccess(false)
    try {
      // 后端 createQASchema:title 必填且 ≤200、content 可选 ⇒ 前 200 字作标题、全文进 content,输入不丢
      const res = await fetchApi('/api/edu/qa', {
        method: 'POST',
        body: JSON.stringify({ title: text.slice(0, 200), content: text }),
      })
      if (!res.success) throw new Error()
      setSuccess(true)
      setQuestion('')
    } catch {
      setError(t('courseQAAsk.submitting'))
    } finally {
      setSubmitting(false)
    }
  }

  return (
    <SharedCourseQAAskScreen
      t={t}
      question={question}
      submitting={submitting}
      error={error}
      success={success}
      onQuestionChange={setQuestion}
      onSubmit={submit}
      onBack={() => navigation.goBack()}
      colorScheme={resolvedTheme}
    />
  )
}
