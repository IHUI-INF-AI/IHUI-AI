/**
 * mobile-rn 搜索历史 hook —— 与 web 端 apps/web/src/hooks/use-search-history.ts 同构:
 * 同一 key('searchHistory')、同一上限(10 条、去重最新在前),共享层工厂单点实现。
 * 差异仅在 transport:web 用 localStorage,本端用 AsyncStorage。
 */
import { createHistoryStorage } from '@ihui/shared/utils/storage'
import { createUseHistoryStorage } from '@ihui/shared/hooks/use-storage'
import type { UseSearchHistoryResult } from '@ihui/types'
import { createAsyncStorageTransport } from '../stores/storage-adapter'

const SEARCH_HISTORY_KEY = 'searchHistory'
const MAX_ITEMS = 10

// 模块级构造 transport + storage + hook 工厂(避免每次渲染重建)
const transport = createAsyncStorageTransport()
const searchHistoryStorage = createHistoryStorage<string>({
  transport,
  key: SEARCH_HISTORY_KEY,
  maxItems: MAX_ITEMS,
})
const useSearchHistoryStorage = createUseHistoryStorage<string>({ storage: searchHistoryStorage })

export function useSearchHistory(): UseSearchHistoryResult {
  const { list, push, clear } = useSearchHistoryStorage()
  return {
    history: list,
    // trim 后空串/纯空白跳过,fire-and-forget(与 web 端语义一致)
    addHistory: (item: string) => {
      const trimmed = item.trim()
      if (!trimmed) return
      void push(trimmed)
    },
    clearHistory: () => {
      void clear()
    },
  }
}
