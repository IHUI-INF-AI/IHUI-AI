// #11 引用溯源跨端(第 51 轮):mobile-rn 此前对 citations 帧 0 命中。
// 锁住累积层两条性质:两批追加不互相覆盖、(source,label) 去重、无 url 时不造空字段。
import { describe, expect, it } from 'vitest'

import { appendCitationFrames, type MessageCitation } from '../src/utils/chat-render-model'

const a: MessageCitation = { source: 'codebase', label: 'AGENTS.md §3', url: 'docs/AGENTS.md' }

describe('appendCitationFrames(#11 承接)', () => {
  it('undefined 起点 → 单条,带 url', () => {
    expect(appendCitationFrames(undefined, [a])).toEqual([a])
  })

  it('两批追加不覆盖', () => {
    const once = appendCitationFrames(undefined, [a])
    const twice = appendCitationFrames(once, [{ source: 'rag', label: '历史会话片段' }])
    expect(twice.map((x) => x.label)).toEqual(['AGENTS.md §3', '历史会话片段'])
  })

  it('同 (source,label) 重复帧不产生第二行', () => {
    const once = appendCitationFrames(undefined, [a])
    expect(appendCitationFrames(once, [{ ...a, url: 'other.md' }])).toHaveLength(1)
  })

  it('后端未给 url 时不写空字段(界面据此不给假链接)', () => {
    const out = appendCitationFrames(undefined, [{ source: 'graph', label: '实体 A—B' }])
    expect('url' in (out[0] ?? {})).toBe(false)
  })
})
