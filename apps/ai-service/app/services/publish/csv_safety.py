"""电子表格公式注入中和 —— ai-service 面的唯一出口(G-815997,2026-09-29 立)。

为什么存在:Python ``csv.writer`` 只做引号/分隔符转义,不做公式中和 —— 用户可控文本
(如 ``display_name``)以 ``=`` ``+`` ``-`` ``@`` 开头时,导出 CSV 被 Excel 当公式执行
(DDE 载荷面)。JS 侧同族出口:``apps/web/src/lib/export-utils.ts`` 的
``neutralizeFormulaCell``(带前导空白/制表符面)与 ``apps/api/src/utils/csv-utils.ts``
的 ``sanitizeCsvCell``。本面是 Python 镜像,语义与 **api 版**逐字同型:
首字符 ∈ {=,+,-,@} 即前缀 ``'``;``'`` 本身不是触发字符,天然幂等。

纪律:本面所有 CSV 生成一律经本函数,不得再写第二份转义实现(AGENTS §3 同族)。
"""

_TRIGGER_CHARS = ("=", "+", "-", "@")


def sanitize_csv_cell(value: object) -> str:
    """单元格文本过公式中和:危险首字符前缀单引号,其余逐字不变;数字原样转字符串。"""
    if isinstance(value, bool):
        text = str(value)
    elif isinstance(value, (int, float)):
        # 数字是机器生成的正当用法,不因负号前缀被中和(G-823 同款语义)
        return str(value)
    elif value is None:
        return ""
    else:
        text = str(value)
    if text.startswith(_TRIGGER_CHARS):
        return f"'{text}"
    return text
