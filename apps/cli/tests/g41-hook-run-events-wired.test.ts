/**
 * G-41 生产接线形状锁(2026-10-24 立):实现层事件流(d4f8ba336b)的生产消费者
 * 必须留在 runAgent —— 订阅被静默摘掉时事件面退回"发了没人听",§30 的生产侧
 * 终态出口名存实亡。本锁只判源码形状(import + 订阅 + finally 退订三处在位),
 * 不跑 runAgent(拉起完整 agent 不是本锁的射程)。
 */
import { describe, expect, it } from 'vitest';
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const agentSrc = readFileSync(
  fileURLToPath(new URL('../src/commands/agent.ts', import.meta.url)),
  'utf8',
);

describe('G-41 钩子事件流生产接线形状锁', () => {
  it('runAgent 订阅 onHookRunEvent(import 与调用双在位)', () => {
    expect(agentSrc).toMatch(/import\s*\{[^}]*onHookRunEvent[^}]*\}\s*from\s*'..\/hooks\/index\.js'/);
    expect(agentSrc).toContain('onHookRunEvent((evt)');
  });

  it('json 模式静默(事件出口不得向 JSON 流混入非 JSON 行)', () => {
    expect(agentSrc).toContain("opts.jsonMode === true) return");
  });

  it('finally 退订在 runSessionEndHooks 之后(会话末批钩子终态也出口)', () => {
    const finallyIdx = agentSrc.indexOf('unsubscribeHookRunEvents()');
    const endHooksIdx = agentSrc.indexOf('await runSessionEndHooks(hooksConfig, sessionHookCtx, opts.signal)');
    expect(finallyIdx).toBeGreaterThan(endHooksIdx);
  });
});
