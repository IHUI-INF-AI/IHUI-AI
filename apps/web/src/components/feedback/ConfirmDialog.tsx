'use client'

import * as React from 'react'
import { AlertTriangle } from 'lucide-react'
import { cn } from '@/lib/utils'
import { Modal } from './Modal'

interface ConfirmDialogProps {
  open: boolean
  title?: string
  content?: React.ReactNode
  confirmText?: string
  cancelText?: string
  variant?: 'default' | 'danger'
  onConfirm: () => void
  onCancel: () => void
  loading?: boolean
  /** loading 时确认钮文案(D186 归档在途等本地化在途文案;默认保留旧兜底"处理中...") */
  loadingText?: string
}

export function ConfirmDialog({
  open,
  title = '确认操作',
  content,
  confirmText = '确认',
  cancelText = '取消',
  variant = 'default',
  onConfirm,
  onCancel,
  loading = false,
  loadingText = '处理中...',
}: ConfirmDialogProps) {
  return (
    <Modal
      open={open}
      onClose={onCancel}
      title={
        <div className="flex items-center gap-2">
          {variant === 'danger' && <AlertTriangle className="h-5 w-5 text-destructive" />}
          {title}
        </div>
      }
      size="sm"
      footer={
        <>
          <button
            onClick={onCancel}
            data-testid="confirm-cancel-button"
            className="h-7 rounded-xl border border-border bg-foreground/5 px-3 text-xs font-medium text-muted-foreground transition-colors hover:bg-foreground/10 hover:text-foreground"
          >
            {cancelText}
          </button>
          <button
            onClick={onConfirm}
            disabled={loading}
            data-testid="confirm-button"
            className={cn(
              'h-7 rounded-xl px-3 text-xs font-medium text-primary-foreground hover:opacity-90 disabled:opacity-50',
              variant === 'danger' ? 'bg-destructive' : 'bg-primary',
            )}
          >
            {loading ? loadingText : confirmText}
          </button>
        </>
      }
    >
      {content}
    </Modal>
  )
}
