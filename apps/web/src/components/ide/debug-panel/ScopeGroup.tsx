'use client'
// 2026-09-10 0-6 组件拆分:scope 分组从 debug-panel.tsx 抽出(自订阅 debug store)
import * as React from 'react'
import { useDebugStore } from '@/stores/debug'
import { ChevronRight, ChevronDown } from 'lucide-react'
import type { DebugScope } from '@/lib/api/debug'
import { VariableRow } from './VariableRow'

/** scope 分组(Locals/Globals 等):可折叠,expensive 组首次展开才拉取 */
export function ScopeGroup({ scope }: { scope: DebugScope }) {
  const sessionId = useDebugStore((s) => s.sessionId)
  const expanded = useDebugStore((s) => !!s.scopeExpanded[scope.name])
  const variables = useDebugStore((s) => s.variablesByRef[scope.variablesReference])
  const toggleScope = useDebugStore((s) => s.toggleScope)
  return (
    <div data-testid={`debug-scope-${scope.name}`}>
      <button
        onClick={() => sessionId && toggleScope(sessionId, scope)}
        className="flex w-full items-center gap-1 px-2 py-0.5 text-left text-xs font-medium text-muted-foreground hover:bg-muted/30"
      >
        {expanded ? <ChevronDown className="h-3 w-3" /> : <ChevronRight className="h-3 w-3" />}
        <span>{scope.name}</span>
      </button>
      {expanded &&
        ((variables ?? []).length > 0 ? (
          (variables ?? []).map((v) => <VariableRow key={v.name} v={v} />)
        ) : (
          <div className="px-3 py-1 text-xs text-muted-foreground">—</div>
        ))}
    </div>
  )
}
