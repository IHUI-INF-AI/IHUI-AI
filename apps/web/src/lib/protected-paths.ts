/**
 * 受登录守卫保护的路径 —— 唯一真相源。
 *
 * 两个调用方问的是同一件事,各写一份必然漂移,而漂移的表现是安静的那一侧:
 * - `proxy.ts`:命中即验 cookie,不通过 307 到 /sso/login;
 * - `/sso/login`:只有 redirect 落在这一集合内才自动续种 cookie 并回跳
 *   (用户主动访问授权页、或子项目带外站 redirect 进来时不自动送走)。
 *
 * Edge Runtime 安全:`proxy.ts` 会 import 本文件,故只允许纯常量与纯函数,
 * 不得引入 node: 内建或浏览器 API。
 */
const PROTECTED_PATHS = ['/admin', '/edu/edu-management'] as const

/** 逐字沿用 proxy.ts 的命中口径:`/admin` 与 `/admin/...` 都算,`/administrator` 不算。 */
export function isProtectedPath(pathname: string): boolean {
  return PROTECTED_PATHS.some((p) => pathname === p || pathname.startsWith(`${p}/`))
}

/**
 * 从回跳目标里取出「受保护且同源相对」的路径,不是则返回空串。
 *
 * 只认单斜杠开头的相对路径:`//evil.com`、`/\evil.com`、`javascript:` 与自定义深链
 * 一律不进入自动回跳(协议闸仍由 sso-redirect-guard 的 resolveSafeRedirectTarget 兜底)。
 */
export function protectedPathOf(target: string): string {
  if (!target.startsWith('/') || target.startsWith('//') || target.startsWith('/\\')) return ''
  const pathname = target.split(/[?#]/, 1)[0] ?? ''
  return isProtectedPath(pathname) ? pathname : ''
}
