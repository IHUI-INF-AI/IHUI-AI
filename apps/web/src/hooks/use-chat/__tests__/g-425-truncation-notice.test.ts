import { describe, expect, it } from 'vitest'

import { isMaxTokensTruncatedFinishReason } from '../stream-handlers'

/** G-425(2026-10-07 立,默认档"只提示"):done 帧 finishReason 的截断判定。
 *  口径权威:packages/shared/src/sse/contract.ts 的 done 帧 finishReason 字段注释
 *  —— 小写归一后 ∈ {length, max_tokens};缺席/非串/其余 reason 一律 false
 *  (缺席 = 上游没给,绝不折成"正常结束")。渲染形态:sendMessage/sendAnswer 两处
 *  streamChat 的 onFinishReason → toast.warning(t('truncation.maxLengthNotice'))。 */
describe('G-425 截断判定助手 isMaxTokensTruncatedFinishReason', () => {
  it('阳性:OpenAI 系 length 与 Gemini 系 MAX_TOKENS(含大小写混写)均判截断', () => {
    expect(isMaxTokensTruncatedFinishReason('length')).toBe(true)
    expect(isMaxTokensTruncatedFinishReason('LENGTH')).toBe(true)
    expect(isMaxTokensTruncatedFinishReason('MAX_TOKENS')).toBe(true)
    expect(isMaxTokensTruncatedFinishReason('max_tokens')).toBe(true)
    expect(isMaxTokensTruncatedFinishReason('Max_Tokens')).toBe(true)
  })

  it('阴性:正常结束与工具/安全类 reason 不提示', () => {
    expect(isMaxTokensTruncatedFinishReason('stop')).toBe(false)
    expect(isMaxTokensTruncatedFinishReason('STOP')).toBe(false)
    expect(isMaxTokensTruncatedFinishReason('tool_calls')).toBe(false)
    expect(isMaxTokensTruncatedFinishReason('SAFETY')).toBe(false)
    expect(isMaxTokensTruncatedFinishReason('RECITATION')).toBe(false)
  })

  it('阴性:缺席/空串/非串一律 false(缺席 = 上游没给,不冒充任何结论)', () => {
    expect(isMaxTokensTruncatedFinishReason(undefined)).toBe(false)
    expect(isMaxTokensTruncatedFinishReason(null)).toBe(false)
    expect(isMaxTokensTruncatedFinishReason('')).toBe(false)
  })
})
