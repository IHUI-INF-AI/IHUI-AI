import { useTranslations } from 'next-intl'

const STATUS_STYLE: Record<string, string> = {
  accepted: 'bg-muted text-muted-foreground',
  running: 'bg-blue-100 text-blue-700 dark:bg-blue-900/40 dark:text-blue-300',
  success: 'bg-green-100 text-green-700 dark:bg-green-900/40 dark:text-green-300',
  failed: 'bg-red-100 text-red-700 dark:bg-red-900/40 dark:text-red-300',
}

/**
 * 状态 id(accepted/running/success/failed)是与后端比对的协议字面值,原样保留;
 * 此处只存 aiGeneration 命名空间下的文案键,取词在渲染处完成。
 */
const STATUS_LABEL_KEY: Record<string, string> = {
  accepted: 'statusAccepted',
  running: 'statusGenerating',
  success: 'statusSucceeded',
  failed: 'statusFailed',
}

/** 未知状态返回 undefined,由渲染处回退展示协议字面值本身(不得把未知 id 当键去取词) */
export function getVideoTaskStatusLabelKey(status: string): string | undefined {
  return STATUS_LABEL_KEY[status]
}

export function VideoTaskStatusBadge({ status }: { status: string }) {
  const t = useTranslations('aiGeneration')
  const labelKey = getVideoTaskStatusLabelKey(status)
  return (
    <span
      className={`inline-flex items-center rounded-md px-2 py-0.5 text-xs font-medium ${STATUS_STYLE[status] ?? STATUS_STYLE.accepted}`}
    >
      {labelKey ? t(labelKey) : status}
    </span>
  )
}
