/** 与后端 fim.py 保持一致:scene 缺省(含旧 Redis 快照无该键)按 completion 处理 */
export const DEFAULT_FIM_SCENE = 'completion'

/** 看板展示用场景名:缺省 completion 也显式显示,避免同模型多场景读数混淆 */
export const fimScene = (scene: string | null | undefined): string => scene || DEFAULT_FIM_SCENE

/** model × scene 行唯一键:同一模型多个场景不再撞 key */
export const fimRowKey = (model: string, scene: string | null | undefined): string =>
  `${model}-${fimScene(scene)}`
