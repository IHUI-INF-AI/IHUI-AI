'use client'

import * as React from 'react'
import { useRouter } from 'next/navigation'
import { useTranslations } from 'next-intl'
import { Loader2 } from 'lucide-react'
import { AgentManager, type AgentItem } from '@/components/ai/agent-manager'
import { AgentPill } from '@/components/ai/agent-pill'
import { useAgent } from '@/hooks/use-agent'

/**
 * 「我的 Agent」页签:取数走 `useAgent()` → GET /agents/my(后端按当前登录用户过滤)。
 * 此前该 hook 请求的是 /agents/list(市场列表、无 userId)且只取默认 20 条,
 * 于是"我的"页签显示的是市场前 20 枚、与登录者无关 —— 空态按"没有自己的智能体"如实呈现。
 * 游客点击本页签时由 `fetchApi` 的既有 401 语义弹登录弹窗(lib/api.ts:208),不伪造内容。
 */
export function MyAgentsTab() {
  const router = useRouter()
  const t = useTranslations('agent')
  const { agents, loading, fetchAgents } = useAgent()
  const [selectedId, setSelectedId] = React.useState<string | undefined>()

  React.useEffect(() => {
    void fetchAgents()
  }, [fetchAgents])

  const items: AgentItem[] = agents.map((a) => ({
    id: a.id,
    name: a.name,
    role: a.description || '—',
    status: 'idle',
    model: a.model,
  }))

  if (loading && items.length === 0) {
    return (
      <div className="flex items-center justify-center py-12 text-muted-foreground">
        <Loader2 className="mr-2 h-5 w-5 animate-spin" />
        {t('loading')}
      </div>
    )
  }

  if (items.length === 0) {
    return <div className="py-12 text-center text-sm text-muted-foreground">{t('empty')}</div>
  }

  return (
    <div className="mx-auto max-w-md space-y-4">
      <div className="flex flex-wrap gap-2">
        {items.slice(0, 8).map((a) => (
          <AgentPill
            key={a.id}
            name={a.name}
            status={a.status}
            active={a.id === selectedId}
            onClick={() => {
              setSelectedId(a.id)
              router.push(`/agents/${a.id}`)
            }}
          />
        ))}
      </div>
      <AgentManager
        agents={items}
        selectedId={selectedId}
        onCreate={() => router.push('/agents/create')}
        onSelect={(id) => {
          setSelectedId(id)
          router.push(`/agents/${id}`)
        }}
      />
    </div>
  )
}
