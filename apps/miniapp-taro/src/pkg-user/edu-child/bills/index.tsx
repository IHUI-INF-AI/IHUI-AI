import { useI18n } from '@/i18n'
import ThemeRoot from '@/components/ThemeRoot'
import { get } from '@/api'
import { ChildRecordsView, childIdOf, type ChildRecordRow } from '../records-page'

interface Row {
  enrollmentId: string
  className: string
  termName: string
  totalFee: number
  ledger: { paidAmount: number; arrears: number }
}
export default function Page() {
  const { t } = useI18n()
  return (
    <ThemeRoot>
      <ChildRecordsView
        titleKey="eduChildBills.title"
        columns={[
          { key: 'className', title: t('eduChildBills.className') },
          { key: 'term', title: t('eduChildBills.term') },
          { key: 'total', title: t('eduChildBills.total'), tone: 'warn' },
          { key: 'paid', title: t('eduChildBills.paid'), tone: 'ok' },
          { key: 'arrears', title: t('eduChildBills.arrears'), tone: 'danger' },
        ]}
        load={async (): Promise<ChildRecordRow[]> => {
          const id = childIdOf()
          if (!id) return []
          const res = await get<{ bills: Row[] }>(`/edu-ai-management/parent/children/${id}/bills`)
          return ((res as { bills?: Row[] } | null)?.bills ?? []).map((b) => ({
            id: b.enrollmentId,
            cells: {
              className: b.className,
              term: b.termName,
              total: (b.totalFee / 100).toFixed(2),
              paid: (b.ledger.paidAmount / 100).toFixed(2),
              arrears: (b.ledger.arrears / 100).toFixed(2),
            },
          }))
        }}
      />
    </ThemeRoot>
  )
}
