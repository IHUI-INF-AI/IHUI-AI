import { useI18n } from '@/i18n'
import ThemeRoot from '@/components/ThemeRoot'
import { get } from '@/api'
import { ChildRecordsView, childIdOf, type ChildRecordRow } from '../records-page'

interface Row {
  id: string
  date: string
  status: string
  checkInTime: string | null
  checkOutTime: string | null
}
export default function Page() {
  const { t } = useI18n()
  const st = (s: string) => {
    const k = `eduAttendance.status.${s}`
    const v = t(k)
    return v === k ? s : v
  }
  return (
    <ThemeRoot>
      <ChildRecordsView
        titleKey="eduChildAttendance.title"
        columns={[
          { key: 'date', title: t('eduChildAttendance.date') },
          { key: 'status', title: t('eduAttendance.statusTitle'), tone: 'ok' },
          { key: 'checkIn', title: t('eduAttendance.checkIn') },
          { key: 'checkOut', title: t('eduAttendance.checkOut') },
        ]}
        load={async (): Promise<ChildRecordRow[]> => {
          const id = childIdOf()
          if (!id) return []
          const res = await get<{ list: Row[] }>(`/edu-ai-management/parent/child/${id}/attendance`)
          return ((res as { list?: Row[] } | null)?.list ?? []).map((r) => ({
            id: r.id,
            cells: {
              date: (r.date ?? '').slice(0, 10),
              status: st(r.status),
              checkIn: r.checkInTime?.slice(11, 16) ?? '—',
              checkOut: r.checkOutTime?.slice(11, 16) ?? '—',
            },
          }))
        }}
      />
    </ThemeRoot>
  )
}
