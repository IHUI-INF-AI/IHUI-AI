import Taro from '@tarojs/taro'

export function readFileToBase64(filePath: string): Promise<string> {
  return new Promise((resolve, reject) => {
    const fsm = Taro.getFileSystemManager()
    fsm.readFile({
      filePath,
      encoding: 'base64',
      success: (res) => resolve(res.data as string),
      fail: (err) => reject(err),
    })
  })
}

