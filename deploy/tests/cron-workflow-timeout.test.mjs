/**
 * cron 类 workflow 的 job 超时夹具(P2-8)。
 *
 * 钉:凡 `on.schedule` 带 `cron:` 的 workflow,其每个 job 都必须在 job 级声明
 * `timeout-minutes`。GitHub 对 job 的默认上限是 360min,卡住的 cron 会一直占着
 * concurrency 队列,表现为"定时任务停摆但不红"。修前实测只有 cross-end-sync 缺
 * (cascade 无 timeout-minutes),补 30min 后全清单通过。
 */

import { test } from 'node:test'
import assert from 'node:assert/strict'
import { readdirSync, readFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const HERE = dirname(fileURLToPath(import.meta.url))
const WF_DIR = join(HERE, '..', '..', '.github', 'workflows')

function parseCronWorkflows() {
  return readdirSync(WF_DIR)
    .filter((f) => f.endsWith('.yml'))
    .map((f) => ({ f, text: readFileSync(join(WF_DIR, f), 'utf8') }))
    .filter(({ text }) => /\n\s*- cron:/.test(text))
}

test('T1 每个 cron workflow 的每个 job 都有 timeout-minutes', () => {
  const files = parseCronWorkflows()
  assert.ok(files.length >= 10, `命中 cron workflow 仅 ${files.length} 个,选择器可能失配`)
  const bad = []
  for (const { f, text } of files) {
    const lines = text.split('\n')
    const jobsAt = lines.findIndex((l) => /^jobs:/.test(l))
    if (jobsAt < 0) {
      bad.push(`${f}: 没有 jobs:`)
      continue
    }
    for (let i = jobsAt + 1; i < lines.length; i++) {
      const job = lines[i].match(/^  ([A-Za-z0-9_-]+):\s*$/)
      if (!job) continue
      let end = lines.length
      for (let j = i + 1; j < lines.length; j++) {
        if (/^  [A-Za-z0-9_-]+:\s*$/.test(lines[j])) {
          end = j
          break
        }
      }
      const block = lines.slice(i, end)
      if (!block.some((l) => /^\s{4}timeout-minutes:/.test(l))) bad.push(`${f} :: ${job[1]} (第 ${i + 1} 行)`)
    }
  }
  assert.equal(bad.length, 0, `cron job 缺 timeout-minutes:\n  ${bad.join('\n  ')}`)
})
