# 本机生产 Web 启动器（Windows 服务/手动均可调用）。
# 要求 apps/web/.next 已由 scripts/build-next-prod.ps1 完成生产构建。
$ErrorActionPreference = 'Stop'

$Root = 'C:\IHUI-AI'
$Node = 'C:\Users\Administrator\.workbuddy\binaries\node\versions\22.22.2-6\node.exe'
if (-not (Test-Path -LiteralPath $Node)) {
  $Node = 'C:\Program Files\nodejs\node.exe'
}
if (-not (Test-Path -LiteralPath $Node)) {
  throw "run-web-prod.ps1: Node 未找到"
}

$web = Join-Path $Root 'apps\web'
if (-not (Test-Path -LiteralPath (Join-Path $web '.next\BUILD_ID'))) {
  throw "run-web-prod.ps1: .next/BUILD_ID 不存在，请先运行 scripts/build-next-prod.ps1"
}

$port = if ($env:IHUI_WEB_PORT) { [int]$env:IHUI_WEB_PORT } else { 8801 }
$hostAddr = if ($env:IHUI_WEB_HOST) { $env:IHUI_WEB_HOST } else { '0.0.0.0' }

# 浏览器端同源：/api 与 /ws 都由 next start 的 rewrites 反代到 8802。
# 这里显式清空旧构建可能残留的绝对 API 地址；真实构建期值由 scripts/build-next-prod.ps1 负责。
$env:NEXT_PUBLIC_API_BASE_URL = ''
$env:NEXT_PUBLIC_WS_BASE_URL = ''

Set-Location $web
Write-Host "[IHUI-WEB] production start host=$hostAddr port=$port"
& $Node node_modules/next/dist/bin/next start -H $hostAddr -p $port
exit $LASTEXITCODE
