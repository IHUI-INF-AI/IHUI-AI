# 改为转发后,"改了源码忘同步运行副本"这条路径在结构上不存在。
# 路径由 $PSScriptRoot 推导,不写盘符:deploy/prod-bundle 与 deploy/win 同为仓库根下二级目录。
#
# 若本目录被单独搬到仓库之外(独立部署包形态),下面会明确报错并给出处置:
# 把 nssm 的 AppParameters 直接改成入库源码路径,再重启服务。
# =============================================================================
$source = Join-Path $PSScriptRoot '..\win\ihui-monitor.ps1'
if (-not (Test-Path -LiteralPath $source)) {
  Write-Error "找不到入库源码: $source"
  Write-Error '本文件只是转发器。请把 nssm AppParameters 直接指向入库源码后重启服务:'
  Write-Error '  nssm set IHUI-MONITOR AppParameters "-NoProfile -ExecutionPolicy Bypass -File <仓库根>\deploy\win\ihui-monitor.ps1"'
  exit 1
}

# @args 必须透传:-Once / -ProbeMail / -DryRun 都靠它从服务外壳走到真身;
# 退出码同样透传,否则 -ProbeMail 的成败结论在转发层被抹平成 0。
& $source @args
exit $LASTEXITCODE
